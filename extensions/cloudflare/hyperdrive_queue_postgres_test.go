// financesTree writes finances-stack under root's schemas/services: it
// deploys finances-db, a DB service on Postgres alone with the finances
// app's two queues, PlaidSyncRequested, one waiting and one claimed per
// item, and EmbedLineItem, one waiting per line item, which LineItem's
// trigger enqueues when a line item has a category; and CfStaging, an
// environment on the cloudflare target whose finances-db is on the
// Hyperdrive config stagingHyperdrive. It returns the services' directory.
func financesTree(t *testing.T, root string) string {
	t.Helper()
	services := filepath.Join(root, "schemas", "services")
	for name, content := range map[string]string{
		"finances-db/schema.config.yaml": "name: finances-db\nkind: DB\noutputs:\n  types:\n    go: { enabled: true }\n  sql: { dialects: [postgres] }\n",
		"finances-db/src/db.schema.yaml": `name: finances-db
kind: DB
scalars:
  Identity.UUID:
    name: Identity.UUID
    languagePrimitive: string
    typeMappings: { sql: UUID }
types:
  # A category a line item may take.
  Category:
    name: Category
    role: DBTable
    fields:
      - { name: id, typeRef: { name: Identity.UUID }, required: true, key: true, autoGenerated: true }
      - { name: name, typeRef: { name: string }, required: true }
  # A line of a statement, whose category enqueues its embedding.
  LineItem:
    name: LineItem
    role: DBTable
    fields:
      - { name: id, typeRef: { name: Identity.UUID }, required: true, key: true, autoGenerated: true }
      - { name: name, typeRef: { name: string }, required: true }
      - { name: category, typeRef: { name: Category }, relation: { type: Category, onDelete: SET NULL } }
    enqueueOnChange:
      - queue: EmbedLineItem
        "on": [insert, update]
        fields: [category]
        when: [{ field: category, notNull: true }]
        message: { lineItemId: id }
  # Embedding work, one waiting message per line item, the latest.
  EmbedLineItem:
    name: EmbedLineItem
    role: EmbeddedStruct
    queue: { retries: 5, key: lineItemId, onDuplicate: replace }
    fields:
      - { name: lineItemId, typeRef: { name: Identity.UUID }, required: true }
  # A sync of one Plaid item, one at a time per item.
  PlaidSyncRequested:
    name: PlaidSyncRequested
    role: EmbeddedStruct
    queue: { retries: 8, key: plaidItemId, onDuplicate: skip, serialize: true }
    fields:
      - { name: plaidItemId, typeRef: { name: string }, required: true }
      - { name: reason, typeRef: { name: string }, required: true }
`,
		"finances-stack/schema.config.yaml": "name: finances-stack\nkind: Stack\noutputs: {}\n",
		"finances-stack/src/stack.schema.yaml": `kind: Stack
types:
  Finances:
    name: Finances
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: finances-db, kind: DB }
  CfStaging:
    name: CfStaging
    role: EmbeddedStruct
    environment:
      target: cloudflare
      values: { accountId: ` + accountID + ` }
      settings:
        - of: { service: { name: finances-db, kind: DB } }
          values: { hyperdrive: ` + stagingHyperdrive + ` }
`,
	} {
		path := filepath.Join(services, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return services
}

// The messages and rows TestStackQueueOnACloudflareEnvironment seeds.
const (
	plaidDeadID    = "00000000-0000-4000-8000-0000000000b1"
	plaidDroppedID = "00000000-0000-4000-8000-0000000000b2"
	plaidReadyID   = "00000000-0000-4000-8000-0000000000b3"
	groceriesID    = "00000000-0000-4000-8000-0000000000c1"
	cornerShopID   = "00000000-0000-4000-8000-0000000000d1"
	marketID       = "00000000-0000-4000-8000-0000000000d2"
	transferID     = "00000000-0000-4000-8000-0000000000d3"
	waitingEmbedID = "00000000-0000-4000-8000-0000000000e1"
)

// TestStackQueueOnACloudflareEnvironment runs `stack queue` through the
// CLI, the cloudflare target linked, over CfStaging, whose finances-db is
// on Hyperdrive (D96). The origin is a database of its own on the Postgres
// SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL names, holding finances-db's
// tables as its build writes them, and HYPERDRIVE_ORIGIN_FINANCES_DB names
// it; the fake Cloudflare holds the Hyperdrive config, whose origin is the
// same host, port, database and user, and the manifest of a deploy. The
// commands run the migration runner, built from runtime/migrate/go, on
// this machine against the origin:
//   - dead lists PlaidSyncRequested's two dead messages;
//   - with no HYPERDRIVE_ORIGIN_FINANCES_DB, or a config that reaches
//     another database, user, host or port, retry --all is refused, naming
//     the variable and what it must match, and every message stays dead;
//   - retry makes one ready, due now, with no attempts, and drop deletes the
//     other, after which dead finds none;
//   - backfill enqueues an EmbedLineItem for each line item with a category,
//     replacing the one that waits for the first, so each waits once, and
//     a second backfill still leaves one message per line item.
func TestStackQueueOnACloudflareEnvironment(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: builds the migration runner and runs it against Postgres")
	}
	admin := os.Getenv("SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL")
	if admin == "" {
		t.Skip("set SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL to a Postgres whose role may create databases")
	}
	u, err := url.Parse(admin)
	if err != nil {
		t.Fatal(err)
	}
	port := 5432
	if p := u.Port(); p != "" {
		if _, err := fmt.Sscan(p, &port); err != nil {
			t.Fatal(err)
		}
	}
	runner := buildRunner(t)
	queuedb := buildQueueDB(t)

	root := t.TempDir()
	services := financesTree(t, root)
	stackDir := filepath.Join(services, "finances-stack")
	suffix := make([]byte, 6)
	if _, err := rand.Read(suffix); err != nil {
		t.Fatal(err)
	}
	database := "cf_queue_" + hex.EncodeToString(suffix)
	origin := *u
	origin.Path = "/" + database

	cloud := newFakeCloud()
	config := &cloudflare.HyperdriveConfig{ID: stagingHyperdrive, Name: "finances-stack-cf-staging-finances-db"}
	config.Origin.Host, config.Origin.Port, config.Origin.Database, config.Origin.User, config.Origin.Scheme = u.Hostname(), port, database, u.User.Username(), "postgres"
	config.Caching.Disabled = true
	cloud.hyperdrive[stagingHyperdrive] = config
	sh := shell{
		cloudflare.TokenEnv:                 engineerToken,
		cloudflare.MigrateEnv:               runner,
		cloudflare.OriginEnv("finances-db"): origin.String(),
	}
	ext := cloudflare.Extension{Cloud: cloud, Getenv: sh.getenv}
	run := func(args ...string) (string, string, error) {
		t.Helper()
		var stdout, stderr bytes.Buffer
		root := cli.New(cli.Config{}, ext, pulumiStub{})
		root.SetOut(&stdout)
		root.SetErr(&stderr)
		root.SetIn(strings.NewReader(""))
		root.SetArgs(args)
		err := root.Execute()
		return stdout.String(), stderr.String(), err
	}
	queue := func(args ...string) (string, string, error) {
		t.Helper()
		return run(append(append([]string{"stack", "queue"}, args...), "--stack", stackDir)...)
	}

	// finances-db's tables, as its build writes them, with two dead sync
	// messages and a waiting one; three line items, two with a category,
	// whose messages the trigger enqueued and which are taken back, as if
	// a plan had added the trigger after them; and one waiting embedding,
	// with attempts, for the first.
	dist := filepath.Join(root, "dist")
	if out, errOut, err := run("build", filepath.Join(services, "finances-db"), "--out", dist, "--skip-format"); err != nil {
		t.Fatalf("build finances-db: %v\n%s%s", err, out, errOut)
	}
	createSQL, err := os.ReadFile(filepath.Join(dist, "sql", "finances-db", "create.sql"))
	if err != nil {
		t.Fatal(err)
	}
	seed := filepath.Join(root, "seed.sql")
	if err := os.WriteFile(seed, append(createSQL, []byte(`
INSERT INTO plaid_sync_requested_queue (id, plaid_item_id, reason, state, attempts, last_error, updated_at) VALUES
  ('`+plaidDeadID+`', 'item-1', 'webhook', 'dead', 9, 'ITEM_LOGIN_REQUIRED', now() - interval '2 hours'),
  ('`+plaidDroppedID+`', 'item-2', 'schedule', 'dead', 1, 'the claim of its last attempt expired before its handler finished', now() - interval '1 hour');
INSERT INTO plaid_sync_requested_queue (id, plaid_item_id, reason, state, due_at) VALUES ('`+plaidReadyID+`', 'item-3', 'webhook', 'ready', now() + interval '1 hour');
INSERT INTO category (id, name) VALUES ('`+groceriesID+`', 'Groceries');
INSERT INTO line_item (id, name, category_id) VALUES
  ('`+cornerShopID+`', 'Corner shop', '`+groceriesID+`'),
  ('`+marketID+`', 'Market', '`+groceriesID+`'),
  ('`+transferID+`', 'Transfer', NULL);
DELETE FROM embed_line_item_queue;
INSERT INTO embed_line_item_queue (id, line_item_id, attempts, last_error, due_at) VALUES ('`+waitingEmbedID+`', '`+cornerShopID+`', 2, 'Voyage answered 429', now() + interval '1 hour');
`)...), 0o644); err != nil {
		t.Fatal(err)
	}
	queueDB(t, queuedb, "create", admin, database, seed)
	t.Cleanup(func() { queueDB(t, queuedb, "drop", admin, database) })
	sync := func(id string) string {
		t.Helper()
		return strings.TrimSpace(queueDB(t, queuedb, "query", admin, database,
			`SELECT state, attempts, due_at <= now(), claim_token IS NULL, COALESCE(last_error, '') FROM plaid_sync_requested_queue WHERE id = '`+id+`'`))
	}

	// The deploy's manifest, which stack queue reads before it runs.
	reg, err := registry.Assemble(registry.DefaultNaming(), ext, pulumiStub{})
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	if _, err := cloud.EnsureBucket(ctx, accountID, cloudflare.StateBucket); err != nil {
		t.Fatal(err)
	}
	manifest, err := json.Marshal(stack.Manifest{Version: 1, Stack: "finances-stack", Environment: "CfStaging", Run: "CfStaging", Status: "deployed"})
	if err != nil {
		t.Fatal(err)
	}
	target, _ := reg.Target(cloudflare.Target)
	staging := registry.Run{Environment: &ir.ResolvedEnvironment{Stack: "finances-stack", Environment: "CfStaging", Values: map[string]any{"accountId": accountID}}}
	if err := target.State.WriteManifest(ctx, staging, manifest); err != nil {
		t.Fatal(err)
	}

	where := fmt.Sprintf("database %s of %s:%d as %s", database, u.Hostname(), port, u.User.Username())
	out, errOut, err := queue("dead", "CfStaging", "finances-db.PlaidSyncRequested")
	if err != nil {
		t.Fatalf("dead: %v\n%s%s", err, out, errOut)
	}
	for _, want := range []string{
		"Queue finances-db.PlaidSyncRequested of CfStaging: 2 dead messages, the oldest death first.\n\n" + plaidDeadID + "\n  attempts:   9\n  died at:    ",
		"  last error: ITEM_LOGIN_REQUIRED\n  message:    {\"reason\":\"webhook\",\"plaid_item_id\":\"item-1\"}\n\n" + plaidDroppedID + "\n  attempts:   1\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("dead printed no %q:\n%s", want, out)
		}
	}
	if strings.Contains(out, plaidReadyID) {
		t.Errorf("dead lists the waiting message:\n%s", out)
	}
	if want := "run a queue operation on finances-db, in database finances-db of CfStaging\n  finances-db: the queue operation on " + where + ", through Hyperdrive config " + stagingHyperdrive + ", with " + runner + " on this machine\n"; errOut != want {
		t.Errorf("dead logged %q, want %q", errOut, want)
	}

	// Refused before the runner runs: the queue does not change.
	mismatch := func(reached string) string {
		return "cloudflare: database finances-db's Hyperdrive config " + stagingHyperdrive + " reaches " + reached + ", and HYPERDRIVE_ORIGIN_FINANCES_DB reaches " + where +
			": stack queue would read and change the queues of one database while its Workers drain another's; point the config or the variable at the same database, as the same user"
	}
	at := func(host string, port int, database, user string) string {
		return fmt.Sprintf("database %s of %s:%d as %s", database, host, port, user)
	}
	for name, tc := range map[string]struct {
		edit func(*cloudflare.HyperdriveConfig)
		want string
	}{
		"no origin": {
			edit: func(*cloudflare.HyperdriveConfig) { delete(sh, cloudflare.OriginEnv("finances-db")) },
			want: "cloudflare: database finances-db is on cloudflare.hyperdrive, and stack queue runs from this machine on its origin: set HYPERDRIVE_ORIGIN_FINANCES_DB to the origin's connection string, postgres://<user>:<password>@<host>:<port>/<database>, with the host, port, database and user of its Hyperdrive config, " + stagingHyperdrive,
		},
		"another database": {
			edit: func(c *cloudflare.HyperdriveConfig) { c.Origin.Database = "finances" },
			want: mismatch(at(u.Hostname(), port, "finances", u.User.Username())),
		},
		"another user": {
			edit: func(c *cloudflare.HyperdriveConfig) { c.Origin.User = "finances" },
			want: mismatch(at(u.Hostname(), port, database, "finances")),
		},
		"another host": {
			edit: func(c *cloudflare.HyperdriveConfig) { c.Origin.Host = "db.example.com" },
			want: mismatch(at("db.example.com", port, database, u.User.Username())),
		},
		"another port": {
			edit: func(c *cloudflare.HyperdriveConfig) { c.Origin.Port = port + 1 },
			want: mismatch(at(u.Hostname(), port+1, database, u.User.Username())),
		},
	} {
		t.Run(name, func(t *testing.T) {
			saved := *config
			tc.edit(config)
			defer func() {
				*config = saved
				sh[cloudflare.OriginEnv("finances-db")] = origin.String()
			}()
			out, errOut, err := queue("retry", "CfStaging", "finances-db.PlaidSyncRequested", "--all")
			if err == nil || err.Error() != tc.want {
				t.Fatalf("retry --all = %v\nwant %s\n%s%s", err, tc.want, out, errOut)
			}
			if got := sync(plaidDeadID); got != "dead|9|true|true|ITEM_LOGIN_REQUIRED" {
				t.Errorf("after the refusal the dead message is %s", got)
			}
		})
	}

	out, errOut, err = queue("retry", "CfStaging", "finances-db.PlaidSyncRequested", plaidDeadID)
	if err != nil {
		t.Fatalf("retry: %v\n%s%s", err, out, errOut)
	}
	if want := "Retried 1 dead message of finances-db.PlaidSyncRequested in CfStaging: each is ready, due now, with no attempts.\n  " + plaidDeadID + "\n"; out != want {
		t.Errorf("retry printed %q, want %q", out, want)
	}
	if got := sync(plaidDeadID); got != "ready|0|true|true|ITEM_LOGIN_REQUIRED" {
		t.Errorf("the retried message is %s, want ready, due now, with no attempts", got)
	}

	out, errOut, err = queue("drop", "CfStaging", "finances-db.PlaidSyncRequested", plaidDroppedID)
	if err != nil {
		t.Fatalf("drop: %v\n%s%s", err, out, errOut)
	}
	if want := "Dropped 1 dead message of finances-db.PlaidSyncRequested in CfStaging.\n  " + plaidDroppedID + "\n"; out != want {
		t.Errorf("drop printed %q, want %q", out, want)
	}
	if got := sync(plaidDroppedID); got != "" {
		t.Errorf("the dropped message is %s", got)
	}
	if out, _, err = queue("dead", "CfStaging", "finances-db.PlaidSyncRequested"); err != nil || out != "Queue finances-db.PlaidSyncRequested of CfStaging has no dead messages.\n" {
		t.Errorf("dead after the retry and the drop = %v, %q", err, out)
	}
	if got := sync(plaidReadyID); got != "ready|0|false|true|" {
		t.Errorf("the waiting message is %s, want it as it was", got)
	}

	embeds := func() string {
		t.Helper()
		return strings.TrimSpace(queueDB(t, queuedb, "query", admin, database,
			`SELECT id = '`+waitingEmbedID+`', line_item_id::text, state, attempts, due_at <= now(), COALESCE(last_error, '') FROM embed_line_item_queue ORDER BY line_item_id`))
	}
	// Each backfill leaves one waiting message per line item with a
	// category: the corner shop's, which waited, replaced under its id, due
	// now with no attempts, and the market's.
	want := "true|" + cornerShopID + "|ready|0|true|\nfalse|" + marketID + "|ready|0|true|"
	for i := range 2 {
		out, errOut, err = queue("backfill", "CfStaging", "finances-db.EmbedLineItem")
		if err != nil {
			t.Fatalf("backfill %d: %v\n%s%s", i+1, err, out, errOut)
		}
		if want := "Backfilled queue finances-db.EmbedLineItem of CfStaging: enqueued 2 messages, one for each row that meets its triggers' conditions.\n"; out != want {
			t.Errorf("backfill %d printed %q, want %q", i+1, out, want)
		}
		if got := embeds(); got != want {
			t.Errorf("after backfill %d the queue holds\n%s\nwant\n%s", i+1, got, want)
		}
	}
}

// buildRunner builds the migration runner from runtime/migrate/go and
// returns the binary.
func buildRunner(t *testing.T) string {
	t.Helper()
	runner := filepath.Join(t.TempDir(), cloudflare.MigrateBinary)
	build := exec.Command("go", "build", "-o", runner, "./cmd/superschematic-migrate")
	build.Dir = filepath.Join("..", "..", "runtime", "migrate", "go")
	build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build the migration runner: %v\n%s", err, out)
	}
	return runner
}

// buildQueueDB builds the cli package's testdata/queuedb, a module of its
// own that makes, reads and drops a test's database, and returns the
// binary.
func buildQueueDB(t *testing.T) string {
	t.Helper()
	module := t.TempDir()
	if err := os.CopyFS(module, os.DirFS(filepath.Join("..", "..", "cli", "testdata", "queuedb"))); err != nil {
		t.Fatal(err)
	}
	bin := filepath.Join(t.TempDir(), "queuedb")
	build := exec.Command("go", "build", "-o", bin, ".")
	build.Dir = module
	build.Env = append(os.Environ(), "GOFLAGS=-mod=readonly", "CGO_ENABLED=0", "GOWORK=off")
	if out, err := build.CombinedOutput(); err != nil {
		t.Fatalf("build queuedb: %v\n%s", err, out)
	}
	return bin
}

// queueDB runs the queuedb binary and returns what it printed.
func queueDB(t *testing.T, bin string, args ...string) string {
	t.Helper()
	out, err := exec.Command(bin, args...).CombinedOutput()
	if err != nil {
		t.Fatalf("queuedb %s: %v\n%s", args[0], err, out)
	}
	return string(out)
}
