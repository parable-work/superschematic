// coreNaming is the default naming with the core's own auth provider
// selected: the in-tree default names the Parable provider, which only the
// Parable extension registers, and this extension registers none.
func coreNaming() registry.Naming {
	n := registry.DefaultNaming()
	n.AuthProvider = "session"
	return n
}

// build assembles the core plus the deploy extension, loads the fixture
// service and generates into a fresh output root, returning the root and the
// error from Generate.
func build(t *testing.T, servicePath string) (string, error) {
	t.Helper()
	reg, err := registry.Assemble(coreNaming(), deploy.Extension{})
	if err != nil {
		t.Fatalf("Assemble: %v", err)
	}
	schema, cfg, err := loader.LoadServiceWithConfig(servicePath, loader.WithRegistry(reg))
	if err != nil {
		t.Fatalf("LoadService: %v", err)
	}
	if _, ok := schema.Documents[deploy.Name]; !ok {
		t.Fatalf("Schema.Documents has no %q; keys: %v", deploy.Name, schema.Documents)
	}
	out := t.TempDir()
	_, err = registry.Generate(schema, cfg, registry.Options{
		OutputRoot:  out,
		ServicePath: servicePath,
		Registry:    reg,
	})
	return out, err
}

// TestExampleGeneratesValuesFiles is the extension's acceptance test: the
// example service under testdata produces a base values.yaml and one merged
// file per environment, as a Kubernetes env list sorted by name.
func TestExampleGeneratesValuesFiles(t *testing.T) {
	out, err := build(t, filepath.Join("testdata", "services", "example"))
	if err != nil {
		t.Fatalf("Generate: %v", err)
	}
	dir := deploy.OutDir(out, "example")

	want := map[string]string{
		"values.yaml": `# Generated by psgen (extensions/deploy) from deploy.values.yaml. Do not edit.
env:
    - name: API_TOKEN
      valueFrom:
        secretKeyRef:
            name: example-secrets
            key: api-token
    - name: PORT
      value: "9000"
`,
		"values.production.yaml": `# Generated by psgen (extensions/deploy) from deploy.values.yaml. Do not edit.
env:
    - name: API_TOKEN
      valueFrom:
        secretKeyRef:
            name: example-secrets
            key: api-token
    - name: DATABASE_URL
      value: postgres://db.internal/example
    - name: PORT
      value: "9000"
`,
		"values.staging.yaml": `# Generated by psgen (extensions/deploy) from deploy.values.yaml. Do not edit.
env:
    - name: API_TOKEN
      valueFrom:
        secretKeyRef:
            name: example-secrets
            key: api-token
    - name: DATABASE_URL
      value: postgres://db.staging.internal/example
    - name: LOG_LEVEL
      value: debug
    - name: PORT
      value: "9000"
`,
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("ReadDir(%s): %v", dir, err)
	}
	if len(entries) != len(want) {
		t.Errorf("wrote %d files, want %d", len(entries), len(want))
	}
	for name, body := range want {
		got, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Errorf("%s: %v", name, err)
			continue
		}
		if string(got) != body {
			t.Errorf("%s:\n--- got\n%s--- want\n%s", name, got, body)
		}
	}
}

// writeExample copies the fixture service with deploy.values.yaml replaced.
func writeExample(t *testing.T, values string) string {
	t.Helper()
	src := filepath.Join("testdata", "services", "example")
	dir := t.TempDir()
	for _, rel := range []string{"schema.config.yaml", filepath.Join("src", "config.schema.yaml")} {
		data, err := os.ReadFile(filepath.Join(src, rel))
		if err != nil {
			t.Fatal(err)
		}
		if err := os.MkdirAll(filepath.Dir(filepath.Join(dir, rel)), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, rel), data, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, deploy.File), []byte(values), 0o644); err != nil {
		t.Fatal(err)
	}
	return dir
}

// TestGenerateRejectsValuesOutsideTheEnvVarsContract pins the three checks
// the static JSON Schema cannot make: unknown keys, inline @secret values
// and incomplete environments.
func TestGenerateRejectsValuesOutsideTheEnvVarsContract(t *testing.T) {
	cases := []struct {
		name, values, want string
	}{
		{
			name: "unknown key",
			values: `env:
  DATABASE_URL: postgres://db/example
  API_TOKEN: { secretRef: { name: s, key: k } }
  REPLICAS: 3
`,
			want: "env.REPLICAS is not a field of ExampleConfig",
		},
		{
			name: "inline secret",
			values: `env:
  DATABASE_URL: postgres://db/example
  API_TOKEN: plaintext
`,
			want: "env.API_TOKEN is @secret and must be a secretRef",
		},
		{
			name: "incomplete environment",
			values: `env:
  API_TOKEN: { secretRef: { name: s, key: k } }
environments:
  production:
    env:
      DATABASE_URL: postgres://db/example
  staging:
    env: {}
`,
			want: "environments.staging.env is missing required fields with no default: [DATABASE_URL]",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := build(t, writeExample(t, tc.values))
			if err == nil {
				t.Fatal("Generate accepted a document outside the @envVars contract")
			}
			if !strings.Contains(err.Error(), tc.want) {
				t.Errorf("error = %v, want it to contain %q", err, tc.want)
			}
		})
	}
}

// TestLoaderRejectsMalformedDocument pins that the JSON Schema runs at load
// time: a secretRef missing its key never reaches the generator.
func TestLoaderRejectsMalformedDocument(t *testing.T) {
	dir := writeExample(t, `env:
  API_TOKEN: { secretRef: { name: s } }
`)
	reg, err := registry.Assemble(coreNaming(), deploy.Extension{})
	if err != nil {
		t.Fatal(err)
	}
	_, _, err = loader.LoadServiceWithConfig(dir, loader.WithRegistry(reg))
	if err == nil {
		t.Fatal("LoadService accepted a secretRef without a key")
	}
	if !strings.Contains(err.Error(), deploy.File) {
		t.Errorf("error does not name the document file: %v", err)
	}
}
