// The migration runner (docs/stack-model.md, sections 7.2 and 8.4, and
// D46). Each phase a deploy runs on a database is one execution of the
// stack's Cloud Run job, `<stack>-migrate`, which runs
// `superschematic-migrate job` as the stack's `migrator` account:
//
//  1. the runner writes each plan with steps in the phase, and a job
//     document naming them, into the state bucket, under
//     superschematic/migrations/<stack>/<run>/;
//  2. it finds the runner's image, or builds it with Cloud Build (below);
//  3. it creates or updates the job to run that image, and runs it once
//     with the job document's gs:// URL as its argument, waiting for the
//     execution to finish.
//
// The job reaches the Cloud SQL instance through the Cloud SQL Go connector
// with IAM database authentication, as the migrator's IAM database user,
// which the Cloud SQL platform gives each instance with the
// cloudsqlsuperuser role, so the tables it creates are its own. After the
// plan's phase the job gives each server that connects to the DB service,
// by its IAM database user, read and write privileges on the DB service's
// tables, and takes them back from a server that no longer connects. The
// job is not a node of the graph (D45): it is made from the release the
// binary pins, which the graph does not depend on.
//
// The runner's image is built from a generated Dockerfile that installs
// the runner with `go install` from its module at the release's tag
// (runtime/migrate/go carries no replace directive), which the Go checksum
// database verifies, onto distroless static. It is tagged with the
// release, so each project builds it once per release.

// migrateImage names the runner's image in the stack's repository.
const migrateImage = "superschematic-migrate"

// migrateModule is the runner's command, which `go install` takes at a
// release's tag.
const migrateModule = "github.com/parable-work/superschematic/runtime/migrate/go/cmd/superschematic-migrate"

// extensionModule is this module, whose version in the binary's build
// information is the release it is part of.
const extensionModule = "github.com/parable-work/superschematic/extensions/gcp"

// MigrateImageEnv names an image of the runner, by digest, which the
// migration job runs in place of the one built from the release the
// binary pins. A binary built from a checkout pins no release, so it needs
// one.
const MigrateImageEnv = "SUPERSCHEMATIC_MIGRATE_IMAGE"

// migrationPrefix is where the job documents and plans sit in the state
// bucket.
const migrationPrefix = "superschematic/migrations/"

// The job's settings: its container's name and how long one run may take.
const (
	migrateContainer = "migrate"
	migrateTimeout   = time.Hour
)

// migrateDockerfile is the runner's Dockerfile at a release.
func migrateDockerfile(version string) string {
	return fmt.Sprintf(`# Generated by superschematic: the image of the migration runner,
# superschematic-migrate %[1]s, which a deploy runs as a Cloud Run job
# (docs/stack-model.md, section 8.4). go install fetches the runner's
# module at the release's tag through the Go module proxy and checks it,
# and every module it requires, against the Go checksum database.
ARG GO_VERSION=%[2]s

FROM golang:${GO_VERSION}-trixie AS build
ENV GOTOOLCHAIN=local CGO_ENABLED=0 GOBIN=/out GOFLAGS=-trimpath
RUN go install %[3]s@v%[1]s

FROM gcr.io/distroless/static-debian13:nonroot
COPY --from=build /out/superschematic-migrate /superschematic-migrate
ENTRYPOINT ["/superschematic-migrate"]
`, version, stack.GoVersion, migrateModule)
}

// releaseVersion returns the release the binary is part of, from the
// version of this module in its build information, or "" for a binary
// built from a checkout, whose modules are at 0.0.0.
func releaseVersion() string {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return ""
	}
	version := ""
	if info.Main.Path == extensionModule {
		version = info.Main.Version
	}
	for _, dep := range info.Deps {
		if dep.Path == extensionModule {
			version = dep.Version
		}
	}
	version = strings.TrimPrefix(version, "v")
	if version == "" || version == "(devel)" || version == "0.0.0" {
		return ""
	}
	return version
}

// The job document `superschematic-migrate job` runs (runtime/migrate/
// README.md, "Jobs"). The target writes it; it does not import the runner,
// whose module holds the database drivers (D27).
type migrateJob struct {
	Version   int              `json:"version"`
	Phase     string           `json:"phase"`
	CloudSQL  migrateCloudSQL  `json:"cloudSql"`
	Databases []*migrateTarget `json:"databases"`
}

type migrateCloudSQL struct {
	Instance string `json:"instance"`
	User     string `json:"user"`
}

type migrateTarget struct {
	Service    string             `json:"service"`
	Database   string             `json:"database"`
	Plan       string             `json:"plan,omitempty"`
	Privileges *migratePrivileges `json:"privileges"`
}

type migratePrivileges struct {
	ReadWrite []string `json:"readWrite"`
}

// migrationRunner is the gcp target's MigrationRunner.
type migrationRunner struct{ ext Extension }

var _ registry.MigrationRunner = migrationRunner{}

// Migrate runs one phase of req's plans on its database as an execution of
// the stack's migration job.
func (r migrationRunner) Migrate(ctx context.Context, req registry.MigrationRequest) error {
	if err := req.Run.Check(); err != nil {
		return err
	}
	env := req.Run.Environment
	v, err := envValues(env)
	if err != nil {
		return err
	}
	log := req.Log
	if log == nil {
		log = io.Discard
	}
	logf := func(format string, args ...any) { _, _ = fmt.Fprintf(log, "  "+format+"\n", args...) }
	cloud := r.ext.cloud()
	bucket := stateBucket(v.project)
	dir := migrationPrefix + kebab(env.Stack) + "/" + req.Run.Name() + "/"

	job, plans, err := migrationJob(req, v)
	if err != nil {
		return err
	}
	for object, doc := range plans {
		if err := cloud.WriteObject(ctx, bucket, dir+object, doc); err != nil {
			return err
		}
	}
	for _, d := range job.Databases {
		if d.Plan != "" {
			d.Plan = "gs://" + bucket + "/" + dir + d.Plan
		}
	}
	doc, err := json.MarshalIndent(job, "", "  ")
	if err != nil {
		return err
	}
	sum := sha256.Sum256(doc)
	object := dir + req.Database + "/" + string(req.Phase) + "-" + hex.EncodeToString(sum[:8]) + ".json"
	if err := cloud.WriteObject(ctx, bucket, object, append(doc, '\n')); err != nil {
		return err
	}

	image, err := r.ext.migrateImage(ctx, env, v, log)
	if err != nil {
		return err
	}
	name := kebab(env.Stack) + "-migrate"
	changed, err := cloud.EnsureJob(ctx, v.project, v.region, JobSpec{
		Name:           name,
		Container:      migrateContainer,
		Image:          image,
		ServiceAccount: accountEmail(v, env.Stack, "migrator"),
		Timeout:        migrateTimeout,
		Labels:         map[string]string{"superschematic-stack": kebab(env.Stack)},
	})
	if err != nil {
		return err
	}
	if changed {
		logf("job %s runs %s", name, image)
	}
	ref := "gs://" + bucket + "/" + object
	logf("run job %s: %s", name, ref)
	run, err := cloud.RunJob(ctx, v.project, v.region, name, []string{"job", "--job", ref})
	if err != nil {
		return err
	}
	if !run.Succeeded {
		return fmt.Errorf("gcp: the %s phase on %s failed in job %s, execution %s: %s (logs: %s)", req.Phase, req.Database, name, run.Name, run.Message, run.LogURI)
	}
	logf("execution %s finished", run.Name)
	return nil
}

// migrationJob returns the job document of req, its plans' paths relative
// to the run's directory, and the plan documents to write there.
func migrationJob(req registry.MigrationRequest, v values) (*migrateJob, map[string][]byte, error) {
	env := req.Run.Environment
	d := env.Deployable(req.Database)
	if d == nil || d.Kind != ir.DeployableDatabase {
		return nil, nil, fmt.Errorf("gcp: environment %s has no database %s", env.Environment, req.Database)
	}
	params := req.Run.Parameters
	instance, err := nodeString(env, req.Database+".instance", "name", params)
	if err != nil {
		return nil, nil, err
	}
	job := &migrateJob{
		Version:  1,
		Phase:    string(req.Phase),
		CloudSQL: migrateCloudSQL{Instance: v.project + ":" + v.region + ":" + instance, User: migratorUser(env.Stack, v.project)},
	}
	plans := map[string][]byte{}
	for _, plan := range req.Plans {
		database, err := nodeString(env, req.Database+".database."+plan.Service, "name", params)
		if err != nil {
			return nil, nil, err
		}
		target := &migrateTarget{Service: plan.Service, Database: database, Privileges: &migratePrivileges{ReadWrite: []string{}}}
		if plan.Steps > 0 {
			if len(plan.Plan) == 0 {
				return nil, nil, fmt.Errorf("gcp: the migration plan of %s has steps and no document", plan.Service)
			}
			sum := sha256.Sum256(plan.Plan)
			target.Plan = "plans/" + plan.Service + "-" + hex.EncodeToString(sum[:]) + ".json"
			plans[target.Plan] = plan.Plan
		}
		for _, server := range plan.Servers {
			user, err := nodeString(env, server+".database-user."+req.Database, "name", params)
			if err != nil {
				return nil, nil, fmt.Errorf("gcp: server %s connects to %s: %w", server, plan.Service, err)
			}
			target.Privileges.ReadWrite = append(target.Privileges.ReadWrite, user)
		}
		job.Databases = append(job.Databases, target)
	}
	if len(job.Databases) == 0 {
		return nil, nil, fmt.Errorf("gcp: the %s phase on %s has no plans", req.Phase, req.Database)
	}
	return job, plans, nil
}

// nodeString returns a string property of a node, with the run's
// parameter values in place of its references to them.
func nodeString(env *ir.ResolvedEnvironment, id, property string, params map[string]string) (string, error) {
	res := env.Resources.Resource(id)
	if res == nil {
		return "", fmt.Errorf("gcp: environment %s has no node %s", env.Environment, id)
	}
	value, err := literal(res.Properties[property], params)
	if err != nil {
		return "", fmt.Errorf("gcp: node %s, property %s: %w", id, property, err)
	}
	return value, nil
}

// literal is a value that is a string, a parameter or their concatenation,
// with each parameter's value in its place.
func literal(v any, params map[string]string) (string, error) {
	switch v := v.(type) {
	case string:
		return v, nil
	case ir.Parameter:
		value, ok := params[string(v)]
		if !ok {
			return "", fmt.Errorf("parameter %s has no value", string(v))
		}
		return value, nil
	case ir.Concat:
		var b strings.Builder
		for _, part := range v {
			s, err := literal(part, params)
			if err != nil {
				return "", err
			}
			b.WriteString(s)
		}
		return b.String(), nil
	}
	return "", fmt.Errorf("%v is not a string", v)
}

// migrateImage returns the runner's image by digest: the one
// MigrateImage or SUPERSCHEMATIC_MIGRATE_IMAGE names, else the stack's
// image of the release the binary is part of, which it builds when the
// release's tag does not exist yet.
func (e Extension) migrateImage(ctx context.Context, env *ir.ResolvedEnvironment, v values, log io.Writer) (string, error) {
	image := e.MigrateImage
	if image == "" {
		image = os.Getenv(MigrateImageEnv)
	}
	if image != "" {
		repo, digest, err := stack.SplitImage(image)
		if err != nil {
			return "", fmt.Errorf("gcp: the migration runner's image: %w", err)
		}
		return repo + "@" + digest, nil
	}
	version := e.MigrateVersion
	if version == "" {
		version = releaseVersion()
	}
	if version == "" {
		return "", fmt.Errorf("gcp: this binary was built from a checkout, so it names no release of superschematic-migrate to build the migration job's image from; "+
			"set %s to an image of the runner by digest, in the stack's Artifact Registry repository", MigrateImageEnv)
	}
	dir, err := os.MkdirTemp("", "superschematic-migrate-image-")
	if err != nil {
		return "", err
	}
	defer func() { _ = os.RemoveAll(dir) }()
	dockerfile := filepath.Join(dir, "Dockerfile")
	if err := os.WriteFile(dockerfile, []byte(migrateDockerfile(version)), 0o644); err != nil {
		return "", err
	}
	var archive bytes.Buffer
	if _, err := stack.WriteContext(&archive, dir, dockerfile); err != nil {
		return "", err
	}
	repo := imageRepository(v, env.Stack, migrateImage)
	object := buildPrefix + kebab(env.Stack) + "/" + migrateImage + "/" + version + ".tar.gz"
	return e.build(ctx, v, env.Stack, repo, version, "Dockerfile", object, archive.Bytes(), log)
}

// migratorUser is the IAM database user of the stack's migrator account:
// its email without `.gserviceaccount.com`.
func migratorUser(stack, project string) string {
	return accountID(stack, "migrator") + "@" + project + ".iam"
}
