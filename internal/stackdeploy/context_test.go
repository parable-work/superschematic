// TestIgnoreMatcher checks the ignore file's rules against what BuildKit
// decides for the same patterns: the last pattern that matches a path or
// one of its parents wins.
func TestIgnoreMatcher(t *testing.T) {
	cases := []struct {
		patterns []string
		path     string
		excluded bool
	}{
		{[]string{"*"}, "a", true},
		{[]string{"*"}, "a/b/c", true},
		{[]string{"*", "!a/b"}, "a/b/c", false},
		{[]string{"*", "!a/b"}, "a/c", true},
		{[]string{"*", "!a/b"}, "a", true},
		{[]string{"*", "!a/b", "a/b/lib"}, "a/b/lib/x.a", true},
		{[]string{"*", "!a/b", "a/b/lib"}, "a/b/libx", false},
		{[]string{"**/node_modules"}, "node_modules", true},
		{[]string{"**/node_modules"}, "x/y/node_modules/z.js", true},
		{[]string{"**/node_modules"}, "x/node_modules_old/z.js", false},
		{[]string{"a/*.go"}, "a/x.go", true},
		{[]string{"a/*.go"}, "a/b/x.go", false},
		{[]string{"a/**/b"}, "a/b", true},
		{[]string{"a/**/b"}, "a/x/y/b/c", true},
		{[]string{"a/**"}, "a/x/y", true},
		{[]string{"a/**"}, "ab", false},
		{[]string{"?.txt"}, "a.txt", true},
		{[]string{"?.txt"}, "ab.txt", false},
		{[]string{"[ab].txt"}, "b.txt", true},
		{[]string{"[ab].txt"}, "c.txt", false},
		{[]string{"a.b"}, "axb", false},
		{[]string{"!a", "a"}, "a", true},
		{[]string{"a", "!a"}, "a/b", false},
		{[]string{`\*`}, "*", true},
		{[]string{`\*`}, "x", false},
	}
	for _, tc := range cases {
		m, err := newIgnoreMatcher(tc.patterns)
		if err != nil {
			t.Fatalf("%q: %v", tc.patterns, err)
		}
		if got := m.excludes(tc.path); got != tc.excluded {
			t.Errorf("%q excludes %s = %v, want %v", tc.patterns, tc.path, got, tc.excluded)
		}
	}
	if _, err := newIgnoreMatcher([]string{"!"}); err == nil {
		t.Error("a lone ! is accepted")
	}
	if _, err := newIgnoreMatcher([]string{"[a"}); err == nil {
		t.Error("a malformed bracket expression is accepted")
	}
}

// TestReadIgnoreFile reads comments, blank lines, exceptions and absolute
// patterns as Docker does.
func TestReadIgnoreFile(t *testing.T) {
	got, err := readIgnoreFile([]byte("\xef\xbb\xbf# a comment\n\n  *  \n! /a/b/../c\n/d/\n  # not a comment\n"))
	if err != nil {
		t.Fatal(err)
	}
	want := []string{"*", "!a/c", "d", "# not a comment"}
	if !slices.Equal(got, want) {
		t.Errorf("patterns %q, want %q", got, want)
	}
}

// writeTree writes files under root; a name ending in a slash is an empty
// directory, and content "->target" a symlink.
func writeTree(t *testing.T, root string, files map[string]string) {
	t.Helper()
	for name, content := range files {
		p := filepath.Join(root, filepath.FromSlash(name))
		if strings.HasSuffix(name, "/") {
			if err := os.MkdirAll(p, 0o755); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if target, ok := strings.CutPrefix(content, "->"); ok {
			if err := os.Symlink(target, p); err != nil {
				t.Fatal(err)
			}
			continue
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

// generatedIgnore is a server's Dockerfile.dockerignore as servergen
// writes it.
const generatedIgnore = `# Code generated by superschematic. DO NOT EDIT.
*
!go/shop-api
!ir
!schemas/dist/server/shop-stack/shop-api
!third_party/superscalar/Cargo.lock
!third_party/superscalar/Cargo.toml
!third_party/superscalar/crates
!third_party/superscalar/go
third_party/superscalar/go/lib
**/node_modules
**/target
**/.git
`

func contextTree(t *testing.T) (root, dockerfile string) {
	t.Helper()
	root = t.TempDir()
	dir := "schemas/dist/server/shop-stack/shop-api/"
	writeTree(t, root, map[string]string{
		dir + "Dockerfile":                      "FROM scratch\n",
		dir + "Dockerfile.dockerignore":         generatedIgnore,
		dir + "main.go":                         "package main\n",
		"go/shop-api/implementation.go":         "package shopapi\n",
		"go/shop-api/run.sh":                    "#!/bin/sh\n",
		"go/shop-api/latest":                    "->implementation.go",
		"go/shop-api/node_modules/x.js":         "x",
		"go/shop-api/empty/":                    "",
		"ir/ir.go":                              "package ir\n",
		"ir/.git/config":                        "[core]\n",
		"schemas/services/shop-api/schema.ts":   "export {}\n",
		"schemas/dist/api/shop-api/api.go":      "package api\n",
		"third_party/superscalar/Cargo.toml":    "[workspace]\n",
		"third_party/superscalar/Cargo.lock":    "# lock\n",
		"third_party/superscalar/README.md":     "# superscalar\n",
		"third_party/superscalar/crates/a/a.rs": "fn a() {}\n",
		"third_party/superscalar/target/big":    "build output",
		"third_party/superscalar/go/scalar.go":  "package scalar\n",
		"third_party/superscalar/go/lib/x/l.a":  "archive",
		"secrets.env":                           "KEY=value\n",
	})
	if err := os.Chmod(filepath.Join(root, "go/shop-api/run.sh"), 0o750); err != nil {
		t.Fatal(err)
	}
	return root, filepath.Join(root, filepath.FromSlash(dir), "Dockerfile")
}

// archive is one entry of a written context.
type archive struct {
	name string
	mode int64
	link string
	body string
}

func readArchive(t *testing.T, data []byte) []archive {
	t.Helper()
	gz, err := gzip.NewReader(bytes.NewReader(data))
	if err != nil {
		t.Fatal(err)
	}
	tr := tar.NewReader(gz)
	var out []archive
	for {
		hdr, err := tr.Next()
		if errors.Is(err, io.EOF) {
			return out
		}
		if err != nil {
			t.Fatal(err)
		}
		if !hdr.ModTime.Equal(time.Unix(0, 0)) || hdr.Uid != 0 || hdr.Gid != 0 || hdr.Uname != "" || hdr.Gname != "" {
			t.Errorf("%s: time %v, owner %d:%d %q:%q", hdr.Name, hdr.ModTime, hdr.Uid, hdr.Gid, hdr.Uname, hdr.Gname)
		}
		body, _ := io.ReadAll(tr)
		out = append(out, archive{hdr.Name, hdr.Mode, hdr.Linkname, string(body)})
	}
}

// TestWriteContext writes the context of a server's Dockerfile: what the
// generated ignore file admits, in path order, with times, owners and
// modes normalized, and a digest that follows the content of the files
// it holds and nothing else.
func TestWriteContext(t *testing.T) {
	root, dockerfile := contextTree(t)
	var buf bytes.Buffer
	c, err := WriteContext(&buf, root, dockerfile)
	if err != nil {
		t.Fatal(err)
	}
	if c.Dockerfile != "schemas/dist/server/shop-stack/shop-api/Dockerfile" {
		t.Errorf("Dockerfile %s", c.Dockerfile)
	}
	entries := readArchive(t, buf.Bytes())
	var names []string
	for _, e := range entries {
		names = append(names, e.name)
	}
	want := []string{
		"go/shop-api/",
		"go/shop-api/empty/",
		"go/shop-api/implementation.go",
		"go/shop-api/latest",
		"go/shop-api/run.sh",
		"ir/",
		"ir/ir.go",
		"schemas/dist/server/shop-stack/shop-api/",
		"schemas/dist/server/shop-stack/shop-api/Dockerfile",
		"schemas/dist/server/shop-stack/shop-api/Dockerfile.dockerignore",
		"schemas/dist/server/shop-stack/shop-api/main.go",
		"third_party/superscalar/Cargo.lock",
		"third_party/superscalar/Cargo.toml",
		"third_party/superscalar/crates/",
		"third_party/superscalar/crates/a/",
		"third_party/superscalar/crates/a/a.rs",
		"third_party/superscalar/go/",
		"third_party/superscalar/go/scalar.go",
	}
	if !slices.Equal(names, want) {
		t.Errorf("the context holds\n  %s\nwant\n  %s", strings.Join(names, "\n  "), strings.Join(want, "\n  "))
	}
	if c.Files != 11 {
		t.Errorf("Files = %d, want 11", c.Files)
	}
	for _, e := range entries {
		switch e.name {
		case "go/shop-api/run.sh", "go/shop-api/", "ir/":
			if e.mode != 0o755 {
				t.Errorf("%s has mode %o, want 755", e.name, e.mode)
			}
		case "go/shop-api/latest":
			if e.link != "implementation.go" {
				t.Errorf("the link points at %q", e.link)
			}
		case "ir/ir.go":
			if e.mode != 0o644 || e.body != "package ir\n" {
				t.Errorf("ir/ir.go: mode %o, body %q", e.mode, e.body)
			}
		}
	}

	digest := func() string {
		t.Helper()
		c, err := WriteContext(io.Discard, root, dockerfile)
		if err != nil {
			t.Fatal(err)
		}
		return c.Digest
	}
	if got := digest(); got != c.Digest {
		t.Fatalf("a second write has digest %s, the first %s", got, c.Digest)
	}
	// A file's time and its mode bits but the executable one do not
	// change the context; a file the ignore file leaves out does not
	// either; a file it holds does.
	impl := filepath.Join(root, "go/shop-api/implementation.go")
	if err := os.Chtimes(impl, time.Now(), time.Now().Add(-time.Hour)); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(impl, 0o600); err != nil {
		t.Fatal(err)
	}
	writeTree(t, root, map[string]string{"third_party/superscalar/target/more": "x", "secrets.env": "KEY=other\n"})
	if got := digest(); got != c.Digest {
		t.Errorf("times, modes and left-out files changed the digest")
	}
	writeTree(t, root, map[string]string{"go/shop-api/new.go": "package shopapi\n"})
	if got := digest(); got == c.Digest {
		t.Errorf("a new file of the implementation left the digest as it was")
	}
}

// TestWriteContextRefusals: a Dockerfile outside its context or missing.
func TestWriteContextRefusals(t *testing.T) {
	root, dockerfile := contextTree(t)
	if _, err := WriteContext(io.Discard, filepath.Join(root, "go"), dockerfile); err == nil || !strings.Contains(err.Error(), "outside its build context") {
		t.Errorf("a Dockerfile outside the context: %v", err)
	}
	if _, err := WriteContext(io.Discard, root, filepath.Join(root, "Dockerfile")); err == nil {
		t.Error("a missing Dockerfile is accepted")
	}
}

// TestWriteContextKeepsTheDockerfile: as Docker's client does, the context
// holds the Dockerfile and its ignore file even when the ignore file
// leaves them out, and falls back to the root's .dockerignore.
func TestWriteContextKeepsTheDockerfile(t *testing.T) {
	root := t.TempDir()
	writeTree(t, root, map[string]string{
		"build/Dockerfile": "FROM scratch\n",
		".dockerignore":    "*\n!src\n",
		"src/a.go":         "package a\n",
		"other/b.go":       "package b\n",
	})
	var buf bytes.Buffer
	if _, err := WriteContext(&buf, root, filepath.Join(root, "build/Dockerfile")); err != nil {
		t.Fatal(err)
	}
	var names []string
	for _, e := range readArchive(t, buf.Bytes()) {
		names = append(names, e.name)
	}
	want := []string{".dockerignore", "build/Dockerfile", "src/", "src/a.go"}
	if !slices.Equal(names, want) {
		t.Errorf("the context holds %q, want %q", names, want)
	}
}
