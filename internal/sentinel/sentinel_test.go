func TestContent(t *testing.T) {
	got := Content("web-db", ir.SchemaKindDB, naming.Default())
	want := `// Code generated by superschematic sentinel. DO NOT EDIT.
import { service, SchemaKind } from "@superschematic/schema-config";
export const WebDb = service({ name: "web-db", kind: SchemaKind.DB });
`
	if got != want {
		t.Errorf("Content mismatch\ngot:\n%s\nwant:\n%s", got, want)
	}

	for _, kind := range []ir.SchemaKind{
		ir.SchemaKindDB, ir.SchemaKindAPI, ir.SchemaKindGeneral,
	} {
		content := Content("svc", kind, naming.Default())
		if !strings.Contains(content, "kind: SchemaKind."+string(kind)) {
			t.Errorf("Content(svc, %s) does not pass the kind through:\n%s", kind, content)
		}
	}
}

// TestContentImportsThroughThePackageAlias: a distribution that re-exports
// the schema-config package under its own name declares the alias in
// [package_aliases]; the sentinel then imports the author's spelling, so a
// committed sentinel does not move when the distribution adopts the core.
func TestContentImportsThroughThePackageAlias(t *testing.T) {
	n := naming.Default()
	n.PackageAliases = map[string]string{"@acme/schema-config": ConfigPackage}
	got := Content("web-db", ir.SchemaKindDB, n)
	want := `// Code generated by superschematic sentinel. DO NOT EDIT.
import { service, SchemaKind } from "@acme/schema-config";
export const WebDb = service({ name: "web-db", kind: SchemaKind.DB });
`
	if got != want {
		t.Errorf("Content mismatch\ngot:\n%s\nwant:\n%s", got, want)
	}
}

// TestContentRendersAnExtensionKindAsAString: SchemaKind is a closed enum of
// the core kinds, so a kind an extension registers has no member to name.
// The sentinel writes the string form, which the kind slot's SchemaKindName
// type admits, and drops the SchemaKind import it would not use.
func TestContentRendersAnExtensionKindAsAString(t *testing.T) {
	got := Content("fleet-svc", ir.SchemaKind("Fleet"), naming.Default())
	want := `// Code generated by superschematic sentinel. DO NOT EDIT.
import { service } from "@superschematic/schema-config";
export const FleetSvc = service({ name: "fleet-svc", kind: "Fleet" });
`
	if got != want {
		t.Errorf("Content mismatch\ngot:\n%s\nwant:\n%s", got, want)
	}
	if strings.Contains(got, "SchemaKind") {
		t.Errorf("extension-kind sentinel references the closed SchemaKind enum:\n%s", got)
	}
}

func TestEmitServiceRejectsAKindTheRegistryDoesNotKnow(t *testing.T) {
	reg := registry.New(naming.Naming{})
	cfg := &schemaconfig.SchemaConfig{Name: "svc", Kind: ir.SchemaKind("Bogus")}
	_, err := EmitService(t.TempDir(), cfg, reg)
	if err == nil {
		t.Fatal("EmitService wrote a sentinel for a kind the registry does not know")
	}
	if !strings.Contains(err.Error(), "unknown schema kind") {
		t.Errorf("error %q does not name the unknown kind", err.Error())
	}
}

// groupingRegistry registers a fixture kind whose services get no sentinel,
// the way an extension's grouping kind does. The kind set is the
// registry's, so the name is arbitrary.
func groupingRegistry(t *testing.T) *registry.Registry {
	t.Helper()
	reg := registry.New(naming.Naming{})
	if err := reg.RegisterKind(registry.KindSpec{Name: "Grouping", Extension: "test", NoSentinel: true}); err != nil {
		t.Fatal(err)
	}
	return reg
}

func TestSkipsFollowsKindSpecNoSentinel(t *testing.T) {
	reg := groupingRegistry(t)
	if !Skips(reg, ir.SchemaKind("Grouping")) {
		t.Error("Skips(Grouping) = false, want true for a NoSentinel kind")
	}
	if Skips(reg, ir.SchemaKindDB) {
		t.Error("Skips(DB) = true, want false")
	}
	if Skips(nil, ir.SchemaKind("Grouping")) {
		t.Error("Skips with a nil registry must skip nothing")
	}
	cfg := &schemaconfig.SchemaConfig{Name: "grp", Kind: ir.SchemaKind("Grouping")}
	if _, err := EmitService(t.TempDir(), cfg, reg); err == nil {
		t.Error("EmitService wrote a sentinel for a NoSentinel kind")
	}
}

func TestEmitServiceIdempotent(t *testing.T) {
	dir := t.TempDir()
	cfg := &schemaconfig.SchemaConfig{Name: "web-db", Kind: ir.SchemaKindDB}

	changed, err := EmitService(dir, cfg, nil)
	if err != nil {
		t.Fatal(err)
	}
	if !changed {
		t.Error("first EmitService reported no change")
	}
	first, err := os.ReadFile(filepath.Join(dir, "src", "service.generated.ts"))
	if err != nil {
		t.Fatal(err)
	}

	changed, err = EmitService(dir, cfg, nil)
	if err != nil {
		t.Fatal(err)
	}
	if changed {
		t.Error("second EmitService reported a change")
	}
	second, err := os.ReadFile(filepath.Join(dir, "src", "service.generated.ts"))
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Error("sentinel bytes changed across runs")
	}
}

func TestEnsureIndexExport(t *testing.T) {
	t.Run("creates missing index", func(t *testing.T) {
		dir := t.TempDir()
		cfg := &schemaconfig.SchemaConfig{Name: "web-db", Kind: ir.SchemaKindDB}
		if _, err := EmitService(dir, cfg, nil); err != nil {
			t.Fatal(err)
		}
		data, err := os.ReadFile(filepath.Join(dir, "src", "index.ts"))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.Contains(string(data), indexExportLine) {
			t.Errorf("created index missing re-export:\n%s", data)
		}
	})

	t.Run("appends to hand-written index once", func(t *testing.T) {
		dir := t.TempDir()
		indexPath := filepath.Join(dir, "src", "index.ts")
		if err := os.MkdirAll(filepath.Dir(indexPath), 0o755); err != nil {
			t.Fatal(err)
		}
		handWritten := "export { Tenant } from \"./tenant.schema\";\n"
		if err := os.WriteFile(indexPath, []byte(handWritten), 0o644); err != nil {
			t.Fatal(err)
		}

		cfg := &schemaconfig.SchemaConfig{Name: "web-db", Kind: ir.SchemaKindDB}
		if _, err := EmitService(dir, cfg, nil); err != nil {
			t.Fatal(err)
		}
		data, err := os.ReadFile(indexPath)
		if err != nil {
			t.Fatal(err)
		}
		want := handWritten + indexExportLine + "\n"
		if string(data) != want {
			t.Errorf("index after append\ngot:\n%s\nwant:\n%s", data, want)
		}

		if _, err := EmitService(dir, cfg, nil); err != nil {
			t.Fatal(err)
		}
		again, err := os.ReadFile(indexPath)
		if err != nil {
			t.Fatal(err)
		}
		if string(again) != want {
			t.Errorf("rerun duplicated the re-export line:\n%s", again)
		}
	})

	t.Run("recognizes single-quote line", func(t *testing.T) {
		dir := t.TempDir()
		indexPath := filepath.Join(dir, "src", "index.ts")
		if err := os.MkdirAll(filepath.Dir(indexPath), 0o755); err != nil {
			t.Fatal(err)
		}
		existing := "export * from './service.generated';\n"
		if err := os.WriteFile(indexPath, []byte(existing), 0o644); err != nil {
			t.Fatal(err)
		}
		changed, err := ensureIndexExport(dir)
		if err != nil {
			t.Fatal(err)
		}
		if changed {
			t.Error("single-quote re-export line was not recognized")
		}
	})
}

func TestEnsureSiblings(t *testing.T) {
	root := t.TempDir()

	writeService := func(name string, files map[string]string) string {
		dir := filepath.Join(root, name)
		for rel, content := range files {
			path := filepath.Join(dir, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
		}
		return dir
	}

	dataSvc := writeService("data-svc", map[string]string{
		"tsconfig.json":      "{}",
		"schema.config.json": `{"name": "data-svc", "kind": "DB", "outputs": {}}`,
	})
	noTSConfig := writeService("no-tsconfig", map[string]string{
		"schema.config.json": `{"name": "no-tsconfig", "kind": "DB", "outputs": {}}`,
	})
	notAService := writeService("not-a-service", map[string]string{
		"tsconfig.json": "{}",
	})
	underscoreSvc := writeService("_fixture", map[string]string{
		"tsconfig.json":      "{}",
		"schema.config.json": `{"name": "_fixture", "kind": "DB", "outputs": {}}`,
	})
	// The data-form kind enum is @superschematic/schema-config's, so a fixture kind
	// can only arrive through the TypeScript form here.
	groupingSvc := writeService("grouping-svc", map[string]string{
		"tsconfig.json":    "{}",
		"schema.config.ts": "// read through the injected hook",
	})
	tsSvc := writeService("ts-svc", map[string]string{
		"tsconfig.json":    "{}",
		"schema.config.ts": "// read through the injected hook",
	})

	var tsReads []string
	err := EnsureSiblings(root, Options{
		Registry: groupingRegistry(t),
		ReadTSConfig: func(servicePath string) (*schemaconfig.SchemaConfig, error) {
			name := filepath.Base(servicePath)
			tsReads = append(tsReads, name)
			if name == "grouping-svc" {
				return &schemaconfig.SchemaConfig{Name: name, Kind: ir.SchemaKind("Grouping")}, nil
			}
			return &schemaconfig.SchemaConfig{Name: name, Kind: ir.SchemaKindAPI}, nil
		},
	})
	if err != nil {
		t.Fatal(err)
	}

	if _, err := os.Stat(filepath.Join(dataSvc, "src", "service.generated.ts")); err != nil {
		t.Errorf("data-form sibling got no sentinel: %v", err)
	}
	if _, err := os.Stat(filepath.Join(tsSvc, "src", "service.generated.ts")); err != nil {
		t.Errorf("ts-form sibling got no sentinel: %v", err)
	}
	if len(tsReads) != 2 || tsReads[0] != "grouping-svc" || tsReads[1] != "ts-svc" {
		t.Errorf("ReadTSConfig calls = %v, want grouping-svc and ts-svc", tsReads)
	}
	for _, dir := range []string{noTSConfig, notAService, underscoreSvc, groupingSvc} {
		if _, err := os.Stat(filepath.Join(dir, "src", "service.generated.ts")); err == nil {
			t.Errorf("%s should have been skipped", filepath.Base(dir))
		}
	}

	// A sentinel newer than the config is fresh: the config is not re-read.
	past := time.Now().Add(-time.Hour)
	if err := os.Chtimes(filepath.Join(tsSvc, "schema.config.ts"), past, past); err != nil {
		t.Fatal(err)
	}
	// The grouping service never gets a sentinel, so it has nothing to be
	// fresh against and is read on every sweep.
	tsReads = nil
	err = EnsureSiblings(root, Options{
		Registry: groupingRegistry(t),
		ReadTSConfig: func(servicePath string) (*schemaconfig.SchemaConfig, error) {
			name := filepath.Base(servicePath)
			tsReads = append(tsReads, name)
			if name == "grouping-svc" {
				return &schemaconfig.SchemaConfig{Name: name, Kind: ir.SchemaKind("Grouping")}, nil
			}
			return &schemaconfig.SchemaConfig{Name: name, Kind: ir.SchemaKindAPI}, nil
		},
	})
	if err != nil {
		t.Fatal(err)
	}
	if len(tsReads) != 1 || tsReads[0] != "grouping-svc" {
		t.Errorf("ReadTSConfig calls = %v, want just grouping-svc (ts-svc is fresh)", tsReads)
	}
}
