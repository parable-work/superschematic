// TestEnsureSiblingsKeepsTheConfigTypeABuildWrote: the sweep reads configs
// only, so when a config edit makes a typed sentinel stale it keeps the
// config type the service's build wrote, and drops it only when the
// service stops being an API.
func TestEnsureSiblingsKeepsTheConfigTypeABuildWrote(t *testing.T) {
	root := t.TempDir()
	dir := filepath.Join(root, "shop-api")
	if err := os.MkdirAll(dir, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "tsconfig.json"), []byte("{}"), 0o644); err != nil {
		t.Fatal(err)
	}
	configType := &ConfigType{Name: "ShopApiConfig", Module: "./config.schema"}
	if _, err := EmitService(dir, &schemaconfig.SchemaConfig{Name: "shop-api", Kind: ir.SchemaKindAPI}, nil, configType); err != nil {
		t.Fatal(err)
	}
	sentinelPath := filepath.Join(dir, "src", "service.generated.ts")

	sweepAfterEditing := func(config string) string {
		t.Helper()
		configPath := filepath.Join(dir, "schema.config.json")
		if err := os.WriteFile(configPath, []byte(config), 0o644); err != nil {
			t.Fatal(err)
		}
		past, now := time.Now().Add(-time.Hour), time.Now()
		if err := os.Chtimes(sentinelPath, past, past); err != nil {
			t.Fatal(err)
		}
		if err := os.Chtimes(configPath, now, now); err != nil {
			t.Fatal(err)
		}
		if err := EnsureSiblings(root, Options{}); err != nil {
			t.Fatal(err)
		}
		data, err := os.ReadFile(sentinelPath)
		if err != nil {
			t.Fatal(err)
		}
		return string(data)
	}

	if got, want := sweepAfterEditing(`{"name": "shop-api", "kind": "API", "public": true, "outputs": {}}`), Content("shop-api", ir.SchemaKindAPI, naming.Default(), configType); got != want {
		t.Errorf("the sweep stripped the config type\ngot:\n%s\nwant:\n%s", got, want)
	}

	// A build that wrote the API's jobs too: the sweep keeps both.
	if _, err := EmitService(dir, &schemaconfig.SchemaConfig{Name: "shop-api", Kind: ir.SchemaKindAPI}, nil, configType, "Reindex", "ShipOrders"); err != nil {
		t.Fatal(err)
	}
	if got, want := sweepAfterEditing(`{"name": "shop-api", "kind": "API", "outputs": {}}`), Content("shop-api", ir.SchemaKindAPI, naming.Default(), configType, "Reindex", "ShipOrders"); got != want {
		t.Errorf("the sweep stripped the jobs\ngot:\n%s\nwant:\n%s", got, want)
	}
	if got, want := sweepAfterEditing(`{"name": "shop-api", "kind": "General", "outputs": {}}`), Content("shop-api", ir.SchemaKindGeneral, naming.Default(), nil); got != want {
		t.Errorf("a General handle kept a config type\ngot:\n%s\nwant:\n%s", got, want)
	}
}

// TestTypedSentinelTypeChecks compiles a typed sentinel with tsc beside the
// @envVars class it imports: the handle is the API handle with that config
// type, and not a DB handle.
func TestTypedSentinelTypeChecks(t *testing.T) {
	tsc, err := filepath.Abs(filepath.Join("..", "..", "packages", "node_modules", ".bin", "tsc"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(tsc); err != nil {
		testpaths.RequireOrSkipTS(t, "packages/ dependencies not installed (run bun install in packages/)")
	}
	configPackage, err := filepath.Abs(filepath.Join("..", "..", "packages", "schema-config", "src", "index.ts"))
	if err != nil {
		t.Fatal(err)
	}

	schema := ir.NewSchema("shop-api", ir.SchemaKindAPI)
	schema.Types["ShopApiConfig"] = &ir.TypeDef{Name: "ShopApiConfig", Owner: "src/config.schema.ts", EnvVars: true}
	dir := t.TempDir()
	files := map[string]string{
		"tsconfig.json": fmt.Sprintf(`{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "moduleResolution": "Bundler",
    "strict": true,
    "strictPropertyInitialization": false,
    "experimentalDecorators": true,
    "noEmit": true,
    "skipLibCheck": true,
    "paths": { "@superschematic/schema-config": [%q] }
  },
  "include": ["src/**/*.ts"]
}
`, configPackage),
		"src/config.schema.ts": `import { envVars } from "@superschematic/schema-config";

@envVars
export abstract class ShopApiConfig {
  LOG_LEVEL: string;
}
`,
		"src/service.generated.ts": Content("shop-api", ir.SchemaKindAPI, naming.Default(), ConfigTypeOf(schema)),
		"src/check.ts": `import type { ServiceHandle } from "@superschematic/schema-config";
import type { ShopApiConfig } from "./config.schema";
import { ShopApi } from "./service.generated";

export const typed: ServiceHandle<"API", ShopApiConfig> = ShopApi;
// @ts-expect-error an API handle is not a DB handle
export const db: ServiceHandle<"DB"> = ShopApi;
`,
	}
	for rel, content := range files {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	cmd := exec.Command(tsc, "-p", "tsconfig.json")
	cmd.Dir = dir
	if out, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("the typed sentinel does not type-check: %v\n%s", err, out)
	}
}
