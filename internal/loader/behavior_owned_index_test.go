// ownedIndexDB is a database whose Ticket numbers its rows on its number
// field, a Numbering (D103's step 4), and keeps an index over keys, and
// whose Allowance implements a Budget whose meter reads its limit from the
// table's budgetLimit field (D104). edit, when given, changes the document
// before it is written.
func ownedIndexDB(t *testing.T, keys []string, edit func(types map[string]any)) (*ir.Schema, error) {
	t.Helper()
	field := func(name, typeName string, more map[string]any) map[string]any {
		f := map[string]any{"name": name, "typeRef": map[string]any{"name": typeName}}
		for k, v := range more {
			f[k] = v
		}
		return f
	}
	key := map[string]any{"required": true, "key": true, "autoGenerated": true}
	types := map[string]any{
		"Ticket": map[string]any{"name": "Ticket", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Numbering", "field": "number", "config": map[string]any{"format": "T-{seq}"}}},
			"indexes":   []any{map[string]any{"keys": keys, "unique": true}},
			"fields": []any{
				field("id", "Identity.UUID", key),
				field("title", "string", map[string]any{"required": true}),
				field("createdAt", "Temporal.DateTime", map[string]any{"required": true}),
			}},
		"Allowance": map[string]any{"name": "Allowance", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Budget", "implements": true, "config": map[string]any{
				"meters": map[string]any{"cost": map[string]any{"limitField": "budgetLimit", "reset": "monthly"}},
			}}},
			"fields": []any{
				field("id", "Identity.UUID", key),
				field("budgetLimit", "Generic.Int64", nil),
			}},
	}
	if edit != nil {
		edit(types)
	}
	doc := map[string]any{
		"name": "notes-db", "kind": "DB",
		"scalars": map[string]any{
			"Identity.UUID":     map[string]any{"name": "Identity.UUID", "languagePrimitive": "string"},
			"Temporal.DateTime": map[string]any{"name": "Temporal.DateTime", "languagePrimitive": "string"},
			"Generic.Int64":     map[string]any{"name": "Generic.Int64", "languagePrimitive": "number"},
		},
		"types": types,
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return LoadService(writeService(t, map[string]string{
		"schema.config.json":    `{"name": "notes-db", "kind": "DB", "outputs": {}}`,
		"src/notes.schema.json": string(data),
	}))
}

// TestAnIndexOnAnOwnedFieldKeepsTheBehaviorsTables: an index that names a
// field a behavior owns, a Numbering's number alone or after a field of the
// table's own, beside a table whose Budget reads a field of its own, loads
// with every use's storage: Ticket's counts, and Allowance's Budget
// sub-tables. The behaviors' checks read each table's fields with the
// fields its uses own already beside them, so the index does not leave
// every table of the database with no fields to read.
func TestAnIndexOnAnOwnedFieldKeepsTheBehaviorsTables(t *testing.T) {
	for name, keys := range map[string][]string{
		"the owned field alone":    {"number"},
		"after a field of its own": {"title", "number"},
	} {
		t.Run(name, func(t *testing.T) {
			db, err := ownedIndexDB(t, keys, nil)
			if err != nil {
				t.Fatal(err)
			}
			for _, want := range []string{"TicketNumberCounts", "AllowanceBudgetMeters"} {
				if td := db.Types[want]; td == nil || td.BehaviorTable == nil {
					t.Errorf("the schema has no %s: its types are %v", want, slices.Sorted(maps.Keys(db.Types)))
				}
			}
		})
	}
	// A use of the indexed table itself whose config names a field of it,
	// a Constants over its title, reads that field too.
	db, err := ownedIndexDB(t, []string{"number"}, func(types map[string]any) {
		delete(types, "Allowance")
		ticket := types["Ticket"].(map[string]any)
		ticket["behaviors"] = append(ticket["behaviors"].([]any),
			map[string]any{"name": "Constants", "implements": true, "config": map[string]any{"fields": []any{"title"}}})
	})
	if err != nil {
		t.Fatal(err)
	}
	if td := db.Types["TicketNumberCounts"]; td == nil || td.BehaviorTable == nil {
		t.Errorf("the schema has no TicketNumberCounts: its types are %v", slices.Sorted(maps.Keys(db.Types)))
	}
}

// TestAnIndexOfNoFieldLeavesOtherTablesFieldsRead: an index that names no
// field of its table is refused for that table alone. Another table's
// Budget, whose limitField is a field of its own, is not also said to name
// no field, as it was when the refused table left every table of the
// database unmodelled.
func TestAnIndexOfNoFieldLeavesOtherTablesFieldsRead(t *testing.T) {
	_, err := ownedIndexDB(t, []string{"nubmer"}, nil)
	if want := `key "nubmer" names no field of Ticket`; err == nil || !strings.Contains(err.Error(), want) {
		t.Fatalf("LoadService = %v, want an error holding %q", err, want)
	}
	if strings.Contains(err.Error(), "Allowance") {
		t.Errorf("LoadService = %v, which also refuses Allowance's Budget", err)
	}
}

// TestAConfigOfAnUnmodelledTableSaysWhy: a field-reading config of a table
// the build refuses (its index names no field) says why the table's fields
// cannot be read, not that it has none.
func TestAConfigOfAnUnmodelledTableSaysWhy(t *testing.T) {
	_, err := ownedIndexDB(t, []string{"nubmer"}, func(types map[string]any) {
		ticket := types["Ticket"].(map[string]any)
		ticket["behaviors"] = append(ticket["behaviors"].([]any),
			map[string]any{"name": "Constants", "implements": true, "config": map[string]any{"fields": []any{"title"}}})
	})
	if err == nil {
		t.Fatal("LoadService loaded an index that names no field")
	}
	if strings.Contains(err.Error(), "its fields: none)") {
		t.Errorf("LoadService = %v, which says Ticket has no fields", err)
	}
	if want := `its fields: none, as the build refuses the table: table Ticket: unique key "nubmer" names no column of table ticket`; !strings.Contains(err.Error(), want) {
		t.Errorf("LoadService = %v, want an error holding %q", err, want)
	}
}
