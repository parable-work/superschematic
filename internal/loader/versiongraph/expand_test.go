package versiongraph

import (
	"reflect"
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// TestReleasedTable: a member with released: true gets <Member>Released
// (D139): a key of its own, the relation to the root, which takes the row
// with it, the entity key, the member's content fields as the member
// declares them, and the commit and sequence of the release; unique per
// root and entity, with the member's indexes over content alone.
func TestReleasedTable(t *testing.T) {
	schema := ir.NewSchema("recipes", ir.SchemaKindDB)
	schema.Types["Recipe"] = &ir.TypeDef{
		Name: "Recipe", Role: ir.RoleDBTable, Owner: "src/recipe.schema.ts", VersionGraph: &ir.VersionGraphConfig{},
		Fields: []*ir.FieldDef{{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true}},
	}
	schema.Types["Part"] = &ir.TypeDef{
		Name: "Part", Role: ir.RoleDBTable, Owner: "src/recipe.schema.ts", Versioned: true,
		GraphMember: &ir.GraphMemberConfig{Graph: "Recipe", Order: "rank", Released: true},
		Fields: []*ir.FieldDef{
			{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true},
			{Name: "recipe", TypeRef: ir.TypeRef{Name: "Recipe"}, Required: true, Relation: &ir.RelationDef{Type: "Recipe"}},
			{Name: "rank", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: "heading", TypeRef: ir.TypeRef{Name: "string"}, Required: true, SearchField: true},
			{Name: "notes", TypeRef: ir.TypeRef{Name: "Generic.JSON"}, ConflictUnit: ir.ConflictUnitKeyed},
			{Name: "scratch", TypeRef: ir.TypeRef{Name: "string"}, ConflictUnit: ir.ConflictUnitExcluded},
			{Name: "updatedBy", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true},
		},
		Indexes: []ir.IndexDef{
			{Keys: []string{"rank"}},
			{Keys: []string{"heading"}, Unique: true, Name: "heading"},
			{Keys: []string{"recipe", "rank"}},
			{Keys: []string{"scratch"}},
		},
	}
	schema.Types["Step"] = &ir.TypeDef{
		Name: "Step", Role: ir.RoleDBTable, Owner: "src/recipe.schema.ts", Versioned: true,
		GraphMember: &ir.GraphMemberConfig{Graph: "Recipe"},
		Fields: []*ir.FieldDef{
			{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true},
			{Name: "recipe", TypeRef: ir.TypeRef{Name: "Recipe"}, Required: true, Relation: &ir.RelationDef{Type: "Recipe"}},
		},
	}
	Expand(schema)

	if schema.Types["StepReleased"] != nil {
		t.Fatal("a member without released got a released table")
	}
	released := schema.Types["PartReleased"]
	if released == nil {
		t.Fatal("no PartReleased")
	}
	if released.ReleasedOf != "Part" || released.Role != ir.RoleDBTable || released.Origin != ir.OriginVersionGraph || released.Versioned || released.GraphMember != nil {
		t.Fatalf("PartReleased is %+v", released)
	}
	var names []string
	fields := map[string]*ir.FieldDef{}
	for _, fd := range released.Fields {
		names = append(names, fd.Name)
		fields[fd.Name] = fd
	}
	if want := []string{"id", "recipe", "entityKey", "rank", "heading", "notes", "commit", "sequence"}; !reflect.DeepEqual(names, want) {
		t.Fatalf("PartReleased has fields %v, want %v", names, want)
	}
	if !fields["id"].Key || !fields["id"].AutoGenerated {
		t.Errorf("id is %+v, want a generated key", fields["id"])
	}
	if rel := fields["recipe"].Relation; rel == nil || rel.Type != "Recipe" || rel.OnDelete != "CASCADE" || !fields["recipe"].Required {
		t.Errorf("recipe is %+v, want a required relation deleted with its root", fields["recipe"])
	}
	if rel := fields["commit"].Relation; rel == nil || rel.Type != "RecipeCommit" || rel.OnDelete != "CASCADE" {
		t.Errorf("commit is %+v, want a relation to RecipeCommit", fields["commit"])
	}
	if fd := fields["entityKey"]; fd.TypeRef.Name != "Identity.UUID" || !fd.Required || fd.AutoGenerated {
		t.Errorf("entityKey is %+v, want a required UUID the release gives", fd)
	}
	if !fields["heading"].SearchField {
		t.Error("heading lost its @searchField")
	}
	if fields["notes"].ConflictUnit != "" || schema.Types["Part"].Fields[4].ConflictUnit != ir.ConflictUnitKeyed {
		t.Error("the released copy keeps a conflict unit, or cleared the member's")
	}
	wantIndexes := []ir.IndexDef{
		{Keys: []string{"recipe", "entityKey"}, Unique: true, Name: "root_entity"},
		{Keys: []string{"rank"}},
		{Keys: []string{"heading"}, Unique: true, Name: "heading"},
	}
	if !reflect.DeepEqual(released.Indexes, wantIndexes) {
		t.Fatalf("PartReleased has indexes %+v, want %+v", released.Indexes, wantIndexes)
	}
	generated := map[string]bool{}
	for _, idx := range Indexes(schema, schema.Types["Recipe"]) {
		generated[idx.Type+"."+idx.Index.Name] = true
	}
	if !generated["PartReleased.root_entity"] {
		t.Error("Indexes does not list the released table's root_entity index")
	}
}
