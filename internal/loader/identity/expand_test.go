// userSchema returns a DB schema whose Account table carries the User trait
// and, with roles, whose Role table carries the UserRole trait.
func userSchema(roles bool) *ir.Schema {
	schema := ir.NewSchema("users", ir.SchemaKindDB)
	schema.Scalars["Contact.Email"] = &ir.ScalarDef{Name: "Contact.Email", LanguagePrimitive: ir.LanguageString, CaseInsensitive: true}
	schema.Scalars["Identity.UUID"] = &ir.ScalarDef{Name: "Identity.UUID", LanguagePrimitive: ir.LanguageString}
	key := func() *ir.FieldDef {
		return &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true}
	}
	schema.Types["Account"] = &ir.TypeDef{
		Name: "Account", Role: ir.RoleDBTable, Owner: "src/accounts.schema.ts",
		User: &ir.UserTrait{Login: "email"},
		Fields: []*ir.FieldDef{
			key(),
			{Name: "email", TypeRef: ir.TypeRef{Name: "Contact.Email"}, Required: true, Unique: true},
		},
	}
	if roles {
		schema.Types["Role"] = &ir.TypeDef{
			Name: "Role", Role: ir.RoleDBTable, Owner: "src/roles.schema.ts",
			UserRole: &ir.UserRoleTrait{},
			Fields: []*ir.FieldDef{
				key(),
				{Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
				{Name: "permissions", TypeRef: ir.TypeRef{Name: "string", IsArray: true}, Required: true},
			},
		}
	}
	return schema
}

// column is what a test reads of an added field.
type column struct {
	name     string
	typeName string
	required bool
	unique   bool
	key      bool
	auto     bool
	secret   bool
	onDelete string // the relation's, "" for a field that is not one
}

func columnOf(fd *ir.FieldDef) column {
	c := column{
		name: fd.Name, typeName: fd.TypeRef.Name, required: fd.Required, unique: fd.Unique,
		key: fd.Key, auto: fd.AutoGenerated, secret: fd.Secret,
	}
	if fd.Relation != nil {
		c.onDelete = fd.Relation.OnDelete
		if fd.Relation.Type != fd.TypeRef.Name {
			c.onDelete = "relation to " + fd.Relation.Type
		}
	}
	return c
}

// TestExpandAddsTheContractTables: the added tables have exactly the fields
// ir/identity.go lists, typed and constrained as it says, each with the
// identity origin, owned by the User table's file.
func TestExpandAddsTheContractTables(t *testing.T) {
	schema := userSchema(true)
	scalars := Expand(schema)

	id := column{name: "id", typeName: "Identity.UUID", required: true, key: true, auto: true}
	want := map[string][]column{
		ir.IdentitySessionTable: {
			id,
			{name: ir.IdentitySessionUserField, typeName: "Account", required: true, onDelete: "CASCADE"},
			{name: ir.IdentitySessionTokenHashField, typeName: "Crypto.SHA256", required: true, unique: true},
			{name: ir.IdentitySessionCreatedAtField, typeName: "Temporal.DateTime", required: true},
			{name: ir.IdentitySessionExpiresAtField, typeName: "Temporal.DateTime", required: true},
			{name: ir.IdentitySessionLastSeenAtField, typeName: "Temporal.DateTime"},
			{name: ir.IdentitySessionRevokedAtField, typeName: "Temporal.DateTime"},
		},
		ir.IdentityCredentialTable: {
			id,
			{name: ir.IdentityCredentialUserField, typeName: "Account", required: true, unique: true, onDelete: "CASCADE"},
			{name: ir.IdentityCredentialPasswordHashField, typeName: "string", required: true, secret: true},
			{name: ir.IdentityCredentialPasswordChangedAtField, typeName: "Temporal.DateTime", required: true},
			{name: ir.IdentityCredentialDisabledAtField, typeName: "Temporal.DateTime"},
		},
		ir.IdentityRoleGrantTable: {
			id,
			{name: ir.IdentityRoleGrantUserField, typeName: "Account", required: true, onDelete: "CASCADE"},
			{name: ir.IdentityRoleGrantRoleField, typeName: "Role", required: true, onDelete: "CASCADE"},
			{name: ir.IdentityRoleGrantGrantedAtField, typeName: "Temporal.DateTime", required: true},
		},
	}
	for name, columns := range want {
		td := schema.Types[name]
		if td == nil {
			t.Fatalf("Expand added no %s", name)
		}
		if td.Role != ir.RoleDBTable || td.Origin != ir.OriginIdentity || td.Owner != "src/accounts.schema.ts" {
			t.Errorf("%s: role %s, origin %q, owner %q; want a DB table of origin identity owned by the User table's file", name, td.Role, td.Origin, td.Owner)
		}
		var got []column
		for _, fd := range td.Fields {
			got = append(got, columnOf(fd))
			if fd.Origin != ir.OriginIdentity {
				t.Errorf("%s.%s has origin %q, want %q", name, fd.Name, fd.Origin, ir.OriginIdentity)
			}
			if fd.TypeRef.IsArray || fd.TypeRef.IsMap || fd.JsonField {
				t.Errorf("%s.%s is not one column", name, fd.Name)
			}
		}
		if !reflect.DeepEqual(got, columns) {
			t.Errorf("%s fields:\n got %+v\nwant %+v", name, got, columns)
		}
	}

	grant := schema.Types[ir.IdentityRoleGrantTable]
	wantIndex := []ir.IndexDef{{Keys: []string{"user", "role"}, Unique: true, Name: "user_role", Origin: ir.OriginIdentity}}
	if !reflect.DeepEqual(grant.Indexes, wantIndex) {
		t.Errorf("UserRoleGrant indexes = %+v, want %+v", grant.Indexes, wantIndex)
	}
	session := schema.Types[ir.IdentitySessionTable]
	wantSessionIndex := []ir.IndexDef{{Keys: []string{"user"}, Name: "user", Origin: ir.OriginIdentity}}
	if !reflect.DeepEqual(session.Indexes, wantSessionIndex) {
		t.Errorf("Session indexes = %+v, want %+v", session.Indexes, wantSessionIndex)
	}
	if indexes := schema.Types[ir.IdentityCredentialTable].Indexes; len(indexes) != 0 {
		t.Errorf("UserCredential has indexes %+v, want none", indexes)
	}
	wantGenerated := []GeneratedIndex{{ir.IdentitySessionTable, wantSessionIndex[0]}, {ir.IdentityRoleGrantTable, wantIndex[0]}}
	if got := Indexes(schema); !reflect.DeepEqual(got, wantGenerated) {
		t.Errorf("Indexes = %+v, want the indexes Expand adds, %+v", got, wantGenerated)
	}

	if want := []string{"Identity.UUID", "Temporal.DateTime", "Crypto.SHA256"}; !slices.Equal(scalars, want) {
		t.Errorf("Expand returned scalars %v, want %v", scalars, want)
	}
	for _, name := range scalars {
		if schema.Scalars[name] == nil {
			t.Errorf("Expand did not add scalar %s to the schema", name)
		}
	}
	if def := schema.Scalars["Identity.UUID"]; def.LanguagePrimitive != ir.LanguageString {
		t.Errorf("Expand replaced the schema's Identity.UUID: %+v", def)
	}
}

// TestExpandWithoutRoles: a User table without a UserRole table gets
// Session and UserCredential, and no UserRoleGrant.
func TestExpandWithoutRoles(t *testing.T) {
	schema := userSchema(false)
	Expand(schema)
	if schema.Types[ir.IdentitySessionTable] == nil || schema.Types[ir.IdentityCredentialTable] == nil {
		t.Fatal("Expand did not add Session and UserCredential")
	}
	if schema.Types[ir.IdentityRoleGrantTable] != nil {
		t.Error("Expand added UserRoleGrant to a schema without a UserRole table")
	}
	if got := Indexes(schema); len(got) != 1 || got[0].Type != ir.IdentitySessionTable {
		t.Errorf("Indexes = %+v for a schema without a UserRole table, want Session's alone", got)
	}
}

// TestExpandWithoutTheTraits: a schema without a User table is left as it
// was, its Session table included.
func TestExpandWithoutTheTraits(t *testing.T) {
	schema := userSchema(false)
	schema.Types["Account"].User = nil
	schema.Types["Session"] = &ir.TypeDef{Name: "Session", Role: ir.RoleDBTable}
	before, err := json.Marshal(schema)
	if err != nil {
		t.Fatal(err)
	}
	if scalars := Expand(schema); scalars != nil {
		t.Errorf("Expand returned scalars %v for a schema without a User table", scalars)
	}
	after, err := json.Marshal(schema)
	if err != nil {
		t.Fatal(err)
	}
	if string(before) != string(after) {
		t.Errorf("Expand changed a schema without a User table:\n%s\n%s", before, after)
	}
}

// TestExpandLeavesTheTraitTablesAndIsDeterministic: two expansions of the
// same schema are the same bytes, and neither changes the User and UserRole
// tables.
func TestExpandLeavesTheTraitTablesAndIsDeterministic(t *testing.T) {
	authored, err := json.Marshal(userSchema(true).Types)
	if err != nil {
		t.Fatal(err)
	}
	var runs [][]byte
	for range 2 {
		schema := userSchema(true)
		Expand(schema)
		out, err := json.Marshal(schema)
		if err != nil {
			t.Fatal(err)
		}
		runs = append(runs, out)

		traitTables := map[string]*ir.TypeDef{"Account": schema.Types["Account"], "Role": schema.Types["Role"]}
		got, err := json.Marshal(traitTables)
		if err != nil {
			t.Fatal(err)
		}
		if string(got) != string(authored) {
			t.Errorf("Expand changed the User or UserRole table:\n%s\nwant\n%s", got, authored)
		}
	}
	if string(runs[0]) != string(runs[1]) {
		t.Errorf("two expansions differ:\n%s\n%s", runs[0], runs[1])
	}
}
