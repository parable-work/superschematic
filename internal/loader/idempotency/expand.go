// Package idempotency adds the columns of the table that keeps idempotency
// keys (D140). A DB schema declares the table with one reserved class,
// `export abstract class IdempotencyKey implements IdempotencyKeys {}`,
// and the loader adds its key and its fields, each marked
// ir.OriginIdempotency, before verification, so the table is checked,
// migrated and generated as any other. The HTTP runtimes read and write
// its rows by the names the build hands them (idempotencydesc).
package idempotency

import (
	"fmt"

	ir "github.com/parable-work/superschematic/ir"
)

// uuidScalar is the key's scalar, which the loader hydrates.
const uuidScalar = "Identity.UUID"

// keyField is the table's key.
const keyField = "id"

// expiresIndex indexes the table by when each row expires, so the sweep of
// expired rows reads no other.
func expiresIndex() ir.IndexDef {
	return ir.IndexDef{Keys: []string{ir.IdempotencyExpiresAtField}, Name: "expires", Origin: ir.OriginIdempotency}
}

// fields are what the expansion adds, in column order.
func fields() []*ir.FieldDef {
	text := func(name, comment string) *ir.FieldDef {
		return &ir.FieldDef{Name: name, Comment: comment, TypeRef: ir.TypeRef{Name: "string"}, Required: true}
	}
	number := func(name, comment string, required bool) *ir.FieldDef {
		return &ir.FieldDef{Name: name, Comment: comment, TypeRef: ir.TypeRef{Name: "number"}, Required: required}
	}
	lookup := text(ir.IdempotencyLookupField, "What names the row: the SHA-256 of the operation, the principal and the key.")
	lookup.Unique = true
	return []*ir.FieldDef{
		{Name: keyField, TypeRef: ir.TypeRef{Name: uuidScalar}, Required: true, Key: true, AutoGenerated: true},
		lookup,
		text(ir.IdempotencyOperationField, "The operation the key was sent to."),
		text(ir.IdempotencyPrincipalField, "The caller the key belongs to; empty for a request with none."),
		text(ir.IdempotencyKeyField, "The key, as the Idempotency-Key header carried it."),
		text(ir.IdempotencyRequestHashField, "The SHA-256 of the request's method, path and body."),
		text(ir.IdempotencyStateField, "running while the first request runs, then done."),
		number(ir.IdempotencyStatusField, "The stored answer's status.", false),
		{Name: ir.IdempotencyBodyField, Comment: "The stored answer's body.", TypeRef: ir.TypeRef{Name: "string"}},
		number(ir.IdempotencyStartedAtField, "When the attempt that holds the row started, in milliseconds since the epoch.", true),
		number(ir.IdempotencyExpiresAtField, "When the row expires, in milliseconds since the epoch.", true),
	}
}

// FieldNames are the names of the fields the expansion adds.
func FieldNames() []string {
	added := fields()
	names := make([]string, len(added))
	for i, field := range added {
		names[i] = field.Name
	}
	return names
}

// Expand adds the key, the fields and the index of the table that keeps
// idempotency keys to each DB table of schema that implements
// IdempotencyKeys, and returns the scalars they use. A field the class
// declares under a name the expansion adds is an error: the class is
// declared empty. A table it already expanded is left as it is.
func Expand(schema *ir.Schema) ([]string, error) {
	var scalars []string
	for _, td := range schema.Types {
		if td == nil || td.IdempotencyKeys == nil || td.Role != ir.RoleDBTable {
			continue
		}
		expanded := false
		for _, field := range td.Fields {
			if field.Origin == ir.OriginIdempotency {
				expanded = true
			}
		}
		if expanded {
			continue
		}
		added := fields()
		for _, field := range added {
			for _, declared := range td.Fields {
				if declared.Name == field.Name {
					return nil, fmt.Errorf("type %s: it implements %s, which adds the field %s, and declares one of that name; the class is declared with no fields of those names", td.Name, ir.IdempotencyKeysTraitName, field.Name)
				}
			}
			field.Origin = ir.OriginIdempotency
		}
		td.Fields = append(added, td.Fields...)
		td.Indexes = append(td.Indexes, expiresIndex())
		scalars = append(scalars, uuidScalar)
	}
	return scalars, nil
}
