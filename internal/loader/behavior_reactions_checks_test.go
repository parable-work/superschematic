// projectsDB is a JSON DB schema whose Project's Reactions hears its
// Tasks through task.project and whose Task's Reactions moves its project
// (D103), for the checks' cases to edit.
func projectsDB() map[string]any {
	field := func(name, typeName string, more map[string]any) map[string]any {
		f := map[string]any{"name": name, "typeRef": map[string]any{"name": typeName}}
		for k, v := range more {
			f[k] = v
		}
		return f
	}
	flow := func(states ...string) map[string]any {
		var transitions []any
		for _, to := range states[1:] {
			transitions = append(transitions, map[string]any{"from": states[0], "to": to})
		}
		return map[string]any{"states": states, "transitions": transitions, "outcomes": map[string]any{states[len(states)-1]: "success"}}
	}
	return map[string]any{
		"name": "projects-db",
		"kind": "DB",
		"scalars": map[string]any{
			"Identity.UUID":     map[string]any{"name": "Identity.UUID", "languagePrimitive": "string"},
			"Temporal.DateTime": map[string]any{"name": "Temporal.DateTime", "languagePrimitive": "string"},
			"Blob":              map[string]any{"name": "Blob", "description": "Bytes, a BYTEA column.", "languagePrimitive": "string", "typeMappings": map[string]any{"sql": "BYTEA"}},
		},
		"types": map[string]any{
			"Project": map[string]any{
				"name": "Project",
				"role": "DBTable",
				"behaviors": []any{
					map[string]any{"name": "Reactions", "implements": true, "config": map[string]any{"rules": []any{
						map[string]any{"when": map[string]any{"allTerminal": map[string]any{"schema": "Task", "link": "project"}}, "then": map[string]any{"transition": "done"}},
					}}},
					map[string]any{"name": "Workflow", "field": "status", "config": flow("active", "done")},
				},
				"fields": []any{
					field("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
					field("name", "string", map[string]any{"required": true}),
				},
			},
			"Task": map[string]any{
				"name": "Task",
				"role": "DBTable",
				"behaviors": []any{
					map[string]any{"name": "Reactions", "implements": true, "config": map[string]any{"rules": []any{
						map[string]any{"when": map[string]any{"changes": map[string]any{"field": "priority", "to": "urgent"}}, "then": map[string]any{"link": "project", "transition": "done"}},
					}}},
					map[string]any{"name": "Workflow", "field": "status", "config": flow("todo", "done")},
				},
				"fields": []any{
					field("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
					field("title", "string", map[string]any{"required": true}),
					field("priority", "string", nil),
					field("blob", "Blob", nil),
					field("project", "Project", map[string]any{"required": true, "relation": map[string]any{"type": "Project"}}),
				},
			},
		},
	}
}

// loadProjects writes the edited schema as a JSON service and loads it.
func loadProjects(t *testing.T, edit func(doc, project, task map[string]any)) (*ir.Schema, error) {
	t.Helper()
	doc := projectsDB()
	types := doc["types"].(map[string]any)
	if edit != nil {
		edit(doc, types["Project"].(map[string]any), types["Task"].(map[string]any))
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	dir := writeService(t, map[string]string{
		"schema.config.json":       `{"name": "projects-db", "kind": "DB", "outputs": {}}`,
		"src/projects.schema.json": string(data),
	})
	return LoadService(dir)
}

// reactionsRules sets a table's Reactions rules, and its config's other
// members.
func reactionsRules(table map[string]any, rules []any, more ...string) {
	config := map[string]any{"rules": rules}
	for i := 0; i+1 < len(more); i += 2 {
		config[more[i]] = more[i+1]
	}
	table["behaviors"].([]any)[0].(map[string]any)["config"] = config
}

// rule is one Reactions rule of a when and a then.
func rule(when, then map[string]any) any {
	return map[string]any{"when": when, "then": then}
}

// TestReactionsFromTheDataForms: a JSON table's `{ name: "Reactions",
// implements: true }` loads as the TypeScript form's does, each table with
// its change queue, the table another's Reactions hears marked with it
// (D103).
func TestReactionsFromTheDataForms(t *testing.T) {
	schema, err := loadProjects(t, nil)
	if err != nil {
		t.Fatal(err)
	}
	if project := schema.Types["Project"]; !project.Optimistic || len(project.ImplementsBehaviors()) != 1 || project.IsEngineType() {
		t.Errorf("Project = %+v", project)
	}
	task := schema.BehaviorQueueOf("Task", ir.BehaviorQueueChanges)
	if task == nil || strings.Join(task.BehaviorQueue.HeardBy, ",") != "Project" || strings.Join(task.BehaviorQueue.Behaviors, ",") != "Reactions" {
		t.Errorf("Task's change queue = %+v", task)
	}
}

// TestReactionsChecks (D103): a table's Reactions config is refused, in
// the core's words where the core has them, when it reads what the table
// and its database do not hold: a status that is no Workflow of it; a
// changes rule's field that is dotted, no field of the table, a Workflow's
// enteredAt or a column a write's image leaves out; a holds or revised
// rule, which waits for step 4; a read of the status of several
// Workflows; an allTerminal or anyTerminal rule's linking table that is no
// table, has no to-one relation of that name to this table or one that
// holds a list, or composes no Workflow or several; and a then.link that
// is no to-one relation, or whose target composes no Workflow, several, or
// one without the state. A table whose writes are heard has one key field
// and leaves its change queue's name to the build. An engine type's
// Reactions that names status is refused too.
func TestReactionsChecks(t *testing.T) {
	enters := func(state string) map[string]any { return map[string]any{"enters": state} }
	changes := func(field string) map[string]any { return map[string]any{"changes": map[string]any{"field": field}} }
	all := func(schema, link string) map[string]any {
		return map[string]any{"allTerminal": map[string]any{"schema": schema, "link": link}}
	}
	moveTo := func(state string) map[string]any { return map[string]any{"transition": state} }
	linkTo := func(link, state string) map[string]any { return map[string]any{"link": link, "transition": state} }
	secondWorkflow := func(table map[string]any) {
		table["behaviors"] = append(table["behaviors"].([]any), map[string]any{"name": "Workflow", "field": "phase", "config": map[string]any{
			"states": []any{"a", "b"}, "transitions": []any{map[string]any{"from": "a", "to": "b"}},
		}})
	}
	for _, tc := range []struct {
		name string
		edit func(doc, project, task map[string]any)
		want string
	}{
		{"status names no Workflow", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(enters("done"), moveTo("done"))}, "status", "phase")
		}, `type Task: behavior Reactions config: status "phase" is not a Workflow of the type (its Workflows: status)`},
		{"a dotted field", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("status.enteredAt"), moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 1: when.changes names status.enteredAt: a table's rule names a field of the table by its name, and a member path below one, or a field a behavior computes, waits for a later step (D103)"},
		{"no field", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("colour"), moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 1: when.changes names colour, which is not a field of Task (title, priority, blob, project, status)"},
		{"a Workflow's enteredAt", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("statusEnteredAt"), moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 1: when.changes names statusEnteredAt, which every move of the status moves; a rule on status hears those"},
		{"a binary field", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("blob"), moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 1: when.changes names blob, a Blob field, which a write's image leaves out: a rule hears the fields a write carries (D103)"},
		{"holds", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(map[string]any{"holds": "allDone"}, moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 1: when.holds names rollup allDone: a rule that hears a rollup waits for Rollups on the core (D103's order of the work, step 4)"},
		{"revised", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("title"), moveTo("done")), rule(map[string]any{"revised": map[string]any{"link": "project"}}, moveTo("done"))})
		}, "type Task: behavior Reactions config: rule 2: when.revised names link project: a rule that hears a revision or a release waits for Revisions and Branches on the core (D103's order of the work, step 4)"},
		{"the status of several Workflows", func(_, _, task map[string]any) {
			secondWorkflow(task)
			reactionsRules(task, []any{rule(changes("title"), linkTo("project", "done")), rule(enters("done"), linkTo("project", "done"))})
		}, "type Task: behavior Reactions config: rule 2: when.enters reads the status of Workflow, and the type has several (status, phase): status names the field whose Workflow it reads"},
		{"a linking table that is no table", func(_, project, _ map[string]any) {
			reactionsRules(project, []any{rule(all("Milestone", "project"), moveTo("done"))})
		}, "type Project: behavior Reactions config: rule 1: when.allTerminal names Milestone, which is not a table of projects-db"},
		{"no such link", func(_, project, _ map[string]any) {
			reactionsRules(project, []any{rule(all("Task", "title"), moveTo("done"))})
		}, "type Project: behavior Reactions config: rule 1: when.allTerminal names link title of Task, which has no such link to Project"},
		{"a link to another table", func(_, project, _ map[string]any) {
			reactionsRules(project, []any{rule(map[string]any{"anyTerminal": map[string]any{"schema": "Project", "link": "name", "outcomes": []any{"success"}}}, moveTo("done"))})
		}, "type Project: behavior Reactions config: rule 1: when.anyTerminal names link name of Project, which has no such link to Project"},
		{"a link that holds a list", func(_, project, task map[string]any) {
			task["fields"] = append(task["fields"].([]any), map[string]any{"name": "related", "typeRef": map[string]any{"name": "Project", "isArray": true}, "manyToMany": true})
			reactionsRules(project, []any{rule(all("Task", "related"), moveTo("done"))})
		}, "type Project: behavior Reactions config: rule 1: when.allTerminal names link related of Task, which holds a list of targets, and the rule reads the one instance it points at"},
		{"a linking table with several Workflows", func(_, project, task map[string]any) {
			secondWorkflow(task)
			reactionsRules(task, []any{rule(changes("title"), linkTo("project", "done"))}, "status", "status")
		}, "type Project: behavior Reactions config: rule 1: when.allTerminal names Task, which has several Workflows (status, phase): a rule reads a linking table's one Workflow"},
		{"a linking table with no Workflow", func(doc, project, _ map[string]any) {
			doc["types"].(map[string]any)["Note"] = map[string]any{"name": "Note", "role": "DBTable", "fields": []any{
				map[string]any{"name": "id", "typeRef": map[string]any{"name": "Identity.UUID"}, "required": true, "key": true},
				map[string]any{"name": "project", "typeRef": map[string]any{"name": "Project"}, "required": true, "relation": map[string]any{"type": "Project"}},
			}}
			reactionsRules(project, []any{rule(all("Note", "project"), moveTo("done"))})
		}, "type Project: behavior Reactions config: rule 1: when.allTerminal names Note, which does not compose Workflow, so its rows have no terminal state"},
		{"a then.link to a table with no Workflow", func(doc, _, task map[string]any) {
			doc["types"].(map[string]any)["Note"] = map[string]any{"name": "Note", "role": "DBTable", "fields": []any{
				map[string]any{"name": "id", "typeRef": map[string]any{"name": "Identity.UUID"}, "required": true, "key": true},
			}}
			task["fields"] = append(task["fields"].([]any), map[string]any{"name": "note", "typeRef": map[string]any{"name": "Note"}, "relation": map[string]any{"type": "Note"}})
			reactionsRules(task, []any{rule(changes("title"), linkTo("note", "done"))})
		}, "type Task: behavior Reactions config: rule 1: then.link note points at Note, which does not compose Workflow"},
		{"a heard table's key of several fields", func(_, _, task map[string]any) {
			fields := task["fields"].([]any)
			fields[1].(map[string]any)["key"] = true
		}, "type Task: its writes are heard (Reactions, Project's Reactions), and Task's key is 2 fields (id, title): a table whose writes are heard has one @key field, which its change queue's messages name (D103)"},
		{"the change queue's name taken", func(doc, _, _ map[string]any) {
			doc["types"].(map[string]any)["TaskChange"] = map[string]any{"name": "TaskChange", "role": "EmbeddedStruct", "queue": map[string]any{}, "fields": []any{map[string]any{"name": "note", "typeRef": map[string]any{"name": "string"}, "required": true}}}
		}, "type Task: its writes are heard (Reactions, Project's Reactions), whose queue the build adds as TaskChange (task_change_queue), which the schema also declares; rename that type (D103)"},
		{"a then.link that is no relation", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("title"), linkTo("title", "done"))})
		}, "type Task: behavior Reactions config: rule 1: then.link title is not a to-one relation of Task (project)"},
		{"a then.link to a table with several Workflows", func(_, project, _ map[string]any) {
			secondWorkflow(project)
			reactionsRules(project, []any{rule(all("Task", "project"), moveTo("done"))}, "status", "status")
		}, "type Task: behavior Reactions config: rule 1: then.link project points at Project, which has several Workflows (status, phase): a rule moves a table's one Workflow"},
		{"a then.transition the target has not", func(_, _, task map[string]any) {
			reactionsRules(task, []any{rule(changes("title"), linkTo("project", "archived"))})
		}, `type Task: behavior Reactions config: rule 1: then.transition "archived" is not a state of Project's Workflow (active, done)`},
		{"an engine type's status", func(doc, _, _ map[string]any) {
			doc["types"].(map[string]any)["Note"] = map[string]any{"name": "Note", "role": "DBTable", "behaviors": []any{
				map[string]any{"name": "Workflow", "config": map[string]any{"states": []any{"a", "b"}, "transitions": []any{map[string]any{"from": "a", "to": "b"}}}},
				map[string]any{"name": "Reactions", "config": map[string]any{"status": "Workflow", "rules": []any{rule(enters("b"), moveTo("b"))}}},
			}, "fields": []any{map[string]any{"name": "id", "typeRef": map[string]any{"name": "Identity.UUID"}, "required": true, "key": true}}}
		}, "type Note: @behavior Reactions names status, the Workflow field a table's Reactions reads (implements Reactions<Note, C>, D103); an engine type's Reactions reads its one Workflow, so leave status out"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := loadProjects(t, tc.edit)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("LoadService = %v, want an error holding %q", err, tc.want)
			}
		})
	}
}
