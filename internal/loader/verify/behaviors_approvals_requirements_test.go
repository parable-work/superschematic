import "testing"

// requirements adds what a gate that reads its requirements from rows
// needs (D200): a Rule table, a Requirement table whose rows point at a
// rule and compose Constants, and Task's own list of the rules it reads,
// beside its createdFor.
func requirements(doc, task map[string]any) {
	doc["scalars"].(map[string]any)["Generic.JSON"] = map[string]any{"name": "Generic.JSON", "languagePrimitive": "object"}
	types := doc["types"].(map[string]any)
	types["Rule"] = map[string]any{"name": "Rule", "role": "DBTable", "fields": []any{
		taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
	}}
	types["Requirement"] = map[string]any{
		"name": "Requirement",
		"role": "DBTable",
		"behaviors": []any{
			map[string]any{"name": "Constants", "implements": true, "config": map[string]any{"fields": []any{"name"}}},
		},
		"fields": []any{
			taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
			taskField("rule", "Rule", map[string]any{"required": true, "relation": map[string]any{"type": "Rule"}}),
			taskField("task", "Task", map[string]any{"relation": map[string]any{"type": "Task"}}),
			taskField("name", "string", map[string]any{"required": true}),
			taskField("count", "Generic.Int64", nil),
			taskField("permission", "string", map[string]any{"required": true}),
			map[string]any{"name": "callers", "typeRef": map[string]any{"name": "string", "isArray": true}},
			map[string]any{"name": "resetOn", "typeRef": map[string]any{"name": "string", "isArray": true}},
			taskField("recheckPermission", "boolean", nil),
			taskField("when", "Generic.JSON", nil),
			taskField("archivedAt", "Temporal.DateTime", nil),
		},
	}
	addField(task, map[string]any{"name": "rules", "typeRef": map[string]any{"name": "Identity.UUID", "isArray": true}})
	addField(task, map[string]any{"name": "pushers", "typeRef": map[string]any{"name": "Identity.UUID", "isArray": true}})
	addField(task, taskField("createdFor", "Identity.UUID", nil))
}

// TestApprovalsRequirementsAreHeldToTheTable (D200): a gate that reads its
// requirements from rows names no requirement member and names its
// resetOn; its in is an own list field; its schema is a table of the
// schema that composes a behavior, its link a to-one relation of it (to
// Task when in is absent), and the table holds a permission and each
// member it holds is of a type the core reads. Each field pinOn,
// excludeSubjectsIn and a condition of when name is an own field of Task,
// and excludeCreatorPerson needs createdFor.
func TestApprovalsRequirementsAreHeldToTheTable(t *testing.T) {
	const prefix = "type Task: behavior Approvals config: "
	gates := func(task map[string]any) map[string]any { return config(task, "Approvals")["gates"].(map[string]any) }
	rows := func(members map[string]any, from map[string]any) func(doc, task map[string]any) {
		return func(doc, task map[string]any) {
			requirements(doc, task)
			g := map[string]any{"resetOn": []any{}, "pinOn": []any{"proof"}, "requirementsFrom": from}
			for k, v := range members {
				if v == nil {
					delete(g, k)
					continue
				}
				g[k] = v
			}
			gates(task)["done"] = g
		}
	}
	byRule := map[string]any{"schema": "Requirement", "link": "rule", "in": "rules"}
	requirement := func(edit func(requirement map[string]any)) func(doc, task map[string]any) {
		return func(doc, task map[string]any) {
			rows(nil, byRule)(doc, task)
			edit(doc["types"].(map[string]any)["Requirement"].(map[string]any))
		}
	}
	inline := func(members map[string]any) func(doc, task map[string]any) {
		return func(doc, task map[string]any) {
			requirements(doc, task)
			g := map[string]any{"count": 1, "permission": "tasks.review"}
			for k, v := range members {
				g[k] = v
			}
			gates(task)["done"] = g
		}
	}
	allFields := "title, owner, reviewer, plan, proof, urgent, attempts, rules, pushers, createdFor, createdBy"
	holdRefusals(t, "Approvals", []refusalCase{
		{"a requirement member on a gate that reads rows", rows(map[string]any{"count": 2}, byRule),
			prefix + `gate "done" reads its requirements from Requirement's rows, so it names no count: each row holds its own`},
		{"a gate that reads rows with no resetOn", rows(map[string]any{"resetOn": nil}, byRule),
			prefix + `gate "done" reads its requirements from Requirement's rows and names no resetOn, so any update would consume every sign-off, the writes of the facts its rows read among them: name the fields whose change spends every sign-off, [] for none, and give each row its own resetOn`},
		{"an in the table lacks", rows(nil, map[string]any{"schema": "Requirement", "link": "rule", "in": "ruleList"}),
			prefix + `gate "done": requirementsFrom's in names "ruleList", which is not a field of Task (its fields: ` + allFields + ")"},
		{"an in that is no list", rows(nil, map[string]any{"schema": "Requirement", "link": "rule", "in": "title"}),
			prefix + `gate "done": requirementsFrom's in names "title", which is no list: in names a list field of Task that holds the keys Requirement.rule points at`},
		{"a schema that is no table", rows(nil, map[string]any{"schema": "Rules", "link": "rule", "in": "rules"}),
			prefix + `gate "done": requirementsFrom names Rules, which is not a table of tasks-db`},
		{"a schema that composes no behavior", rows(nil, map[string]any{"schema": "Rule", "link": "rule", "in": "rules"}),
			prefix + `gate "done": requirementsFrom names Rule, which composes no behavior, so the behaviors' core holds none of its rows: a gate reads its requirements from a table that composes one, Revisions among them (D103)`},
		{"a link that is no relation", rows(nil, map[string]any{"schema": "Requirement", "link": "name", "in": "rules"}),
			prefix + `gate "done": requirementsFrom's link names "name", which is not a to-one relation of Requirement to a table`},
		{"a link to another table with no in", rows(nil, map[string]any{"schema": "Requirement", "link": "rule"}),
			prefix + `gate "done": requirementsFrom's link names "rule", which is not a to-one relation of Requirement to Task`},
		{"a requirement table with no permission", requirement(func(r map[string]any) { dropField(r, "permission") }),
			prefix + `gate "done": requirementsFrom names Requirement, which has no field permission: each row names the permission its signers hold`},
		{"a member of a type the core does not read", requirement(func(r map[string]any) {
			dropField(r, "count")
			addField(r, taskField("count", "string", nil))
		}), prefix + `gate "done": requirementsFrom names Requirement, whose count holds string, which the core does not read as a requirement's count`},
		{"a pinOn field the table lacks", rows(map[string]any{"pinOn": []any{"sha"}}, byRule),
			prefix + `gate "done": pinOn names "sha", which is not a field of Task (its fields: ` + allFields + ")"},
		{"an excludeSubjectsIn field the table lacks", inline(map[string]any{"excludeSubjectsIn": []any{"reviewers"}}),
			prefix + `gate "done": excludeSubjectsIn names "reviewers", which is not a field of Task (its fields: ` + allFields + ")"},
		{"a condition on a field the table lacks", inline(map[string]any{"when": []any{map[string]any{"field": "size", "test": "at-most", "values": []any{"1"}}}}),
			prefix + `gate "done": when condition 0 names "size", which is not a field of Task (its fields: ` + allFields + ")"},
		{"excludeCreatorPerson with no createdFor", func(doc, task map[string]any) {
			inline(map[string]any{"excludeCreatorPerson": true})(doc, task)
			dropField(task, "createdFor")
		}, prefix + `gate "done": excludeCreatorPerson reads the person the creator acted for from createdFor, and Task has no field createdFor`},
		{"a caller that is no class", inline(map[string]any{"callers": []any{"robot"}}),
			`type "Task": behavior Approvals config: jsonschema validation failed with 'superschematic://behaviors/Approvals/config.json#'
- at '/gates/done/callers/0': value must be one of 'person', 'acting-for-person', 'agent'`},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"a gate that reads rows by a list of rules":    rows(nil, byRule),
		"a gate that reads rows that point at the row": rows(nil, map[string]any{"schema": "Requirement", "link": "task"}),
		"a gate with every requirement member": inline(map[string]any{
			"callers":              []any{"person", "acting-for-person"},
			"proof":                "recent-sign-in",
			"proofWithinMs":        600000,
			"excludeCreatorPerson": true,
			"excludeSubjectsIn":    []any{"pushers"},
			"recheckPermission":    true,
			"pinOn":                []any{"proof"},
			"when":                 []any{map[string]any{"field": "plan", "test": "any-matches", "values": []any{"docs/**"}, "negate": true}},
		}),
	})
}
