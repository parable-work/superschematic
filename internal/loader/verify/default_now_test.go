// TestDefaultNowRefusedInIR: Default<T, "now"> (D88) is a required, single
// date, time or timestamp column's default of a DB table, and nothing
// else's; a required timestamp with neither it nor an audit name leaves a
// queue's trigger no default for a field it does not map.
func TestDefaultNowRefusedInIR(t *testing.T) {
	now := func() *string { v := "now"; return &v }
	at := ir.TypeRef{Name: "Temporal.DateTime"}
	schema := ir.NewSchema("ledger-db", ir.SchemaKindDB)
	schema.Types["Line"] = &ir.TypeDef{Name: "Line", Role: ir.RoleDBTable, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "postedAt", TypeRef: at, Required: true, Default: now()},
		{Name: "postedOn", TypeRef: ir.TypeRef{Name: "Temporal.Date"}, Required: true, Default: now()},
		{Name: "reviewedAt", TypeRef: at, Default: now()},
		{Name: "seenAt", TypeRef: ir.TypeRef{Name: "Temporal.DateTime", IsArray: true}, Required: true, Default: now()},
		// A string's "now" is its text.
		{Name: "label", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: now()},
	}}
	schema.Types["Posted"] = &ir.TypeDef{Name: "Posted", Role: ir.RoleEmbeddedStruct, Queue: &ir.QueueDef{}, Fields: []*ir.FieldDef{
		{Name: "lineId", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true},
		{Name: "at", TypeRef: at, Required: true, Default: now()},
	}}
	schema.Types["LineView"] = &ir.TypeDef{Name: "LineView", Role: ir.RoleEmbeddedStruct, Fields: []*ir.FieldDef{
		{Name: "postedAt", TypeRef: at, Required: true, Default: now()},
	}}
	r := &Result{}
	checkDefaultNow(schema, r)
	var got []string
	for _, d := range r.Errors {
		got = append(got, d.Msg)
	}
	want := []string{
		`Line.reviewedAt: Default<T, "now"> is a required column's default; an optional column's is NULL, which the ORMs write for a value left unset, and a key's is generated`,
		`Line.seenAt: Default<T, "now"> is the default of a single date, time or timestamp column, and seenAt is a list, a map, a JSON value or an Encrypted<T> field`,
		`LineView.postedAt: Default<T, "now"> is a DB table column's default, the time of the insert, which the database fills in; no decoder fills in a payload's, so give postedAt no default or a literal one`,
		`Posted.at: Default<T, "now"> is a table column's default, and a queue's enqueues write every required field of the message; the queue's own created_at holds when a message was enqueued`,
	}
	if !slices.Equal(got, want) {
		t.Errorf("errors =\n%q\nwant\n%q", got, want)
	}
}

// TestUnmappedTimestampNeedsDefaultNow: a required timestamp of a queue's
// message the trigger leaves out has no default unless it declares one
// (D88), where it used to take the database's clock; a mapped one is fine.
func TestUnmappedTimestampNeedsDefaultNow(t *testing.T) {
	str := ir.TypeRef{Name: "string"}
	at := ir.TypeRef{Name: "Temporal.DateTime"}
	schema := ir.NewSchema("orders-db", ir.SchemaKindDB)
	schema.Types["Placed"] = &ir.TypeDef{Name: "Placed", Role: ir.RoleEmbeddedStruct, Queue: &ir.QueueDef{}, Fields: []*ir.FieldDef{
		{Name: "orderId", TypeRef: str, Required: true},
		{Name: "placedAt", TypeRef: at, Required: true},
	}}
	schema.Types["Order"] = &ir.TypeDef{Name: "Order", Role: ir.RoleDBTable,
		Fields: []*ir.FieldDef{
			{Name: "id", TypeRef: str, Required: true, Key: true},
			{Name: "placedAt", TypeRef: at, Required: true},
		},
		EnqueueOnChange: []*ir.EnqueueOnChange{{Queue: "Placed", On: []string{"insert"}, Message: map[string]string{"orderId": "id"}}},
	}
	r := &Result{}
	checkEnqueueOnChange(schema, r)
	if len(r.Errors) != 1 || r.Errors[0].Msg != `@enqueueOnChange(Placed) on Order: Placed's field placedAt is required and its column has no default, so the message maps it to a field of Order` {
		t.Fatalf("errors = %+v", r.Errors)
	}
	schema.Types["Order"].EnqueueOnChange[0].Message["placedAt"] = "placedAt"
	r = &Result{}
	checkEnqueueOnChange(schema, r)
	if len(r.Errors) != 0 {
		t.Fatalf("a mapped placedAt: errors = %+v", r.Errors)
	}
}
