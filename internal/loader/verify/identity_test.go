package verify

import (
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// userModel returns a DB schema with a valid user model: the Account table
// carries the User trait, whose login is a case-insensitive email and whose
// name is displayName, and the Role table the UserRole trait. The scalars
// carry what hydration gives them, except that Contact.Email is declared
// case-insensitive here: the scalar catalog does not carry the declaration
// yet, so every catalog scalar reads as case-sensitive.
func userModel() *ir.Schema {
	schema := ir.NewSchema("users", ir.SchemaKindDB)
	for _, scalar := range []*ir.ScalarDef{
		{Name: "Identity.UUID", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "UUID", "json_schema": "string"}},
		{Name: "Identity.Name", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "VARCHAR(255)", "json_schema": "string"}},
		{Name: "Contact.Email", LanguagePrimitive: ir.LanguageString, CaseInsensitive: true, TypeMappings: map[string]string{"sql": "CITEXT", "json_schema": "string"}},
		{Name: "Generic.Int64", LanguagePrimitive: ir.LanguageNumber, TypeMappings: map[string]string{"sql": "BIGINT", "json_schema": "integer"}},
		{Name: "Generic.JSON", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "JSONB", "json_schema": "any"}},
	} {
		schema.Scalars[scalar.Name] = scalar
	}
	key := func() *ir.FieldDef {
		return &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true}
	}
	schema.Types["Account"] = &ir.TypeDef{
		Name: "Account", Role: ir.RoleDBTable, Owner: "src/users.schema.ts",
		User: &ir.UserTrait{Login: "email", Name: "displayName"},
		Fields: []*ir.FieldDef{
			key(),
			{Name: "email", TypeRef: ir.TypeRef{Name: "Contact.Email"}, Required: true, Unique: true},
			{Name: "displayName", TypeRef: ir.TypeRef{Name: "Identity.Name"}, Required: true},
			{Name: "visits", TypeRef: ir.TypeRef{Name: "Generic.Int64"}},
		},
	}
	schema.Types["Role"] = &ir.TypeDef{
		Name: "Role", Role: ir.RoleDBTable, Owner: "src/users.schema.ts",
		UserRole: &ir.UserRoleTrait{},
		Fields: []*ir.FieldDef{
			key(),
			{Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
			{Name: "permissions", TypeRef: ir.TypeRef{Name: "string", IsArray: true}, Required: true},
		},
	}
	return schema
}

// TestUserModelTraits runs every User and UserRole rule once where it holds
// and once where it breaks. A case with no want must verify clean.
func TestUserModelTraits(t *testing.T) {
	account := func(s *ir.Schema) *ir.TypeDef { return s.Types["Account"] }
	role := func(s *ir.Schema) *ir.TypeDef { return s.Types["Role"] }
	accountField := func(s *ir.Schema, name string) *ir.FieldDef { return fieldNamed(s.Types["Account"], name) }
	roleField := func(s *ir.Schema, name string) *ir.FieldDef { return fieldNamed(s.Types["Role"], name) }
	cases := []struct {
		name   string
		mutate func(s *ir.Schema)
		want   string
	}{
		{name: "the valid model", mutate: func(*ir.Schema) {}},
		{name: "a User table without a UserRole table", mutate: func(s *ir.Schema) { delete(s.Types, "Role") }},

		// Placement.
		{
			name: "two User tables",
			mutate: func(s *ir.Schema) {
				member := *account(s)
				member.Name = "Member"
				s.Types["Member"] = &member
			},
			want: "Member: a schema has at most one User table, and Account is one",
		},
		{
			name: "two UserRole tables",
			mutate: func(s *ir.Schema) {
				team := *role(s)
				team.Name = "Team"
				s.Types["Team"] = &team
			},
			want: "Team: a schema has at most one UserRole table, and Role is one",
		},
		{
			name:   "the User trait outside a DB schema",
			mutate: func(s *ir.Schema) { s.Kind = ir.SchemaKindGeneral },
			want:   "Account: the User trait is only allowed in a DB schema (this schema has kind General)",
		},
		{
			name:   "the UserRole trait outside a DB schema",
			mutate: func(s *ir.Schema) { s.Kind = ir.SchemaKindGeneral },
			want:   "Role: the UserRole trait is only allowed in a DB schema (this schema has kind General)",
		},
		{
			name:   "the User trait on an API view",
			mutate: func(s *ir.Schema) { account(s).Role = ir.RoleAPIView },
			want:   "Account: the User trait is only allowed on DB table types (this type has role APIView)",
		},
		{
			name:   "the UserRole trait on an embedded struct",
			mutate: func(s *ir.Schema) { role(s).Role = ir.RoleEmbeddedStruct },
			want:   "Role: the UserRole trait is only allowed on DB table types (this type has role EmbeddedStruct)",
		},
		{
			name:   "the User trait on a @jsonField type",
			mutate: func(s *ir.Schema) { account(s).JsonField = true },
			want:   "Account: the User trait is on a @jsonField type, which is stored as JSON and gets no table",
		},
		{
			name: "the User trait on a base class",
			mutate: func(s *ir.Schema) {
				s.Types["Customer"] = &ir.TypeDef{Name: "Customer", Role: ir.RoleDBTable, Extends: "Account", Fields: account(s).Fields}
			},
			want: "Account: the User trait is on a base class, which gets no table; implement it on the table that extends Account (Customer)",
		},
		{
			name:   "both traits on one table",
			mutate: func(s *ir.Schema) { account(s).UserRole = &ir.UserRoleTrait{} },
			want:   "Account: a table implements User or UserRole, not both",
		},
		{
			name:   "a UserRole table without a User table",
			mutate: func(s *ir.Schema) { account(s).User = nil },
			want:   "Role: the UserRole trait needs a User table in the same schema",
		},

		// The login.
		{
			name:   "no login",
			mutate: func(s *ir.Schema) { account(s).User.Login = "" },
			want:   "Account: the User trait needs login, the field users sign in with",
		},
		{
			name:   "a login that names no field",
			mutate: func(s *ir.Schema) { account(s).User.Login = "mail" },
			want:   `Account: the User trait's login "mail" is not a field of Account`,
		},
		{
			name:   "a login that is not @unique",
			mutate: func(s *ir.Schema) { accountField(s, "email").Unique = false },
			want:   "Account.email: the User trait's login must be @unique",
		},
		{
			name:   "a nullable login",
			mutate: func(s *ir.Schema) { accountField(s, "email").Required = false },
			want:   "Account.email: the User trait's login must be required",
		},
		{
			name:   "a list login",
			mutate: func(s *ir.Schema) { accountField(s, "email").TypeRef.IsArray = true },
			want:   "Account.email: the User trait's login must be one value, not a list",
		},
		{
			name:   "a map login",
			mutate: func(s *ir.Schema) { accountField(s, "email").TypeRef.IsMap = true },
			want:   "Account.email: the User trait's login must be one value, not a map",
		},
		{
			name:   "a string login",
			mutate: func(s *ir.Schema) { accountField(s, "email").TypeRef.Name = "string" },
			want:   "Account.email: the User trait's login must be typed by a scalar declared case-insensitive, and string is not one",
		},
		{
			name:   "a login scalar that is not declared case-insensitive",
			mutate: func(s *ir.Schema) { s.Scalars["Contact.Email"].CaseInsensitive = false },
			want:   "Account.email: the User trait's login must be typed by a scalar declared case-insensitive, and Contact.Email is not one",
		},
		{
			name: "any scalar declared case-insensitive",
			mutate: func(s *ir.Schema) {
				s.Scalars["Local.Handle"] = &ir.ScalarDef{Name: "Local.Handle", LanguagePrimitive: ir.LanguageString, CaseInsensitive: true}
				accountField(s, "email").TypeRef.Name = "Local.Handle"
			},
		},
		{
			name:   "an enum login",
			mutate: func(s *ir.Schema) { accountField(s, "email").TypeRef.Name = "Plan" },
			want:   "Account.email: the User trait's login must be typed by a scalar declared case-insensitive, and Plan is not one",
		},

		// The name.
		{
			name:   "a name that names no field",
			mutate: func(s *ir.Schema) { account(s).User.Name = "nick" },
			want:   `Account: the User trait's name "nick" is not a field of Account`,
		},
		{
			name:   "a string name",
			mutate: func(s *ir.Schema) { accountField(s, "displayName").TypeRef.Name = "string" },
		},
		{
			name:   "an optional name",
			mutate: func(s *ir.Schema) { accountField(s, "displayName").Required = false },
		},
		{
			name:   "a numeric name",
			mutate: func(s *ir.Schema) { account(s).User.Name = "visits" },
			want:   "Account.visits: the User trait's name must be text (a string, or a scalar whose values are strings), and Generic.Int64 is not",
		},
		{
			name:   "a name whose values are any JSON",
			mutate: func(s *ir.Schema) { accountField(s, "displayName").TypeRef.Name = "Generic.JSON" },
			want:   "Account.displayName: the User trait's name must be text (a string, or a scalar whose values are strings), and Generic.JSON is not",
		},
		{
			name:   "a list name",
			mutate: func(s *ir.Schema) { accountField(s, "displayName").TypeRef = ir.TypeRef{Name: "string", IsArray: true} },
			want:   "Account.displayName: the User trait's name must be text (a string, or a scalar whose values are strings), and string[] is not",
		},
		{
			name:   "no name, so the login names the principal",
			mutate: func(s *ir.Schema) { account(s).User.Name = "" },
		},
		{
			name: "no name and a login that is not text",
			mutate: func(s *ir.Schema) {
				s.Scalars["Local.Number"] = &ir.ScalarDef{Name: "Local.Number", LanguagePrimitive: ir.LanguageNumber, CaseInsensitive: true}
				account(s).User.Name = ""
				accountField(s, "email").TypeRef.Name = "Local.Number"
			},
			want: "Account.email: the User trait has no name, so a principal's name is the login, which must then be text",
		},

		// The keys.
		{
			name:   "a User table without a key",
			mutate: func(s *ir.Schema) { accountField(s, "id").Key = false },
			want:   "Account: the User trait requires exactly one @key field, found 0",
		},
		{
			name:   "a User table with two keys",
			mutate: func(s *ir.Schema) { accountField(s, "email").Key = true },
			want:   "Account: the User trait requires exactly one @key field, found 2",
		},
		{
			name:   "a UserRole table without a key",
			mutate: func(s *ir.Schema) { roleField(s, "id").Key = false },
			want:   "Role: the UserRole trait requires exactly one @key field, found 0",
		},

		// The role table.
		{
			name:   "a role without a name",
			mutate: func(s *ir.Schema) { roleField(s, "name").Name = "title" },
			want:   "Role: the UserRole trait needs a name field, the role's @unique text name",
		},
		{
			name:   "a role name that is not @unique",
			mutate: func(s *ir.Schema) { roleField(s, "name").Unique = false },
			want:   "Role.name: the UserRole trait's name must be @unique",
		},
		{
			name:   "a role name typed by a text scalar",
			mutate: func(s *ir.Schema) { roleField(s, "name").TypeRef.Name = "Identity.Name" },
		},
		{
			name:   "a role name that is not text",
			mutate: func(s *ir.Schema) { roleField(s, "name").TypeRef.Name = "Generic.Int64" },
			want:   "Role.name: the UserRole trait's name must be text (a string, or a scalar whose values are strings), and Generic.Int64 is not",
		},
		{
			name:   "a role without permissions",
			mutate: func(s *ir.Schema) { roleField(s, "permissions").Name = "grants" },
			want:   "Role: the UserRole trait needs a permissions field, a list of strings",
		},
		{
			name:   "permissions that are one string",
			mutate: func(s *ir.Schema) { roleField(s, "permissions").TypeRef.IsArray = false },
			want:   "Role.permissions: the UserRole trait's permissions must be a list of strings, and it is string",
		},
		{
			name:   "permissions that are a list of a scalar",
			mutate: func(s *ir.Schema) { roleField(s, "permissions").TypeRef.Name = "Identity.Name" },
			want:   "Role.permissions: the UserRole trait's permissions must be a list of strings, and it is Identity.Name[]",
		},
		{
			name:   "permissions that are a list of lists",
			mutate: func(s *ir.Schema) { roleField(s, "permissions").TypeRef.IsArrayOfArrays = true },
			want:   "Role.permissions: the UserRole trait's permissions must be a list of strings, and it is string[][]",
		},
		{
			name:   "permissions that are a map",
			mutate: func(s *ir.Schema) { roleField(s, "permissions").TypeRef.IsMap = true },
			want:   "Role.permissions: the UserRole trait's permissions must be a list of strings, and it is Map<string, string[]>",
		},

		// The names the expansion takes.
		{
			name: "an authored Session table",
			mutate: func(s *ir.Schema) {
				s.Types["Session"] = &ir.TypeDef{Name: "Session", Role: ir.RoleDBTable, Owner: "src/sessions.schema.ts"}
			},
			want: "src/sessions.schema.ts: Session: the User trait of Account adds a table named Session, which the schema already defines; rename it",
		},
		{
			name: "an authored UserCredential view",
			mutate: func(s *ir.Schema) {
				s.Types["UserCredential"] = &ir.TypeDef{Name: "UserCredential", Role: ir.RoleAPIView}
			},
			want: "UserCredential: the User trait of Account adds a table named UserCredential, which the schema already defines",
		},
		{
			name: "an authored UserRoleGrant without a UserRole table",
			mutate: func(s *ir.Schema) {
				delete(s.Types, "Role")
				s.Types["UserRoleGrant"] = &ir.TypeDef{Name: "UserRoleGrant", Role: ir.RoleDBTable}
			},
			want: "UserRoleGrant: the User trait of Account adds a table named UserRoleGrant, which the schema already defines",
		},
		{
			name:   "an enum named Session",
			mutate: func(s *ir.Schema) { s.Enums["Session"] = &ir.EnumDef{Name: "Session"} },
			want:   "Session: the User trait of Account adds a table named Session, which the schema already defines",
		},
		{
			name: "a table whose name is the added table's",
			mutate: func(s *ir.Schema) {
				s.Types["User_Credential"] = &ir.TypeDef{Name: "User_Credential", Role: ir.RoleDBTable}
			},
			want: "User_Credential: its table user_credential is the table of UserCredential, which the User trait of Account adds; rename it",
		},
		{
			name: "an authored Session table without a User table",
			mutate: func(s *ir.Schema) {
				delete(s.Types, "Role")
				account(s).User = nil
				s.Types["Session"] = &ir.TypeDef{Name: "Session", Role: ir.RoleDBTable}
			},
		},
		{
			name: "an index named as the grant index",
			mutate: func(s *ir.Schema) {
				s.Types["User"] = &ir.TypeDef{
					Name: "User", Role: ir.RoleDBTable,
					Fields:  []*ir.FieldDef{{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Key: true}},
					Indexes: []ir.IndexDef{{Keys: []string{"id"}, Unique: true, Name: "role_grant_user_role"}},
				}
			},
			want: "User: index uq_user_role_grant_user_role collides with the index the user model adds to UserRoleGrant; give it another name",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			schema := userModel()
			schema.Enums["Plan"] = &ir.EnumDef{Name: "Plan", Values: []ir.EnumValueDef{{Name: "Free", SerializedAs: "free"}}}
			tc.mutate(schema)
			r := Run(schema, Input{})
			if tc.want == "" {
				if len(r.Errors) > 0 {
					t.Fatalf("want a clean verification, got %v", errorStrings(r))
				}
				return
			}
			if !hasError(r, tc.want) {
				t.Fatalf("want an error containing %q, got %v", tc.want, errorStrings(r))
			}
		})
	}
}
