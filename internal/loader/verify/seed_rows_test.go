package verify

import (
	"slices"
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// seededTrust is a DB schema with a channel kind's trust table, keyed by
// a generated id and unique by its kind, seeded with seeds.
func seededTrust(seeds *ir.SeedRows) *ir.Schema {
	db := ir.NewSchema("notices", ir.SchemaKindDB)
	db.Types["ChannelTrust"] = &ir.TypeDef{Name: "ChannelTrust", Role: ir.RoleDBTable, SeedRows: seeds, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "channelKind", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
		{Name: "level", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
		{Name: "permissions", TypeRef: ir.TypeRef{Name: "string", IsArray: true}},
		{Name: "note", TypeRef: ir.TypeRef{Name: "string"}},
	}}
	return db
}

// TestSeedRowsRefusedInIR: @seedRows is on a DB table; each field a row
// names is one of the table's, held in a column of its own and no
// secret; every row gives each field a row needs and its key, which the
// table's key, a unique field or the declared key names; and no two rows
// have one key (#625).
func TestSeedRowsRefusedInIR(t *testing.T) {
	r := &Result{}
	checkSeedRows(seededTrust(&ir.SeedRows{Rows: []map[string]any{
		{"channelKind": "sms", "level": "low", "permissions": []any{}},
		{"channelKind": "email", "level": "standard", "permissions": nil},
	}}), Input{}, r)
	if len(r.Errors) != 0 {
		t.Errorf("a clean seed: errors = %q", messages(r.Errors))
	}

	db := seededTrust(&ir.SeedRows{Key: []string{"channelKind"}, Rows: []map[string]any{
		{"channelKind": "sms", "level": "low", "secret": "x", "rate": 3.0},
		{"channelKind": "sms", "level": "high"},
		{"level": "standard"},
		{"channelKind": "chat"},
	}})
	db.Types["ChannelTrust"].Fields = append(db.Types["ChannelTrust"].Fields,
		&ir.FieldDef{Name: "secret", TypeRef: ir.TypeRef{Name: "string"}, Secret: true},
		&ir.FieldDef{Name: "owner", TypeRef: ir.TypeRef{Name: "Account"}, Relation: &ir.RelationDef{}},
	)
	db.Types["ChannelTrust"].SeedRows.Rows[3]["owner"] = "a"
	db.Types["Shape"] = &ir.TypeDef{Name: "Shape", Role: ir.RoleEmbeddedStruct, SeedRows: &ir.SeedRows{Rows: []map[string]any{{"a": 1.0}}}}
	db.Types["Note"] = &ir.TypeDef{Name: "Note", Role: ir.RoleDBTable, SeedRows: &ir.SeedRows{Rows: []map[string]any{{"body": "hi"}}}, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "body", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
	}}
	db.Types["Pin"] = &ir.TypeDef{Name: "Pin", Role: ir.RoleDBTable, SeedRows: &ir.SeedRows{Key: []string{"slot", "slot", "missing"}, Rows: []map[string]any{{"slot": "a"}}}, Fields: []*ir.FieldDef{
		{Name: "slot", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Key: true},
	}}
	r = &Result{}
	checkSeedRows(db, Input{}, r)
	want := []string{
		`ChannelTrust: @seedRows names ChannelTrust.rate: the table has no such field`,
		`ChannelTrust: @seedRows names ChannelTrust.secret: it holds a secret, which a migration's SQL would carry in plain text`,
		`ChannelTrust: @seedRows rows 0 and 1 have one key (channelKind = ["sms"]); a key names one row`,
		`ChannelTrust: @seedRows row 2 gives no channelKind, which is required and has no default its column carries; give it, make it optional or give it a Default<T, V>`,
		`ChannelTrust: @seedRows row 2 gives no channelKind, which its key names`,
		`ChannelTrust: @seedRows names ChannelTrust.owner: it is held in no column of its own; name a field that holds a value`,
		`ChannelTrust: @seedRows row 3 gives no level, which is required and has no default its column carries; give it, make it optional or give it a Default<T, V>`,
		`Note: @seedRows finds no fields that identify a seeded row: no row gives the table's key, and no unique field or unique index of Note is given by every row; name them with @seedRows([...], { key: ["field"] })`,
		`Pin: @seedRows's key lists slot twice`,
		`Pin: @seedRows names Pin.missing: the table has no such field`,
		`Shape: @seedRows seeds the rows of a table of a DB service, and Shape is not one`,
	}
	if got := messages(r.Errors); !slices.Equal(got, want) {
		t.Errorf("errors =\n%q\nwant\n%q", got, want)
	}
}
