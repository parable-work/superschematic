// checkQueues checks a DB service's queues (D53) in every form. Only a DB
// schema declares one. A queue's class is a message: an embedded struct
// with fields and none of a table's declarations, whose fields are values
// a column holds, a scalar, an enum or a JSON value, never a reference to
// a table, a key or a generated value, and take no name of a column the
// queue keeps itself. Its table takes no other table's name, and its
// arguments are what @queue takes (registry.CheckQueue). Its key, when it
// has one, is a required field whose column a unique index can hold
// (D80).
func checkQueues(schema *ir.Schema, r *Result) {
	queues := schema.Queues()
	if len(queues) == 0 {
		return
	}
	if schema.Kind != ir.SchemaKindDB {
		r.errorf(queues[0].Owner, "schema %s is a %s service and declares queue %s; only a DB service declares one, whose database holds it", schema.Name, schema.Kind, queues[0].Name)
		return
	}
	tables := map[string]string{}
	for _, td := range schema.Types {
		if td != nil && td.Role == ir.RoleDBTable && !td.JsonField {
			tables[codegen.ToSnakeCase(td.Name)] = td.Name
		}
	}
	extended := map[string]bool{}
	for _, td := range schema.Types {
		if td != nil && td.Extends != "" {
			extended[td.Extends] = true
		}
	}
	for _, td := range queues {
		where := "queue " + td.Name
		if err := registry.CheckQueue(td.Queue); err != nil {
			r.errorf(td.Owner, "%s: %v", where, err)
		}
		switch {
		case td.Role != ir.RoleEmbeddedStruct:
			r.errorf(td.Owner, "%s has role %s; a queue's class is its message, role %s, and no table", where, td.Role, ir.RoleEmbeddedStruct)
		case len(td.Fields) == 0:
			r.errorf(td.Owner, "%s has no fields; a queue's class holds its message's fields", where)
		case td.JsonField || td.Versioned || td.Optimistic || td.VersionGraph != nil || td.GraphMember != nil || td.Projection != nil || len(td.Indexes) > 0:
			r.errorf(td.Owner, "%s is also a @jsonField, @versioned, @optimistic, version graph, projection or indexed class; a queue's class declares the message and nothing else", where)
		case extended[td.Name]:
			r.errorf(td.Owner, "%s is extended by another class; a queue's message is no base class", where)
		}
		table := codegen.ToSnakeCase(td.Name) + ir.QueueTableSuffix
		if other, clash := tables[table]; clash {
			r.errorf(td.Owner, "%s's table is %s, the table of %s; rename one of them", where, table, other)
		}
		checkQueueKey(schema, td, r)
		reserved := ir.QueueColumns()
		for _, f := range td.Fields {
			if f == nil {
				continue
			}
			column := codegen.ToSnakeCase(f.Name)
			target := schema.Types[f.TypeRef.Name]
			switch {
			case slices.Contains(reserved, column):
				r.errorf(td.Owner, "%s field %s is the column %s, which the queue keeps itself; rename the field", where, f.Name, column)
			case f.Key || f.AutoGenerated || f.Unique || f.SearchField:
				r.errorf(td.Owner, "%s field %s is a @key, @unique, @searchField or generated field; a message's fields are values, and the queue keys each message itself", where, f.Name)
			case f.Relation != nil || f.HasMany || f.ManyToMany:
				r.errorf(td.Owner, "%s field %s is a relation; a message holds the key of what it names, not a reference to its table", where, f.Name)
			case target != nil && target.Role == ir.RoleDBTable && !target.JsonField && !f.JsonField:
				r.errorf(td.Owner, "%s field %s is of type %s, a table; a message holds its key instead", where, f.Name, target.Name)
			case target != nil && target.Queue != nil:
				r.errorf(td.Owner, "%s field %s is of type %s, another queue's message; a message holds values", where, f.Name, target.Name)
			}
		}
	}
}

// checkQueueKey checks a queue's key (D80): a field of its message that is
// required, so every message has one, and a single scalar or enum, not a
// list, a map or a JSON value, whose column an index compares by
// equality, which a POINT and the PostGIS types are not.
func checkQueueKey(schema *ir.Schema, td *ir.TypeDef, r *Result) {
	if td.Queue == nil || td.Queue.Key == "" {
		return
	}
	where := "queue " + td.Name
	var key *ir.FieldDef
	for _, f := range td.Fields {
		if f != nil && f.Name == td.Queue.Key {
			key = f
		}
	}
	if key == nil {
		r.errorf(td.Owner, "%s's key %q names no field of the message; name one of its fields, as key: %q", where, td.Queue.Key, firstFieldName(td))
		return
	}
	_, union := schema.Unions[key.TypeRef.Name]
	target := schema.Types[key.TypeRef.Name]
	sqlType := strings.ToUpper(sqlutil.ColumnType(key, sqlutil.ScalarSQLTypes(schema)))
	switch {
	case !key.Required:
		r.errorf(td.Owner, "%s's key %s is optional; a key is a required field, so every message has one", where, key.Name)
	case key.TypeRef.IsArray || key.TypeRef.IsMap || key.JsonField || union || (target != nil && target.JsonField) || sqlType == "JSONB" || sqlType == "JSON":
		r.errorf(td.Owner, "%s's key %s is a list, a map or a JSON value; a key is one scalar or enum value", where, key.Name)
	case sqlType == "POINT" || sqlType == "GEOGRAPHY" || sqlType == "GEOMETRY":
		r.errorf(td.Owner, "%s's key %s is a %s column, which an index does not compare by equality; key the message by another field", where, key.Name, sqlType)
	}
}

// firstFieldName is the name of a type's first field, for an example in an
// error.
func firstFieldName(td *ir.TypeDef) string {
	for _, f := range td.Fields {
		if f != nil {
			return f.Name
		}
	}
	return "id"
}

// checkWorkers checks an API service's workers (D53) in every form: only
// an API declares one, each has a name no other worker, job, type or
// operation set of the schema takes and whose Go method no other worker's
// takes, each names a queue class the schema imports, and each worker's
// arguments are what @worker takes (registry.CheckWorker). Whether the
// queue is a queue of the API's database is the API's build's to check, and
// resolution's: each reads that database's schema.
func checkWorkers(schema *ir.Schema, r *Result) {
	if len(schema.Workers) == 0 {
		return
	}
	if schema.Kind != ir.SchemaKindAPI {
		r.errorf("", "schema %s is a %s service and declares workers; only an API service declares one", schema.Name, schema.Kind)
		return
	}
	sets := map[string]bool{}
	for _, set := range schema.OperationSets {
		if set != nil {
			sets[set.Name] = true
		}
	}
	imported := map[string]bool{}
	for _, imp := range schema.Imports {
		for _, name := range imp.Types {
			imported[name] = true
		}
	}
	seen := map[string]bool{}
	methods := map[string]string{}
	for _, worker := range schema.Workers {
		if worker == nil {
			continue
		}
		if err := registry.CheckWorker(worker); err != nil {
			r.errorf("", "worker %s: %v", worker.Name, err)
			continue
		}
		switch {
		case seen[worker.Name]:
			r.errorf("", "worker %s is declared twice", worker.Name)
			continue
		case schema.Types[worker.Name] != nil:
			r.errorf("", "worker %s takes the name of a type of the schema; a worker's class is no type, so give one of them another name", worker.Name)
		case sets[worker.Name]:
			r.errorf("", "worker %s takes the name of an operation set of the schema; give one of them another name", worker.Name)
		case schema.Job(worker.Name) != nil:
			r.errorf("", "worker %s takes the name of a job of the schema, and both would be the deployable %s; give one of them another name", worker.Name, ir.WorkerDeployableName(schema.Name, worker.Name))
		}
		if !imported[worker.Queue] {
			r.errorf("", "worker %s handles queue %s, which the schema does not import; a queue is a @queue class of the API's database, which the schema imports from it", worker.Name, worker.Queue)
		}
		seen[worker.Name] = true
		method := goutil.GoPublicIdentifier(worker.Name)
		if other, clash := methods[method]; clash {
			r.errorf("", "workers %s and %s are both the method %s of the API's Workers interface; give one of them another name", other, worker.Name, method)
			continue
		}
		methods[method] = worker.Name
	}
}
