import (
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// mergeableModel returns a DB schema whose Label table implements
// Mergeable (D147), beside a Document that does not.
func mergeableModel() *ir.Schema {
	schema := ir.NewSchema("labels", ir.SchemaKindDB)
	schema.Scalars["Identity.UUID"] = &ir.ScalarDef{Name: "Identity.UUID", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "UUID", "json_schema": "string"}}
	key := func() *ir.FieldDef {
		return &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true}
	}
	schema.Types["Label"] = &ir.TypeDef{
		Name: "Label", Role: ir.RoleDBTable, Owner: "src/labels.schema.ts", Mergeable: true,
		Fields: []*ir.FieldDef{key(), {Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true}},
	}
	schema.Types["Document"] = &ir.TypeDef{
		Name: "Document", Role: ir.RoleDBTable, Owner: "src/labels.schema.ts",
		Fields: []*ir.FieldDef{key(), {Name: "title", TypeRef: ir.TypeRef{Name: "string"}, Required: true}},
	}
	return schema
}

// TestMergeableTrait runs each rule of where the Mergeable trait may stand
// once where it holds and once where it breaks (D147). A case with no want
// must verify clean.
func TestMergeableTrait(t *testing.T) {
	label := func(s *ir.Schema) *ir.TypeDef { return s.Types["Label"] }
	cases := []struct {
		name   string
		mutate func(s *ir.Schema)
		want   string
	}{
		{name: "a table that implements Mergeable", mutate: func(*ir.Schema) {}},
		{name: "two tables that implement Mergeable", mutate: func(s *ir.Schema) { s.Types["Document"].Mergeable = true }},
		{
			name:   "a schema of another kind",
			mutate: func(s *ir.Schema) { s.Kind = ir.SchemaKindGeneral; label(s).Role = ir.RoleEmbeddedStruct },
			want:   "Label: the Mergeable trait is only allowed in a DB schema (this schema has kind General)",
		},
		{
			name:   "a type that is no table",
			mutate: func(s *ir.Schema) { label(s).Role = ir.RoleEmbeddedStruct },
			want:   "Label: the Mergeable trait is only allowed on DB table types (this type has role EmbeddedStruct)",
		},
		{
			name:   "a @jsonField type",
			mutate: func(s *ir.Schema) { label(s).JsonField = true },
			want:   "Label: the Mergeable trait is on a @jsonField type, which is stored as JSON and gets no table",
		},
		{
			name: "a base class",
			mutate: func(s *ir.Schema) {
				s.Types["Tag"] = &ir.TypeDef{Name: "Tag", Role: ir.RoleDBTable, Extends: "Label", Fields: label(s).Fields}
			},
			want: "Label: the Mergeable trait is on a base class, which gets no table; implement it on the table that extends Label (Tag)",
		},
		{
			name:   "a queue",
			mutate: func(s *ir.Schema) { label(s).Queue = &ir.QueueDef{} },
			want:   "Label: the Mergeable trait is on a queue, whose rows are messages no relation references",
		},
		{
			name:   "a version graph's member",
			mutate: func(s *ir.Schema) { label(s).GraphMember = &ir.GraphMemberConfig{} },
			want:   "Label: the Mergeable trait is on a version graph's table, whose rows a commit versions",
		},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			schema := mergeableModel()
			tc.mutate(schema)
			r := &Result{}
			checkMergeable(schema, r)
			if tc.want == "" {
				if len(r.Errors) > 0 {
					t.Fatalf("want a clean verification, got %v", errorStrings(r))
				}
				return
			}
			if !hasError(r, tc.want) {
				t.Fatalf("want an error containing %q, got %v", tc.want, errorStrings(r))
			}
		})
	}
}
