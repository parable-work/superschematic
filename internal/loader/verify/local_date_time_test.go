package verify

import (
	"slices"
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// TestLocalDateTimeHeldToWhereItIsCarried: a wall date-time is a column of
// a DB table and a field of a payload; a list or a key of them in a table,
// a queue's message, a version graph's entity, a projection and "now" are
// refused by name.
func TestLocalDateTimeHeldToWhereItIsCarried(t *testing.T) {
	now := "now"
	wall := ir.TypeRef{Name: "Temporal.LocalDateTime"}
	schema := ir.NewSchema("clinic-db", ir.SchemaKindDB)
	schema.Types["Visit"] = &ir.TypeDef{Name: "Visit", Role: ir.RoleDBTable, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "startsAt", TypeRef: wall, Required: true},
		{Name: "endsAt", TypeRef: wall},
		{Name: "bookedAt", TypeRef: wall, Required: true, Default: &now},
		{Name: "reminders", TypeRef: ir.TypeRef{Name: "Temporal.LocalDateTime", IsArray: true}},
		{Name: "history", TypeRef: ir.TypeRef{Name: "Temporal.LocalDateTime", IsArray: true}, JsonField: true},
	}}
	schema.Types["Slot"] = &ir.TypeDef{Name: "Slot", Role: ir.RoleDBTable, Fields: []*ir.FieldDef{
		{Name: "at", TypeRef: wall, Required: true, Key: true},
	}}
	schema.Types["Chart"] = &ir.TypeDef{Name: "Chart", Role: ir.RoleDBTable, GraphMember: &ir.GraphMemberConfig{}, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "takenAt", TypeRef: wall},
	}}
	schema.Types["Reminder"] = &ir.TypeDef{Name: "Reminder", Role: ir.RoleEmbeddedStruct, Queue: &ir.QueueDef{}, Fields: []*ir.FieldDef{
		{Name: "at", TypeRef: wall, Required: true},
	}}
	schema.Types["VisitView"] = &ir.TypeDef{Name: "VisitView", Role: ir.RoleEmbeddedStruct, Fields: []*ir.FieldDef{
		{Name: "startsAt", TypeRef: wall, Required: true},
	}}
	r := &Result{}
	checkLocalDateTime(schema, r)
	var got []string
	for _, d := range r.Errors {
		got = append(got, d.Msg)
	}
	want := []string{
		`Chart.takenAt: a version graph's entity does not carry a wall date-time (Temporal.LocalDateTime) yet`,
		`Reminder.at: a queue's message does not carry a wall date-time (Temporal.LocalDateTime) yet; give it a string or a Temporal.DateTime`,
		`Slot.at: a wall date-time (Temporal.LocalDateTime) is not a table's key yet`,
		`Visit.bookedAt: Default<T, "now"> is the time of the insert, an instant, and Temporal.LocalDateTime is a wall date-time, which has no zone to read that instant in; give it a Temporal.DateTime or no default`,
		`Visit.reminders: a table does not hold a list of wall date-times (Temporal.LocalDateTime) yet; hold one, or a @jsonField list`,
	}
	if !slices.Equal(got, want) {
		t.Errorf("checkLocalDateTime:\n got %q\nwant %q", got, want)
	}
}
