// commerce makes tasks-db a shop (D70 on the core, D103's step 4): an
// Inventory table implementing Stock, and Task a claim, its status
// Workflow with Holds beside it holding the lines a list of Line names and
// the inventory its to-one relation wrap points at, as fixture-commerce-db's
// Checkout implements them. holds replaces Holds' holds when given.
func commerce(holds map[string]any) func(doc, task map[string]any) {
	return func(doc, task map[string]any) {
		types := doc["types"].(map[string]any)
		types["Inventory"] = map[string]any{"name": "Inventory", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Stock", "implements": true, "config": map[string]any{"permission": "stock.adjust"}}},
			"fields": []any{
				taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
				taskField("title", "string", map[string]any{"required": true}),
			}}
		types["Line"] = map[string]any{"name": "Line", "role": "EmbeddedStruct", "fields": []any{
			taskField("inventoryId", "string", map[string]any{"required": true}),
			taskField("quantity", "Generic.Int64", map[string]any{"required": true}),
		}}
		if holds == nil {
			holds = map[string]any{
				"lines": map[string]any{"each": map[string]any{"field": "lines", "target": "inventoryId"}, "schema": "Inventory", "quantity": map[string]any{"field": "quantity"}},
				"wrap":  map[string]any{"link": "wrap", "quantity": 1},
			}
		}
		task["behaviors"] = []any{
			map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
				"states":      []any{"cart", "held", "placed", "cancelled"},
				"transitions": []any{map[string]any{"from": "cart", "to": "held"}, map[string]any{"from": "held", "to": "placed"}, map[string]any{"from": "held", "to": "cancelled"}},
			}},
			map[string]any{"name": "Holds", "implements": true, "config": map[string]any{
				"holds": holds, "takeOn": []any{"held"}, "commitOn": []any{"placed"}, "releaseOn": []any{"cancelled"},
			}},
		}
		addField(task, map[string]any{"name": "lines", "typeRef": map[string]any{"name": "Line", "isArray": true}})
		addField(task, taskField("wrap", "Inventory", map[string]any{"relation": map[string]any{"type": "Inventory"}}))
	}
}

// TestHoldsNamesATableThatImplementsSupply (D103's step 4): the table a
// hold names, an each hold's schema or a link hold's relation's target,
// is a table of the database that implements Supply, asked what it holds;
// an each hold's field is a list whose elements' type has the target field.
// A Holds and a Stock as fixture-commerce-db composes them load.
func TestHoldsNamesATableThatImplementsSupply(t *testing.T) {
	const prefix = "type Task: behavior Holds config: "
	lines := func(spec map[string]any) func(doc, task map[string]any) {
		return commerce(map[string]any{"lines": spec})
	}
	each := map[string]any{"field": "lines", "target": "inventoryId"}
	holdRefusals(t, "Holds", []refusalCase{
		{"a schema that is no table", lines(map[string]any{"each": each, "schema": "Shelf", "quantity": map[string]any{"field": "quantity"}}),
			prefix + "holds.lines names Shelf, which is not a table of tasks-db: a hold takes what a table that implements Supply gives (D103)"},
		{"a table that implements no Supply", edits(lines(map[string]any{"each": each, "schema": "Person", "quantity": map[string]any{"field": "quantity"}}), func(doc, _ map[string]any) { person(doc) }),
			prefix + "holds.lines names Person, which implements no behavior that implements Supply (Stock, Calendar or a supply of its own): a hold takes what a supply gives (D103)"},
		{"a link to a table that implements no Supply", edits(commerce(map[string]any{"gift": map[string]any{"link": "sponsor", "quantity": 1}}), func(doc, task map[string]any) {
			person(doc)
			addField(task, taskField("sponsor", "Person", map[string]any{"relation": map[string]any{"type": "Person"}}))
		}),
			prefix + "holds.gift names Person, which implements no behavior that implements Supply (Stock, Calendar or a supply of its own): a hold takes what a supply gives (D103)"},
		{"an interval of Stock", lines(map[string]any{"each": each, "schema": "Inventory", "interval": map[string]any{"start": "startsAt", "durationMs": 3600000}}),
			prefix + "holds.lines asks an interval of Inventory, whose Stock holds units: a hold of units asks a quantity"},
		{"an each field that is no list", lines(map[string]any{"each": map[string]any{"field": "title", "target": "inventoryId"}, "schema": "Inventory", "quantity": 1}),
			prefix + `holds.lines.each.field "title" is not a list field of Task: an each hold takes one item per element of a list`},
		{"a target the element lacks", lines(map[string]any{"each": map[string]any{"field": "lines", "target": "sku"}, "schema": "Inventory", "quantity": 1}),
			prefix + `holds.lines.each.target "sku" is not a field of Line, the type of Task's lines (its fields: inventoryId, quantity)`},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"a cart's lines and its wrap": commerce(nil),
	})
}

// TestHoldsRequiresWorkflow (D70): Holds requires Workflow, naming the one
// missing, as its declaration says. Stock and Calendar conflict by their
// declarations too, which checkTypeBehaviors holds once a table may
// implement Calendar.
func TestHoldsRequiresWorkflow(t *testing.T) {
	_, err := loadTasks(t, edits(commerce(nil), func(_, task map[string]any) {
		task["behaviors"] = task["behaviors"].([]any)[1:]
	}))
	if want := "type Task: behavior Holds requires behavior Workflow, which the type does not list"; err == nil || !strings.Contains(err.Error(), want) {
		t.Fatalf("LoadService = %v, want %q", err, want)
	}
}
