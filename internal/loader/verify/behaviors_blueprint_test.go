package verify_test

import "testing"

// run adds Run, a table that implements Blueprint with steps over Task, its
// child table, and gives Task what a child holds (D149): a to-one relation
// run to Run, the string field step its key is held in, Constants over
// step beside its owner, and Dependencies beside its Workflow.
func run(given map[string]any) func(doc, task map[string]any) {
	return func(doc, task map[string]any) {
		blueprint := map[string]any{"schema": "Task", "parentLink": "run", "keyField": "step", "steps": map[string]any{
			"plan": map[string]any{"data": map[string]any{"title": "Plan it"}},
			"work": map[string]any{"after": []any{"plan"}, "when": map[string]any{"field": "labels", "includes": "work"}},
		}}
		// A member given as nil is left out.
		for k, v := range given {
			if v == nil {
				delete(blueprint, k)
				continue
			}
			blueprint[k] = v
		}
		doc["types"].(map[string]any)["Run"] = map[string]any{"name": "Run", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Blueprint", "implements": true, "config": blueprint}},
			"fields": []any{
				taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
				taskField("title", "string", map[string]any{"required": true}),
				taskField("labels", "string", map[string]any{"typeRef": map[string]any{"name": "string", "isArray": true}}),
				taskField("tasks", "Task", map[string]any{"typeRef": map[string]any{"name": "Task", "isArray": true}, "hasMany": true}),
			},
		}
		addField(task, taskField("run", "Run", map[string]any{"relation": map[string]any{"type": "Run"}}))
		addField(task, taskField("step", "string", nil))
		config(task, "Constants")["fields"] = []any{"owner", "step"}
		task["behaviors"] = append(task["behaviors"].([]any), map[string]any{"name": "Dependencies", "implements": true, "config": map[string]any{}})
	}
}

// TestBlueprintConfigIsHeldToItsChildTable (D149): a table's Blueprint
// config is held to the child table it names, which a type's define check
// on the core cannot see, in the engine's words where it has them: the
// child is a table, keyed by a UUID or a string, composing no Blueprint;
// its relation to the table, its key field, its Constants over the fields
// a stamp sets, its Dependencies for a step after another, and the fields
// a copy and a step's data set; a when's includes reads a list; and from,
// whose pinned revision a table's relation does not hold, is refused. A
// template over a child that holds all of it loads.
func TestBlueprintConfigIsHeldToItsChildTable(t *testing.T) {
	const prefix = "type Run: behavior Blueprint config: "
	holdRefusals(t, "Blueprint", []refusalCase{
		{"a child the database lacks", run(map[string]any{"schema": "Ghost"}),
			prefix + "schema Ghost is not a table of tasks-db"},
		{"a relation that is not one to this table", run(map[string]any{"parentLink": "owner"}),
			prefix + "schema Task has no to-one relation owner to Run, through which its children point at their parent"},
		{"a key field that holds no string", run(map[string]any{"keyField": "attempts"}),
			prefix + "keyField attempts is not a string field of Task"},
		{"a copied field the child's Constants leaves loose", run(map[string]any{"copyFields": []any{"title"}}),
			prefix + "schema Task's Constants does not list title, which each stamp sets and nothing may change after"},
		{"a step's data the child lacks", run(map[string]any{"steps": map[string]any{"plan": map[string]any{"data": map[string]any{"colour": "red"}}}}),
			prefix + "step plan: data sets colour, which is not a field of Task"},
		{"an includes over no list", run(map[string]any{"steps": map[string]any{"plan": map[string]any{"when": map[string]any{"field": "title", "includes": "x"}}}}),
			prefix + "steps: step plan: when includes reads title as a list, and Run's title is not one"},
		{"from", run(map[string]any{"steps": nil, "from": map[string]any{"link": "plan", "field": "steps"}}),
			prefix + "from reads its steps from the revision a pinned link records, and a table's relation pins none: a table's Blueprint takes inline steps (D149)"},
		{"a child with no Dependencies for an after", edits(run(nil), func(_, task map[string]any) {
			var kept []any
			for _, entry := range task["behaviors"].([]any) {
				if entry.(map[string]any)["name"] != "Dependencies" {
					kept = append(kept, entry)
				}
			}
			task["behaviors"] = kept
		}), prefix + "schema Task does not compose Dependencies, so a step's after cannot block its child"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"a template over a child that holds it": run(nil),
		"a copied field the child keeps": edits(run(map[string]any{"copyFields": []any{"title"}}), func(_, task map[string]any) {
			config(task, "Constants")["fields"] = []any{"owner", "step", "title"}
		}),
	})
}
