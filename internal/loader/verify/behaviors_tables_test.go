// tasksDB is a JSON DB schema shaped as fixture-approvals-db (D104), for the
// checks' cases to edit: Task implements Constants, StateRules and
// Approvals beside its status Workflow, and its createdBy is the audit
// field StateRules' by and Approvals' gates read.
func tasksDB() map[string]any {
	return map[string]any{
		"name": "tasks-db",
		"kind": "DB",
		"scalars": map[string]any{
			"Identity.UUID":     map[string]any{"name": "Identity.UUID", "languagePrimitive": "string"},
			"Identity.UserID":   map[string]any{"name": "Identity.UserID", "languagePrimitive": "string"},
			"Temporal.DateTime": map[string]any{"name": "Temporal.DateTime", "languagePrimitive": "string"},
			"Generic.Int64":     map[string]any{"name": "Generic.Int64", "languagePrimitive": "number"},
			"Generic.Float64":   map[string]any{"name": "Generic.Float64", "languagePrimitive": "number"},
			"Generic.Decimal":   map[string]any{"name": "Generic.Decimal", "languagePrimitive": "string"},
		},
		"types": map[string]any{
			"Task": map[string]any{
				"name": "Task",
				"role": "DBTable",
				"behaviors": []any{
					map[string]any{"name": "Constants", "implements": true, "config": map[string]any{
						"fields": []any{"owner"}, "oneWay": map[string]any{"urgent": "up", "attempts": "up"}, "permission": "tasks.admin",
					}},
					map[string]any{"name": "StateRules", "implements": true, "config": map[string]any{"states": map[string]any{
						"planned": map[string]any{"frozen": []any{"plan"}, "by": []any{"createdBy"}},
						"working": map[string]any{"frozen": []any{"plan"}, "by": []any{"reviewer"}},
						"proving": map[string]any{"required": []any{"proof"}},
					}}},
					map[string]any{"name": "Approvals", "implements": true, "config": map[string]any{"gates": map[string]any{
						"proving": map[string]any{"count": 1, "permission": "tasks.review", "resetOn": []any{}},
						"done":    map[string]any{"count": 1, "permission": "tasks.review", "resetOn": []any{"proof"}, "pinned": true},
					}}},
					map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
						"states": []any{"planned", "working", "proving", "done", "cancelled"},
						"transitions": []any{
							map[string]any{"from": "planned", "to": "working", "by": []any{"owner"}},
							map[string]any{"from": "working", "to": "proving", "by": []any{"owner"}},
							map[string]any{"from": "proving", "to": "working"},
							map[string]any{"from": "proving", "to": "done"},
							map[string]any{"from": "planned", "to": "cancelled"},
							map[string]any{"from": "working", "to": "cancelled"},
						},
					}},
				},
				"fields": []any{
					taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
					taskField("title", "string", map[string]any{"required": true}),
					taskField("owner", "Identity.UUID", map[string]any{"required": true}),
					taskField("reviewer", "Identity.UUID", nil),
					taskField("plan", "string", nil),
					taskField("proof", "string", nil),
					taskField("urgent", "boolean", map[string]any{"required": true}),
					taskField("attempts", "number", map[string]any{"required": true}),
					taskField("createdBy", "Identity.UUID", nil),
				},
			},
		},
	}
}

// taskFields are Task's fields as the core's spec lists them, as a refusal
// of a field the type lacks names them.
const taskFields = "title, owner, reviewer, plan, proof, urgent, attempts, createdBy"

func taskField(name, typeName string, more map[string]any) map[string]any {
	f := map[string]any{"name": name, "typeRef": map[string]any{"name": typeName}}
	for k, v := range more {
		f[k] = v
	}
	return f
}

// writeFiles writes files under a new directory of the test's.
func writeFiles(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := filepath.Join(t.TempDir(), "service")
	for rel, contents := range files {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(contents), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// writeTasks writes the edited schema as a JSON service, for loadTasks and
// an API's dependency loader.
func writeTasks(t *testing.T, edit func(doc, task map[string]any)) string {
	t.Helper()
	doc := tasksDB()
	task := doc["types"].(map[string]any)["Task"].(map[string]any)
	if edit != nil {
		edit(doc, task)
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return writeFiles(t, map[string]string{
		"schema.config.json":    `{"name": "tasks-db", "kind": "DB", "outputs": {}}`,
		"src/tasks.schema.json": string(data),
	})
}

// loadTasks loads the edited schema.
func loadTasks(t *testing.T, edit func(doc, task map[string]any)) (*ir.Schema, error) {
	t.Helper()
	return loader.LoadService(writeTasks(t, edit))
}

// use is Task's use of behavior, to edit: its entry in behaviors.
func use(task map[string]any, behavior string) map[string]any {
	for _, entry := range task["behaviors"].([]any) {
		if ref := entry.(map[string]any); ref["name"] == behavior {
			return ref
		}
	}
	panic("Task has no use of " + behavior)
}

// config is the config of Task's use of behavior, to edit.
func config(task map[string]any, behavior string) map[string]any {
	return use(task, behavior)["config"].(map[string]any)
}

// addField appends a field to Task.
func addField(task map[string]any, field map[string]any) {
	task["fields"] = append(task["fields"].([]any), field)
}

// dropField removes Task's field name.
func dropField(task map[string]any, name string) {
	var kept []any
	for _, f := range task["fields"].([]any) {
		if f.(map[string]any)["name"] != name {
			kept = append(kept, f)
		}
	}
	task["fields"] = kept
}

// person adds a table Task may relate to.
func person(doc map[string]any) {
	doc["types"].(map[string]any)["Person"] = map[string]any{"name": "Person", "role": "DBTable", "fields": []any{
		taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
	}}
}

// review adds a second Workflow to Task, on its field review.
func review(task map[string]any) {
	task["behaviors"] = append(task["behaviors"].([]any), map[string]any{"name": "Workflow", "field": "review", "config": map[string]any{
		"states": []any{"pending", "reviewed"}, "transitions": []any{map[string]any{"from": "pending", "to": "reviewed"}},
	}})
}

// refusalCase is a table check's case: an edit and the one problem it
// draws of the behavior's config.
type refusalCase struct {
	name string
	edit func(doc, task map[string]any)
	want string
}

// holdRefusals loads each case's schema and holds its error to want, with
// one problem of behavior's config.
func holdRefusals(t *testing.T, behavior string, cases []refusalCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := loadTasks(t, tc.edit)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("LoadService = %v, want an error holding %q", err, tc.want)
			}
			if got := strings.Count(err.Error(), "behavior "+behavior+" config"); got != 1 {
				t.Errorf("LoadService = %v, want one problem of %s's config", err, behavior)
			}
		})
	}
}

// holdAccepted loads each edit's schema and holds it to load.
func holdAccepted(t *testing.T, cases map[string]func(doc, task map[string]any)) {
	t.Helper()
	for name, edit := range cases {
		t.Run("accepts "+name, func(t *testing.T) {
			if _, err := loadTasks(t, edit); err != nil {
				t.Fatalf("LoadService = %v", err)
			}
		})
	}
}

// warningsOf loads an API over the edited tasks-db whose sets are sets, a
// JSON list of operation sets, beside the types given, and returns its
// warnings of D104.
func warningsOf(t *testing.T, edit func(doc, task map[string]any), types, sets string) []string {
	t.Helper()
	db, err := loader.LoadService(writeTasks(t, edit))
	if err != nil {
		t.Fatal(err)
	}
	api := writeFiles(t, map[string]string{
		"schema.config.json": `{"name": "tasks-api", "kind": "API", "dependencies": [{"name": "tasks-db", "kind": "DB"}], "outputs": {}}`,
		"src/tasks.schema.json": `{"imports": [{"package": "@schemas/tasks-db", "types": ["Task"]}],
		  "scalars": {"Identity.UUID": {"name": "Identity.UUID", "languagePrimitive": "string"}},
		  "types": ` + types + `, "operationSets": ` + sets + `}`,
	})
	var warnings []string
	if _, err := loader.LoadService(api, loader.WithDependencyLoader(func(name string) (*ir.Schema, error) {
		if name != db.Name {
			return nil, os.ErrNotExist
		}
		return db, nil
	}), loader.WithWarnings(func(d *verify.Diagnostic) {
		if strings.Contains(d.Msg, "(D104)") {
			warnings = append(warnings, d.Msg)
		}
	})); err != nil {
		t.Fatalf("LoadService: %v", err)
	}
	return warnings
}
