// calendar makes tasks-db a booking desk (D70 on the core, D103's step 4):
// a Desk table implementing Calendar, and Task a booking, its status
// Workflow with Holds beside it holding time of the desk its to-one
// relation desk points at, as fixture-calendar-db's Booking implements
// them. slot replaces the hold when given.
func calendar(slot map[string]any) func(doc, task map[string]any) {
	return func(doc, task map[string]any) {
		types := doc["types"].(map[string]any)
		types["Desk"] = map[string]any{"name": "Desk", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Calendar", "implements": true, "config": map[string]any{
				"timeZone": "Europe/London",
				"hours":    map[string]any{"mon": []any{[]any{"09:00", "17:30"}}},
			}}},
			"fields": []any{
				taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
				taskField("title", "string", map[string]any{"required": true}),
			}}
		if slot == nil {
			slot = map[string]any{"link": "desk", "interval": map[string]any{"start": "slotStart", "end": "slotEnd"}}
		}
		task["behaviors"] = []any{
			map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
				"states":      []any{"draft", "held", "booked", "cancelled"},
				"transitions": []any{map[string]any{"from": "draft", "to": "held"}, map[string]any{"from": "held", "to": "booked"}, map[string]any{"from": "held", "to": "cancelled"}},
			}},
			map[string]any{"name": "Holds", "implements": true, "config": map[string]any{
				"holds": map[string]any{"slot": slot}, "takeOn": []any{"held"}, "commitOn": []any{"booked"}, "releaseOn": []any{"cancelled"},
			}},
		}
		addField(task, taskField("slotStart", "Temporal.DateTime", nil))
		addField(task, taskField("slotEnd", "Temporal.DateTime", nil))
		addField(task, taskField("desk", "Desk", map[string]any{"relation": map[string]any{"type": "Desk"}}))
	}
}

// TestHoldsAsksTimeOfACalendar (D103's step 4): a hold of a table that
// implements Calendar asks an interval, and one that asks a quantity of it
// is refused; a booking as fixture-calendar-db composes it loads.
func TestHoldsAsksTimeOfACalendar(t *testing.T) {
	const prefix = "type Task: behavior Holds config: "
	holdRefusals(t, "Holds", []refusalCase{
		{"a quantity of Calendar", calendar(map[string]any{"link": "desk", "quantity": 1}),
			prefix + "holds.slot asks a quantity of Desk, whose Calendar holds time: a hold of time asks an interval"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"a booking's slot of its desk": calendar(nil),
	})
}

// TestStockAndCalendarConflict (D70): Stock and Calendar declare the same
// contract operations, so one table implements one of them, as their
// declarations' conflicts say, which checkTypeBehaviors holds.
func TestStockAndCalendarConflict(t *testing.T) {
	_, err := loadTasks(t, edits(calendar(nil), func(doc, _ map[string]any) {
		desk := doc["types"].(map[string]any)["Desk"].(map[string]any)
		desk["behaviors"] = append(desk["behaviors"].([]any), map[string]any{"name": "Stock", "implements": true, "config": map[string]any{"permission": "stock.adjust"}})
	}))
	if want := "type Desk: behavior Calendar conflicts with behavior Stock, which the type also lists"; err == nil || !strings.Contains(err.Error(), want) {
		t.Fatalf("LoadService = %v, want %q", err, want)
	}
}
