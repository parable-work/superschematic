// seededUsers is a DB schema with a User table and a Role table that seeds
// the roles given (D88).
func seededUsers(seeds ...*ir.RoleSeed) *ir.Schema {
	db := ir.NewSchema("users", ir.SchemaKindDB)
	uuid := ir.TypeRef{Name: "Identity.UUID"}
	db.Types["Account"] = &ir.TypeDef{Name: "Account", Role: ir.RoleDBTable, User: &ir.UserTrait{Login: "email"}, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: uuid, Required: true, Key: true, AutoGenerated: true},
		{Name: "email", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
	}}
	db.Types["Role"] = &ir.TypeDef{Name: "Role", Role: ir.RoleDBTable, UserRole: &ir.UserRoleTrait{}, SeedRoles: seeds, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: uuid, Required: true, Key: true, AutoGenerated: true},
		{Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
		{Name: "permissions", TypeRef: ir.TypeRef{Name: "string", IsArray: true}, Required: true},
	}}
	return db
}

func messages(ds []*Diagnostic) []string {
	var out []string
	for _, d := range ds {
		out = append(out, d.Msg)
	}
	return out
}

// TestSeedRolesRefusedInIR: @seedRoles is on the UserRole table, names
// each role once with permissions of a permission's form, each once, and
// the table takes a row from a name and permissions alone (D88).
func TestSeedRolesRefusedInIR(t *testing.T) {
	db := seededUsers(
		&ir.RoleSeed{Name: "member", Permissions: []string{"orders.read", "orders read", "orders.read"}},
		&ir.RoleSeed{Name: "member", Permissions: []string{}},
		&ir.RoleSeed{Name: " ", Permissions: []string{"orders"}},
	)
	db.Types["Role"].Fields = append(db.Types["Role"].Fields, &ir.FieldDef{Name: "createdBy", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true})
	db.Types["Account"].SeedRoles = []*ir.RoleSeed{{Name: "admin", Permissions: []string{"orders"}}}
	r := &Result{}
	checkSeedRoles(db, r)
	want := []string{
		`Account: @seedRoles seeds the roles of the table that implements UserRole from @superschematic/db, and Account does not`,
		`Role: @seedRoles role "member"'s permission "orders read" is not dotted segments of letters, digits, _ and -, such as orders.read`,
		`Role: @seedRoles role "member" lists the permission "orders.read" twice`,
		`Role: @seedRoles names the role "member" twice`,
		`Role: @seedRoles holds a role with no name`,
		`Role: @seedRoles inserts each role with its name and permissions alone, and Role.createdBy is required and has no default its column carries; make it optional or give it a Default<T, V>`,
	}
	if got := messages(r.Errors); !slices.Equal(got, want) {
		t.Errorf("errors =\n%q\nwant\n%q", got, want)
	}

	r = &Result{}
	checkSeedRoles(seededUsers(&ir.RoleSeed{Name: "member", Permissions: []string{"orders.read"}}), r)
	if len(r.Errors) != 0 {
		t.Errorf("a clean seed: errors = %q", messages(r.Errors))
	}
}

// TestSeededRolesWarnings: an API checks the roles its registration grants
// against its authDb's seeds and its own permissions (D88), and warns of a
// default role no seed holds, a seeded permission that covers none the
// API requires, a seed that overrides firstUser's permissions, and a
// default role the first administrator cannot approve anyone into.
func TestSeededRolesWarnings(t *testing.T) {
	api := func(cfg *ir.UserSessionsConfig) (*ir.Schema, *ir.OperationSet) {
		schema := ir.NewSchema("orders-api", ir.SchemaKindAPI)
		sessions := &ir.OperationSet{Name: "Account", UserSessions: cfg}
		schema.OperationSets = []*ir.OperationSet{sessions, {Name: "Orders", Operations: []*ir.FieldDef{
			{Name: "list", Permissions: []string{"orders.read"}},
			{Name: "place", Permissions: []string{"orders.write"}},
		}}}
		return schema, sessions
	}

	schema, sessions := api(&ir.UserSessionsConfig{Register: true, Registration: ir.IdentityRegistrationApproval,
		DefaultRoles: []string{"member", "guest"},
		FirstUser:    &ir.IdentityFirstUser{Role: "admin", Permissions: []string{"identity", "orders.read"}},
	})
	db := seededUsers(
		&ir.RoleSeed{Name: "member", Permissions: []string{"orders.read", "orders.write"}},
		&ir.RoleSeed{Name: "auditor", Permissions: []string{"orders.raed"}},
	)
	r := &Result{}
	checkSeededRoles(schema, db, sessions, "identity", r)
	want := []string{
		`users's @seedRoles gives the role auditor the permission orders.raed, which covers no permission orders-api requires (identity.roles.read, identity.roles.write, identity.users.read, identity.users.write, orders.read, orders.write)`,
		`Account: @userSessions defaultRoles grants guest, which users's @seedRoles does not seed: the first registration creates it with no permissions, so a user approved into it can do nothing until an administrator gives it some; seed it with @seedRoles on Role`,
		`Account: the first administrator's role admin does not cover orders.write, which the default role member carries: approveUser needs the approver's permissions to cover the user's, so that administrator can approve no one`,
	}
	if got := messages(r.Warnings); !slices.Equal(got, want) {
		t.Errorf("warnings =\n%q\nwant\n%q", got, want)
	}

	// A seed of the administrator's role holds over firstUser's
	// permissions, and covers the member's.
	db = seededUsers(
		&ir.RoleSeed{Name: "member", Permissions: []string{"orders.read"}},
		&ir.RoleSeed{Name: "admin", Permissions: []string{"identity", "orders"}},
	)
	schema, sessions = api(&ir.UserSessionsConfig{Register: true, Registration: ir.IdentityRegistrationApproval,
		DefaultRoles: []string{"member"},
		FirstUser:    &ir.IdentityFirstUser{Role: "admin", Permissions: []string{"identity"}},
	})
	r = &Result{}
	checkSeededRoles(schema, db, sessions, "identity", r)
	want = []string{
		`Account: @userSessions firstUser gives admin the permissions identity, and users's @seedRoles seeds it with identity, orders, which hold: firstUser's apply only to a role register creates`,
	}
	if got := messages(r.Warnings); !slices.Equal(got, want) {
		t.Errorf("warnings =\n%q\nwant\n%q", got, want)
	}
}
