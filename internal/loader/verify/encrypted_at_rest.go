package verify

import (
	"slices"
	"strings"

	"github.com/parable-work/superschematic/internal/generator/codegen"
	ir "github.com/parable-work/superschematic/ir"
)

// checkEncryptedFields holds each Encrypted<T> field (D85) to what the ORMs
// can encrypt and decrypt: a text column of a DB table they keep, whose
// row key they know before the insert, since the ciphertext is bound to
// it. A ciphertext compares with nothing, so the field takes no @key,
// @unique, @searchField, @index or Default, and no history image keeps it.
// A queue's message carries none (checkEnqueueOnChange refuses a trigger
// that reads one). Each refusal names the fix. An Encrypted<T> field is a Secret<T>, which
// the data forms may leave unsaid, so the pass marks it one.
func checkEncryptedFields(schema *ir.Schema, r *Result) {
	bases := codegen.BaseTypeNames(schema)
	for _, name := range sortedTypeNames(schema.Types) {
		td := schema.Types[name]
		for _, fd := range td.Fields {
			if fd != nil && fd.Decrypted && td.Source == nil {
				r.errorf(td.Owner, "%s.%s: @decrypted marks a field of a @source view that reads an Encrypted<T> field, and %s is no @source view", td.Name, fd.Name, td.Name)
			}
			if fd == nil || !fd.EncryptedAtRest {
				continue
			}
			fd.Secret = true
			owner := td.Name + "." + fd.Name
			switch {
			case schema.Kind != ir.SchemaKindDB:
				r.errorf(td.Owner, "%s: Encrypted<T> marks a stored field of a DB table, and %s is a schema of kind %s; a request or a response carries the value itself", owner, schema.Name, schema.Kind)
				continue
			case bases[td.Name]:
				// A base class's fields are checked on each table that
				// extends it, where they are copied.
				continue
			case td.Queue != nil:
				r.errorf(td.Owner, "%s: Encrypted<T> marks a field of a table the ORMs keep, and %s is a @queue, whose workers read its message as it was enqueued; carry the key of the row that holds the value, and read the field through the row's repository", owner, td.Name)
				continue
			case !hasTable(td, bases):
				r.errorf(td.Owner, "%s: Encrypted<T> marks a field of a table; %s is no table, and its value is stored whole with the row that holds it", owner, td.Name)
				continue
			}
			checkEncryptedField(schema, td, fd, owner, r)
		}
	}
}

func checkEncryptedField(schema *ir.Schema, td *ir.TypeDef, fd *ir.FieldDef, owner string, r *Result) {
	ref := fd.TypeRef
	switch {
	case codegen.IsEngineType(td):
		r.errorf(td.Owner, "%s: %s composes behaviors, so the engine keeps its rows, and the engine does not encrypt a field; keep the value in a table of its own, which the ORMs keep (support follows)", owner, td.Name)
		return
	case td.User != nil || td.Origin == ir.OriginIdentity:
		r.errorf(td.Owner, "%s: the identity stores read and write the user model's tables without the ORMs, so they cannot encrypt a field; keep the value in a table of its own that relates to %s", owner, td.Name)
		return
	case td.VersionGraph != nil || td.GraphMember != nil:
		r.errorf(td.Owner, "%s: a version graph's runtimes do not encrypt a field; keep the value in a table outside the graph (support follows)", owner)
		return
	case ref.Name != "string" || ref.IsArray || ref.IsMap:
		r.errorf(td.Owner, "%s: Encrypted<T> takes string for now, and this one is %s; encode the value as text (support for other types follows)", owner, typeRefString(ref))
		return
	}
	refuse := func(what, why string) {
		r.errorf(td.Owner, "%s: an Encrypted<T> field %s: %s", owner, what, why)
	}
	if fd.Key {
		refuse("cannot be the @key", "its ciphertext is bound to the row's key; give the table another key")
	}
	if fd.Unique {
		refuse("cannot be @unique", "each write's ciphertext differs, so the database cannot compare two; drop @unique, or keep a hash of the value in a field of its own")
	}
	if fd.SearchField {
		refuse("cannot be a @searchField", "the search column would hold its ciphertext; drop @searchField")
	}
	if fd.JsonField {
		refuse("cannot be @jsonField", "its column holds the ciphertext's text; drop @jsonField")
	}
	if fd.Relation != nil {
		refuse("cannot be a relation", "a foreign key compares the value itself; drop the encryption")
	}
	if fd.AutoGenerated {
		refuse("cannot be AutoGenerate<T>", "the database cannot write a ciphertext; drop AutoGenerate")
	}
	if fd.Default != nil || fd.PlatformDefault != "" {
		refuse("takes no Default<T, V>", "the database cannot write a ciphertext, and a default the schema holds is no secret; leave the default to the code that creates the row")
	}
	for _, idx := range td.Indexes {
		if slices.Contains(idx.Keys, fd.Name) {
			refuse("cannot be an @index key", "each write's ciphertext differs, so an index finds nothing by it; drop it from @index(["+strings.Join(idx.Keys, ", ")+"])")
			break
		}
	}
	if td.Versioned && (td.VersionedConfig == nil || !slices.Contains(td.VersionedConfig.Exclude, fd.Name)) {
		refuse("must be left out of the history of a @versioned table", "a history image would keep its ciphertext, which the history readers do not decrypt; list it in @versioned({ exclude: [\""+fd.Name+"\"] })")
	}
	checkEncryptedTableKey(schema, td, owner, r)
}

// checkEncryptedTableKey refuses an encrypted field of a table whose key
// the database generates and the ORMs cannot: the ciphertext is bound to
// the row's key, so the ORM must know it before the insert. A UUID key,
// the id a table without @key gets among them, the ORMs generate when a
// create leaves it unset; any other key the create must set.
func checkEncryptedTableKey(schema *ir.Schema, td *ir.TypeDef, owner string, r *Result) {
	for _, key := range td.Fields {
		if key == nil || !key.Key {
			continue
		}
		if key.AutoGenerated && !isUUIDField(schema, key) {
			r.errorf(td.Owner, "%s: an Encrypted<T> field's ciphertext is bound to its row's key, which the ORMs must know before the insert, and the database generates %s.%s; give the table a UUID key, or a key each create sets", owner, td.Name, key.Name)
		}
		return
	}
}
