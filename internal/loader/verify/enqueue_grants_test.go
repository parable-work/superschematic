package verify

import (
	"slices"
	"strings"
	"testing"

	ir "github.com/parable-work/superschematic/ir"
)

// TestARoleTablesGrantsEventIsHeldToTheGrants (#625): an @enqueueOnChange
// of a UserRole table's grants names UserRoleGrant's fields, which the
// pass checks before the expansion adds the table, and a table that is no
// UserRole table has no grants to declare one of.
func TestARoleTablesGrantsEventIsHeldToTheGrants(t *testing.T) {
	uuid := ir.TypeRef{Name: "Identity.UUID"}
	key := func() *ir.FieldDef {
		return &ir.FieldDef{Name: "id", TypeRef: uuid, Required: true, Key: true, AutoGenerated: true}
	}
	schema := ir.NewSchema("users-db", ir.SchemaKindDB)
	schema.Scalars["Identity.UUID"] = &ir.ScalarDef{Name: "Identity.UUID", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "UUID"}}
	schema.Scalars["Temporal.DateTime"] = &ir.ScalarDef{Name: "Temporal.DateTime", LanguagePrimitive: ir.LanguageString, TypeMappings: map[string]string{"sql": "TIMESTAMPTZ"}}
	schema.Types["User"] = &ir.TypeDef{Name: "User", Role: ir.RoleDBTable, User: &ir.UserTrait{Login: "email"}, Fields: []*ir.FieldDef{
		key(), {Name: "email", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
	}}
	grants := func(message map[string]string) *ir.EnqueueOnChange {
		return &ir.EnqueueOnChange{Queue: "Granted", Of: ir.EnqueueOfGrants, On: []string{ir.EnqueueOnInsert}, Message: message}
	}
	schema.Types["Role"] = &ir.TypeDef{Name: "Role", Role: ir.RoleDBTable, UserRole: &ir.UserRoleTrait{}, Fields: []*ir.FieldDef{
		key(), {Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
	}, EnqueueOnChange: []*ir.EnqueueOnChange{grants(map[string]string{"user": "user", "role": "role"})}}
	schema.Types["Team"] = &ir.TypeDef{Name: "Team", Role: ir.RoleDBTable, Fields: []*ir.FieldDef{key()},
		EnqueueOnChange: []*ir.EnqueueOnChange{grants(map[string]string{"user": "id", "role": "id"})}}
	schema.Types["Granted"] = &ir.TypeDef{Name: "Granted", Role: ir.RoleEmbeddedStruct, Queue: &ir.QueueDef{}, Fields: []*ir.FieldDef{
		{Name: "user", TypeRef: uuid, Required: true}, {Name: "role", TypeRef: uuid, Required: true},
	}}
	r := &Result{}
	checkEnqueueOnChange(schema, Input{}, r)
	var got []string
	for _, d := range r.Errors {
		got = append(got, d.Msg)
	}
	want := []string{
		`@enqueueOnChange(Granted) on Team: of "grants" is a UserRole table's grants, and Team is no UserRole table of a schema with a User table; leave of out to enqueue on Team's own writes`,
	}
	if !slices.Equal(got, want) {
		t.Fatalf("errors =\n%q\nwant\n%q", got, want)
	}

	// A message that names a field the grants lack is refused as of
	// UserRoleGrant.
	schema.Types["Role"].EnqueueOnChange = []*ir.EnqueueOnChange{grants(map[string]string{"user": "user", "role": "name"})}
	delete(schema.Types, "Team")
	r = &Result{}
	checkEnqueueOnChange(schema, Input{}, r)
	if len(r.Errors) != 1 || !strings.Contains(r.Errors[0].Msg, "on UserRoleGrant") || !strings.Contains(r.Errors[0].Msg, `"name"`) {
		t.Fatalf("a grants' message naming the role's own field: %v", r.Errors)
	}
}
