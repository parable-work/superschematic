package verify_test

import "testing"

// project adds Project, a table with a status Workflow that implements
// Rollups with rollups, and gives Task a to-one relation project to it, the
// rows a HasMany of Project lists (D104's step 4).
func project(rollups map[string]any) func(doc, task map[string]any) {
	return func(doc, task map[string]any) {
		doc["types"].(map[string]any)["Project"] = map[string]any{"name": "Project", "role": "DBTable",
			"behaviors": []any{
				map[string]any{"name": "Rollups", "implements": true, "config": map[string]any{"rollups": rollups}},
				map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
					"states": []any{"active", "done"}, "transitions": []any{map[string]any{"from": "active", "to": "done"}},
				}},
			},
			"fields": []any{
				taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
				taskField("tasks", "Task", map[string]any{"typeRef": map[string]any{"name": "Task", "isArray": true}, "hasMany": true}),
			},
		}
		addField(task, taskField("project", "Project", map[string]any{"relation": map[string]any{"type": "Project"}}))
	}
}

// rollup is one rollup over Task's project relation.
func rollup(function string, more map[string]any) map[string]any {
	out := map[string]any{"schema": "Task", "link": "project", "function": function}
	for k, v := range more {
		out[k] = v
	}
	return out
}

// TestRollupsConfigIsHeldToItsTables (D104's step 4): a table's Rollups
// config is held to the tables of its database, which a type's define
// check on the core cannot see: the rollup's table, its relation to this
// table, the Workflow all and any read and the field each function reads,
// in the engine's words where it has them; latest waits, in the core's.
// Rollups over the rows a HasMany lists loads.
func TestRollupsConfigIsHeldToItsTables(t *testing.T) {
	const prefix = "type Project: behavior Rollups config: "
	holdRefusals(t, "Rollups", []refusalCase{
		{"a table the database lacks", project(map[string]any{"tasks": map[string]any{"schema": "Ghost", "link": "project", "function": "count"}}),
			prefix + "rollup tasks: Ghost is not a table of tasks-db"},
		{"a relation that is not one to this table", project(map[string]any{"tasks": map[string]any{"schema": "Task", "link": "owner", "function": "count"}}),
			prefix + "rollup tasks: Task has no to-one relation owner to Project (its relations to Project: project)"},
		{"a countBy field the table lacks", project(map[string]any{"byKind": rollup("countBy", map[string]any{"field": "kind"})}),
			prefix + "rollup byKind: Task has no field kind; countBy takes a string, enum or boolean field of its type, or Workflow.status when it composes Workflow"},
		{"a countBy field of a number", project(map[string]any{"byAttempts": rollup("countBy", map[string]any{"field": "attempts"})}),
			prefix + "rollup byAttempts: countBy takes a string, enum or boolean field, and Task's attempts holds a number"},
		{"a sum of a string", project(map[string]any{"total": rollup("sum", map[string]any{"field": "title"})}),
			prefix + "rollup total: sum takes a number or integer field, and Task's title holds a string"},
		{"latest", project(map[string]any{"last": rollup("latest", map[string]any{"field": "title"})}),
			prefix + "rollup last: latest reads the linked row created last, and a table's row carries no time of its creation the core reads: latest waits for a later step (D104's step 4)"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"every function over the rows a HasMany lists": project(map[string]any{
			"tasks":    rollup("count", nil),
			"byStatus": rollup("countBy", map[string]any{"field": "status"}),
			"byFlow":   rollup("countBy", map[string]any{"field": "Workflow.status"}),
			"urgent":   rollup("countBy", map[string]any{"field": "urgent"}),
			"attempts": rollup("sum", map[string]any{"field": "attempts"}),
			"least":    rollup("min", map[string]any{"field": "attempts"}),
			"done":     rollup("all", map[string]any{"gatedStates": []any{"done"}, "outcomes": []any{"success"}}),
			"any":      rollup("any", nil),
		}),
	})
}

// dependencies gives Task the implements Dependencies use of config beside
// its Workflow (D104's step 4).
func dependencies(config map[string]any) func(doc, task map[string]any) {
	return func(_, task map[string]any) {
		task["behaviors"] = append(task["behaviors"].([]any), map[string]any{"name": "Dependencies", "implements": true, "config": config})
	}
}

// TestDependenciesConfigIsHeldToItsTables (D104's step 4): each table a
// Dependencies config's schemas names is a table of the database that
// composes one Workflow, and the table itself composes one. Blockers of the
// table itself, and of another table with a Workflow, load.
func TestDependenciesConfigIsHeldToItsTables(t *testing.T) {
	const prefix = "type Task: behavior Dependencies config: "
	holdRefusals(t, "Dependencies", []refusalCase{
		{"a table the database lacks", dependencies(map[string]any{"schemas": []any{"Task", "Ghost"}}),
			prefix + "schemas names Ghost, which is not a table of tasks-db"},
		{"a table with no Workflow", edits(func(doc, _ map[string]any) { person(doc) }, dependencies(map[string]any{"schemas": []any{"Person"}})),
			prefix + "schemas names Person, which does not compose Workflow, so its rows cannot block"},
		{"a table with two Workflows", edits(func(_, task map[string]any) { review(task) }, dependencies(map[string]any{})),
			prefix + "it gates the type's Workflow, and the type has several (status, review): Dependencies gates a type's one Workflow"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"blockers of the table itself":   dependencies(map[string]any{}),
		"blockers of a table it relates": edits(project(map[string]any{"tasks": rollup("count", nil)}), dependencies(map[string]any{"schemas": []any{"Task", "Project"}, "gatedStates": []any{"done"}})),
	})
}
