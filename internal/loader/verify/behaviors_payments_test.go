import "testing"

// refunds makes tasks-db a shop that refunds (D70 on the core, D103's step
// 4): an Order table implementing Payments over its own amount, recording
// with payments.record, and Task a refund of one, its status Workflow with
// Payments beside it naming the to-one relation order as refundOf, as
// fixture-payments-db's Refund implements them. record is the refund's
// record.permission; required says whether order is required.
func refunds(record string, required bool) func(doc, task map[string]any) {
	return func(doc, task map[string]any) {
		types := doc["types"].(map[string]any)
		types["Order"] = map[string]any{"name": "Order", "role": "DBTable",
			"behaviors": []any{map[string]any{"name": "Payments", "implements": true, "config": map[string]any{
				"amount": map[string]any{"field": "totalCents"}, "currency": "GBP",
				"record": map[string]any{"permission": "payments.record"},
			}}},
			"fields": []any{
				taskField("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
				taskField("totalCents", "Generic.Int64", map[string]any{"required": true}),
			}}
		task["behaviors"] = []any{
			map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
				"states":      []any{"requested", "approved"},
				"transitions": []any{map[string]any{"from": "requested", "to": "approved"}},
			}},
			map[string]any{"name": "Payments", "implements": true, "config": map[string]any{
				"refundOf": map[string]any{"link": "order"}, "amount": map[string]any{"field": "amountCents"}, "currency": "GBP",
				"issueOn": []any{"approved"}, "record": map[string]any{"permission": record},
			}},
		}
		addField(task, taskField("amountCents", "Generic.Int64", map[string]any{"required": true}))
		addField(task, taskField("order", "Order", map[string]any{"required": required, "relation": map[string]any{"type": "Order"}}))
	}
}

// TestARefundNamesWhatItRefunds (D70 on the core): a refund table's
// refundOf names a required to-one relation to a table that implements
// Payments, is no refund itself, and records with the same
// record.permission, since the adapter that records the refund's outcome
// on that table settles it on the refund in the same call. A refund as
// fixture-payments-db composes it loads.
func TestARefundNamesWhatItRefunds(t *testing.T) {
	const prefix = "type Task: behavior Payments config: refundOf.link order"
	holdRefusals(t, "Payments", []refusalCase{
		{"another record permission", refunds("refunds.record", true),
			prefix + ": record.permission is refunds.record, and Order's Payments, whose adapter settles this refund's outcome here, records with payments.record; give both the same"},
		{"a relation that is not required", refunds("payments.record", false),
			prefix + " is not required, and every refund names what it refunds"},
		{"a table that implements no Payments", edits(refunds("payments.record", true), func(doc, task map[string]any) {
			person(doc)
			dropField(task, "order")
			addField(task, taskField("order", "Person", map[string]any{"required": true, "relation": map[string]any{"type": "Person"}}))
		}),
			prefix + ": Person, which the link points at, does not implement Payments"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"a refund of an order": refunds("payments.record", true),
	})
}

// TestAnAmountFromHoldsFollowsHolds (D70 on the core): an amount from
// Holds' total needs the table to list Holds, before Payments, whose
// after-change hook reads the total Holds' writes; the build says so in
// the core's words.
func TestAnAmountFromHoldsFollowsHolds(t *testing.T) {
	const prefix = "type Task: behavior Payments config: "
	owes := func(task map[string]any) map[string]any {
		return map[string]any{"name": "Payments", "implements": true, "config": map[string]any{
			"amount": map[string]any{"holds": true}, "record": map[string]any{"permission": "payments.record"},
		}}
	}
	holdRefusals(t, "Payments", []refusalCase{
		{"no Holds", func(doc, task map[string]any) {
			task["behaviors"] = []any{owes(task)}
		}, prefix + "amount.holds reads Holds.total, and the type does not list Holds"},
		{"Payments before Holds", edits(commerce(nil), func(doc, task map[string]any) {
			behaviors := task["behaviors"].([]any)
			task["behaviors"] = []any{behaviors[0], owes(task), behaviors[1]}
		}), prefix + "amount.holds reads Holds.total, so the type lists Payments after Holds"},
	})
	holdAccepted(t, map[string]func(doc, task map[string]any){
		"Payments after Holds": edits(commerce(nil), func(doc, task map[string]any) {
			task["behaviors"] = append(task["behaviors"].([]any), owes(task))
		}),
	})
}
