// vaultSchema has PlaidItem, a table whose accessToken is Encrypted<T>,
// edited by edit.
func vaultSchema(edit func(td *ir.TypeDef, token *ir.FieldDef)) *ir.Schema {
	str := ir.TypeRef{Name: "string"}
	schema := ir.NewSchema("vault-db", ir.SchemaKindDB)
	schema.Scalars["Identity.UUID"] = &ir.ScalarDef{Name: "Identity.UUID", TypeMappings: map[string]string{"sql": "UUID"}}
	token := &ir.FieldDef{Name: "accessToken", TypeRef: str, Required: true, EncryptedAtRest: true}
	td := &ir.TypeDef{Name: "PlaidItem", Role: ir.RoleDBTable, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "itemId", TypeRef: str, Required: true},
		token,
	}}
	schema.Types[td.Name] = td
	if edit != nil {
		edit(td, token)
	}
	return schema
}

func encryptedErrors(schema *ir.Schema) []string {
	r := &Result{}
	checkEncryptedFields(schema, r)
	return errorStrings(r)
}

// TestEncryptedFieldsLoad: an Encrypted<T> field of a table, text, with a
// UUID key the ORMs generate, loads, and is a Secret<T> once verified,
// whatever form declared it (D85).
func TestEncryptedFieldsLoad(t *testing.T) {
	schema := vaultSchema(nil)
	if errs := encryptedErrors(schema); len(errs) != 0 {
		t.Fatalf("errors = %v", errs)
	}
	if !schema.Types["PlaidItem"].Fields[2].Secret {
		t.Error("an Encrypted<T> field is not Secret")
	}
	keyed := vaultSchema(func(td *ir.TypeDef, _ *ir.FieldDef) {
		td.Fields[0] = &ir.FieldDef{Name: "code", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Key: true}
	})
	if errs := encryptedErrors(keyed); len(errs) != 0 {
		t.Errorf("a key each create sets: errors = %v", errs)
	}
	versioned := vaultSchema(func(td *ir.TypeDef, _ *ir.FieldDef) {
		td.Versioned = true
		td.VersionedConfig = &ir.VersionedConfig{Exclude: []string{"accessToken"}}
	})
	if errs := encryptedErrors(versioned); len(errs) != 0 {
		t.Errorf("a versioned table that excludes it: errors = %v", errs)
	}
}

// TestEncryptedFieldsRefusals: each use the ORMs cannot keep fails the
// load, naming the fix (D85).
func TestEncryptedFieldsRefusals(t *testing.T) {
	for _, tc := range []struct {
		name string
		edit func(td *ir.TypeDef, token *ir.FieldDef)
		want string
	}{
		{"@index", func(td *ir.TypeDef, _ *ir.FieldDef) {
			td.Indexes = []ir.IndexDef{{Keys: []string{"itemId", "accessToken"}}}
		},
			"PlaidItem.accessToken: an Encrypted<T> field cannot be an @index key: each write's ciphertext differs, so an index finds nothing by it; drop it from @index([itemId, accessToken])"},
		{"@unique", func(_ *ir.TypeDef, f *ir.FieldDef) { f.Unique = true },
			"cannot be @unique: each write's ciphertext differs, so the database cannot compare two; drop @unique, or keep a hash of the value in a field of its own"},
		{"@searchField", func(_ *ir.TypeDef, f *ir.FieldDef) { f.SearchField = true },
			"cannot be a @searchField: the search column would hold its ciphertext; drop @searchField"},
		{"Default", func(_ *ir.TypeDef, f *ir.FieldDef) { v := "x"; f.Default = &v },
			"takes no Default<T, V>: the database cannot write a ciphertext, and a default the schema holds is no secret; leave the default to the code that creates the row"},
		{"@key", func(td *ir.TypeDef, f *ir.FieldDef) { td.Fields[0].Key = false; f.Key = true },
			"cannot be the @key: its ciphertext is bound to the row's key; give the table another key"},
		{"a list", func(_ *ir.TypeDef, f *ir.FieldDef) { f.TypeRef.IsArray = true },
			"Encrypted<T> takes string for now, and this one is string[]; encode the value as text (support for other types follows)"},
		{"a scalar", func(_ *ir.TypeDef, f *ir.FieldDef) { f.TypeRef.Name = "Identity.UUID" },
			"Encrypted<T> takes string for now, and this one is Identity.UUID"},
		{"history", func(td *ir.TypeDef, _ *ir.FieldDef) { td.Versioned = true },
			`must be left out of the history of a @versioned table: a history image would keep its ciphertext, which the history readers do not decrypt; list it in @versioned({ exclude: ["accessToken"] })`},
		{"a key the database generates", func(td *ir.TypeDef, _ *ir.FieldDef) {
			td.Fields[0] = &ir.FieldDef{Name: "seq", TypeRef: ir.TypeRef{Name: "number"}, Required: true, Key: true, AutoGenerated: true}
		}, "the database generates PlaidItem.seq; give the table a UUID key, or a key each create sets"},
		{"the user model", func(td *ir.TypeDef, _ *ir.FieldDef) { td.User = &ir.UserTrait{} },
			"the identity stores read and write the user model's tables without the ORMs"},
		{"an engine type", func(td *ir.TypeDef, _ *ir.FieldDef) { td.Behaviors = []ir.BehaviorRef{{Name: "Workflow"}} },
			"PlaidItem composes behaviors, so the engine keeps its rows, and the engine does not encrypt a field"},
		{"a version graph", func(td *ir.TypeDef, _ *ir.FieldDef) { td.VersionGraph = &ir.VersionGraphConfig{} },
			"a version graph's runtimes do not encrypt a field"},
		{"a @jsonField type", func(td *ir.TypeDef, _ *ir.FieldDef) { td.JsonField = true },
			"Encrypted<T> marks a field of a table; PlaidItem is no table"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			errs := encryptedErrors(vaultSchema(tc.edit))
			if !slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, tc.want) }) {
				t.Fatalf("errors = %v, want one that says %q", errs, tc.want)
			}
		})
	}

	api := vaultSchema(nil)
	api.Kind = ir.SchemaKindAPI
	if errs := encryptedErrors(api); len(errs) != 1 || !strings.Contains(errs[0], "Encrypted<T> marks a stored field of a DB table, and vault-db is a schema of kind API") {
		t.Errorf("an API's field: errors = %v", errs)
	}
}

// TestASourceViewOfAnEncryptedFieldSaysSo: a @source view's field that
// reads an Encrypted<T> field must be @decrypted, since every response of
// the view would carry its plaintext, and @decrypted marks such a field
// alone (D85).
func TestASourceViewOfAnEncryptedFieldSaysSo(t *testing.T) {
	db := vaultSchema(nil)
	str := ir.TypeRef{Name: "string"}
	view := func(fields ...*ir.FieldDef) *ir.Schema {
		schema := ir.NewSchema("vault-api", ir.SchemaKindAPI)
		schema.Types["PlaidItemView"] = &ir.TypeDef{Name: "PlaidItemView", Role: ir.RoleEmbeddedStruct, Source: &ir.SourceRef{Target: "vault-db.PlaidItem"}, Fields: fields}
		return schema
	}
	run := func(schema *ir.Schema) []string {
		r := Run(schema, Input{ExternalTypes: map[string]*ir.TypeDef{"vault-db.PlaidItem": db.Types["PlaidItem"]}})
		return errorStrings(r)
	}
	has := func(errs []string, want string) bool {
		return slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, want) })
	}
	if errs := run(view(&ir.FieldDef{Name: "itemId", TypeRef: str, Required: true})); has(errs, "Encrypted") || has(errs, "decrypted") {
		t.Errorf("a view that leaves it out: %v", errs)
	}
	if errs := run(view(&ir.FieldDef{Name: "accessToken", TypeRef: str, Required: true})); !has(errs, "PlaidItemView.accessToken reads vault-db.PlaidItem.accessToken, which is Encrypted<T>: a response of PlaidItemView would carry its plaintext. Leave the field out of the view, or mark it @decrypted to send it") {
		t.Errorf("a view that reads it: %v", errs)
	}
	if errs := run(view(&ir.FieldDef{Name: "accessToken", TypeRef: str, Required: true, Decrypted: true})); has(errs, "Encrypted") || has(errs, "decrypted") {
		t.Errorf("a view that says so: %v", errs)
	}
	if errs := run(view(&ir.FieldDef{Name: "itemId", TypeRef: str, Required: true, Decrypted: true})); !has(errs, "PlaidItemView.itemId is @decrypted, which marks a field that reads an Encrypted<T> field of vault-db.PlaidItem, and it reads none") {
		t.Errorf("@decrypted on a plain field: %v", errs)
	}
	plain := ir.NewSchema("vault-api", ir.SchemaKindAPI)
	plain.Types["Note"] = &ir.TypeDef{Name: "Note", Role: ir.RoleEmbeddedStruct, Fields: []*ir.FieldDef{{Name: "body", TypeRef: str, Decrypted: true}}}
	if errs := run(plain); !has(errs, "Note.body: @decrypted marks a field of a @source view that reads an Encrypted<T> field, and Note is no @source view") {
		t.Errorf("@decrypted outside a view: %v", errs)
	}
}

// TestEncryptedFieldsStayOutOfQueues: a queue's message carries no
// Encrypted<T> field, and an @enqueueOnChange neither copies one into a
// message, nor compares one, nor tests what it equals, since its column
// holds a ciphertext the trigger cannot open; whether it is null it may
// test (D85, D80).
func TestEncryptedFieldsStayOutOfQueues(t *testing.T) {
	str := ir.TypeRef{Name: "string"}
	queue := func(fields ...*ir.FieldDef) *ir.TypeDef {
		return &ir.TypeDef{Name: "Linked", Role: ir.RoleEmbeddedStruct, Queue: &ir.QueueDef{}, Fields: fields}
	}
	t.Run("a message field", func(t *testing.T) {
		schema := vaultSchema(nil)
		schema.Types["Linked"] = queue(&ir.FieldDef{Name: "token", TypeRef: str, Required: true, EncryptedAtRest: true})
		want := "Linked.token: Encrypted<T> marks a field of a table the ORMs keep, and Linked is a @queue, whose workers read its message as it was enqueued"
		if errs := encryptedErrors(schema); !slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, want) }) {
			t.Fatalf("errors = %v, want one that says %q", errs, want)
		}
	})
	enqueue := func(def *ir.EnqueueOnChange) []string {
		schema := vaultSchema(func(td *ir.TypeDef, token *ir.FieldDef) {
			token.Required = false
			def.Queue = "Linked"
			if def.On == nil {
				def.On = []string{"insert", "update"}
			}
			td.EnqueueOnChange = []*ir.EnqueueOnChange{def}
		})
		schema.Types["Linked"] = queue(
			&ir.FieldDef{Name: "itemId", TypeRef: str, Required: true},
			&ir.FieldDef{Name: "token", TypeRef: str},
		)
		r := &Result{}
		checkEnqueueOnChange(schema, r)
		return errorStrings(r)
	}
	for _, tc := range []struct {
		name string
		def  *ir.EnqueueOnChange
		want string
	}{
		{"a mapped field", &ir.EnqueueOnChange{Message: map[string]string{"itemId": "itemId", "token": "accessToken"}},
			"message field token takes accessToken, an Encrypted<T> field, whose ciphertext is bound to PlaidItem's row and no worker opens"},
		{"a compared field", &ir.EnqueueOnChange{Fields: []string{"accessToken"}, Message: map[string]string{"itemId": "itemId"}},
			"fields names accessToken, an Encrypted<T> field, whose ciphertext every write and every key rotation changes"},
		{"a field it equals", &ir.EnqueueOnChange{When: []*ir.EnqueueCondition{{Field: "accessToken", Equals: "x"}}, Message: map[string]string{"itemId": "itemId"}},
			"when accessToken equals x: accessToken is an Encrypted<T> field, whose column holds a ciphertext no value equals"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if errs := enqueue(tc.def); !slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, tc.want) }) {
				t.Fatalf("errors = %v, want one that says %q", errs, tc.want)
			}
		})
	}
	t.Run("a null test", func(t *testing.T) {
		def := &ir.EnqueueOnChange{When: []*ir.EnqueueCondition{{Field: "accessToken", NotNull: true}}, Message: map[string]string{"itemId": "itemId"}}
		if errs := enqueue(def); len(errs) != 0 {
			t.Fatalf("errors = %v", errs)
		}
	})
}

// TestEncryptedFieldsAreNoFiles: D81's file types and Encrypted<T> meet
// nowhere. A FileUpload is a field of an API's input, where Encrypted<T>
// is refused, and a DB table's field is no FileUpload, so an encrypted
// upload fails the load in either schema; FileDownload marks a result, no
// field (D85, D81).
func TestEncryptedFieldsAreNoFiles(t *testing.T) {
	str := ir.TypeRef{Name: "string"}
	file := func(kind ir.SchemaKind) *ir.Schema {
		schema := vaultSchema(nil)
		schema.Kind = kind
		schema.Types["PlaidItem"].Fields = append(schema.Types["PlaidItem"].Fields,
			&ir.FieldDef{Name: "statement", TypeRef: str, Required: true, EncryptedAtRest: true, FileUpload: &ir.FileUploadConfig{MaxSize: 1 << 20}})
		return schema
	}
	for _, tc := range []struct {
		kind ir.SchemaKind
		want []string
	}{
		{ir.SchemaKindDB, []string{"PlaidItem.statement: FileUpload in a DB schema"}},
		{ir.SchemaKindAPI, []string{"PlaidItem.statement: Encrypted<T> marks a stored field of a DB table, and vault-db is a schema of kind API"}},
	} {
		schema := file(tc.kind)
		r := &Result{}
		checkEncryptedFields(schema, r)
		checkFileTransfers(schema, r)
		errs := errorStrings(r)
		for _, want := range tc.want {
			if !slices.ContainsFunc(errs, func(e string) bool { return strings.Contains(e, want) }) {
				t.Errorf("%s: errors = %v, want one that says %q", tc.kind, errs, want)
			}
		}
	}
}
