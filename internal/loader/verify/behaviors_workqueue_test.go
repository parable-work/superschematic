// agentsTable is the table name of doc, to edit.
func agentsTable(doc map[string]any, name string) map[string]any {
	return doc["types"].(map[string]any)[name].(map[string]any)
}

// agentsConfig is the config of the use of behavior on doc's table name,
// to edit.
func agentsConfig(doc map[string]any, name, behavior string) map[string]any {
	return use(agentsTable(doc, name), behavior)["config"].(map[string]any)
}

// writeAgents writes the edited schema as a JSON service.
func writeAgents(t *testing.T, edit func(doc map[string]any)) string {
	t.Helper()
	doc := agentsDB()
	if edit != nil {
		edit(doc)
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	return writeFiles(t, map[string]string{
		"schema.config.json":     `{"name": "agents-db", "kind": "DB", "outputs": {}}`,
		"src/agents.schema.json": string(data),
	})
}

// agentsCase is one edit of agentsDB and the one problem it is refused
// with.
type agentsCase struct {
	name string
	edit func(doc map[string]any)
	want string
}

// holdAgentsRefusals loads each case's schema and holds its error to want,
// with one problem of behavior's config.
func holdAgentsRefusals(t *testing.T, behavior string, cases []agentsCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			_, err := loader.LoadService(writeAgents(t, tc.edit))
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("LoadService = %v, want an error holding %q", err, tc.want)
			}
			if got := strings.Count(err.Error(), "behavior "+behavior+" config"); got != 1 {
				t.Errorf("LoadService = %v, want one problem of %s's config", err, behavior)
			}
		})
	}
}

// holdAgentsAccepted loads each edit's schema and holds it to load.
func holdAgentsAccepted(t *testing.T, cases map[string]func(doc map[string]any)) {
	t.Helper()
	for name, edit := range cases {
		t.Run("accepts "+name, func(t *testing.T) {
			if _, err := loader.LoadService(writeAgents(t, edit)); err != nil {
				t.Fatalf("LoadService = %v", err)
			}
		})
	}
}

// agentsWarnings loads an API over the edited agents-db whose behavior
// workers are workers, a JSON list, and returns its warnings of D104.
func agentsWarnings(t *testing.T, edit func(doc map[string]any), imports []string, workers string) []string {
	t.Helper()
	db, err := loader.LoadService(writeAgents(t, edit))
	if err != nil {
		t.Fatal(err)
	}
	names, _ := json.Marshal(imports)
	api := writeFiles(t, map[string]string{
		"schema.config.json": `{"name": "agents-api", "kind": "API", "dependencies": [{"name": "agents-db", "kind": "DB"}], "outputs": {}}`,
		"src/agents.schema.json": `{"imports": [{"package": "@schemas/agents-db", "types": ` + string(names) + `}],
		  "scalars": {"Identity.UUID": {"name": "Identity.UUID", "languagePrimitive": "string"}},
		  "workers": ` + workers + `}`,
	})
	var warnings []string
	if _, err := loader.LoadService(api, loader.WithDependencyLoader(func(name string) (*ir.Schema, error) {
		if name != db.Name {
			return nil, os.ErrNotExist
		}
		return db, nil
	}), loader.WithWarnings(func(d *verify.Diagnostic) {
		if strings.Contains(d.Msg, "(D104)") {
			warnings = append(warnings, d.Msg)
		}
	})); err != nil {
		t.Fatalf("LoadService: %v", err)
	}
	return warnings
}

// coreList reads the list name of the core's source at path, `pub const
// NAME: [&str; n] = [...]`, for a test that holds the build's to it.
func coreList(t *testing.T, path, name string) []string {
	t.Helper()
	data, err := os.ReadFile(filepath.Join(testpaths.RepoRoot(t), filepath.FromSlash(path)))
	if err != nil {
		t.Fatal(err)
	}
	match := regexp.MustCompile(`pub const ` + name + `: \[&str; \d+\] = \[([^\]]*)\];`).FindSubmatch(data)
	if match == nil {
		t.Fatalf("%s declares no %s", path, name)
	}
	var core []string
	for _, quoted := range regexp.MustCompile(`"([^"]*)"`).FindAllSubmatch(match[1], -1) {
		core = append(core, string(quoted[1]))
	}
	return core
}

// holdCoreList holds the build's list to the core's name at path (D104).
func holdCoreList(t *testing.T, path, name string, build []string) {
	t.Helper()
	if core := coreList(t, path, name); !slices.Equal(build, core) {
		t.Errorf("the build's %s = %v, the core's = %v (%s)", name, build, core, path)
	}
}
