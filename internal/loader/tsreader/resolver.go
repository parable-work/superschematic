// typeInfo is the resolver's output for one type expression: the IR type
// reference plus everything the type-level wrappers encoded.
type typeInfo struct {
	ref ir.TypeRef

	// nullable is set by Nullable<T>.
	nullable bool

	// nullableDepth is the list depth of the type Nullable<T> or T | null
	// was applied to; wrapArray reads it to refuse a nullable inner list.
	nullableDepth int

	// defaultValue is set by Default<T, V>.
	defaultValue *string

	// platformDefault is set by PlatformDefault<T>.
	platformDefault bool

	// validate holds the Validate<T, C> config keys (min, max,
	// uploadMaxBytes, minLength, maxLength, listMin, listMax, pattern).
	validate map[string]any

	// listBoundsDepth is the list depth of the type a Validate config with
	// listMin or listMax was applied to; wrapArray reads it to refuse bounds
	// on the inner lists of an array of arrays.
	listBoundsDepth int

	// Wrapper markers.
	autoGenerated bool
	relation      bool

	// relationOnDelete holds the Relation<T, { onDelete }> action when set
	// (CASCADE|RESTRICT|NO ACTION|SET NULL); empty means the generator
	// default.
	relationOnDelete string
	hasMany          bool
	manyToMany       bool
	jsonField        bool
	secret           bool
	queryParam       bool
	encrypted        bool

	// references is set by RefersTo<T, Target, C> (D61): the target and
	// the config's members as written.
	references *ir.ReferenceDef

	// search is set by SearchQuery<T> (D62).
	search bool

	// sortBy is set by SortBy<Item, Fields> (D60, amended): Fields' names,
	// non-nil even when the tuple is empty, which the loader refuses.
	// sortItem is Item's ref name, which the operation's result must list.
	sortBy   []string
	sortItem string

	// Classification of the base reference.
	isScalar    bool
	isEnum      bool
	isObject    bool
	isPrimitive bool

	// importPkg names the external (non-toolchain) package the reference was
	// declared in; empty for same-service and toolchain references.
	importPkg string

	// importedName is the declared name in the external package (the ref
	// name is service-qualified for cross-service references).
	importedName string

	// decl is the declaration node of the referenced named type.
	decl *astNode
}

// wrapperNames is the set of type-level wrapper aliases recognized from the
// @superschematic/* toolchain packages. Identity is checked by declaring package, not
// import path, so re-exports and renamed imports still resolve.
var wrapperNames = map[string]bool{
	"Default": true, "PlatformDefault": true, "Nullable": true, "Validate": true, "Secret": true,
	"Relation": true, "HasMany": true, "ManyToMany": true, "AutoGenerate": true,
	"JsonField": true, "QueryParam": true, "EncryptedField": true,
	"RefersTo": true, "SearchQuery": true, "SortBy": true,
}

// resolveTypeNode resolves a type expression into a typeInfo. It works
// syntactically over the written expression (so wrapper composition and
// Default literals stay readable) and drops to the checker for symbol
// identity, scalar brands, and enum values.
func (w *walker) resolveTypeNode(node *astNode) (*typeInfo, *SchemaError) {
	switch node.Kind {
	case kindParenthesizedType:
		return w.resolveTypeNode(node.AsParenthesizedTypeNode().Type)

	case kindTypeOperator:
		// readonly T[] -- the operator carries no schema meaning.
		return w.resolveTypeNode(node.AsTypeOperatorNode().Type)

	case kindArrayType:
		info, serr := w.resolveTypeNode(node.AsArrayTypeNode().ElementType)
		if serr != nil {
			return nil, serr
		}
		return wrapArray(node, info)

	case kindUnionType:
		return w.resolveUnionType(node)

	case kindStringKeyword:
		return &typeInfo{ref: ir.TypeRef{Name: "string"}, isPrimitive: true}, nil
	case kindNumberKeyword:
		return &typeInfo{ref: ir.TypeRef{Name: "number"}, isPrimitive: true}, nil
	case kindBooleanKeyword:
		return &typeInfo{ref: ir.TypeRef{Name: "boolean"}, isPrimitive: true}, nil
	case kindAnyKeyword, kindUnknownKeyword, kindObjectKeyword:
		return nil, errorAtNode(node, "untyped fields are not allowed in schemas; use a scalar, enum, or named type")

	case kindTypeLiteral:
		return nil, errorAtNode(node, "inline object types are not supported; declare a named exported type")

	case kindTypeReference:
		return w.resolveTypeReference(node)
	}

	return nil, errorAtNode(node, "unsupported type expression in schema")
}

// resolveUnionType handles the one union form the schema DSL allows at field
// level: T | null (the expansion of Nullable<T>).
func (w *walker) resolveUnionType(node *astNode) (*typeInfo, *SchemaError) {
	members := node.AsUnionTypeNode().Types.Nodes
	var nonNull []*astNode
	sawNull := false
	for _, m := range members {
		if m.Kind == kindLiteralType && m.AsLiteralTypeNode().Literal.Kind == kindNullKeyword {
			sawNull = true
			continue
		}
		nonNull = append(nonNull, m)
	}
	if !sawNull || len(nonNull) != 1 {
		return nil, errorAtNode(node, "union types are not supported at field level (except T | null); declare a named union or enum instead")
	}
	info, serr := w.resolveTypeNode(nonNull[0])
	if serr != nil {
		return nil, serr
	}
	info.markNullable()
	return info, nil
}

// markNullable records Nullable<T> (or T | null) and the list depth it was
// applied at.
func (info *typeInfo) markNullable() {
	info.nullable = true
	info.nullableDepth = info.ref.ArrayDepth()
}

// wrapArray applies one list level to info: T becomes T[] and T[] becomes
// T[][]. Nesting stops at two levels. The wrappers that only make sense on
// the whole field are refused on the inner lists of T[][]: an inner list is
// never null, and list bounds belong to the outer list.
func wrapArray(node *astNode, info *typeInfo) (*typeInfo, *SchemaError) {
	if !info.ref.IsArray {
		info.ref.IsArray = true
		return info, nil
	}
	switch {
	case info.ref.IsArrayOfArrays:
		return nil, errorAtNode(node, "arrays nest at most two levels (T[][]); declare a named object type for the inner list")
	case info.ref.IsMap:
		return nil, errorAtNode(node, "map values cannot be arrays of arrays; declare a named object type for the value")
	case info.nullable && info.nullableDepth == 1:
		return nil, errorAtNode(node, "the inner lists of an array of arrays cannot be null; write Nullable<T[][]> to make the field optional")
	case info.listBoundsDepth == 1:
		return nil, errorAtNode(node, "list bounds of an array of arrays apply to the outer list; write Validate<T[][], { listMin, listMax }>")
	}
	info.ref.IsArrayOfArrays = true
	return info, nil
}

// resolveTypeReference resolves a named type reference: a wrapper, a branded
// scalar, an enum, or an object type.
func (w *walker) resolveTypeReference(node *astNode) (*typeInfo, *SchemaError) {
	refNode := node.AsTypeReferenceNode()
	id, ok := w.identityOf(refNode.TypeName)
	if !ok {
		return nil, errorAtNode(node, "cannot resolve type %q", entityNameText(refNode.TypeName))
	}

	if id.name == "Record" && id.pkg == "" {
		return w.resolveRecordType(node)
	}
	if (id.name == "Array" || id.name == "ReadonlyArray") && id.pkg == "" {
		return w.resolveArrayReference(node, id.name)
	}

	if w.isAuthoring(id) && wrapperNames[id.name] {
		return w.resolveWrapper(node, id)
	}

	// Branded scalar: the resolved type carries a __brand string literal.
	t := w.checker.GetTypeFromTypeNode(node)
	if brand, ok := w.scalarBrand(t); ok {
		w.registerScalar(brand, t)
		return &typeInfo{ref: ir.TypeRef{Name: brand}, isScalar: true, decl: id.decl}, nil
	}

	sym := w.checker.GetSymbolAtLocation(entityRightmost(refNode.TypeName))
	if sym != nil {
		sym = w.checker.SkipAlias(sym)
	}

	info := &typeInfo{decl: id.decl}
	switch {
	case sym != nil && sym.Flags&symbolFlagsEnum != 0:
		info.isEnum = true
	case sym != nil && sym.Flags&(symbolFlagsClass|symbolFlagsTypeAlias|symbolFlagsInterface) != 0:
		info.isObject = true
	default:
		return nil, errorAtNode(node, "type %q is not a scalar, enum, or schema type", id.name)
	}

	declFile := getSourceFileOfNode(id.decl)
	local := declFile != nil && strings.HasPrefix(declFile.FileName(), w.servicePath+"/")
	if local {
		info.ref.Name = id.name
		return info, nil
	}
	if id.pkg == "" {
		return nil, errorAtNode(node, "type %q is declared outside the service and outside any named package", id.name)
	}
	if w.isAuthoring(id) {
		return nil, errorAtNode(node, "type %q from %s is not usable as a schema field type", id.name, w.reg.Naming().Specifier(id.pkg))
	}
	// Cross-service reference: keep the field type as the imported symbol name
	// and record the package separately. Imports carry the provenance; target
	// language generators can then alias the symbol normally instead of handling
	// service-qualified type names in every field mapper.
	info.importPkg = id.pkg
	info.importedName = id.name
	info.ref.Name = id.name
	if info.isEnum {
		w.recordExternalEnum(id)
	}
	return info, nil
}

// recordExternalEnum records a dependency's enum a local field uses, for
// the loader's checks of the field's defaults (verify.Input.ExternalEnums,
// which validateDefaultValues and loadCompositeDefaults read). Its
// members are read as walkEnum reads them, so a @title the reader refuses
// fails here too. The dependent's IR does not copy the enum: a UI labels
// its members from the dependency's own schema.
func (w *walker) recordExternalEnum(id symbolIdentity) {
	if id.decl == nil || id.decl.Kind != kindEnumDeclaration {
		return
	}
	if existing, exists := w.externalEnums[id.name]; exists {
		if existing.Owner != id.pkg {
			w.addErr(errorAtNode(
				id.decl,
				"external enum %q is declared by both %s and %s; dependency enum names must be unique",
				id.name,
				existing.Owner,
				id.pkg,
			))
		}
		return
	}
	enum := id.decl.AsEnumDeclaration()
	def := &ir.EnumDef{Name: id.name, Owner: id.pkg, Comment: leadingComment(id.decl)}
	for _, node := range enum.Members.Nodes {
		member := node.AsEnumMember()
		valueName := node.Name().Text()
		value := ir.EnumValueDef{Name: valueName}
		var err error
		if value.Title, value.Comment, err = memberTitle(node); err != nil {
			w.addErr(errorAtNode(node, "enum %s member %s: %v", id.name, valueName, err))
		}
		if member.Initializer != nil {
			if member.Initializer.Kind != kindStringLiteral {
				w.addErr(errorAtNode(
					node,
					"external enum %q from %s member %q must use a string literal initializer",
					id.name,
					id.pkg,
					valueName,
				))
				return
			}
			if serialized := member.Initializer.Text(); serialized != valueName {
				value.SerializedAs = serialized
			}
		}
		def.Values = append(def.Values, value)
	}
	w.externalEnums[id.name] = def
}

// resolveArrayReference resolves Array<T> and ReadonlyArray<T>, the
// generic spellings of T[].
func (w *walker) resolveArrayReference(node *astNode, name string) (*typeInfo, *SchemaError) {
	args := node.AsTypeReferenceNode().TypeArguments
	if args == nil || len(args.Nodes) != 1 {
		return nil, errorAtNode(node, "%s requires one element type", name)
	}
	info, serr := w.resolveTypeNode(args.Nodes[0])
	if serr != nil {
		return nil, serr
	}
	return wrapArray(node, info)
}

func (w *walker) resolveRecordType(node *astNode) (*typeInfo, *SchemaError) {
	args := node.AsTypeReferenceNode().TypeArguments
	if args == nil || len(args.Nodes) != 2 {
		return nil, errorAtNode(node, "Record requires string keys and one value type")
	}
	if args.Nodes[0].Kind != kindStringKeyword {
		return nil, errorAtNode(args.Nodes[0], "schema Record keys must be string")
	}

	info, serr := w.resolveTypeNode(args.Nodes[1])
	if serr != nil {
		return nil, serr
	}
	if info.ref.IsMap {
		return nil, errorAtNode(node, "nested Record types are not supported; declare a named value type")
	}
	if info.ref.IsArrayOfArrays {
		return nil, errorAtNode(node, "map values cannot be arrays of arrays; declare a named object type for the value")
	}
	info.ref.IsMap = true
	return info, nil
}

// resolveWrapper applies one @superschematic wrapper alias and recurses into its
// payload type argument.
func (w *walker) resolveWrapper(node *astNode, id symbolIdentity) (*typeInfo, *SchemaError) {
	args := node.AsTypeReferenceNode().TypeArguments
	if id.name == "SearchQuery" && (args == nil || len(args.Nodes) == 0) {
		// SearchQuery<T extends string = string>: a bare SearchQuery is text.
		return &typeInfo{ref: ir.TypeRef{Name: "string"}, isPrimitive: true, queryParam: true, nullable: true, search: true}, nil
	}
	if id.name == "SortBy" {
		// SortBy<Item, Fields>: args[0] is the item type, not the value's.
		var nodes []*astNode
		if args != nil {
			nodes = args.Nodes
		}
		return w.sortByFromTypeArgs(node, nodes)
	}
	if args == nil || len(args.Nodes) == 0 {
		return nil, errorAtNode(node, "%s requires a type argument", id.name)
	}

	info, serr := w.resolveTypeNode(args.Nodes[0])
	if serr != nil {
		return nil, serr
	}

	switch id.name {
	case "Nullable":
		info.markNullable()

	case "Default":
		if len(args.Nodes) != 2 {
			return nil, errorAtNode(node, "Default<T, V> requires the default value as its second type argument")
		}
		v, serr := w.defaultValueString(args.Nodes[1])
		if serr != nil {
			return nil, serr
		}
		info.defaultValue = &v

	case "PlatformDefault":
		if len(args.Nodes) != 1 {
			return nil, errorAtNode(node, "PlatformDefault<T> takes exactly one type argument")
		}
		if !info.isObject || info.ref.IsArray || info.ref.IsMap {
			return nil, errorAtNode(node, "PlatformDefault<T> requires a named object type")
		}
		info.platformDefault = true

	case "Validate":
		if len(args.Nodes) != 2 {
			return nil, errorAtNode(node, "Validate<T, C> requires a config object as its second type argument")
		}
		cfg, serr := w.validateConfigFromTypeNode(args.Nodes[1])
		if serr != nil {
			return nil, serr
		}
		info.validate = cfg
		_, hasListMin := cfg["listMin"]
		_, hasListMax := cfg["listMax"]
		if hasListMin || hasListMax {
			info.listBoundsDepth = info.ref.ArrayDepth()
		}

	case "Secret":
		info.secret = true
	case "AutoGenerate":
		info.autoGenerated = true
	case "Relation":
		info.relation = true
		if !info.isObject {
			return nil, errorAtNode(node, "Relation<T> requires a schema type argument")
		}
		// Optional 2nd type arg: Relation<T, { onDelete: ... }>. A 3rd arg is a
		// TS arity error (TS2558) that surfaces before the walk, so no Go arity
		// guard is needed here.
		if len(args.Nodes) == 2 {
			onDelete, serr := w.relationConfigFromTypeNode(args.Nodes[1])
			if serr != nil {
				return nil, serr
			}
			info.relationOnDelete = onDelete
		}
	case "HasMany":
		info.hasMany = true
		info.ref.IsArray = true
		if !info.isObject {
			return nil, errorAtNode(node, "HasMany<T> requires a schema type argument")
		}
	case "ManyToMany":
		info.manyToMany = true
		info.ref.IsArray = true
		if !info.isObject {
			return nil, errorAtNode(node, "ManyToMany<T> requires a schema type argument")
		}
	case "JsonField":
		info.jsonField = true
	case "QueryParam":
		info.queryParam = true
	case "EncryptedField":
		info.encrypted = true
	case "RefersTo":
		if info.references != nil {
			return nil, errorAtNode(node, "RefersTo is written once on a value; this one already refers to %s", info.references.Type)
		}
		ref, serr := w.referenceFromTypeArgs(node, args.Nodes)
		if serr != nil {
			return nil, serr
		}
		info.references = ref
	case "SearchQuery":
		info.queryParam = true
		info.search = true
		info.markNullable()
	}

	return info, nil
}

// sortByUsage is how SortBy is written, for its errors.
const sortByUsage = `SortBy<Item, Fields> needs the item type and a tuple of its field names: SortBy<OrderView, ["placedAt"]>`

// sortByFromTypeArgs reads SortBy<Item, Fields> (D60, amended): Item names
// an object type, the operation's item, and Fields is a tuple of string
// literals, the item's fields by their JSON names. The value is text, an
// optional query parameter; the loader holds the fields to the item.
func (w *walker) sortByFromTypeArgs(node *astNode, args []*astNode) (*typeInfo, *SchemaError) {
	if len(args) != 2 {
		return nil, errorAtNode(node, "%s", sortByUsage)
	}
	item, serr := w.resolveTypeNode(args[0])
	if serr != nil {
		return nil, serr
	}
	if !item.isObject || item.ref.IsArray || item.ref.IsMap || item.nullable {
		return nil, errorAtNode(args[0], "%s", sortByUsage)
	}
	w.recordReference(item)
	tuple := args[1]
	for tuple.Kind == kindTypeOperator || tuple.Kind == kindParenthesizedType {
		if tuple.Kind == kindTypeOperator {
			tuple = tuple.AsTypeOperatorNode().Type
		} else {
			tuple = tuple.AsParenthesizedTypeNode().Type
		}
	}
	if tuple.Kind != kindTupleType {
		return nil, errorAtNode(args[1], "%s", sortByUsage)
	}
	fields := []string{}
	for _, element := range tuple.Elements() {
		name, ok := stringLiteralType(element)
		if !ok || name == "" {
			return nil, errorAtNode(element, "SortBy's fields are string literals, each a field of %s", item.ref.Name)
		}
		fields = append(fields, name)
	}
	return &typeInfo{
		ref: ir.TypeRef{Name: "string"}, isPrimitive: true, queryParam: true, nullable: true,
		sortBy: fields, sortItem: item.ref.Name,
	}, nil
}

// referenceFromTypeArgs reads RefersTo<T, Target, C> (D61): Target names a
// schema type, an object type the loader holds the reference to, and C, when
// given, is an object type of string literals under options, value and label.
func (w *walker) referenceFromTypeArgs(node *astNode, args []*astNode) (*ir.ReferenceDef, *SchemaError) {
	if len(args) < 2 {
		return nil, errorAtNode(node, "RefersTo<T, Target> needs a schema type as Target")
	}
	target, serr := w.resolveTypeNode(args[1])
	if serr != nil {
		return nil, serr
	}
	if !target.isObject && !target.isEnum || target.ref.IsArray || target.ref.IsMap || target.nullable ||
		target.validate != nil || target.defaultValue != nil || target.references != nil {
		return nil, errorAtNode(args[1], "RefersTo<T, Target> needs a schema type as Target")
	}
	w.recordReference(target)
	ref := &ir.ReferenceDef{Type: target.ref.Name}
	if len(args) < 3 {
		return ref, nil
	}
	t := w.checker.GetTypeFromTypeNode(args[2])
	if t == nil {
		return nil, errorAtNode(args[2], "cannot resolve the RefersTo config")
	}
	for _, prop := range w.checker.GetPropertiesOfType(t) {
		v, ok := literalValue(w.checker.GetTypeOfSymbol(prop))
		text, isText := v.(string)
		if !ok || !isText || text == "" {
			return nil, errorAtNode(args[2], "RefersTo %s must be a non-empty string literal", prop.Name)
		}
		switch prop.Name {
		case "options":
			ref.Options = text
		case "value":
			ref.Value = text
		case "label":
			ref.Label = text
		default:
			return nil, errorAtNode(args[2], "unsupported RefersTo config key %q (options, value, label)", prop.Name)
		}
	}
	return ref, nil
}

// scalarBrand extracts the scalar identity from a branded type: the __brand
// property's string literal type names the scalar (e.g., "Identity.UUID").
func (w *walker) scalarBrand(t *checkerType) (string, bool) {
	if t == nil {
		return "", false
	}
	prop := w.checker.GetPropertyOfType(t, "__brand")
	if prop == nil {
		return "", false
	}
	bt := w.checker.GetTypeOfSymbol(prop)
	if bt == nil || bt.Flags()&typeFlagsStringLiteral == 0 {
		return "", false
	}
	brand, ok := bt.AsLiteralType().Value().(string)
	return brand, ok
}

// registerScalar records a ScalarDef the first time a brand is referenced.
// The walker only knows the brand identity and the host-language backing; the
// scalar registry owns the rich metadata (patterns, normalization, mappings),
// which the loader hydrates.
func (w *walker) registerScalar(brand string, t *checkerType) {
	if _, ok := w.schema.Scalars[brand]; ok {
		return
	}
	w.schema.Scalars[brand] = &ir.ScalarDef{
		Name:              brand,
		LanguagePrimitive: languagePrimitiveOf(t),
		TypeMappings:      w.scalarTypeMappings(brand),
	}
}

// scalarTypeMappings is what a brand records of its catalog row before the
// loader hydrates it: the core table's SQL type, and, from the registry's
// catalog, the json_schema type mapping when it says which JSON the scalar
// holds (object, array or any). A document written from the TypeScript form
// (format --to=json) then carries that mapping, so a reader that knows only
// the builtin catalog, as the engine does, holds an extension's JSON scalar
// to JSON and does not refuse it (D14, amended).
func (w *walker) scalarTypeMappings(brand string) map[string]string {
	mappings := scalarSQLTypeMapping(brand)
	row, ok := w.reg.Scalars().Scalar(brand)
	if !ok {
		return mappings
	}
	switch row.JSONSchemaType {
	case ir.JSONSchemaObjectType, ir.JSONSchemaArrayType, ir.JSONSchemaAnyType:
		if mappings == nil {
			mappings = make(map[string]string, 1)
		}
		mappings["json_schema"] = row.JSONSchemaType
	}
	return mappings
}

func scalarSQLTypeMapping(brand string) map[string]string {
	metadata, ok := scalars.ScalarMetadataByCanonical[brand]
	if !ok || metadata.SQLType == "" {
		return nil
	}
	return map[string]string{"sql": metadata.SQLType}
}

// languagePrimitiveOf determines what host-language primitive a branded type
// bottoms out on by inspecting the brand intersection's members.
func languagePrimitiveOf(t *checkerType) ir.LanguagePrimitive {
	if t == nil {
		return ir.LanguageObject
	}
	members := []*checkerType{t}
	if t.Flags()&typeFlagsIntersection != 0 {
		members = t.Types()
	}
	for _, m := range members {
		flags := m.Flags()
		switch {
		case flags&typeFlagsStringLike != 0:
			return ir.LanguageString
		case flags&typeFlagsNumberLike != 0:
			return ir.LanguageNumber
		case flags&typeFlagsBooleanLike != 0:
			return ir.LanguageBoolean
		}
	}
	return ir.LanguageObject
}

// defaultValueString renders the V in Default<T, V> as the IR default string.
// Literal type nodes are read syntactically; enum member references resolve
// through the checker to their serialized value.
func (w *walker) defaultValueString(node *astNode) (string, *SchemaError) {
	if node.Kind == kindLiteralType {
		lit := node.AsLiteralTypeNode().Literal
		switch lit.Kind {
		case kindStringLiteral:
			return lit.Text(), nil
		case kindNumericLiteral:
			return lit.Text(), nil
		case kindTrueKeyword:
			return "true", nil
		case kindFalseKeyword:
			return "false", nil
		case kindPrefixUnaryExpression:
			unary := lit.AsPrefixUnaryExpression()
			if unary.Operator == kindMinusToken && unary.Operand.Kind == kindNumericLiteral {
				return "-" + unary.Operand.Text(), nil
			}
		}
		return "", errorAtNode(node, "unsupported literal in Default<T, V>")
	}

	t := w.checker.GetTypeFromTypeNode(node)
	if v, ok := literalValue(t); ok {
		return formatLiteral(v), nil
	}
	return "", errorAtNode(node, "Default<T, V> requires a literal or enum member value")
}

// validateConfigFromTypeNode reads the C in Validate<T, C>: an inline object
// type whose properties are literal types.
func (w *walker) validateConfigFromTypeNode(node *astNode) (map[string]any, *SchemaError) {
	t := w.checker.GetTypeFromTypeNode(node)
	if t == nil {
		return nil, errorAtNode(node, "cannot resolve Validate config")
	}
	cfg := make(map[string]any)
	for _, prop := range w.checker.GetPropertiesOfType(t) {
		pt := w.checker.GetTypeOfSymbol(prop)
		v, ok := literalValue(pt)
		if !ok {
			return nil, errorAtNode(node, "Validate config values must be literals (key %q)", prop.Name)
		}
		switch prop.Name {
		case "uploadMaxBytes":
			uploadMaxBytes, valid := safeIntegerLiteral(v)
			if !valid {
				return nil, errorAtNode(node, "Validate uploadMaxBytes must be a finite JavaScript-safe integer literal")
			}
			cfg[prop.Name] = uploadMaxBytes
		case "minLength", "maxLength", "listMin", "listMax":
			// A length or item count is a whole number: the JSON and YAML
			// forms type these bounds as integers, so a fraction is refused
			// here rather than truncated.
			bound, valid := safeIntegerLiteral(v)
			if !valid {
				return nil, errorAtNode(node, "Validate %s must be a finite JavaScript-safe integer literal, got %s", prop.Name, formatLiteral(v))
			}
			cfg[prop.Name] = int(bound)
		case "min", "max", "pattern":
			cfg[prop.Name] = v
		default:
			return nil, errorAtNode(node, "unsupported Validate config key %q", prop.Name)
		}
	}
	return cfg, nil
}

// maxJavaScriptSafeInteger is Number.MAX_SAFE_INTEGER: the largest integer a
// TypeScript number literal carries exactly.
const maxJavaScriptSafeInteger = float64(1<<53 - 1)

// safeIntegerLiteral accepts a number literal that is a finite integer a
// TypeScript number represents exactly, and returns it as int64. Integer
// options read through it are refused, not truncated, when the author wrote
// a fraction.
func safeIntegerLiteral(value any) (int64, bool) {
	number, ok := value.(float64)
	if !ok || math.IsNaN(number) || math.IsInf(number, 0) ||
		math.Trunc(number) != number || math.Abs(number) > maxJavaScriptSafeInteger {
		return 0, false
	}
	return int64(number), true
}

// relationConfigFromTypeNode reads the Relation<T, { onDelete }> config object
// and returns the onDelete action ("" when unset). Modeled on
// validateConfigFromTypeNode. It guards unknown/typo keys here because keys are
// dropped after parsing, so this is the only place that can catch them (the DSL
// OnDeleteAction union also rejects a bad value at author time). The onDelete
// VALUE is validated by ir.Schema.Validate, which runs for every load format
// (TS, JSON, YAML) -- so no value check is duplicated here.
func (w *walker) relationConfigFromTypeNode(node *astNode) (string, *SchemaError) {
	t := w.checker.GetTypeFromTypeNode(node)
	if t == nil {
		return "", errorAtNode(node, "cannot resolve Relation config")
	}
	onDelete := ""
	for _, prop := range w.checker.GetPropertiesOfType(t) {
		pt := w.checker.GetTypeOfSymbol(prop)
		v, ok := literalValue(pt)
		if !ok {
			return "", errorAtNode(node, "Relation config values must be literals (key %q)", prop.Name)
		}
		switch prop.Name {
		case "onDelete":
			s, ok := v.(string)
			if !ok {
				return "", errorAtNode(node, "Relation onDelete must be a string literal")
			}
			onDelete = s
		default:
			return "", errorAtNode(node, "unsupported Relation config key %q", prop.Name)
		}
	}
	return onDelete, nil
}

// formatLiteral renders an evaluated literal as the IR default string.
func formatLiteral(v any) string {
	switch val := v.(type) {
	case string:
		return val
	case bool:
		if val {
			return "true"
		}
		return "false"
	case float64:
		return strconv.FormatFloat(val, 'f', -1, 64)
	case nil:
		return "null"
	}
	return ""
}

// entityNameText renders an entity name (Identifier or QualifiedName) as
// written, for messages.
func entityNameText(node *astNode) string {
	if node.Kind == kindQualifiedName {
		qn := node.AsQualifiedName()
		return entityNameText(qn.Left) + "." + qn.Right.Text()
	}
	return node.Text()
}

// entityRightmost returns the rightmost identifier of an entity name.
func entityRightmost(node *astNode) *astNode {
	if node.Kind == kindQualifiedName {
		return node.AsQualifiedName().Right
	}
	return node
}
