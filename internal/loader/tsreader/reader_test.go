// TestTypedSentinelEvaluatesToItsHandle: the static read ignores the type
// arguments of a typed sentinel, service<"API", Config>({...}), and keeps
// the kind an imported authDb handle gives.
func TestTypedSentinelEvaluatesToItsHandle(t *testing.T) {
	services := filepath.Join("testdata", "services")
	callee, err := os.MkdirTemp(services, "fixture-typed-callee-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(callee) })
	caller, err := os.MkdirTemp(services, "fixture-typed-caller-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(caller) })
	tsconfig := `{ "extends": "../../tsconfig.base.json", "include": ["schema.config.ts", "src/**/*.ts"] }`
	write := func(dir string, files map[string]string) {
		t.Helper()
		files["tsconfig.json"] = tsconfig
		files["package.json"] = fmt.Sprintf(`{ "name": "@schemas/%s", "private": true }`, filepath.Base(dir))
		for rel, content := range files {
			path := filepath.Join(dir, filepath.FromSlash(rel))
			if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
				t.Fatal(err)
			}
		}
	}
	write(callee, map[string]string{
		"schema.config.ts": `import { defineConfig, SchemaKind } from "@superschematic/schema-config";
export default defineConfig({ name: "typed-callee", kind: SchemaKind.API, outputs: {} });
`,
		"src/config.schema.ts": `import { envVars } from "@superschematic/schema-config";
@envVars
export abstract class TypedCalleeConfig {
  LOG_LEVEL: string;
}
`,
		"src/service.generated.ts": `// Code generated by superschematic sentinel. DO NOT EDIT.
import { service, SchemaKind } from "@superschematic/schema-config";
import type { TypedCalleeConfig } from "./config.schema";
export const TypedCallee = service<"API", TypedCalleeConfig>({ name: "typed-callee", kind: SchemaKind.API });
`,
		"src/index.ts": "export * from \"./service.generated\";\n",
	})
	write(caller, map[string]string{
		"schema.config.ts": fmt.Sprintf(`import { defineConfig, SchemaKind } from "@superschematic/schema-config";
import { FixtureDb } from "@schemas/fixture-db";
import { TypedCallee } from "@schemas/%s";
export default defineConfig({
  name: "typed-caller",
  kind: SchemaKind.API,
  authDb: FixtureDb,
  calls: [TypedCallee],
  outputs: {}
});
`, filepath.Base(callee)),
		"src/probe.schema.ts": "export enum Probe {\n  Ok = \"ok\"\n}\n",
	})

	schema, cfg, _, err := LoadServiceWithConfig(caller)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.AuthDB != "fixture-db" || cfg.AuthDBKind != ir.SchemaKindDB {
		t.Errorf("authDb = %q of kind %q, want fixture-db of kind DB", cfg.AuthDB, cfg.AuthDBKind)
	}
	want := []ir.ServiceRef{{Name: "typed-callee", Kind: ir.SchemaKindAPI}}
	if !reflect.DeepEqual(schema.Calls, want) {
		t.Errorf("IR calls = %+v, want %+v", schema.Calls, want)
	}
}

func TestMethodLevelAuthDecoratorSurvivesOperationSetDefault(t *testing.T) {
	schema, _, err := LoadService(filepath.Join("testdata", "services", "fixture-api"))
	if err != nil {
		t.Fatal(err)
	}

	var currentTenantAuth bool
	found := false
	for _, set := range schema.OperationSets {
		for _, op := range set.Operations {
			if op.Name == "currentTenant" {
				found = true
				currentTenantAuth = op.Auth
			}
		}
	}
	if !found {
		t.Fatal("currentTenant operation not found")
	}
	if !currentTenantAuth {
		t.Fatal("method-level @auth was not preserved")
	}
}

// TestLoadServiceRoundTrip ensures the produced IR survives a JSON round trip
// (marshal -> unmarshal -> marshal) without loss.
func TestLoadServiceRoundTrip(t *testing.T) {
	schema, _, err := LoadService(filepath.Join("testdata", "services", "fixture-db"))
	if err != nil {
		t.Fatal(err)
	}
	first, err := json.Marshal(schema)
	if err != nil {
		t.Fatal(err)
	}
	decoded := schema
	if err := json.Unmarshal(first, &decoded); err != nil {
		t.Fatal(err)
	}
	second, err := json.Marshal(decoded)
	if err != nil {
		t.Fatal(err)
	}
	if string(first) != string(second) {
		t.Error("IR does not round-trip through JSON")
	}
}

func TestProgramCacheMatchesPerServiceLoads(t *testing.T) {
	services := []string{
		"fixture-db",
		"fixture-api",
		"fixture-general",
		"fixture-authdb-import",
		"fixture-calls",
		"fixture-json-config",
		"fixture-traits",
		"fixture-docs",
		"fixture-mcp",
		"fixture-projection",
	}
	serviceDirs := make([]string, 0, len(services))
	for _, svc := range services {
		serviceDirs = append(serviceDirs, filepath.Join("testdata", "services", svc))
	}
	cache := NewProgramCache(serviceDirs)
	t.Cleanup(cache.Close)

	for _, svc := range services {
		t.Run(svc, func(t *testing.T) {
			serviceDir := filepath.Join("testdata", "services", svc)
			want, _, err := LoadService(serviceDir)
			if err != nil {
				t.Fatalf("LoadService(%s): %v", svc, err)
			}
			got, _, _, err := LoadServiceWithConfig(serviceDir, WithProgramCache(cache))
			if err != nil {
				t.Fatalf("LoadServiceWithConfig(%s, shared): %v", svc, err)
			}

			wantJSON, err := json.Marshal(want)
			if err != nil {
				t.Fatal(err)
			}
			gotJSON, err := json.Marshal(got)
			if err != nil {
				t.Fatal(err)
			}
			if string(gotJSON) != string(wantJSON) {
				t.Fatalf("shared program IR differs from per-service load")
			}
		})
	}
}

// TestProgramCacheSkipsUncoveredService: a service the shared program was
// not built over loads through its own program. From the shared one it
// classified no schema files and loaded with no types and no error.
func TestProgramCacheSkipsUncoveredService(t *testing.T) {
	cache := NewProgramCache([]string{filepath.Join("testdata", "services", "fixture-db")})
	t.Cleanup(cache.Close)

	serviceDir := filepath.Join("testdata", "services", "fixture-json-config")
	want, _, err := LoadService(serviceDir)
	if err != nil {
		t.Fatalf("LoadService: %v", err)
	}
	if len(want.Types) == 0 {
		t.Fatal("fixture-json-config loads no types on its own; the test needs some")
	}
	got, _, _, err := LoadServiceWithConfig(serviceDir, WithProgramCache(cache))
	if err != nil {
		t.Fatalf("LoadServiceWithConfig(shared): %v", err)
	}
	wantJSON, err := json.Marshal(want)
	if err != nil {
		t.Fatal(err)
	}
	gotJSON, err := json.Marshal(got)
	if err != nil {
		t.Fatal(err)
	}
	if string(gotJSON) != string(wantJSON) {
		t.Fatalf("uncovered service IR differs from per-service load")
	}
}
