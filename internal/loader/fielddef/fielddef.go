// Package fielddef builds the fields a behavior expansion adds to a table
// (access, agents, conversations, notifications): its key and its
// required and optional fields, the one copy the expanders share.
package fielddef

import (
	"github.com/parable-work/superschematic/internal/generator/codegen"
	ir "github.com/parable-work/superschematic/ir"
)

// uuidScalar is the scalar of an added table's key.
const uuidScalar = "Identity.UUID"

// Key is an added table's key: id, a UUID the database generates.
func Key() *ir.FieldDef {
	return &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: uuidScalar}, Required: true, Key: true, AutoGenerated: true}
}

// Required is a required field of type typeName.
func Required(name, typeName, comment string) *ir.FieldDef {
	return &ir.FieldDef{Name: name, Comment: comment, TypeRef: ir.TypeRef{Name: typeName}, Required: true}
}

// Optional is an optional field of type typeName.
func Optional(name, typeName, comment string) *ir.FieldDef {
	return &ir.FieldDef{Name: name, Comment: comment, TypeRef: ir.TypeRef{Name: typeName}}
}

// WithDefault sets fd's default to value and returns fd.
func WithDefault(fd *ir.FieldDef, value *string) *ir.FieldDef {
	fd.Default = value
	return fd
}

// Now is the default of a time the insert takes.
func Now() *string {
	s := codegen.DefaultNow
	return &s
}
