package loader

import (
	"strings"
	"testing"
)

// TestSeedRowValuesAreChecked: each value a table's @seedRows gives is
// held to its field, as a default is (#625): its type, its scalar's rules,
// and null only where the field is optional; a JSON field takes any JSON
// value. A table whose values fit loads.
func TestSeedRowValuesAreChecked(t *testing.T) {
	table := func(rows string) map[string]string {
		return map[string]string{
			"schema.config.json": `{"name": "tiers-db", "kind": "DB", "outputs": {}}`,
			"src/tier.schema.json": `{"name": "tiers-db", "kind": "DB",
"scalars": {
  "Generic.Int64": {"name": "Generic.Int64", "languagePrimitive": "number"},
  "Generic.JSON": {"name": "Generic.JSON", "languagePrimitive": "object"},
  "Identity.Slug": {"name": "Identity.Slug", "languagePrimitive": "string"},
  "Identity.UUID": {"name": "Identity.UUID", "languagePrimitive": "string"}
},
"types": {"Tier": {"name": "Tier", "role": "DBTable", "fields": [
  {"name": "id", "typeRef": {"name": "Identity.UUID"}, "required": true, "key": true, "autoGenerated": true},
  {"name": "slug", "typeRef": {"name": "Identity.Slug"}, "required": true, "unique": true},
  {"name": "seats", "typeRef": {"name": "Generic.Int64"}, "required": true},
  {"name": "listed", "typeRef": {"name": "boolean"}, "required": true},
  {"name": "features", "typeRef": {"name": "string", "isArray": true}},
  {"name": "limits", "typeRef": {"name": "Generic.JSON"}}
], "seedRows": {"rows": ` + rows + `}}}}`,
		}
	}
	if _, err := LoadService(writeService(t, table(`[
  {"slug": "free", "seats": 1, "listed": true, "features": ["inbox"], "limits": {"storageGb": 5}},
  {"slug": "team", "seats": 10, "listed": false, "features": null, "limits": [1, "two"]}
]`))); err != nil {
		t.Fatalf("a seed whose values fit: %v", err)
	}
	_, err := LoadService(writeService(t, table(`[
  {"slug": "Not a slug!", "seats": "ten", "listed": null, "features": [1]}
]`)))
	if err == nil {
		t.Fatal("LoadService took seed values that do not fit their fields")
	}
	for _, want := range []string{
		`Tier: @seedRows row 0's slug: slug does not match scalar "Identity.Slug"`,
		`Tier: @seedRows row 0's seats: seats must be a number`,
		`Tier: @seedRows row 0's listed: it is null, and the field is required`,
		`Tier: @seedRows row 0's features: features[0] must be a string`,
	} {
		if !strings.Contains(err.Error(), want) {
			t.Errorf("the error does not say %q:\n%v", want, err)
		}
	}
}
