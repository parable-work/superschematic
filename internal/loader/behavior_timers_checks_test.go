// ticketsDB is a JSON DB schema whose Ticket implements Timers beside its
// status Workflow (D103), for the checks' cases to edit.
func ticketsDB() map[string]any {
	field := func(name, typeName string, more map[string]any) map[string]any {
		f := map[string]any{"name": name, "typeRef": map[string]any{"name": typeName}}
		for k, v := range more {
			f[k] = v
		}
		return f
	}
	return map[string]any{
		"name": "tickets-db",
		"kind": "DB",
		"scalars": map[string]any{
			"Identity.UUID":     map[string]any{"name": "Identity.UUID", "languagePrimitive": "string"},
			"Temporal.DateTime": map[string]any{"name": "Temporal.DateTime", "languagePrimitive": "string"},
		},
		"types": map[string]any{
			"Ticket": map[string]any{
				"name": "Ticket",
				"role": "DBTable",
				"behaviors": []any{
					map[string]any{"name": "Timers", "implements": true, "config": map[string]any{"deadlines": map[string]any{
						"respond": map[string]any{"start": map[string]any{"create": true}, "afterMs": 1500, "then": map[string]any{"transition": "closed"}},
					}}},
					map[string]any{"name": "Workflow", "field": "status", "config": map[string]any{
						"states": []any{"open", "closed"}, "transitions": []any{map[string]any{"from": "open", "to": "closed"}},
					}},
				},
				"fields": []any{
					field("id", "Identity.UUID", map[string]any{"required": true, "key": true, "autoGenerated": true}),
					field("title", "string", map[string]any{"required": true}),
					field("visitAt", "Temporal.DateTime", nil),
				},
			},
		},
	}
}

// loadTickets writes the edited schema as a JSON service and loads it.
func loadTickets(t *testing.T, edit func(doc map[string]any, ticket map[string]any)) (*ir.Schema, error) {
	t.Helper()
	doc := ticketsDB()
	ticket := doc["types"].(map[string]any)["Ticket"].(map[string]any)
	if edit != nil {
		edit(doc, ticket)
	}
	data, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	dir := writeService(t, map[string]string{
		"schema.config.json":      `{"name": "tickets-db", "kind": "DB", "outputs": {}}`,
		"src/tickets.schema.json": string(data),
	})
	return LoadService(dir)
}

// timersConfig sets Ticket's Timers config.
func timersConfig(ticket map[string]any, config map[string]any) {
	ticket["behaviors"].([]any)[0].(map[string]any)["config"] = config
}

// TestTimersFromTheDataForms: a JSON table's `{ name: "Timers",
// implements: true }` loads as the TypeScript form's does, with its
// sub-table, its deadline queue and _version (D103).
func TestTimersFromTheDataForms(t *testing.T) {
	schema, err := loadTickets(t, nil)
	if err != nil {
		t.Fatal(err)
	}
	if ticket := schema.Types["Ticket"]; !ticket.Optimistic || len(ticket.ImplementsBehaviors()) != 1 || ticket.IsEngineType() {
		t.Errorf("Ticket = %+v", ticket)
	}
	if schema.Types["TicketTimersDeadlines"] == nil || schema.Types["TicketDeadline"] == nil {
		t.Errorf("types = %v, want the sub-table and the queue", keysOf(schema.Types))
	}
}

func keysOf[V any](m map[string]V) []string {
	var out []string
	for k := range m {
		out = append(out, k)
	}
	return out
}

// TestTimersChecks (D103): a table's use it implements is refused, in these
// words, when the core does not run its behavior, when the behavior names a
// value field, when the table lists it twice or beside @behavior, when the
// type is no table, when one use is both field and implements, when two
// uses sit under one member, when the table keeps sub-tables with a key of
// several fields, when a type the build adds is the schema's, and when
// Timers' config does not fit the table.
func TestTimersChecks(t *testing.T) {
	for _, tc := range []struct {
		name string
		edit func(doc, ticket map[string]any)
		want string
	}{
		{"a behavior the core does not run", func(_, ticket map[string]any) {
			ticket["behaviors"] = append(ticket["behaviors"].([]any), map[string]any{"name": "Comments", "implements": true})
		}, "type Ticket implements Comments, which the behaviors' core does not run: a table implements one of Reactions, Constants, StateRules, Approvals, Timers, Lease, Presence, Budget, Retries, Seats, Schedules (D103)"},
		{"a behavior with a value field", func(_, ticket map[string]any) {
			ticket["behaviors"] = append(ticket["behaviors"].([]any), map[string]any{"name": "Workflow", "implements": true, "config": map[string]any{"states": []any{"a"}, "transitions": []any{}}})
		}, "type Ticket implements Workflow, whose declaration names its value field status, so it is anchored on a field: write status: Workflow<{ ... }> (D103)"},
		{"twice", func(_, ticket map[string]any) {
			behaviors := ticket["behaviors"].([]any)
			ticket["behaviors"] = append(behaviors, behaviors[0])
		}, "type Ticket lists behavior Timers twice"},
		{"beside @behavior", func(_, ticket map[string]any) {
			ticket["behaviors"] = []any{map[string]any{"name": "Comments"}, ticket["behaviors"].([]any)[0]}
		}, "type Ticket composes behavior Comments on the type (@behavior) and behavior Timers by implements: a type composes its behaviors with @behavior (an engine type, D58) or on a table, by implements and field types (D103), never both"},
		{"not a table", func(_, ticket map[string]any) {
			ticket["jsonField"] = true
			ticket["behaviors"] = ticket["behaviors"].([]any)[:1]
		}, "type Ticket implements Timers, and a type implements a behavior on a DB table, which Ticket is not (D103)"},
		{"field and implements", func(_, ticket map[string]any) {
			ticket["behaviors"].([]any)[0].(map[string]any)["field"] = "status"
		}, "type Ticket: behavior Timers is anchored on field status and implemented by the type: a use is one or the other (D103)"},
		{"two uses under one member", func(_, ticket map[string]any) {
			ticket["behaviors"].([]any)[1].(map[string]any)["field"] = "timers"
		}, "type Ticket: implements Timers, whose operations sit under timers, and its field timers is a Workflow: rename the field (D103)"},
		{"a key of several fields", func(_, ticket map[string]any) {
			fields := ticket["fields"].([]any)
			fields[1].(map[string]any)["key"] = true
			fields[0].(map[string]any)["name"] = "a"
			fields[1].(map[string]any)["name"] = "b"
		}, "type Ticket: behavior Timers keeps rows of its own per row, and Ticket's key is 2 fields (a, b): a table whose behaviors keep sub-tables or arm deadlines has one @key field (D103)"},
		{"the sub-table's name taken", func(doc, _ map[string]any) {
			doc["types"].(map[string]any)["TicketTimersDeadlines"] = map[string]any{"name": "TicketTimersDeadlines", "role": "DBTable", "fields": []any{map[string]any{"name": "note", "typeRef": map[string]any{"name": "string"}}}}
		}, "type Ticket: behavior Timers adds the table TicketTimersDeadlines (ticket_timers_deadlines) for its deadlines, which the schema also declares; rename that type (D103)"},
		{"the queue's name taken", func(doc, _ map[string]any) {
			doc["types"].(map[string]any)["TicketDeadline"] = map[string]any{"name": "TicketDeadline", "role": "EmbeddedStruct", "queue": map[string]any{}, "fields": []any{map[string]any{"name": "note", "typeRef": map[string]any{"name": "string"}, "required": true}}}
		}, "type Ticket: its behaviors arm deadlines (Timers), whose queue the build adds as TicketDeadline (ticket_deadline_queue), which the schema also declares; rename that type (D103)"},
		{"reads the status of no Workflow", func(_, ticket map[string]any) {
			ticket["behaviors"] = []any{map[string]any{"name": "Timers", "implements": true, "config": map[string]any{"deadlines": map[string]any{
				"respond": map[string]any{"start": map[string]any{"enters": "open"}},
			}}}}
		}, "type Ticket: behavior Timers config: deadlines.respond.start.enters reads the status of Workflow, which the type does not list"},
		{"reads the status of several", func(_, ticket map[string]any) {
			ticket["behaviors"] = append(ticket["behaviors"].([]any), map[string]any{"name": "Workflow", "field": "payment", "config": map[string]any{
				"states": []any{"unpaid", "paid"}, "transitions": []any{map[string]any{"from": "unpaid", "to": "paid"}},
			}})
			timersConfig(ticket, map[string]any{"deadlines": map[string]any{
				"early": map[string]any{"start": map[string]any{"create": true}},
				"late":  map[string]any{"start": map[string]any{"create": true}, "then": map[string]any{"transition": "closed"}},
			}})
		}, "type Ticket: behavior Timers config: deadlines.late.then reads the status of Workflow, and the type has several (status, payment): status names the field whose Workflow it reads"},
		{"status names no Workflow", func(_, ticket map[string]any) {
			timersConfig(ticket, map[string]any{"status": "phase", "deadlines": map[string]any{"respond": map[string]any{"start": map[string]any{"create": true}}}})
		}, `type Ticket: behavior Timers config: status "phase" is not a Workflow of the type (its Workflows: status)`},
		{"a field start of no field", func(_, ticket map[string]any) {
			timersConfig(ticket, map[string]any{"deadlines": map[string]any{"remind": map[string]any{"start": map[string]any{"field": "when"}}}})
		}, `type Ticket: behavior Timers config: deadlines.remind.start.field "when" is not a field of Ticket (its fields: title, visitAt)`},
		{"a field start of no date-time", func(_, ticket map[string]any) {
			timersConfig(ticket, map[string]any{"deadlines": map[string]any{"remind": map[string]any{"start": map[string]any{"field": "title"}}}})
		}, `type Ticket: behavior Timers config: deadlines.remind.start.field "title" is not a date-time field of Ticket: a deadline starts from the time a value holds`},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := loadTickets(t, tc.edit)
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("LoadService = %v, want an error holding %q", err, tc.want)
			}
		})
	}
}
