// One search index per environment (#740): the environment's index a
// search database holds (outputs.sql.search.environmentIndex), and the
// sequence each source database's copies of its index rows are versioned
// by (outputs.sql.search.environment).

// ownerOf is the schema file the added environment index is said to be
// of: the first of the schema's types that names one.
func ownerOf(schema *ir.Schema) string {
	names := make([]string, 0, len(schema.Types))
	for name := range schema.Types {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		if td := schema.Types[name]; td != nil && td.Owner != "" {
			return td.Owner
		}
	}
	return ""
}

// sequencePiece is the raw SQL that makes ir.SearchEnvironmentSequence in
// a source database (#740), whose nextval versions each copy of one of
// its index rows into the environment's index. It runs again over what it
// made; its down drops the sequence.
func sequencePiece() ir.RawSQLDef {
	return ir.RawSQLDef{
		ID:       ir.SearchEnvironmentPiece,
		Up:       "CREATE SEQUENCE IF NOT EXISTS " + ir.SearchEnvironmentSequence + ";",
		Down:     "DROP SEQUENCE IF EXISTS " + ir.SearchEnvironmentSequence + ";",
		After:    ir.RawSQLAfterTables,
		Dialects: []string{"postgres"},
	}
}

// environmentTable is the environment's search index (#740): a database's
// index row and where it came from, unique on its database, table, key
// and object; its words, a GIN index over ir.SearchDocumentIn; its copied
// audience and its grants' reach, GIN indexes over the arrays; and its
// scope. With fold its words are in ir.SearchFoldedConfig, and with piece
// it holds the raw SQL that makes that configuration.
func environmentTable(owner string, fold, piece bool) *ir.TypeDef {
	config := ir.SearchTextConfig
	if fold {
		config = ir.SearchFoldedConfig
	}
	td := &ir.TypeDef{
		Name:        ir.EnvironmentSearchIndexTypeName,
		Owner:       owner,
		Comment:     "The search index of the environment's databases (#740): a copy of each source database's index rows, with the database, table, key and object each is of, its audience, its grants' reach and its version.",
		Role:        ir.RoleDBTable,
		Origin:      ir.OriginSearch,
		SearchIndex: true,
		SearchFolds: fold,
		Fields: []*ir.FieldDef{
			{Name: ir.SearchIDField, TypeRef: ir.TypeRef{Name: uuidScalar}, Required: true, Key: true, AutoGenerated: true},
			{Name: ir.EnvironmentSearchDatabaseField, Description: "The source database, by its name in the stack.", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: ir.SearchSourceTableField, Description: "The record's table, by its type's name.", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: ir.SearchSourceKeyField, Description: "The record's key as its database writes it as text.", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: ir.EnvironmentSearchObjectField, Description: "What the row indexes: row, the record with its conversation and files.", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: text(ir.EnvironmentSearchObjectRow)},
			{Name: ir.SearchTitleField, Description: "The record's title.", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: text("")},
			{Name: ir.SearchBodyField, Description: "Its body fields' text, joined.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchCommentsField, Description: "The text of its conversation's messages.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchFilesField, Description: "Its files' extracted text.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchScopeField, Description: "The value of its scope field as text; null for none.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchAudienceField, Description: "Its effective audience, as its database's index row holds it: null for everyone, empty for no one (D156).", TypeRef: ir.TypeRef{Name: uuidScalar, IsArray: true}},
			{Name: ir.SearchAgentsField, Description: "Its effective agent access (D156).", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: text(ir.AgentsFollowRole)},
			{Name: ir.EnvironmentSearchReachField, Description: "What its database's grants reach it by: <grant> on a grant's target, <grant>:<Type>:<path> on a row a path of its role reaches.", TypeRef: ir.TypeRef{Name: "string", IsArray: true}},
			{Name: ir.SearchTextHashField, Description: "The SHA-256 of its text.", TypeRef: ir.TypeRef{Name: sha256Scalar}},
			{Name: ir.SearchEmbeddingField, Description: "Its embedding, as its database's index row holds it.", TypeRef: ir.TypeRef{Name: floatScalar, IsArray: true}},
			{Name: ir.SearchEmbeddingModelField, Description: "The model its embedding is from.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.EnvironmentSearchVersionField, Description: "The version of the copy: its database's sequence, read with the row.", TypeRef: ir.TypeRef{Name: int64Scalar}, Required: true},
			{Name: ir.SearchIndexedAtField, Description: "When the copy was written.", TypeRef: ir.TypeRef{Name: dateTimeScalar}, Required: true, Default: text(codegen.DefaultNow)},
		},
		Indexes: []ir.IndexDef{
			{Keys: []string{ir.EnvironmentSearchDatabaseField, ir.SearchSourceTableField, ir.SearchSourceKeyField, ir.EnvironmentSearchObjectField}, Unique: true, Name: "source", Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchTitleField, ir.SearchBodyField, ir.SearchCommentsField, ir.SearchFilesField}, Name: "words", Method: ir.IndexMethodGIN, Expression: ir.SearchDocumentIn(config, ""), Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchAudienceField}, Name: "audience", Method: ir.IndexMethodGIN, Origin: ir.OriginSearch},
			{Keys: []string{ir.EnvironmentSearchReachField}, Name: "reach", Method: ir.IndexMethodGIN, Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchScopeField}, Name: "scope", Origin: ir.OriginSearch},
		},
	}
	for _, fd := range td.Fields {
		fd.Origin = ir.OriginSearch
	}
	if piece {
		td.RawSQL = []ir.RawSQLDef{unaccentPiece()}
	}
	return td
}
