// Package search expands a DB schema's @searchable declarations (D155)
// into ordinary types: the database's one search index table, which holds
// a row per record of every @searchable table, and the fields of the
// queues the declarations name, when they declare none. The sql and types
// generators emit the index as any table's, with no repository
// (ir.TypeDef.SearchIndex), and sqlgen adds the triggers that keep its
// access columns and enqueue a record's indexing.
//
// It runs before the verification pass, so the pass reads the added type
// and fields as the schema's own. Every type and field it adds carries
// ir.OriginSearch, so the schema writer can skip it and write the
// declaration instead.
package search

import (
	"slices"

	"github.com/parable-work/superschematic/internal/generator/codegen"
	ir "github.com/parable-work/superschematic/ir"
)

// Scalars the added fields use.
const (
	uuidScalar     = "Identity.UUID"
	dateTimeScalar = "Temporal.DateTime"
	floatScalar    = "Generic.Float64"
	sha256Scalar   = "Crypto.SHA256"
)

// Expand adds the search index to a schema with a @searchable table when
// it has none yet, and fills each queue the declarations name that
// declares no fields. With fold (outputs.sql.search.foldDiacritics, #740)
// the index folds diacritics: its words are in ir.SearchFoldedConfig,
// which a piece of its raw SQL makes on Postgres. It returns the scalar
// names the added fields use, so the caller can hydrate any the schema
// did not already reference.
func Expand(schema *ir.Schema, fold bool) []string {
	tables := schema.SearchableTables()
	if len(tables) == 0 {
		return nil
	}
	if schema.Types[ir.SearchIndexTypeName] == nil {
		schema.Types[ir.SearchIndexTypeName] = indexTable(tables[0].Owner, fold)
	}
	for _, td := range tables {
		fill(schema, td.Searchable.Queue)
	}
	scalars := []string{uuidScalar, dateTimeScalar, floatScalar, sha256Scalar}
	for _, name := range scalars {
		if schema.Scalars[name] == nil {
			schema.Scalars[name] = &ir.ScalarDef{Name: name}
		}
	}
	return scalars
}

// fill gives the queue class named queue the indexing message's fields
// when it is a @queue class of the schema that declares none.
func fill(schema *ir.Schema, queue string) {
	td := schema.Types[queue]
	if queue == "" || td == nil || td.Queue == nil || len(td.Fields) > 0 {
		return
	}
	td.Fields = []*ir.FieldDef{
		{Name: "sourceTable", Description: "The table of the row to index, by its type's name.", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Origin: ir.OriginSearch},
		{Name: "sourceKey", Description: "The row's key as the database writes it as text.", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Origin: ir.OriginSearch},
	}
	// A row keeps one ready message, however many writes it takes before a
	// worker claims it, and one claim at a time, so two workers never
	// rebuild one index row at once (D80's key).
	q := td.Queue
	if q.Key == "" && len(q.Keys) == 0 {
		q.Keys = slices.Clone(ir.SearchIndexingFields)
		if q.OnDuplicate == "" {
			q.OnDuplicate = ir.QueueOnDuplicateSkip
		}
		q.Serialize = true
	}
}

func text(value string) *string { return &value }

// indexTable is the search index (D155): one row per record, unique on
// its table and key; its words, a GIN index over ir.SearchDocumentIn; its
// copied audience, a GIN index over the array; and its scope. One that
// folds holds the raw SQL of its configuration (#740).
func indexTable(owner string, fold bool) *ir.TypeDef {
	config := ir.SearchTextConfig
	if fold {
		config = ir.SearchFoldedConfig
	}
	td := &ir.TypeDef{
		Name:        ir.SearchIndexTypeName,
		Owner:       owner,
		Comment:     "The search index of the database's @searchable tables (D155): one row per record, its text, an optional embedding, and the columns its audience check reads.",
		Role:        ir.RoleDBTable,
		Origin:      ir.OriginSearch,
		SearchIndex: true,
		Fields: []*ir.FieldDef{
			{Name: ir.SearchIDField, TypeRef: ir.TypeRef{Name: uuidScalar}, Required: true, Key: true, AutoGenerated: true},
			{Name: ir.SearchSourceTableField, Description: "The record's table, by its type's name.", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: ir.SearchSourceKeyField, Description: "The record's key as the database writes it as text.", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: ir.SearchTitleField, Description: "The record's title.", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: text("")},
			{Name: ir.SearchBodyField, Description: "Its body fields' text, joined.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchCommentsField, Description: "The text of its conversation's messages.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchFilesField, Description: "Its files' extracted text.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchScopeField, Description: "The value of its scope field as text; null for none.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchAudienceField, Description: "Its effective audience, copied by its table's trigger: null for everyone (D156).", TypeRef: ir.TypeRef{Name: uuidScalar, IsArray: true}},
			{Name: ir.SearchAgentsField, Description: "Its effective agent access, copied by its table's trigger (D156).", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Default: text(ir.AgentsFollowRole)},
			{Name: ir.SearchTextHashField, Description: "The SHA-256 of the text its embedding is of; null until embedded.", TypeRef: ir.TypeRef{Name: sha256Scalar}},
			{Name: ir.SearchEmbeddingField, Description: "Its embedding, of unit length; null until embedded, or with embeddings off.", TypeRef: ir.TypeRef{Name: floatScalar, IsArray: true}},
			{Name: ir.SearchEmbeddingModelField, Description: "The model its embedding is from.", TypeRef: ir.TypeRef{Name: "string"}},
			{Name: ir.SearchIndexedAtField, Description: "When its text was last indexed.", TypeRef: ir.TypeRef{Name: dateTimeScalar}, Required: true, Default: text(codegen.DefaultNow)},
		},
		Indexes: []ir.IndexDef{
			{Keys: []string{ir.SearchSourceTableField, ir.SearchSourceKeyField}, Unique: true, Name: "source", Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchTitleField, ir.SearchBodyField, ir.SearchCommentsField, ir.SearchFilesField}, Name: "words", Method: ir.IndexMethodGIN, Expression: ir.SearchDocumentIn(config, ""), Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchAudienceField}, Name: "audience", Method: ir.IndexMethodGIN, Origin: ir.OriginSearch},
			{Keys: []string{ir.SearchScopeField}, Name: "scope", Origin: ir.OriginSearch},
		},
	}
	for _, fd := range td.Fields {
		fd.Origin = ir.OriginSearch
	}
	if fold {
		td.SearchFolds = true
		td.RawSQL = []ir.RawSQLDef{unaccentPiece()}
	}
	return td
}

// unaccentPiece is the raw SQL that makes ir.SearchFoldedConfig on
// Postgres (#740), after the tables and before the index over it: the
// unaccent extension where the database lacks it, in
// ir.SearchExtensionSchema, as the engine's index makes it (D58); then
// the configuration in the current schema unless it is there, a copy of
// simple whose words go through unaccent first. Each statement runs again
// over what it made. Its down drops the configuration, once the index
// over it is gone; the extension may serve others and stays.
func unaccentPiece() ir.RawSQLDef {
	up := `DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_extension WHERE extname = 'unaccent') THEN
    CREATE SCHEMA IF NOT EXISTS ` + ir.SearchExtensionSchema + `;
    CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA ` + ir.SearchExtensionSchema + `;
  END IF;
END $$;
DO $$
DECLARE
  dictionary text;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_catalog.pg_ts_config WHERE cfgname = '` + ir.SearchFoldedConfig + `' AND cfgnamespace = pg_catalog.current_schema()::regnamespace) THEN
    SELECT pg_catalog.quote_ident(n.nspname) || '.unaccent' INTO dictionary
      FROM pg_catalog.pg_extension AS e JOIN pg_catalog.pg_namespace AS n ON n.oid = e.extnamespace
      WHERE e.extname = 'unaccent';
    CREATE TEXT SEARCH CONFIGURATION ` + ir.SearchFoldedConfig + ` (COPY = pg_catalog.simple);
    EXECUTE pg_catalog.format('ALTER TEXT SEARCH CONFIGURATION ` + ir.SearchFoldedConfig + ` ALTER MAPPING FOR word, hword, hword_part, numword, numhword, hword_numpart WITH %s, pg_catalog.simple', dictionary);
  END IF;
END $$;`
	return ir.RawSQLDef{
		ID:       ir.SearchUnaccentPiece,
		Up:       up,
		Down:     "DROP TEXT SEARCH CONFIGURATION IF EXISTS " + ir.SearchFoldedConfig + ";",
		After:    ir.RawSQLAfterTables,
		Dialects: []string{"postgres"},
	}
}
