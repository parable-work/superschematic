// writtenSource writes schema in the format into a temp directory and
// returns every written file's content, concatenated.
func writtenSource(t *testing.T, schema *ir.Schema, format Format) string {
	t.Helper()
	dir := t.TempDir()
	if _, err := WriteService(schema, format, dir); err != nil {
		t.Fatalf("WriteService(%s): %v", format, err)
	}
	var source strings.Builder
	err := filepath.WalkDir(dir, func(path string, d os.DirEntry, err error) error {
		if err == nil && !d.IsDir() {
			data, readErr := os.ReadFile(path)
			if readErr != nil {
				return readErr
			}
			source.Write(data)
		}
		return err
	})
	if err != nil {
		t.Fatal(err)
	}
	return source.String()
}

// TestTSWriterRoundTripsUserTraits: the corpus skips the TS leg of a
// TS-native fixture, so this writes fixture-users-db back to TypeScript
// and reloads it. The traits lead the implements clause, after the base
// class, and import from @superschematic/db.
func TestTSWriterRoundTripsUserTraits(t *testing.T) {
	schema, err := loader.LoadService(tsFixtures + "/fixture-users-db")
	if err != nil {
		t.Fatalf("loading fixture: %v", err)
	}
	want := normalizeIR(t, schema)
	if got := normalizeIR(t, writeAndReload(t, schema, FormatTS)); got != want {
		t.Errorf("IR mismatch after TS -> TS round trip\nwant:\n%s\ngot:\n%s", want, got)
	}
	source := writtenSource(t, schema, FormatTS)
	for _, want := range []string{
		`import { AutoGenerate, Relation, User, UserRole, key, unique } from "@superschematic/db";`,
		`export abstract class Account extends Auditable implements User<{ login: "email"; name: "displayName" }> {`,
		`export abstract class Role extends Auditable implements UserRole {`,
		`export abstract class Note extends Auditable {`,
	} {
		if !strings.Contains(source, want) {
			t.Errorf("written TypeScript lacks %s:\n%s", want, source)
		}
	}
}

// TestTSWriterAliasesUserTraits: tables named User and UserRole take the
// traits of those names, so the written file imports the traits under an
// alias, which the reader knows by its import.
func TestTSWriterAliasesUserTraits(t *testing.T) {
	schema, err := loader.LoadService(dataFixtures + "/fixture-user-handles-json")
	if err != nil {
		t.Fatalf("loading fixture: %v", err)
	}
	source := writtenSource(t, schema, FormatTS)
	for _, want := range []string{
		`import { AutoGenerate, User as UserTrait, UserRole as UserRoleTrait, key, unique } from "@superschematic/db";`,
		`export abstract class User implements UserTrait<{ login: "handle" }> {`,
		`export abstract class UserRole implements UserRoleTrait {`,
	} {
		if !strings.Contains(source, want) {
			t.Errorf("written TypeScript lacks %s:\n%s", want, source)
		}
	}
}

// TestWritersSkipIdentityTables: what the loader adds for the user model
// (Origin ir.OriginIdentity) is loader output. Every format writes the
// traits and leaves the added tables, fields and indexes out, and reading
// the file back gives the IR without them, which the loader's own
// expansion then adds again.
func TestWritersSkipIdentityTables(t *testing.T) {
	schema, err := loader.LoadService(tsFixtures + "/fixture-users-db")
	if err != nil {
		t.Fatalf("loading fixture: %v", err)
	}
	want := normalizeIR(t, schema)

	expanded := cloneSchema(t, schema)
	expanded.Types["IdentityProbe"] = &ir.TypeDef{
		Name: "IdentityProbe", Owner: "src/account.schema.ts", Role: ir.RoleDBTable, Origin: ir.OriginIdentity,
		Fields: []*ir.FieldDef{
			{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true, Origin: ir.OriginIdentity},
			{Name: "probeTokenHash", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true, Origin: ir.OriginIdentity},
		},
	}
	account := expanded.Types["Account"]
	account.Fields = append(account.Fields, &ir.FieldDef{Name: "probeField", TypeRef: ir.TypeRef{Name: "string"}, Origin: ir.OriginIdentity})
	account.Indexes = append(account.Indexes, ir.IndexDef{Keys: []string{"probeField"}, Name: "probe_index", Origin: ir.OriginIdentity})

	for _, format := range []Format{FormatTS, FormatJSON, FormatYAML} {
		t.Run(string(format), func(t *testing.T) {
			source := writtenSource(t, expanded, format)
			for _, added := range []string{"IdentityProbe", "probeTokenHash", "probeField", "probe_index"} {
				if strings.Contains(source, added) {
					t.Errorf("written %s carries the loader's %s:\n%s", format, added, source)
				}
			}
			if !strings.Contains(source, "email") {
				t.Errorf("written %s lost the User table:\n%s", format, source)
			}
			if got := normalizeIR(t, writeAndReload(t, expanded, format)); got != want {
				t.Errorf("IR mismatch after writing %s\nwant:\n%s\ngot:\n%s", format, want, got)
			}
		})
	}
}

// cloneSchema deep-copies a schema through its JSON form.
func cloneSchema(t *testing.T, schema *ir.Schema) *ir.Schema {
	t.Helper()
	data, err := json.Marshal(schema)
	if err != nil {
		t.Fatal(err)
	}
	var clone ir.Schema
	if err := json.Unmarshal(data, &clone); err != nil {
		t.Fatal(err)
	}
	return &clone
}
