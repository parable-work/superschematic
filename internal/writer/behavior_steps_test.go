// TestStepsRoundTrip (D104's step 4): a table that implements Rollups over
// the rows a HasMany lists and one that implements Dependencies, each
// beside a Workflow field, are written in every format as their uses,
// `implements Rollups<Batch, { ... }>` and `implements Dependencies<Step,
// { ... }>` in TypeScript and `{ name, implements: true, config }` in the
// data forms, without the blockers' sub-table the loader adds, and read back
// to the same IR; the API that serves their behavior operations reads back
// over its database to the same expanded IR, with neither the operations
// nor the types the loader adds in its written form.
func TestStepsRoundTrip(t *testing.T) {
	schema, err := loader.LoadService(tsFixtures + "/fixture-steps-db")
	if err != nil {
		t.Fatalf("loading fixture: %v", err)
	}
	schema.Description = ""
	want := normalizeIR(t, schema)
	contains := map[Format][]string{
		FormatTS: {
			`implements Rollups<Batch, {`,
			`function: "all"`,
			`gatedStates: ["done"]`,
			`implements Dependencies<Step, {`,
			`gatedStates: ["doing", "done"]`,
			`HasMany<Step>`,
		},
		FormatJSON: {`"implements": true`, `"name": "Rollups"`, `"name": "Dependencies"`, `"link": "batch"`},
		FormatYAML: {"implements: true", "name: Rollups", "name: Dependencies", "link: batch"},
	}
	for _, format := range []Format{FormatTS, FormatJSON, FormatYAML} {
		t.Run(string(format), func(t *testing.T) {
			source := writtenSource(t, schema, format)
			for _, want := range contains[format] {
				if !strings.Contains(source, want) {
					t.Errorf("written %s lacks %q:\n%s", format, want, source)
				}
			}
			for _, added := range []string{"StepDependenciesBlockers", "blockerKey", "behaviorTable", "optimistic", "@behavior"} {
				if strings.Contains(source, added) {
					t.Errorf("written %s carries the loader's %s:\n%s", format, added, source)
				}
			}
			if got := normalizeIR(t, writeAndReload(t, schema, format)); got != want {
				t.Errorf("IR mismatch after the %s round trip\nwant:\n%s\ngot:\n%s", format, want, got)
			}
		})
	}

	db := schema
	api, err := loader.LoadService(tsFixtures+"/fixture-steps-api", loader.WithWarnings(func(*verify.Diagnostic) {}))
	if err != nil {
		t.Fatalf("loading fixture: %v", err)
	}
	wantAPI := normalizeIR(t, api)
	for _, format := range []Format{FormatTS, FormatJSON, FormatYAML} {
		t.Run("api "+string(format), func(t *testing.T) {
			dir := t.TempDir()
			if _, err := WriteService(api, format, dir); err != nil {
				t.Fatalf("WriteService: %v", err)
			}
			cfg := fmt.Sprintf(`{"name": %q, "kind": "API", "dependencies": [{"name": "fixture-steps-db", "kind": "DB"}], "outputs": {}}`+"\n", api.Name)
			if err := os.WriteFile(filepath.Join(dir, "schema.config.json"), []byte(cfg), 0o644); err != nil {
				t.Fatal(err)
			}
			if format == FormatTS {
				writeTSProject(t, dir, api)
			}
			source := writtenSource(t, api, format)
			for _, added := range []string{"dependenciesAddBlocker", "statusTransition", "StepDependenciesAddBlockerInput", "\"origin\""} {
				if strings.Contains(source, added) {
					t.Errorf("written %s carries the loader's %s:\n%s", format, added, source)
				}
			}
			reloaded, err := loader.LoadService(dir, loader.WithWarnings(func(*verify.Diagnostic) {}), loader.WithDependencyLoader(func(name string) (*ir.Schema, error) {
				if name != db.Name {
					return nil, fmt.Errorf("no service %s", name)
				}
				return db, nil
			}))
			if err != nil {
				dumpService(t, dir)
				t.Fatalf("reloading %s output: %v", format, err)
			}
			if got := normalizeIR(t, reloaded); got != wantAPI {
				t.Errorf("IR mismatch after writing %s\nwant:\n%s\ngot:\n%s", format, wantAPI, got)
			}
		})
	}
}
