func note(fields ...*ir.FieldDef) *ir.TypeDef {
	return &ir.TypeDef{
		Name: "Note", Role: ir.RoleEmbeddedStruct, Description: "A note.",
		Behaviors: []ir.BehaviorRef{
			{Name: "Workflow", Config: []byte(`{"states":["draft","published"]}`)},
			{Name: "Comments"},
			{Name: "Numbering", Config: []byte(`{"format":"N-{n}"}`)},
		},
		Fields: append([]*ir.FieldDef{{Name: "title", TypeRef: ir.TypeRef{Name: "string"}, Required: true, Description: "Its title."}}, fields...),
	}
}

// TestTypeLowersAGeneralTypeToItsTable: the type is a DB table with
// development mode's key; a behavior whose declaration names a value
// field is anchored on a field of that name, Workflow's status and
// Numbering's label, and the others are ones the table implements; its
// description and its fields' are their comments. The type given is left
// as it was.
func TestTypeLowersAGeneralTypeToItsTable(t *testing.T) {
	td := note()
	table, err := Type(td, CoreValues())
	require.NoError(t, err)
	assert.Equal(t, ir.RoleDBTable, table.Role)
	require.Len(t, table.Fields, 2)
	assert.Equal(t, &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true}, table.Fields[0])
	assert.Equal(t, "Its title.", table.Fields[1].Comment)
	assert.Empty(t, table.Fields[1].Description)
	assert.Equal(t, "A note.", table.Comment)
	assert.Empty(t, table.Description)
	assert.Equal(t, []ir.BehaviorRef{
		{Name: "Workflow", Field: "status", Config: []byte(`{"states":["draft","published"]}`)},
		{Name: "Comments", Implements: true},
		{Name: "Numbering", Field: "label", Config: []byte(`{"format":"N-{n}"}`)},
	}, table.Behaviors)

	assert.Equal(t, ir.RoleEmbeddedStruct, td.Role)
	assert.Len(t, td.Fields, 1)
	assert.Equal(t, "Its title.", td.Fields[0].Description)
	assert.Empty(t, td.Behaviors[0].Field)
	assert.False(t, td.Behaviors[1].Implements)

	// A key the type marks is its key.
	keyed := note(&ir.FieldDef{Name: "slug", TypeRef: ir.TypeRef{Name: "string"}, Key: true})
	table, err = Type(keyed, CoreValues())
	require.NoError(t, err)
	assert.Len(t, table.Fields, 2)
	assert.Equal(t, "slug", table.Fields[1].Name)
}

// TestTypeRefusesWhatTheTableCannotHold: a field named as the value field
// a behavior lowers to (decision 3: a type with a status field and a
// Workflow), a field anchor of that name already taken, and an id that is
// not the key.
func TestTypeRefusesWhatTheTableCannotHold(t *testing.T) {
	for _, tc := range []struct {
		name string
		td   *ir.TypeDef
		want string
	}{
		{"a status field", note(&ir.FieldDef{Name: "status", TypeRef: ir.TypeRef{Name: "string"}}),
			"type Note has a field status, and its Workflow lowers to the field form status: Workflow<{ ... }>, which its declaration names its value field (D117): rename the field"},
		{"a field anchor of that name", &ir.TypeDef{Name: "Order", Behaviors: []ir.BehaviorRef{{Name: "Workflow", Field: "status"}, {Name: "Workflow"}}},
			"type Order anchors Workflow on the field status, and its Workflow lowers to the field form status: Workflow<{ ... }> (D117): anchor one of them on another field"},
		{"an id that is no key", note(&ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: "string"}}),
			"type Note has a field id and marks no field key"},
	} {
		_, err := Type(tc.td, CoreValues())
		require.Error(t, err, tc.name)
		assert.Contains(t, err.Error(), tc.want, tc.name)
	}
}

// TestDocumentsAreOneServicesTables: each document's instance type is its
// table, the documents are of kind DB and named after the service, the key's
// scalar is declared once across them, and the documents' description is
// the instance type's comment.
func TestDocumentsAreOneServicesTables(t *testing.T) {
	docs := []*schemafile.Document{
		{Name: "Job", Kind: ir.SchemaKindGeneral, Description: "A job.", Types: map[string]*ir.TypeDef{
			"Job":    {Name: "Job", Role: ir.RoleEmbeddedStruct, Behaviors: []ir.BehaviorRef{{Name: "Workflow"}}},
			"Result": {Name: "Result", Role: ir.RoleEmbeddedStruct},
		}},
		{Name: "Worker", Kind: ir.SchemaKindGeneral, Types: map[string]*ir.TypeDef{
			"Worker": {Name: "Worker", Role: ir.RoleEmbeddedStruct},
		}},
	}
	lowered, err := Documents(docs, "jobs-db", CoreValues())
	require.NoError(t, err)
	require.Len(t, lowered, 2)
	for _, doc := range lowered {
		assert.Equal(t, ir.SchemaKindDB, doc.Kind)
		assert.Equal(t, "jobs-db", doc.Name)
		assert.Empty(t, doc.Description)
	}
	assert.Equal(t, ir.RoleDBTable, lowered[0].Types["Job"].Role)
	assert.Equal(t, "A job.", lowered[0].Types["Job"].Comment)
	assert.Equal(t, ir.RoleEmbeddedStruct, lowered[0].Types["Result"].Role, "a type that is not the instance type stays an object type")
	assert.Equal(t, ir.RoleDBTable, lowered[1].Types["Worker"].Role, "an instance type with no behaviors is a table too")
	assert.NotNil(t, lowered[0].Scalars["Identity.UUID"])
	assert.Nil(t, lowered[1].Scalars["Identity.UUID"], "the service declares the key's scalar once")
	assert.Equal(t, ir.SchemaKindGeneral, docs[0].Kind, "the documents given are left as they were")
	assert.Equal(t, ir.RoleEmbeddedStruct, docs[0].Types["Job"].Role)

	_, err = Documents([]*schemafile.Document{{Name: "shop", Kind: ir.SchemaKindGeneral, Types: map[string]*ir.TypeDef{
		"Order": {Name: "Order"}, "Customer": {Name: "Customer"},
	}}}, "shop-db", CoreValues())
	require.Error(t, err)
	assert.Equal(t, "shop has no instance type: development mode serves the type named like the document, or its only type, as a table (D117)", err.Error())

	_, err = Documents([]*schemafile.Document{{Name: "shop-db", Kind: ir.SchemaKindDB}}, "shop-db", CoreValues())
	require.Error(t, err)
	assert.Contains(t, err.Error(), "only development mode's General documents lower to tables")
}

// TestServiceIsTheOneNamedOrTheOneShared: the service General documents
// lower into is the one the caller names, else the name they share.
func TestServiceIsTheOneNamedOrTheOneShared(t *testing.T) {
	service, err := Service([]string{"notes"}, "")
	require.NoError(t, err)
	assert.Equal(t, "notes", service)
	service, err = Service([]string{"Batch", "Job"}, "jobs-db")
	require.NoError(t, err)
	assert.Equal(t, "jobs-db", service)
	_, err = Service([]string{"Batch", "Job", "Worker", "Job"}, "")
	require.Error(t, err)
	assert.Equal(t, "the documents are development mode's General schemas Batch, Job and Worker, which lower to the tables of one DB service (D117): name the service", err.Error())
}

// TestDocumentLeavesAGeneralServicesOwnTypes: a General document whose
// types compose no behavior on the type is returned as it is; one that
// composes one is a DB document of its tables for the TypeScript writer.
func TestDocumentLeavesAGeneralServicesOwnTypes(t *testing.T) {
	plain := &schemafile.Document{Name: "shared", Kind: ir.SchemaKindGeneral, Description: "Shared types.", Types: map[string]*ir.TypeDef{
		"Money": {Name: "Money", Role: ir.RoleEmbeddedStruct},
	}}
	same, err := Document(plain, CoreValues())
	require.NoError(t, err)
	assert.Same(t, plain, same)

	notes := &schemafile.Document{Name: "notes", Kind: ir.SchemaKindGeneral, Description: "Notes.", Types: map[string]*ir.TypeDef{"Note": note()}}
	lowered, err := Document(notes, CoreValues())
	require.NoError(t, err)
	assert.Equal(t, ir.SchemaKindDB, lowered.Kind)
	assert.Equal(t, "notes", lowered.Name)
	assert.Empty(t, lowered.Description)
	assert.Equal(t, "Notes.\nA note.", lowered.Types["Note"].Comment)
	assert.Equal(t, ir.RoleDBTable, lowered.Types["Note"].Role)
}
