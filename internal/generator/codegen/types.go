package codegen

import (
	ir "github.com/parable-work/superschematic/ir"
)

// ScalarInfo holds information about a semantic scalar extracted from the
// Schema IR. This is a language-agnostic representation; each generator maps
// TargetType to the appropriate language-specific type.
type ScalarInfo struct {
	// Name is the canonical scalar identity (e.g., "Identity.UUID").
	Name string

	// TargetType is the language-specific type this scalar maps to.
	// For Go: "string", "int64", "time.Time", "UUID", etc.
	// For TypeScript: "string", "number", "JSDate", etc.
	// For Python: "str", "int", "datetime.datetime", etc.
	TargetType string

	// Primitive is the host-language primitive the scalar bottoms out on
	// (string, number, boolean, object).
	Primitive ir.LanguagePrimitive

	// Description is the scalar's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema.
	Comment string

	// MaxLength is the maximum string length constraint (0 means no limit).
	MaxLength int

	// MinLength is the minimum string length constraint (0 means no minimum).
	MinLength int

	// Pattern is a regex pattern for validation.
	Pattern string

	// Format is an optional format hint (e.g., "email", "uri", "date-time").
	Format string

	// CaseInsensitive indicates whether string comparisons should be case-insensitive.
	CaseInsensitive bool

	// ReservedWords are disallowed exact-match string values for this scalar.
	ReservedWords []string

	// ReservedWordsCaseInsensitive controls case-insensitive reserved word matching.
	ReservedWordsCaseInsensitive bool

	// ReservedWordsMatchPartial controls partial-match reserved word matching.
	ReservedWordsMatchPartial bool

	// Minimum is the minimum numeric value (nil means no minimum).
	Minimum *int64

	// Maximum is the maximum numeric value (nil means no maximum).
	Maximum *int64

	// Example is an example value for documentation.
	Example string

	// HasCustomNormalize indicates superscalar has a custom normalize implementation.
	HasCustomNormalize bool

	// HasCustomValidate indicates superscalar has a custom validate implementation.
	HasCustomValidate bool

	// HasCustomParse indicates superscalar has a custom parse implementation.
	HasCustomParse bool

	// Tokens contains normalized scalar identity tokens used by generators.
	Tokens ScalarTokens

	// Traits captures semantic properties used for generator behavior.
	Traits ScalarTraits
}

// ScalarTokens contains normalized scalar identity representations.
type ScalarTokens struct {
	// Canonical is the canonical scalar identity (e.g. "Identity.UUID").
	Canonical string

	// Symbol is an identifier-safe symbol stem (e.g. "IdentityUUID").
	Symbol string

	// Module is a module/file stem token (e.g. "identity_uuid").
	Module string

	// Segments is the canonical identity split into namespace segments.
	Segments []string
}

// Leaf returns the last identity segment (e.g. "UUID" for "Identity.UUID").
func (t ScalarTokens) Leaf() string {
	if len(t.Segments) == 0 {
		return t.Canonical
	}
	return t.Segments[len(t.Segments)-1]
}

// ScalarTraits captures scalar semantics that generators can share.
type ScalarTraits struct {
	IsStringLike   bool
	IsIntegerLike  bool
	IsFloatLike    bool
	IsBooleanLike  bool
	IsObjectLike   bool
	IsUUIDLike     bool
	IsDateLike     bool
	IsTimeLike     bool
	IsDateTimeLike bool
	IsDurationLike bool
	IsJSONLike     bool
	IsLocationLike bool
	IsEmailLike    bool
	IsURLLike      bool
	IsIDLike       bool
	IsPathLike     bool
}

// FieldInfo holds information about a field in a type. This is a
// language-agnostic representation that each generator extends.
//
// The field name is the JSON name: custom JSON tags are not a feature of the
// schema language.
type FieldInfo struct {
	// Name is the schema field name (and the JSON serialization key).
	Name string

	// TargetName is the language-specific field name.
	// For Go: PascalCase (e.g., "UserName")
	// For TypeScript: camelCase (e.g., "userName")
	// For Python: snake_case (e.g., "user_name")
	TargetName string

	// Type is the schema type name (e.g., "Identity.UUID", "string", "User").
	Type string

	// TargetType is the language-specific type.
	TargetType string

	// Required indicates whether the field is non-nullable.
	// Note: fields with @autoGenerated are not required for validation.
	Required bool

	// InternalMetadata marks fields owned by superschematic rather than schema authors.
	// These fields remain readable in generated types but are skipped by
	// user-input validation paths.
	InternalMetadata bool

	// Secret indicates whether the field has @secret metadata.
	Secret bool

	// IsArray indicates whether the field is a list type.
	IsArray bool

	// IsMap indicates whether the field is a map/dictionary type with string
	// keys. When true, Type and IsArray describe the map value type.
	IsMap bool

	// IsScalar indicates whether the field's base type is a semantic scalar.
	IsScalar bool

	// IsPrimitive indicates the field's base type is a bare language
	// primitive (string, number, boolean, object) rather than a named
	// definition.
	IsPrimitive bool

	// IsUnion indicates whether the field's base type is a discriminated
	// union. Generators use this to emit specialized JSON marshaling logic
	// that dispatches through the union's wrapper type.
	IsUnion bool

	// IsRelation indicates this field is a FK relation to another object type.
	// Relation fields should be optional in serialization types because the
	// full object may not be loaded.
	IsRelation bool

	// InheritedFrom names the base class or trait that contributed this
	// field. Empty for fields declared directly on the type.
	InheritedFrom string

	// Description is the field's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema. Node comments
	// become doc comments in generated code.
	Comment string

	// ScalarInfo contains scalar constraint info if IsScalar is true.
	ScalarInfo *ScalarInfo

	// Validations contains validation rules derived from scalar and field constraints.
	Validations []ValidationRule

	// Default is the raw @default value as written in the schema. Nil means
	// the field has no default. Per-language generators parse this string
	// into a typed literal using the field's primitive / scalar / enum
	// metadata.
	Default *string
}

// Doc returns the documentation text for the field (description, falling
// back to the node-attached comment).
func (f FieldInfo) Doc() string {
	return DocText(f.Description, f.Comment)
}

// TypeInfo holds information about an object type.
type TypeInfo struct {
	// Name is the schema type name.
	Name string

	// Owner is the source schema file this type was defined in.
	Owner string

	// Role classifies what the type is for. Generators key off Role.
	Role ir.Role

	// Description is the type's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema.
	Comment string

	// Extends is the base-class name this type inherits fields from. Fields
	// are pre-flattened; Extends is informational for structure-preserving
	// generators.
	Extends string

	// Fields contains all fields of this type, including pre-flattened
	// inherited fields.
	Fields []FieldInfo

	// JsonField indicates the type is a @jsonField payload type stored as
	// JSONB rather than a relational table.
	JsonField bool

	// DenyUnknownFields indicates the type carries @denyUnknownFields: its
	// generated Rust deserializer rejects a key the type does not declare.
	DenyUnknownFields bool

	// StrictJSON indicates the type carries @strictJSON: every generated
	// decoder rejects an undeclared key and an absent or null required field.
	StrictJSON bool

	// EnvVars indicates the type declares the service's environment-variable
	// configuration surface.
	EnvVars bool

	// Versioned marks DB table types that get generated history tracking.
	Versioned bool

	// VersionedConfig carries optional history retention/partition settings.
	VersionedConfig *ir.VersionedConfig
}

// Doc returns the documentation text for the type.
func (t TypeInfo) Doc() string {
	return DocText(t.Description, t.Comment)
}

// UnionInfo holds information about a union type.
type UnionInfo struct {
	// Name is the union type name.
	Name string

	// Description is the union's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema.
	Comment string

	// Types contains the names of member types in this union.
	Types []string

	// Discriminator is the name of the field that selects which member type
	// applies to a payload (e.g., "type"). Empty when no shared
	// discriminator field is present on every member.
	//
	// Detection rule: every member of the union has a field marked
	// @internalMetadata with a matching name.
	Discriminator string

	// Members lists each member type with its discriminator literal value
	// (from @default on the @internalMetadata field). Members[i].Name
	// matches Types[i].
	Members []UnionMemberInfo
}

// Doc returns the documentation text for the union.
func (u UnionInfo) Doc() string {
	return DocText(u.Description, u.Comment)
}

// UnionMemberInfo holds per-member metadata for a discriminated union.
type UnionMemberInfo struct {
	// Name is the member type name (matches an entry in UnionInfo.Types).
	Name string

	// DiscriminatorValue is the literal value the member's discriminator
	// field holds in serialized payloads. Empty when the union has no
	// discriminator or the member lacks a @default for it.
	DiscriminatorValue string
}

// ValidationRule represents a validation constraint for a field.
type ValidationRule struct {
	// Validator is the validation type: "required", "maxLength", "minLength",
	// "listMax", "listMin", "pattern", "min", "max", etc.
	Validator string

	// Message is the human-readable validation error message.
	Message string

	// Value is the constraint value (e.g., max length number, regex pattern string).
	Value interface{}
}

// EnumInfo holds information about an enum type.
type EnumInfo struct {
	// Name is the enum type name.
	Name string

	// Owner identifies the source schema that owns this enum.
	Owner string

	// Description is the enum's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema.
	Comment string

	// Values contains all enum values.
	Values []EnumValueInfo
}

// Doc returns the documentation text for the enum.
func (e EnumInfo) Doc() string {
	return DocText(e.Description, e.Comment)
}

// EnumValueInfo holds information about a single enum value.
type EnumValueInfo struct {
	// Name is the enum value name as declared.
	Name string

	// Value is the serialized value (SerializedAs, or same as Name).
	Value string

	// Description is the value's description from the schema.
	Description string

	// Comment is the node-attached comment from the schema.
	Comment string
}

// Doc returns the documentation text for the enum value.
func (v EnumValueInfo) Doc() string {
	return DocText(v.Description, v.Comment)
}

// ScalarMap is a convenience type for mapping scalar names to their info.
type ScalarMap map[string]*ScalarInfo

// BuildScalarMap creates a ScalarMap from a slice of ScalarInfo for quick lookups.
func BuildScalarMap(scalars []ScalarInfo) ScalarMap {
	m := make(ScalarMap, len(scalars))
	for i := range scalars {
		m[scalars[i].Name] = &scalars[i]
	}
	return m
}
