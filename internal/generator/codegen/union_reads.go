package codegen

import (
	"fmt"
	"sort"
	"strings"

	ir "github.com/parable-work/superschematic/ir"
)

// The structural predicate a union picks its member by, in every language
// (D31, amended). A member reads a payload exactly when the payload decodes
// under the member's types, as serde decodes it for the Rust member:
//
//   - the payload is a JSON object, and a @strictJSON member's holds no key
//     the member does not declare;
//   - each required field (ReadField.Required) is present and not null;
//   - each field present and not null has the field's JSON kind at every
//     list level and in every map value, none of whose elements or values
//     is null: a string, a number, a boolean, an object or an array, an
//     enum's string one of its values, a scalar's value one its scalar's
//     own validator passes (the scalar's format), a nested object one its
//     type reads, and a nested union one some member reads.
//
// A field's own rules (Validate<>: lengths, patterns, ranges) take no part:
// a member that breaks one is picked, and its validator refuses it after.
//
// ReadModel is that predicate as data, which each generator writes into
// its language beside one interpreter of it, so Go, TypeScript, Rust and
// Python read a payload alike by construction.
type ReadModel struct {
	// Types are the object types the unions reach, through their members'
	// fields too, sorted by name.
	Types []ReadType
	// Unions are the unions the model reads: the schema's own and any its
	// members' fields reach, sorted by name.
	Unions []ReadUnion
}

// ReadType is one object type of the predicate.
type ReadType struct {
	Name   string
	Strict bool
	Fields []ReadField
}

// ReadField is one field of a ReadType.
type ReadField struct {
	// Name is the field's JSON name.
	Name string
	// Required is true when a payload must hold the field, not null: the
	// field is required, has no @default, is not @autoGenerated and is not
	// a versioned table's _version, which every decoder fills in.
	Required bool
	// Depth is the field's list levels, 0, 1 or 2; Map marks a map, whose
	// values have the Depth.
	Depth int
	Map   bool
	// Kind is the kind of each value: ReadString, ReadNumber, ReadBoolean,
	// ReadEnum, ReadScalar, ReadObject, ReadUnion or ReadAny.
	Kind string
	// Values are an enum's serialized values.
	Values []string
	// Scalar is a scalar's canonical name, and ScalarJSON its value's JSON
	// kind (ReadString, ReadNumber, ReadInteger, ReadBoolean, ReadJSONObject,
	// ReadJSONArray or ReadAny), which a language checks when it has no
	// validator of the scalar.
	Scalar     string
	ScalarJSON string
	// Ref names the object type or union of an object or union field.
	Ref string
}

// Kinds of a ReadField's values.
const (
	ReadString     = "string"
	ReadNumber     = "number"
	ReadInteger    = "integer"
	ReadBoolean    = "boolean"
	ReadEnum       = "enum"
	ReadScalar     = "scalar"
	ReadObject     = "object"
	ReadUnionKind  = "union"
	ReadAny        = "any"
	ReadJSONObject = "jsonObject"
	ReadJSONArray  = "jsonArray"
)

// ReadUnion is one union of the predicate. With a Discriminator, the member
// its value names is the only candidate; otherwise the candidates are the
// members whose Fields include every payload key and whose Tags the payload
// allows, then, when none of those reads it, the members whose Tags allow
// it. The first candidate that reads the payload is the member.
type ReadUnion struct {
	Name          string
	Discriminator string
	Members       []ReadUnionMember
}

// ReadUnionMember is one member of a ReadUnion: its type, the value of the
// union's discriminator that names it, and its shape (UnionShapes).
type ReadUnionMember struct {
	Type   string
	Tag    string
	Fields []string
	Tags   []UnionTag
}

// IsDiscriminated reports whether the union picks its member by its
// discriminator.
func (u ReadUnion) IsDiscriminated() bool { return u.Discriminator != "" }

// BuildReadModel builds the predicate for the schema's unions and every
// object type and union their members reach, declared by the schema or by
// a dependency, looked up as a reference's target is.
func BuildReadModel(schema *ir.Schema, deps map[string]*ir.Schema) (*ReadModel, error) {
	b := &readModelBuilder{schema: schema, deps: deps, types: map[string]*ReadType{}, unions: map[string]*ReadUnion{}}
	names := make([]string, 0, len(schema.Unions))
	for name := range schema.Unions {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := b.union(name); err != nil {
			return nil, err
		}
	}
	model := &ReadModel{}
	for _, t := range b.types {
		model.Types = append(model.Types, *t)
	}
	for _, u := range b.unions {
		model.Unions = append(model.Unions, *u)
	}
	sort.Slice(model.Types, func(i, j int) bool { return model.Types[i].Name < model.Types[j].Name })
	sort.Slice(model.Unions, func(i, j int) bool { return model.Unions[i].Name < model.Unions[j].Name })
	return model, nil
}

type readModelBuilder struct {
	schema *ir.Schema
	deps   map[string]*ir.Schema
	types  map[string]*ReadType
	unions map[string]*ReadUnion
}

// owner returns the schema that declares name as a type, an enum, a scalar
// or a union: the schema's own, then the dependencies in name order.
func (b *readModelBuilder) owner(has func(*ir.Schema) bool) *ir.Schema {
	if has(b.schema) {
		return b.schema
	}
	depNames := make([]string, 0, len(b.deps))
	for name := range b.deps {
		depNames = append(depNames, name)
	}
	sort.Strings(depNames)
	for _, name := range depNames {
		if dep := b.deps[name]; dep != nil && has(dep) {
			return dep
		}
	}
	return nil
}

func (b *readModelBuilder) union(name string) error {
	if _, done := b.unions[name]; done {
		return nil
	}
	owner := b.owner(func(s *ir.Schema) bool { return s.Unions[name] != nil })
	if owner == nil {
		return fmt.Errorf("codegen: union %s is not declared by the schema or its dependencies", name)
	}
	def := owner.Unions[name]
	read := &ReadUnion{Name: name}
	b.unions[name] = read
	members := make([][]FieldInfo, len(def.Types))
	discriminator := ""
	for _, info := range ExtractUnions(owner) {
		if info.Name != name {
			continue
		}
		discriminator = info.Discriminator
		for _, m := range info.Members {
			read.Members = append(read.Members, ReadUnionMember{Type: m.Name, Tag: m.DiscriminatorValue})
			if m.DiscriminatorValue == "" {
				discriminator = ""
			}
		}
	}
	if len(read.Members) != len(def.Types) {
		read.Members = read.Members[:0]
		for _, member := range def.Types {
			read.Members = append(read.Members, ReadUnionMember{Type: member})
		}
		discriminator = ""
	}
	read.Discriminator = discriminator
	isEnum := func(typeName string) bool {
		return b.owner(func(s *ir.Schema) bool { return s.Enums[typeName] != nil }) != nil
	}
	for i, member := range def.Types {
		typeDef := b.typeDef(member)
		if typeDef == nil {
			return fmt.Errorf("codegen: union %s member %s is not an object type of the schema or its dependencies", name, member)
		}
		for _, field := range typeDef.Fields {
			if field == nil {
				continue
			}
			members[i] = append(members[i], FieldInfo{
				Name:    field.Name,
				Type:    field.TypeRef.Name,
				IsArray: field.TypeRef.IsArray,
				IsMap:   field.TypeRef.IsMap,
				Default: field.Default,
			})
		}
		if err := b.objectType(member); err != nil {
			return err
		}
	}
	if discriminator == "" {
		for i, shape := range UnionShapes(members, isEnum) {
			read.Members[i].Fields = shape.Fields
			read.Members[i].Tags = shape.Tags
		}
	}
	return nil
}

func (b *readModelBuilder) typeDef(name string) *ir.TypeDef {
	owner := b.owner(func(s *ir.Schema) bool { return s.Types[name] != nil })
	if owner == nil {
		return nil
	}
	return owner.Types[name]
}

func (b *readModelBuilder) objectType(name string) error {
	if _, done := b.types[name]; done {
		return nil
	}
	def := b.typeDef(name)
	if def == nil {
		return fmt.Errorf("codegen: type %s is not declared by the schema or its dependencies", name)
	}
	read := &ReadType{Name: name, Strict: def.StrictJSON}
	b.types[name] = read
	for _, field := range def.Fields {
		if field == nil {
			continue
		}
		rf := ReadField{
			Name:     field.Name,
			Required: ReadRequired(field),
			Depth:    field.TypeRef.ArrayDepth(),
			Map:      field.TypeRef.IsMap,
		}
		if err := b.kind(&rf, field.TypeRef.Name); err != nil {
			return fmt.Errorf("codegen: %s.%s: %w", name, field.Name, err)
		}
		read.Fields = append(read.Fields, rf)
	}
	return nil
}

// ReadRequired reports whether a payload must hold field, not null, for its
// type to read the payload: it is required, has no @default a decoder
// fills in (Default<T, "now"> is the database's, D88), and is neither
// @autoGenerated nor a versioned table's _version, which every decoder
// fills in.
func ReadRequired(field *ir.FieldDef) bool {
	isVersion := field.Name == "_version" && field.InternalMetadata
	decoded := field.Default != nil && !IsDefaultNow(field.TypeRef.Name, field.Default)
	return field.Required && !decoded && !field.AutoGenerated && !isVersion
}

// kind sets the kind of a field's values from its type's name.
func (b *readModelBuilder) kind(rf *ReadField, typeName string) error {
	switch typeName {
	case PrimitiveString:
		rf.Kind = ReadString
		return nil
	case PrimitiveNumber:
		rf.Kind = ReadNumber
		return nil
	case PrimitiveBoolean:
		rf.Kind = ReadBoolean
		return nil
	}
	if owner := b.owner(func(s *ir.Schema) bool { return s.Enums[typeName] != nil }); owner != nil {
		rf.Kind = ReadEnum
		for _, value := range owner.Enums[typeName].Values {
			serialized := value.SerializedAs
			if serialized == "" {
				serialized = value.Name
			}
			rf.Values = append(rf.Values, serialized)
		}
		return nil
	}
	if owner := b.owner(func(s *ir.Schema) bool { return s.Scalars[typeName] != nil }); owner != nil {
		rf.Kind = ReadScalar
		rf.Scalar = typeName
		rf.ScalarJSON = scalarReadJSON(owner.Scalars[typeName])
		return nil
	}
	if b.owner(func(s *ir.Schema) bool { return s.Unions[typeName] != nil }) != nil {
		rf.Kind = ReadUnionKind
		rf.Ref = typeName
		return b.union(typeName)
	}
	if b.typeDef(typeName) != nil {
		rf.Kind = ReadObject
		rf.Ref = typeName
		return b.objectType(typeName)
	}
	rf.Kind = ReadAny
	return nil
}

// scalarReadJSON is the JSON kind of a scalar's values: its json_schema type
// mapping, else its language primitive.
func scalarReadJSON(scalar *ir.ScalarDef) string {
	switch strings.TrimSpace(scalar.TypeMappings["json_schema"]) {
	case "string":
		return ReadString
	case "integer":
		return ReadInteger
	case "number":
		return ReadNumber
	case "boolean":
		return ReadBoolean
	case ir.JSONSchemaObjectType:
		return ReadJSONObject
	case ir.JSONSchemaArrayType:
		return ReadJSONArray
	case ir.JSONSchemaAnyType:
		return ReadAny
	}
	switch scalar.LanguagePrimitive {
	case ir.LanguageNumber:
		return ReadNumber
	case ir.LanguageBoolean:
		return ReadBoolean
	case ir.LanguageObject:
		return ReadAny
	}
	return ReadString
}

// ReadModelTypeNames returns the names of the model's object types.
func (m *ReadModel) ReadModelTypeNames() []string {
	names := make([]string, len(m.Types))
	for i, t := range m.Types {
		names[i] = t.Name
	}
	return names
}

// ScalarNames returns the scalars the model's fields hold, sorted.
func (m *ReadModel) ScalarNames() []string {
	seen := map[string]bool{}
	var names []string
	for _, t := range m.Types {
		for _, f := range t.Fields {
			if f.Kind == ReadScalar && !seen[f.Scalar] {
				seen[f.Scalar] = true
				names = append(names, f.Scalar)
			}
		}
	}
	sort.Strings(names)
	return names
}

// UnionIndex returns the position of a union in m.Unions, or -1.
func (m *ReadModel) UnionIndex(name string) int {
	for i, u := range m.Unions {
		if u.Name == name {
			return i
		}
	}
	return -1
}
