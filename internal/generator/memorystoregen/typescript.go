// The TypeScript definitions of a MemoryStore service (D75): a package at
// types/typescript/<store>, named as the naming file names a schema's
// types package (`@schemas/shop-cache-types`), with a const per
// declaration whose `for` takes the declaration's parts in order and
// returns the HTTP runtime's Channel<T> or Key:
//
//	import { stockChanged } from '@schemas/shop-cache-types';
//	await stockChanged.for(productId).publish(deps.shopCache, signal);
//
// A key whose life depends on the call (maxTtlSeconds) has `forTTL(ttlMs,
// ...parts)` in place of `for`, which refuses a TTL above the maximum. A
// channel's payload type comes from the types package its schema already
// generates, and its decoder keeps only the members the payload's type
// declares, at every depth, before the type's own parser checks the rest,
// so replicas of two releases share a channel while a deploy rolls.

// The files of the TypeScript definitions package.
const (
	TypeScriptIndexFile    = "index.ts"
	TypeScriptPackageFile  = "package.json"
	TypeScriptTSConfigFile = "tsconfig.json"
)

// GenerateTypeScript writes the store's TypeScript definitions into
// in.Dir: a package with a const per declaration whose `for` takes the
// parts in order and returns the runtime's Channel<T> or Key (D75).
func GenerateTypeScript(in Input) error {
	n := in.Context.Options.Naming.OrDefault()
	w := &tsWriter{in: in, typesImports: map[string]map[string]bool{}, parsers: map[string]map[string]bool{}}
	body, err := w.definitions()
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("// Code generated by superschematic (memorystoregen). DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "/*\nThe definitions of the memory store %s (D75): a value per channel and key\n", in.Store)
	b.WriteString("its schema declares, whose `for` takes the declaration's parts in order and\n")
	b.WriteString("returns the HTTP runtime's Channel or Key, so a caller never formats a name.\n")
	b.WriteString("Each call takes the MemoryStore an API's Deps holds for the store. A part\n")
	b.WriteString("that is no segment throws MemoryStoreNameError; a store that is disabled\n")
	b.WriteString("or unreachable throws MemoryStoreUnavailableError, and the caller takes its\n")
	b.WriteString("fallback path. A channel's decoder keeps the members its payload's type\n")
	b.WriteString("declares, at every depth, and drops the message when the rest does not\n")
	b.WriteString("parse.\n*/\n\n")
	b.WriteString(w.imports(n.HTTPRuntimeNpmPackage, n.NpmTypesPackage))
	fmt.Fprintf(&b, "\n/** The store's name, the first segment of every name it holds. */\nexport const STORE = %s;\n", tsString(in.Store))
	b.WriteString(body)

	files := map[string][]byte{TypeScriptIndexFile: []byte(b.String())}
	pkg, err := w.packageJSON(n.NpmTypesPackage(in.Store), n.HTTPRuntimeNpmPackage, n.NpmTypesPackage)
	if err != nil {
		return err
	}
	files[TypeScriptPackageFile] = pkg
	files[TypeScriptTSConfigFile] = []byte(tsConfig)
	for name, data := range files {
		if err := os.WriteFile(filepath.Join(in.Dir, name), data, 0o644); err != nil {
			return fmt.Errorf("memory store %s: %w", in.Store, err)
		}
	}
	return nil
}

const tsConfig = `{
  "compilerOptions": {
    "target": "ES2022",
    "module": "ESNext",
    "lib": ["ES2022"],
    "declaration": true,
    "noEmit": true,
    "strict": true,
    "esModuleInterop": true,
    "skipLibCheck": true,
    "forceConsistentCasingInFileNames": true,
    "moduleResolution": "bundler"
  },
  "include": ["*.ts"],
  "exclude": ["node_modules", "dist", "*.test.ts"]
}
`

// tsWriter writes one store's definitions, collecting what index.ts
// imports as it goes.
type tsWriter struct {
	in Input

	// runtime are the names imported from the HTTP runtime's main entry.
	runtime []string

	// typesImports are the type names imported from each dependency's
	// types package's ./types entry, by its service.
	typesImports map[string]map[string]bool

	// parsers are the parsers imported from each dependency's types
	// package, by its service.
	parsers map[string]map[string]bool

	// pickers are the object types whose picker index.ts holds, by
	// service and type, in the order first reached.
	pickers []pickedType
	picked  map[pickedType]bool

	// pickLists and pickMaps say index.ts holds the list and map pickers.
	pickLists, pickMaps bool
}

type pickedType struct{ service, name string }

func (w *tsWriter) use(name string) {
	if !slices.Contains(w.runtime, name) {
		w.runtime = append(w.runtime, name)
	}
}

func (w *tsWriter) importType(service, name string) {
	if w.typesImports[service] == nil {
		w.typesImports[service] = map[string]bool{}
	}
	w.typesImports[service][name] = true
}

func (w *tsWriter) imports(runtimePackage string, typesPackage func(string) string) string {
	var b strings.Builder
	var values, types []string
	for _, name := range w.runtime {
		if rest, ok := strings.CutPrefix(name, "type "); ok {
			types = append(types, rest)
		} else {
			values = append(values, name)
		}
	}
	sort.Strings(values)
	sort.Strings(types)
	names := values
	for _, t := range types {
		if !slices.Contains(values, t) {
			names = append(names, "type "+t)
		}
	}
	fmt.Fprintf(&b, "import { %s } from %s;\n", strings.Join(names, ", "), tsString(runtimePackage))
	for _, service := range sortedKeys(w.parsers) {
		fmt.Fprintf(&b, "import { %s } from %s;\n", strings.Join(sortedKeys(w.parsers[service]), ", "), tsString(typesPackage(service)))
	}
	for _, service := range sortedKeys(w.typesImports) {
		fmt.Fprintf(&b, "import type { %s } from %s;\n", strings.Join(sortedKeys(w.typesImports[service]), ", "), tsString(typesPackage(service)+"/types"))
	}
	return b.String()
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// definitions writes the const of each declaration, then the codecs and
// pickers of the payloads.
func (w *tsWriter) definitions() (string, error) {
	var b strings.Builder
	consts := map[string]string{}
	codecs := map[string]bool{}
	var codecOrder []string
	for _, decl := range w.in.Declarations {
		name := tsIdentifier(tsutil.ToCamelCase(decl.Symbol))
		if prev, clash := consts[name]; clash {
			return "", fmt.Errorf("memory store %s: declarations %s and %s are both the TypeScript const %s; give one another class name", w.in.Store, prev, decl.Symbol, name)
		}
		consts[name] = decl.Symbol
		params, wires, err := w.parts(decl)
		if err != nil {
			return "", err
		}
		args := tsString(decl.Name)
		if len(wires) > 0 {
			args += ", " + strings.Join(wires, ", ")
		}
		ref := fmt.Sprintf("{ declaration: %s, name: memoryStoreName(%s) }", tsString(decl.Name), args)
		w.use("memoryStoreName")
		b.WriteString("\n")
		b.WriteString(tsDocBlock("", decl.Doc, declarationNote(decl)))
		fmt.Fprintf(&b, "export const %s = {\n", name)
		fmt.Fprintf(&b, "  /** The declaration's name, the segment after the store's. */\n  name: %s,\n", tsString(decl.Name))
		switch {
		case decl.Kind == ir.MemoryStoreChannel:
			payload, ok := w.in.PayloadOf(decl)
			var typ, build string
			if ok {
				codec := tsutil.ToCamelCase(payload.Type) + "Codec"
				if !codecs[payload.Type] {
					codecs[payload.Type] = true
					codecOrder = append(codecOrder, payload.Type)
				}
				w.importType(payload.Service, payload.Type)
				w.use("Channel")
				typ = fmt.Sprintf("Channel<%s>", payload.Type)
				build = fmt.Sprintf("new Channel(%s, %s)", ref, codec)
			} else {
				w.use("signalChannel")
				w.use("type Channel")
				w.use("type Signal")
				typ = "Channel<Signal>"
				build = fmt.Sprintf("signalChannel(%s)", ref)
			}
			fmt.Fprintf(&b, "  /** The channel of %s. Throws MemoryStoreNameError for a part that is no segment. */\n", partList(decl))
			fmt.Fprintf(&b, "  for(%s): %s {\n    return %s;\n  },\n", strings.Join(params, ", "), typ, build)
		case decl.MaxTTLSeconds > 0:
			w.use("Key")
			w.use("checkTtl")
			maxMs := int64(decl.MaxTTLSeconds) * 1000
			fmt.Fprintf(&b, "  /** The longest TTL, in milliseconds, a call may give the key. */\n  maxTtlMs: %s,\n", tsInt(maxMs))
			fmt.Fprintf(&b, "  /**\n   * The key of %s, whose write that creates it sets a TTL of ttlMs.\n", partList(decl))
			b.WriteString("   * Throws RangeError for a TTL above maxTtlMs, and MemoryStoreNameError for a\n   * part that is no segment.\n   */\n")
			fmt.Fprintf(&b, "  forTTL(%s): Key {\n", strings.Join(append([]string{"ttlMs: number"}, params...), ", "))
			fmt.Fprintf(&b, "    checkTtl(ttlMs, %s);\n    return new Key(%s, ttlMs);\n  },\n", tsInt(maxMs), ref)
		default:
			w.use("Key")
			ttlMs := int64(decl.TTLSeconds) * 1000
			fmt.Fprintf(&b, "  /** The key's TTL, in milliseconds, from the write that creates it. */\n  ttlMs: %s,\n", tsInt(ttlMs))
			fmt.Fprintf(&b, "  /** The key of %s. Throws MemoryStoreNameError for a part that is no segment. */\n", partList(decl))
			fmt.Fprintf(&b, "  for(%s): Key {\n    return new Key(%s, %s);\n  },\n", strings.Join(params, ", "), ref, tsInt(ttlMs))
		}
		b.WriteString("} as const;\n")
	}
	for _, typeName := range codecOrder {
		payload := w.in.Payloads[typeName]
		parser := "parse" + payload.Type + "JsonNonStrict"
		if w.parsers[payload.Service] == nil {
			w.parsers[payload.Service] = map[string]bool{}
		}
		w.parsers[payload.Service][parser] = true
		w.use("jsonCodec")
		picker := w.picker(payload.Service, payload.Type)
		fmt.Fprintf(&b, "\n/** A %s message: its JSON, with only the members %s declares at every depth, then %s's own parser. */\n", payload.Type, payload.Type, payload.Type)
		fmt.Fprintf(&b, "const %sCodec = jsonCodec<%s>(value => %s(%s(value)));\n", tsutil.ToCamelCase(payload.Type), payload.Type, parser, picker)
	}
	if len(w.pickers) > 0 {
		pickers, err := w.pickerFunctions()
		if err != nil {
			return "", err
		}
		b.WriteString(pickers)
	}
	return b.String(), nil
}

// parts are a declaration's parameters and the wire string of each, in
// order.
func (w *tsWriter) parts(decl *ir.MemoryStoreDeclaration) (params, wires []string, err error) {
	taken := map[string]bool{}
	if decl.MaxTTLSeconds > 0 {
		taken["ttlMs"] = true
	}
	for _, part := range decl.Parts {
		param := tsIdentifier(part.Name)
		for taken[param] {
			param += "_"
		}
		taken[param] = true
		var typ, wire string
		switch part.Format {
		case ir.MemoryStorePartString, "":
			typ, wire = "string", param
			if uuidLike(part.Type.Name) {
				// A UUID's name segment is its canonical lowercase form.
				wire = param + ".toLowerCase()"
			}
		case ir.MemoryStorePartInteger:
			w.use("integerPart")
			typ, wire = "number", "integerPart("+param+")"
		case ir.MemoryStorePartBoolean:
			typ, wire = "boolean", "("+param+" ? 'true' : 'false')"
		case ir.MemoryStorePartEnum:
			pkg := importOf(w.in.Schema, part.Type.Name)
			if pkg == "" {
				return nil, nil, fmt.Errorf("memory store %s: part %s of %s is enum %s, which the schema imports from no dependency", w.in.Store, part.Name, decl.Name, part.Type.Name)
			}
			w.importType(typegen.DependencyServiceName(pkg), part.Type.Name)
			// A TypeScript enum member's value is its wire value.
			typ, wire = part.Type.Name, "String("+param+")"
		default:
			return nil, nil, fmt.Errorf("memory store %s: part %s of %s has the format %q, which the TypeScript definitions do not write", w.in.Store, part.Name, decl.Name, part.Format)
		}
		params = append(params, param+": "+typ)
		wires = append(wires, wire)
	}
	return params, wires, nil
}

// uuidLike reports whether a part's type is a UUID scalar, whose wire form
// is its canonical lowercase string.
func uuidLike(typeName string) bool {
	return strings.Contains(strings.ToLower(typeName), "uuid")
}

// picker is the name of the function that keeps the members of an object
// type, which pickerFunctions writes.
func (w *tsWriter) picker(service, name string) string {
	t := pickedType{service, name}
	if w.picked == nil {
		w.picked = map[pickedType]bool{}
	}
	if !w.picked[t] {
		w.picked[t] = true
		w.pickers = append(w.pickers, t)
	}
	return "pick" + name
}

// objectType is the object type a field of service's schema names, and
// the service whose schema declares it, or nil for a scalar, an enum, a
// union or a type the store's build has not loaded.
func (w *tsWriter) objectType(service, name string) (*ir.TypeDef, string) {
	schema := w.in.Dependencies[service]
	if schema == nil {
		return nil, ""
	}
	if def := schema.Types[name]; def != nil && !def.IsTrait && def.Role != ir.RoleTrait {
		return def, service
	}
	return nil, ""
}

// fieldsOf are a type's fields with those of the type it extends first.
func (w *tsWriter) fieldsOf(service string, def *ir.TypeDef, seen map[string]bool) []*ir.FieldDef {
	if seen[def.Name] {
		return nil
	}
	seen[def.Name] = true
	var out []*ir.FieldDef
	if def.Extends != "" {
		if base, _ := w.objectType(service, def.Extends); base != nil {
			out = append(out, w.fieldsOf(service, base, seen)...)
		}
	}
	for _, f := range def.Fields {
		if f != nil && !slices.ContainsFunc(out, func(o *ir.FieldDef) bool { return o.Name == f.Name }) {
			out = append(out, f)
		}
	}
	return out
}

// pickerFunctions writes a picker per object type a payload reaches: it
// copies the members the type declares, each object member through its
// own type's picker, lists and maps of them element by element, and
// leaves any other value as it is, which the type's parser then checks.
func (w *tsWriter) pickerFunctions() (string, error) {
	var b strings.Builder
	for i := 0; i < len(w.pickers); i++ {
		t := w.pickers[i]
		def, _ := w.objectType(t.service, t.name)
		if def == nil {
			return "", fmt.Errorf("memory store %s: a payload reaches %s, which %s does not declare as an object type", w.in.Store, t.name, t.service)
		}
		fmt.Fprintf(&b, "\n/** value with only the members %s declares, at every depth. */\n", t.name)
		fmt.Fprintf(&b, "function pick%s(value: unknown): unknown {\n", t.name)
		b.WriteString("  if (value === null || typeof value !== 'object' || Array.isArray(value)) return value;\n")
		b.WriteString("  const v = value as Record<string, unknown>;\n")
		b.WriteString("  const out: Record<string, unknown> = {};\n")
		for _, f := range w.fieldsOf(t.service, def, map[string]bool{}) {
			key := tsString(f.Name)
			read := fmt.Sprintf("v[%s]", key)
			value := read
			if nested, svc := w.objectType(t.service, f.TypeRef.Name); nested != nil {
				value = w.pickValue(read, f.TypeRef.ArrayDepth(), f.TypeRef.IsMap, w.picker(svc, nested.Name))
			}
			fmt.Fprintf(&b, "  if (%s in v) out[%s] = %s;\n", key, key, value)
		}
		b.WriteString("  return out;\n}\n")
	}
	if w.pickLists {
		b.WriteString("\n/** Each element of a list through pick, or value as it is when it is no list. */\n")
		b.WriteString("function pickList(value: unknown, pick: (element: unknown) => unknown): unknown {\n")
		b.WriteString("  return Array.isArray(value) ? value.map(pick) : value;\n}\n")
	}
	if w.pickMaps {
		b.WriteString("\n/** Each value of a map through pick, or value as it is when it is no map. */\n")
		b.WriteString("function pickMap(value: unknown, pick: (element: unknown) => unknown): unknown {\n")
		b.WriteString("  if (value === null || typeof value !== 'object' || Array.isArray(value)) return value;\n")
		b.WriteString("  return Object.fromEntries(Object.entries(value as Record<string, unknown>).map(([k, e]) => [k, pick(e)]));\n}\n")
	}
	return b.String(), nil
}

// pickValue is the expression that picks read, a member that holds an
// object type whose picker is picker: in depth lists, or a map's values.
func (w *tsWriter) pickValue(read string, depth int, isMap bool, picker string) string {
	inner := func(d int) string {
		m := picker
		for i := 0; i < d; i++ {
			w.pickLists = true
			m = "(e: unknown) => pickList(e, " + m + ")"
		}
		return m
	}
	switch {
	case isMap:
		w.pickMaps = true
		return fmt.Sprintf("pickMap(%s, %s)", read, inner(depth))
	case depth > 0:
		w.pickLists = true
		return fmt.Sprintf("pickList(%s, %s)", read, inner(depth-1))
	default:
		return fmt.Sprintf("%s(%s)", picker, read)
	}
}

// packageJSON is the package's manifest: the HTTP runtime, and each
// dependency whose types index.ts imports, from the workspace.
func (w *tsWriter) packageJSON(name, runtimePackage string, typesPackage func(string) string) ([]byte, error) {
	deps := map[string]string{runtimePackage: "*"}
	for service := range w.typesImports {
		deps[typesPackage(service)] = "workspace:*"
	}
	for service := range w.parsers {
		deps[typesPackage(service)] = "workspace:*"
	}
	type entry struct {
		Types  string `json:"types"`
		Import string `json:"import"`
	}
	type manifest struct {
		Name            string            `json:"name"`
		Version         string            `json:"version"`
		Description     string            `json:"description"`
		Type            string            `json:"type"`
		Main            string            `json:"main"`
		Types           string            `json:"types"`
		Exports         map[string]entry  `json:"exports"`
		License         string            `json:"license"`
		Private         bool              `json:"private"`
		Dependencies    map[string]string `json:"dependencies"`
		DevDependencies map[string]string `json:"devDependencies"`
	}
	m := manifest{
		Name:            name,
		Version:         "1.0.0",
		Description:     fmt.Sprintf("TypeScript definitions of the channels and keys of the memory store %s (D75)", w.in.Store),
		Type:            "module",
		Main:            TypeScriptIndexFile,
		Types:           TypeScriptIndexFile,
		Exports:         map[string]entry{".": {Types: "./" + TypeScriptIndexFile, Import: "./" + TypeScriptIndexFile}},
		License:         "UNLICENSED",
		Private:         true,
		Dependencies:    deps,
		DevDependencies: map[string]string{"typescript": tsrestgen.TypeScriptVersion},
	}
	data, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(data, '\n'), nil
}

// declarationNote is the second paragraph of a declaration's doc: what it
// is, its name pattern, and how long a key lives.
func declarationNote(decl *ir.MemoryStoreDeclaration) string {
	pattern := decl.NamePattern()
	switch {
	case decl.Kind == ir.MemoryStoreChannel && decl.Payload == nil:
		return fmt.Sprintf("A signal channel, whose name is the whole message: `%s`.", pattern)
	case decl.Kind == ir.MemoryStoreChannel:
		return fmt.Sprintf("A channel of %s messages: `%s`.", decl.Payload.Name, pattern)
	case decl.MaxTTLSeconds > 0:
		return fmt.Sprintf("A %s whose TTL a call gives, at most %d s: `%s`.", decl.Kind, decl.MaxTTLSeconds, pattern)
	default:
		return fmt.Sprintf("A %s that lives %d s from the write that creates it: `%s`.", decl.Kind, decl.TTLSeconds, pattern)
	}
}

// partList names a declaration's parts for a doc line.
func partList(decl *ir.MemoryStoreDeclaration) string {
	if len(decl.Parts) == 0 {
		return "the declaration, which has no parts"
	}
	names := make([]string, len(decl.Parts))
	for i, p := range decl.Parts {
		names[i] = p.Name
	}
	return "one " + strings.Join(names, ", ")
}

// tsDocBlock is a JSDoc comment of paragraphs, indented by indent.
func tsDocBlock(indent string, paragraphs ...string) string {
	var lines []string
	for _, p := range paragraphs {
		p = strings.TrimSpace(strings.ReplaceAll(p, "*/", "*\\/"))
		if p == "" {
			continue
		}
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		lines = append(lines, strings.Split(p, "\n")...)
	}
	if len(lines) == 0 {
		return ""
	}
	var b strings.Builder
	b.WriteString(indent + "/**\n")
	for _, l := range lines {
		if l == "" {
			b.WriteString(indent + " *\n")
		} else {
			b.WriteString(indent + " * " + l + "\n")
		}
	}
	b.WriteString(indent + " */\n")
	return b.String()
}

// tsString is s as a single-quoted TypeScript string.
func tsString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `'`, `\'`, "\n", `\n`, "\r", `\r`, " ", ` `, " ", ` `)
	return "'" + r.Replace(s) + "'"
}

// tsInt is n with an underscore every three digits.
func tsInt(n int64) string {
	s := fmt.Sprintf("%d", n)
	if len(s) <= 4 {
		return s
	}
	var b strings.Builder
	pre := len(s) % 3
	if pre > 0 {
		b.WriteString(s[:pre])
	}
	for i := pre; i < len(s); i += 3 {
		if b.Len() > 0 {
			b.WriteByte('_')
		}
		b.WriteString(s[i : i+3])
	}
	return b.String()
}

// tsReserved are the words no const or parameter may be.
var tsReserved = map[string]bool{
	"break": true, "case": true, "catch": true, "class": true, "const": true, "continue": true, "debugger": true,
	"default": true, "delete": true, "do": true, "else": true, "enum": true, "export": true, "extends": true,
	"false": true, "finally": true, "for": true, "function": true, "if": true, "import": true, "in": true,
	"instanceof": true, "new": true, "null": true, "return": true, "super": true, "switch": true, "this": true,
	"throw": true, "true": true, "try": true, "typeof": true, "var": true, "void": true, "while": true,
	"with": true, "yield": true, "let": true, "static": true, "implements": true, "interface": true,
	"package": true, "private": true, "protected": true, "public": true, "await": true, "arguments": true,
	"eval": true, "STORE": true,
}

// tsIdentifier is name, with an underscore after a reserved word.
func tsIdentifier(name string) string {
	if tsReserved[name] {
		return name + "_"
	}
	return name
}
