// Package rulescore builds the project's rules crate of a DB schema whose
// tables compose a behavior the core's crate does not ship (D103's step
// 5): one a class or an extension declares, whose hooks a Rust crate
// implements over the core's API (registry.BehaviorSpec.Rules). A
// project's core is a value its build assembles: the core's behaviors
// (superschematic_rules_behaviors::core) with each composed behavior's
// crate added (Core::with). A schema
// whose tables compose the core's behaviors alone needs no crate: the
// stock core, the release's archive and module, runs them.
//
// The crate is <output root>/rules/rust/<schema>, named
// Naming.RustRulesCrate(schema) (<prefix><schema>-rules), a workspace of
// its own:
//
//   - Cargo.toml depends on superschematic-rules, superschematic-rules-
//     behaviors and superschematic-rules-wasm, the core's ABI without its
//     abi feature, by path at the [paths] key rules_behaviors_rust and its
//     siblings (rules, rules-wasm), and on each composed behavior's crate by
//     its path in the project, the parent of the schemas root. Its lib is a
//     cdylib, an rlib and a staticlib.
//   - declarations/<name>.behavior.json holds each composed behavior's
//     declaration, the canonical copy the registry holds.
//   - src/lib.rs gives COMPOSED, the composed behaviors; core(), the core
//     with them; declarations(), every registered behavior's declaration
//     file in the core's order, the core's and then theirs; and exports
//     the core's ABI over them (superschematic_rules_wasm::
//     export_rules_abi): the static archive the Go binding links in the
//     stock one's place, staged as libsuperschematic_rules.a by
//     scripts/rules-archive.sh --crate <crate> --out <dir>, and the wasm32
//     module @superschematic/rules loads when a host names it. Its tests
//     find every composed behavior registered and declared through the ABI.
//
// Build writes nothing when a composed behavior's crate is not in the
// project, and says why: the core runs a behavior from its crate alone.
package rulescore

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/parable-work/superschematic/internal/generator/naming"
	"github.com/parable-work/superschematic/internal/registry"
	ir "github.com/parable-work/superschematic/ir"
)

// The core's crates the project's rules crate depends on.
const (
	RulesCrate     = "superschematic-rules"
	BehaviorsCrate = "superschematic-rules-behaviors"
	ABICrate       = "superschematic-rules-wasm"
	// Version is the crates' version when no [paths] key names a checkout
	// of them: the core's workspace's, which publishes none yet.
	Version = "0.0.0"
)

// Header opens every file the crate holds, by which a build knows a crate
// in the directory is its own.
const Header = "Code generated by superschematic. DO NOT EDIT."

// The files of the crate.
const (
	ManifestFile    = "Cargo.toml"
	LibFile         = "src/lib.rs"
	DeclarationsDir = "declarations"
)

// Options configures Build.
type Options struct {
	// SchemaName is the schema's service name.
	SchemaName string
	// Registry declares the behaviors and their crates. Required.
	Registry *registry.Registry
	// Naming names the crate.
	Naming naming.Naming
	// RepositoryRoot is the project, the parent of the schemas root, which
	// a behavior's crate path is relative to.
	RepositoryRoot string
	// Paths locates the core's crates: rules_behaviors_rust, whose siblings
	// rules and rules-wasm are the core and its ABI. Unset, the crate names
	// their version.
	Paths naming.LocalPaths
	// Dir is the crate's directory, which every path dependency is
	// relative to.
	Dir string
	// RustVersion is the toolchain the crate states as its rust-version.
	RustVersion string
}

// Crate is a schema's project rules crate.
type Crate struct {
	// Name is the Cargo package name and Ident the crate as Rust spells it.
	Name, Ident string
	// Schema is the schema's service name.
	Schema      string
	RustVersion string
	// Rules, Behaviors and ABI are the core's crates.
	Rules, Behaviors, ABI Dependency
	// Composed are the behaviors the crate adds to the core's, sorted by
	// name, each with its crate and the declaration it embeds.
	Composed []Composed
}

// Dependency is one of the core's crates: by path when Path is set, else
// by Version.
type Dependency struct {
	Crate string
	Path  string
}

// Composed is a behavior the crate adds to the core's.
type Composed struct {
	// Name is the behavior's registered name.
	Name string
	// Crate is its crate's Cargo name, Path its directory relative to the
	// crate's, and Register the Rust value Core::with takes.
	Crate, Path, Register string
	// Declaration is its canonical declaration.
	Declaration []byte
}

// Build returns the rules crate of schema, a DB schema, or nil when it
// needs none: no table composes a behavior whose crate the core's does not
// ship. A nil crate with a reason is one the schema needs and Build cannot
// write, because a composed behavior's crate is not in the project.
func Build(schema *ir.Schema, opts Options) (*Crate, string, error) {
	reg := opts.Registry
	if reg == nil {
		return nil, "", errors.New("rulescore: no registry")
	}
	var names []string
	for _, td := range schema.Types {
		if td == nil || td.Role != ir.RoleDBTable {
			continue
		}
		for _, ref := range td.TableBehaviors() {
			b, ok := reg.Behavior(ref.Name)
			if ok && b.Rules.Declared() && !registry.RunsOnTheCore(b.Name) && !contains(names, b.Name) {
				names = append(names, b.Name)
			}
		}
	}
	if len(names) == 0 {
		return nil, "", nil
	}
	sort.Strings(names)
	c := &Crate{
		Name:        opts.Naming.RustRulesCrate(opts.SchemaName),
		Schema:      opts.SchemaName,
		RustVersion: opts.RustVersion,
	}
	c.Ident = strings.ReplaceAll(c.Name, "-", "_")
	var missing []string
	for _, name := range names {
		b, _ := reg.Behavior(name)
		dir := filepath.Join(opts.RepositoryRoot, filepath.FromSlash(b.Rules.Path))
		if opts.RepositoryRoot == "" {
			missing = append(missing, fmt.Sprintf("%s's crate %s is at %s in the project, and the build names no project", name, b.Rules.Crate, b.Rules.Path))
			continue
		}
		if _, err := os.Stat(filepath.Join(dir, ManifestFile)); err != nil {
			missing = append(missing, fmt.Sprintf("%s's crate %s is not at %s in the project (%s holds no %s)", name, b.Rules.Crate, b.Rules.Path, dir, ManifestFile))
			continue
		}
		rel, err := naming.PhysicalRelPath(opts.Dir, dir)
		if err != nil {
			return nil, "", fmt.Errorf("rulescore: crate %s of %s: %w", b.Rules.Crate, name, err)
		}
		declaration, err := registry.CanonicalDeclaration(b.BehaviorDeclaration)
		if err != nil {
			return nil, "", fmt.Errorf("rulescore: %s: %w", name, err)
		}
		c.Composed = append(c.Composed, Composed{Name: name, Crate: b.Rules.Crate, Path: rel, Register: b.Rules.Register, Declaration: declaration})
	}
	if len(missing) > 0 {
		return nil, fmt.Sprintf("no core can run %s's behaviors, so no rules crate is written: %s (D103)", opts.SchemaName, strings.Join(missing, "; ")), nil
	}
	behaviors := opts.Paths.RulesBehaviorsRust
	var err error
	if c.Behaviors, err = dependency(BehaviorsCrate, behaviors, opts.Dir); err != nil {
		return nil, "", err
	}
	if behaviors != "" {
		behaviors = filepath.Dir(behaviors)
	}
	if c.Rules, err = dependency(RulesCrate, sibling(behaviors, "rules"), opts.Dir); err != nil {
		return nil, "", err
	}
	if c.ABI, err = dependency(ABICrate, sibling(behaviors, "rules-wasm"), opts.Dir); err != nil {
		return nil, "", err
	}
	return c, "", nil
}

func sibling(parent, name string) string {
	if parent == "" {
		return ""
	}
	return filepath.Join(parent, name)
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// dependency is one of the core's crates, by path relative to from when
// dir is set.
func dependency(crate, dir, from string) (Dependency, error) {
	if dir == "" {
		return Dependency{Crate: crate}, nil
	}
	rel, err := naming.PhysicalRelPath(from, dir)
	if err != nil {
		return Dependency{}, fmt.Errorf("rulescore: %s: %w", crate, err)
	}
	return Dependency{Crate: crate, Path: rel}, nil
}

// spec is the dependency's Cargo.toml value; the ABI's without its abi
// feature, which exports the stock core's.
func (d Dependency) spec(defaultFeatures bool) string {
	features := ""
	if !defaultFeatures {
		features = ", default-features = false"
	}
	if d.Path != "" {
		return fmt.Sprintf("{ path = %s%s }", quoteTOML(filepath.ToSlash(d.Path)), features)
	}
	return fmt.Sprintf("{ version = %s%s }", quoteTOML(Version), features)
}

// Files are the crate's files by their path in it.
func (c *Crate) Files() map[string][]byte {
	out := map[string][]byte{ManifestFile: c.manifest(), LibFile: c.lib()}
	for _, b := range c.Composed {
		out[DeclarationsDir+"/"+b.Name+".behavior.json"] = b.Declaration
	}
	return out
}

func (c *Crate) manifest() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "# %s\n#\n", Header)
	fmt.Fprintf(&b, "# %s's rules crate (D103's step 5): the behaviors' core with the\n", c.Schema)
	b.WriteString("# behaviors its tables compose that the core's crate does not ship, each\n")
	b.WriteString("# from its crate, behind the core's ABI: the archive and module that\n")
	b.WriteString("# stand in the stock ones' place.\n")
	b.WriteString("[package]\n")
	fmt.Fprintf(&b, "name = %s\n", quoteTOML(c.Name))
	b.WriteString("version = \"0.0.0\"\nedition = \"2021\"\n")
	if c.RustVersion != "" {
		fmt.Fprintf(&b, "rust-version = %s\n", quoteTOML(c.RustVersion))
	}
	b.WriteString("publish = false\n\n")
	b.WriteString("[lib]\n")
	b.WriteString("# A cdylib for the wasm32 module, a staticlib for the Go binding's\n# archive, an rlib for the tests.\n")
	b.WriteString("crate-type = [\"cdylib\", \"rlib\", \"staticlib\"]\n\n")
	b.WriteString("[dependencies]\n")
	fmt.Fprintf(&b, "%s = %s\n", c.Rules.Crate, c.Rules.spec(true))
	fmt.Fprintf(&b, "%s = %s\n", c.Behaviors.Crate, c.Behaviors.spec(true))
	fmt.Fprintf(&b, "%s = %s\n", c.ABI.Crate, c.ABI.spec(false))
	seen := map[string]bool{}
	for _, composed := range c.Composed {
		if seen[composed.Crate] {
			continue
		}
		seen[composed.Crate] = true
		fmt.Fprintf(&b, "%s = { path = %s }\n", composed.Crate, quoteTOML(filepath.ToSlash(composed.Path)))
	}
	b.WriteString("\n# A workspace of its own, wherever the output root lies.\n[workspace]\n")
	return b.Bytes()
}

func (c *Crate) lib() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "//! %s\n//!\n", Header)
	fmt.Fprintf(&b, "//! %s's rules core (D103's step 5): the behaviors' core with the\n", c.Schema)
	b.WriteString("//! behaviors its tables compose that the core's crate does not ship, each\n")
	b.WriteString("//! registered from its crate, behind the core's ABI.\n\n")
	b.WriteString("use superschematic_rules::Core;\n\n")
	b.WriteString("/// The behaviors the crate adds to the core's, by their registered names.\n")
	fmt.Fprintf(&b, "pub const COMPOSED: [&str; %d] = [", len(c.Composed))
	for i, composed := range c.Composed {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", composed.Name)
	}
	b.WriteString("];\n\n")
	b.WriteString("/// The declaration file of each behavior [`core`] registers, in its order:\n")
	b.WriteString("/// the core's, then the composed ones'.\n")
	b.WriteString("pub fn declarations() -> Vec<&'static str> {\n")
	b.WriteString("    let mut out = superschematic_rules_behaviors::DECLARATIONS.to_vec();\n")
	for _, composed := range c.Composed {
		fmt.Fprintf(&b, "    out.push(include_str!(%q));\n", "../"+DeclarationsDir+"/"+composed.Name+".behavior.json")
	}
	b.WriteString("    out\n}\n\n")
	b.WriteString("/// The core with every behavior the core's crate ports and the composed\n/// ones.\n")
	b.WriteString("pub fn core() -> Core {\n    superschematic_rules_behaviors::core()")
	for _, composed := range c.Composed {
		fmt.Fprintf(&b, "\n        .with(%s)", composed.Register)
	}
	b.WriteString("\n}\n\n")
	b.WriteString("superschematic_rules_wasm::export_rules_abi!(core = crate::core, declarations = crate::declarations);\n\n")
	b.WriteString(`#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_core_registers_every_composed_behavior() {
        let names = core().names();
        for name in COMPOSED {
            assert!(names.iter().any(|known| known == name), "{name} is not registered");
        }
    }

    #[test]
    fn the_abi_declares_every_composed_behavior() {
        let rules = superschematic_rules_wasm::Rules::new(core, declarations());
        let (out, ok) = superschematic_rules_wasm::run_json_on(
            &rules,
            superschematic_rules_wasm::Op::Declarations,
            b"",
        );
        assert!(ok, "{out}");
        for name in COMPOSED {
            assert!(out.contains(&format!("\"name\":\"{name}\"")), "{name} is not declared");
        }
    }
}
`)
	return b.Bytes()
}

// Write writes the crate's files into dir, replacing the files and
// declarations an earlier build wrote.
func (c *Crate) Write(dir string) error {
	if err := os.RemoveAll(filepath.Join(dir, DeclarationsDir)); err != nil {
		return fmt.Errorf("rulescore: %w", err)
	}
	for name, data := range c.Files() {
		path := filepath.Join(dir, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return fmt.Errorf("rulescore: %w", err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			return fmt.Errorf("rulescore: %w", err)
		}
	}
	return nil
}

// quoteTOML is s as a TOML basic string.
func quoteTOML(s string) string {
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(s) + `"`
}

// RemoveStale removes the crate in dir when its manifest is one a build
// wrote, as a schema that needs none now leaves it.
func RemoveStale(dir string) error {
	data, err := os.ReadFile(filepath.Join(dir, ManifestFile))
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("rulescore: %w", err)
	}
	if !bytes.HasPrefix(data, []byte("# "+Header)) {
		return nil
	}
	return os.RemoveAll(dir)
}
