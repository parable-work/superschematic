package enginedoc

import (
	"fmt"
	"sort"

	"github.com/parable-work/superschematic/internal/generator/codegen"
	ir "github.com/parable-work/superschematic/ir"
)

// Problems lists, sorted, why the engine types of a DB schema cannot be
// engine types (D58), or nil when they can. The build reports them before
// any generator runs, since sql and orm leave the engine types out and a
// table that named one would point at a table that is not there:
//
//   - an engine type reaches a table: one of its fields, or a field of a
//     value type it holds, is typed as a table or as another engine type,
//     whose instances the engine keeps apart; the Links behavior (D16)
//     reaches another instance;
//   - a type that is not an engine type, a table or a value type a table
//     holds, references an engine type, or a projection reads or joins one;
//   - an engine type declares what only a table has: @versioned,
//     @optimistic, a version graph, the User or UserRole trait, a queue or
//     a projection;
//   - an engine type has a field the database generates (AutoGenerate):
//     the engine gives each instance an id of its own and fills no field;
//   - an engine type reaches a map or a union, which the engine's schema
//     runtime does not validate.
//
// A type the schema imports is not checked here: Build reads it from the
// dependency that declares it.
func Problems(schema *ir.Schema) []string {
	engineTypes := codegen.EngineTypes(schema)
	if len(engineTypes) == 0 {
		return nil
	}
	seen := map[string]bool{}
	var problems []string
	add := func(format string, args ...any) {
		problem := fmt.Sprintf(format, args...)
		if !seen[problem] {
			seen[problem] = true
			problems = append(problems, problem)
		}
	}

	for _, td := range engineTypes {
		if feature := tableFeature(td); feature != "" {
			add("engine type %s %s, which only a table has: a type that composes a behavior is an engine type, whose instances the engine keeps, and it gets no table (D58)", td.Name, feature)
		}
		if td.JsonField {
			add("engine type %s is a @jsonField value type, which a table holds as JSON: a type that composes a behavior is an engine type, whose instances the engine keeps, so it cannot be one (D58)", td.Name)
		}
		for _, fd := range td.Fields {
			if fd.AutoGenerated {
				add("field %s.%s of engine type %s is generated by the database (AutoGenerate), but an engine type gets no table: the engine gives each instance an id of its own and generates no field, so drop it (D58)", td.Name, fd.Name, td.Name)
			}
		}
		walkClosure(schema, td, add)
	}

	for _, name := range sortedNames(schema.Types) {
		td := schema.Types[name]
		if td == nil || codegen.IsEngineType(td) {
			continue
		}
		what := describe(td)
		for _, fd := range td.Fields {
			if target := engineTarget(schema, fd); target != "" {
				add("field %s.%s of %s %s references engine type %s, whose instances the engine keeps, not a table: hold the instance's id in a plain field, or make %s an engine type too and link to %s with the Links behavior (D16)",
					td.Name, fd.Name, what, td.Name, target, td.Name, target)
			}
		}
		if p := td.Projection; p != nil {
			if codegen.IsEngineType(schema.Types[p.Source]) {
				add("projection %s reads engine type %s, which gets no table: the engine keeps its instances (D58)", td.Name, p.Source)
			}
			for _, join := range p.Joins {
				if join != nil && codegen.IsEngineType(schema.Types[join.Type]) {
					add("projection %s joins engine type %s, which gets no table: the engine keeps its instances (D58)", td.Name, join.Type)
				}
			}
		}
	}
	sort.Strings(problems)
	return problems
}

// walkClosure checks the fields of root, an engine type, and of every
// value type it reaches.
func walkClosure(schema *ir.Schema, root *ir.TypeDef, add func(string, ...any)) {
	visited := map[string]bool{root.Name: true}
	queue := []*ir.TypeDef{root}
	for len(queue) > 0 {
		td := queue[0]
		queue = queue[1:]
		where := func(fd *ir.FieldDef) string {
			if td == root {
				return fmt.Sprintf("field %s.%s of engine type %s", td.Name, fd.Name, root.Name)
			}
			return fmt.Sprintf("field %s.%s, which engine type %s holds,", td.Name, fd.Name, root.Name)
		}
		for _, fd := range td.Fields {
			if fd.TypeRef.IsMap {
				add("%s is a map, which the engine's schema runtime does not validate: hold a list of a value type instead", where(fd))
				continue
			}
			if schema.Unions[fd.TypeRef.Name] != nil {
				add("%s has the union type %s, which the engine's schema runtime does not validate", where(fd), fd.TypeRef.Name)
				continue
			}
			target := schema.Types[fd.TypeRef.Name]
			if fd.Relation != nil && fd.Relation.Type != "" && schema.Types[fd.Relation.Type] != nil {
				target = schema.Types[fd.Relation.Type]
			}
			switch {
			case target == nil:
				// A primitive, a scalar, an enum or an imported type.
			case codegen.IsEngineType(target):
				add("%s holds engine type %s, whose instances the engine keeps apart: link to it with the Links behavior (D16) instead of a field", where(fd), target.Name)
			case isTable(target) || fd.Relation != nil || fd.HasMany || fd.ManyToMany:
				add("%s is typed as table %s, but an engine type cannot reach a table: make %s an engine type too and link to it with the Links behavior (D16), or hold its key in a plain field", where(fd), target.Name, target.Name)
			case !visited[target.Name]:
				visited[target.Name] = true
				queue = append(queue, target)
			}
		}
	}
}

// engineTarget is the engine type a field of another type names, by its
// type or its relation, or "".
func engineTarget(schema *ir.Schema, fd *ir.FieldDef) string {
	if codegen.IsEngineType(schema.Types[fd.TypeRef.Name]) {
		return fd.TypeRef.Name
	}
	if fd.Relation != nil && codegen.IsEngineType(schema.Types[fd.Relation.Type]) {
		return fd.Relation.Type
	}
	return ""
}

// isTable reports whether td is a table of a DB schema: a DB-table type
// that is not a @jsonField value type and not an engine type.
func isTable(td *ir.TypeDef) bool {
	return td.Role == ir.RoleDBTable && !td.JsonField && !codegen.IsEngineType(td)
}

// describe names what a type that is not an engine type is, for a message.
func describe(td *ir.TypeDef) string {
	switch {
	case td.Projection != nil || td.Role == ir.RoleProjection:
		return "projection"
	case td.Queue != nil:
		return "queue message"
	case isTable(td):
		return "table"
	default:
		return "type"
	}
}

// tableFeature names the first declaration of td that only a table has,
// or "".
func tableFeature(td *ir.TypeDef) string {
	switch {
	case td.Versioned:
		return "is @versioned"
	case td.Optimistic:
		return "is @optimistic"
	case td.VersionGraph != nil:
		return "is a version graph's root (@versionGraph)"
	case td.GraphMember != nil:
		return "is a version graph's member (@graphMember)"
	case td.User != nil:
		return "has the User trait"
	case td.UserRole != nil:
		return "has the UserRole trait"
	case td.Queue != nil:
		return "is a queue's message (@queue)"
	case td.Projection != nil || td.Role == ir.RoleProjection:
		return "is a projection"
	}
	return ""
}

func sortedNames[V any](m map[string]V) []string {
	names := make([]string, 0, len(m))
	for name := range m {
		names = append(names, name)
	}
	sort.Strings(names)
	return names
}
