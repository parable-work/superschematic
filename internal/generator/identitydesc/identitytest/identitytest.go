// Package identitytest builds, for the generator tests, a DB schema with
// the core user model (D50) as the loader leaves it: an Account table with
// the User trait, optionally a Role table with the UserRole trait, and the
// Session, UserCredential and UserRoleGrant tables ir/identity.go names,
// with Origin ir.OriginIdentity on each added type, field and index. The
// fields have the shapes the loader gives a key and a relation, and the
// scalars are hydrated from the scalar catalog as a load hydrates them.
package identitytest

import (
	"testing"

	"github.com/parable-work/superschematic/internal/loader"
	"github.com/parable-work/superschematic/internal/registry"
	ir "github.com/parable-work/superschematic/ir"
)

// Service is the name of the schema Schema builds.
const Service = "fixture-identity-db"

// The scalars the schema's fields use.
const (
	UUID     = "Identity.UUID"
	Email    = "Contact.Email"
	SHA256   = "Crypto.SHA256"
	DateTime = "Temporal.DateTime"
	Int64    = "Generic.Int64"
)

// Options picks the variant of the schema Schema builds.
type Options struct {
	// Roles adds the Role table, with the UserRole trait, and the
	// UserRoleGrant table the loader adds beside it.
	Roles bool
	// Key is the scalar of Account's key, Identity.UUID when empty. Only a
	// UUID key is auto-generated.
	Key string
	// Login is Account's login field, "email" when empty.
	Login string
	// Name is the field the User trait names for the display name; empty
	// leaves the trait's Name unset, so the login is the name.
	Name string
}

// Schema builds the schema opts describes. Account has its key, its login
// (a @unique Contact.Email), displayName and createdAt.
func Schema(tb testing.TB, opts Options) *ir.Schema {
	tb.Helper()
	if opts.Key == "" {
		opts.Key = UUID
	}
	if opts.Login == "" {
		opts.Login = "email"
	}
	const owner = "src/identity.schema.ts"
	schema := ir.NewSchema(Service, ir.SchemaKindDB)

	account := &ir.TypeDef{
		Name:  "Account",
		Owner: owner,
		Role:  ir.RoleDBTable,
		User:  &ir.UserTrait{Login: opts.Login, Name: opts.Name},
		Fields: []*ir.FieldDef{
			{Name: "id", TypeRef: ir.TypeRef{Name: opts.Key}, Required: true, Key: true, AutoGenerated: opts.Key == UUID},
			{Name: opts.Login, TypeRef: ir.TypeRef{Name: Email}, Required: true, Unique: true},
			{Name: "displayName", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
			{Name: "createdAt", TypeRef: ir.TypeRef{Name: DateTime}, Required: true},
		},
	}
	schema.Types[account.Name] = account

	add := func(td *ir.TypeDef) {
		td.Owner, td.Role, td.Origin = owner, ir.RoleDBTable, ir.OriginIdentity
		for _, fd := range td.Fields {
			fd.Origin = ir.OriginIdentity
		}
		for i := range td.Indexes {
			td.Indexes[i].Origin = ir.OriginIdentity
		}
		schema.Types[td.Name] = td
	}
	add(&ir.TypeDef{
		Name: ir.IdentitySessionTable,
		Fields: []*ir.FieldDef{
			idField(),
			relation(ir.IdentitySessionUserField, account.Name, false),
			{Name: ir.IdentitySessionTokenHashField, TypeRef: ir.TypeRef{Name: SHA256}, Required: true, Unique: true},
			{Name: ir.IdentitySessionCreatedAtField, TypeRef: ir.TypeRef{Name: DateTime}, Required: true},
			{Name: ir.IdentitySessionExpiresAtField, TypeRef: ir.TypeRef{Name: DateTime}, Required: true},
			{Name: ir.IdentitySessionLastSeenAtField, TypeRef: ir.TypeRef{Name: DateTime}},
			{Name: ir.IdentitySessionRevokedAtField, TypeRef: ir.TypeRef{Name: DateTime}},
		},
	})
	add(&ir.TypeDef{
		Name: ir.IdentityCredentialTable,
		Fields: []*ir.FieldDef{
			idField(),
			relation(ir.IdentityCredentialUserField, account.Name, true),
			{Name: ir.IdentityCredentialPasswordHashField, TypeRef: ir.TypeRef{Name: "string"}, Required: true, Secret: true},
			{Name: ir.IdentityCredentialPasswordChangedAtField, TypeRef: ir.TypeRef{Name: DateTime}, Required: true},
			{Name: ir.IdentityCredentialDisabledAtField, TypeRef: ir.TypeRef{Name: DateTime}},
		},
	})

	if opts.Roles {
		role := &ir.TypeDef{
			Name:     "Role",
			Owner:    owner,
			Role:     ir.RoleDBTable,
			UserRole: &ir.UserRoleTrait{},
			Fields: []*ir.FieldDef{
				idField(),
				{Name: ir.IdentityRoleNameField, TypeRef: ir.TypeRef{Name: "string"}, Required: true, Unique: true},
				{Name: ir.IdentityRolePermissionsField, TypeRef: ir.TypeRef{Name: "string", IsArray: true}, Required: true},
			},
		}
		schema.Types[role.Name] = role
		add(&ir.TypeDef{
			Name: ir.IdentityRoleGrantTable,
			Fields: []*ir.FieldDef{
				idField(),
				relation(ir.IdentityRoleGrantUserField, account.Name, false),
				relation(ir.IdentityRoleGrantRoleField, role.Name, false),
				{Name: ir.IdentityRoleGrantGrantedAtField, TypeRef: ir.TypeRef{Name: DateTime}, Required: true},
			},
			Indexes: []ir.IndexDef{{Keys: []string{ir.IdentityRoleGrantUserField, ir.IdentityRoleGrantRoleField}, Unique: true}},
		})
	}

	for _, name := range []string{opts.Key, UUID, Email, SHA256, DateTime} {
		schema.Scalars[name] = &ir.ScalarDef{Name: name}
	}
	if err := loader.HydrateScalars(schema, registry.CoreScalars()); err != nil {
		tb.Fatalf("hydrate the identity schema's scalars: %v", err)
	}
	return schema
}

// idField is an added table's key, an AutoGenerate<Identity.UUID>.
func idField() *ir.FieldDef {
	return &ir.FieldDef{Name: "id", TypeRef: ir.TypeRef{Name: UUID}, Required: true, Key: true, AutoGenerated: true}
}

// relation is a required to-one relation to target that cascades on delete.
func relation(name, target string, unique bool) *ir.FieldDef {
	return &ir.FieldDef{
		Name:     name,
		TypeRef:  ir.TypeRef{Name: target},
		Required: true,
		Unique:   unique,
		Relation: &ir.RelationDef{Type: target, OnDelete: "CASCADE"},
	}
}
