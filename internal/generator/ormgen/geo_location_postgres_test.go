const geoStopsService = "geo-stops"

// geoStopsSchema is a versioned table with a required and an optional
// Geo.Location, which sqlgen stores as POINT columns, and a required and an
// optional list of them, which it stores as POINT[] columns.
const geoStopsSchema = `{
  "name": "geo-stops",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Temporal.DateTime": { "name": "Temporal.DateTime", "languagePrimitive": "string" },
    "Geo.Location": { "name": "Geo.Location", "languagePrimitive": "string" }
  },
  "types": {
    "Stop": {
      "name": "Stop",
      "role": "DBTable",
      "versioned": true,
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "at", "typeRef": { "name": "Geo.Location" }, "required": true },
        { "name": "dropoff", "typeRef": { "name": "Geo.Location" } },
        { "name": "route", "typeRef": { "name": "Geo.Location", "isArray": true }, "required": true },
        { "name": "detour", "typeRef": { "name": "Geo.Location", "isArray": true } },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "updatedAt", "typeRef": { "name": "Temporal.DateTime" } },
        { "name": "createdBy", "typeRef": { "name": "Identity.UUID" }, "required": true },
        { "name": "updatedBy", "typeRef": { "name": "Identity.UUID" }, "required": true }
      ]
    }
  }
}
`

// TestGeoLocationColumnsOnPostgres generates the Go types, the ORM and the
// DDL of geoStopsSchema, then builds, vets and tests the ORM module with
// geoLocationORMTest against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL. A Geo.Location column is a
// Postgres POINT, which is (x, y): x is lon and y is lat, and a list of them
// is a POINT[]. The test writes locations and lists of them through
// CreateOne, CreateMany and UpdateOne, a nil list, an empty one and {0, 0}
// among them, reads the columns with SQL as point coordinates, writes points
// with SQL and reads them back through GetOne, FindMany and the versioned
// history readers, whose rows to_jsonb writes with each point as "(x,y)"
// text. A NULL element of a list is refused on read, and a location filters
// on IS NULL only.
func TestGeoLocationColumnsOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the Geo.Location columns against Postgres")
	}
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "geo-stops", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "stops.schema.json"), []byte(geoStopsSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", geoStopsService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + geoStopsService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", geoStopsService)
	ormDir := filepath.Join(tempRoot, "orm", geoStopsService)

	typesOutput, err := typegen.Generate(schema, typegen.Options{
		SchemaName: geoStopsService,
		ModulePath: typesModule,
		Clock:      fixedClock,
	})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatalf("set types replace paths: %v", err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatalf("write types: %v", err)
	}

	ormOutput, err := Generate(schema, Options{
		SchemaName:  geoStopsService,
		ModulePath:  "example.com/schemas/orm/" + geoStopsService,
		TypesModule: typesModule,
		Clock:       fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatalf("set orm replace paths: %v", err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatalf("write orm: %v", err)
	}

	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: geoStopsService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatalf("write ddl: %v", err)
	}
	createSQL, err := os.ReadFile(filepath.Join(ddlDir, "create.sql"))
	if err != nil {
		t.Fatal(err)
	}
	// POINT is a Postgres type of its own, so the DDL needs no PostGIS.
	if strings.Contains(string(createSQL), "postgis") {
		t.Fatalf("create.sql requires PostGIS for a POINT column:\n%s", createSQL)
	}
	for _, column := range []string{"at POINT NOT NULL,", "dropoff POINT,", "route POINT[] DEFAULT '{}' NOT NULL,", "detour POINT[],"} {
		if !strings.Contains(string(createSQL), column) {
			t.Fatalf("create.sql has no %s column:\n%s", column, createSQL)
		}
	}

	out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "geo_location_test.go", geoLocationORMTest)
	if !strings.Contains(out, "--- PASS: TestGeoLocationOnPostgres") {
		t.Fatal("the generated ORM module did not run TestGeoLocationOnPostgres")
	}
}

const geoLocationORMTest = `package orm

import (
	"context"
	"fmt"
	"os"
	"reflect"
	"strings"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
	types "example.com/schemas/types/go/geo-stops"
)

func TestGeoLocationOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	createSQL, err := os.ReadFile("testdata/create.sql")
	if err != nil {
		t.Fatalf("read create.sql: %v", err)
	}
	ctx := context.Background()
	base, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("connect: %v", err)
	}
	defer base.Close()
	schema := fmt.Sprintf("geo_stops_%d", time.Now().UnixNano())
	if _, err := base.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatalf("create schema: %v", err)
	}
	defer func() { _, _ = base.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE") }()
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parse database URL: %v", err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("connect schema pool: %v", err)
	}
	if _, err := pool.Exec(ctx, string(createSQL)); err != nil {
		pool.Close()
		t.Fatalf("apply create.sql: %v", err)
	}
	db, err := ConnectWithPool(pool)
	if err != nil {
		pool.Close()
		t.Fatalf("connect generated orm: %v", err)
	}
	defer db.Close()

	sf := types.GeoLocation{Lat: 37.7749, Lon: -122.4194}
	sydney := types.GeoLocation{Lat: -33.8688, Lon: 151.2093}
	zero := types.GeoLocation{}
	route := []types.GeoLocation{sf, zero}
	detour := []types.GeoLocation{sydney, zero}
	actor := types.NewUUID()
	ctx = WithUserID(ctx, actor)
	created, err := db.Stop.CreateOne(ctx, &types.Stop{At: sf, Route: route, CreatedBy: actor, UpdatedBy: actor})
	if err != nil {
		t.Fatalf("CreateOne: %v", err)
	}
	id := *created.Id
	if created.At != sf || created.Dropoff != nil {
		t.Fatalf("CreateOne = %+v, want at %+v and no dropoff", created, sf)
	}
	// {0, 0} is a location in a list too, and a nil list is no list.
	if !reflect.DeepEqual(created.Route, route) || created.Detour != nil {
		t.Fatalf("CreateOne = route %v detour %#v, want route %v and a nil detour", created.Route, created.Detour, route)
	}

	// The column is a POINT whose x is lon and y is lat.
	var x, y float64
	if err := pool.QueryRow(ctx, "SELECT at[0], at[1] FROM stop WHERE id = $1", id.ToUUID()).Scan(&x, &y); err != nil {
		t.Fatalf("read the at point: %v", err)
	}
	if x != sf.Lon || y != sf.Lat {
		t.Fatalf("at point = (%v, %v), want (lon %v, lat %v)", x, y, sf.Lon, sf.Lat)
	}
	var dropoffNull bool
	if err := pool.QueryRow(ctx, "SELECT dropoff IS NULL FROM stop WHERE id = $1", id.ToUUID()).Scan(&dropoffNull); err != nil || !dropoffNull {
		t.Fatalf("an unset dropoff is stored as NULL: %v, %v", dropoffNull, err)
	}

	// A list is a POINT[] of the same points, and a nil one is NULL.
	var routeLength int
	var x1, y1, x2, y2 float64
	var detourNull bool
	if err := pool.QueryRow(ctx, "SELECT cardinality(route), (route[1])[0], (route[1])[1], (route[2])[0], (route[2])[1], detour IS NULL FROM stop WHERE id = $1", id.ToUUID()).Scan(&routeLength, &x1, &y1, &x2, &y2, &detourNull); err != nil {
		t.Fatalf("read the route points: %v", err)
	}
	if routeLength != 2 || x1 != sf.Lon || y1 != sf.Lat || x2 != 0 || y2 != 0 || !detourNull {
		t.Fatalf("route = %d points (%v, %v), (%v, %v) and detour NULL %v, want (lon %v, lat %v), (0, 0) and a NULL detour", routeLength, x1, y1, x2, y2, detourNull, sf.Lon, sf.Lat)
	}

	// {0, 0} is a location, stored and read back as one, and an empty list
	// is an empty POINT[], not NULL.
	updated, err := db.Stop.UpdateOneIfVersion(ctx, id, created.Version, &StopUpdate{Dropoff: &zero, Detour: &[]types.GeoLocation{}, UpdatedBy: &actor})
	if err != nil {
		t.Fatalf("UpdateOneIfVersion: %v", err)
	}
	if updated.Dropoff == nil || *updated.Dropoff != zero {
		t.Fatalf("UpdateOneIfVersion dropoff = %v, want {0, 0}", updated.Dropoff)
	}
	if updated.Detour == nil || len(updated.Detour) != 0 {
		t.Fatalf("UpdateOneIfVersion detour = %#v, want an empty list", updated.Detour)
	}
	var detourLength int
	if err := pool.QueryRow(ctx, "SELECT cardinality(detour) FROM stop WHERE id = $1 AND detour IS NOT NULL", id.ToUUID()).Scan(&detourLength); err != nil || detourLength != 0 {
		t.Fatalf("an empty detour is stored as an empty POINT[]: %d, %v", detourLength, err)
	}

	// Points written with SQL read back as lat = y, lon = x.
	if _, err := pool.Exec(ctx, "UPDATE stop SET dropoff = point(151.2093, -33.8688), detour = ARRAY[point(151.2093, -33.8688), point(0, 0)] WHERE id = $1", id.ToUUID()); err != nil {
		t.Fatalf("write points with SQL: %v", err)
	}
	got, err := db.Stop.GetOne(ctx, id, nil)
	if err != nil {
		t.Fatalf("GetOne: %v", err)
	}
	if got.At != sf || got.Dropoff == nil || *got.Dropoff != sydney {
		t.Fatalf("GetOne = at %+v dropoff %v, want at %+v dropoff %+v", got.At, got.Dropoff, sf, sydney)
	}
	if !reflect.DeepEqual(got.Route, route) || !reflect.DeepEqual(got.Detour, detour) {
		t.Fatalf("GetOne = route %v detour %v, want route %v detour %v", got.Route, got.Detour, route, detour)
	}

	many, err := db.Stop.CreateMany(ctx, []*types.Stop{
		{At: types.GeoLocation{Lat: 90, Lon: -180}, Route: []types.GeoLocation{}, CreatedBy: actor, UpdatedBy: actor},
		{At: types.GeoLocation{Lat: -90, Lon: 180}, Dropoff: &sydney, Route: []types.GeoLocation{zero}, Detour: detour, CreatedBy: actor, UpdatedBy: actor},
	})
	if err != nil {
		t.Fatalf("CreateMany: %v", err)
	}
	if many[0].At != (types.GeoLocation{Lat: 90, Lon: -180}) || many[1].Dropoff == nil || *many[1].Dropoff != sydney {
		t.Fatalf("CreateMany = %+v, %+v", many[0], many[1])
	}
	if many[0].Route == nil || len(many[0].Route) != 0 || many[0].Detour != nil || !reflect.DeepEqual(many[1].Route, []types.GeoLocation{zero}) || !reflect.DeepEqual(many[1].Detour, detour) {
		t.Fatalf("CreateMany = routes %#v, %v and detours %#v, %v", many[0].Route, many[1].Route, many[0].Detour, many[1].Detour)
	}
	all, total, err := db.Stop.FindMany(ctx, nil, &StopFindOptions{Fields: StopFields{}.All()})
	if err != nil || total != 3 || len(all) != 3 {
		t.Fatalf("FindMany = %d rows (total %d), %v; want 3", len(all), total, err)
	}
	for _, stop := range all {
		if *stop.Id == id && (!reflect.DeepEqual(stop.Route, route) || !reflect.DeepEqual(stop.Detour, detour)) {
			t.Fatalf("FindMany = route %v detour %v, want route %v detour %v", stop.Route, stop.Detour, route, detour)
		}
	}

	// A location filters on IS NULL only: Postgres has no = for a point.
	isNull, notNull := true, false
	withoutDropoff, total, err := db.Stop.FindMany(ctx, &StopFilter{Dropoff: &GeoPointFilter{IsNull: &isNull}}, &StopFindOptions{Fields: StopFields{}.All()})
	if err != nil || total != 1 || len(withoutDropoff) != 1 || *withoutDropoff[0].Id != *many[0].Id {
		t.Fatalf("FindMany dropoff IS NULL = %d rows (total %d), %v; want the first of CreateMany", len(withoutDropoff), total, err)
	}
	withDropoff, total, err := db.Stop.FindMany(ctx, &StopFilter{At: &GeoPointFilter{IsNull: &notNull}, Dropoff: &GeoPointFilter{IsNull: &notNull}}, &StopFindOptions{Fields: StopFields{}.All()})
	if err != nil || total != 2 || len(withDropoff) != 2 {
		t.Fatalf("FindMany dropoff IS NOT NULL = %d rows (total %d), %v; want 2", len(withDropoff), total, err)
	}
	// UpdateMany writes a list where a location filter matches.
	count, err := db.Stop.UpdateMany(ctx, &StopFilter{Dropoff: &GeoPointFilter{IsNull: &isNull}}, &StopUpdate{Detour: &route})
	if err != nil || count != 1 {
		t.Fatalf("UpdateMany = %d rows, %v; want 1", count, err)
	}
	reread, err := db.Stop.GetOne(ctx, *many[0].Id, nil)
	if err != nil || !reflect.DeepEqual(reread.Detour, route) {
		t.Fatalf("GetOne after UpdateMany = %+v, %v; want detour %v", reread, err, route)
	}

	// The history rows hold each point as to_jsonb writes it, "(x,y)", and a
	// list as a JSON list of them.
	versions, err := db.Stop.ListVersions(ctx, id, nil)
	if err != nil {
		t.Fatalf("ListVersions: %v", err)
	}
	if len(versions) < 3 {
		t.Fatalf("ListVersions = %d versions, want at least 3", len(versions))
	}
	var nilDetour, emptyDetour, sqlDetour bool
	for _, version := range versions {
		if version.Value == nil || version.Value.At != sf || !reflect.DeepEqual(version.Value.Route, route) {
			t.Fatalf("version %d = %+v, want at %+v and route %v", version.Version, version.Value, sf, route)
		}
		switch {
		case version.Value.Detour == nil:
			nilDetour = true
		case len(version.Value.Detour) == 0:
			emptyDetour = true
		case reflect.DeepEqual(version.Value.Detour, detour):
			sqlDetour = true
		}
	}
	if !nilDetour || !emptyDetour || !sqlDetour {
		t.Fatalf("history detours: nil %v, empty %v, %v %v; want all three", nilDetour, emptyDetour, detour, sqlDetour)
	}
	latest, err := db.Stop.GetAsOf(ctx, id, time.Now().Add(time.Minute))
	if err != nil {
		t.Fatalf("GetAsOf: %v", err)
	}
	if latest.At != sf || latest.Dropoff == nil || *latest.Dropoff != sydney {
		t.Fatalf("GetAsOf = at %+v dropoff %v, want at %+v dropoff %+v", latest.At, latest.Dropoff, sf, sydney)
	}
	if !reflect.DeepEqual(latest.Route, route) || !reflect.DeepEqual(latest.Detour, detour) {
		t.Fatalf("GetAsOf = route %v detour %v, want route %v detour %v", latest.Route, latest.Detour, route, detour)
	}

	// A list element is never null: a NULL one written with SQL is refused
	// by the read and by the history decoder.
	if _, err := pool.Exec(ctx, "UPDATE stop SET detour = ARRAY[point(1, 2), NULL] WHERE id = $1", many[0].Id.ToUUID()); err != nil {
		t.Fatalf("write a NULL element with SQL: %v", err)
	}
	if _, err := db.Stop.GetOne(ctx, *many[0].Id, nil); err == nil || !strings.Contains(err.Error(), "detour[1]: null element") {
		t.Fatalf("GetOne of a NULL element = %v, want detour[1]: null element", err)
	}
	if _, err := db.Stop.ListVersions(ctx, *many[0].Id, nil); err == nil || !strings.Contains(err.Error(), "detour[1]: null element") {
		t.Fatalf("ListVersions of a NULL element = %v, want detour[1]: null element", err)
	}
}
`
