const geoStopsService = "geo-stops"

// geoStopsSchema is a versioned table with a required and an optional
// Geo.Location, which sqlgen stores as POINT columns.
const geoStopsSchema = `{
  "name": "geo-stops",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Temporal.DateTime": { "name": "Temporal.DateTime", "languagePrimitive": "string" },
    "Geo.Location": { "name": "Geo.Location", "languagePrimitive": "string" }
  },
  "types": {
    "Stop": {
      "name": "Stop",
      "role": "DBTable",
      "versioned": true,
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "at", "typeRef": { "name": "Geo.Location" }, "required": true },
        { "name": "dropoff", "typeRef": { "name": "Geo.Location" } },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "updatedAt", "typeRef": { "name": "Temporal.DateTime" } },
        { "name": "createdBy", "typeRef": { "name": "Identity.UUID" }, "required": true },
        { "name": "updatedBy", "typeRef": { "name": "Identity.UUID" }, "required": true }
      ]
    }
  }
}
`

// TestGeoLocationColumnsOnPostgres generates the Go types, the ORM and the
// DDL of geoStopsSchema, then builds, vets and tests the ORM module with
// geoLocationORMTest against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL. A Geo.Location column is a
// Postgres POINT, which is (x, y): x is lon and y is lat. The test writes
// locations through CreateOne, CreateMany and UpdateOne, reads the columns
// with SQL as point coordinates, writes a point with SQL and reads it back
// through GetOne, FindMany and the versioned history readers, whose rows
// to_jsonb writes with each point as "(x,y)" text.
func TestGeoLocationColumnsOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the Geo.Location columns against Postgres")
	}
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "geo-stops", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "stops.schema.json"), []byte(geoStopsSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", geoStopsService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + geoStopsService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", geoStopsService)
	ormDir := filepath.Join(tempRoot, "orm", geoStopsService)

	typesOutput, err := typegen.Generate(schema, typegen.Options{
		SchemaName: geoStopsService,
		ModulePath: typesModule,
		Clock:      fixedClock,
	})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatalf("set types replace paths: %v", err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatalf("write types: %v", err)
	}

	ormOutput, err := Generate(schema, Options{
		SchemaName:  geoStopsService,
		ModulePath:  "example.com/schemas/orm/" + geoStopsService,
		TypesModule: typesModule,
		Clock:       fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatalf("set orm replace paths: %v", err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatalf("write orm: %v", err)
	}

	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: geoStopsService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatalf("write ddl: %v", err)
	}
	createSQL, err := os.ReadFile(filepath.Join(ddlDir, "create.sql"))
	if err != nil {
		t.Fatal(err)
	}
	// POINT is a Postgres type of its own, so the DDL needs no PostGIS.
	if strings.Contains(string(createSQL), "postgis") {
		t.Fatalf("create.sql requires PostGIS for a POINT column:\n%s", createSQL)
	}
	for _, column := range []string{"at POINT NOT NULL,", "dropoff POINT,"} {
		if !strings.Contains(string(createSQL), column) {
			t.Fatalf("create.sql has no %s column:\n%s", column, createSQL)
		}
	}

	out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "geo_location_test.go", geoLocationORMTest)
	if !strings.Contains(out, "--- PASS: TestGeoLocationOnPostgres") {
		t.Fatal("the generated ORM module did not run TestGeoLocationOnPostgres")
	}
}

const geoLocationORMTest = `package orm

import (
	"context"
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
	types "example.com/schemas/types/go/geo-stops"
)

func TestGeoLocationOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	createSQL, err := os.ReadFile("testdata/create.sql")
	if err != nil {
		t.Fatalf("read create.sql: %v", err)
	}
	ctx := context.Background()
	base, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("connect: %v", err)
	}
	defer base.Close()
	schema := fmt.Sprintf("geo_stops_%d", time.Now().UnixNano())
	if _, err := base.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatalf("create schema: %v", err)
	}
	defer func() { _, _ = base.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE") }()
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parse database URL: %v", err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("connect schema pool: %v", err)
	}
	if _, err := pool.Exec(ctx, string(createSQL)); err != nil {
		pool.Close()
		t.Fatalf("apply create.sql: %v", err)
	}
	db, err := ConnectWithPool(pool)
	if err != nil {
		pool.Close()
		t.Fatalf("connect generated orm: %v", err)
	}
	defer db.Close()

	sf := types.GeoLocation{Lat: 37.7749, Lon: -122.4194}
	actor := types.NewUUID()
	ctx = WithUserID(ctx, actor)
	created, err := db.Stop.CreateOne(ctx, &types.Stop{At: sf, CreatedBy: actor, UpdatedBy: actor})
	if err != nil {
		t.Fatalf("CreateOne: %v", err)
	}
	id := *created.Id
	if created.At != sf || created.Dropoff != nil {
		t.Fatalf("CreateOne = %+v, want at %+v and no dropoff", created, sf)
	}

	// The column is a POINT whose x is lon and y is lat.
	var x, y float64
	if err := pool.QueryRow(ctx, "SELECT at[0], at[1] FROM stop WHERE id = $1", id.ToUUID()).Scan(&x, &y); err != nil {
		t.Fatalf("read the at point: %v", err)
	}
	if x != sf.Lon || y != sf.Lat {
		t.Fatalf("at point = (%v, %v), want (lon %v, lat %v)", x, y, sf.Lon, sf.Lat)
	}
	var dropoffNull bool
	if err := pool.QueryRow(ctx, "SELECT dropoff IS NULL FROM stop WHERE id = $1", id.ToUUID()).Scan(&dropoffNull); err != nil || !dropoffNull {
		t.Fatalf("an unset dropoff is stored as NULL: %v, %v", dropoffNull, err)
	}

	// {0, 0} is a location, stored and read back as one.
	zero := types.GeoLocation{}
	updated, err := db.Stop.UpdateOneIfVersion(ctx, id, created.Version, &StopUpdate{Dropoff: &zero, UpdatedBy: &actor})
	if err != nil {
		t.Fatalf("UpdateOneIfVersion: %v", err)
	}
	if updated.Dropoff == nil || *updated.Dropoff != zero {
		t.Fatalf("UpdateOneIfVersion dropoff = %v, want {0, 0}", updated.Dropoff)
	}

	// A point written with SQL reads back as lat = y, lon = x.
	if _, err := pool.Exec(ctx, "UPDATE stop SET dropoff = point(151.2093, -33.8688) WHERE id = $1", id.ToUUID()); err != nil {
		t.Fatalf("write a point with SQL: %v", err)
	}
	got, err := db.Stop.GetOne(ctx, id, nil)
	if err != nil {
		t.Fatalf("GetOne: %v", err)
	}
	sydney := types.GeoLocation{Lat: -33.8688, Lon: 151.2093}
	if got.At != sf || got.Dropoff == nil || *got.Dropoff != sydney {
		t.Fatalf("GetOne = at %+v dropoff %v, want at %+v dropoff %+v", got.At, got.Dropoff, sf, sydney)
	}

	many, err := db.Stop.CreateMany(ctx, []*types.Stop{
		{At: types.GeoLocation{Lat: 90, Lon: -180}, CreatedBy: actor, UpdatedBy: actor},
		{At: types.GeoLocation{Lat: -90, Lon: 180}, Dropoff: &sydney, CreatedBy: actor, UpdatedBy: actor},
	})
	if err != nil {
		t.Fatalf("CreateMany: %v", err)
	}
	if many[0].At != (types.GeoLocation{Lat: 90, Lon: -180}) || many[1].Dropoff == nil || *many[1].Dropoff != sydney {
		t.Fatalf("CreateMany = %+v, %+v", many[0], many[1])
	}
	all, total, err := db.Stop.FindMany(ctx, nil, &StopFindOptions{Fields: StopFields{}.All()})
	if err != nil || total != 3 || len(all) != 3 {
		t.Fatalf("FindMany = %d rows (total %d), %v; want 3", len(all), total, err)
	}

	// The history rows hold each point as to_jsonb writes it, "(x,y)".
	versions, err := db.Stop.ListVersions(ctx, id, nil)
	if err != nil {
		t.Fatalf("ListVersions: %v", err)
	}
	if len(versions) < 2 {
		t.Fatalf("ListVersions = %d versions, want at least 2", len(versions))
	}
	for _, version := range versions {
		if version.Value == nil || version.Value.At != sf {
			t.Fatalf("version %d at = %+v, want %+v", version.Version, version.Value, sf)
		}
	}
	latest, err := db.Stop.GetAsOf(ctx, id, time.Now().Add(time.Minute))
	if err != nil {
		t.Fatalf("GetAsOf: %v", err)
	}
	if latest.At != sf || latest.Dropoff == nil || *latest.Dropoff != sydney {
		t.Fatalf("GetAsOf = at %+v dropoff %v, want at %+v dropoff %+v", latest.At, latest.Dropoff, sf, sydney)
	}
}
`
