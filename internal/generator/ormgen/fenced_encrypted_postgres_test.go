const fencedVaultService = "fenced-vault"

// fencedVaultSchema is a table whose fence covers an Encrypted<T> field
// (D85, D118): a write of the secret advances rotation, and a write of the
// label alone does not.
const fencedVaultSchema = `{
  "name": "fenced-vault",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Generic.Int64": { "name": "Generic.Int64", "languagePrimitive": "number" }
  },
  "types": {
    "Credential": {
      "name": "Credential",
      "role": "DBTable",
      "fences": [{ "field": "rotation", "covers": ["secret"] }],
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "service", "typeRef": { "name": "string" }, "required": true, "unique": true },
        { "name": "secret", "typeRef": { "name": "string" }, "required": true, "encryptedAtRest": true },
        { "name": "label", "typeRef": { "name": "string" }, "required": true },
        { "name": "rotation", "typeRef": { "name": "Generic.Int64" }, "required": true, "default": "0" }
      ]
    }
  }
}
`

// TestFenceOverAnEncryptedFieldOnPostgres generates the ORM module of
// fencedVaultSchema, then builds, vets and tests it. Its generated test,
// against the Postgres at SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL (it skips
// without the database), holds the writes of an encrypted field to the
// fence that covers it (D118), under the fence's trigger: an update of the
// secret advances rotation by one; an upsert's second statement, which
// sets the secret sealed under the key of the row it updates (D89), is an
// UpdateOne and advances it as one; and Reencrypt's reseal, whose columns
// are fixed, carries the bump in its statement, once for a row it reseals
// and not at all for a row the current key sealed.
func TestFenceOverAnEncryptedFieldOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	config := `{"name": "fenced-vault", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}, "sql": {"encryption": {"key": "VaultKeys.VAULT_DB_FIELD_KEYS"}}}}`
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(config), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "vault.schema.json"), []byte(fencedVaultSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	ormDir := generateORMModuleAt(t, serviceDir, fencedVaultService)
	if err := os.WriteFile(filepath.Join(ormDir, "fenced_vault_test.go"), []byte(fencedVaultORMTest), 0o644); err != nil {
		t.Fatalf("write the test: %v", err)
	}
	out := runORMModule(t, ormDir)
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") != "" && !strings.Contains(out, "--- PASS: TestFenceOverAnEncryptedFieldOnPostgres") {
		t.Fatalf("the generated ORM did not run TestFenceOverAnEncryptedFieldOnPostgres:\n%s", out)
	}
}

