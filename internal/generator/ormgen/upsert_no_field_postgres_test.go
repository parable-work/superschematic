const noFieldUpsertService = "no-field-upserts"

// noFieldUpsertSchema is a versioned table, whose updates move its version
// and record history, keyed by a unique handle and by a unique index over
// lower(email), an expression.
const noFieldUpsertSchema = `{
  "name": "no-field-upserts",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Temporal.DateTime": { "name": "Temporal.DateTime", "languagePrimitive": "string" }
  },
  "types": {
    "Account": {
      "name": "Account",
      "role": "DBTable",
      "versioned": true,
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "handle", "typeRef": { "name": "string" }, "required": true, "unique": true },
        { "name": "email", "typeRef": { "name": "string" }, "required": true },
        { "name": "name", "typeRef": { "name": "string" }, "required": true },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "updatedAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true }
      ],
      "indexes": [{ "keys": ["email"], "unique": true, "expression": "lower(email)" }]
    }
  }
}
`

// TestNoFieldUpsertsOnPostgres generates the ORM module of
// noFieldUpsertSchema, then builds, vets and tests it. Its generated test,
// against the Postgres at SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL (it skips
// without the database), upserts held keys with updates that set no field,
// by the handle, by lower(email) and many at once: each returns the held
// row unchanged and leaves its version, its stamp and its history as they
// were (D79). An update that sets a field still moves the version once.
func TestNoFieldUpsertsOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "no-field-upserts", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "accounts.schema.json"), []byte(noFieldUpsertSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	ormDir := generateORMModuleAt(t, serviceDir, noFieldUpsertService)
	if err := os.WriteFile(filepath.Join(ormDir, "no_field_upserts_test.go"), []byte(noFieldUpsertsORMTest), 0o644); err != nil {
		t.Fatalf("write upsert test: %v", err)
	}
	out := runORMModule(t, ormDir)
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") != "" && !strings.Contains(out, "--- PASS: TestNoFieldUpsertsOnPostgres") {
		t.Fatalf("the generated ORM did not run TestNoFieldUpsertsOnPostgres:\n%s", out)
	}
}

