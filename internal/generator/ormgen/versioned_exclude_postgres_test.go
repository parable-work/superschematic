// TestVersionedExcludeAndOptimisticOnPostgres generates the Go types, the
// ORM and the DDL of excludeOptimisticSchema, then builds, vets and tests
// the ORM module with excludeOptimisticORMTest against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL: the excluded columns are absent
// from every INSERT, UPDATE and DELETE history image and read back as zero
// values, and an @optimistic table bumps _version and fences its writes
// with no history table.
func TestVersionedExcludeAndOptimisticOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the excluded history and the optimistic fences against Postgres")
	}
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "exclude-optimistic-recipes", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "recipes.schema.json"), []byte(excludeOptimisticSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", excludeOptimisticService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + excludeOptimisticService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", excludeOptimisticService)
	ormDir := filepath.Join(tempRoot, "orm", excludeOptimisticService)

	typesOutput, err := typegen.Generate(schema, typegen.Options{
		SchemaName: excludeOptimisticService,
		ModulePath: typesModule,
		Clock:      fixedClock,
	})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatalf("set types replace paths: %v", err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatalf("write types: %v", err)
	}

	ormOutput, err := Generate(schema, Options{
		SchemaName:  excludeOptimisticService,
		ModulePath:  "example.com/schemas/orm/" + excludeOptimisticService,
		TypesModule: typesModule,
		Clock:       fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatalf("set orm replace paths: %v", err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatalf("write orm: %v", err)
	}

	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: excludeOptimisticService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatalf("write ddl: %v", err)
	}

	out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "exclude_optimistic_test.go", excludeOptimisticORMTest)
	for _, name := range []string{"TestExcludedHistoryColumnsOnPostgres", "TestOptimisticFencesOnPostgres"} {
		if !strings.Contains(out, "--- PASS: "+name) {
			t.Fatalf("the generated ORM module did not run %s", name)
		}
	}
}

