// TestOwnSelectionOnPostgres generates the types, the ORM and the DDL of
// ownSelectionSchema under both values of go.orm_default_selection and
// runs ownSelectionORMTest in each ORM module against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL (D164). A relation selected
// without a nested selection reads the target's All under "all", so the
// store's region is read too, and the target's Own under "own", so the
// region is an id-only stub. A nested selection without Id still finds
// its row under "own".
func TestOwnSelectionOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the default selection against Postgres")
	}
	paths := testpaths.Local(t)
	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "own-selection", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "orders.schema.json"), []byte(ownSelectionSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", ownSelectionService, err)
	}
	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: ownSelectionService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatal(err)
	}

	for selection, wantRegionName := range map[string]string{naming.GoSelectAll: "north", naming.GoSelectOwn: ""} {
		t.Run(selection, func(t *testing.T) {
			n := naming.Naming{Go: naming.GoConfig{ORMDefaultSelection: selection}}
			typesModule := "example.com/schemas/types/go/" + ownSelectionService
			root := t.TempDir()
			typesDir := filepath.Join(root, "types", "go", ownSelectionService)
			ormDir := filepath.Join(root, "orm", ownSelectionService)
			typesOutput, err := typegen.Generate(schema, typegen.Options{SchemaName: ownSelectionService, ModulePath: typesModule, Naming: n, Clock: fixedClock})
			if err != nil {
				t.Fatal(err)
			}
			if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
				t.Fatal(err)
			}
			if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
				t.Fatal(err)
			}
			ormOutput, err := Generate(schema, Options{
				SchemaName: ownSelectionService, ModulePath: "example.com/schemas/orm/" + ownSelectionService, TypesModule: typesModule, Naming: n, Clock: fixedClock,
			})
			if err != nil {
				t.Fatal(err)
			}
			if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
				t.Fatal(err)
			}
			if err := WriteORM(ormOutput, ormDir); err != nil {
				t.Fatal(err)
			}
			code := strings.ReplaceAll(ownSelectionORMTest, "WANT_REGION_NAME", `"`+wantRegionName+`"`)
			code = strings.Replace(code, "OWN_ONLY", map[string]string{naming.GoSelectAll: "false", naming.GoSelectOwn: "true"}[selection], 1)
			if selection == naming.GoSelectOwn {
				code += ownSelectionOwnOnlyTest
			}
			out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "own_selection_test.go", code)
			if !strings.Contains(out, "--- PASS: TestDefaultSelectionOnPostgres") {
				t.Fatal("the generated ORM module did not run TestDefaultSelectionOnPostgres")
			}
		})
	}
}

const ownSelectionORMTest = `package orm

import (
	"context"
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
	types "example.com/schemas/types/go/own-selection"
)

func openOwnSelection(t *testing.T) (*Database, context.Context) {
	t.Helper()
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	createSQL, err := os.ReadFile("testdata/create.sql")
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	base, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(base.Close)
	schema := fmt.Sprintf("own_selection_%d", time.Now().UnixNano())
	if _, err := base.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _, _ = base.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE") })
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pool.Exec(ctx, string(createSQL)); err != nil {
		pool.Close()
		t.Fatal(err)
	}
	db, err := ConnectWithPool(pool)
	if err != nil {
		pool.Close()
		t.Fatal(err)
	}
	t.Cleanup(db.Close)
	return db, ctx
}

func seedOwnSelection(t *testing.T, db *Database, ctx context.Context) *types.Order {
	t.Helper()
	region, err := db.Region.CreateOne(ctx, &types.Region{Name: "north"})
	if err != nil {
		t.Fatal(err)
	}
	store, err := db.Store.CreateOne(ctx, &types.Store{Name: "main", Region: *region})
	if err != nil {
		t.Fatal(err)
	}
	order, err := db.Order.CreateOne(ctx, &types.Order{Label: "first", Store: *store})
	if err != nil {
		t.Fatal(err)
	}
	return order
}

func TestDefaultSelectionOnPostgres(t *testing.T) {
	db, ctx := openOwnSelection(t)
	order := seedOwnSelection(t, db, ctx)
	read, err := db.Order.GetOne(ctx, *order.Id, &OrderGetOptions{Fields: OrderFields{Id: true, Label: true, Store: true}})
	if err != nil {
		t.Fatal(err)
	}
	if read.Store.Name != "main" || read.Store.Region.Id == nil {
		t.Fatalf("store = %+v, want its columns and its region's id", read.Store)
	}
	if read.Store.Region.Name != WANT_REGION_NAME {
		t.Fatalf("the store's region name = %q, want %q (own only: %v)", read.Store.Region.Name, WANT_REGION_NAME, OWN_ONLY)
	}
	many, _, err := db.Order.FindMany(ctx, nil, &OrderFindOptions{Fields: OrderFields{Id: true, Store: true}})
	if err != nil {
		t.Fatal(err)
	}
	if len(many) != 1 || many[0].Store.Name != "main" || many[0].Store.Region.Name != WANT_REGION_NAME {
		t.Fatalf("FindMany = %+v, want the store and a region name of %q", many, WANT_REGION_NAME)
	}
}
`

// ownSelectionOwnOnlyTest runs under "own" only: Own is a method there.
const ownSelectionOwnOnlyTest = `
func TestOwnNamesTheColumnsAndStubsTheRelations(t *testing.T) {
	if got := (StoreFields{}).Own(); !got.Id || !got.Name || got.Region || got.RegionNested != (RegionFields{Id: true}) {
		t.Fatalf("StoreFields.Own() = %+v", got)
	}
	db, ctx := openOwnSelection(t)
	order := seedOwnSelection(t, db, ctx)
	// A nested selection without Id still finds its row.
	read, err := db.Order.GetOne(ctx, *order.Id, &OrderGetOptions{Fields: OrderFields{Id: true, StoreNested: StoreFields{Name: true}}})
	if err != nil {
		t.Fatal(err)
	}
	if read.Store.Name != "main" {
		t.Fatalf("store = %+v, want its name", read.Store)
	}
}
`
