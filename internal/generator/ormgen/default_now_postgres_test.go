const ledgerLinesService = "ledger-lines"

// ledgerLinesSchema is a ledger line with a posting time that has no
// default, a day it was entered on and a time it was recorded at, each
// declared Default<T, "now">, and the audit createdAt (D88).
const ledgerLinesSchema = `{
  "name": "ledger-lines",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Temporal.DateTime": { "name": "Temporal.DateTime", "languagePrimitive": "string" },
    "Temporal.Date": { "name": "Temporal.Date", "languagePrimitive": "string" }
  },
  "types": {
    "Line": {
      "name": "Line",
      "role": "DBTable",
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "postedAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "enteredOn", "typeRef": { "name": "Temporal.Date" }, "required": true, "default": "now" },
        { "name": "recordedAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true, "default": "now" },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true }
      ]
    }
  }
}
`

// TestDefaultNowOnPostgres generates the Go types, the ORM and the DDL of
// ledgerLinesSchema and runs defaultNowORMTest in the ORM module against
// the Postgres at SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL (D88): the DDL
// gives enteredOn, recordedAt and createdAt the time of the insert and
// postedAt no default, and the ORM's CreateOne and CreateMany leave a
// Default<T, "now"> field the input leaves zero to the database, and write
// one it sets.
func TestDefaultNowOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run Default<T, \"now\"> against Postgres")
	}
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "ledger-lines", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "lines.schema.json"), []byte(ledgerLinesSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", ledgerLinesService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + ledgerLinesService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", ledgerLinesService)
	ormDir := filepath.Join(tempRoot, "orm", ledgerLinesService)
	typesOutput, err := typegen.Generate(schema, typegen.Options{SchemaName: ledgerLinesService, ModulePath: typesModule, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatal(err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatal(err)
	}
	ormOutput, err := Generate(schema, Options{
		SchemaName: ledgerLinesService, ModulePath: "example.com/schemas/orm/" + ledgerLinesService, TypesModule: typesModule, Clock: fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatal(err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatal(err)
	}
	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: ledgerLinesService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatal(err)
	}
	createSQL, err := os.ReadFile(filepath.Join(ddlDir, "create.sql"))
	if err != nil {
		t.Fatal(err)
	}
	for _, column := range []string{"posted_at TIMESTAMPTZ NOT NULL,", "entered_on DATE DEFAULT CURRENT_DATE NOT NULL,", "recorded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,", "created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL"} {
		if !strings.Contains(string(createSQL), column) {
			t.Fatalf("create.sql has no %s column:\n%s", column, createSQL)
		}
	}

	out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "default_now_test.go", defaultNowORMTest)
	if !strings.Contains(out, "--- PASS: TestDefaultNowOnPostgres") {
		t.Fatal("the generated ORM module did not run TestDefaultNowOnPostgres")
	}
}

const defaultNowORMTest = `package orm

import (
	"context"
	"errors"
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
	types "example.com/schemas/types/go/ledger-lines"
)

func TestDefaultNowOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	createSQL, err := os.ReadFile("testdata/create.sql")
	if err != nil {
		t.Fatal(err)
	}
	ctx := context.Background()
	base, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatal(err)
	}
	defer base.Close()
	schema := fmt.Sprintf("ledger_lines_%d", time.Now().UnixNano())
	if _, err := base.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatal(err)
	}
	defer func() { _, _ = base.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE") }()
	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pool.Exec(ctx, string(createSQL)); err != nil {
		pool.Close()
		t.Fatal(err)
	}
	db, err := ConnectWithPool(pool)
	if err != nil {
		pool.Close()
		t.Fatal(err)
	}
	defer db.Close()

	// stamped reads whether the database gave a line's enteredOn and
	// recordedAt the time of its insert.
	stamped := func(id types.IdentityUUID) bool {
		t.Helper()
		var ok bool
		if err := pool.QueryRow(ctx, "SELECT entered_on = CURRENT_DATE AND recorded_at > now() - interval '1 minute' AND created_at > now() - interval '1 minute' FROM line WHERE id = $1", id.ToUUID()).Scan(&ok); err != nil {
			t.Fatal(err)
		}
		return ok
	}
	posted := types.TemporalDateTime(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))

	left, err := db.Line.CreateOne(ctx, &types.Line{PostedAt: posted})
	if err != nil {
		t.Fatalf("CreateOne leaving enteredOn and recordedAt unset: %v", err)
	}
	if !stamped(*left.Id) || time.Time(left.RecordedAt).IsZero() || left.EnteredOn == "" {
		t.Fatalf("the database did not stamp a line created without them: %+v", left)
	}

	recorded := types.TemporalDateTime(time.Date(2025, 6, 7, 8, 9, 10, 0, time.UTC))
	set, err := db.Line.CreateOne(ctx, &types.Line{PostedAt: posted, EnteredOn: "2025-06-07", RecordedAt: recorded})
	if err != nil {
		t.Fatalf("CreateOne setting them: %v", err)
	}
	if string(set.EnteredOn) != "2025-06-07" || !time.Time(set.RecordedAt).Equal(time.Time(recorded)) {
		t.Fatalf("a line created with enteredOn and recordedAt read back %+v", set)
	}

	many, err := db.Line.CreateMany(ctx, []*types.Line{{PostedAt: posted}, {PostedAt: posted, EnteredOn: "2025-06-07", RecordedAt: recorded}})
	if err != nil {
		t.Fatalf("CreateMany: %v", err)
	}
	if len(many) != 2 || !stamped(*many[0].Id) || string(many[1].EnteredOn) != "2025-06-07" || !time.Time(many[1].RecordedAt).Equal(time.Time(recorded)) {
		t.Fatalf("CreateMany read back %+v and %+v", many[0], many[1])
	}

	_, err = pool.Exec(ctx, "INSERT INTO line (entered_on) VALUES (CURRENT_DATE)")
	var pgErr *pgconn.PgError
	if !errors.As(err, &pgErr) || pgErr.Code != "23502" || pgErr.ColumnName != "posted_at" {
		t.Fatalf("a raw insert without posted_at: %v, want a not-null violation on posted_at", err)
	}
}
`
