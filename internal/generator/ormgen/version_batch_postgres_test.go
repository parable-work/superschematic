// TestVersionBatchReadsOnPostgres generates the Go types, the ORM and the
// DDL of versionBatchSchema, then builds, vets and tests the ORM module
// with versionBatchORMTest against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL (D166): GetVersions answers each
// key as GetVersion does, in key order, with nil for a missing version and
// a delete tombstone, for a UUID, a string and an integer key, and
// GetVersionsWithFields reads only the selected fields and refuses an
// empty selection and a nested one.
func TestVersionBatchReadsOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the batch history reads against Postgres")
	}
	ormDir, createSQL := generateVersionBatchModule(t)
	out := runGeneratedORMModule(t, ormDir, createSQL, "version_batch_test.go", versionBatchORMTest)
	for _, name := range []string{"TestGetVersionsOnPostgres", "TestGetVersionsWithFieldsOnPostgres", "TestGetVersionsOfOtherKeysOnPostgres"} {
		if !strings.Contains(out, "--- PASS: "+name) {
			t.Fatalf("the generated ORM module did not run %s", name)
		}
	}
}

// generateVersionBatchModule writes the Go types and the ORM of
// versionBatchSchema into a temporary tree, and its DDL beside them. It
// returns the ORM module's directory and the path of create.sql.
func generateVersionBatchModule(t *testing.T) (string, string) {
	t.Helper()
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "version-batch-recipes", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "recipes.schema.json"), []byte(versionBatchSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", versionBatchService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + versionBatchService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", versionBatchService)
	ormDir := filepath.Join(tempRoot, "orm", versionBatchService)

	typesOutput, err := typegen.Generate(schema, typegen.Options{
		SchemaName: versionBatchService,
		ModulePath: typesModule,
		Clock:      fixedClock,
	})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatalf("set types replace paths: %v", err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatalf("write types: %v", err)
	}

	ormOutput, err := Generate(schema, Options{
		SchemaName:  versionBatchService,
		ModulePath:  "example.com/schemas/orm/" + versionBatchService,
		TypesModule: typesModule,
		Clock:       fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatalf("set orm replace paths: %v", err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatalf("write orm: %v", err)
	}

	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: versionBatchService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatalf("write ddl: %v", err)
	}
	return ormDir, filepath.Join(ddlDir, "create.sql")
}

