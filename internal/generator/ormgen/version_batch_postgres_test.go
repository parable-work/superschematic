// recipeVersions is a kitchen, a recipe at three versions, and a recipe
// deleted at its second, whose version 2 is a tombstone.
type recipeVersions struct {
	kitchen types.IdentityUUID
	bread   types.IdentityUUID
	soup    types.IdentityUUID
}

func writeRecipeVersions(t *testing.T, ctx context.Context, db *Database) recipeVersions {
	t.Helper()
	kitchen, err := db.Kitchen.CreateOne(ctx, &types.Kitchen{Name: "Bakery"})
	if err != nil {
		t.Fatalf("create the kitchen: %v", err)
	}
	bread, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Bread", Servings: 2, Note: "warm", Kitchen: &types.Kitchen{Id: kitchen.Id}})
	if err != nil {
		t.Fatalf("create bread: %v", err)
	}
	rye, cold := "Rye", "cold"
	if _, err := db.Recipe.UpdateOne(ctx, *bread.Id, &RecipeUpdate{Title: &rye}); err != nil {
		t.Fatalf("update bread to version 2: %v", err)
	}
	if _, err := db.Recipe.UpdateOne(ctx, *bread.Id, &RecipeUpdate{Note: &cold}); err != nil {
		t.Fatalf("update bread to version 3: %v", err)
	}
	soup, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Soup", Servings: 4})
	if err != nil {
		t.Fatalf("create soup: %v", err)
	}
	if err := db.Recipe.DeleteOne(ctx, *soup.Id); err != nil {
		t.Fatalf("delete soup: %v", err)
	}
	return recipeVersions{kitchen: *kitchen.Id, bread: *bread.Id, soup: *soup.Id}
}

// mixedKeys are keys out of version order: bread at 2, soup at 1, bread at
// 1, a missing row, a missing version, soup's tombstone, and bread at 2
// again.
func mixedKeys(t *testing.T, v recipeVersions) []VersionKey[types.IdentityUUID] {
	missing := mustUUID(t, "00000000-0000-4000-8000-00000000dead")
	return []VersionKey[types.IdentityUUID]{
		{ID: v.bread, Version: 2},
		{ID: v.soup, Version: 1},
		{ID: v.bread, Version: 1},
		{ID: missing, Version: 1},
		{ID: v.bread, Version: 9},
		{ID: v.soup, Version: 2},
		{ID: v.bread, Version: 2},
	}
}

func TestGetVersionsOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	db, _ := openRecipesDatabase(t, dsn)
	ctx := WithUserID(context.Background(), mustUUID(t, "00000000-0000-4000-8000-0000000000a1"))
	v := writeRecipeVersions(t, ctx, db)
	keys := mixedKeys(t, v)

	// Each entry is what GetVersion returns for its key, nil where it
	// returns ErrNotFound, through the pool, a transaction and the
	// read-only interface.
	check := func(label string, got []*types.Recipe) {
		t.Helper()
		if len(got) != len(keys) {
			t.Fatalf("%s returned %d entries, want %d", label, len(got), len(keys))
		}
		for i, key := range keys {
			want, err := db.Recipe.GetVersion(ctx, key.ID, key.Version)
			if errors.Is(err, ErrNotFound) {
				want = nil
			} else if err != nil {
				t.Fatalf("GetVersion(%d): %v", i, err)
			}
			if !reflect.DeepEqual(got[i], want) {
				t.Fatalf("%s entry %d = %+v, want %+v", label, i, got[i], want)
			}
		}
		if got[0] == nil || got[0].Title != "Rye" || got[0].Note != "warm" || got[0].Version != 2 {
			t.Fatalf("%s entry 0 = %+v, want bread at version 2 (Rye, warm)", label, got[0])
		}
		if got[1] == nil || got[1].Title != "Soup" || got[2] == nil || got[2].Title != "Bread" {
			t.Fatalf("%s entries 1 and 2 = %+v, %+v; want soup and bread at version 1", label, got[1], got[2])
		}
		if got[3] != nil || got[4] != nil || got[5] != nil {
			t.Fatalf("%s entries 3 to 5 = %+v, %+v, %+v; want nil for a missing row, a missing version and a tombstone", label, got[3], got[4], got[5])
		}
		if got[6] == got[0] || !reflect.DeepEqual(got[6], got[0]) {
			t.Fatalf("%s entry 6 = %p, want its own copy of entry 0", label, got[6])
		}
		if got[0].Kitchen == nil || got[0].Kitchen.Id == nil || *got[0].Kitchen.Id != v.kitchen || got[0].Kitchen.Name != "" {
			t.Fatalf("%s entry 0's kitchen = %+v, want the stored key %s and no row", label, got[0].Kitchen, v.kitchen.ToUUID())
		}
	}

	got, err := db.Recipe.GetVersions(ctx, keys)
	if err != nil {
		t.Fatalf("GetVersions: %v", err)
	}
	check("GetVersions", got)

	if err := db.Transaction(ctx, func(tx TxInterface) error {
		got, err := tx.GetRecipeRepository().GetVersions(ctx, keys)
		if err != nil {
			return err
		}
		check("GetVersions in a transaction", got)
		return nil
	}); err != nil {
		t.Fatalf("Transaction: %v", err)
	}

	got, err = db.ReadOnly().GetRecipeReadOnlyRepository().GetVersions(ctx, keys)
	if err != nil {
		t.Fatalf("read-only GetVersions: %v", err)
	}
	check("read-only GetVersions", got)

	// No keys is an empty result, and the no-op repository answers nil
	// for every key.
	none, err := db.Recipe.GetVersions(ctx, nil)
	if err != nil || none == nil || len(none) != 0 {
		t.Fatalf("GetVersions(nil) = %v, %v; want an empty result", none, err)
	}
	noop, err := NewNoOpDatabase().GetRecipeRepository().GetVersions(ctx, keys)
	if err != nil || len(noop) != len(keys) {
		t.Fatalf("no-op GetVersions = %d entries, %v; want %d", len(noop), err, len(keys))
	}
	for i, value := range noop {
		if value != nil {
			t.Fatalf("no-op GetVersions entry %d = %+v, want nil", i, value)
		}
	}
}

func TestGetVersionsWithFieldsOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	db, _ := openRecipesDatabase(t, dsn)
	ctx := WithUserID(context.Background(), mustUUID(t, "00000000-0000-4000-8000-0000000000a1"))
	v := writeRecipeVersions(t, ctx, db)
	keys := mixedKeys(t, v)

	// Title and the kitchen's key, and nothing else.
	got, err := db.Recipe.GetVersionsWithFields(ctx, keys, RecipeFields{Title: true, Kitchen: true})
	if err != nil {
		t.Fatalf("GetVersionsWithFields: %v", err)
	}
	if len(got) != len(keys) {
		t.Fatalf("GetVersionsWithFields returned %d entries, want %d", len(got), len(keys))
	}
	wantTitles := []string{"Rye", "Soup", "Bread", "", "", "", "Rye"}
	for i, title := range wantTitles {
		if title == "" {
			if got[i] != nil {
				t.Fatalf("entry %d = %+v, want nil", i, got[i])
			}
			continue
		}
		if got[i] == nil || got[i].Title != title {
			t.Fatalf("entry %d = %+v, want title %q", i, got[i], title)
		}
		if got[i].Note != "" || got[i].Servings != 0 || got[i].Id != nil || got[i].Version != 0 {
			t.Fatalf("entry %d = %+v, want only the title and the kitchen", i, got[i])
		}
	}
	if got[0].Kitchen == nil || *got[0].Kitchen.Id != v.kitchen || got[1].Kitchen != nil {
		t.Fatalf("kitchens = %+v, %+v; want bread's stored key and none for soup", got[0].Kitchen, got[1].Kitchen)
	}

	// The read-only interface and the no-op repository have it too.
	if _, err := db.ReadOnly().GetRecipeReadOnlyRepository().GetVersionsWithFields(ctx, keys, RecipeFields{Note: true}); err != nil {
		t.Fatalf("read-only GetVersionsWithFields: %v", err)
	}
	noop, err := NewNoOpDatabase().GetRecipeRepository().GetVersionsWithFields(ctx, keys, RecipeFields{Title: true})
	if err != nil || len(noop) != len(keys) || noop[0] != nil {
		t.Fatalf("no-op GetVersionsWithFields = %v, %v; want %d nil entries", noop, err, len(keys))
	}

	// An empty selection and a nested one are refused.
	if _, err := db.Recipe.GetVersionsWithFields(ctx, keys, RecipeFields{}); err == nil {
		t.Fatal("GetVersionsWithFields with no field returned no error")
	}
	if _, err := db.Recipe.GetVersionsWithFields(ctx, keys, RecipeFields{Title: true, KitchenNested: KitchenFields{Name: true}}); err == nil {
		t.Fatal("GetVersionsWithFields with a nested selection returned no error")
	}
}

func TestGetVersionsOfOtherKeysOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	db, pool := openRecipesDatabase(t, dsn)
	ctx := WithUserID(context.Background(), mustUUID(t, "00000000-0000-4000-8000-0000000000a1"))

	// A string key. The rows are inserted with SQL, since CreateOne leaves
	// out a key it does not generate; the history trigger records them.
	if _, err := pool.Exec(ctx, "INSERT INTO label (code, name) VALUES ('flour', 'Flour')"); err != nil {
		t.Fatalf("insert the label: %v", err)
	}
	wholemeal := "Wholemeal flour"
	if _, err := db.Label.UpdateOne(ctx, "flour", &LabelUpdate{Name: &wholemeal}); err != nil {
		t.Fatalf("update the label: %v", err)
	}
	labels, err := db.Label.GetVersions(ctx, []VersionKey[string]{{ID: "flour", Version: 2}, {ID: "salt", Version: 1}, {ID: "flour", Version: 1}})
	if err != nil {
		t.Fatalf("Label.GetVersions: %v", err)
	}
	if len(labels) != 3 || labels[0] == nil || labels[0].Name != wholemeal || labels[1] != nil || labels[2] == nil || labels[2].Name != "Flour" {
		t.Fatalf("Label.GetVersions = %+v, want (Wholemeal flour, nil, Flour)", labels)
	}

	// An integer key.
	if _, err := pool.Exec(ctx, "INSERT INTO batch (number, name) VALUES (7, 'Morning')"); err != nil {
		t.Fatalf("insert the batch: %v", err)
	}
	if err := db.Batch.DeleteOne(ctx, 7); err != nil {
		t.Fatalf("delete the batch: %v", err)
	}
	batches, err := db.Batch.GetVersionsWithFields(ctx, []VersionKey[types.GenericInt64]{{ID: 7, Version: 2}, {ID: 7, Version: 1}, {ID: 8, Version: 1}}, BatchFields{Name: true})
	if err != nil {
		t.Fatalf("Batch.GetVersionsWithFields: %v", err)
	}
	if len(batches) != 3 || batches[0] != nil || batches[1] == nil || batches[1].Name != "Morning" || batches[1].Number != 0 || batches[2] != nil {
		t.Fatalf("Batch.GetVersionsWithFields = %+v, want (nil, Morning without its number, nil)", batches)
	}
}
