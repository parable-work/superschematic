const recipesVersionedService = "versioned-recipes"

// recipesVersionedSchema is a small versioned schema. A recipe has no
// deletedAt, so its deletes are hard, and its updatedBy is the actor its
// delete tombstones record. A step has deletedAt and deletedBy, so its
// deletes are soft and deletedBy is the tombstone actor of a hard delete.
const recipesVersionedSchema = `{
  "name": "versioned-recipes",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": { "name": "Identity.UUID", "languagePrimitive": "string" },
    "Temporal.DateTime": { "name": "Temporal.DateTime", "languagePrimitive": "string" }
  },
  "types": {
    "Recipe": {
      "name": "Recipe",
      "role": "DBTable",
      "versioned": true,
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "title", "typeRef": { "name": "string" }, "required": true },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "updatedAt", "typeRef": { "name": "Temporal.DateTime" } },
        { "name": "createdBy", "typeRef": { "name": "Identity.UUID" }, "required": true },
        { "name": "updatedBy", "typeRef": { "name": "Identity.UUID" }, "required": true }
      ]
    },
    "Step": {
      "name": "Step",
      "role": "DBTable",
      "versioned": true,
      "fields": [
        { "name": "id", "typeRef": { "name": "Identity.UUID" }, "required": true, "key": true, "autoGenerated": true },
        { "name": "recipe", "typeRef": { "name": "Recipe" }, "required": true, "relation": { "type": "Recipe", "onDelete": "RESTRICT" } },
        { "name": "instruction", "typeRef": { "name": "string" }, "required": true },
        { "name": "createdAt", "typeRef": { "name": "Temporal.DateTime" }, "required": true },
        { "name": "deletedAt", "typeRef": { "name": "Temporal.DateTime" } },
        { "name": "deletedBy", "typeRef": { "name": "Identity.UUID" } }
      ]
    }
  }
}
`

// TestVersionedWritesOnPostgres generates the Go types, the ORM and the DDL
// of recipesVersionedSchema, then builds, vets and tests the ORM module with
// versionedWritesORMTest, which runs against the Postgres at
// SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL: the history an upsert, a fenced
// update and fenced deletes write, the actor a hard delete's tombstone
// records, and what the history readers return after a delete.
func TestVersionedWritesOnPostgres(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	if os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL") == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the versioned writes against Postgres")
	}
	paths := testpaths.Local(t)

	serviceDir := t.TempDir()
	if err := os.MkdirAll(filepath.Join(serviceDir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "schema.config.json"), []byte(`{"name": "versioned-recipes", "kind": "DB", "outputs": {"types": {"go": {"enabled": true}}}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(serviceDir, "src", "recipes.schema.json"), []byte(recipesVersionedSchema), 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(serviceDir)
	if err != nil {
		t.Fatalf("load %s: %v", recipesVersionedService, err)
	}

	fixedClock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	typesModule := "example.com/schemas/types/go/" + recipesVersionedService
	tempRoot := t.TempDir()
	typesDir := filepath.Join(tempRoot, "types", "go", recipesVersionedService)
	ormDir := filepath.Join(tempRoot, "orm", recipesVersionedService)

	typesOutput, err := typegen.Generate(schema, typegen.Options{
		SchemaName: recipesVersionedService,
		ModulePath: typesModule,
		Clock:      fixedClock,
	})
	if err != nil {
		t.Fatalf("generate types: %v", err)
	}
	if err := typegen.SetReplacePaths(typesOutput, paths, typesDir); err != nil {
		t.Fatalf("set types replace paths: %v", err)
	}
	if err := typegen.WriteTypes(typesOutput, typesDir); err != nil {
		t.Fatalf("write types: %v", err)
	}

	ormOutput, err := Generate(schema, Options{
		SchemaName:  recipesVersionedService,
		ModulePath:  "example.com/schemas/orm/" + recipesVersionedService,
		TypesModule: typesModule,
		Clock:       fixedClock,
	})
	if err != nil {
		t.Fatalf("generate orm: %v", err)
	}
	if err := SetReplacePaths(ormOutput, paths, ormDir); err != nil {
		t.Fatalf("set orm replace paths: %v", err)
	}
	if err := WriteORM(ormOutput, ormDir); err != nil {
		t.Fatalf("write orm: %v", err)
	}

	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: recipesVersionedService, Clock: fixedClock})
	if err != nil {
		t.Fatalf("generate ddl: %v", err)
	}
	ddlDir := t.TempDir()
	if err := sqlgen.WriteDDL(ddl, ddlDir); err != nil {
		t.Fatalf("write ddl: %v", err)
	}

	out := runGeneratedORMModule(t, ormDir, filepath.Join(ddlDir, "create.sql"), "versioned_writes_test.go", versionedWritesORMTest)
	if !strings.Contains(out, "--- PASS: TestVersionedWritesOnPostgres") {
		t.Fatal("the generated ORM module did not run TestVersionedWritesOnPostgres")
	}
}

const versionedWritesORMTest = `package orm

import (
	"context"
	"errors"
	"fmt"
	"os"
	"testing"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
	types "example.com/schemas/types/go/versioned-recipes"
)

func TestVersionedWritesOnPostgres(t *testing.T) {
	dsn := os.Getenv("SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set SUPERSCHEMATIC_ORMGEN_TEST_DATABASE_URL to run the generated ORM against Postgres")
	}
	db, pool := openRecipesDatabase(t, dsn)

	author := mustUUID(t, "00000000-0000-4000-8000-0000000000a1")
	editor := mustUUID(t, "00000000-0000-4000-8000-0000000000e1")
	missing := mustUUID(t, "00000000-0000-4000-8000-00000000dead")
	ctx := WithUserID(context.Background(), author)
	editorCtx := WithUserID(context.Background(), editor)

	// An upsert that becomes an update records one UPDATE history row with
	// the row as stored, not the insert it proposed.
	bread, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Bread"})
	if err != nil {
		t.Fatalf("CreateOne: %v", err)
	}
	breadID := *bread.Id
	if _, err := pool.Exec(ctx, ` + "`" + `INSERT INTO recipe (id, title, created_by, updated_by) VALUES ($1, $2, $3, $3)
ON CONFLICT (id) DO UPDATE SET title = recipe.title || ' and ' || EXCLUDED.title` + "`" + `, breadID.ToUUID(), "Butter", author.ToUUID()); err != nil {
		t.Fatalf("upsert: %v", err)
	}
	history := listRecipeVersions(t, db, breadID)
	if len(history) != 2 {
		t.Fatalf("history after the upsert = %d rows, want INSERT and one UPDATE", len(history))
	}
	if history[0].Operation != "INSERT" || history[0].Version != 1 || history[0].Value.Title != "Bread" {
		t.Fatalf("history[0] = (%s, %d, %q), want (INSERT, 1, Bread)", history[0].Operation, history[0].Version, history[0].Value.Title)
	}
	if history[1].Operation != "UPDATE" || history[1].Version != 2 || history[1].Value.Title != "Bread and Butter" || history[1].Value.Version != 2 {
		t.Fatalf("history[1] = (%s, %d, %q, image version %d), want (UPDATE, 2, Bread and Butter, 2)",
			history[1].Operation, history[1].Version, history[1].Value.Title, history[1].Value.Version)
	}

	// UpdateOneIfVersion: a stale version conflicts, a missing id is not
	// found, the stored version wins.
	rye := "Rye"
	_, err = db.Recipe.UpdateOneIfVersion(ctx, breadID, 1, &RecipeUpdate{Title: &rye})
	assertVersionConflict(t, "UpdateOneIfVersion(stale)", err)
	_, err = db.Recipe.UpdateOneIfVersion(ctx, missing, 1, &RecipeUpdate{Title: &rye})
	assertNotFoundOnly(t, "UpdateOneIfVersion(missing)", err)
	updated, err := db.Recipe.UpdateOneIfVersion(ctx, breadID, 2, &RecipeUpdate{Title: &rye})
	if err != nil {
		t.Fatalf("UpdateOneIfVersion(2): %v", err)
	}
	if updated.Version != 3 || updated.Title != "Rye" {
		t.Fatalf("UpdateOneIfVersion(2) = (%d, %q), want (3, Rye)", updated.Version, updated.Title)
	}
	beforeDelete := dbTime(t, pool)

	// DeleteOneIfVersion on a table without deletedAt hard-deletes.
	assertVersionConflict(t, "DeleteOneIfVersion(stale)", db.Recipe.DeleteOneIfVersion(editorCtx, breadID, 2))
	assertNotFoundOnly(t, "DeleteOneIfVersion(missing)", db.Recipe.DeleteOneIfVersion(editorCtx, missing, 1))

	// In a transaction the delete sets the history actor for its statement
	// only: a bare DELETE after it keeps the row's own updated_by.
	scones, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Scones"})
	if err != nil {
		t.Fatalf("CreateOne(Scones): %v", err)
	}
	sconesID := *scones.Id
	if err := db.Transaction(editorCtx, func(tx TxInterface) error {
		if err := tx.GetRecipeRepository().DeleteOneIfVersion(editorCtx, breadID, 3); err != nil {
			return fmt.Errorf("DeleteOneIfVersion(3): %w", err)
		}
		_, err := tx.Exec(editorCtx, "DELETE FROM recipe WHERE id = $1", sconesID.ToUUID())
		return err
	}); err != nil {
		t.Fatalf("delete transaction: %v", err)
	}
	if _, err := db.Recipe.GetOne(ctx, breadID, nil); !errors.Is(err, ErrNotFound) {
		t.Fatalf("GetOne after the delete = %v, want ErrNotFound", err)
	}
	history = listRecipeVersions(t, db, breadID)
	tombstone := history[len(history)-1]
	if tombstone.Operation != "DELETE" || tombstone.Version != 4 {
		t.Fatalf("tombstone = (%s, %d), want (DELETE, 4)", tombstone.Operation, tombstone.Version)
	}
	if tombstone.Value.Version != 4 || tombstone.Value.Title != "Rye" {
		t.Fatalf("tombstone image = (version %d, %q), want the pre-delete row at version 4", tombstone.Value.Version, tombstone.Value.Title)
	}
	if tombstone.Value.UpdatedBy.ToUUID() != editor.ToUUID() {
		t.Fatalf("tombstone updated_by = %s, want the deleting user %s", tombstone.Value.UpdatedBy.ToUUID(), editor.ToUUID())
	}
	sconesHistory := listRecipeVersions(t, db, sconesID)
	sconesTombstone := sconesHistory[len(sconesHistory)-1]
	if sconesTombstone.Operation != "DELETE" || sconesTombstone.Value.UpdatedBy.ToUUID() != author.ToUUID() {
		t.Fatalf("bare delete tombstone = (%s, updated_by %s), want (DELETE, the row's own %s)",
			sconesTombstone.Operation, sconesTombstone.Value.UpdatedBy.ToUUID(), author.ToUUID())
	}

	// A hard delete outside a transaction records the actor too.
	toast, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Toast"})
	if err != nil {
		t.Fatalf("CreateOne(Toast): %v", err)
	}
	if err := db.Recipe.DeleteOne(editorCtx, *toast.Id); err != nil {
		t.Fatalf("DeleteOne(Toast): %v", err)
	}
	toastHistory := listRecipeVersions(t, db, *toast.Id)
	if last := toastHistory[len(toastHistory)-1]; last.Operation != "DELETE" || last.Version != 2 || last.Value.UpdatedBy.ToUUID() != editor.ToUUID() {
		t.Fatalf("DeleteOne tombstone = (%s, %d, updated_by %s), want (DELETE, 2, %s)", last.Operation, last.Version, last.Value.UpdatedBy.ToUUID(), editor.ToUUID())
	}
	muffins, err := db.Recipe.CreateMany(ctx, []*types.Recipe{{Title: "Muffins"}, {Title: "Muffin tops"}})
	if err != nil {
		t.Fatalf("CreateMany: %v", err)
	}
	title := "Muffins"
	deleted, err := db.Recipe.DeleteMany(editorCtx, &RecipeFilter{Title: &StringFilter{Eq: &title}})
	if err != nil || deleted != 1 {
		t.Fatalf("DeleteMany = %d, %v; want 1", deleted, err)
	}
	muffinsHistory := listRecipeVersions(t, db, *muffins[0].Id)
	if last := muffinsHistory[len(muffinsHistory)-1]; last.Operation != "DELETE" || last.Value.UpdatedBy.ToUUID() != editor.ToUUID() {
		t.Fatalf("DeleteMany tombstone = (%s, updated_by %s), want (DELETE, %s)", last.Operation, last.Value.UpdatedBy.ToUUID(), editor.ToUUID())
	}
	if _, err := db.Recipe.GetOne(ctx, *muffins[1].Id, nil); err != nil {
		t.Fatalf("DeleteMany deleted a row its filter does not match: %v", err)
	}

	// The history readers never return a tombstone's image.
	if _, err := db.Recipe.GetVersion(ctx, breadID, 4); !errors.Is(err, ErrNotFound) {
		t.Fatalf("GetVersion(tombstone) = %v, want ErrNotFound", err)
	}
	if got, err := db.Recipe.GetVersion(ctx, breadID, 3); err != nil || got.Title != "Rye" {
		t.Fatalf("GetVersion(3) = %+v, %v; want Rye", got, err)
	}
	if _, err := db.Recipe.GetAsOf(ctx, breadID, dbTime(t, pool)); !errors.Is(err, ErrNotFound) {
		t.Fatalf("GetAsOf after the delete = %v, want ErrNotFound", err)
	}
	if got, err := db.Recipe.GetAsOf(ctx, breadID, beforeDelete); err != nil || got.Title != "Rye" {
		t.Fatalf("GetAsOf before the delete = %+v, %v; want Rye", got, err)
	}

	// A table with deletedAt: DeleteOneIfVersion soft-deletes, the as-of
	// readers treat the soft-deleted image as gone, and a later hard delete's
	// tombstone takes its deleted_by from the deleting user.
	pastry, err := db.Recipe.CreateOne(ctx, &types.Recipe{Title: "Pastry"})
	if err != nil {
		t.Fatalf("CreateOne(Pastry): %v", err)
	}
	pastryID := *pastry.Id
	fold, err := db.Step.CreateOne(ctx, &types.Step{Recipe: types.Recipe{Id: &pastryID}, Instruction: "Fold the butter in"})
	if err != nil {
		t.Fatalf("CreateOne(step): %v", err)
	}
	rest, err := db.Step.CreateOne(ctx, &types.Step{Recipe: types.Recipe{Id: &pastryID}, Instruction: "Rest the dough"})
	if err != nil {
		t.Fatalf("CreateOne(second step): %v", err)
	}
	foldID := *fold.Id
	beforeSoftDelete := dbTime(t, pool)
	assertVersionConflict(t, "Step.DeleteOneIfVersion(stale)", db.Step.DeleteOneIfVersion(ctx, foldID, 2))
	assertNotFoundOnly(t, "Step.DeleteOneIfVersion(missing)", db.Step.DeleteOneIfVersion(ctx, missing, 1))
	if err := db.Step.DeleteOneIfVersion(ctx, foldID, 1); err != nil {
		t.Fatalf("Step.DeleteOneIfVersion(1): %v", err)
	}
	assertNotFoundOnly(t, "Step.DeleteOneIfVersion(soft-deleted)", db.Step.DeleteOneIfVersion(ctx, foldID, 2))
	if _, err := db.Step.GetAsOf(ctx, foldID, dbTime(t, pool)); !errors.Is(err, ErrNotFound) {
		t.Fatalf("GetAsOf after the soft delete = %v, want ErrNotFound", err)
	}
	if got, err := db.Step.GetAsOf(ctx, foldID, beforeSoftDelete); err != nil || got.Instruction != "Fold the butter in" {
		t.Fatalf("GetAsOf before the soft delete = %+v, %v", got, err)
	}
	live, err := db.Step.ListAsOfByRecipeID(ctx, pastryID, dbTime(t, pool), nil)
	if err != nil {
		t.Fatalf("ListAsOfByRecipeID: %v", err)
	}
	if len(live) != 1 || live[0].Value.Id.ToUUID() != rest.Id.ToUUID() {
		t.Fatalf("ListAsOfByRecipeID after the soft delete = %d rows, want only the second step", len(live))
	}

	if err := db.Step.HardDeleteOne(editorCtx, foldID); err != nil {
		t.Fatalf("HardDeleteOne: %v", err)
	}
	stepHistory, err := db.Step.ListVersions(ctx, foldID, nil)
	if err != nil {
		t.Fatalf("Step.ListVersions: %v", err)
	}
	stepTombstone := stepHistory[len(stepHistory)-1]
	if stepTombstone.Operation != "DELETE" || stepTombstone.Version != 3 || stepTombstone.Value.Version != 3 {
		t.Fatalf("step tombstone = (%s, %d, image version %d), want (DELETE, 3, 3)", stepTombstone.Operation, stepTombstone.Version, stepTombstone.Value.Version)
	}
	if stepTombstone.Value.DeletedBy == nil || stepTombstone.Value.DeletedBy.ToUUID() != editor.ToUUID() {
		t.Fatalf("step tombstone deleted_by = %v, want the hard-deleting user %s", stepTombstone.Value.DeletedBy, editor.ToUUID())
	}
}

func assertVersionConflict(t *testing.T, label string, err error) {
	t.Helper()
	if !errors.Is(err, ErrVersionConflict) || !errors.Is(err, ErrNotFound) {
		t.Fatalf("%s = %v, want ErrVersionConflict that is also ErrNotFound", label, err)
	}
}

func assertNotFoundOnly(t *testing.T, label string, err error) {
	t.Helper()
	if !errors.Is(err, ErrNotFound) || errors.Is(err, ErrVersionConflict) {
		t.Fatalf("%s = %v, want ErrNotFound and not ErrVersionConflict", label, err)
	}
}

func listRecipeVersions(t *testing.T, db *Database, id types.IdentityUUID) []types.HistoryRecord[*types.Recipe] {
	t.Helper()
	history, err := db.Recipe.ListVersions(context.Background(), id, nil)
	if err != nil {
		t.Fatalf("ListVersions: %v", err)
	}
	if len(history) == 0 {
		t.Fatalf("ListVersions(%s) is empty", id.ToUUID())
	}
	return history
}

func dbTime(t *testing.T, pool *pgxpool.Pool) time.Time {
	t.Helper()
	var ts time.Time
	if err := pool.QueryRow(context.Background(), "SELECT clock_timestamp()").Scan(&ts); err != nil {
		t.Fatalf("read the database clock: %v", err)
	}
	return ts
}

func mustUUID(t *testing.T, raw string) types.IdentityUUID {
	t.Helper()
	id, err := types.ParseIdentityUUID(raw)
	if err != nil {
		t.Fatalf("parse uuid %q: %v", raw, err)
	}
	return id
}

// openRecipesDatabase applies testdata/create.sql in a fresh schema and
// connects the generated ORM to it.
func openRecipesDatabase(t *testing.T, dsn string) (*Database, *pgxpool.Pool) {
	t.Helper()
	createSQL, err := os.ReadFile("testdata/create.sql")
	if err != nil {
		t.Fatalf("read create.sql: %v", err)
	}
	ctx := context.Background()
	base, err := pgxpool.New(ctx, dsn)
	if err != nil {
		t.Fatalf("connect: %v", err)
	}
	t.Cleanup(base.Close)
	schema := fmt.Sprintf("versioned_writes_%d", time.Now().UnixNano())
	if _, err := base.Exec(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatalf("create schema: %v", err)
	}
	t.Cleanup(func() { _, _ = base.Exec(context.Background(), "DROP SCHEMA "+schema+" CASCADE") })

	cfg, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatalf("parse database URL: %v", err)
	}
	cfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("connect schema pool: %v", err)
	}
	if _, err := pool.Exec(ctx, string(createSQL)); err != nil {
		pool.Close()
		t.Fatalf("apply create.sql: %v", err)
	}
	db, err := ConnectWithPool(pool)
	if err != nil {
		pool.Close()
		t.Fatalf("connect generated orm: %v", err)
	}
	t.Cleanup(db.Close)
	return db, pool
}
`
