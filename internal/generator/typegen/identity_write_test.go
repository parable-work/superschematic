func generateModule(t *testing.T, name string, schema *ir.Schema) *ModuleOutput {
	t.Helper()
	output, err := Generate(schema, Options{
		SchemaName: name,
		ModulePath: "example.com/schemas/types/go/" + name,
		Clock:      codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC)),
	})
	if err != nil {
		t.Fatalf("generate %s: %v", name, err)
	}
	return output
}

// TestWriteTypesWritesTheIdentityDescriptor: a schema with a User table
// gets identity/<schema>.json and identity.go, whose IdentityDescriptor is
// the same document, and the README lists it. Writing a schema without one
// over the module removes both.
func TestWriteTypesWritesTheIdentityDescriptor(t *testing.T) {
	schema := identitytest.Schema(t, identitytest.Options{Roles: true, Name: "displayName"})
	d, ok, err := identitydesc.Describe(schema)
	if err != nil || !ok {
		t.Fatalf("Describe = %v, %v", ok, err)
	}
	want, err := d.JSON()
	if err != nil {
		t.Fatal(err)
	}

	outDir := t.TempDir()
	if err := WriteTypes(generateModule(t, identitytest.Service, schema), outDir); err != nil {
		t.Fatalf("write types: %v", err)
	}
	read := func(name string) string {
		t.Helper()
		b, err := os.ReadFile(filepath.Join(outDir, filepath.FromSlash(name)))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	if got := read("identity/" + identitytest.Service + ".json"); got != string(want) {
		t.Fatalf("identity/%s.json:\n%s\nwant:\n%s", identitytest.Service, got, want)
	}
	constant := "const IdentityDescriptor = `" + strings.TrimSuffix(string(want), "\n") + "`\n"
	if got := read("identity.go"); !strings.HasSuffix(got, constant) || !strings.HasPrefix(got, "// Code generated by superschematic typegen. DO NOT EDIT.\n\npackage types\n") {
		t.Fatalf("identity.go does not end with the descriptor constant:\n%s", got)
	}
	if got := read("README.md"); !strings.Contains(got, "| `identity.go` | `IdentityDescriptor`, the identity descriptor (D50); `identity/"+identitytest.Service+".json`") {
		t.Fatalf("README.md does not list identity.go:\n%s", got)
	}

	plain, err := loader.LoadService(filepath.Join(fixturesDir, "fixture-db"))
	if err != nil {
		t.Fatal(err)
	}
	if err := WriteTypes(generateModule(t, identitytest.Service, plain), outDir); err != nil {
		t.Fatalf("write types: %v", err)
	}
	for _, name := range []string{"identity.go", "identity"} {
		if _, err := os.Stat(filepath.Join(outDir, name)); !os.IsNotExist(err) {
			t.Errorf("a schema without a User table leaves %s behind: %v", name, err)
		}
	}
	if strings.Contains(read("README.md"), "identity.go") {
		t.Errorf("the README of a schema without a User table lists identity.go")
	}
}

// TestGenerateRefusesAUserTableWithoutItsTables: a User table whose Session
// table is missing fails generation with the descriptor's error, rather
// than writing types without a descriptor.
func TestGenerateRefusesAUserTableWithoutItsTables(t *testing.T) {
	schema := identitytest.Schema(t, identitytest.Options{})
	delete(schema.Types, ir.IdentitySessionTable)
	_, err := Generate(schema, Options{SchemaName: identitytest.Service, ModulePath: "example.com/schemas/types/go/" + identitytest.Service})
	if err == nil || !strings.HasPrefix(err.Error(), "identitydesc: the schema has a User table but no Session table") {
		t.Fatalf("Generate = %v, want the descriptor's refusal", err)
	}
}
