var update = flag.Bool("update", false, "rewrite runtime/schema/testdata/pattern_dialect.json")

// corpusPath holds dialectCases with RE2's verdicts, for the TypeScript,
// Python and Rust schema runtimes' own suites, whose rewrites port this
// package's.
const corpusPath = "runtime/schema/testdata/pattern_dialect.json"

type corpusCase struct {
	Pattern string `json:"pattern"`
	Text    string `json:"text"`
	Match   bool   `json:"match"`
}

// TestDialectCorpus keeps runtime/schema/testdata/pattern_dialect.json equal
// to dialectCases as Go's regexp matches them. It fails when the committed
// file is stale; -update rewrites it.
func TestDialectCorpus(t *testing.T) {
	corpus := struct {
		Comment string       `json:"comment"`
		Cases   []corpusCase `json:"cases"`
	}{Comment: "Generated by internal/generator/patterndialect (go test ./internal/generator/patterndialect -update). " +
		"Each case is a schema pattern, a text and whether Go's regexp (RE2) finds a match in it; every schema runtime must agree."}
	for _, c := range dialectCases {
		re := regexp.MustCompile(c.pattern)
		for _, text := range c.texts {
			corpus.Cases = append(corpus.Cases, corpusCase{Pattern: c.pattern, Text: text, Match: re.MatchString(text)})
		}
	}
	var data bytes.Buffer
	encoder := json.NewEncoder(&data)
	encoder.SetEscapeHTML(false)
	encoder.SetIndent("", "  ")
	if err := encoder.Encode(corpus); err != nil {
		t.Fatal(err)
	}
	// Plain ASCII: every other character is a \u escape.
	var ascii bytes.Buffer
	for _, r := range data.String() {
		switch {
		case r < 0x80:
			ascii.WriteRune(r)
		case r < 0x10000:
			fmt.Fprintf(&ascii, `\u%04x`, r)
		default:
			hi, lo := utf16.EncodeRune(r)
			fmt.Fprintf(&ascii, `\u%04x\u%04x`, hi, lo)
		}
	}
	data = ascii
	path := filepath.Join(testpaths.RepoRoot(t), filepath.FromSlash(corpusPath))
	if *update {
		if err := os.WriteFile(path, data.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./internal/generator/patterndialect -update)", corpusPath, err)
	}
	if !bytes.Equal(committed, data.Bytes()) {
		t.Fatalf("%s is stale; run go test ./internal/generator/patterndialect -update", corpusPath)
	}
}

// dialectCases are patterns with texts RE2 matches differently from
// JavaScript's RegExp (u flag) or Python's re as written.
