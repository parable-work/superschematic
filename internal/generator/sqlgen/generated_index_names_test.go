// mergeRequirementSchema is a DB schema whose table MergeRequirement keeps
// its revisions (Revisions with review, D16): the behavior adds the
// sub-table merge_requirement_revisions_proposals and its unique index over
// the row and the proposal, whose default name is 68 bytes.
const mergeRequirementSchema = `{
  "name": "merge-db",
  "kind": "DB",
  "scalars": {
    "Identity.UUID": {"name": "Identity.UUID", "languagePrimitive": "string"},
    "Temporal.DateTime": {"name": "Temporal.DateTime", "languagePrimitive": "string"},
    "Generic.Int64": {"name": "Generic.Int64", "languagePrimitive": "number"},
    "Generic.JSON": {"name": "Generic.JSON", "languagePrimitive": "object"}
  },
  "types": {
    "MergeRequirement": {
      "name": "MergeRequirement",
      "role": "DBTable",
      "behaviors": [{"name": "Revisions", "implements": true, "config": {"review": {"permission": "merge-rules.approve"}}}],
      "fields": [
        {"name": "id", "typeRef": {"name": "Identity.UUID"}, "required": true, "key": true, "autoGenerated": true},
        {"name": "name", "typeRef": {"name": "string"}, "required": true},
        {"name": "permission", "typeRef": {"name": "string"}, "required": true}
      ]
    }
  }
}`

// TestABehaviorsLongIndexNameIsShortened runs the loader and the generator
// over a table whose behavior's sub-table index has a default name over
// PostgreSQL's 63 bytes. No author can name that index, so the generator
// shortens it in a fixed way, the name's first bytes and eight hex digits
// of its SHA-256, where it refused the build before D200.
func TestABehaviorsLongIndexNameIsShortened(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "merge-db")
	for path, contents := range map[string]string{
		"schema.config.json":    `{"name": "merge-db", "kind": "DB", "outputs": {"sql": {"dialects": ["postgres", "sqlite"]}}}`,
		"src/merge.schema.json": mergeRequirementSchema,
	} {
		full := filepath.Join(dir, filepath.FromSlash(path))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(contents), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	schema, err := loader.LoadService(dir)
	if err != nil {
		t.Fatal(err)
	}
	out, err := Generate(schema, Options{SchemaName: "merge-db"})
	if err != nil {
		t.Fatalf("the generator refused the behavior's index: %v", err)
	}
	const long = "idx_merge_requirement_revisions_proposals_merge_requirement_proposal"
	want := sqlutil.ShortIdentifier(long)
	if len(want) > sqlutil.PostgresIdentifierLimit || !strings.HasPrefix(want, "idx_merge_requirement_revisions_proposals_merge_requi") {
		t.Fatalf("ShortIdentifier(%q) = %q (%d bytes)", long, want, len(want))
	}
	create, err := renderTemplate("create.tmpl", out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(create), want) {
		t.Errorf("create.sql names no index %s:\n%s", want, create)
	}
	for _, table := range out.Tables {
		for _, index := range table.Indexes {
			if len(index.Name) > sqlutil.PostgresIdentifierLimit {
				t.Errorf("%s's index %s is %d bytes", table.Name, index.Name, len(index.Name))
			}
		}
	}
	// The author's own index still asks for a purpose name.
	if _, err := sqlutil.IndexName("merge_requirement_revisions_proposals", []string{"mergeRequirement", "proposal"}, "", true); err == nil {
		t.Error("an author's overlong default name passed")
	}
}

// TestShortIdentifier: a name that fits is itself; a longer one is cut at a
// character and ends in its hash, the same each time, and two that share
// their first bytes stay apart.
func TestShortIdentifier(t *testing.T) {
	if got := sqlutil.ShortIdentifier("idx_note_title"); got != "idx_note_title" {
		t.Errorf("ShortIdentifier kept no short name: %q", got)
	}
	a := sqlutil.ShortIdentifier(strings.Repeat("a", 70) + "_one")
	b := sqlutil.ShortIdentifier(strings.Repeat("a", 70) + "_two")
	if a == b || len(a) != sqlutil.PostgresIdentifierLimit || a != sqlutil.ShortIdentifier(strings.Repeat("a", 70)+"_one") {
		t.Errorf("ShortIdentifier = %q, %q", a, b)
	}
	if got := sqlutil.ShortIdentifier(strings.Repeat("é", 40)); len(got) > sqlutil.PostgresIdentifierLimit || !strings.HasPrefix(got, strings.Repeat("é", 27)) {
		t.Errorf("ShortIdentifier cut a character: %q", got)
	}
}
