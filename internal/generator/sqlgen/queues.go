// A queue's table (docs/stack-model.md, section 8.8, D53). A DB service's
// `@queue` class is a message, not a table, and its queue is a table named
// after the class with ir.QueueTableSuffix: the message's ID, a column per
// message field, as a table's field becomes one, and the columns the queue
// keeps (ir.QueueColumns). A claim reads the messages that are ready and
// due, or claimed past their claim's expiry, and a prune the done messages
// by when they were done, their updated_at (D68), so a partial index on
// each serves it. A queue with a key (D80) adds a partial unique index of
// its ready messages by key when it keeps one per key, the target of an
// enqueue's ON CONFLICT, and one of its claimed messages by key when it
// serializes its keys, which holds a key to one claim whatever two workers
// claim at once; a queue that serializes and appends indexes its ready
// messages by key too, which a claim reads a key's line by. The table is a
// table like any other to the migration planner (D27), in every dialect
// the service lists: the SQLite model reads it from this output, as it
// reads every table.

// QueueTableName is the table of the queue whose class is name
// (sqlutil.QueueTableName, `order_placed_queue`).
func QueueTableName(name string) string {
	return sqlutil.QueueTableName(name)
}

// convertQueueToTable builds the table of the queue typeDef declares.
func convertQueueToTable(typeDef *ir.TypeDef, schema *ir.Schema, deps map[string]*ir.Schema, scalarMapping map[string]string, compositeDefaults map[string]*ir.CompositeDefaultDef) (Table, error) {
	message, err := convertTypeToTable(typeDef, schema, deps, scalarMapping, compositeDefaults)
	if err != nil {
		return Table{}, err
	}
	if len(message.ForeignKeys) > 0 || message.PrimaryKey != "" || len(message.Unique) > 0 || len(message.SearchFields) > 0 || len(message.Indexes) > 0 {
		return Table{}, fmt.Errorf("queue %s: a message's fields are values, with no key, reference, unique field, search field or index", typeDef.Name)
	}
	name := QueueTableName(typeDef.Name)
	doc := message.Doc
	if doc == "" {
		doc = "Messages of the queue " + typeDef.Name + ", one row each."
	}
	column := func(name, typ string, nullable bool, def string) Column {
		return Column{Name: name, QuotedName: sqlutil.QuoteIdentifier(name), Type: typ, Nullable: nullable, DefaultValue: def}
	}
	id := column(ir.QueueColumnID, "UUID", false, "gen_random_uuid()")
	id.IsPrimaryKey, id.AutoGenerated = true, true
	columns := append([]Column{id}, message.Columns...)
	columns = append(columns,
		column(ir.QueueColumnState, "TEXT", false, "'"+ir.QueueStateReady+"'"),
		column(ir.QueueColumnAttempts, "INTEGER", false, "0"),
		column(ir.QueueColumnDueAt, "TIMESTAMPTZ", false, "CURRENT_TIMESTAMP"),
		column(ir.QueueColumnClaimExpiresAt, "TIMESTAMPTZ", true, ""),
		column(ir.QueueColumnClaimToken, "UUID", true, ""),
		column(ir.QueueColumnLastError, "TEXT", true, ""),
		column(ir.QueueColumnCreatedAt, "TIMESTAMPTZ", false, "CURRENT_TIMESTAMP"),
		column(ir.QueueColumnUpdatedAt, "TIMESTAMPTZ", false, "CURRENT_TIMESTAMP"),
	)
	seen := map[string]bool{}
	for _, c := range columns {
		if seen[c.Name] {
			return Table{}, fmt.Errorf("queue %s: column %s is both a field of the message and a column the queue keeps; rename the field", typeDef.Name, c.Name)
		}
		seen[c.Name] = true
	}
	// A claim reads the ready messages by when they are due, and the
	// claimed ones by when their claim expires; a prune reads the done ones
	// by when they were done.
	var indexes []Index
	for _, idx := range []struct{ column, state string }{
		{ir.QueueColumnDueAt, ir.QueueStateReady},
		{ir.QueueColumnClaimExpiresAt, ir.QueueStateClaimed},
		{ir.QueueColumnUpdatedAt, ir.QueueStateDone},
	} {
		indexName, err := sqlutil.IndexName(name, []string{idx.column}, "", false)
		if err != nil {
			return Table{}, err
		}
		indexes = append(indexes, Index{
			Name:    indexName,
			Columns: []string{sqlutil.QuoteIdentifier(idx.column)},
			Type:    "BTREE",
			Where:   sqlutil.QuoteIdentifier(ir.QueueColumnState) + " = '" + idx.state + "'",
		})
	}
	keyIndexes, err := queueKeyIndexes(name, typeDef)
	if err != nil {
		return Table{}, fmt.Errorf("queue %s: %w", typeDef.Name, err)
	}
	indexes = append(indexes, keyIndexes...)
	table := Table{
		Name:         name,
		QuotedName:   sqlutil.QuoteIdentifier(name),
		OriginalName: typeDef.Name,
		Doc:          doc,
		Columns:      columns,
		PrimaryKey:   id.QuotedName,
		Unique:       [][]string{},
		ForeignKeys:  []ForeignKey{},
		Indexes:      indexes,
		Checks:       message.Checks,
	}
	// The queue's table follows the tables whose checks Generate names.
	if err := assignCheckNames(&table); err != nil {
		return Table{}, err
	}
	return table, nil
}

// The purposes of the indexes a queue's key adds (D80), which name them
// uq_<table>_<purpose> or idx_<table>_<purpose>.
const (
	queueReadyKeyPurpose   = "ready_key"
	queueClaimedKeyPurpose = "claimed_key"
)

// QueueReadyKeyIndex is the name of the partial unique index of the ready
// messages by key of the queue table table, which keeps one per key.
func QueueReadyKeyIndex(table string) string {
	return "uq_" + table + "_" + queueReadyKeyPurpose
}

// queueKeyIndexes are the indexes a queue's key adds to its table: the
// ready messages' by key, unique when the queue keeps one per key, and the
// claimed messages', unique, when it serializes its keys.
func queueKeyIndexes(table string, td *ir.TypeDef) ([]Index, error) {
	key := sqlutil.QueueKeyColumn(td)
	if key == "" {
		return nil, nil
	}
	def := td.Queue
	state := func(s string) string { return sqlutil.QuoteIdentifier(ir.QueueColumnState) + " = '" + s + "'" }
	var out []Index
	add := func(purpose string, unique bool, where string) error {
		name, err := sqlutil.IndexName(table, nil, purpose, unique)
		if err != nil {
			return err
		}
		out = append(out, Index{Name: name, Columns: []string{key}, Type: "BTREE", Unique: unique, Where: where})
		return nil
	}
	if def.Dedupes() || def.Serializes() {
		if err := add(queueReadyKeyPurpose, def.Dedupes(), state(ir.QueueStateReady)); err != nil {
			return nil, err
		}
	}
	if def.Serializes() {
		if err := add(queueClaimedKeyPurpose, true, state(ir.QueueStateClaimed)); err != nil {
			return nil, err
		}
	}
	return out, nil
}
