// identityDocument is the identity schema's descriptor as identity.rs
// holds it, without the trailing newline.
func identityDocument(t *testing.T, schema *ir.Schema) string {
	t.Helper()
	d, ok, err := identitydesc.Describe(schema)
	if err != nil || !ok {
		t.Fatalf("Describe = %v, %v", ok, err)
	}
	text, err := d.JSON()
	if err != nil {
		t.Fatal(err)
	}
	return strings.TrimSuffix(string(text), "\n")
}

// TestWriteTypesHoldsTheIdentityDescriptor: a schema with a User table gets
// src/identity.rs, whose IDENTITY_DESCRIPTOR is the descriptor; lib.rs
// declares and re-exports the module and the README lists it. A schema
// without one gets none of them.
func TestWriteTypesHoldsTheIdentityDescriptor(t *testing.T) {
	clock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	schema := identitytest.Schema(t, identitytest.Options{Roles: true, Name: "displayName"})
	plain, err := loader.LoadService(filepath.Join(fixturesDir, "fixture-db"))
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name   string
		schema *ir.Schema
		holds  bool
	}{
		{"a User table", schema, true},
		{"no User table", plain, false},
	} {
		t.Run(tc.name, func(t *testing.T) {
			output, err := Generate(tc.schema, Options{SchemaName: identitytest.Service, Clock: clock})
			if err != nil {
				t.Fatalf("generate: %v", err)
			}
			dir := t.TempDir()
			if err := WriteTypes(output, dir); err != nil {
				t.Fatalf("write types: %v", err)
			}
			read := func(name string) string {
				t.Helper()
				b, err := os.ReadFile(filepath.Join(dir, filepath.FromSlash(name)))
				if err != nil {
					t.Fatal(err)
				}
				return string(b)
			}
			lib, readme := read("src/lib.rs"), read("README.md")
			_, statErr := os.Stat(filepath.Join(dir, "src", "identity.rs"))
			if !tc.holds {
				if !os.IsNotExist(statErr) || strings.Contains(lib, "mod identity;") || strings.Contains(readme, "identity.rs") {
					t.Fatalf("a schema without a User table has src/identity.rs (%v) or names it:\n%s\n%s", statErr, lib, readme)
				}
				return
			}
			constant := "pub const IDENTITY_DESCRIPTOR: &str = r#\"" + identityDocument(t, schema) + "\"#;\n"
			if got := read("src/identity.rs"); !strings.HasSuffix(got, constant) || !strings.HasPrefix(got, "// Code generated by rustgen. DO NOT EDIT.\n") {
				t.Fatalf("src/identity.rs does not end with the descriptor:\n%s", got)
			}
			if !strings.Contains(lib, "\npub mod identity;\n") || !strings.Contains(lib, "\npub use identity::*;\n") {
				t.Fatalf("lib.rs does not declare and re-export identity:\n%s", lib)
			}
			if !strings.Contains(readme, "- `src/identity.rs` - `IDENTITY_DESCRIPTOR`, the identity descriptor (D50)\n") {
				t.Fatalf("README.md does not list src/identity.rs:\n%s", readme)
			}
		})
	}
}

// TestIdentityDescriptorCompiles builds the identity schema's crate with
// cargo and checks, in a test of the crate's own, that the crate root's
// IDENTITY_DESCRIPTOR is the descriptor and parses as JSON.
func TestIdentityDescriptorCompiles(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping the compiled identity descriptor in short mode")
	}
	cargoPath, err := exec.LookPath("cargo")
	if err != nil {
		t.Skip("cargo not available; skipping the compiled identity descriptor")
	}
	schema := identitytest.Schema(t, identitytest.Options{Roles: true, Name: "displayName"})
	output, err := Generate(schema, Options{SchemaName: identitytest.Service, Clock: codegen.FixedClock(time.Unix(0, 0).UTC())})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	outDir := testpaths.TempDir(t)
	if err := SetLocalPaths(output, testpaths.Local(t), outDir); err != nil {
		t.Fatal(err)
	}
	if err := WriteTypes(output, outDir); err != nil {
		t.Fatalf("write types: %v", err)
	}
	manifest := filepath.Join(outDir, "Cargo.toml")
	cargoToml, err := os.ReadFile(manifest)
	if err != nil {
		t.Fatal(err)
	}
	cargoToml = append(cargoToml, []byte("\n[dev-dependencies]\nserde_json = \"1.0\"\n")...)
	if err := os.WriteFile(manifest, cargoToml, 0o644); err != nil {
		t.Fatal(err)
	}
	testsDir := filepath.Join(outDir, "tests")
	if err := os.Mkdir(testsDir, 0o755); err != nil {
		t.Fatal(err)
	}
	check := `use ` + strings.ReplaceAll(output.CrateName, "-", "_") + `::IDENTITY_DESCRIPTOR;

const EXPECTED: &str = ` + rustutil.RawString(identityDocument(t, schema)) + `;

#[test]
fn identity_descriptor_is_the_document() {
    assert_eq!(IDENTITY_DESCRIPTOR, EXPECTED);
    let document: serde_json::Value =
        serde_json::from_str(IDENTITY_DESCRIPTOR).expect("parse the identity descriptor");
    assert_eq!(document["version"], 1);
    assert_eq!(document["user"]["table"], "account");
}
`
	if err := os.WriteFile(filepath.Join(testsDir, "identity.rs"), []byte(check), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(cargoPath, "test", "--quiet", "--test", "identity")
	cmd.Dir = outDir
	cmd.Env = append(os.Environ(), "CARGO_TARGET_DIR="+filepath.Join(outDir, "target"))
	if combined, err := cmd.CombinedOutput(); err != nil {
		t.Fatalf("cargo test failed: %v\n%s", err, combined)
	}
}
