func loadMCPFixture(t *testing.T) *ir.Schema {
	t.Helper()
	schema, err := loader.LoadService(filepath.Join(fixturesDir, "fixture-mcp"))
	if err != nil {
		t.Fatalf("load fixture-mcp: %v", err)
	}
	return schema
}

func generateMCP(schema *ir.Schema) (*apigen.APIOutput, error) {
	return apigen.Generate(schema, apigen.Options{
		Provider:    sessionauth.Provider{},
		SchemaName:  "fixture-mcp",
		ModulePath:  "example.com/schemas/api/fixture-mcp",
		TypesModule: "example.com/schemas/types/go/fixture-mcp",
	})
}

func endpointNamed(t *testing.T, output *apigen.APIOutput, name string) apigen.EndpointInfo {
	t.Helper()
	for _, endpoint := range output.Endpoints {
		if endpoint.Name == name {
			return endpoint
		}
	}
	t.Fatalf("endpoint %s not found", name)
	return apigen.EndpointInfo{}
}

// TestResolveOperationMCP: a visible tool's name and description come from
// @docs and its icon from @icon; the schema's own record is not changed; a
// hidden record keeps its reason; an unclassified operation has none.
func TestResolveOperationMCP(t *testing.T) {
	schema := loadMCPFixture(t)
	output, err := generateMCP(schema)
	if err != nil {
		t.Fatal(err)
	}

	get := endpointNamed(t, output, "getOrder")
	want := &ir.OperationMCP{
		Handle:      "get_order",
		Meta:        map[string]any{"ui": map[string]any{"resourceUri": "ui://orders/detail"}},
		Name:        "Get an order",
		Description: "Returns one order by its identifier.",
		Icon:        &ir.MCPIcon{Name: "receipt"},
	}
	if !reflect.DeepEqual(get.MCP, want) {
		t.Fatalf("getOrder MCP = %+v\nwant %+v", get.MCP, want)
	}
	for _, set := range schema.OperationSets {
		for _, op := range set.Operations {
			if op.MCP != nil && (op.MCP.Name != "" || op.MCP.Icon != nil) {
				t.Fatalf("resolution wrote into the schema's record of %s: %+v", op.Name, op.MCP)
			}
		}
	}

	del := endpointNamed(t, output, "deleteOrder")
	if !reflect.DeepEqual(del.MCP, &ir.OperationMCP{Hidden: true, HiddenReason: "Staff console only."}) {
		t.Fatalf("deleteOrder MCP = %+v", del.MCP)
	}
	if export := endpointNamed(t, output, "exportOrders"); export.MCP != nil {
		t.Fatalf("exportOrders MCP = %+v", export.MCP)
	}

	// An icon is optional in the core.
	operationIn(schema, "getOrder").Icon = ""
	output, err = generateMCP(schema)
	if err != nil {
		t.Fatal(err)
	}
	if icon := endpointNamed(t, output, "getOrder").MCP.Icon; icon != nil {
		t.Fatalf("getOrder without @icon has icon %+v", icon)
	}
}

func operationIn(schema *ir.Schema, name string) *ir.FieldDef {
	for _, set := range schema.OperationSets {
		for _, op := range set.Operations {
			if op.Name == name {
				return op
			}
		}
	}
	return nil
}

func TestMCPResolutionErrors(t *testing.T) {
	for _, test := range []struct {
		name   string
		mutate func(*ir.Schema)
		want   string
	}{
		{
			name:   "visible without docs",
			mutate: func(s *ir.Schema) { operationIn(s, "getOrder").Docs = nil },
			want:   "apigen: visible @mcp tool order.getOrder must also declare @docs",
		},
		{
			name:   "invalid record",
			mutate: func(s *ir.Schema) { operationIn(s, "getOrder").MCP.Handle = "Get" },
			want:   "apigen: operation order.getOrder has an invalid @mcp: handle",
		},
		{
			name:   "handle collision",
			mutate: func(s *ir.Schema) { operationIn(s, "listOrders").MCP.Handle = "get_order" },
			want:   `apigen: MCP handle collision: "get_order" is declared by both order.listOrders and order.getOrder`,
		},
		{
			name: "display name collision",
			mutate: func(s *ir.Schema) {
				docs := *operationIn(s, "listOrders").Docs
				docs.Title = "GET AN ORDER"
				operationIn(s, "listOrders").Docs = &docs
			},
			want: `apigen: MCP display name collision: "Get an order" is generated by both order.listOrders and order.getOrder`,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			schema := loadMCPFixture(t)
			test.mutate(schema)
			_, err := generateMCP(schema)
			if err == nil || !strings.Contains(err.Error(), test.want) {
				t.Fatalf("err = %v, want %q", err, test.want)
			}
		})
	}

	// Hidden operations take no part in the collision checks.
	schema := loadMCPFixture(t)
	operationIn(schema, "listOrders").MCP = &ir.OperationMCP{Hidden: true, HiddenReason: "Not a tool."}
	operationIn(schema, "deleteOrder").MCP = &ir.OperationMCP{Hidden: true, HiddenReason: "Not a tool."}
	if _, err := generateMCP(schema); err != nil {
		t.Fatalf("hidden operations: %v", err)
	}
}

// TestOpenAPIDocsCarryReplay: an operation with a replay mode carries it
// under the docs record's replay key, both pointer lists always present; an
// operation without one has no replay key.
func TestOpenAPIDocsCarryReplay(t *testing.T) {
	output, err := generateMCP(loadMCPFixture(t))
	if err != nil {
		t.Fatal(err)
	}
	var spec map[string]any
	if err := json.Unmarshal([]byte(output.OpenAPISpecRaw), &spec); err != nil {
		t.Fatal(err)
	}
	docs := openAPIOperation(t, spec, "/api/returns", "post")[apigen.OpenAPIDocsKey].(map[string]any)
	want := map[string]any{"mode": "idempotent", "idempotencyKeyPointers": []any{"/requestId"}, "expectedRevisionPointers": []any{}}
	if !reflect.DeepEqual(docs["replay"], want) {
		t.Fatalf("openReturn replay = %#v\nwant %#v", docs["replay"], want)
	}

	var plain map[string]any
	if err := json.Unmarshal([]byte(generateDocsFixtureAPI(t).OpenAPISpecRaw), &plain); err != nil {
		t.Fatal(err)
	}
	if _, ok := openAPIOperation(t, plain, "/api/orders/{id}", "get")[apigen.OpenAPIDocsKey].(map[string]any)["replay"]; ok {
		t.Fatal("an operation without a replay mode carries a replay key")
	}
}
