type engineParityCase struct {
	Name              string          `json:"name"`
	Keys              engineToolKeys  `json:"keys"`
	Parameters        json.RawMessage `json:"parameters"`
	InputSchemaDigest string          `json:"inputSchemaDigest"`
}

type engineToolKeys struct {
	Scalar     string               `json:"scalar"`
	Guidance   string               `json:"guidance"`
	Parameters []engineToolKeyValue `json:"parameters"`
}

type engineToolKeyValue struct {
	Key   string `json:"key"`
	Value any    `json:"value"`
}

type engineParityDefaults struct {
	Keys             engineToolKeys         `json:"keys"`
	InvocationPolicy engineInvocationPolicy `json:"invocationPolicy"`
}

type engineInvocationPolicy struct {
	Key     string   `json:"key"`
	Values  []string `json:"values"`
	Default string   `json:"default"`
}

