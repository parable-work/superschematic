// engineFixtureDocument is the schema-file document the engine loads: the
// fixture's own types, plus every catalog scalar, declared by name as the
// data forms' loader requires and as an optional field of the instance
// type.
func engineFixtureDocument(t *testing.T) []byte {
	t.Helper()
	var document struct {
		Scalars map[string]map[string]any `json:"scalars"`
		Enums   map[string]any            `json:"enums"`
		Types   map[string]struct {
			Name   string           `json:"name"`
			Role   string           `json:"role"`
			Fields []map[string]any `json:"fields"`
		} `json:"types"`
	}
	if err := json.Unmarshal([]byte(engineFixtureTypes), &document); err != nil {
		t.Fatalf("decode the fixture: %v", err)
	}
	names := make([]string, 0, len(scalars.ScalarMetadataByCanonical))
	for name := range scalars.ScalarMetadataByCanonical {
		names = append(names, name)
	}
	sort.Strings(names)
	shelf := document.Types["Shelf"]
	for _, name := range names {
		if _, declared := document.Scalars[name]; !declared {
			document.Scalars[name] = map[string]any{"name": name, "languagePrimitive": "string"}
		}
		shelf.Fields = append(shelf.Fields, map[string]any{
			"name":    "catalog" + strings.ReplaceAll(name, ".", ""),
			"typeRef": map[string]any{"name": name},
		})
	}
	document.Types["Shelf"] = shelf
	out, err := json.MarshalIndent(map[string]any{
		"kind":    "General",
		"name":    "Shelf",
		"scalars": document.Scalars,
		"enums":   document.Enums,
		"types":   document.Types,
	}, "", "  ")
	if err != nil {
		t.Fatalf("encode the fixture: %v", err)
	}
	return out
}

// engineParityKeys are the vendor keys each case builds the arguments with:
// the core's, a distribution's (another scalar key and keys at the root of
// every argument schema), and none.
var engineParityKeys = []struct {
	name string
	keys apigen.ToolKeys
}{
	{"the core's keys", apigen.DefaultToolKeys()},
	{"a distribution's keys", apigen.ToolKeys{
		Scalar:     "x-acme-scalar",
		Guidance:   "acme/operation-guidance",
		Parameters: []apigen.ToolKeyValue{{Key: "x-acme-arguments", Value: 1}, {Key: "x-acme-source", Value: "a <b> & c"}},
	}},
	{"no keys", apigen.ToolKeys{}},
}

// TestEngineToolParametersParity keeps runtime/engine/testdata/
// tool_parameters_parity.json equal to what the SDK generators write for
// the fixture's instance type. It fails when the committed file is stale;
// -update rewrites it.
func TestEngineToolParametersParity(t *testing.T) {
	document := engineFixtureDocument(t)
	dir := t.TempDir()
	if err := os.WriteFile(filepath.Join(dir, "schema.config.json"), []byte(`{"name": "Shelf", "kind": "General", "outputs": {}}`), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Join(dir, "src"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "src", "shelf.schema.json"), document, 0o644); err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadService(dir)
	if err != nil {
		t.Fatalf("load the fixture: %v", err)
	}
	// apigen reads a schema's types, enums and scalars only when it has an
	// operation; one that returns the instance type is enough.
	schema.OperationSets = []*ir.OperationSet{{
		Name:       "ShelfQueries",
		Operations: []*ir.FieldDef{{Name: "getShelf", TypeRef: ir.TypeRef{Name: "Shelf"}}},
	}}
	output, err := apigen.Generate(schema, apigen.Options{Provider: sessionauth.Provider{}, SchemaName: "Shelf"})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}

	corpus := engineParityCorpus{
		Comment:      engineParityComment,
		Document:     document,
		InstanceType: "Shelf",
		Defaults: engineParityDefaults{
			Keys:             engineKeysOf(apigen.DefaultToolKeys()),
			InvocationPolicy: engineInvocationPolicyOf(apigen.DefaultToolInvocationPolicy()),
		},
		Keys: map[string][]string{
			"ToolManifest":          jsonKeysOf(reflect.TypeFor[ir.ToolManifest]()),
			"ToolManifestTool":      jsonKeysOf(reflect.TypeFor[ir.ToolManifestTool]()),
			"ToolReplayContract":    jsonKeysOf(reflect.TypeFor[ir.ToolReplayContract]()),
			"ToolOperationGuidance": jsonKeysOf(reflect.TypeFor[ir.ToolOperationGuidance]()),
			"ToolReturnSchema":      jsonKeysOf(reflect.TypeFor[ir.ToolReturnSchema]()),
		},
	}
	for _, input := range engineNameInputs {
		corpus.Names = append(corpus.Names, engineNameVector{Input: input, Kebab: codegen.ToKebabCase(input), Snake: codegen.ToSnakeCase(input)})
	}
	for _, handle := range engineHandleInputs {
		err := ir.ValidateOperationMCP(&ir.OperationMCP{Handle: handle})
		corpus.Handles = append(corpus.Handles, engineVerdict{Value: handle, Valid: err == nil})
	}
	for _, key := range enginePolicyKeyInputs {
		corpus.PolicyKeys = append(corpus.PolicyKeys, engineVerdict{Value: key, Valid: ir.ValidateMCPInvocationKey(key) == nil})
	}
	for _, value := range enginePolicyValueInputs {
		err := apigen.ToolInvocationPolicy{Key: "review", Values: []string{value}, Default: value}.Validate()
		corpus.PolicyValues = append(corpus.PolicyValues, engineVerdict{Value: value, Valid: err == nil})
	}
	for _, variant := range engineParityKeys {
		parameters := toolsutil.BuildParametersSchema(
			nil, nil, true, "Shelf", toolsutil.BuildInputTypeFieldsMap(output), output.TypeUnions, output.TypeEnums,
			nil, false, output.Scalars,
			// The engine keys a field by its JSON key; the fixture's fields
			// have no jsonTag, so that is the field's name.
			func(name, _ string) string { return name },
			variant.keys,
		)
		encoded, err := json.Marshal(parameters)
		if err != nil {
			t.Fatalf("%s: encode the parameters: %v", variant.name, err)
		}
		corpus.Cases = append(corpus.Cases, engineParityCase{
			Name:              variant.name,
			Keys:              engineKeysOf(variant.keys),
			Parameters:        documentParameters(t, parameters),
			InputSchemaDigest: fmt.Sprintf("sha256:%x", sha256.Sum256(encoded)),
		})
	}

	data, err := json.MarshalIndent(corpus, "", "  ")
	if err != nil {
		t.Fatalf("encode the corpus: %v", err)
	}
	data = append(data, '\n')
	path := filepath.Join(testpaths.RepoRoot(t), filepath.FromSlash(engineParityPath))
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatalf("write the corpus: %v", err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./internal/generator/toolsutil -run TestEngineToolParametersParity -update)", engineParityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale; run go test ./internal/generator/toolsutil -run TestEngineToolParametersParity -update", engineParityPath)
	}
}

// documentParameters is the argument schema as tools/schema.json writes it
// (templates/tools-schema.tmpl): type, additionalProperties, the vendor
// keys, each property through JSONSchemaPropertyLiteral, and required when
// it lists a field.
func documentParameters(t *testing.T, parameters toolsutil.JSONSchemaObject) json.RawMessage {
	t.Helper()
	properties := make(map[string]json.RawMessage, len(parameters.Properties))
	for name, property := range parameters.Properties {
		properties[name] = json.RawMessage(toolsutil.JSONSchemaPropertyLiteral(property))
	}
	document := map[string]any{
		"type":                 "object",
		"additionalProperties": false,
		"properties":           properties,
	}
	for _, vendor := range parameters.Vendor {
		document[vendor.Key] = vendor.Value
	}
	if len(parameters.Required) > 0 {
		document["required"] = parameters.Required
	}
	encoded, err := json.Marshal(document)
	if err != nil {
		t.Fatalf("encode the document parameters: %v", err)
	}
	return encoded
}

func engineKeysOf(keys apigen.ToolKeys) engineToolKeys {
	out := engineToolKeys{Scalar: keys.Scalar, Guidance: keys.Guidance, Parameters: []engineToolKeyValue{}}
	for _, kv := range keys.Parameters {
		out.Parameters = append(out.Parameters, engineToolKeyValue{Key: kv.Key, Value: kv.Value})
	}
	return out
}

func engineInvocationPolicyOf(policy apigen.ToolInvocationPolicy) engineInvocationPolicy {
	return engineInvocationPolicy{Key: policy.Key, Values: policy.Values, Default: policy.Default}
}

// jsonKeysOf lists a struct's JSON keys in declaration order.
func jsonKeysOf(typ reflect.Type) []string {
	var keys []string
	for i := range typ.NumField() {
		name, _, _ := strings.Cut(typ.Field(i).Tag.Get("json"), ",")
		if name == "" || name == "-" {
			continue
		}
		keys = append(keys, name)
	}
	return keys
}
