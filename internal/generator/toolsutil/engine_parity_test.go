// engineParityPath is the corpus the engine's suite reads
// (runtime/engine/typescript/test/tools-parity.test.ts). The engine writes
// the JSON Schema of a schema's instance type itself, from the schema-file
// document; this file holds it to what the SDK generators write for the
// same type's fields as tool arguments.
const engineParityPath = "runtime/engine/testdata/tool_parameters_parity.json"

const engineParityComment = "Generated by internal/generator/toolsutil (go test ./internal/generator/toolsutil -run TestEngineToolParametersParity -update). " +
	"For the schema-file document, each case holds the tool argument schema the SDK generators build (toolsutil.BuildParametersSchema) " +
	"with the instance type as the input type, as tools/schema.json writes it, and its inputSchemaDigest. " +
	"The engine must write the same schema for the instance type, keyed by the fields' JSON keys, and the same digest. " +
	"defaults and keys are the Go values the engine's defaults and tool documents follow; " +
	"names, handles, policyKeys and policyValues are the Go verdicts on the names the engine derives and the options it checks."

// engineParityCorpus is the file TestEngineToolParametersParity writes.
type engineParityCorpus struct {
	Comment      string               `json:"comment"`
	Document     json.RawMessage      `json:"document"`
	InstanceType string               `json:"instanceType"`
	Cases        []engineParityCase   `json:"cases"`
	Defaults     engineParityDefaults `json:"defaults"`
	// Keys lists the JSON keys of the tool document types, in the order
	// tools/schema.json writes them.
	Keys map[string][]string `json:"keys"`
	// Names holds the case conversions a tool's name and derived MCP
	// handle are built with (codegen.ToKebabCase, codegen.ToSnakeCase).
	Names []engineNameVector `json:"names"`
	// Handles, PolicyKeys and PolicyValues hold what @mcp and the registry
	// accept: an MCP handle (ir.ValidateOperationMCP), an invocation policy
	// key (ir.ValidateMCPInvocationKey) and a policy value
	// (apigen.ToolInvocationPolicy.Validate).
	Handles      []engineVerdict `json:"handles"`
	PolicyKeys   []engineVerdict `json:"policyKeys"`
	PolicyValues []engineVerdict `json:"policyValues"`
}

type engineNameVector struct {
	Input string `json:"input"`
	Kebab string `json:"kebab"`
	Snake string `json:"snake"`
}

type engineVerdict struct {
	Value string `json:"value"`
	Valid bool   `json:"valid"`
}

