// header starts every module this package writes.
const header = "// Code generated by engineclientgen. DO NOT EDIT.\n"

// clientMembers are the wrapper's own members, which no operation may be
// named like: create, get, list, update and delete the engine gives every
// schema and no behavior may take; operate the wrapper adds.
var clientMembers = []string{"create", "get", "list", "update", "delete", "operate"}

// module accumulates the module's text, the names it exports, and the
// client's names its body uses.
type module struct {
	ts      behaviortypes.TSRenderer
	b       strings.Builder
	exports map[string]string
	uses    map[string]bool
}

func render(models []*schemaModel, names naming.Naming) ([]byte, error) {
	m := &module{exports: map[string]string{}, uses: map[string]bool{}}
	for _, model := range models {
		if err := m.schema(model); err != nil {
			return nil, err
		}
	}
	if m.ts.UsesJSONObject {
		m.uses["JSONObject"] = true
	}
	var out strings.Builder
	out.WriteString(header)
	out.WriteString("//\n")
	out.WriteString("// Typed wrappers over the engine's client: each schema's instances, create\n")
	out.WriteString("// input and patches, and its behaviors' create parameters, preconditions,\n")
	out.WriteString("// operations, signals and veto codes, as their configs narrow them.\n")
	out.WriteString("//\n")
	for _, model := range models {
		fmt.Fprintf(&out, "// Schema %s: %s, %s.\n", model.name, model.client, codegen.ToCamelCase(model.client))
	}
	out.WriteString("\n")
	client := names.EngineNpmPackage + "/client"
	if m.uses["isVeto"] {
		fmt.Fprintf(&out, "import { isVeto } from %s;\n", behaviortypes.TSQuote(client))
	}
	var typeNames []string
	for name := range m.uses {
		if name != "isVeto" {
			typeNames = append(typeNames, name)
		}
	}
	sort.Strings(typeNames)
	fmt.Fprintf(&out, "import type { %s } from %s;\n", strings.Join(typeNames, ", "), behaviortypes.TSQuote(client))
	out.WriteString(m.b.String())
	return []byte(out.String()), nil
}

// export claims an exported name, refusing one two parts of the module
// would both take.
func (m *module) export(name, owner string) error {
	if !behaviortypes.TSIdentifier.MatchString(name) {
		return fmt.Errorf("engine-client: %s would export %q, which is not a TypeScript identifier", owner, name)
	}
	if prev, taken := m.exports[name]; taken {
		return fmt.Errorf("engine-client: %s and %s would both export %s; generate their schemas into separate modules", prev, owner, name)
	}
	m.exports[name] = owner
	return nil
}

func (m *module) line(format string, args ...any) {
	fmt.Fprintf(&m.b, format, args...)
	m.b.WriteByte('\n')
}

func (m *module) doc(indent, text string) {
	if strings.TrimSpace(text) != "" {
		m.line("%s%s", indent, behaviortypes.TSDoc(text))
	}
}

// typeAlias writes `export type name = <schema>;`.
func (m *module) typeAlias(name, owner, doc string, schema any) error {
	if err := m.export(name, owner); err != nil {
		return err
	}
	m.b.WriteByte('\n')
	m.doc("", doc)
	m.line("export type %s = %s;", name, m.ts.Render(schema, ""))
	return nil
}

// operationInfo is one operation of a type, in the order the module lists
// them: the behaviors' in list order, each behavior's in declaration order.
type operationInfo struct {
	behavior string
	// core is whether the behavior is the core's, not an extension's.
	core        bool
	declaration registry.BehaviorOperation
	params      any
	result      any
	paramsType  string
	resultType  string
}

func (op operationInfo) schemaScope() bool {
	return op.declaration.Scope == registry.OperationScopeSchema
}

// paramsOptional reports whether an operation's parameters require
// nothing, so its method takes them optionally.
func (op operationInfo) paramsOptional() bool {
	return requiresNothing(op.params)
}

// requiresNothing reports whether a schema of parameters or of a signal's
// data requires no member, so {} is one it takes.
func requiresNothing(schema any) bool {
	params, ok := schema.(map[string]any)
	if !ok {
		return true
	}
	if _, ok := params["anyOf"]; ok {
		return false
	}
	if _, ok := params["oneOf"]; ok {
		return false
	}
	required, _ := params["required"].([]any)
	return len(required) == 0
}

// signalInfo is one signal of a type (D77), in the order the module lists
// them: the behaviors' in list order, each behavior's in declaration
// order.
type signalInfo struct {
	behavior    string
	core        bool
	declaration registry.BehaviorSignal
	data        any
	// dataType is <Base><Signal>Signal, or <Base><Behavior><Signal>Signal
	// when another behavior of the type declares a signal of its name.
	dataType string
	// send is the wrapper's method that sends it, send<Signal> or
	// send<Behavior><Signal>; "" for a signal of access operation, which
	// only the behavior's operations send.
	send string
}

// dataOptional reports whether the signal's data requires no member, so
// its send helper takes it optionally.
func (sig signalInfo) dataOptional() bool {
	return requiresNothing(sig.data)
}

func (m *module) schema(s *schemaModel) error {
	owner := "schema " + s.name
	m.line("")
	m.line("// The %s schema.", s.name)

	if err := m.documentTypes(s); err != nil {
		return err
	}
	if err := m.instanceTypes(s); err != nil {
		return err
	}
	for _, behavior := range s.behaviors {
		for _, a := range behavior.Narrowed.Aliases {
			if err := m.typeAlias(a.Name, owner+" behavior "+behavior.Declaration.Name, a.Doc, a.Schema); err != nil {
				return err
			}
		}
	}

	createParams, createRequired, err := m.createParams(s)
	if err != nil {
		return err
	}
	preconditions, err := m.preconditions(s)
	if err != nil {
		return err
	}
	ops, err := m.operations(s)
	if err != nil {
		return err
	}
	if err := m.vetoes(s); err != nil {
		return err
	}
	signals, err := m.signals(s, ops)
	if err != nil {
		return err
	}

	createOptions := s.base + "CreateOptions"
	writeOptions := s.base + "WriteOptions"
	if err := m.export(createOptions, owner); err != nil {
		return err
	}
	if err := m.export(writeOptions, owner); err != nil {
		return err
	}
	m.uses["CreateOptions"] = true
	m.uses["WriteOptions"] = true
	m.line("")
	m.doc("", fmt.Sprintf("%s create's options: its id, and each behavior's create parameters.", capitalAn(s.base)))
	switch {
	case createParams == "":
		m.line("export type %s = Omit<CreateOptions, 'behaviors'>;", createOptions)
	case createRequired:
		m.line("export type %s = Omit<CreateOptions, 'behaviors'> & { readonly behaviors: %s };", createOptions, createParams)
	default:
		m.line("export type %s = Omit<CreateOptions, 'behaviors'> & { readonly behaviors?: %s };", createOptions, createParams)
	}
	m.line("")
	m.doc("", fmt.Sprintf("%s write's options: the sequence it expects, and each behavior's preconditions.", capitalAn(s.base)))
	if preconditions == "" {
		m.line("export type %s = Omit<WriteOptions, 'preconditions'>;", writeOptions)
	} else {
		m.line("export type %s = Omit<WriteOptions, 'preconditions'> & { readonly preconditions?: %s };", writeOptions, preconditions)
	}

	if len(s.behaviors) > 0 {
		if err := m.vetoGuard(s); err != nil {
			return err
		}
	}
	if len(signals) > 0 {
		if err := m.signalGuard(s); err != nil {
			return err
		}
	}
	return m.client(s, ops, signals, createRequired)
}

// documentTypes writes the enums and types an instance can hold besides
// the instance type, and the types its Variants name, by name.
func (m *module) documentTypes(s *schemaModel) error {
	roots := []string{s.instance.Name}
	if s.variants != nil {
		for _, value := range behaviortypes.SortedKeys(s.variants.Types) {
			roots = append(roots, s.variants.Types[value])
		}
	}
	types := map[string]bool{}
	enums := map[string]bool{}
	for _, root := range roots {
		for _, name := range reachableTypes(s.schema, root) {
			types[name] = true
			for _, field := range s.schema.Types[name].Fields {
				if field != nil && s.schema.Enums[field.TypeRef.Name] != nil {
					enums[field.TypeRef.Name] = true
				}
			}
		}
	}
	delete(types, s.instance.Name)
	owner := "schema " + s.name
	for _, name := range behaviortypes.SortedKeys(enums) {
		enum := s.schema.Enums[name]
		values := behaviortypes.EnumValues(enum)
		if err := m.typeAlias(name, owner+" enum "+name, codegen.DocText(enum.Description, enum.Comment), behaviortypes.EnumOf(values)); err != nil {
			return err
		}
	}
	for _, name := range behaviortypes.SortedKeys(types) {
		td := s.schema.Types[name]
		if err := m.export(name, owner+" type "+name); err != nil {
			return err
		}
		m.line("")
		m.doc("", codegen.DocText(td.Description, td.Comment))
		m.line("export type %s = %s;", name, m.ownFields(s, td, nil, false))
	}
	return nil
}

// ownFields writes a type's own fields as an object type, leaving out the
// keys skip names. In a patch every field is optional and only an
// optional one takes null.
func (m *module) ownFields(s *schemaModel, td *ir.TypeDef, skip map[string]bool, patch bool) string {
	var b strings.Builder
	b.WriteString("{\n")
	for _, field := range td.Fields {
		if field == nil || skip[behaviortypes.JSONKey(field)] {
			continue
		}
		if doc := codegen.DocText(field.Description, field.Comment); strings.TrimSpace(doc) != "" {
			b.WriteString("  " + behaviortypes.TSDoc(doc) + "\n")
		}
		fmt.Fprintf(&b, "  %s: %s;\n", fieldKey(field, patch), m.fieldType(s, field))
	}
	b.WriteString("}")
	return b.String()
}

// fieldKey is a field's key, optional unless the field is required and
// this is not a patch.
func fieldKey(field *ir.FieldDef, patch bool) string {
	key := behaviortypes.TSPropertyKey(behaviortypes.JSONKey(field))
	if patch || !field.Required {
		return key + "?"
	}
	return key
}

// fieldType is a field's TypeScript type: its value, a list of them or a
// list of lists, and null beside it for an optional field.
func (m *module) fieldType(s *schemaModel, field *ir.FieldDef) string {
	t := m.valueType(s, field.TypeRef.Name) + strings.Repeat("[]", field.TypeRef.ArrayDepth())
	if !field.Required && t != "unknown" {
		t += " | null"
	}
	return t
}

// valueType is the TypeScript type of one value of a field's type, as the
// engine's JSON holds it: a scalar is its JSON type, not its scalar
// library's symbol, which may be a Date or a brand (D25).
func (m *module) valueType(s *schemaModel, name string) string {
	switch name {
	case codegen.PrimitiveString:
		return "string"
	case codegen.PrimitiveNumber:
		return "number"
	case codegen.PrimitiveBoolean:
		return "boolean"
	}
	if s.schema.Enums[name] != nil {
		return name
	}
	if s.schema.Types[name] != nil {
		if name == s.instance.Name {
			return s.base + "Fields"
		}
		return name
	}
	if scalar := s.schema.Scalars[name]; scalar != nil {
		switch behaviortypes.ScalarJSONType(scalar) {
		case "any":
			return "unknown"
		case "object":
			m.ts.UsesJSONObject = true
			return behaviortypes.JSONObjectType
		case "array":
			return "unknown[]"
		case "number", "integer":
			return "number"
		case "boolean":
			return "boolean"
		}
		return "string"
	}
	return "unknown"
}

// instanceTypes writes <T>Fields, <T>, <T>Behaviors and <T>Patch.
func (m *module) instanceTypes(s *schemaModel) error {
	owner := "schema " + s.name
	fieldsName, readName, behaviorsName, patchName := s.base+"Fields", s.base, s.base+"Behaviors", s.base+"Patch"
	for _, name := range []string{fieldsName, readName, behaviorsName, patchName} {
		if err := m.export(name, owner); err != nil {
			return err
		}
	}

	m.line("")
	description := codegen.DocText(s.instance.Description, s.instance.Comment)
	if description == "" {
		description = s.schema.Description
	}
	m.doc("", fmt.Sprintf("%s's own fields, as a create gives them. %s", capitalAn(s.base), description))
	if s.variants == nil {
		m.line("export type %s = %s;", fieldsName, m.ownFields(s, s.instance, nil, false))
	} else {
		skip := map[string]bool{s.variants.Field: true, s.variants.By: true}
		m.line("export type %s = %s & (", fieldsName, m.ownFields(s, s.instance, skip, false))
		for _, branch := range m.variantBranches(s) {
			m.line("  | %s", branch)
		}
		m.line(");")
	}

	m.line("")
	m.doc("", fmt.Sprintf("%s's data as a read returns it: its own fields. Its behaviors' fields are in %s.", capitalAn(s.base), behaviorsName))
	m.line("export type %s = %s;", readName, fieldsName)

	m.line("")
	m.doc("", fmt.Sprintf("The fields of %s's behaviors as a read returns them, by behavior name: each behavior that declares a field, with those of its fields that have a value.", behaviortypes.An(s.base)))
	if members := m.ts.BehaviorMembers(s.behaviors); members == "" {
		m.line("export type %s = Record<string, never>;", behaviorsName)
	} else {
		m.line("export type %s = {\n%s};", behaviorsName, members)
	}

	m.line("")
	m.doc("", fmt.Sprintf("A merge patch of %s's own fields (RFC 7386): null removes an optional field. Its behaviors' fields change through their operations.", behaviortypes.An(s.base)))
	if s.variants == nil {
		m.line("export type %s = %s;", patchName, m.ownFields(s, s.instance, nil, true))
		return nil
	}
	patch := m.ownFields(s, s.instance, map[string]bool{s.variants.Field: true}, true)
	field := behaviortypes.OwnField(s.instance, s.variants.Field)
	var types []string
	for _, value := range behaviortypes.SortedKeys(s.variants.Types) {
		types = append(types, s.variants.Types[value])
	}
	if !field.Required {
		types = append(types, "null")
	}
	doc := codegen.DocText(field.Description, field.Comment)
	var extra strings.Builder
	if strings.TrimSpace(doc) != "" {
		extra.WriteString("  " + behaviortypes.TSDoc(doc) + "\n")
	}
	fmt.Fprintf(&extra, "  %s?: %s;\n", behaviortypes.TSPropertyKey(s.variants.Field), behaviortypes.TSUnion(types))
	m.line("export type %s = %s;", patchName, strings.TrimSuffix(patch, "}")+extra.String()+"}")
	return nil
}

// variantBranches are the shapes a type with Variants takes: per listed
// value, by holds it and field its type; then, unless field is required,
// by holding any other value or none, and field none.
func (m *module) variantBranches(s *schemaModel) []string {
	v := s.variants
	field := behaviortypes.OwnField(s.instance, v.Field)
	by := behaviortypes.OwnField(s.instance, v.By)
	fieldKeyText, byKeyText := behaviortypes.TSPropertyKey(v.Field), behaviortypes.TSPropertyKey(v.By)
	var branches []string
	for _, value := range behaviortypes.SortedKeys(v.Types) {
		member := fmt.Sprintf("%s: %s", fieldKeyText, v.Types[value])
		if !field.Required {
			member = fmt.Sprintf("%s?: %s | null", fieldKeyText, v.Types[value])
		}
		branches = append(branches, fmt.Sprintf("{ %s: %s; %s }", byKeyText, behaviortypes.TSQuote(value), member))
	}
	if field.Required {
		return branches
	}
	other := "string"
	if enum := s.schema.Enums[by.TypeRef.Name]; enum != nil {
		var rest []string
		for _, value := range behaviortypes.EnumValues(enum) {
			if _, listed := v.Types[value]; !listed {
				rest = append(rest, behaviortypes.TSQuote(value))
			}
		}
		other = strings.Join(rest, " | ")
	}
	switch {
	case by.Required && other == "":
	case by.Required:
		branches = append(branches, fmt.Sprintf("{ %s: %s; %s?: null }", byKeyText, other, fieldKeyText))
	case other == "":
		branches = append(branches, fmt.Sprintf("{ %s?: null; %s?: null }", byKeyText, fieldKeyText))
	default:
		branches = append(branches, fmt.Sprintf("{ %s?: %s | null; %s?: null }", byKeyText, other, fieldKeyText))
	}
	return branches
}

// capitalAn is behaviortypes.An at the start of a sentence.
func capitalAn(name string) string {
	text := behaviortypes.An(name)
	return strings.ToUpper(text[:1]) + text[1:]
}

// possessive writes a name's possessive: Links', Workflow's.
func possessive(name string) string {
	if strings.HasSuffix(name, "s") {
		return name + "'"
	}
	return name + "'s"
}

// createParams writes <T>CreateParams when a behavior of the type takes
// create parameters: each such behavior's, by name, required where its
// schema requires a member, since the engine checks a missing entry as {}.
func (m *module) createParams(s *schemaModel) (name string, required bool, err error) {
	properties := map[string]any{}
	var requiredNames []any
	for _, behavior := range s.behaviors {
		schema, ok := behavior.Narrowed.CreateParams.(map[string]any)
		if !ok {
			continue
		}
		properties[behavior.Declaration.Name] = schema
		if list, _ := schema["required"].([]any); len(list) > 0 {
			requiredNames = append(requiredNames, behavior.Declaration.Name)
		}
	}
	if len(properties) == 0 {
		return "", false, nil
	}
	name = s.base + "CreateParams"
	object := map[string]any{"type": "object", "additionalProperties": false, "properties": properties}
	if len(requiredNames) > 0 {
		object["required"] = requiredNames
	}
	doc := fmt.Sprintf("The parameters %s's create gives its behaviors, by behavior name.", behaviortypes.An(s.base))
	return name, len(requiredNames) > 0, m.typeAlias(name, "schema "+s.name, doc, object)
}

// preconditions writes <T>Preconditions when a behavior of the type takes
// a precondition: each such behavior's entry, by name.
func (m *module) preconditions(s *schemaModel) (string, error) {
	properties := map[string]any{}
	for _, behavior := range s.behaviors {
		if behavior.Narrowed.Preconditions != nil {
			properties[behavior.Declaration.Name] = behavior.Narrowed.Preconditions
		}
	}
	if len(properties) == 0 {
		return "", nil
	}
	name := s.base + "Preconditions"
	doc := fmt.Sprintf("What a write to %s asserts, by behavior name: the Preconditions header.", behaviortypes.An(s.base))
	object := map[string]any{"type": "object", "additionalProperties": false, "properties": properties}
	return name, m.typeAlias(name, "schema "+s.name, doc, object)
}

// operations writes each operation's parameters and result, then
// <T>Operations and <T>InstanceOperation.
func (m *module) operations(s *schemaModel) ([]operationInfo, error) {
	owner := "schema " + s.name
	var ops []operationInfo
	for _, behavior := range s.behaviors {
		for _, declared := range behavior.Declaration.Operations {
			for _, member := range clientMembers {
				if declared.Name == member {
					return nil, fmt.Errorf("engine-client: %s: behavior %s's operation %s is named like the wrapper's own %s", owner, behavior.Declaration.Name, declared.Name, member)
				}
			}
			op := operationInfo{
				behavior:    behavior.Declaration.Name,
				core:        behavior.Declaration.Extension == "",
				declaration: declared,
				params:      behavior.Narrowed.Params[declared.Name],
				result:      behavior.Narrowed.Results[declared.Name],
				paramsType:  s.base + codegen.ToPascalCase(declared.Name) + "Params",
				resultType:  s.base + codegen.ToPascalCase(declared.Name) + "Result",
			}
			doc := fmt.Sprintf("%s %s: %s", possessive(op.behavior), declared.Name, declared.Description)
			if err := m.typeAlias(op.paramsType, owner+" operation "+declared.Name, "The parameters of "+doc, op.params); err != nil {
				return nil, err
			}
			resultDoc := behaviortypes.DescriptionOf(op.result)
			if resultDoc == "" {
				resultDoc = fmt.Sprintf("What %s %s returns.", possessive(op.behavior), declared.Name)
			}
			if err := m.typeAlias(op.resultType, owner+" operation "+declared.Name, resultDoc, behaviortypes.WithoutDescription(op.result)); err != nil {
				return nil, err
			}
			ops = append(ops, op)
		}
	}
	if len(ops) == 0 {
		return nil, nil
	}
	operations := s.base + "Operations"
	if err := m.export(operations, owner); err != nil {
		return nil, err
	}
	m.line("")
	m.doc("", fmt.Sprintf("Each operation %s's behaviors add: its scope, parameters and result.", behaviortypes.An(s.base)))
	m.line("export type %s = {", operations)
	var instanceOps []string
	for _, op := range ops {
		scope := registry.OperationScopeInstance
		if op.schemaScope() {
			scope = registry.OperationScopeSchema
		} else {
			instanceOps = append(instanceOps, behaviortypes.TSQuote(op.declaration.Name))
		}
		m.line("  %s: { scope: %s; params: %s; result: %s };", op.declaration.Name, behaviortypes.TSQuote(scope), op.paramsType, op.resultType)
	}
	m.line("};")
	if len(instanceOps) > 0 {
		name := s.base + "InstanceOperation"
		if err := m.export(name, owner); err != nil {
			return nil, err
		}
		m.line("")
		m.doc("", fmt.Sprintf("The name of an operation on one %s.", s.base))
		m.line("export type %s = %s;", name, strings.Join(instanceOps, " | "))
	}
	return ops, nil
}

// vetoes writes <T>Vetoes: the codes each behavior's vetoes carry.
func (m *module) vetoes(s *schemaModel) error {
	if len(s.behaviors) == 0 {
		return nil
	}
	name := s.base + "Vetoes"
	if err := m.export(name, "schema "+s.name); err != nil {
		return err
	}
	m.line("")
	m.doc("", fmt.Sprintf("The codes the vetoes of %s's behaviors carry, by behavior: what a refused call's details.code holds.", behaviortypes.An(s.base)))
	m.line("export type %s = {", name)
	for _, behavior := range s.behaviors {
		codes := make([]string, 0, len(behavior.Declaration.Vetoes))
		for _, veto := range behavior.Declaration.Vetoes {
			codes = append(codes, behaviortypes.TSQuote(veto.Code))
		}
		m.line("  %s: %s;", behaviortypes.TSPropertyKey(behavior.Declaration.Name), behaviortypes.TSUnion(codes))
	}
	m.line("};")
	return nil
}

// vetoGuard writes is<T>Veto, the client's isVeto with the type's
// behaviors and codes.
func (m *module) vetoGuard(s *schemaModel) error {
	name := "is" + s.base + "Veto"
	if err := m.export(name, "schema "+s.name); err != nil {
		return err
	}
	vetoes := s.base + "Vetoes"
	m.uses["isVeto"] = true
	m.uses["EngineVeto"] = true
	m.line("")
	m.doc("", fmt.Sprintf("%s is isVeto with the behaviors of %s and their codes.", name, behaviortypes.An(s.base)))
	m.line("export function %s<B extends keyof %s>(error: unknown, behavior?: B, codes?: %s[B] | ReadonlyArray<%s[B]>): error is EngineVeto {", name, vetoes, vetoes, vetoes)
	m.line("  return isVeto(error, behavior, codes);")
	m.line("}")
	return nil
}

// signals writes the data type of each signal the type's behaviors
// declare (D77), <T>Signals, the data types by behavior and name, and
// <T>SignalMessage, the stream's signal message narrowed to them; it
// names each signal's send helper. A type whose behaviors declare no
// signal gets none of them.
func (m *module) signals(s *schemaModel, ops []operationInfo) ([]signalInfo, error) {
	owner := "schema " + s.name
	declaredBy := map[string]int{}
	for _, behavior := range s.behaviors {
		for _, declared := range behavior.Declaration.Signals {
			declaredBy[declared.Name]++
		}
	}
	if len(declaredBy) == 0 {
		return nil, nil
	}
	taken := map[string]string{}
	for _, member := range clientMembers {
		taken[member] = "the wrapper's own " + member
	}
	for _, op := range ops {
		taken[op.declaration.Name] = possessive(op.behavior) + " operation " + op.declaration.Name
	}
	sends := map[string]int{}
	for _, behavior := range s.behaviors {
		for _, declared := range behavior.Declaration.Signals {
			if declared.Access != registry.SignalAccessOperation {
				sends["send"+codegen.ToPascalCase(declared.Name)]++
			}
		}
	}
	var signals []signalInfo
	for _, behavior := range s.behaviors {
		for _, declared := range behavior.Declaration.Signals {
			pascal := codegen.ToPascalCase(declared.Name)
			qualified := behaviortypes.MemberName(behavior.Declaration.Name) + pascal
			sig := signalInfo{
				behavior:    behavior.Declaration.Name,
				core:        behavior.Declaration.Extension == "",
				declaration: declared,
				data:        behavior.Narrowed.Signals[declared.Name],
				dataType:    s.base + pascal + "Signal",
			}
			if declaredBy[declared.Name] > 1 {
				sig.dataType = s.base + qualified + "Signal"
			}
			if declared.Access != registry.SignalAccessOperation {
				sig.send = "send" + pascal
				if _, clash := taken[sig.send]; clash || sends[sig.send] > 1 {
					sig.send = "send" + qualified
				}
				if prev, clash := taken[sig.send]; clash {
					return nil, fmt.Errorf("engine-client: %s: the send helper of %s signal %s would be %s, which %s already takes", owner, possessive(sig.behavior), declared.Name, sig.send, prev)
				}
				taken[sig.send] = possessive(sig.behavior) + " signal " + declared.Name
			}
			doc := fmt.Sprintf("The data of %s %s signal.", possessive(sig.behavior), declared.Name)
			if declared.Description != "" {
				doc = strings.TrimSuffix(doc, ".") + ": " + declared.Description
			}
			if note := coreSignalNotes[sig.behavior+"."+declared.Name]; sig.core && note != "" {
				doc += " " + note
			}
			if err := m.typeAlias(sig.dataType, owner+" signal "+declared.Name, doc, behaviortypes.WithoutDescription(sig.data)); err != nil {
				return nil, err
			}
			signals = append(signals, sig)
		}
	}

	name := s.base + "Signals"
	if err := m.export(name, owner); err != nil {
		return nil, err
	}
	m.line("")
	m.doc("", fmt.Sprintf("The data of the signals of %s's behaviors, by behavior, then signal name: what a signal's data holds.", behaviortypes.An(s.base)))
	m.line("export type %s = {", name)
	for _, behavior := range s.behaviors {
		var members []string
		for _, sig := range signals {
			if sig.behavior == behavior.Declaration.Name {
				members = append(members, fmt.Sprintf("%s: %s", behaviortypes.TSPropertyKey(sig.declaration.Name), sig.dataType))
			}
		}
		if len(members) > 0 {
			m.line("  %s: { %s };", behaviortypes.TSPropertyKey(behavior.Declaration.Name), strings.Join(members, "; "))
		}
	}
	m.line("};")

	message := s.base + "SignalMessage"
	if err := m.export(message, owner); err != nil {
		return nil, err
	}
	m.uses["EngineSignal"] = true
	m.line("")
	m.doc("", fmt.Sprintf("A signal of %s, as a stream opened with signals hands it out: its behavior, its name and its data, typed.", behaviortypes.An(s.base)))
	branches := make([]string, len(signals))
	for i, sig := range signals {
		branches[i] = fmt.Sprintf("  | { readonly type: 'signal'; readonly signal: EngineSignal & { readonly behavior: %s; readonly name: %s; readonly data: %s } }",
			behaviortypes.TSQuote(sig.behavior), behaviortypes.TSQuote(sig.declaration.Name), sig.dataType)
	}
	m.line("export type %s =\n%s;", message, strings.Join(branches, "\n"))
	return signals, nil
}

// coreOperationNotes add to the doc of a core behavior's operation's
// method, by <Behavior>.<operation>, what a reader does with its result;
// %s is the type's base name.
var coreOperationNotes = map[string]string{
	"Comments.getMessage": "%sDraftSignal says how a reader follows a draft.",
}

// coreSignalNotes add to the doc of a core behavior's signal's data, by
// <Behavior>.<signal>, what a reader does with it.
var coreSignalNotes = map[string]string{
	"Comments.draft": "A reader opens the stream with signals before it reads, counts what it holds in code points (Array.from(body).length), and drops a draft at its message's finish, interrupt, deleteMessage or purge event; a draft signal may arrive after that event, and is then ignored.",
}

// signalGuard writes is<T>Signal, which tells the type's signals from the
// other messages of a stream and types their data.
func (m *module) signalGuard(s *schemaModel) error {
	name := "is" + s.base + "Signal"
	if err := m.export(name, "schema "+s.name); err != nil {
		return err
	}
	signals, message := s.base+"Signals", s.base+"SignalMessage"
	m.uses["SignalMessage"] = true
	m.uses["StreamMessage"] = true
	m.line("")
	m.doc("", fmt.Sprintf("%s reports whether a message of a stream opened with signals is a signal of the %s schema, of the behavior and with the name when they are given, and types its data.", name, s.name))
	m.line("export function %s<B extends keyof %s = keyof %s, N extends (B extends keyof %s ? keyof %s[B] : never) = B extends keyof %s ? keyof %s[B] : never>(", name, signals, signals, signals, signals, signals, signals)
	m.line("  message: StreamMessage | SignalMessage,")
	m.line("  behavior?: B,")
	m.line("  name?: N")
	m.line("): message is Extract<%s, { readonly signal: { readonly behavior: B; readonly name: N } }> {", message)
	m.line("  return (")
	m.line("    message.type === 'signal' &&")
	m.line("    message.signal.schema === %s &&", behaviortypes.TSQuote(s.name))
	m.line("    (behavior === undefined || message.signal.behavior === behavior) &&")
	m.line("    (name === undefined || message.signal.name === name)")
	m.line("  );")
	m.line("}")
	return nil
}

// client writes the wrapper's interface and its factory.
func (m *module) client(s *schemaModel, ops []operationInfo, signals []signalInfo, createRequired bool) error {
	owner := "schema " + s.name
	factory := codegen.ToCamelCase(s.client)
	if err := m.export(s.client, owner); err != nil {
		return err
	}
	if err := m.export(factory, owner); err != nil {
		return err
	}
	for _, name := range []string{"EngineClient", "CallOptions", "Instance", "InstancePage", "ListOptions"} {
		m.uses[name] = true
	}
	read, fields, patch := s.base, s.base+"Fields", s.base+"Patch"
	// typeArgs are Instance's: the data, then the behaviors' fields.
	typeArgs := read + ", " + s.base + "Behaviors"
	createOptions, writeOptions := s.base+"CreateOptions", s.base+"WriteOptions"
	createOptional := "?"
	if createRequired {
		createOptional = ""
	}
	instanceOps := false
	for _, op := range ops {
		if !op.schemaScope() {
			instanceOps = true
		}
	}

	m.line("")
	m.doc("", fmt.Sprintf("The %s schema's calls, typed: the engine's built-in operations, then each operation its behaviors add.", s.name))
	m.line("export interface %s {", s.client)
	m.doc("  ", fmt.Sprintf("create stores a new %s, with its behaviors' create parameters.", s.base))
	m.line("  create(data: %s, options%s: %s): Promise<Instance<%s>>;", fields, createOptional, createOptions, typeArgs)
	m.doc("  ", fmt.Sprintf("get reads %s; one that does not exist is 404 not_found.", behaviortypes.An(s.base)))
	m.line("  get(id: string, options?: CallOptions): Promise<Instance<%s>>;", typeArgs)
	m.doc("  ", "list returns a page in creation order.")
	m.line("  list(options?: ListOptions): Promise<InstancePage<%s>>;", typeArgs)
	m.doc("  ", "update applies a merge patch of the own fields.")
	m.line("  update(id: string, patch: %s, options?: %s): Promise<Instance<%s>>;", patch, writeOptions, typeArgs)
	m.doc("  ", fmt.Sprintf("delete removes %s.", behaviortypes.An(s.base)))
	m.line("  delete(id: string, options?: %s): Promise<void>;", writeOptions)
	if instanceOps {
		m.uses["OperationOutcome"] = true
		m.doc("  ", "operate calls an instance operation and returns its result with the instance's sequence after it.")
		m.line("  operate<K extends %sInstanceOperation>(id: string, operation: K, params: %sOperations[K]['params'], options?: %s): Promise<OperationOutcome<%sOperations[K]['result']>>;",
			s.base, s.base, writeOptions, s.base)
	}
	for _, op := range ops {
		doc := fmt.Sprintf("%s %s: %s", possessive(op.behavior), op.declaration.Name, op.declaration.Description)
		if note := coreOperationNotes[op.behavior+"."+op.declaration.Name]; note != "" && op.core {
			doc += " " + fmt.Sprintf(note, s.base)
		}
		m.doc("  ", doc)
		optional := ""
		if op.paramsOptional() {
			optional = "?"
		}
		if op.schemaScope() {
			m.line("  %s(params%s: %s, options?: CallOptions): Promise<%s>;", op.declaration.Name, optional, op.paramsType, op.resultType)
		} else {
			m.line("  %s(id: string, params%s: %s, options?: %s): Promise<%s>;", op.declaration.Name, optional, op.paramsType, writeOptions, op.resultType)
		}
	}
	for _, sig := range signals {
		if sig.send == "" {
			continue
		}
		m.doc("  ", fmt.Sprintf("%s sends %s %s signal to the streams open on %s, as the policy lets its caller %s; nothing is stored, and past the engine's rate it is 429 rate_limited. %s",
			sig.send, possessive(sig.behavior), sig.declaration.Name, behaviortypes.An(s.base), sig.declaration.Access, sig.declaration.Description))
		optional := ""
		if sig.dataOptional() {
			optional = "?"
		}
		m.line("  %s(id: string, data%s: %s, options?: CallOptions): Promise<void>;", sig.send, optional, sig.dataType)
	}
	m.line("}")

	schemaName := behaviortypes.TSQuote(s.name)
	m.line("")
	m.doc("", fmt.Sprintf("%s wraps an EngineClient with the %s schema's types.", factory, s.name))
	m.line("export function %s(client: EngineClient): %s {", factory, s.client)
	m.line("  return {")
	m.line("    create(data, options) {")
	m.line("      return client.instances.create<%s>(%s, data, options);", typeArgs, schemaName)
	m.line("    },")
	m.line("    get(id, options) {")
	m.line("      return client.instances.get<%s>(%s, id, options);", typeArgs, schemaName)
	m.line("    },")
	m.line("    list(options) {")
	m.line("      return client.instances.list<%s>(%s, options);", typeArgs, schemaName)
	m.line("    },")
	m.line("    update(id, patch, options) {")
	m.line("      return client.instances.update<%s>(%s, id, patch, options);", typeArgs, schemaName)
	m.line("    },")
	m.line("    delete(id, options) {")
	m.line("      return client.instances.delete(%s, id, options);", schemaName)
	m.line("    },")
	if instanceOps {
		m.line("    operate<K extends %sInstanceOperation>(id: string, operation: K, params: %sOperations[K]['params'], options?: %s) {", s.base, s.base, writeOptions)
		m.line("      return client.instances.operate<%sOperations[K]['result']>(%s, id, operation, params, options);", s.base, schemaName)
		m.line("    },")
	}
	for _, op := range ops {
		params := "params"
		if op.paramsOptional() {
			params = "params ?? {}"
		}
		if op.schemaScope() {
			m.line("    %s(params, options) {", op.declaration.Name)
			m.line("      return client.instances.invokeSchema<%s>(%s, %s, %s, options);", op.resultType, schemaName, behaviortypes.TSQuote(op.declaration.Name), params)
		} else {
			m.line("    %s(id, params, options) {", op.declaration.Name)
			m.line("      return client.instances.invoke<%s>(%s, id, %s, %s, options);", op.resultType, schemaName, behaviortypes.TSQuote(op.declaration.Name), params)
		}
		m.line("    },")
	}
	for _, sig := range signals {
		if sig.send == "" {
			continue
		}
		data := "data"
		if sig.dataOptional() {
			data = "data: data ?? {}"
		}
		m.line("    %s(id, data, options) {", sig.send)
		m.line("      return client.signals.send({ schema: %s, instanceId: id, behavior: %s, name: %s, %s }, options);",
			schemaName, behaviortypes.TSQuote(sig.behavior), behaviortypes.TSQuote(sig.declaration.Name), data)
		m.line("    },")
	}
	m.line("  };")
	m.line("}")
	return nil
}
