// loadDocument loads one schema document from its JSON text.
func loadDocument(t *testing.T, reg *registry.Registry, text string) *ir.Schema {
	t.Helper()
	doc, err := jsonreader.ReadWith([]byte(text), "doc.schema.json", reg)
	if err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadDocument(doc, "doc.schema.json", loader.WithRegistry(reg))
	if err != nil {
		t.Fatal(err)
	}
	return schema
}

// Two schemas whose types share a name, or a type named like an export
// the module writes, are refused: one module cannot export both.
func TestRefusesCollidingExports(t *testing.T) {
	reg := coreRegistry(t)
	withBox := func(name string) string {
		return `{"kind": "General", "name": "` + name + `", "types": {
  "` + name + `": {"name": "` + name + `", "role": "EmbeddedStruct", "fields": [{"name": "box", "typeRef": {"name": "Box"}}]},
  "Box": {"name": "Box", "role": "EmbeddedStruct", "fields": [{"name": "w", "typeRef": {"name": "number"}}]}}}`
	}
	_, err := Generate([]*ir.Schema{loadDocument(t, reg, withBox("Shelf")), loadDocument(t, reg, withBox("Crate"))}, Options{Registry: reg})
	if want := "engine-client: schema Crate type Box and schema Shelf type Box would both export Box; generate their schemas into separate modules"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}

	patch := `{"kind": "General", "name": "Shelf", "types": {
  "Shelf": {"name": "Shelf", "role": "EmbeddedStruct", "fields": [{"name": "patch", "typeRef": {"name": "ShelfPatch"}}]},
  "ShelfPatch": {"name": "ShelfPatch", "role": "EmbeddedStruct", "fields": [{"name": "w", "typeRef": {"name": "number"}}]}}}`
	_, err = Generate([]*ir.Schema{loadDocument(t, reg, patch)}, Options{Registry: reg})
	if want := "engine-client: schema Shelf type ShelfPatch and schema Shelf would both export ShelfPatch; generate their schemas into separate modules"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}
}

