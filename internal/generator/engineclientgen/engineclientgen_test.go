// parityPath is the vector the engine's suite reads.
const parityPath = "runtime/engine/testdata/client_codegen_parity.json"

const parityComment = "Generated by internal/generator/engineclientgen (go test ./internal/generator/engineclientgen -run TestClientCodegenParity -update). " +
	"documents are engine schemas in the order an engine defines and publishes them. " +
	"For each schema, createParams is each behavior's create parameters as the generator narrows them for its config, which the engine's describe document must show in the same shape, descriptions aside; " +
	"fields is each behavior field's JSON Schema as the generator types it, by behavior name, then field name, with present true for one every read holds: a read's behaviors must hold an entry for each of these behaviors and no other, and its fields must satisfy them."

func coreRegistry(t *testing.T) *registry.Registry {
	t.Helper()
	return generator.CoreRegistry(naming.Default())
}

// loadSchemas loads schema documents as the engine-client command does.
func loadSchemas(t *testing.T, reg *registry.Registry, paths []string) []*ir.Schema {
	t.Helper()
	root := testpaths.RepoRoot(t)
	schemas := make([]*ir.Schema, 0, len(paths))
	for _, path := range paths {
		abs := filepath.Join(root, filepath.FromSlash(path))
		doc, err := jsonreader.ReadFileWith(abs, filepath.Base(abs), reg)
		if err != nil {
			t.Fatalf("read %s: %v", path, err)
		}
		schema, err := loader.LoadDocument(doc, filepath.Base(abs), loader.WithRegistry(reg))
		if err != nil {
			t.Fatalf("load %s: %v", path, err)
		}
		schemas = append(schemas, schema)
	}
	return schemas
}

// checkFile compares a generated file with the committed one, or writes it
// under -update.
func checkFile(t *testing.T, rel string, data []byte, rerun string) {
	t.Helper()
	path := filepath.Join(testpaths.RepoRoot(t), filepath.FromSlash(rel))
	if *update {
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run %s)", rel, err, rerun)
	}
	if !bytes.Equal(committed, data) {
		t.Errorf("%s is stale; run %s", rel, rerun)
	}
}

// TestGoldens keeps each committed module equal to what the generator
// writes for its schemas.
func TestGoldens(t *testing.T) {
	reg := coreRegistry(t)
	for _, golden := range goldens {
		module, err := Generate(loadSchemas(t, reg, golden.schemas), Options{Registry: reg, Naming: naming.Default()})
		if err != nil {
			t.Fatalf("%s: %v", golden.out, err)
		}
		checkFile(t, golden.out, module, "go test ./internal/generator/engineclientgen -update")
	}
}

type parityCorpus struct {
	Comment   string                  `json:"comment"`
	Documents []json.RawMessage       `json:"documents"`
	Schemas   map[string]paritySchema `json:"schemas"`
}

type paritySchema struct {
	CreateParams map[string]any `json:"createParams"`
	// Fields are the behavior fields by behavior name, then field name.
	Fields map[string]map[string]parityField `json:"fields"`
}

type parityField struct {
	Schema  any  `json:"schema"`
	Present bool `json:"present"`
}

// TestClientCodegenParity keeps runtime/engine/testdata/
// client_codegen_parity.json equal to the generator's narrowings for the
// fixture and notes schemas. The engine's suite holds its describe
// document's create parameters to createParams, and the behaviors' fields
// its reads return to fields.
func TestClientCodegenParity(t *testing.T) {
	reg := coreRegistry(t)
	root := testpaths.RepoRoot(t)
	corpus := parityCorpus{Comment: parityComment, Schemas: map[string]paritySchema{}}
	paths := append(append([]string(nil), fixtureSchemas...), notesSchemas...)
	for _, path := range paths {
		data, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err != nil {
			t.Fatal(err)
		}
		var compact bytes.Buffer
		if err := json.Compact(&compact, data); err != nil {
			t.Fatalf("%s: %v", path, err)
		}
		corpus.Documents = append(corpus.Documents, compact.Bytes())
	}
	models, err := buildModels(loadSchemas(t, reg, paths), reg)
	if err != nil {
		t.Fatal(err)
	}
	for _, model := range models {
		entry := paritySchema{CreateParams: map[string]any{}, Fields: map[string]map[string]parityField{}}
		aliases := map[string]any{}
		for _, behavior := range model.behaviors {
			for _, a := range behavior.narrowed.aliases {
				aliases[a.name] = a.schema
			}
		}
		for _, behavior := range model.behaviors {
			if behavior.narrowed.createParams != nil {
				entry.CreateParams[behavior.declaration.Name] = behavior.narrowed.createParams
			}
			if len(behavior.narrowed.fields) == 0 {
				continue
			}
			fields := map[string]parityField{}
			for name, shape := range behavior.narrowed.fields {
				resolved, err := resolveRefs(shape.schema, aliases)
				if err != nil {
					t.Fatalf("schema %s field %s.%s: %v", model.name, behavior.declaration.Name, name, err)
				}
				fields[name] = parityField{Schema: resolved, Present: shape.present}
			}
			entry.Fields[behavior.declaration.Name] = fields
		}
		corpus.Schemas[model.name] = entry
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(corpus); err != nil {
		t.Fatal(err)
	}
	checkFile(t, parityPath, buf.Bytes(), "go test ./internal/generator/engineclientgen -run TestClientCodegenParity -update")
}

// resolveRefs replaces each {"$ts": name} node with the alias it names, so
// a schema in the vector is plain JSON Schema.
func resolveRefs(schema any, aliases map[string]any) (any, error) {
	switch s := schema.(type) {
	case map[string]any:
		if name, ok := s[refKey].(string); ok {
			target, ok := aliases[name]
			if !ok {
				return nil, fmt.Errorf("%s is no alias of the type", name)
			}
			out := map[string]any{}
			for key, value := range target.(map[string]any) {
				out[key] = value
			}
			if description, ok := s["description"]; ok {
				out["description"] = description
			}
			return out, nil
		}
		out := make(map[string]any, len(s))
		for key, value := range s {
			resolved, err := resolveRefs(value, aliases)
			if err != nil {
				return nil, err
			}
			out[key] = resolved
		}
		return out, nil
	case []any:
		out := make([]any, len(s))
		for i, value := range s {
			resolved, err := resolveRefs(value, aliases)
			if err != nil {
				return nil, err
			}
			out[i] = resolved
		}
		return out, nil
	}
	return schema, nil
}

// TestNamingEnginePackage writes the client's import from the naming
// file's engine package.
func TestNamingEnginePackage(t *testing.T) {
	reg := coreRegistry(t)
	names := naming.Default()
	names.EngineNpmPackage = "@acme/engine"
	module, err := Generate(loadSchemas(t, reg, notesSchemas), Options{Registry: reg, Naming: names})
	if err != nil {
		t.Fatal(err)
	}
	text := string(module)
	if !strings.Contains(text, "from '@acme/engine/client'") || strings.Contains(text, "@superschematic/engine") {
		t.Fatalf("the module does not import the client from the naming file's engine package:\n%s", text[:400])
	}
}

// loadDocument loads one schema document from its JSON text.
func loadDocument(t *testing.T, reg *registry.Registry, text string) *ir.Schema {
	t.Helper()
	doc, err := jsonreader.ReadWith([]byte(text), "doc.schema.json", reg)
	if err != nil {
		t.Fatal(err)
	}
	schema, err := loader.LoadDocument(doc, "doc.schema.json", loader.WithRegistry(reg))
	if err != nil {
		t.Fatal(err)
	}
	return schema
}

// Two schemas whose types share a name, or a type named like an export
// the module writes, are refused: one module cannot export both.
func TestRefusesCollidingExports(t *testing.T) {
	reg := coreRegistry(t)
	withBox := func(name string) string {
		return `{"kind": "General", "name": "` + name + `", "types": {
  "` + name + `": {"name": "` + name + `", "role": "EmbeddedStruct", "fields": [{"name": "box", "typeRef": {"name": "Box"}}]},
  "Box": {"name": "Box", "role": "EmbeddedStruct", "fields": [{"name": "w", "typeRef": {"name": "number"}}]}}}`
	}
	_, err := Generate([]*ir.Schema{loadDocument(t, reg, withBox("Shelf")), loadDocument(t, reg, withBox("Crate"))}, Options{Registry: reg})
	if want := "engine-client: schema Crate type Box and schema Shelf type Box would both export Box; generate their schemas into separate modules"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}

	patch := `{"kind": "General", "name": "Shelf", "types": {
  "Shelf": {"name": "Shelf", "role": "EmbeddedStruct", "fields": [{"name": "patch", "typeRef": {"name": "ShelfPatch"}}]},
  "ShelfPatch": {"name": "ShelfPatch", "role": "EmbeddedStruct", "fields": [{"name": "w", "typeRef": {"name": "number"}}]}}}`
	_, err = Generate([]*ir.Schema{loadDocument(t, reg, patch)}, Options{Registry: reg})
	if want := "engine-client: schema Shelf type ShelfPatch and schema Shelf would both export ShelfPatch; generate their schemas into separate modules"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}
}

// A schema the engine would refuse is refused: another kind, and a
// Variants config whose types are not the schema's.
func TestRefusesWhatTheEngineRefuses(t *testing.T) {
	reg := coreRegistry(t)
	variants := `{"kind": "General", "name": "Step", "scalars": {"Generic.JSON": {"name": "Generic.JSON", "languagePrimitive": "string"}}, "types": {
  "Step": {"name": "Step", "role": "EmbeddedStruct",
    "behaviors": [{"name": "Variants", "config": {"field": "result", "by": "kind", "types": {"fetch": "Step"}}}],
    "fields": [{"name": "kind", "typeRef": {"name": "string"}}, {"name": "result", "typeRef": {"name": "Generic.JSON"}}]}}}`
	_, err := Generate([]*ir.Schema{loadDocument(t, reg, variants)}, Options{Registry: reg})
	if want := "engine-client: type Step of schema Step: behavior Variants: types: Step is not a type of the schema besides Step"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}

	db := ir.NewSchema("shop", ir.SchemaKindDB)
	db.Types["shop"] = &ir.TypeDef{Name: "shop"}
	_, err = Generate([]*ir.Schema{db}, Options{Registry: reg})
	if want := "engine-client: schema shop is of kind DB; the engine runs General schemas"; err == nil || err.Error() != want {
		t.Fatalf("err = %v, want %q", err, want)
	}
}

// Each core narrowing types only fields its behavior declares, so a field a
// declaration renames fails here, whether or not a golden composes the
// behavior. Variants is left out: its config names the type's own fields,
// and it declares none.
func TestCoreNarrowingsTypeDeclaredFields(t *testing.T) {
	reg := coreRegistry(t)
	document := ir.NewSchema("items", ir.SchemaKindGeneral)
	target := narrowTarget{schema: "items", base: "Item", document: document, instance: &ir.TypeDef{Name: "Item"}}
	for _, name := range sortedKeys(coreNarrowers) {
		if name == "Variants" {
			continue
		}
		declaration, ok := reg.Behavior(name)
		if !ok {
			t.Errorf("%s has a narrowing and no declaration", name)
			continue
		}
		if _, err := narrow(declaration, nil, target); err != nil {
			t.Errorf("%s: %v", name, err)
		}
	}
}
