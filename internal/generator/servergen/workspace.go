// The Cargo workspace of the Rust servers, jobs and workers (D57, D65;
// docs/stack-model.md, section 8.6), the twin of the Bun workspace D51
// roots at the output root. `<output-root>/Cargo.toml` is a virtual
// manifest whose members are the crates of the Rust servers, jobs and
// workers of every stack built into the output root,
// `server/<stack>/<deployable>`, and its lockfile, `<output-root>/Cargo.lock`,
// pins every crate they reach: the generated API, SDK and types crates and
// the mirrors of the implementations under `impl/` (D65; mirror.go) are
// path dependencies, not members, and land in the lockfile all the same.
// The lockfile lies outside `server/<stack>`, which each
// build of a stack empties, so it outlasts every build, and the project
// commits it (D51, amended), as it commits bun.lock: a server's image and
// the generated CI build with `--locked` from it.
//
// The members are the crates on disk once a stack's build writes its own,
// so the root names the Rust servers, jobs and workers of every stack the
// output root holds, and is the same bytes on every build of the same schemas.
// A pattern cannot name them: `server/*/*` holds the Go and TypeScript
// servers too, whose directories have no Cargo.toml, which Cargo refuses
// in a member. The root excludes `api`, `engine`, `sdk` and `types`, so a
// generated crate under them, a project's engine crate (D58) among them,
// is no member, though it lies under the root, and builds on its own as
// it did before the root existed: Cargo refuses a crate under a
// workspace's root that the workspace neither lists nor excludes. It
// excludes `impl` too, so a mirror is a path dependency, as the
// implementation it copies was, and no member: Cargo would make a path
// dependency under the root one, and resolve a member's dev-dependencies
// into the lockfile.

// RustWorkspaceFile is the Cargo workspace's root, and RustLockfileName
// its lockfile, both in the output root.
const (
	RustWorkspaceFile = "Cargo.toml"
	RustLockfileName  = "Cargo.lock"
)

// rustWorkspaceHeader opens the root's manifest, by which a build knows
// the file is its own.
const rustWorkspaceHeader = "# Code generated by superschematic. DO NOT EDIT.\n"

// rustWorkspaceExclude are the directories of the output root whose
// crates are no members of the workspace: the generated crates, a
// project's engine crate among them, which build on their own, and the
// implementations' mirrors.
var rustWorkspaceExclude = []string{"api", "engine", MirrorRoot, "sdk", "types"}

// RustWorkspaceMembers lists the crates of the Rust servers, jobs and
// workers the output root holds, `server/<stack>/<deployable>` with a
// Cargo.toml, slash-separated and sorted.
func RustWorkspaceMembers(outputRoot string) ([]string, error) {
	matches, err := filepath.Glob(filepath.Join(outputRoot, "server", "*", "*", RustManifestFile))
	if err != nil {
		return nil, err
	}
	members := make([]string, 0, len(matches))
	for _, m := range matches {
		rel, err := filepath.Rel(outputRoot, filepath.Dir(m))
		if err != nil {
			return nil, err
		}
		members = append(members, filepath.ToSlash(rel))
	}
	slices.Sort(members)
	return members, nil
}

// RustWorkspaceManifest is the root's Cargo.toml for members.
func RustWorkspaceManifest(members []string) string {
	var b strings.Builder
	b.WriteString(rustWorkspaceHeader)
	b.WriteString(`#
# The Cargo workspace of the Rust servers, jobs and workers of the stacks
# built into this output root (D57, D65; docs/stack-model.md, section 8.6):
# each member is the crate of a server, a job or a worker, which each
# build of its stack writes. The generated crates they depend on and the
# implementations' mirrors under impl/, which each build copies, are path
# dependencies, so Cargo.lock beside this file pins every crate they reach.
# Commit Cargo.lock: the images and the generated CI build with --locked
# from it, and the stack's build brings it up to date.
[workspace]
resolver = "2"
members = [
`)
	for _, m := range members {
		fmt.Fprintf(&b, "    %s,\n", quoteToml(m))
	}
	b.WriteString("]\n")
	b.WriteString("# The generated crates under the output root build on their own too, and\n# the mirrors are path dependencies, whose dev-dependencies the lockfile\n# leaves out.\n")
	quoted := make([]string, len(rustWorkspaceExclude))
	for i, e := range rustWorkspaceExclude {
		quoted[i] = quoteToml(e)
	}
	fmt.Fprintf(&b, "exclude = [%s]\n", strings.Join(quoted, ", "))
	return b.String()
}

// WriteRustWorkspace writes the root's Cargo.toml into outputRoot for the
// crates of the Rust servers, jobs and workers on disk, and reports
// whether it names any. With none it removes a root an earlier build
// wrote, which would otherwise name members that are gone, and leaves the
// lockfile, which the project commits. The write is atomic and skipped
// when the file has the same content.
func WriteRustWorkspace(outputRoot string) (bool, error) {
	members, err := RustWorkspaceMembers(outputRoot)
	if err != nil {
		return false, fmt.Errorf("servergen: the Cargo workspace: %w", err)
	}
	target := filepath.Join(outputRoot, RustWorkspaceFile)
	existing, err := os.ReadFile(target)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return false, fmt.Errorf("servergen: the Cargo workspace: %w", err)
	}
	if len(members) == 0 {
		if err == nil && bytes.HasPrefix(existing, []byte(rustWorkspaceHeader)) {
			if err := os.Remove(target); err != nil {
				return false, fmt.Errorf("servergen: the Cargo workspace: %w", err)
			}
		}
		return false, nil
	}
	if err == nil && !bytes.HasPrefix(existing, []byte(rustWorkspaceHeader)) {
		return false, fmt.Errorf("servergen: %s is not the Cargo workspace a build writes, and the build owns that file: move it, or its crates, out of the output root", target)
	}
	manifest := RustWorkspaceManifest(members)
	if string(existing) == manifest {
		return true, nil
	}
	tmp, err := os.CreateTemp(outputRoot, ".Cargo.toml-*")
	if err != nil {
		return false, fmt.Errorf("servergen: stage the Cargo workspace: %w", err)
	}
	name := tmp.Name()
	_, err = tmp.WriteString(manifest)
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err == nil {
		err = os.Chmod(name, 0o644)
	}
	if err == nil {
		err = os.Rename(name, target)
	}
	if err != nil {
		_ = os.Remove(name)
		return false, fmt.Errorf("servergen: write the Cargo workspace: %w", err)
	}
	return true, nil
}

// UpdateRustLockfile brings the workspace's lockfile in outputRoot up to
// date with the crates its members reach, with `cargo update --workspace`:
// it writes the lockfile when there is none, adds what a crate gained and
// drops what none needs, and changes no version it pinned of a crate that
// is still needed. So a committed lockfile follows the schemas and the
// implementations through each build, as stack dev's bun install keeps
// bun.lock (D51, amended), and changes only when a manifest does. cargo
// reads the crates.io index, so the update needs the network when the
// lockfile lacks a crate. It returns cargo's output with its error.
func UpdateRustLockfile(cargo, outputRoot string) error {
	cmd := exec.Command(cargo, "update", "--workspace", "--quiet")
	cmd.Dir = outputRoot
	out, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s update --workspace in %s: %w: %s", cargo, outputRoot, err, strings.TrimSpace(string(out)))
	}
	return nil
}
