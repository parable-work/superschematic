// The mirror of a TypeScript implementation (D65, amended;
// docs/stack-model.md, section 8.6), the twin of a Rust one (mirror.go).
// The package the project edits, at the naming file's
// [implementation_paths] typescript template, is a member of the default
// output root's Bun workspace, `<schemas-root>/dist`, and an install links
// a member's node_modules into the root that installs it. A second output
// root that listed the package too, as `stack dev --out` writes, would
// relink them into itself, and leave them dangling once it was gone. So
// each build of a stack into any other output root copies each
// TypeScript implementation its servers, jobs and workers build against
// into `<output-root>/impl/<service>/`, and that root's workspace lists
// the copies, `impl/*`, in place of the project's packages (tsgen's
// workspace.go): a server's package.json names the implementation by its
// package's name, which the copy keeps, so it resolves to the root's own
// copy, and the project's node_modules stay the default root's. A build
// into the default root copies nothing: its servers build against the
// project's packages, its members, as before.
//
// The mirror holds the package's files, as a checkout of the package holds
// them:
//
//   - package.json, written in its place: the package's, each member in
//     its order, with a first member "//" saying it is a mirror a build
//     writes, by which a build knows the directory as its own, and each
//     dependency on a path (file:, link:, or ./ and ../) re-based for the
//     mirror's directory: one into the default output root names the same
//     place under the current one, one inside the package is left as it
//     is, since the mirror holds it, and any other names the same
//     directory. A dependency by name or with workspace: needs none.
//   - every other file, by the walk a Rust mirror selects its files by,
//     with the package's .gitignore files' rules: not `.git`, a
//     node_modules directory at any depth, which the output root's install
//     links anew, or the root's bun.lock or bun.lockb, the lockfile of an
//     install of the package alone, which the output root's lockfile
//     stands in for. A TypeScript package has no build directory its
//     toolchain fixes, as Cargo's target/: the package's .gitignore files
//     say what its build writes.
//
// A build copies only the files whose content changed and removes the
// mirror's files the package no longer has, as a Rust mirror's does, and
// removes a mirror no server, job or worker package under the output root
// depends on.

// typeScriptMirrorNotice opens the "//" member of a mirror's package.json.
const typeScriptMirrorNotice = "Code generated by superschematic. DO NOT EDIT."

// typeScriptDependencyTables are the members of a package.json whose
// entries are dependencies.
var typeScriptDependencyTables = []string{"dependencies", "devDependencies", "optionalDependencies", "peerDependencies"}

// TypeScriptMirror is the plan of one TypeScript implementation's mirror,
// or of a site's (D55; PlanSiteMirror).
type TypeScriptMirror struct {
	Service string

	// Site is set for the mirror of a site's package, which the site's
	// build writes and the site builds in, rather than of an
	// implementation a server, job or worker builds against.
	Site bool

	// Package is the implementation's npm name, which the mirror keeps.
	Package string

	// Source is the implementation package's directory, Dir the mirror's,
	// MirrorDir, OutputRoot the output root it lies in, and DefaultRoot
	// the default output root, whose places a path dependency into it
	// names under OutputRoot instead; each absolute.
	Source      string
	Dir         string
	OutputRoot  string
	DefaultRoot string
}

// planTypeScriptMirror plans the mirror under outputRoot of the
// implementation of API a, given defaultRoot, the default output root, and
// checks the package's manifest when it is on disk; a scaffold the build
// is about to write needs no checking.
func planTypeScriptMirror(outputRoot, defaultRoot string, a TypeScriptAPIInput) (*TypeScriptMirror, error) {
	return newTypeScriptMirror(&TypeScriptMirror{Service: a.Output.SchemaName, Package: a.Implementation.Package}, a.Implementation.Dir, outputRoot, defaultRoot)
}

// PlanSiteMirror plans the mirror under outputRoot of the package of the
// site service, at dir, given defaultRoot, the default output root (D55;
// D65, amended). The mirror is a TypeScript implementation's, in the same
// place, `<output-root>/impl/<site>/`: the output root's Bun workspace
// lists it, `impl/*`, in place of the project's site, so its install links
// the mirror's node_modules and leaves the package's, and the site builds
// in the mirror, against the root's own SDKs (tsgen.SiteDir).
func PlanSiteMirror(outputRoot, defaultRoot, site, dir string) (*TypeScriptMirror, error) {
	return newTypeScriptMirror(&TypeScriptMirror{Service: site, Site: true}, dir, outputRoot, defaultRoot)
}

// newTypeScriptMirror fills in m's directories, from source, the package's,
// outputRoot and defaultRoot, and checks the package's manifest when it is
// on disk; a scaffold the build is about to write needs no checking. It
// takes the package's name from its manifest when m names none.
func newTypeScriptMirror(m *TypeScriptMirror, source, outputRoot, defaultRoot string) (*TypeScriptMirror, error) {
	var err error
	for _, p := range []struct {
		dst  *string
		from string
	}{
		{&m.Source, source},
		{&m.OutputRoot, outputRoot},
		{&m.Dir, MirrorDir(outputRoot, m.Service)},
		{&m.DefaultRoot, defaultRoot},
	} {
		if p.from == "" {
			continue
		}
		if *p.dst, err = filepath.Abs(p.from); err != nil {
			return nil, err
		}
	}
	if within(m.Dir, m.Source) || within(m.Source, m.Dir) {
		template := "typescript"
		if m.Site {
			template = "site"
		}
		return nil, m.errorf("lies in or around its mirror's directory, %s, which each build rewrites; move the package, with the naming file's [implementation_paths] %s", m.Dir, template)
	}
	if source, err := os.ReadFile(filepath.Join(m.Source, TypeScriptPackageFile)); err == nil {
		if _, err := m.manifest(source); err != nil {
			return nil, err
		}
		if m.Package == "" {
			var pkg struct {
				Name string `json:"name"`
			}
			_ = json.Unmarshal(source, &pkg)
			m.Package = pkg.Name
		}
	} else if !errors.Is(err, fs.ErrNotExist) {
		return nil, m.errorf("%w", err)
	}
	return m, nil
}

// errorf is an error about the implementation m mirrors, named with its
// directory.
func (m *TypeScriptMirror) errorf(format string, args ...any) error {
	if m.Site {
		return fmt.Errorf("the site %s, at %s, "+format, append([]any{m.Service, m.Source}, args...)...)
	}
	return fmt.Errorf("the implementation of %s, at %s, "+format, append([]any{m.Service, m.Source}, args...)...)
}

// typeScriptSiteMirrorNotice opens the "//" member of a site's mirror's
// package.json, after typeScriptMirrorNotice.
const typeScriptSiteMirrorNotice = typeScriptMirrorNotice + " The mirror of the site "

// notice is the "//" member of the mirror's package.json.
func (m *TypeScriptMirror) notice() string {
	source, err := naming.RelPath(m.Dir, m.Source)
	if err != nil {
		source = filepath.ToSlash(m.Source)
	}
	if m.Site {
		return typeScriptSiteMirrorNotice + m.Service + ", the package at " + source +
			" (D55; D65, amended; docs/stack-model.md, section 8.10). Each build of the site into this output root copies the package's files here" +
			" and writes this file from its package.json, with each dependency on a path re-based for this directory." +
			" The site builds here, against this output root's SDKs, and its Bun workspace lists the mirror in place of the package." +
			" Edit the package, not the mirror."
	}
	return typeScriptMirrorNotice + " The mirror of the implementation of " + m.Service + ", the package at " + source +
		" (D65; docs/stack-model.md, section 8.6). Each build of a stack into this output root copies the package's files here" +
		" and writes this file from its package.json, with each dependency on a path re-based for this directory." +
		" This output root's servers, jobs and workers build against the mirror, which its Bun workspace lists in place of the package." +
		" Edit the package, not the mirror."
}

// manifest returns the mirror's package.json for the package's, source.
func (m *TypeScriptMirror) manifest(source []byte) ([]byte, error) {
	doc, err := parseJSONObject(source)
	if err != nil {
		return nil, m.errorf("has a package.json that does not parse: %w", err)
	}
	notice, err := jsonString(m.notice())
	if err != nil {
		return nil, err
	}
	out := jsonObject{{Key: "//", Value: notice}}
	for _, member := range doc {
		if member.Key == "//" {
			// The package's own comment: the notice takes its place.
			continue
		}
		if slices.Contains(typeScriptDependencyTables, member.Key) {
			deps, err := parseJSONObject(member.Value)
			if err != nil {
				return nil, m.errorf("has a package.json whose %s is not an object: %w", member.Key, err)
			}
			for i, dep := range deps {
				var spec string
				if json.Unmarshal(dep.Value, &spec) != nil {
					continue
				}
				rebased, err := m.rebaseSpec(spec)
				if err != nil {
					return nil, m.errorf("its %s %s: %w", member.Key, dep.Key, err)
				}
				if rebased != spec {
					if deps[i].Value, err = jsonString(rebased); err != nil {
						return nil, err
					}
				}
			}
			if member.Value, err = deps.MarshalJSON(); err != nil {
				return nil, err
			}
		}
		out = append(out, member)
	}
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(out); err != nil {
		return nil, m.errorf("package.json: %w", err)
	}
	return b.Bytes(), nil
}

// rebaseSpec is the mirror's spec for the package's dependency spec: a
// path, `file:<path>`, `link:<path>`, or one that starts ./ or ../, re-based
// (rebase), and any other as it is.
func (m *TypeScriptMirror) rebaseSpec(spec string) (string, error) {
	protocol, p := "", spec
	switch {
	case strings.HasPrefix(spec, "file:"), strings.HasPrefix(spec, "link:"):
		protocol, p = spec[:5], spec[5:]
	case strings.HasPrefix(spec, "./"), strings.HasPrefix(spec, "../"):
	default:
		return spec, nil
	}
	rebased, err := m.rebase(p)
	if err != nil {
		return "", err
	}
	return protocol + rebased, nil
}

// rebase is the mirror's path for the package's path dependency p: one
// inside the package as it is, which the mirror holds; one into the
// default output root the same place under the current one; one outside
// both the same directory, from the mirror's, or as it is when absolute.
// A relative path climbs from the mirror's physical path, the one Bun
// resolves it from (naming.PhysicalRelPath).
func (m *TypeScriptMirror) rebase(p string) (string, error) {
	target := filepath.FromSlash(p)
	if !filepath.IsAbs(target) {
		target = filepath.Join(m.Source, target)
	}
	target = filepath.Clean(target)
	switch {
	case within(m.Source, target):
		return p, nil
	case m.DefaultRoot != "" && within(m.DefaultRoot, target):
		rel, err := filepath.Rel(m.DefaultRoot, target)
		if err != nil {
			return "", err
		}
		target = filepath.Join(m.OutputRoot, rel)
	case filepath.IsAbs(filepath.FromSlash(p)):
		return p, nil
	}
	rel, err := naming.PhysicalRelPath(m.Dir, target)
	if err != nil {
		return "", err
	}
	if rel != "." && !strings.HasPrefix(rel, "../") {
		rel = "./" + rel
	}
	return rel, nil
}

// skipTypeScript is what a TypeScript mirror leaves out by the
// toolchain's rules: a node_modules directory at any depth, which an
// install links, and the root's package.json, which the mirror writes,
// and its bun.lock or bun.lockb.
func skipTypeScript(rel, name, _ string, dir bool) bool {
	if dir {
		return name == "node_modules"
	}
	return rel == "" && (name == TypeScriptPackageFile || name == tsgen.LockfileName || name == "bun.lockb")
}

// WriteTypeScriptMirror brings the mirror m up to date with its package:
// it writes each file whose content differs from the package's, and the
// manifest, and removes every other file. It refuses a directory a build
// did not write.
func WriteTypeScriptMirror(m *TypeScriptMirror) error {
	fail := func(err error) error {
		if m.Site {
			return fmt.Errorf("servergen: the mirror of the site %s: %w", m.Service, err)
		}
		return fmt.Errorf("servergen: the mirror of %s's implementation: %w", m.Service, err)
	}
	source, err := os.ReadFile(filepath.Join(m.Source, TypeScriptPackageFile))
	if err != nil {
		return fail(err)
	}
	manifest, err := m.manifest(source)
	if err != nil {
		return fail(err)
	}
	files, err := packageFiles(m.Source, mirrorSelection{}, skipTypeScript)
	if err != nil {
		return fail(err)
	}
	if existing, err := os.ReadFile(filepath.Join(m.Dir, TypeScriptPackageFile)); err == nil && !isTypeScriptMirror(existing) {
		return fail(fmt.Errorf("%s holds a package.json no build wrote, and the build owns that directory: move the package out of the output root", m.Dir))
	} else if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return fail(err)
	}
	if err := writeMirror(m.Source, m.Dir, files, TypeScriptPackageFile, manifest); err != nil {
		return fail(err)
	}
	return nil
}

// isTypeScriptMirror reports whether manifest, a package.json, is one a
// build wrote for a mirror.
func isTypeScriptMirror(manifest []byte) bool {
	return strings.HasPrefix(mirrorNotice(manifest), typeScriptMirrorNotice)
}

// mirrorNotice is the "//" member of manifest, a package.json, or "".
func mirrorNotice(manifest []byte) string {
	var doc struct {
		Notice string `json:"//"`
	}
	if json.Unmarshal(manifest, &doc) != nil {
		return ""
	}
	return doc.Notice
}

// PruneTypeScriptMirrors removes each TypeScript mirror under outputRoot's
// impl/ that no package under server/ depends on, whichever stack's it is,
// but a site's whose package is named in sites, the project's sites, or,
// when the output root is not mirrored (tsgen.Mirrored), every one, whose
// name would clash with the project's package in the workspace; and impl/
// itself once it is empty. It leaves a directory there whose package.json
// no build wrote, and every Rust mirror (PruneRustMirrors).
func PruneTypeScriptMirrors(outputRoot string, mirrored bool, sites []string) error {
	fail := func(err error) error {
		return fmt.Errorf("servergen: the mirrors of the TypeScript implementations: %w", err)
	}
	outputRoot, err := filepath.Abs(outputRoot)
	if err != nil {
		return fail(err)
	}
	root := filepath.Join(outputRoot, MirrorRoot)
	entries, err := os.ReadDir(root)
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fail(err)
	}
	used := map[string]bool{}
	if mirrored {
		packages, err := filepath.Glob(filepath.Join(outputRoot, "server", "*", "*", TypeScriptPackageFile))
		if err != nil {
			return fail(err)
		}
		for _, file := range packages {
			data, err := os.ReadFile(file)
			if err != nil {
				return fail(err)
			}
			var pkg struct {
				Dependencies    map[string]string `json:"dependencies"`
				DevDependencies map[string]string `json:"devDependencies"`
			}
			if err := json.Unmarshal(data, &pkg); err != nil {
				return fail(fmt.Errorf("%s: %w", file, err))
			}
			for name := range pkg.Dependencies {
				used[name] = true
			}
			for name := range pkg.DevDependencies {
				used[name] = true
			}
		}
	}
	for _, e := range entries {
		dir := filepath.Join(root, e.Name())
		if !e.IsDir() {
			continue
		}
		manifest, err := os.ReadFile(filepath.Join(dir, TypeScriptPackageFile))
		if err != nil || !isTypeScriptMirror(manifest) {
			continue
		}
		var pkg struct {
			Name string `json:"name"`
		}
		if json.Unmarshal(manifest, &pkg) == nil && mirrored {
			site := strings.HasPrefix(mirrorNotice(manifest), typeScriptSiteMirrorNotice)
			if used[pkg.Name] && !site || site && slices.Contains(sites, pkg.Name) {
				continue
			}
		}
		if err := os.RemoveAll(dir); err != nil {
			return fail(err)
		}
	}
	if left, err := os.ReadDir(root); err == nil && len(left) == 0 {
		if err := os.Remove(root); err != nil {
			return fail(err)
		}
	}
	return nil
}

// jsonMember is one member of a JSON object, its value as the source
// wrote it.
type jsonMember struct {
	Key   string
	Value json.RawMessage
}

// jsonObject is a JSON object whose members keep their order, so a
// package.json written from another reads as it did.
type jsonObject []jsonMember

// parseJSONObject reads data, which must hold one JSON object.
func parseJSONObject(data []byte) (jsonObject, error) {
	dec := json.NewDecoder(bytes.NewReader(data))
	tok, err := dec.Token()
	if err != nil {
		return nil, err
	}
	if d, ok := tok.(json.Delim); !ok || d != '{' {
		return nil, errors.New("not a JSON object")
	}
	obj := jsonObject{}
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		key, ok := tok.(string)
		if !ok {
			return nil, fmt.Errorf("a member named by %v", tok)
		}
		var value json.RawMessage
		if err := dec.Decode(&value); err != nil {
			return nil, err
		}
		obj = append(obj, jsonMember{Key: key, Value: value})
	}
	if _, err := dec.Token(); err != nil {
		return nil, err
	}
	if _, err := dec.Token(); err != io.EOF {
		return nil, errors.New("more than one JSON value")
	}
	return obj, nil
}

// MarshalJSON writes the object's members in their order.
func (o jsonObject) MarshalJSON() ([]byte, error) {
	var b bytes.Buffer
	b.WriteByte('{')
	for i, m := range o {
		if i > 0 {
			b.WriteByte(',')
		}
		key, err := jsonString(m.Key)
		if err != nil {
			return nil, err
		}
		b.Write(key)
		b.WriteByte(':')
		b.Write(m.Value)
	}
	b.WriteByte('}')
	return b.Bytes(), nil
}

// jsonString is s as a JSON string, its HTML characters as they are, as a
// package.json writes them.
func jsonString(s string) (json.RawMessage, error) {
	var b bytes.Buffer
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(s); err != nil {
		return nil, err
	}
	return bytes.TrimSuffix(b.Bytes(), []byte("\n")), nil
}
