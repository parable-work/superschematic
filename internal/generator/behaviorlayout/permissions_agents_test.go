package behaviorlayout_test

import (
	"path/filepath"
	"testing"

	"github.com/parable-work/superschematic/internal/generator/behaviorlayout"
	"github.com/parable-work/superschematic/internal/generator/naming"
	"github.com/parable-work/superschematic/internal/loader"
	"github.com/parable-work/superschematic/internal/registry"
	ir "github.com/parable-work/superschematic/ir"
)

// The layout of a schema with Approvals, the identity tables and an
// @agents("definitions") class also names where an Agent's permissions
// are read (#625): the definitions table, its key, the column of the role
// each agent acts with, and the roles' name column the role names a row
// by.
func TestTheLayoutNamesWhereAnAgentsPermissionsAreRead(t *testing.T) {
	reg := registry.New(naming.Default())
	schema, err := loader.LoadService(filepath.FromSlash("../../loader/tsreader/testdata/services/fixture-approvals-identity-db"), loader.WithRegistry(reg))
	if err != nil {
		t.Fatal(err)
	}
	schema.Types["Agent"] = &ir.TypeDef{Name: "Agent", Role: ir.RoleDBTable, Agents: &ir.AgentsDef{Part: ir.AgentDefinitions}, Fields: []*ir.FieldDef{
		{Name: "id", TypeRef: ir.TypeRef{Name: "Identity.UUID"}, Required: true, Key: true, AutoGenerated: true},
		{Name: "name", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
		{Name: "role", TypeRef: ir.TypeRef{Name: "string"}, Required: true},
	}}
	layout, err := behaviorlayout.Of(schema, reg)
	if err != nil {
		t.Fatal(err)
	}
	p := layout.Permissions
	if p == nil || p.Agents != "agent" || p.Agent == nil || *p.Agent != (behaviorlayout.Column{Field: "id", Column: "id", Type: "Identity.UUID"}) || p.AgentRole != "role" || p.RoleName != "name" {
		t.Fatalf("the layout's permissions = %+v (agent %+v)", p, p.Agent)
	}
}
