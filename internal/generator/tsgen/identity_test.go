// TestWriteTypesExportsTheIdentityDescriptor: a schema with a User table
// gets identity.ts, exporting identityDescriptor as the descriptor's
// object literal; index.ts re-exports it and package.json exports
// "./identity". Writing a schema without one over the package removes
// identity.ts and both exports.
func TestWriteTypesExportsTheIdentityDescriptor(t *testing.T) {
	schema := identitytest.Schema(t, identitytest.Options{Roles: true, Name: "displayName"})
	d, ok, err := identitydesc.Describe(schema)
	if err != nil || !ok {
		t.Fatalf("Describe = %v, %v", ok, err)
	}
	document, err := d.JSON()
	if err != nil {
		t.Fatal(err)
	}
	clock := codegen.FixedClock(time.Date(2026, 1, 2, 3, 4, 5, 0, time.UTC))
	write := func(name string, output *ModuleOutput, err error, dir string) {
		t.Helper()
		if err != nil {
			t.Fatalf("generate %s: %v", name, err)
		}
		if err := WriteTypes(output, dir); err != nil {
			t.Fatalf("write %s: %v", name, err)
		}
	}
	dir := t.TempDir()
	output, err := Generate(schema, Options{SchemaName: identitytest.Service, Clock: clock})
	write(identitytest.Service, output, err, dir)
	read := func(name string) string {
		t.Helper()
		b, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	literal := "export const identityDescriptor = " + strings.TrimSuffix(string(document), "\n") + " as const;\n"
	if got := read("identity.ts"); !strings.HasSuffix(got, literal) || !strings.HasPrefix(got, "// Code generated by tsgen. DO NOT EDIT.\n") {
		t.Fatalf("identity.ts does not end with the descriptor:\n%s", got)
	}
	const reexport = "\n\n// Re-export the identity descriptor\nexport { identityDescriptor } from './identity';\n"
	if got := read("index.ts"); !strings.HasSuffix(got, "export * from './mask';"+reexport) {
		t.Fatalf("index.ts does not re-export identityDescriptor:\n%s", got)
	}
	var manifest struct {
		Exports map[string]map[string]string `json:"exports"`
	}
	if err := json.Unmarshal([]byte(read("package.json")), &manifest); err != nil {
		t.Fatalf("package.json: %v", err)
	}
	if got := manifest.Exports["./identity"]; got["types"] != "./identity.ts" || got["import"] != "./identity.ts" {
		t.Fatalf(`package.json exports "./identity" as %v, want ./identity.ts`, got)
	}

	plain, err := loader.LoadService(filepath.Join(fixturesDir, "fixture-db"))
	if err != nil {
		t.Fatal(err)
	}
	output, err = Generate(plain, Options{SchemaName: identitytest.Service, Clock: clock})
	write("fixture-db", output, err, dir)
	if _, err := os.Stat(filepath.Join(dir, "identity.ts")); !os.IsNotExist(err) {
		t.Errorf("a schema without a User table leaves identity.ts behind: %v", err)
	}
	for _, name := range []string{"index.ts", "package.json"} {
		if got := read(name); strings.Contains(got, "./identity") || strings.Contains(got, "identityDescriptor") {
			t.Errorf("%s of a schema without a User table names the identity descriptor:\n%s", name, got)
		}
	}
}

// TestIdentityDescriptorCompiles type-checks the identity schema's package
// and reads identityDescriptor from its root and from identity.ts with
// bun: each is the descriptor document. Skips when bun is unavailable.
func TestIdentityDescriptorCompiles(t *testing.T) {
	if testing.Short() {
		t.Skip("skipping compile check in -short mode")
	}
	schema := identitytest.Schema(t, identitytest.Options{Roles: true, Name: "displayName"})
	d, ok, err := identitydesc.Describe(schema)
	if err != nil || !ok {
		t.Fatalf("Describe = %v, %v", ok, err)
	}
	want, err := json.Marshal(d)
	if err != nil {
		t.Fatal(err)
	}
	typesRoot, bunPath := buildTSPackages(t, []tsPackageCase{{name: identitytest.Service, schema: schema}})
	pkgDir := filepath.Join(typesRoot, identitytest.Service)
	const driver = `import { identityDescriptor } from './index.ts';
import { identityDescriptor as fromFile } from './identity.ts';

console.log(JSON.stringify(identityDescriptor));
console.log(JSON.stringify(fromFile));
`
	if err := os.WriteFile(filepath.Join(pkgDir, "identity_driver.ts"), []byte(driver), 0o644); err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command(bunPath, "run", "identity_driver.ts")
	cmd.Dir = pkgDir
	out, err := cmd.Output()
	if err != nil {
		t.Fatalf("driver failed: %v\n%s", err, out)
	}
	if got := string(out); got != string(want)+"\n"+string(want)+"\n" {
		t.Fatalf("identityDescriptor is\n%s\nwant %s twice", got, want)
	}
}
