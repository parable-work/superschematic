pub fn ask(runtime: &mut Runtime, request: Value) -> Result<Value, Refusal> {
    runtime.answer(&caller(), &request)
}

pub fn ok(runtime: &mut Runtime, request: Value) -> Value {
    match ask(runtime, request.clone()) {
        Ok(answer) => answer,
        Err(refusal) => panic!("{request} was refused: {refusal:?}"),
    }
}

pub fn create(runtime: &mut Runtime, type_name: &str, data: Value) -> Value {
    ok(
        runtime,
        json!({"kind": "create", "type": type_name, "data": data}),
    )
}

fn hazard_ids(answer: &Value) -> Vec<String> {
    answer["hazards"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|hazard| hazard["id"].as_str().map(str::to_owned))
        .collect()
}

/// Holds a plan to a step on each subject named.
pub fn assert_plans(plan: &Value, subjects: &[&str]) {
    let steps: Vec<&str> = plan["steps"]
        .as_array()
        .expect("steps")
        .iter()
        .filter_map(|step| step["subject"].as_str())
        .collect();
    for subject in subjects {
        assert!(
            steps.iter().any(|step| step.contains(subject)),
            "no step on {subject}: {steps:?}"
        );
    }
}

/// A schema published to an empty database, then a second version that
/// adds a field, a relation and an index: rows written and read through
/// the handler before and after, and a second server that follows the
/// publish with no restart.
pub fn publish_and_extend(open: Open<'_>, binaries: &Binaries) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    let first = runtime
        .publish(&Publish::of(vec![v1()]))
        .expect("v1 publishes");
    assert_eq!(
        first["from"], "",
        "the first plan starts from an empty database"
    );
    assert_eq!(first["applied"], true);
    assert_eq!(first["versions"], json!({"Project": 1, "Task": 1}));

    let project = create(&mut runtime, "Project", json!({"name": "Desk"}));
    let task = create(&mut runtime, "Task", json!({"title": "Sand it"}));
    assert_eq!(task["status"], "open", "Workflow's initial state");
    assert_eq!(task["_version"], 1);
    let task_id = task["id"].as_str().expect("a key").to_owned();
    let read = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": task_id}),
    );
    assert_eq!(read["title"], "Sand it");
    let refused = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Project", "data": {"name": "Desk"}}),
    )
    .expect_err("a unique name held twice");
    assert_eq!(refused.code, Code::Conflict);

    // A second server of the environment, opened before the publish.
    let mut other = host(open, binaries, &clock).with_drain(Drain::WhenAsked);
    assert_eq!(
        ok(&mut other, json!({"kind": "list", "type": "Task"}))["items"]
            .as_array()
            .map(Vec::len),
        Some(1)
    );

    let plan = runtime.plan(&Publish::of(vec![v2()])).expect("v2's plan");
    assert_eq!(
        plan["applies"], true,
        "an add only has no hazard refused: {plan}"
    );
    assert_plans(&plan, &["column/estimate", "column/project_id", "/index/"]);
    let second = runtime
        .publish(&Publish::of(vec![v2()]))
        .expect("v2 publishes");
    assert_eq!(second["from"], first["to"]);
    assert_eq!(second["versions"], json!({"Project": 1, "Task": 2}));

    let project_id = project["id"].as_str().expect("a key").to_owned();
    let linked = create(
        &mut runtime,
        "Task",
        json!({"title": "Oil it", "estimate": 3, "projectId": project_id}),
    );
    assert_eq!(linked["estimate"], 3);
    assert_eq!(linked["projectId"], project_id);
    let old = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": task_id}),
    );
    assert_eq!(
        old["title"], "Sand it",
        "a row the publish kept keeps its values"
    );
    assert!(old.get("estimate").is_none(), "{old}");
    let listed = ok(
        &mut runtime,
        json!({"kind": "list", "type": "Task", "filter": {"projectId": {"eq": project_id}}}),
    );
    assert_eq!(
        listed["items"].as_array().map(Vec::len),
        Some(1),
        "{listed}"
    );
    let missing = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Task", "data": {"title": "Nope", "projectId": "7n42DGM5Tflk9n8mt7Fhc7"}}),
    )
    .expect_err("a relation to no row");
    assert_eq!(missing.code, Code::InvalidInstance);

    // The second server follows the publish: it reads the new layout at
    // its next request.
    let seen = ok(
        &mut other,
        json!({"kind": "get", "type": "Task", "id": linked["id"]}),
    );
    assert_eq!(seen["estimate"], 3, "{seen}");
    let described = ok(&mut other, json!({"kind": "describe", "type": "Task"}));
    assert_eq!(described["version"], 2, "{described}");

    // Deleting the project deletes the task that points at it, as the
    // foreign key the plan wrote does.
    let deleted = ok(
        &mut runtime,
        json!({"kind": "delete", "type": "Project", "id": project_id}),
    );
    assert_eq!(
        deleted["deleted"].as_array().map(Vec::len),
        Some(2),
        "{deleted}"
    );
    let gone = ask(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": linked["id"]}),
    )
    .expect_err("the cascade deleted it");
    assert_eq!(gone.code, Code::NotFound);

    // The handler's define and its publish of one type are refused.
    let define = ask(
        &mut runtime,
        json!({"kind": "define", "document": {"name": "Note"}}),
    )
    .expect_err("no define");
    assert_eq!(define.code, Code::InvalidArgument);
}

/// A rename the publish means keeps the column's values; without it the
/// plan drops the old column, which is refused with the hazard's id.
pub fn rename(open: Open<'_>, binaries: &Binaries) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    runtime
        .publish(&Publish::of(vec![v2()]))
        .expect("v2 publishes");
    let task = create(&mut runtime, "Task", json!({"title": "Sand it"}));

    let refused = runtime
        .publish(&Publish::of(vec![v3_renamed()]))
        .expect_err("a drop and an add");
    assert_eq!(refused.code, Code::IncompatibleChange, "{refused:?}");
    assert_eq!(refused.class, "PlanHazardError");
    assert!(
        refused
            .message
            .contains("destructive:table/task/column/title"),
        "{}",
        refused.message
    );

    let plan = runtime
        .plan(&Publish::of(vec![v3_renamed()]).rename("task.title=task.summary"))
        .expect("the rename's plan");
    assert_eq!(plan["applies"], true, "{plan}");
    assert!(
        !hazard_ids(&plan)
            .iter()
            .any(|id| id.starts_with("destructive:")),
        "{plan}"
    );
    runtime
        .publish(&Publish::of(vec![v3_renamed()]).rename("task.title=task.summary"))
        .expect("the rename publishes");
    let read = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": task["id"]}),
    );
    assert_eq!(read["summary"], "Sand it", "{read}");
    assert!(read.get("title").is_none(), "{read}");
}

/// A drop is refused with its hazard's id until the publish allows it;
/// then the column goes with its values.
pub fn drop_refused_unless_allowed(open: Open<'_>, binaries: &Binaries) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    runtime
        .publish(&Publish::of(vec![v3_renamed()]))
        .expect("v3 publishes to an empty database");
    let task = create(
        &mut runtime,
        "Task",
        json!({"summary": "Sand it", "estimate": 5}),
    );

    let drop = "destructive:table/task/column/estimate";
    let plan = runtime
        .plan(&Publish::of(vec![v4_dropped()]))
        .expect("the drop's plan");
    assert_eq!(plan["applies"], false, "{plan}");
    assert_eq!(plan["refused"], json!([drop]), "{plan}");
    let before = plan["from"].clone();
    let refused = runtime
        .publish(&Publish::of(vec![v4_dropped()]))
        .expect_err("a drop nobody allowed");
    assert_eq!(refused.code, Code::IncompatibleChange);
    assert!(refused.message.contains(drop), "{}", refused.message);
    let kept = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": task["id"]}),
    );
    assert_eq!(kept["estimate"], 5, "a refused publish changes nothing");

    let published = runtime
        .publish(&Publish::of(vec![v4_dropped()]).allow(drop))
        .expect("the drop allowed");
    assert_eq!(published["from"], before);
    let read = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Task", "id": task["id"]}),
    );
    assert!(read.get("estimate").is_none(), "{read}");
    let unknown = ask(
        &mut runtime,
        json!({"kind": "update", "type": "Task", "id": task["id"], "patch": {"estimate": 1}}),
    )
    .expect_err("the field is gone");
    assert_eq!(unknown.code, Code::InvalidInstance);
}

/// A plan asked for is answered with its steps and their hazards and
/// changes nothing; a plan made elsewhere from another model is refused
/// with both models named; and the plan from the database's own model to
/// the documents it holds is empty.
pub fn plan_without_applying(open: Open<'_>, binaries: &Binaries) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    let plan = runtime.plan(&Publish::of(vec![v1()])).expect("v1's plan");
    assert_eq!(plan["from"], "");
    assert!(plan["steps"]
        .as_array()
        .is_some_and(|steps| !steps.is_empty()));
    let step = &plan["steps"][0];
    for member in ["index", "phase", "op", "subject", "statements", "hazards"] {
        assert!(step.get(member).is_some(), "a step's {member}: {step}");
    }
    let refused = ask(&mut runtime, json!({"kind": "list", "type": "Task"}))
        .expect_err("nothing is published");
    assert_eq!(refused.code, Code::NotFound);

    // The plan the CLI makes from an empty database, carried to the
    // database once v1 is there.
    let stale = planned(binaries, runtime.dialect().as_str(), &[v1()], Value::Null);
    runtime
        .publish(&Publish::of(vec![v1()]))
        .expect("v1 publishes");
    let mut carried = Publish::of(vec![v1()]);
    carried.planned = Some(stale);
    let refused = runtime
        .publish(&carried)
        .expect_err("a plan from an empty database");
    assert_eq!(refused.code, Code::Conflict);
    assert_eq!(refused.class, "PlanBaselineError");
    assert!(
        refused.message.contains("an empty database"),
        "{}",
        refused.message
    );

    let empty = runtime
        .plan(&Publish::of(vec![v1()]))
        .expect("the plan from its own model");
    assert_eq!(empty["steps"], json!([]), "{empty}");
    assert_eq!(empty["from"], empty["to"]);

    // The tools a server lists for the plan and the publish.
    let tools = superschematic_rules_runtime::tools();
    let names: Vec<&str> = tools
        .iter()
        .filter_map(|tool| tool["name"].as_str())
        .collect();
    assert_eq!(names, ["plan", "publish"]);
    let answered = ok(&mut runtime, json!({"kind": "plan", "documents": [v2()]}));
    assert_eq!(answered["applies"], true);
}

/// The plan and the layout the CLI answers for documents from a model:
/// what a platform with no process to spawn sends with its schemas.
pub fn planned(binaries: &Binaries, dialect: &str, documents: &[Value], from: Value) -> Planned {
    let request = json!({"version": 1, "dialect": dialect, "documents": documents, "from": from, "layout": true});
    let answer = run(
        &binaries.superschematic,
        &["migrate", "plan", "--request", "-"],
        request.to_string().as_bytes(),
    );
    let answer: Value = serde_json::from_slice(&answer).expect("the planner's JSON");
    Planned {
        plan: answer["plan"].clone(),
        layout: answer["layout"].clone(),
    }
}

/// Runs a binary with stdin and returns its stdout, failing the test when
/// it fails.
pub fn run(binary: &std::path::Path, args: &[&str], stdin: &[u8]) -> Vec<u8> {
    use std::io::Write;
    let mut child = std::process::Command::new(binary)
        .args(args)
        .stdin(std::process::Stdio::piped())
        .stdout(std::process::Stdio::piped())
        .stderr(std::process::Stdio::piped())
        .spawn()
        .expect("the binary runs");
    child
        .stdin
        .take()
        .expect("stdin")
        .write_all(stdin)
        .expect("stdin written");
    let output = child.wait_with_output().expect("the binary finishes");
    assert!(
        output.status.success(),
        "{} {args:?}: {}",
        binary.display(),
        String::from_utf8_lossy(&output.stderr)
    );
    output.stdout
}

/// Builds a database as a compiled build's deploy does: the documents'
/// plan from an empty database (`migrate plan --documents`, which is
/// sqlgen's DDL) applied by the Go runner.
pub fn build_from_empty(binaries: &Binaries, dialect: &str, documents: &[Value], url: &str) {
    let stream: String = documents
        .iter()
        .map(|document| format!("{document}\n"))
        .collect();
    let plan = run(
        &binaries.superschematic,
        &[
            "migrate",
            "plan",
            "--documents",
            "-",
            "--dialect",
            dialect,
            "--format",
            "json",
        ],
        stream.as_bytes(),
    );
    run(
        &binaries.migrate,
        &["apply", "--plan", "-", "--database-url", url],
        &plan,
    );
}

/// A table that composes Workflow and Timers, written through the core: a
/// create arms the deadline in the table's deadline queue and keeps its
/// sub-table row, the change trigger's message is run and spent, a
/// transition moves the status column, and the deadline falls due and
/// escalates an open ticket.
pub fn behavior_tables(open: Open<'_>, binaries: &Binaries) -> (String, String) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    runtime
        .publish(&Publish::of(vec![tickets()]))
        .expect("the tickets publish");
    // Numbering's count is a row of the table's shared table, held to its
    // version.
    let numbers: Vec<Value> = ["Rent", "Power"]
        .iter()
        .map(|title| create(&mut runtime, "Invoice", json!({"title": title}))["number"].clone())
        .collect();
    assert_eq!(numbers, [json!("INV-01"), json!("INV-02")]);

    let ticket = create(&mut runtime, "Ticket", json!({"title": "Printer"}));
    assert_eq!(ticket["status"], "open");
    let id = ticket["id"].as_str().expect("a key").to_owned();
    let other = create(&mut runtime, "Ticket", json!({"title": "Phone"}));
    let moved = ok(
        &mut runtime,
        json!({"kind": "operation", "type": "Ticket", "id": other["id"], "use": "status", "operation": "transition", "params": {"to": "waiting"}}),
    );
    assert!(moved.is_object() || moved.is_null(), "{moved}");
    let read = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Ticket", "id": other["id"]}),
    );
    assert_eq!(read["status"], "waiting", "{read}");
    assert_eq!(read["_version"], 2, "{read}");

    // An hour on, the open ticket's deadline falls due and escalates it;
    // the waiting one's was cleared when it left open.
    clock.advance(3_600_001);
    let ran = runtime.run_due().expect("the queues run");
    assert!(
        ran.iter().any(|ran| ran.outcome.is_ok()),
        "{:?}",
        ran.iter().map(|ran| &ran.outcome).collect::<Vec<_>>()
    );
    let escalated = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Ticket", "id": id}),
    );
    assert_eq!(escalated["status"], "escalated", "{escalated}");
    let waiting = ok(
        &mut runtime,
        json!({"kind": "get", "type": "Ticket", "id": other["id"]}),
    );
    assert_eq!(waiting["status"], "waiting", "{waiting}");
    (id, other["id"].as_str().unwrap_or_default().to_owned())
}
