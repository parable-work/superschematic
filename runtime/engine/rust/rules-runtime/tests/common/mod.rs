//! The scenarios runtime mode runs on SQLite and on Postgres alike: a
//! schema published to an empty database and then extended, a rename, a
//! drop refused until it is allowed, a plan answered without being applied,
//! a plan from another model refused, a second server that follows a
//! publish, and behavior tables written through the core.
//!
//! They run the `superschematic` and `superschematic-migrate` binaries a
//! runtime environment carries: `$SUPERSCHEMATIC_BIN` and
//! `$SUPERSCHEMATIC_MIGRATE_BIN`, else the repository's `bin/`, which `make
//! cli` builds. Without them a scenario says so and passes.

#![allow(dead_code)]

pub mod parity;

use std::path::PathBuf;
use std::sync::atomic::{AtomicI64, Ordering};
use std::sync::Arc;

use serde_json::{json, Value};
use superschematic_rules::{Caller, Code, Refusal};
use superschematic_rules_runtime::{Binaries, Drain, Planned, Publish, Runtime};

/// The binaries the scenarios run, or `None` when neither the environment
/// nor the repository's `bin/` has them.
pub fn binaries() -> Option<Binaries> {
    let repo = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../../bin");
    let find = |var: &str, name: &str| {
        std::env::var_os(var)
            .filter(|value| !value.is_empty())
            .map(PathBuf::from)
            .or_else(|| Some(repo.join(name)).filter(|path| path.exists()))
    };
    let superschematic = find("SUPERSCHEMATIC_BIN", "superschematic")?;
    let migrate = find("SUPERSCHEMATIC_MIGRATE_BIN", "superschematic-migrate")?;
    Some(Binaries {
        superschematic,
        migrate,
    })
}

/// Says why a scenario does not run.
pub fn skipped() {
    println!(
        "set SUPERSCHEMATIC_BIN and SUPERSCHEMATIC_MIGRATE_BIN, or run make cli, to run runtime mode's scenarios"
    );
}

pub fn caller() -> Caller {
    Caller::new("alice", ["tickets.timers", "projects.finish"])
}

/// A clock a scenario moves, from the system's time.
#[derive(Clone)]
pub struct Clock(Arc<AtomicI64>);

impl Clock {
    pub fn now() -> Self {
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map(|since| since.as_millis() as i64)
            .unwrap_or_default();
        Clock(Arc::new(AtomicI64::new(now)))
    }

    pub fn get(&self) -> i64 {
        self.0.load(Ordering::SeqCst)
    }

    pub fn advance(&self, ms: i64) {
        self.0.fetch_add(ms, Ordering::SeqCst);
    }
}

/// A runtime host's opener: the database each scenario runs on, opened
/// afresh as another server of the environment would open it.
pub type Open<'a> = &'a dyn Fn() -> Runtime;

/// The host a scenario runs, with the binaries and a clock.
pub fn host(open: Open<'_>, binaries: &Binaries, clock: &Clock) -> Runtime {
    let clock = clock.clone();
    open()
        .with_binaries(binaries.clone())
        .with_clock(move || clock.get())
}

/// The scalars the documents use, as `format --to=json` declares them
/// with the service's first schema file.
