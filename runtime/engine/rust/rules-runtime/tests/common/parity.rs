/// A soft-deletable table serves its live rows alone: a delete stamps the
/// row's deletedAt and keeps it, a get, a list, a filter through a relation
/// and an update no longer find it, a create of its key is a conflict, and
/// its delete reaches no row that points at it, as no foreign key fires on
/// an update. Its table still holds it, with its version moved on.
pub fn soft_deletes(open: Open<'_>, binaries: &Binaries) -> (String, String) {
    let clock = Clock::now();
    let mut runtime = host(open, binaries, &clock);
    runtime
        .publish(&Publish::of(vec![shelf()]))
        .expect("the shelves publish");
    let ask = |runtime: &mut superschematic_rules_runtime::Runtime, request: Value| {
        runtime.answer(&caller(), &request)
    };
    let shelf = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Shelf", "data": {"name": "Oak"}}),
    )
    .expect("a shelf");
    let shelf_id = shelf["id"].as_str().expect("a key").to_owned();
    let other = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Shelf", "data": {"name": "Pine"}}),
    )
    .expect("another shelf");
    let book = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Book", "data": {"title": "Dune", "shelfId": shelf_id}}),
    )
    .expect("a book on it");
    let book_id = book["id"].as_str().expect("a key").to_owned();
    ask(
        &mut runtime,
        json!({"kind": "create", "type": "Book", "data": {"title": "Emma", "shelfId": other["id"]}}),
    )
    .expect("a book on the other");

    let deleted = ask(
        &mut runtime,
        json!({"kind": "delete", "type": "Shelf", "id": shelf_id}),
    )
    .expect("the shelf deleted");
    assert_eq!(
        deleted["deleted"].as_array().map(Vec::len),
        Some(1),
        "a soft delete reaches no row that points at it: {deleted}"
    );
    let gone = ask(
        &mut runtime,
        json!({"kind": "get", "type": "Shelf", "id": shelf_id}),
    )
    .expect_err("a soft-deleted row is not found");
    assert_eq!(gone.code, Code::NotFound);
    let listed = ask(&mut runtime, json!({"kind": "list", "type": "Shelf"})).expect("the shelves");
    assert_eq!(
        listed["items"].as_array().map(Vec::len),
        Some(1),
        "{listed}"
    );
    let through = ask(
        &mut runtime,
        json!({"kind": "list", "type": "Book", "filter": {"shelf": {"name": {"eq": "Oak"}}}}),
    )
    .expect("the books on Oak");
    assert_eq!(
        through["items"],
        json!([]),
        "a relation reaches live rows alone"
    );
    let kept = ask(
        &mut runtime,
        json!({"kind": "get", "type": "Book", "id": book_id}),
    )
    .expect("the book stays");
    assert_eq!(kept["shelfId"], shelf_id);
    let update = ask(
        &mut runtime,
        json!({"kind": "update", "type": "Shelf", "id": shelf_id, "patch": {"name": "Ash"}}),
    )
    .expect_err("no update of a soft-deleted row");
    assert_eq!(update.code, Code::NotFound);
    let again = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Shelf", "data": {"id": shelf_id, "name": "Oak"}}),
    )
    .expect_err("its key is still held");
    assert_eq!(again.code, Code::Conflict);
    let moved = ask(
        &mut runtime,
        json!({"kind": "create", "type": "Book", "data": {"title": "Ulysses", "shelfId": shelf_id}}),
    )
    .expect_err("no new row points at a soft-deleted one");
    assert_eq!(moved.code, Code::InvalidInstance);

    // A behavior table's soft delete keeps its sub-table rows and runs its
    // change.
    let out = ask(
        &mut runtime,
        json!({"kind": "operation", "type": "Book", "id": book_id, "use": "status", "operation": "transition", "params": {"to": "out"}}),
    )
    .expect("checked out");
    assert!(out.is_object() || out.is_null(), "{out}");
    ask(
        &mut runtime,
        json!({"kind": "delete", "type": "Book", "id": book_id}),
    )
    .expect("the book deleted");
    let books = ask(&mut runtime, json!({"kind": "list", "type": "Book"})).expect("the books");
    assert_eq!(books["items"].as_array().map(Vec::len), Some(1), "{books}");
    (shelf_id, book_id)
}
