fn uuid(n: u32) -> String {
    format!("{n:08x}-0000-4000-8000-{:012x}", u64::from(n) * 7919)
}

/// The UUID's wire form, base62, which a request names a row by.
fn wire(n: u32) -> String {
    let value = superschematic_rules_handler::values::uuid_of(&uuid(n)).unwrap_or_default();
    superschematic_rules_handler::values::base62(value)
}

/// The two hosts the parity test writes to and asks: development mode in a
/// database in memory, and runtime mode over the database the opener
/// names.
struct Both {
    dev: Dev,
    runtime: superschematic_rules_runtime::Runtime,
}

impl Both {
    /// Both answers to a request, which must agree on whether it was
    /// refused, and with what code.
    fn ask(&mut self, request: &Value) -> (Result<Value, Code>, Result<Value, Code>) {
        let typed: Request = serde_json::from_value(request.clone()).expect("a request");
        let dev = self.dev.request(&caller(), &typed).map_err(|r| r.code);
        let runtime = self.runtime.answer(&caller(), request).map_err(|r| r.code);
        (dev, runtime)
    }

    /// The one answer both give.
    fn same(&mut self, request: &Value) -> Result<Value, Code> {
        let (dev, runtime) = self.ask(request);
        assert_eq!(
            runtime, dev,
            "runtime and development mode differ on {request}"
        );
        dev
    }

    fn write(&mut self, request: Value) -> Value {
        match self.same(&request) {
            Ok(answer) => answer,
            Err(code) => panic!("{request} was refused as {code:?}"),
        }
    }
}

