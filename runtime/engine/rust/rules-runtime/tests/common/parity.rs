/// The titles of every page of a list, each page answered alike by both
/// hosts, and how many pages it took.
fn pages_of(both: &mut Both, list: &Value) -> (Vec<String>, usize) {
    let mut request = list.clone();
    let mut titles = Vec::new();
    for page in 1..=20 {
        let answer = match both.same(&request) {
            Ok(answer) => answer,
            Err(code) => panic!("{request} was refused as {code:?}"),
        };
        for item in answer["items"].as_array().into_iter().flatten() {
            titles.push(item["title"].as_str().unwrap_or_default().to_owned());
        }
        let Some(next) = answer["next"].as_str() else {
            return (titles, page);
        };
        request["cursor"] = json!(next);
    }
    panic!("{list} paged past 20 pages");
}

/// Asks every list of [`lists`] of both hosts, page by page, and holds a
/// few to what the cards hold.
fn ask_every_list(both: &mut Both) {
    let (mut pages, mut items, mut empty) = (0, 0, 0);
    for list in lists() {
        let (titles, paged) = pages_of(both, &list);
        pages += paged;
        items += titles.len();
        empty += usize::from(titles.is_empty());
        let filter = &list["filter"];
        if *filter == json!({"title": {"ilike": "AP"}}) {
            let mut sorted = titles.clone();
            sorted.sort();
            assert_eq!(sorted, ["apple", "apple", "apricot"], "{list}");
        }
        if *filter == json!({"points": {"ne": 3}}) {
            assert_eq!(titles.len(), 6, "ne keeps no value: {list} {titles:?}");
        }
        if *filter == json!({"project": {"name": {"eq": "Desk"}}}) {
            assert_eq!(titles.len(), 2, "{list} {titles:?}");
        }
    }
    assert!(pages > lists().len(), "the lists paged: {pages}");
    assert!(
        items > 150 && empty > 3,
        "{items} items, {empty} lists empty"
    );
}

/// The same lists answered alike by development mode and by runtime mode,
/// page by page to the last: every filter a list takes, each sort with
/// values of none last, the key breaking ties, and each cursor's next page.
/// A unique field's holder and a relation's delete are refused and reach
/// alike too.
pub fn lists_answer_as_development_mode(open: Open<'_>, binaries: &Binaries) {
    let clock = Clock::now();
    let start = 1_793_577_600_000; // 2026-11-01T00:00:00Z
    clock.advance(start - clock.get());
    let documents = vec![board()];
    let mut runtime = host(open, binaries, &clock);
    runtime
        .publish(&Publish::of(documents.clone()))
        .expect("the board publishes");
    let dev_clock = clock.clone();
    let mut dev = Dev::memory()
        .expect("development mode in memory")
        .with_clock(move || dev_clock.get());
    for type_name in ["Label", "Project", "Card"] {
        let document = type_document(&documents, type_name).expect("a type document");
        dev.request(&caller(), &Request::Define { document })
            .expect("defined");
        dev.request(
            &caller(),
            &Request::Publish {
                type_name: type_name.into(),
                discard: false,
            },
        )
        .expect("published");
    }
    let mut both = Both { dev, runtime };

    for (code, title) in [("red", "Red"), ("blue", "blue sky"), ("grey", "Grey")] {
        both.write(
            json!({"kind": "create", "type": "Label", "data": {"code": code, "title": title}}),
        );
    }
    for (n, name, rank) in [(101, "Desk", 2), (102, "Shelf", 1)] {
        both.write(json!({"kind": "create", "type": "Project", "data": {"id": uuid(n), "name": name, "rank": rank}}));
    }
    for (i, card) in cards().into_iter().enumerate() {
        let mut data = card;
        data["id"] = json!(uuid(u32::try_from(i).unwrap_or_default() + 1));
        clock.advance(5_000);
        both.write(json!({"kind": "create", "type": "Card", "data": data}));
    }
    // Some cards move on through the Workflow, at other times.
    for (n, to) in [(2, "doing"), (3, "doing"), (3, "done"), (6, "doing")] {
        clock.advance(7_000);
        both.write(json!({"kind": "operation", "type": "Card", "id": wire(n), "use": "status", "operation": "transition", "params": {"to": to}}));
    }

    ask_every_list(&mut both);

    // A cursor this sort did not return, and a filter a field does not
    // take, are refused alike.
    for refused in [
        json!({"kind": "list", "type": "Card", "sort": [{"field": "points"}], "cursor": "[1]"}),
        json!({"kind": "list", "type": "Card", "sort": [{"field": "points"}], "cursor": "[\"x\", \"0\"]"}),
        json!({"kind": "list", "type": "Card", "filter": {"title": {"gt": "a"}}}),
        json!({"kind": "list", "type": "Card", "filter": {"nothing": {"eq": 1}}}),
        json!({"kind": "list", "type": "Card", "sort": [{"field": "meta"}]}),
    ] {
        let (dev, runtime) = both.ask(&refused);
        assert!(dev.is_err(), "{refused}: {dev:?}");
        assert_eq!(runtime.map_err(|_| ()), dev.map_err(|_| ()), "{refused}");
    }

    // A unique name held twice, by a create and by an update.
    let taken = both.same(&json!({"kind": "create", "type": "Project", "data": {"name": "Desk"}}));
    assert_eq!(taken, Err(Code::Conflict));
    let moved = both.same(
        &json!({"kind": "update", "type": "Project", "id": wire(102), "patch": {"name": "Desk"}}),
    );
    assert_eq!(moved, Err(Code::Conflict));
    both.write(json!({"kind": "update", "type": "Project", "id": wire(102), "patch": {"name": "Shelf", "rank": 4}}));

    // A label's delete reaches its cards through their text key, and a
    // project's through its UUID.
    let red = both.write(json!({"kind": "delete", "type": "Label", "id": "red"}));
    assert_eq!(red["deleted"].as_array().map(Vec::len), Some(3), "{red}");
    let desk = both.write(json!({"kind": "delete", "type": "Project", "id": wire(101)}));
    assert_eq!(desk["deleted"].as_array().map(Vec::len), Some(2), "{desk}");
    both.same(&json!({"kind": "list", "type": "Card", "sort": [{"field": "title"}], "limit": 50}))
        .expect("the cards left");
}

