var update = flag.Bool("update", false, "rewrite runtime/http/testdata/search_parity.json")

// parityPath is the vector file the Go, TypeScript and Rust HTTP runtimes
// read, relative to this package.
const parityPath = "../../testdata/search_parity.json"

const parityComment = "Generated by runtime/http/go/search (cd runtime/http/go && go test ./search -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each answer every vector with their search helpers (D62): Terms, LikePattern, Fold and Matches in Go, " +
	"searchTerms, likePattern, foldText and searchMatches in TypeScript, search::terms, search::like_pattern, search::fold and search::matches in Rust. " +
	"terms: the words of text, its runs of characters that are not Unicode White_Space, the first 8, as written. " +
	"patterns: the LIKE pattern of term, its \\, % and _ escaped with \\, between two %. " +
	"folds: each character of text by its simple lowercase mapping, one for one. " +
	"matches: whether text contains every word of query, both folded; a query without words matches every text."

type parityFile struct {
	Comment  string          `json:"comment"`
	Terms    []termsVector   `json:"terms"`
	Patterns []patternVector `json:"patterns"`
	Folds    []foldVector    `json:"folds"`
	Matches  []matchVector   `json:"matches"`
}

type termsVector struct {
	Name  string   `json:"name"`
	Text  string   `json:"text"`
	Terms []string `json:"terms"`
}

type patternVector struct {
	Name    string `json:"name"`
	Term    string `json:"term"`
	Pattern string `json:"pattern"`
}

type foldVector struct {
	Name string `json:"name"`
	Text string `json:"text"`
	Fold string `json:"fold"`
}

type matchVector struct {
	Name  string `json:"name"`
	Text  string `json:"text"`
	Query string `json:"query"`
	Match bool   `json:"match"`
}

// parityCorpus builds the vectors, each with the answer this package gives.
func parityCorpus() parityFile {
	terms := []termsVector{
		{Name: "blank", Text: ""},
		{Name: "spaces only", Text: "   "},
		{Name: "one word", Text: "anvil"},
		{Name: "leading and trailing spaces", Text: "  red anvil  "},
		{Name: "runs of spaces", Text: "red    anvil"},
		{Name: "tabs and newlines", Text: "red\tanvil\nsteel\r\nhammer\vtongs\fbellows"},
		{Name: "nine words keep the first eight", Text: "one two three four five six seven eight nine"},
		{Name: "eight words", Text: "one two three four five six seven eight"},
		{Name: "a no-break space separates", Text: "red\u00a0anvil"},
		{Name: "a next-line character separates", Text: "red\u0085anvil"},
		{Name: "an ideographic space separates", Text: "赤い\u3000金床"},
		{Name: "an ogham space separates", Text: "red\u1680anvil"},
		{Name: "the en quad to the hair space separate", Text: "a\u2000b\u2005c\u200ad"},
		{Name: "line and paragraph separators separate", Text: "red\u2028anvil\u2029steel"},
		{Name: "a narrow no-break space and the medium mathematical space separate", Text: "red\u202fanvil\u205fsteel"},
		{Name: "a byte order mark does not separate", Text: "red\ufeffanvil"},
		{Name: "a zero-width space does not separate", Text: "red\u200banvil"},
		{Name: "the Mongolian vowel separator does not separate", Text: "red\u180eanvil"},
		{Name: "LIKE's own characters stay in a word", Text: `50%_off\ sale`},
		{Name: "an emoji is a word", Text: "🔨 anvil 👍🏽"},
		{Name: "combining marks stay with their letter", Text: "cafe\u0301 au lait"},
		{Name: "case is kept", Text: "Red ANVIL"},
	}
	for i := range terms {
		terms[i].Terms = Terms(terms[i].Text)
	}

	patterns := []patternVector{
		{Name: "a plain word", Term: "anvil"},
		{Name: "a percent sign", Term: "50%"},
		{Name: "an underscore", Term: "a_b"},
		{Name: "a backslash", Term: `c:\tools`},
		{Name: "all three", Term: `50%_off\`},
		{Name: "a trailing backslash", Term: `end\`},
		{Name: "an emoji and combining marks", Term: "cafe\u0301🔨"},
		{Name: "an empty term", Term: ""},
	}
	for i := range patterns {
		patterns[i].Pattern = LikePattern(patterns[i].Term)
	}

	folds := []foldVector{
		{Name: "ASCII", Text: "Red ANVIL 42"},
		{Name: "Latin-1", Text: "ÀÉÎÕÜ Çà"},
		{Name: "a sharp s stays", Text: "Straße ẞ"},
		{Name: "a capital I with a dot is i", Text: "İstanbul"},
		{Name: "a dotless i stays", Text: "ı I"},
		{Name: "sigma, final or not", Text: "ΣΑΣ ΟΔΟΣ"},
		{Name: "a titlecase digraph", Text: "ǄǅǆDž"},
		{Name: "the Kelvin and ohm signs", Text: "\u212a\u2126"},
		{Name: "Cyrillic", Text: "Наковальня"},
		{Name: "fullwidth letters", Text: "ＡＢＣ"},
		{Name: "combining marks", Text: "E\u0301COLE"},
		{Name: "no case", Text: "金床 🔨 123"},
	}
	for i := range folds {
		folds[i].Fold = Fold(folds[i].Text)
	}

	matches := []matchVector{
		{Name: "every word, in any order", Text: "Anvil, red", Query: "red anvil"},
		{Name: "a missing word", Text: "Anvil, red", Query: "red hammer"},
		{Name: "case does not matter", Text: "RED ANVIL", Query: "Red anvil"},
		{Name: "a word inside a word", Text: "anvils", Query: "anvil"},
		{Name: "a blank query keeps everything", Text: "anvil", Query: "  "},
		{Name: "an empty text and a word", Text: "", Query: "anvil"},
		{Name: "a percent sign is itself", Text: "50% off", Query: "50%"},
		{Name: "a percent sign is no wildcard", Text: "500 off", Query: "50%"},
		{Name: "an underscore is itself", Text: "a_b", Query: "a_b"},
		{Name: "an underscore is no wildcard", Text: "axb", Query: "a_b"},
		{Name: "a capital I with a dot", Text: "İstanbul", Query: "istanbul"},
		{Name: "a final sigma", Text: "ΟΔΟΣ", Query: "οδοσ"},
		{Name: "a sharp s is no ss", Text: "Straße", Query: "strasse"},
		{Name: "combining marks are not composed", Text: "e\u0301cole", Query: "école"},
		{Name: "a no-break space splits the query", Text: "anvil, red", Query: "red\u00a0anvil"},
		{Name: "the ninth word does not count", Text: "one two three four five six seven eight", Query: "one two three four five six seven eight nine"},
	}
	for i := range matches {
		matches[i].Match = Matches(matches[i].Text, Terms(matches[i].Query))
	}
	return parityFile{Comment: parityComment, Terms: terms, Patterns: patterns, Folds: folds, Matches: matches}
}

func encodeParity(t *testing.T) []byte {
	t.Helper()
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus()); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

// TestWriteParityVectors keeps runtime/http/testdata/search_parity.json
// equal to the vectors parityCorpus builds. It fails when the committed
// file is stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	data := encodeParity(t)
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./search -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale; run go test ./search -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors answers every committed vector, as the TypeScript and
// Rust runtimes do.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatal(err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	if len(file.Terms) == 0 || len(file.Patterns) == 0 || len(file.Folds) == 0 || len(file.Matches) == 0 {
		t.Fatal("a section has no vectors")
	}
	for _, v := range file.Terms {
		if got := Terms(v.Text); !slices.Equal(got, v.Terms) {
			t.Errorf("terms %s: Terms(%q) = %q, want %q", v.Name, v.Text, got, v.Terms)
		}
	}
	for _, v := range file.Patterns {
		if got := LikePattern(v.Term); got != v.Pattern {
			t.Errorf("patterns %s: LikePattern(%q) = %q, want %q", v.Name, v.Term, got, v.Pattern)
		}
	}
	for _, v := range file.Folds {
		if got := Fold(v.Text); got != v.Fold {
			t.Errorf("folds %s: Fold(%q) = %q, want %q", v.Name, v.Text, got, v.Fold)
		}
	}
	for _, v := range file.Matches {
		if got := Matches(v.Text, Terms(v.Query)); got != v.Match {
			t.Errorf("matches %s: Matches(%q, Terms(%q)) = %v, want %v", v.Name, v.Text, v.Query, got, v.Match)
		}
	}
}

