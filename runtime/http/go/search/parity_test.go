func TestSearchRules(t *testing.T) {
	if got := Terms("one two three four five six seven eight nine"); len(got) != MaxTerms || got[7] != "eight" {
		t.Errorf("nine words = %q", got)
	}
	if got := Terms(" \t\u3000 "); got == nil || len(got) != 0 {
		t.Errorf("blank = %#v, want an empty list", got)
	}
	if got := Terms("red\ufeffanvil"); len(got) != 1 {
		t.Errorf("U+FEFF split the word: %q", got)
	}
	if got, want := LikePattern(`50%_off\`), `%50\%\_off\\%`; got != want {
		t.Errorf("LikePattern = %q, want %q", got, want)
	}
	if got := Fold("İΣ"); got != "iσ" {
		t.Errorf("Fold = %q", got)
	}
	if !Matches("Anvil, red", Terms("RED anvil")) || Matches("500 off", Terms("50%")) || !Matches("anything", nil) {
		t.Error("Matches")
	}
}
