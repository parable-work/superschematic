//go:build ignore

// gen_fold writes fold_table.go: each simple lowercase mapping where Go's
// unicode.ToLower and the Rust runtime's search::fold disagree, read from
// the Rust runtime's fold_mappings example on standard input, one
// "XXXX YYYY" line for each character the fold changes. Rust's char and
// Bun's ICU, which search_parity.json holds to the same folds, know a
// newer Unicode than Go's unicode package, so the table is the mappings
// the newer versions added. Run it through go generate (search.go).
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"
	"unicode"
)

func main() {
	rust := map[rune]rune{}
	scanner := bufio.NewScanner(os.Stdin)
	version := ""
	if scanner.Scan() {
		version, _ = strings.CutPrefix(scanner.Text(), "unicode ")
	}
	for scanner.Scan() {
		from, to, ok := strings.Cut(scanner.Text(), " ")
		r, err1 := strconv.ParseUint(from, 16, 32)
		m, err2 := strconv.ParseUint(to, 16, 32)
		if !ok || err1 != nil || err2 != nil {
			log.Fatalf("gen_fold: a line that is no mapping: %q", scanner.Text())
		}
		rust[rune(r)] = rune(m)
	}
	if err := scanner.Err(); err != nil {
		log.Fatal(err)
	}
	if version == "" || len(rust) < 1000 {
		log.Fatalf("gen_fold: %d mappings on standard input; pipe the Rust runtime's fold_mappings example in", len(rust))
	}

	var table bytes.Buffer
	count := 0
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		want, ok := rust[r]
		if !ok {
			want = r
		}
		if unicode.ToLower(r) != want {
			fmt.Fprintf(&table, "\t0x%04X: 0x%04X,\n", r, want)
			count++
		}
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, `// Code generated by gen_fold.go from the Rust runtime's fold_mappings example; DO NOT EDIT.

package search

// foldAdded is each character whose simple lowercase mapping in Unicode
// %s, which the Rust runtime's search::fold gives, Go's unicode.ToLower,
// of Unicode %s, does not give: %d mappings the later versions added.
// Bun's ICU, the TypeScript runtime's, knows them too. Fold takes them
// first, so the three runtimes fold alike (search_parity.json).
// Regenerate the table with go generate in this package, whose directive
// (search.go) pipes the Rust runtime's fold_mappings example into
// gen_fold.go, after a Go, Rust or Bun upgrade moves a runtime to another
// Unicode version; once Go's tables catch up, it is empty.
var foldAdded = map[rune]rune{
%s}
`, version, unicode.Version, count, table.String())
	source, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("fold_table.go", source, 0o644); err != nil {
		log.Fatal(err)
	}
}
