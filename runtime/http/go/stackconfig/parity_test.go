// parityFile is the shape of stackconfig_parity.json.
type parityFile struct {
	Comment string         `json:"comment"`
	Vectors []parityVector `json:"vectors"`
}

type parityVector struct {
	Name      string             `json:"name"`
	Reader    string             `json:"reader"`
	Field     string             `json:"field"`
	Value     any                `json:"value"`
	Variables map[string]string  `json:"variables"`
	Edits     map[string]*string `json:"edits,omitempty"`
	Want      any                `json:"want"`
	Refusals  []string           `json:"refusals"`
}

// The readers a vector names.
const (
	readerDatabase = "database"
	readerService  = "service"
	readerCallers  = "callers"
	readerCORS     = "cors"
)

// parityKey is a fixed Ed25519 key pair: the private JWK a signed-token
// source signs with, and the public JWK the callee's callers field holds.
func parityKey() (private, public string) {
	seed := bytes.Repeat([]byte{7}, ed25519.SeedSize)
	key := ed25519.NewKeyFromSeed(seed)
	x := base64.RawURLEncoding.EncodeToString(key.Public().(ed25519.PublicKey))
	d := base64.RawURLEncoding.EncodeToString(seed)
	private = fmt.Sprintf(`{"kty":"OKP","crv":"Ed25519","kid":"orders-key","x":%q,"d":%q}`, x, d)
	public = fmt.Sprintf(`{"kty":"OKP","kid":"orders-key","use":"sig","alg":"EdDSA","crv":"Ed25519","x":%q}`, x)
	return private, public
}

func str(s string) *string { return &s }

