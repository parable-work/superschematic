// TestWriteParityVectors keeps runtime/http/testdata/stackconfig_parity.json
// equal to the vectors parityCorpus builds. It fails when the committed
// file is stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus(t)); err != nil {
		t.Fatalf("marshal vectors: %v", err)
	}
	data := buf.Bytes()
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatalf("write vectors: %v", err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./stackconfig -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale; run go test ./stackconfig -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors reads every committed vector with this package's
// readers.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}
	if len(file.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	names := map[string]bool{}
	for _, v := range file.Vectors {
		if names[v.Name] {
			t.Fatalf("vector name %q repeats", v.Name)
		}
		names[v.Name] = true
		t.Run(v.Name, func(t *testing.T) {
			env := map[string]string{}
			for name, value := range v.Variables {
				env[name] = value
			}
			for name, value := range v.Edits {
				if value == nil {
					delete(env, name)
				} else {
					env[name] = *value
				}
			}
			got, err := readVector(v, env)
			if v.Refusals != nil {
				if err == nil {
					t.Fatalf("loaded %s; want a refusal", mustJSON(t, got))
				}
				lines := strings.Split(err.Error(), "\n")
				if len(lines) != len(v.Refusals) {
					t.Fatalf("refusal:\n%s\nwant %d lines beginning:\n%s", err, len(v.Refusals), strings.Join(v.Refusals, "\n"))
				}
				for i, line := range lines {
					if !strings.HasPrefix(line, v.Refusals[i]) {
						t.Errorf("refusal line %d is %q; want it to begin %q", i, line, v.Refusals[i])
					}
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			var want any
			if err := json.Unmarshal(mustJSON(t, v.Want), &want); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(got, want) {
				t.Errorf("loaded %s\nwant %s", mustJSON(t, got), mustJSON(t, want))
			}
		})
	}
}

// readVector reads a vector's field from env with the reader it names,
// and returns the loaded value in the vector's JSON shape.
func readVector(v parityVector, env map[string]string) (any, error) {
	getenv := func(name string) string { return env[name] }
	var loaded any
	switch v.Reader {
	case readerDatabase:
		db, err := loadDatabase(v.Field, getenv)
		if err != nil {
			return nil, err
		}
		if db.CloudSQL != nil {
			loaded = map[string]any{"cloudSql": map[string]any{"instance": db.CloudSQL.Instance, "database": db.CloudSQL.Database, "user": db.CloudSQL.User}}
		} else {
			loaded = map[string]any{"url": db.URL}
		}
	case readerService:
		svc, err := loadService(v.Field, getenv)
		if err != nil {
			return nil, err
		}
		out := map[string]any{"url": svc.URL}
		if c := svc.Credential; c != nil {
			credential := map[string]any{"source": c.Source}
			for name, value := range map[string]string{"audience": c.Audience, "tokenFile": c.TokenFile, "issuer": c.Issuer, "key": c.Key} {
				if value != "" {
					credential[name] = value
				}
			}
			if len(c.Headers) > 0 {
				credential["headers"] = c.Headers
			}
			out["credential"] = credential
		}
		loaded = out
	case readerCallers:
		var environ []string
		for name, value := range env {
			environ = append(environ, name+"="+value)
		}
		cfg, err := loadCallers(v.Field, environ)
		if err != nil {
			return nil, err
		}
		loaded = cfg
	case readerCORS:
		var environ []string
		for name, value := range env {
			environ = append(environ, name+"="+value)
		}
		origins, err := loadCORS(v.Field, environ)
		if err != nil {
			return nil, err
		}
		if origins == nil {
			origins = []string{}
		}
		loaded = map[string]any{"origins": origins}
	default:
		return nil, fmt.Errorf("vector %s names reader %q", v.Name, v.Reader)
	}
	// The vector's JSON shape: what encoding/json makes of the loaded value.
	var out any
	data, err := json.Marshal(loaded)
	if err != nil {
		return nil, err
	}
	return out, json.Unmarshal(data, &out)
}

func mustJSON(t *testing.T, v any) []byte {
	t.Helper()
	data, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return data
}
