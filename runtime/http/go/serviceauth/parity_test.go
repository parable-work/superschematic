// parityFile is the shape of serviceauth_parity.json.
type parityFile struct {
	Comment  string                        `json:"comment"`
	Users    map[string]parityUser         `json:"users"`
	JWKS     map[string]serviceauth.JWKS   `json:"jwks"`
	Configs  map[string]serviceauth.Config `json:"configs"`
	Vectors  []parityVector                `json:"vectors"`
	Signing  []paritySigning               `json:"signing"`
	Loopback parityLoopback                `json:"loopback"`
}

// parityLoopback is the loopback key's section (docs/stack-model.md,
// section 9.9): the key a server generates for its calls between the APIs
// it serves, built here from Seed, the issuer it adds to a callers field,
// and the token it signs at Now.
type parityLoopback struct {
	Seed       string                   `json:"seed"`
	Deployable string                   `json:"deployable"`
	Serves     []string                 `json:"serves"`
	Now        int64                    `json:"now"`
	Issuer     serviceauth.IssuerConfig `json:"issuer"`
	Header     string                   `json:"header"`
	Claims     map[string]any           `json:"claims"`
	Config     string                   `json:"config"`
	Checks     []parityLoopbackCheck    `json:"checks"`
	Refused    []parityLoopbackRefused  `json:"refused"`
	URLs       map[string]bool          `json:"urls"`
}

// parityLoopbackCheck is a token the authenticator of configs[config],
// with the loopback issuer accepted, verifies At seconds after Now: the
// token the key signs at Now when Token is empty.
type parityLoopbackCheck struct {
	Name   string              `json:"name"`
	Token  string              `json:"token"`
	At     int64               `json:"at"`
	Status int                 `json:"status"`
	Code   *string             `json:"code"`
	Caller *serviceauth.Caller `json:"caller"`
}

// parityLoopbackRefused is a callers field the loopback issuer cannot be
// added to.
type parityLoopbackRefused struct {
	Name   string             `json:"name"`
	Config serviceauth.Config `json:"config"`
}

// paritySigning is one vector of the signed-token source (D63): the key a
// caller's credential holds, a private JWK's JSON or a PKCS#8 PEM, and the
// token it signs at now, which verifies against publicKey, the callee's
// SubjectPublicKeyInfo PEM. Want is null for a key the source refuses.
type paritySigning struct {
	Name      string        `json:"name"`
	Key       string        `json:"key"`
	PublicKey string        `json:"publicKey"`
	Issuer    string        `json:"issuer"`
	Audience  string        `json:"audience"`
	Now       int64         `json:"now"`
	Want      *paritySigned `json:"want"`
}

// paritySigned is what a signed token holds: its header segment, exactly,
// the kid the callee's PEM reads as, and its claims but jti.
type paritySigned struct {
	Header string         `json:"header"`
	Kid    string         `json:"kid"`
	Claims map[string]any `json:"claims"`
}

// parityUser is the end-user stub's record for a bearer token.
type parityUser struct {
	Subject     string   `json:"subject"`
	Permissions []string `json:"permissions"`
}

type parityVector struct {
	Name    string            `json:"name"`
	Now     int64             `json:"now"`
	Config  *string           `json:"config"`
	Route   parityRoute       `json:"route"`
	Headers map[string]string `json:"headers"`
	Want    parityWant        `json:"want"`
}

type parityRoute struct {
	Service *parityService   `json:"service"`
	User    parityUserClause `json:"user"`
}

type parityService struct {
	Mode string   `json:"mode"`
	From []string `json:"from"`
}

type parityUserClause struct {
	Required    bool     `json:"required"`
	Permissions []string `json:"permissions"`
}

type parityWant struct {
	Status            int                 `json:"status"`
	Code              *string             `json:"code"`
	Caller            *serviceauth.Caller `json:"caller"`
	User              *string             `json:"user"`
	UserAuthenticated bool                `json:"userAuthenticated"`
}

