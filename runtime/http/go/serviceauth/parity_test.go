// parityPath is the vector file the Go, TypeScript and Rust HTTP runtimes
// read, relative to this package.
const parityPath = "../../testdata/serviceauth_parity.json"

// parityFile is the shape of serviceauth_parity.json.
type parityFile struct {
	Comment string                        `json:"comment"`
	Users   map[string]parityUser         `json:"users"`
	JWKS    map[string]serviceauth.JWKS   `json:"jwks"`
	Configs map[string]serviceauth.Config `json:"configs"`
	Vectors []parityVector                `json:"vectors"`
}

// parityUser is the end-user stub's record for a bearer token.
type parityUser struct {
	Subject     string   `json:"subject"`
	Permissions []string `json:"permissions"`
}

type parityVector struct {
	Name    string            `json:"name"`
	Now     int64             `json:"now"`
	Config  *string           `json:"config"`
	Route   parityRoute       `json:"route"`
	Headers map[string]string `json:"headers"`
	Want    parityWant        `json:"want"`
}

type parityRoute struct {
	Service *parityService   `json:"service"`
	User    parityUserClause `json:"user"`
}

type parityService struct {
	Mode string   `json:"mode"`
	From []string `json:"from"`
}

type parityUserClause struct {
	Required    bool     `json:"required"`
	Permissions []string `json:"permissions"`
}

type parityWant struct {
	Status            int                 `json:"status"`
	Code              *string             `json:"code"`
	Caller            *serviceauth.Caller `json:"caller"`
	User              *string             `json:"user"`
	UserAuthenticated bool                `json:"userAuthenticated"`
}

const parityComment = "Generated by runtime/http/go/serviceauth (cd runtime/http/go && go test ./serviceauth -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each run every vector through their route gate (D37, docs/stack-model.md section 9.8). " +
	"Per vector: build the service authenticator from configs[config] with the clock at now (unix seconds) and a fresh, empty key cache; config null means the server has no service authenticator. " +
	"The key fetcher returns jwks[url] and fails for any other URL. " +
	"Send headers (names are case-insensitive) to a route whose rule is route.service (null: no service clause; mode require or allow; from lists API names, empty lists every caller) and route.user. " +
	"The service step verifies a Service-Authorization credential when present and answers a refusal at once, then applies the rule: require refuses no caller with 401 service_unauthorized and an unlisted one with 403 service_forbidden, then runs the user step; allow admits a listed caller without the user step; without a service authenticator a route with a rule answers 401 service_unauthorized. " +
	"The end-user step is a stub, run when route.user.required: it looks up the Authorization Bearer token in users (absent or unknown: 401 unauthorized), then requires one of route.user.permissions to be covered by a granted permission under the dotted-path rule, a granted a covering a and a.b (else 403 forbidden). " +
	"Compare status; code, the problem code of a refusal (null on 200); caller and user, what the handler saw (null unless 200; user is the stub's subject); userAuthenticated, whether the stub's lookup ran, refusing or not. " +
	"No vector depends on the order of the end-user lookup and the service step on a route without a service clause, since the Go server authenticates the end user there first. " +
	"Tokens are fixed: RS256 and EdDSA signatures are deterministic, and ES256 ones are RFC 6979 deterministic signatures."

// TestWriteParityVectors keeps runtime/http/testdata/serviceauth_parity.json
// equal to the vectors parityCorpus builds. It fails when the committed file
// is stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus(t)); err != nil {
		t.Fatalf("marshal vectors: %v", err)
	}
	data := buf.Bytes()
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatalf("write vectors: %v", err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./serviceauth -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale; run go test ./serviceauth -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors runs every committed vector through this package's gate,
// with the end-user stub in the order the generated Go server runs it.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}
	if len(file.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	names := map[string]bool{}
	for _, v := range file.Vectors {
		if names[v.Name] {
			t.Fatalf("vector name %q repeats", v.Name)
		}
		names[v.Name] = true
		t.Run(v.Name, func(t *testing.T) {
			got := runParityVector(t, file, v)
			if !reflect.DeepEqual(got, v.Want) {
				t.Errorf("got %s\nwant %s", mustJSON(t, got), mustJSON(t, v.Want))
			}
		})
	}
}

// runParityVector serves one vector and reports what the gate did.
func runParityVector(t *testing.T, file parityFile, v parityVector) parityWant {
	t.Helper()
	var authenticator serviceauth.Authenticator
	if v.Config != nil {
		cfg, ok := file.Configs[*v.Config]
		if !ok {
			t.Fatalf("config %q is not in configs", *v.Config)
		}
		now := time.Unix(v.Now, 0)
		verifier, err := serviceauth.New(cfg,
			serviceauth.WithClock(func() time.Time { return now }),
			serviceauth.WithFetcher(func(_ context.Context, url, _ string) ([]byte, error) {
				set, ok := file.JWKS[url]
				if !ok {
					return nil, fmt.Errorf("%s is unreachable", url)
				}
				return json.Marshal(set)
			}),
		)
		if err != nil {
			t.Fatalf("config %q: %v", *v.Config, err)
		}
		authenticator = verifier
	}

	var got parityWant
	userLookup := func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			got.UserAuthenticated = true
			token, _ := session.BearerToken(r.Header)
			user, ok := file.Users[token]
			if !ok {
				response.Error(w, http.StatusUnauthorized, "Authentication required", "unauthorized")
				return
			}
			ctx := session.ContextWithPrincipalID(r.Context(), user.Subject)
			ctx = session.ContextWithRoles(ctx, []session.Role{{Name: "stub", Permissions: user.Permissions}})
			next.ServeHTTP(w, r.WithContext(ctx))
		})
	}
	userPermissions := func(next http.Handler) http.Handler {
		return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if !session.AnyRoleCoversAny(session.GetRoles(r.Context()), v.Route.User.Permissions) {
				response.Error(w, http.StatusForbidden, "Insufficient permissions", "forbidden")
				return
			}
			next.ServeHTTP(w, r)
		})
	}

	// The chain the generated Go server builds: a route with a service
	// clause runs the service step, then its end-user step; one without
	// keeps the protected group's AuthMiddleware ahead of its own chain,
	// whose service step precedes the permission check.
	var chain []func(http.Handler) http.Handler
	user := v.Route.User.Required
	switch rule := v.Route.Service; {
	case rule == nil:
		if user {
			chain = append(chain, userLookup)
		}
		chain = append(chain, serviceauth.Authenticate(authenticator))
		if user {
			chain = append(chain, userPermissions)
		}
	case rule.Mode == "require":
		chain = append(chain, serviceauth.Authenticate(authenticator), serviceauth.Require(rule.From...))
		if user {
			chain = append(chain, userLookup, userPermissions)
		}
	case rule.Mode == "allow":
		var userStep []func(http.Handler) http.Handler
		if user {
			userStep = append(userStep, userLookup, userPermissions)
		}
		chain = append(chain, serviceauth.Authenticate(authenticator), serviceauth.AllowOr(rule.From, userStep...))
	default:
		t.Fatalf("service mode %q", rule.Mode)
	}

	var handler http.Handler = http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if caller, ok := serviceauth.CallerFromContext(r.Context()); ok {
			got.Caller = caller
		}
		if subject := session.GetPrincipalID(r.Context()); subject != "" {
			got.User = &subject
		}
		w.WriteHeader(http.StatusOK)
	})
	for i := len(chain) - 1; i >= 0; i-- {
		handler = chain[i](handler)
	}

	req := httptest.NewRequest(http.MethodPost, "/api/stock/reservations", nil)
	for name, value := range v.Headers {
		req.Header.Set(name, value)
	}
	rec := httptest.NewRecorder()
	handler.ServeHTTP(rec, req)

	got.Status = rec.Code
	if rec.Code != http.StatusOK {
		var problem struct {
			Code string `json:"code"`
		}
		if err := json.Unmarshal(rec.Body.Bytes(), &problem); err != nil {
			t.Fatalf("refusal body %q: %v", rec.Body.String(), err)
		}
		if problem.Code != "" {
			got.Code = &problem.Code
		}
		got.Caller, got.User = nil, nil
	}
	return got
}

