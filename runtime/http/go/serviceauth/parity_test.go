// signedToken is the token SignedToken signs for deployable at iat, with a
// fixed jti.
func signedToken(t testing.TB, key *testKey, deployable string, iat int64) string {
	t.Helper()
	source, err := serviceauth.SignedToken(key.privateJWK(t), deployable, deployable, edgeAudience,
		serviceauth.WithClock(func() time.Time { return time.Unix(iat, 0) }),
		serviceauth.WithRandom(bytes.NewReader(seed(deployable)[:16])),
	)
	if err != nil {
		t.Fatal(err)
	}
	token, err := source(context.Background(), false)
	if err != nil {
		t.Fatal(err)
	}
	return token
}

// segment returns the i-th dot-separated segment of a compact token.
func segment(token string, i int) string {
	return splitToken(token)[i]
}

func splitToken(token string) []string {
	parts := make([]string, 0, 3)
	start := 0
	for i := 0; i < len(token); i++ {
		if token[i] == '.' {
			parts = append(parts, token[start:i])
			start = i + 1
		}
	}
	return append(parts, token[start:])
}

func twoSegments(token string) string {
	return segment(token, 0) + "." + segment(token, 1)
}

// padded adds base64 padding to the token's signature segment, which a
// 256-byte RS256 signature leaves two characters short of a multiple of 4.
func padded(token string) string {
	sig := segment(token, 2)
	for len(sig)%4 != 0 {
		sig += "="
	}
	return segment(token, 0) + "." + segment(token, 1) + "." + sig
}

// unsigned is an alg none token: no signature.
func unsigned(t testing.TB, header, claims object) string {
	return b64(mustJSON(t, header)) + "." + b64(mustJSON(t, claims)) + "."
}

// hs256WithPublicKey is the alg confusion attack: an HS256 MAC whose secret
// is the RSA public key's PEM, which a verifier that let the token pick the
// algorithm would check against the same bytes.
func hs256WithPublicKey(t testing.TB, key *testKey, claims object) string {
	t.Helper()
	der, err := x509.MarshalPKIXPublicKey(&key.rsa.PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	secret := pem.EncodeToMemory(&pem.Block{Type: "PUBLIC KEY", Bytes: der})
	input := b64(mustJSON(t, key.header("HS256"))) + "." + b64(mustJSON(t, claims))
	mac := hmac.New(sha256.New, secret)
	mac.Write([]byte(input))
	return input + "." + b64(mac.Sum(nil))
}

// jwtRaw signs a payload given as bytes, for a payload that is not an
// object.
func (k *testKey) jwtRaw(t testing.TB, alg string, header object, payload []byte) string {
	t.Helper()
	input := b64(mustJSON(t, header)) + "." + b64(payload)
	return input + "." + b64(k.sign(t, alg, []byte(input)))
}
