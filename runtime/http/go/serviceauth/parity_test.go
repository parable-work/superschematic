// TestParityLoopback runs the committed loopback section through
// NewLoopback, Accept, the verifier and IsLoopbackURL.
func TestParityLoopback(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}
	v := file.Loopback
	keySeed, err := base64.RawURLEncoding.DecodeString(v.Seed)
	if err != nil || len(keySeed) != 32 {
		t.Fatalf("seed %q: %v", v.Seed, err)
	}
	random := append(keySeed, make([]byte, 16)...)
	l, err := serviceauth.NewLoopback(v.Deployable, v.Serves,
		serviceauth.WithClock(func() time.Time { return time.Unix(v.Now, 0) }),
		serviceauth.WithRandom(bytes.NewReader(random)))
	if err != nil {
		t.Fatal(err)
	}
	if got, want := mustJSON(t, l.Issuer()), mustJSON(t, v.Issuer); string(got) != string(want) {
		t.Errorf("issuer = %s, want %s", got, want)
	}
	token, err := l.TokenSource()(context.Background(), false)
	if err != nil {
		t.Fatal(err)
	}
	if got := segment(token, 0); got != v.Header {
		t.Errorf("header = %s, want %s", got, v.Header)
	}
	var claims map[string]any
	if err := json.Unmarshal(unb64(t, segment(token, 1)), &claims); err != nil {
		t.Fatal(err)
	}
	if jti, _ := claims["jti"].(string); len(unb64(t, jti)) != 16 {
		t.Errorf("jti = %q, want 16 bytes in base64url", jti)
	}
	delete(claims, "jti")
	if string(mustJSON(t, claims)) != string(mustJSON(t, v.Claims)) {
		t.Errorf("claims = %s, want %s", mustJSON(t, claims), mustJSON(t, v.Claims))
	}
	cfg, err := l.Accept(file.Configs[v.Config])
	if err != nil {
		t.Fatal(err)
	}
	for _, check := range v.Checks {
		t.Run(check.Name, func(t *testing.T) {
			verifier, err := serviceauth.New(cfg, serviceauth.WithClock(func() time.Time { return time.Unix(v.Now+check.At, 0) }))
			if err != nil {
				t.Fatal(err)
			}
			sent := check.Token
			if sent == "" {
				sent = token
			}
			r := httptest.NewRequest(http.MethodGet, "/", nil)
			r.Header.Set(serviceauth.HeaderName, "Bearer "+sent)
			caller, err := verifier.Authenticate(r)
			if check.Code == nil {
				if err != nil || !reflect.DeepEqual(caller, check.Caller) {
					t.Errorf("Authenticate = %+v, %v; want %+v", caller, err, check.Caller)
				}
				return
			}
			var refusal *serviceauth.Error
			if !errors.As(err, &refusal) || refusal.Status != check.Status || refusal.Code != *check.Code {
				t.Errorf("Authenticate = %+v, %v; want %d %s", caller, err, check.Status, *check.Code)
			}
		})
	}
	for _, refused := range v.Refused {
		if _, err := l.Accept(refused.Config); err == nil {
			t.Errorf("Accept took %s", refused.Name)
		}
	}
	for raw, want := range v.URLs {
		if got := serviceauth.IsLoopbackURL(raw); got != want {
			t.Errorf("IsLoopbackURL(%q) = %t, want %t", raw, got, want)
		}
	}
}

// paritySigningVectors builds the signed-token source's vectors (D63):
// the edge key of orders as the generic connector's key node writes it, a
// PKCS#8 PEM, and as the local target's key pair does, a private JWK whose
// kid is the same thumbprint, which sign the same token; and keys the
// source refuses.
func paritySigningVectors(t testing.TB, keys parityKeys) []paritySigning {
	encode := func(label string, marshal func() ([]byte, error)) string {
		t.Helper()
		der, err := marshal()
		if err != nil {
			t.Fatal(err)
		}
		return string(pem.EncodeToMemory(&pem.Block{Type: label, Bytes: der}))
	}
	orders := keys.edgeOrders
	privatePEM := encode("PRIVATE KEY", func() ([]byte, error) { return x509.MarshalPKCS8PrivateKey(orders.ed) })
	publicPEM := encode("PUBLIC KEY", func() ([]byte, error) { return x509.MarshalPKIXPublicKey(orders.ed.Public()) })
	p256PEM := encode("PRIVATE KEY", func() ([]byte, error) { return x509.MarshalPKCS8PrivateKey(keys.kubeEC.ec) })
	now := int64(parityNow)
	want := func() *paritySigned {
		source, err := serviceauth.SignedToken([]byte(privatePEM), "orders", "orders", edgeAudience,
			serviceauth.WithClock(func() time.Time { return time.Unix(now, 0) }))
		if err != nil {
			t.Fatal(err)
		}
		token, err := source(context.Background(), false)
		if err != nil {
			t.Fatal(err)
		}
		return &paritySigned{
			Header: segment(token, 0),
			Kid:    orders.kid,
			Claims: map[string]any{"iss": "orders", "sub": "orders", "aud": edgeAudience, "iat": now, "exp": now + 300},
		}
	}()
	vector := func(name, key string, signed *paritySigned) paritySigning {
		v := paritySigning{Name: name, Key: key, Issuer: "orders", Audience: edgeAudience, Now: now, Want: signed}
		if signed != nil {
			v.PublicKey = publicPEM
		}
		return v
	}
	crlf := "\n  " + strings.ReplaceAll(privatePEM, "\n", "\r\n") + "\n"
	return []paritySigning{
		vector("a PKCS#8 PEM, as the generic connector's key node writes it", privatePEM, want),
		vector("the same key as a private JWK, its kid the thumbprint", string(orders.privateJWK(t)), want),
		vector("a PEM with CRLF lines and whitespace around it", crlf, want),
		vector("a P-256 key's PKCS#8 PEM", p256PEM, nil),
		vector("a public key's PEM", publicPEM, nil),
		vector("a PEM whose body is not base64", "-----BEGIN PRIVATE KEY-----\n!!!!\n-----END PRIVATE KEY-----\n", nil),
		vector("a PEM with no end", strings.TrimSuffix(privatePEM, "-----END PRIVATE KEY-----\n"), nil),
	}
}

// TestParitySigning runs every committed signing vector through
// SignedToken, PublicJWKFromPEM and a verifier of that key.
func TestParitySigning(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}
	if len(file.Signing) == 0 {
		t.Fatal("no signing vectors")
	}
	for _, v := range file.Signing {
		t.Run(v.Name, func(t *testing.T) {
			clock := serviceauth.WithClock(func() time.Time { return time.Unix(v.Now, 0) })
			var token string
			source, err := serviceauth.SignedToken([]byte(v.Key), v.Issuer, v.Issuer, v.Audience, clock)
			if err == nil {
				token, err = source(context.Background(), false)
			}
			if v.Want == nil {
				if err == nil {
					t.Fatalf("the source signed %s with a key it should refuse", token)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			if got := segment(token, 0); got != v.Want.Header {
				t.Errorf("header = %s, want %s", got, v.Want.Header)
			}
			var claims map[string]any
			payload, _ := base64.RawURLEncoding.DecodeString(segment(token, 1))
			if err := json.Unmarshal(payload, &claims); err != nil {
				t.Fatal(err)
			}
			jti, _ := claims["jti"].(string)
			if raw, err := base64.RawURLEncoding.DecodeString(jti); err != nil || len(raw) != 16 {
				t.Errorf("jti = %q, want 16 bytes in base64url", jti)
			}
			delete(claims, "jti")
			if string(mustJSON(t, claims)) != string(mustJSON(t, v.Want.Claims)) {
				t.Errorf("claims = %s, want %s", mustJSON(t, claims), mustJSON(t, v.Want.Claims))
			}
			key, err := serviceauth.PublicJWKFromPEM([]byte(v.PublicKey))
			if err != nil {
				t.Fatal(err)
			}
			if key.Kid != v.Want.Kid {
				t.Errorf("the public key's kid = %s, want %s", key.Kid, v.Want.Kid)
			}
			verifier, err := serviceauth.New(serviceauth.Config{Issuers: []serviceauth.IssuerConfig{{
				Issuer: v.Issuer, Audience: v.Audience, Algorithms: []string{serviceauth.AlgEdDSA},
				Keys: []serviceauth.JWK{key}, MaxLifetimeSeconds: 300,
				Callers: map[string]serviceauth.CallerConfig{v.Issuer: {Deployable: v.Issuer, Serves: []string{"shop-orders"}}},
			}}}, clock)
			if err != nil {
				t.Fatal(err)
			}
			r := httptest.NewRequest(http.MethodGet, "/", nil)
			r.Header.Set(serviceauth.HeaderName, "Bearer "+token)
			caller, err := verifier.Authenticate(r)
			if err != nil || caller == nil || caller.Deployable != v.Issuer {
				t.Errorf("Authenticate = %+v, %v; want %s", caller, err, v.Issuer)
			}
		})
	}
}

