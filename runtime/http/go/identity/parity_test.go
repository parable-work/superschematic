// phcWith writes a PHC string with any salt and hash length, as another
// runtime might have.
func phcWith(password string, salt []byte, keyLen uint32, p identity.Argon2Params) string {
	key := argon2.IDKey([]byte(password), salt, p.Iterations, p.MemoryKiB, uint8(p.Parallelism), keyLen)
	return fmt.Sprintf("$argon2id$v=19$m=%d,t=%d,p=%d$%s$%s", p.MemoryKiB, p.Iterations, p.Parallelism,
		base64.RawStdEncoding.EncodeToString(salt), base64.RawStdEncoding.EncodeToString(key))
}

