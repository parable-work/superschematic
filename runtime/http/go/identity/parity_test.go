// parityPath is the vector file the Go, TypeScript and Rust identity
// runtimes read, relative to this package.
const parityPath = "../../testdata/identity_parity.json"

const parityComment = "Generated by runtime/http/go/identity (cd runtime/http/go && go test ./identity -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust identity runtimes (D50) each run every section; runtime/http/testdata/README.md states the harness of each in full."

// parityFile is the shape of identity_parity.json. Every section is a
// list of cases, each with a name unique in its section.
type parityFile struct {
	Comment              string             `json:"comment"`
	Config               []configCase       `json:"config"`
	PasswordRule         []passwordRuleCase `json:"passwordRule"`
	Hashes               []hashCase         `json:"hashes"`
	Verify               []verifyCase       `json:"verify"`
	Tokens               []tokenCase        `json:"tokens"`
	Cookies              []cookieCase       `json:"cookies"`
	Credentials          []credentialCase   `json:"credentials"`
	CrossOrigin          []crossOriginCase  `json:"crossOrigin"`
	PermissionNames      []permissionCase   `json:"permissionNames"`
	EffectivePermissions []effectiveCase    `json:"effectivePermissions"`
	Grants               []grantCase        `json:"grants"`
	Capabilities         capabilitiesTable  `json:"capabilities"`
}

// configCase: the config JSON input reads as want, the config with its
// defaults (every member, the cookie's name resolved), or is refused when
// want is null.
type configCase struct {
	Name  string           `json:"name"`
	Input json.RawMessage  `json:"input"`
	Want  *effectiveConfig `json:"want"`
}

// effectiveConfig is a config with every member present.
type effectiveConfig struct {
	SessionTTLSeconds    int64    `json:"sessionTtlSeconds"`
	IdleTimeoutSeconds   int64    `json:"idleTimeoutSeconds"`
	TouchIntervalSeconds int64    `json:"touchIntervalSeconds"`
	Cookie               cookieFx `json:"cookie"`
	TrustedOrigins       []string `json:"trustedOrigins"`
	Password             struct {
		Argon2 identity.Argon2Params `json:"argon2"`
	} `json:"password"`
}

type cookieFx struct {
	Name     string `json:"name"`
	Domain   string `json:"domain"`
	Secure   bool   `json:"secure"`
	SameSite string `json:"sameSite"`
}

func effective(c identity.Config) *effectiveConfig {
	c = c.WithDefaults()
	e := &effectiveConfig{
		SessionTTLSeconds:    *c.SessionTTLSeconds,
		IdleTimeoutSeconds:   *c.IdleTimeoutSeconds,
		TouchIntervalSeconds: *c.TouchIntervalSeconds,
		Cookie:               cookieFx{Name: c.Cookie.Name, Domain: c.Cookie.Domain, Secure: *c.Cookie.Secure, SameSite: c.Cookie.SameSite},
		TrustedOrigins:       c.TrustedOrigins,
	}
	e.Password.Argon2 = c.Argon2Params()
	return e
}

// passwordRuleCase: whether Auth.Password admits password.
type passwordRuleCase struct {
	Name     string `json:"name"`
	Password string `json:"password"`
	Valid    bool   `json:"valid"`
}

// hashCase: password hashed with argon2id at params and the salt (base64,
// standard alphabet, no padding) to a 32-byte hash is phc.
type hashCase struct {
	Name     string                `json:"name"`
	Password string                `json:"password"`
	Salt     string                `json:"salt"`
	Params   identity.Argon2Params `json:"params"`
	PHC      string                `json:"phc"`
}

// verifyCase: verifying password against phc, with the config's cost
// current, answers want.
type verifyCase struct {
	Name     string                `json:"name"`
	PHC      string                `json:"phc"`
	Password string                `json:"password"`
	Current  identity.Argon2Params `json:"current"`
	Want     verifyWant            `json:"want"`
}

type verifyWant struct {
	Malformed bool `json:"malformed"`
	OK        bool `json:"ok"`
	Rehash    bool `json:"rehash"`
}

// tokenCase: the token's random bytes (hex) encode as token, whose stored
// hash is hash.
type tokenCase struct {
	Name  string `json:"name"`
	Bytes string `json:"bytes"`
	Token string `json:"token"`
	Hash  string `json:"hash"`
}

// cookieCase: under the config, a cookie login's Set-Cookie for token with
// maxAgeSeconds left is set, and logout's is clear.
type cookieCase struct {
	Name          string          `json:"name"`
	Config        json.RawMessage `json:"config"`
	Token         string          `json:"token"`
	MaxAgeSeconds int64           `json:"maxAgeSeconds"`
	Want          cookieWant      `json:"want"`
}

type cookieWant struct {
	Set   string `json:"set"`
	Clear string `json:"clear"`
}

// credentialCase: a request with headers (name, value pairs, in order,
// repeats kept) carries want, the session cookie being cookieName.
type credentialCase struct {
	Name       string         `json:"name"`
	CookieName string         `json:"cookieName"`
	Headers    [][2]string    `json:"headers"`
	Want       credentialWant `json:"want"`
}

type credentialWant struct {
	// Outcome is none, usable or invalid.
	Outcome string `json:"outcome"`
	// Transport is bearer or cookie, null with none.
	Transport *string `json:"transport"`
	// Token is the token read, null unless usable.
	Token *string `json:"token"`
}

// crossOriginCase: the cross-origin check on a request with method, the
// Host host and headers, under trustedOrigins, answers allow or refuse.
type crossOriginCase struct {
	Name           string            `json:"name"`
	Method         string            `json:"method"`
	Host           string            `json:"host"`
	Headers        map[string]string `json:"headers"`
	TrustedOrigins []string          `json:"trustedOrigins"`
	Want           string            `json:"want"`
}

type permissionCase struct {
	Permission string `json:"permission"`
	Valid      bool   `json:"valid"`
}

// effectiveCase: the permissions of roles, in the order given, are want.
type effectiveCase struct {
	Name  string       `json:"name"`
	Roles []parityRole `json:"roles"`
	Want  []string     `json:"want"`
}

type parityRole struct {
	Name        string   `json:"name"`
	Permissions []string `json:"permissions"`
}

// grantCase: a caller holding held may write a role with given, or grant a
// role carrying it, when allowed; uncovered lists what held does not
// cover.
type grantCase struct {
	Name  string    `json:"name"`
	Held  []string  `json:"held"`
	Given []string  `json:"given"`
	Want  grantWant `json:"want"`
}

type grantWant struct {
	Allowed   bool     `json:"allowed"`
	Uncovered []string `json:"uncovered"`
}

// capabilitiesTable: for each caller, an authenticated principal holding
// permissions, capabilities over routes answers want.
type capabilitiesTable struct {
	Routes  []identity.Route `json:"routes"`
	Callers []capabilityCase `json:"callers"`
}

type capabilityCase struct {
	Name        string          `json:"name"`
	Permissions []string        `json:"permissions"`
	Want        map[string]bool `json:"want"`
}

// TestWriteParityVectors keeps runtime/http/testdata/identity_parity.json
// equal to the vectors parityCorpus builds. It fails when the committed
// file is stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus(t)); err != nil {
		t.Fatalf("marshal vectors: %v", err)
	}
	data := buf.Bytes()
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatalf("write vectors: %v", err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./identity -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale; run go test ./identity -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors runs every committed vector through this package, as
// the TypeScript and Rust runtimes run them through theirs.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}

	t.Run("config", func(t *testing.T) {
		for _, c := range unique(t, file.Config, func(c configCase) string { return c.Name }) {
			cfg, err := identity.ParseConfig(c.Input)
			var got *effectiveConfig
			if err == nil {
				got = effective(cfg)
			}
			check(t, c.Name, got, c.Want)
		}
	})
	t.Run("passwordRule", func(t *testing.T) {
		for _, c := range unique(t, file.PasswordRule, func(c passwordRuleCase) string { return c.Name }) {
			check(t, c.Name, identity.CheckPassword(c.Password) == nil, c.Valid)
		}
	})
	t.Run("hashes", func(t *testing.T) {
		for _, c := range unique(t, file.Hashes, func(c hashCase) string { return c.Name }) {
			salt, err := base64.RawStdEncoding.DecodeString(c.Salt)
			if err != nil {
				t.Fatalf("%s: salt: %v", c.Name, err)
			}
			check(t, c.Name, identity.HashPasswordWithSalt(c.Password, salt, c.Params), c.PHC)
		}
	})
	t.Run("verify", func(t *testing.T) {
		for _, c := range unique(t, file.Verify, func(c verifyCase) string { return c.Name }) {
			check(t, c.Name, verify(c.PHC, c.Password, c.Current), c.Want)
		}
	})
	t.Run("tokens", func(t *testing.T) {
		for _, c := range unique(t, file.Tokens, func(c tokenCase) string { return c.Name }) {
			b, err := hex.DecodeString(c.Bytes)
			if err != nil {
				t.Fatalf("%s: bytes: %v", c.Name, err)
			}
			token, err := identity.NewToken(bytes.NewReader(b))
			if err != nil {
				t.Fatalf("%s: %v", c.Name, err)
			}
			check(t, c.Name, [2]string{token, identity.HashToken(c.Token)}, [2]string{c.Token, c.Hash})
		}
	})
	t.Run("cookies", func(t *testing.T) {
		for _, c := range unique(t, file.Cookies, func(c cookieCase) string { return c.Name }) {
			check(t, c.Name, cookies(t, c), c.Want)
		}
	})
	t.Run("credentials", func(t *testing.T) {
		for _, c := range unique(t, file.Credentials, func(c credentialCase) string { return c.Name }) {
			check(t, c.Name, credential(c), c.Want)
		}
	})
	t.Run("crossOrigin", func(t *testing.T) {
		for _, c := range unique(t, file.CrossOrigin, func(c crossOriginCase) string { return c.Name }) {
			check(t, c.Name, crossOrigin(t, c), c.Want)
		}
	})
	t.Run("permissionNames", func(t *testing.T) {
		for _, c := range unique(t, file.PermissionNames, func(c permissionCase) string { return c.Permission }) {
			check(t, c.Permission, identity.ValidPermission(c.Permission), c.Valid)
		}
	})
	t.Run("effectivePermissions", func(t *testing.T) {
		for _, c := range unique(t, file.EffectivePermissions, func(c effectiveCase) string { return c.Name }) {
			check(t, c.Name, identity.EffectivePermissions(sessionRoles(c.Roles)), c.Want)
		}
	})
	t.Run("grants", func(t *testing.T) {
		for _, c := range unique(t, file.Grants, func(c grantCase) string { return c.Name }) {
			uncovered := identity.Uncovered(c.Held, c.Given)
			check(t, c.Name, grantWant{Allowed: len(uncovered) == 0, Uncovered: uncovered}, c.Want)
		}
	})
	t.Run("capabilities", func(t *testing.T) {
		for _, c := range unique(t, file.Capabilities.Callers, func(c capabilityCase) string { return c.Name }) {
			roles := []session.Role{{Name: "caller", Permissions: c.Permissions}}
			check(t, c.Name, identity.CapabilitiesOf(file.Capabilities.Routes, roles, nil), c.Want)
		}
	})
}

// unique fails when two cases share a name, and returns the cases.
func unique[C any](t *testing.T, cases []C, name func(C) string) []C {
	t.Helper()
	if len(cases) == 0 {
		t.Fatal("the section has no cases")
	}
	seen := map[string]bool{}
	for _, c := range cases {
		if seen[name(c)] {
			t.Fatalf("case %q repeats", name(c))
		}
		seen[name(c)] = true
	}
	return cases
}

func check(t *testing.T, name string, got, want any) {
	t.Helper()
	if !reflect.DeepEqual(got, want) {
		g, _ := json.Marshal(got)
		w, _ := json.Marshal(want)
		t.Errorf("%s: got %s, want %s", name, g, w)
	}
}

func verify(phc, password string, current identity.Argon2Params) verifyWant {
	ok, rehash, err := identity.VerifyPassword(phc, password, current)
	return verifyWant{Malformed: err != nil, OK: ok, Rehash: rehash}
}

func cookies(t *testing.T, c cookieCase) cookieWant {
	t.Helper()
	cfg, err := identity.ParseConfig(c.Config)
	if err != nil {
		t.Fatalf("%s: config: %v", c.Name, err)
	}
	set := cfg.SessionCookie(c.Token, time.Duration(c.MaxAgeSeconds)*time.Second)
	return cookieWant{Set: set.String(), Clear: cfg.ClearCookie().String()}
}

func credential(c credentialCase) credentialWant {
	h := http.Header{}
	for _, kv := range c.Headers {
		h.Add(kv[0], kv[1])
	}
	cred, outcome := identity.ExtractCredential(h, c.CookieName)
	var want credentialWant
	switch outcome {
	case identity.NoCredential:
		want.Outcome = "none"
	case identity.UsableCredential:
		want.Outcome = "usable"
		token := cred.Token
		want.Token = &token
	case identity.InvalidCredential:
		want.Outcome = "invalid"
	}
	if cred.Transport != "" {
		transport := string(cred.Transport)
		want.Transport = &transport
	}
	return want
}

func crossOrigin(t *testing.T, c crossOriginCase) string {
	t.Helper()
	input, err := json.Marshal(map[string]any{"trustedOrigins": c.TrustedOrigins})
	if err != nil {
		t.Fatal(err)
	}
	cfg, err := identity.ParseConfig(input)
	if err != nil {
		t.Fatalf("%s: config: %v", c.Name, err)
	}
	r := httptest.NewRequest(c.Method, "http://"+c.Host+"/auth/logout", nil)
	r.Host = c.Host
	for k, v := range c.Headers {
		r.Header.Set(k, v)
	}
	if identity.CheckCrossOrigin(cfg, r) != nil {
		return "refuse"
	}
	return "allow"
}

func sessionRoles(roles []parityRole) []session.Role {
	out := make([]session.Role, len(roles))
	for i, r := range roles {
		out[i] = session.Role{Name: r.Name, Permissions: r.Permissions}
	}
	return out
}

