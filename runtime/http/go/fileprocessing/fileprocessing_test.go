// memBucket is a bucket in memory.
type memBucket struct {
	mu      sync.Mutex
	objects map[string]memObject
}

type memObject struct {
	data        []byte
	contentType string
}

func (b *memBucket) Name() string { return "mem" }

func (b *memBucket) Put(_ context.Context, name string, body io.Reader, opts bucket.PutOptions) (bucket.PutResult, error) {
	data, err := io.ReadAll(body)
	if err != nil {
		return bucket.PutResult{}, err
	}
	b.mu.Lock()
	defer b.mu.Unlock()
	b.objects[name] = memObject{data: data, contentType: opts.ContentType}
	return bucket.PutResult{Object: bucket.Object{Name: name, Size: int64(len(data)), ContentType: opts.ContentType}, Created: true}, nil
}

func (b *memBucket) Head(_ context.Context, name string) (bucket.Object, bool, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	o, ok := b.objects[name]
	return bucket.Object{Name: name, Size: int64(len(o.data))}, ok, nil
}

func (b *memBucket) Get(_ context.Context, name string) (*bucket.Reader, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	o, ok := b.objects[name]
	if !ok {
		return nil, fmt.Errorf("%w: %s", bucket.ErrNotFound, name)
	}
	return &bucket.Reader{ReadCloser: io.NopCloser(bytes.NewReader(o.data)), Object: bucket.Object{Name: name, Size: int64(len(o.data)), ContentType: o.contentType}}, nil
}

func (b *memBucket) Delete(_ context.Context, name string) error {
	b.mu.Lock()
	defer b.mu.Unlock()
	delete(b.objects, name)
	return nil
}

func (b *memBucket) List(context.Context, bucket.ListOptions) (bucket.Page, error) {
	return bucket.Page{}, nil
}

func (b *memBucket) SignedURL(_ context.Context, name string, _ bucket.SignedURLOptions) (string, error) {
	return "https://mem.example/" + name, nil
}

// memAttachments are the attachments' pending and processed over rows in
// memory, as the repositories run them.
type memAttachments struct{ rows []parityRow }

func (m *memAttachments) Pending(_ context.Context, kind string, limit int) ([]rowrefs.PendingObject, error) {
	seen := map[string]bool{}
	var out []rowrefs.PendingObject
	for _, r := range m.rows {
		state := r.Extraction
		if kind == rowrefs.KindPreview {
			state = r.Preview
		}
		if state != rowrefs.ProcessingPending || seen[r.ObjectKey] {
			continue
		}
		seen[r.ObjectKey] = true
		out = append(out, rowrefs.PendingObject{ObjectKey: r.ObjectKey, MediaType: r.MediaType, ContentHash: "h"})
	}
	if len(out) > limit {
		out = out[:limit]
	}
	return out, nil
}

func (m *memAttachments) Processed(_ context.Context, in rowrefs.ProcessedInput) (int64, error) {
	var n int64
	for i := range m.rows {
		r := &m.rows[i]
		if r.ObjectKey != in.ObjectKey {
			continue
		}
		if p := in.Extraction; p != nil {
			r.Extraction = p.State
			if p.Text != nil {
				r.ExtractedText = p.Text
			}
		}
		if p := in.Preview; p != nil {
			r.Preview = p.State
			if p.Object != nil {
				r.PreviewObject = p.Object
			}
		}
		n++
	}
	return n, nil
}

// scenarioProcessor is a processor a scenario names, which records each
// call into it in asked.
type scenarioProcessor struct {
	spec  parityProcessor
	asked *[]string
}

func (p scenarioProcessor) MediaTypes() []string { return p.spec.MediaTypes }

func (p scenarioProcessor) fails(mediaType string) bool {
	return slices.ContainsFunc(p.spec.FailsOn, func(t string) bool { return providers.ReadsMediaType([]string{t}, mediaType) })
}

func (p scenarioProcessor) ExtractText(_ context.Context, file providers.FileInput) (*providers.ExtractedText, error) {
	*p.asked = append(*p.asked, p.spec.Name+":extractText:"+file.MediaType)
	switch {
	case p.fails(file.MediaType) || p.spec.Extract == "fail":
		return nil, errors.New("the extraction failed")
	case p.spec.Extract == "upper":
		return &providers.ExtractedText{Text: strings.ToUpper(string(file.Bytes))}, nil
	}
	return nil, nil
}

func (p scenarioProcessor) Preview(_ context.Context, file providers.FileInput, _ providers.PreviewOptions) (*providers.Preview, error) {
	*p.asked = append(*p.asked, p.spec.Name+":preview:"+file.MediaType)
	switch {
	case p.fails(file.MediaType) || p.spec.Preview == "fail":
		return nil, errors.New("the preview failed")
	case p.spec.Preview == "svg":
		return &providers.Preview{MediaType: "image/svg+xml", Bytes: []byte("<svg/>"), Width: 1, Height: 1}, nil
	}
	return nil, nil
}

// runScenario runs s's two passes and answers what they did.
func runScenario(t *testing.T, s parityScenario) parityWant {
	t.Helper()
	var asked []string
	slots := map[string]providers.Interface{}
	config := map[string]providers.ConfigValue{}
	var definitions []providers.Definition
	for _, spec := range s.Processors {
		slots[spec.Slot] = providers.Files
		config[spec.Slot] = providers.Text(spec.Name)
		definitions = append(definitions, providers.MustDefine(providers.Definition{
			Name:       spec.Name,
			Implements: providers.Files,
			Create: func(context.Context, providers.Settings, providers.Context) (any, error) {
				return scenarioProcessor{spec: spec, asked: &asked}, nil
			},
		}))
	}
	registry, err := providers.From(providers.Options{Slots: slots, Config: config, Definitions: definitions})
	if err != nil {
		t.Fatal(err)
	}
	objects := &memBucket{objects: map[string]memObject{}}
	for _, o := range s.Objects {
		data := []byte(o.Text)
		if o.Size > 0 {
			data = make([]byte, o.Size)
		}
		objects.objects[o.Name] = memObject{data: data}
	}
	rows := &memAttachments{rows: slices.Clone(s.Files)}
	core, logs := observer.New(zap.DebugLevel)
	var out parityWant
	for range 2 {
		run, err := Process(context.Background(), Options{Attachments: rows, Providers: registry, Bucket: objects, Logger: zap.New(core), MaxBytes: s.MaxBytes})
		if err != nil {
			t.Fatal(err)
		}
		out.Runs = append(out.Runs, run)
	}
	out.Files = rows.rows
	for name, o := range objects.objects {
		if o.contentType != "" {
			out.Previews = append(out.Previews, parityPreview{Name: name, ContentType: o.contentType, Text: string(o.data)})
		}
	}
	sort.Slice(out.Previews, func(i, j int) bool { return out.Previews[i].Name < out.Previews[j].Name })
	out.Asked = asked
	for _, entry := range logs.All() {
		if entry.Message != "a file was not processed" {
			t.Errorf("logged %q", entry.Message)
		}
		out.Reasons = append(out.Reasons, entry.ContextMap()["reason"].(string))
		// The failure is logged without the file's bytes or text.
		for _, o := range s.Objects {
			if o.Text != "" && strings.Contains(fmt.Sprint(entry.ContextMap()), o.Text) {
				t.Errorf("a failure logs %q", o.Text)
			}
		}
	}
	if out.Previews == nil {
		out.Previews = []parityPreview{}
	}
	if out.Asked == nil {
		out.Asked = []string{}
	}
	if out.Reasons == nil {
		out.Reasons = []string{}
	}
	return out
}

// TestFileProcessingParity runs every scenario and holds what Process
// does to runtime/http/testdata/file_processing_parity.json, which the
// TypeScript and Rust passes run too; -update writes it.
func TestFileProcessingParity(t *testing.T) {
	corpus := parityFile{Comment: parityComment, Scenarios: parityScenarios()}
	for i := range corpus.Scenarios {
		corpus.Scenarios[i].Want = runScenario(t, corpus.Scenarios[i])
	}
	data, err := json.MarshalIndent(corpus, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	data = append(data, '\n')
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("%v (go test ./fileprocessing -run TestFileProcessingParity -update writes it)", err)
	}
	var file parityFile
	if err := json.Unmarshal(committed, &file); err != nil {
		t.Fatal(err)
	}
	for _, s := range file.Scenarios {
		if got := runScenario(t, s); !reflect.DeepEqual(got, s.Want) {
			t.Errorf("%s:\n got %+v\nwant %+v", s.Name, got, s.Want)
		}
	}
	if !bytes.Equal(committed, data) {
		t.Errorf("%s is stale: go test ./fileprocessing -run TestFileProcessingParity -update", parityPath)
	}
}

// TestTheFirstScenarioIsTheTypeScriptPass holds the first scenario's
// answers to what the TypeScript pass's own test expects of the same
// files (file-processing.test.ts).
func TestTheFirstScenarioIsTheTypeScriptPass(t *testing.T) {
	got := runScenario(t, parityScenarios()[0])
	if want := (Run{Extracted: 1, Previewed: 1, Failed: 3}); got.Runs[0] != want || got.Runs[1] != (Run{}) {
		t.Fatalf("runs %+v", got.Runs)
	}
	upper, preview := "HELLO", rowrefs.PreviewObjectOf("attachments/a")
	if r := got.Files[0]; r.Extraction != "done" || *r.ExtractedText != upper || r.Preview != "done" || *r.PreviewObject != preview {
		t.Errorf("the first file: %+v", r)
	}
	if r := got.Files[1]; r.Extraction != "done" || *r.ExtractedText != upper {
		t.Errorf("the file filed elsewhere: %+v", r)
	}
	for i, want := range []string{"", "", "failed", "", "failed"} {
		if want != "" && got.Files[i].Extraction != want {
			t.Errorf("file %d: %+v", i, got.Files[i])
		}
	}
	if got.Files[3].Preview != "failed" {
		t.Errorf("the broken preview: %+v", got.Files[3])
	}
	if !slices.Contains(got.Reasons, "no files slot of the environment reads image/png") {
		t.Errorf("reasons %q", got.Reasons)
	}
	if got.Asked[0] != "first:extractText:text/plain" || slices.Contains(got.Asked, "second:extractText:text/plain") {
		t.Errorf("asked %q", got.Asked)
	}
}

// TestProcessNeedsItsSeams refuses a pass with no attachments or bucket.
func TestProcessNeedsItsSeams(t *testing.T) {
	if _, err := Process(context.Background(), Options{Bucket: &memBucket{}}); err == nil {
		t.Error("a pass with no attachments ran")
	}
	if _, err := Process(context.Background(), Options{Attachments: &memAttachments{}}); err == nil {
		t.Error("a pass with no bucket ran")
	}
}
