const parityComment = "Generated by runtime/http/go/fileprocessing (cd runtime/http/go && go test ./fileprocessing -run TestFileProcessingParity -update); do not edit. " +
	"The file processor's pass (D154, D159, #603): Go's fileprocessing.Process, TypeScript's processFiles and Rust's file_processing::process_files each run every scenario. " +
	"A scenario's files are rows of an attachments sub-table in memory, in the order given: pending lists each object of a kind still pending once, in that order, and processed sets the state, and the text or preview object, on every row of the object. " +
	"Its objects are a bucket in memory: an object holds text's UTF-8 bytes, or size zero bytes. " +
	"Its processors fill files slots, asked in slot order: each reads mediaTypes; extract is upper (the bytes as UTF-8, upper-cased), none (no answer) or fail (an error, 'the extraction failed'); preview is svg (image/svg+xml '<svg/>', 1 by 1), none or fail ('the preview failed'); a type of failsOn fails both. " +
	"maxBytes is the pass's limit, its default when 0. The pass runs twice: want.runs are both passes' counts, want.files the rows after them, want.previews the objects the passes put, by name, " +
	"want.asked each call into a processor as name:operation:mediaType, and want.reasons the reason each failure is logged with, in order."

type parityFile struct {
	Comment   string           `json:"comment"`
	Scenarios []parityScenario `json:"scenarios"`
}

type parityScenario struct {
	Name       string            `json:"name"`
	Processors []parityProcessor `json:"processors"`
	Files      []parityRow       `json:"files"`
	Objects    []parityObject    `json:"objects"`
	MaxBytes   int64             `json:"maxBytes"`
	Want       parityWant        `json:"want"`
}

type parityProcessor struct {
	Slot       string   `json:"slot"`
	Name       string   `json:"name"`
	MediaTypes []string `json:"mediaTypes"`
	Extract    string   `json:"extract"`
	Preview    string   `json:"preview"`
	FailsOn    []string `json:"failsOn,omitempty"`
}

type parityRow struct {
	ObjectKey     string  `json:"objectKey"`
	MediaType     string  `json:"mediaType"`
	Extraction    string  `json:"extraction"`
	ExtractedText *string `json:"extractedText,omitempty"`
	Preview       string  `json:"preview"`
	PreviewObject *string `json:"previewObject,omitempty"`
}

type parityObject struct {
	Name string `json:"name"`
	Text string `json:"text,omitempty"`
	Size int    `json:"size,omitempty"`
}

type parityPreview struct {
	Name        string `json:"name"`
	ContentType string `json:"contentType"`
	Text        string `json:"text"`
}

type parityWant struct {
	Runs     []Run           `json:"runs"`
	Files    []parityRow     `json:"files"`
	Previews []parityPreview `json:"previews"`
	Asked    []string        `json:"asked"`
	Reasons  []string        `json:"reasons"`
}

