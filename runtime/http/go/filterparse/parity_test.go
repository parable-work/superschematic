// parityPath is the vector file the Go, TypeScript and Rust HTTP runtimes
// read, relative to this package.
const parityPath = "../../testdata/filter_parity.json"

const parityComment = "Generated by runtime/http/go/filterparse (cd runtime/http/go && go test ./filterparse -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each run every vector through their filter reader (D106): filterparse.Parse in Go, readFilters in TypeScript and FilterSpec::query in Rust. " +
	"reads: spec is an operation's FilterBy, its fields and each one's operators, and query a raw query string, which the runtime parses as its router does, WHATWG's form-urlencoded parser: pairs split at & alone, + a space, a % that starts no escape kept as it is; " +
	"the reader answers filters, each a field, an operator and its values as the query sent them (in's split at commas and trimmed), in the spec's field order and then the operators' (eq, in, gt, gte, lt, lte, contains, isNull), or refuses the request with problem, the 400's status, code, detail and details, compared as JSON values. " +
	"The reader reads a request's filter keys in ascending order of their UTF-8 bytes, so a request with two faults is refused for the same one in every runtime. A value's own type is not the reader's to check: the route decodes it as an item of a query list of the field's type. " +
	"queries: filters written as the bracket form's query parameters (filterparse.Query), pairs of a name and a value, unescaped, in the filters' order; an SDK that writes a typed filter sends these pairs, and reading them back under a spec that names their fields gives the filters."

type parityFieldSpec struct {
	Name      string   `json:"name"`
	Operators []string `json:"operators"`
}

type paritySpec struct {
	Fields []parityFieldSpec `json:"fields"`
}

// spec is the vector's spec as the router carries it.
func (s paritySpec) spec() Spec {
	spec := Spec{}
	for _, field := range s.Fields {
		operators := make([]Operator, len(field.Operators))
		for i, operator := range field.Operators {
			operators[i] = Operator(operator)
		}
		spec.Fields = append(spec.Fields, FieldSpec{Name: field.Name, Operators: operators})
	}
	return spec
}

type parityFilter struct {
	Field    string   `json:"field"`
	Operator string   `json:"operator"`
	Values   []string `json:"values"`
}

func filterVectors(request []Filter) []parityFilter {
	vectors := make([]parityFilter, len(request))
	for i, filter := range request {
		vectors[i] = parityFilter{Field: filter.Field, Operator: string(filter.Operator), Values: filter.Values}
	}
	return vectors
}

type parityProblem struct {
	Status  int            `json:"status"`
	Code    string         `json:"code"`
	Detail  string         `json:"detail"`
	Details paging.Details `json:"details"`
}

type parityRead struct {
	Name    string         `json:"name"`
	Spec    paritySpec     `json:"spec"`
	Query   string         `json:"query"`
	Filters []parityFilter `json:"filters,omitempty"`
	Problem *parityProblem `json:"problem,omitempty"`
}

type parityQuery struct {
	Name    string         `json:"name"`
	Filters []parityFilter `json:"filters"`
	Pairs   [][2]string    `json:"pairs"`
}

type parityFile struct {
	Comment string        `json:"comment"`
	Reads   []parityRead  `json:"reads"`
	Queries []parityQuery `json:"queries"`
}

// problemFromAppError is the vector's view of a refusal: the problem the
// router writes for it.
func problemFromAppError(t *testing.T, err error) parityProblem {
	t.Helper()
	var appErr *apperror.AppError
	if !errors.As(err, &appErr) {
		t.Fatalf("not an app error: %v", err)
	}
	details, ok := appErr.Details.(paging.Details)
	if !ok {
		t.Fatalf("details %T, want paging.Details", appErr.Details)
	}
	return parityProblem{Status: appErr.HTTPStatus(), Code: appErr.ErrorCode, Detail: appErr.Message, Details: details}
}

// The operators of each kind of field (ir.FilterOperators), as the specs
// below write them.
var (
	equalsOps  = []string{"eq", "in"}
	orderedOps = []string{"eq", "in", "gt", "gte", "lt", "lte"}
	textOps    = []string{"eq", "in", "contains"}
)

func nullable(operators []string) []string {
	return append(append([]string{}, operators...), "isNull")
}

// parityCorpus builds the vectors, each with the answer the Go runtime
// gives.
func parityCorpus(t *testing.T) parityFile {
	t.Helper()
	issues := paritySpec{Fields: []parityFieldSpec{
		{Name: "assigneeId", Operators: nullable(equalsOps)},
		{Name: "stateId", Operators: equalsOps},
		{Name: "priority", Operators: orderedOps},
		{Name: "title", Operators: textOps},
		{Name: "createdAt", Operators: orderedOps},
		{Name: "dueOn", Operators: nullable(orderedOps)},
	}}
	one := paritySpec{Fields: []parityFieldSpec{{Name: "status", Operators: equalsOps}}}
	var fifty, fiftyOne, hundred, hundredOne []string
	for i := range 101 {
		value := fmt.Sprintf("v%03d", i)
		if i < 100 {
			hundred = append(hundred, value)
		}
		hundredOne = append(hundredOne, value)
		if i < 51 {
			fiftyOne = append(fiftyOne, "filter[status]="+value)
		}
		if i < 50 {
			fifty = append(fifty, "other"+itoa(i)+"=x")
		}
	}
	reads := []parityRead{
		{Name: "nothing sent", Spec: issues, Query: ""},
		{Name: "no filter among other parameters", Spec: issues, Query: "limit=5&sort=-priority&q=filter"},
		{Name: "equality without an operator", Spec: issues, Query: "filter[stateId]=open"},
		{Name: "equality by its operator", Spec: issues, Query: "filter[stateId][eq]=open"},
		{Name: "brackets percent-encoded", Spec: issues, Query: "filter%5BstateId%5D%5Bin%5D=open%2Cdone"},
		{Name: "an in of three", Spec: issues, Query: "filter[stateId][in]=open,started,done"},
		{Name: "an in trims its values and drops empty ones", Spec: issues, Query: "filter[stateId][in]=+open+,,done,"},
		{Name: "an in of one", Spec: issues, Query: "filter[stateId][in]=open"},
		{Name: "an in of 100 values", Spec: issues, Query: "filter[stateId][in]=" + strings.Join(hundred, ",")},
		{Name: "an in of 101 values", Spec: issues, Query: "filter[stateId][in]=" + strings.Join(hundredOne, ",")},
		{Name: "an in of no value", Spec: issues, Query: "filter[stateId][in]="},
		{Name: "an in of commas alone", Spec: issues, Query: "filter[stateId][in]=,+,"},
		{Name: "a range", Spec: issues, Query: "filter[priority][gte]=2&filter[priority][lt]=5"},
		{Name: "every ordered operator", Spec: issues, Query: "filter[priority][lte]=9&filter[priority][gt]=1&filter[priority][lt]=8&filter[priority][gte]=2&filter[priority]=3&filter[priority][in]=3,4"},
		{Name: "contains", Spec: issues, Query: "filter[title][contains]=crash+on+save"},
		{Name: "contains keeps a comma and its spaces", Spec: issues, Query: "filter[title][contains]=+a,+b+"},
		{Name: "contains of no text", Spec: issues, Query: "filter[title][contains]="},
		{Name: "equality with an empty value", Spec: issues, Query: "filter[title]="},
		{Name: "equality keeps a comma", Spec: issues, Query: "filter[title]=a,b"},
		{Name: "a value with a bracket and an equals sign", Spec: issues, Query: "filter[title]=%5Bdraft%5D=1"},
		{Name: "isNull true", Spec: issues, Query: "filter[assigneeId][isNull]=true"},
		{Name: "isNull false", Spec: issues, Query: "filter[dueOn][isNull]=false"},
		{Name: "isNull in another case", Spec: issues, Query: "filter[assigneeId][isNull]=True"},
		{Name: "isNull as a number", Spec: issues, Query: "filter[assigneeId][isNull]=1"},
		{Name: "isNull on a field that is never null", Spec: issues, Query: "filter[stateId][isNull]=true"},
		{Name: "the fields in the spec's order", Spec: issues, Query: "filter[title]=x&filter[createdAt][gte]=2026-01-01T00:00:00Z&filter[assigneeId]=u1&filter[stateId]=open"},
		{Name: "a field's operators in their order", Spec: issues, Query: "filter[assigneeId][isNull]=false&filter[assigneeId][in]=u1,u2&filter[assigneeId]=u1"},
		{Name: "a field the spec does not name", Spec: issues, Query: "filter[secret]=x"},
		{Name: "a field in another case", Spec: issues, Query: "filter[StateId]=open"},
		{Name: "a field of one spec's that another lacks", Spec: one, Query: "filter[priority]=1"},
		{Name: "an operator no field takes", Spec: issues, Query: "filter[stateId][neq]=open"},
		{Name: "an operator the field does not take", Spec: issues, Query: "filter[stateId][gt]=open"},
		{Name: "contains on a field that is not text", Spec: issues, Query: "filter[priority][contains]=1"},
		{Name: "an operator in another case", Spec: issues, Query: "filter[stateId][IN]=open"},
		{Name: "a key sent twice", Spec: issues, Query: "filter[stateId]=open&filter[stateId]=done"},
		{Name: "equality sent both ways", Spec: issues, Query: "filter[stateId][eq]=open&filter[stateId]=done"},
		{Name: "an in sent twice", Spec: issues, Query: "filter[stateId][in]=a&filter[stateId][in]=b"},
		{Name: "filter alone", Spec: issues, Query: "filter=open"},
		{Name: "an empty field", Spec: issues, Query: "filter[]=open"},
		{Name: "an empty operator", Spec: issues, Query: "filter[stateId][]=open"},
		{Name: "three brackets", Spec: issues, Query: "filter[stateId][in][0]=open"},
		{Name: "an unclosed bracket", Spec: issues, Query: "filter[stateId=open"},
		{Name: "text after the bracket", Spec: issues, Query: "filter[stateId]x=open"},
		{Name: "a bracket inside the field", Spec: issues, Query: "filter[state[Id]=open"},
		{Name: "a key that only starts like a filter", Spec: issues, Query: "filters[stateId]=open&filtered=1"},
		{Name: "two faults, the first key in byte order refused", Spec: issues, Query: "filter[zzz]=1&filter[aaa]=2"},
		{Name: "a malformed key before an unknown field", Spec: issues, Query: "filter[zzz]=1&filter[]=2"},
		{Name: "50 other parameters and one filter", Spec: one, Query: strings.Join(fifty, "&") + "&filter[status]=open"},
		{Name: "51 filter parameters", Spec: one, Query: strings.Join(fiftyOne, "&")},
		{Name: "51 filter parameters, counted before any is read", Spec: one, Query: "filter[]=x&" + strings.Join(fiftyOne[:50], "&")},
		{Name: "equality on a field that takes only another operator", Spec: paritySpec{Fields: []parityFieldSpec{{Name: "status", Operators: []string{"in"}}}}, Query: "filter[status]=open"},
		{Name: "a spec of no field", Spec: paritySpec{Fields: []parityFieldSpec{}}, Query: "filter[status]=open"},
	}
	for i := range reads {
		request, refusal := Parse(paging.QueryValues(reads[i].Query), reads[i].Spec.spec())
		if refusal != nil {
			problem := problemFromAppError(t, refusal)
			reads[i].Problem = &problem
			continue
		}
		reads[i].Filters = filterVectors(request)
	}

	queries := []parityQuery{
		{Name: "equality", Filters: []parityFilter{{Field: "stateId", Operator: "eq", Values: []string{"open"}}}},
		{Name: "an in", Filters: []parityFilter{{Field: "stateId", Operator: "in", Values: []string{"open", "done"}}}},
		{Name: "a range and a null check", Filters: []parityFilter{
			{Field: "priority", Operator: "gte", Values: []string{"2"}},
			{Field: "priority", Operator: "lt", Values: []string{"5"}},
			{Field: "assigneeId", Operator: "isNull", Values: []string{"true"}},
		}},
		{Name: "contains with spaces", Filters: []parityFilter{{Field: "title", Operator: "contains", Values: []string{"crash on save"}}}},
		{Name: "every operator", Filters: []parityFilter{
			{Field: "priority", Operator: "eq", Values: []string{"3"}},
			{Field: "priority", Operator: "in", Values: []string{"3", "4"}},
			{Field: "priority", Operator: "gt", Values: []string{"1"}},
			{Field: "priority", Operator: "gte", Values: []string{"2"}},
			{Field: "priority", Operator: "lt", Values: []string{"8"}},
			{Field: "priority", Operator: "lte", Values: []string{"9"}},
			{Field: "title", Operator: "contains", Values: []string{"a&b=c"}},
			{Field: "dueOn", Operator: "isNull", Values: []string{"false"}},
		}},
	}
	for i := range queries {
		filters := make([]Filter, len(queries[i].Filters))
		for j, filter := range queries[i].Filters {
			filters[j] = Filter{Field: filter.Field, Operator: Operator(filter.Operator), Values: filter.Values}
		}
		values := Query(filters)
		for _, filter := range filters {
			key := at(filter.Field)
			if filter.Operator != OperatorEq {
				key += "[" + string(filter.Operator) + "]"
			}
			queries[i].Pairs = append(queries[i].Pairs, [2]string{key, values.Get(key)})
		}
		// What Query writes reads back as the filters, under their spec.
		request, refusal := Parse(values, issues.spec())
		if refusal != nil {
			t.Fatalf("%s: reading its query back: %v", queries[i].Name, refusal)
		}
		if got, want := filterSet(request), filterSet(filters); !reflect.DeepEqual(got, want) {
			t.Fatalf("%s: read back %v, want %v", queries[i].Name, got, want)
		}
	}
	return parityFile{Comment: parityComment, Reads: reads, Queries: queries}
}

// filterSet is a request's filters by field and operator, whatever their
// order.
func filterSet(filters []Filter) map[string][]string {
	set := map[string][]string{}
	for _, filter := range filters {
		set[filter.Field+" "+string(filter.Operator)] = filter.Values
	}
	return set
}

func itoa(n int) string {
	data, _ := json.Marshal(n)
	return string(data)
}

// TestWriteParityVectors writes the corpus with -update, and otherwise
// fails when the committed file is not what the corpus gives.
func TestWriteParityVectors(t *testing.T) {
	data, err := json.MarshalIndent(parityCorpus(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	data = append(data, '\n')
	if *update {
		if err := os.WriteFile(parityPath, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(parityPath)
	if err != nil {
		t.Fatalf("read %s (write it with -update): %v", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale: run go test ./filterparse -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors runs the committed file through the Go reader, as the
// TypeScript and Rust runtimes run it: through Read, the router's entry,
// so the problem a route writes is the vector's.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(parityPath)
	if err != nil {
		t.Fatal(err)
	}
	var file parityFile
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&file); err != nil {
		t.Fatal(err)
	}
	if len(file.Reads) == 0 || len(file.Queries) == 0 {
		t.Fatal("a section of the vectors is empty")
	}
	refused, read := 0, 0
	for _, vector := range file.Reads {
		recorder := httptest.NewRecorder()
		request := httptest.NewRequest(http.MethodGet, "/issues?"+vector.Query, nil)
		got, ok := Read(recorder, request, vector.Spec.spec())
		switch {
		case vector.Problem != nil:
			refused++
			if ok {
				t.Errorf("%s: read %v, want it refused", vector.Name, got)
				continue
			}
			var body struct {
				Status  int            `json:"status"`
				Code    string         `json:"code"`
				Detail  string         `json:"detail"`
				Details paging.Details `json:"details"`
			}
			if err := json.Unmarshal(recorder.Body.Bytes(), &body); err != nil {
				t.Errorf("%s: the problem is not JSON: %v", vector.Name, err)
				continue
			}
			if problem := (parityProblem{Status: body.Status, Code: body.Code, Detail: body.Detail, Details: body.Details}); !reflect.DeepEqual(problem, *vector.Problem) {
				t.Errorf("%s: problem %+v, want %+v", vector.Name, problem, *vector.Problem)
			}
		case !ok:
			t.Errorf("%s: refused with %s, want %v", vector.Name, recorder.Body.String(), vector.Filters)
		default:
			read++
			want := vector.Filters
			if want == nil {
				want = []parityFilter{}
			}
			if filters := filterVectors(got); !reflect.DeepEqual(filters, want) {
				t.Errorf("%s: filters %v, want %v", vector.Name, filters, want)
			}
		}
	}
	if refused == 0 || read == 0 {
		t.Fatalf("the vectors hold %d reads and %d refusals; want both", read, refused)
	}
}
