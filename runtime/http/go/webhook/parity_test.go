var update = flag.Bool("update", false, "rewrite runtime/http/testdata/webhook_jwt_parity.json")

const parityPath = "../../testdata/webhook_jwt_parity.json"

// The corpus names no key and carries no signature: each runtime signs
// every vector's token with P-256 keys it generates for the run, so no key
// is committed and a vector reads the same in Go, TypeScript and Rust.
const parityComment = "Generated by runtime/http/go/webhook (cd runtime/http/go && go test ./webhook -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each run every vector through their JWT body-hash webhook verifier (D81): webhook.JWTBodyHashVerifier in Go, jwtBodyHashVerifier in TypeScript, JwtBodyHashVerifier in Rust. " +
	"Build the verifier from verifier (seconds and bytes as each runtime takes them) with the clock at the vector's now (unix seconds), a fresh cache, and a key lookup that fails when lookupFails, " +
	"answers each kid in keys with the public JWK (kty EC, crv P-256, kid, use sig, alg ES256) of a P-256 key the run generates (the trusted key), and answers no key for any other kid. " +
	"Mount it in front of a POST route that answers 200 with the body it reads, and POST body (UTF-8) with Content-Type application/json and, unless token is null, the header verifier.header. " +
	"The header's value is token.raw when it is set. Otherwise it is token.signingInput, a dot, and the base64url of a signature: the ES256 signature (r||s, 64 bytes) of token.signed, or of token.signingInput when signed is empty, by token.signer, " +
	"trusted, or stranger (a second key the run generates, which the lookup never answers), or none (no signature, so the token ends in a dot); " +
	"then token.tamper, when set, changes it: flip XORs its last byte with 1, truncate drops its last byte. token.header and token.claims are the two JSON objects signingInput encodes, for reading. " +
	"Compare the status and want.code, the problem code of a refusal (null on 200); on 200 the route read body exactly."

type parityFile struct {
	Comment  string         `json:"comment"`
	Verifier parityVerifier `json:"verifier"`
	Vectors  []parityVector `json:"vectors"`
}

type parityVerifier struct {
	Header           string `json:"header"`
	Alg              string `json:"alg"`
	MaxAgeSeconds    int64  `json:"maxAgeSeconds"`
	ClockSkewSeconds int64  `json:"clockSkewSeconds"`
	BodyHashClaim    string `json:"bodyHashClaim"`
	MaxBodyBytes     int64  `json:"maxBodyBytes"`
}

type parityVector struct {
	Name        string       `json:"name"`
	Now         int64        `json:"now"`
	Keys        []string     `json:"keys"`
	LookupFails bool         `json:"lookupFails"`
	Token       *parityToken `json:"token"`
	Body        string       `json:"body"`
	Want        parityWant   `json:"want"`
}

type parityToken struct {
	Raw          string          `json:"raw,omitempty"`
	Header       json.RawMessage `json:"header,omitempty"`
	Claims       json.RawMessage `json:"claims,omitempty"`
	SigningInput string          `json:"signingInput,omitempty"`
	Signed       string          `json:"signed,omitempty"`
	Signer       string          `json:"signer,omitempty"`
	Tamper       string          `json:"tamper,omitempty"`
}

type parityWant struct {
	Status int     `json:"status"`
	Code   *string `json:"code"`
}

// member and object are a JSON object that keeps its members' order, so a
// token's segments are fixed.
type member struct {
	name  string
	value any
}

type object []member

func (o object) MarshalJSON() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteByte('{')
	for i, m := range o {
		if i > 0 {
			buf.WriteByte(',')
		}
		name, err := json.Marshal(m.name)
		if err != nil {
			return nil, err
		}
		value, err := json.Marshal(m.value)
		if err != nil {
			return nil, err
		}
		buf.Write(name)
		buf.WriteByte(':')
		buf.Write(value)
	}
	buf.WriteByte('}')
	return buf.Bytes(), nil
}

func (o object) with(name string, value any) object {
	out := make(object, 0, len(o)+1)
	found := false
	for _, m := range o {
		if m.name == name {
			m.value = value
			found = true
		}
		out = append(out, m)
	}
	if !found {
		out = append(out, member{name, value})
	}
	return out
}

func (o object) without(name string) object {
	out := make(object, 0, len(o))
	for _, m := range o {
		if m.name != name {
			out = append(out, m)
		}
	}
	return out
}

func b64(b []byte) string { return base64.RawURLEncoding.EncodeToString(b) }

func hexSHA256(body string) string {
	sum := sha256.Sum256([]byte(body))
	return hex.EncodeToString(sum[:])
}

func compact(t testing.TB, v any) []byte {
	t.Helper()
	data, err := json.Marshal(v)
	if err != nil {
		t.Fatal(err)
	}
	return data
}

// The verifier every vector runs: Plaid's header and claim.
var parityConfig = parityVerifier{
	Header:           "Plaid-Verification",
	Alg:              "ES256",
	MaxAgeSeconds:    300,
	ClockSkewSeconds: 60,
	BodyHashClaim:    "request_body_sha256",
	MaxBodyBytes:     1024,
}

// plaidBody is a webhook as Plaid sends one, pretty-printed: the hash is of
// these bytes, not of the JSON they parse to.
const plaidBody = "{\n  \"environment\": \"sandbox\",\n  \"historical_update_complete\": false,\n  \"initial_update_complete\": true,\n  \"item_id\": \"item-sandbox-1\",\n  \"webhook_code\": \"SYNC_UPDATES_AVAILABLE\",\n  \"webhook_type\": \"TRANSACTIONS\"\n}"

const parityNow = 1767225600 // 2026-01-01T00:00:00Z

func parityCorpus(t testing.TB) parityFile {
	t.Helper()
	header := object{{"alg", "ES256"}, {"kid", "k1"}, {"typ", "JWT"}}
	claims := object{{"iat", parityNow}, {"request_body_sha256", hexSHA256(plaidBody)}}
	signed := func(header, claims object) *parityToken {
		h, c := compact(t, header), compact(t, claims)
		return &parityToken{Header: h, Claims: c, SigningInput: b64(h) + "." + b64(c), Signer: "trusted"}
	}
	code := func(c string) *string { return &c }
	ok := parityWant{Status: http.StatusOK}
	refused := parityWant{Status: http.StatusUnauthorized, Code: code(webhook.CodeInvalidSignature)}
	large := strings.Repeat("x", int(parityConfig.MaxBodyBytes)+1)

	tokenWith := func(change func(*parityToken)) *parityToken {
		tok := signed(header, claims)
		change(tok)
		return tok
	}
	vectors := []parityVector{
		{Name: "a signed webhook reaches the route with its body", Token: signed(header, claims), Body: plaidBody, Want: ok},
		{Name: "an iat maxAge old is accepted", Token: signed(header, claims.with("iat", parityNow-300)), Body: plaidBody, Want: ok},
		{Name: "an iat older than maxAge is refused", Token: signed(header, claims.with("iat", parityNow-301)), Body: plaidBody, Want: refused},
		{Name: "an iat clockSkew ahead is accepted", Token: signed(header, claims.with("iat", parityNow+60)), Body: plaidBody, Want: ok},
		{Name: "an iat further ahead is refused", Token: signed(header, claims.with("iat", parityNow+61)), Body: plaidBody, Want: refused},
		{Name: "a token without iat is refused", Token: signed(header, claims.without("iat")), Body: plaidBody, Want: refused},
		{Name: "an iat that is no number is refused", Token: signed(header, claims.with("iat", "1767225600")), Body: plaidBody, Want: refused},
		{Name: "a body whose hash is not the claim's is refused", Token: signed(header, claims), Body: strings.Replace(plaidBody, "sandbox", "production", 1), Want: refused},
		{Name: "an uppercase body hash is refused", Token: signed(header, claims.with("request_body_sha256", strings.ToUpper(hexSHA256(plaidBody)))), Body: plaidBody, Want: refused},
		{Name: "a token without the body hash claim is refused", Token: signed(header, claims.without("request_body_sha256")), Body: plaidBody, Want: refused},
		{Name: "a body hash that is no string is refused", Token: signed(header, claims.with("request_body_sha256", 12345)), Body: plaidBody, Want: refused},
		{Name: "an empty body with its hash is accepted", Token: signed(header, claims.with("request_body_sha256", hexSHA256(""))), Body: "", Want: ok},
		{Name: "an unknown kid is refused", Token: signed(header.with("kid", "k2"), claims), Body: plaidBody, Want: refused},
		{Name: "a token without kid is refused", Token: signed(header.without("kid"), claims), Body: plaidBody, Want: refused},
		{Name: "an empty kid is refused", Token: signed(header.with("kid", ""), claims), Body: plaidBody, Want: refused},
		{Name: "another alg in the header is refused", Token: signed(header.with("alg", "RS256"), claims), Body: plaidBody, Want: refused},
		{Name: "a lowercase alg is refused", Token: signed(header.with("alg", "es256"), claims), Body: plaidBody, Want: refused},
		{Name: "alg none without a signature is refused", Token: tokenWith(func(tok *parityToken) {
			*tok = *signed(header.with("alg", "none"), claims)
			tok.Signer = "none"
		}), Body: plaidBody, Want: refused},
		{Name: "a token without a signature is refused", Token: tokenWith(func(tok *parityToken) { tok.Signer = "none" }), Body: plaidBody, Want: refused},
		{Name: "a tampered signature is refused", Token: tokenWith(func(tok *parityToken) { tok.Tamper = "flip" }), Body: plaidBody, Want: refused},
		{Name: "a truncated signature is refused", Token: tokenWith(func(tok *parityToken) { tok.Tamper = "truncate" }), Body: plaidBody, Want: refused},
		{Name: "a signature by a key the lookup does not answer is refused", Token: tokenWith(func(tok *parityToken) { tok.Signer = "stranger" }), Body: plaidBody, Want: refused},
		{Name: "claims changed after signing are refused", Token: tokenWith(func(tok *parityToken) {
			changed := signed(header, claims.with("iat", parityNow+30))
			tok.Signed = changed.SigningInput
		}), Body: plaidBody, Want: refused},
		{Name: "a request without the header is refused", Token: nil, Body: plaidBody, Want: refused},
		{Name: "a token that is not three segments is refused", Token: &parityToken{Raw: "eyJhbGciOiJFUzI1NiJ9.e30"}, Body: plaidBody, Want: refused},
		{Name: "a segment that is not JSON is refused", Token: &parityToken{Raw: "eyJhbGciOiJFUzI1NiIsImtpZCI6ImsxIn0.bm90IGpzb24.AAAA"}, Body: plaidBody, Want: refused},
		{Name: "a key that cannot be looked up answers 503", Token: signed(header, claims), Body: plaidBody, LookupFails: true, Want: parityWant{Status: http.StatusServiceUnavailable, Code: code(webhook.CodeKeyUnavailable)}},
		{Name: "a signed body over maxBodyBytes answers 413", Token: signed(header, claims.with("request_body_sha256", hexSHA256(large))), Body: large, Want: parityWant{Status: http.StatusRequestEntityTooLarge, Code: code(webhook.CodePayloadTooLarge)}},
		{Name: "an unsigned body over maxBodyBytes is refused for its signature", Token: nil, Body: large, Want: refused},
	}
	for i := range vectors {
		vectors[i].Now = parityNow
		if vectors[i].Keys == nil {
			vectors[i].Keys = []string{"k1"}
		}
	}
	return parityFile{Comment: parityComment, Verifier: parityConfig, Vectors: vectors}
}

// TestWriteParityVectors keeps runtime/http/testdata/webhook_jwt_parity.json
// equal to the vectors parityCorpus builds. It fails when the committed
// file is stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus(t)); err != nil {
		t.Fatalf("marshal vectors: %v", err)
	}
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatalf("write vectors: %v", err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./webhook -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, buf.Bytes()) {
		t.Fatalf("%s is stale; run go test ./webhook -run TestWriteParityVectors -update", parityPath)
	}
}

// testKey is a P-256 key generated for one run.
type testKey struct {
	private *ecdsa.PrivateKey
}

func newTestKey(t testing.TB) testKey {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	return testKey{key}
}

// jwk is the key's public JWK under kid, as Plaid's key endpoint answers.
func (k testKey) jwk(kid string) serviceauth.JWK {
	point, err := k.private.PublicKey.Bytes()
	if err != nil {
		panic(err)
	}
	return serviceauth.JWK{Kty: "EC", Crv: "P-256", Kid: kid, Use: "sig", Alg: "ES256", X: b64(point[1:33]), Y: b64(point[33:])}
}

// sign is the ES256 signature of input: r||s, 32 bytes each.
func (k testKey) sign(t testing.TB, input string) []byte {
	t.Helper()
	digest := sha256.Sum256([]byte(input))
	r, s, err := ecdsa.Sign(rand.Reader, k.private, digest[:])
	if err != nil {
		t.Fatal(err)
	}
	signature := make([]byte, 64)
	r.FillBytes(signature[:32])
	s.FillBytes(signature[32:])
	return signature
}

// token signs a vector's token with the run's keys.
func token(t testing.TB, tok *parityToken, trusted, stranger testKey) string {
	t.Helper()
	if tok.Raw != "" {
		return tok.Raw
	}
	signed := tok.Signed
	if signed == "" {
		signed = tok.SigningInput
	}
	var signature []byte
	switch tok.Signer {
	case "trusted":
		signature = trusted.sign(t, signed)
	case "stranger":
		signature = stranger.sign(t, signed)
	case "none":
	default:
		t.Fatalf("unknown signer %q", tok.Signer)
	}
	switch tok.Tamper {
	case "":
	case "flip":
		signature[len(signature)-1] ^= 1
	case "truncate":
		signature = signature[:len(signature)-1]
	default:
		t.Fatalf("unknown tamper %q", tok.Tamper)
	}
	return tok.SigningInput + "." + b64(signature)
}

// echo answers 200 with the body it reads, so a vector sees whether the
// route could read the body after the verifier.
func echo(t testing.TB) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		body, err := io.ReadAll(r.Body)
		if err != nil {
			t.Errorf("read body: %v", err)
		}
		w.WriteHeader(http.StatusOK)
		_, _ = w.Write(body)
	})
}

func readCorpus(t testing.TB) parityFile {
	t.Helper()
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatalf("read %s: %v", parityPath, err)
	}
	var file parityFile
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&file); err != nil {
		t.Fatalf("parse %s: %v", parityPath, err)
	}
	return file
}

// TestParityVectors runs every committed vector through the verifier, with
// keys generated for this run.
func TestParityVectors(t *testing.T) {
	file := readCorpus(t)
	if len(file.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	trusted, stranger := newTestKey(t), newTestKey(t)
	cfg := file.Verifier
	names := map[string]bool{}
	for _, v := range file.Vectors {
		if names[v.Name] {
			t.Fatalf("two vectors are named %q", v.Name)
		}
		names[v.Name] = true
		t.Run(v.Name, func(t *testing.T) {
			lookup := func(_ context.Context, kid string) (*serviceauth.JWK, error) {
				if v.LookupFails {
					return nil, errors.New("the key endpoint is down")
				}
				if !slices.Contains(v.Keys, kid) {
					return nil, nil
				}
				j := trusted.jwk(kid)
				return &j, nil
			}
			verify, err := webhook.JWTBodyHashVerifier(webhook.JWTBodyHashOptions{
				Header:        cfg.Header,
				Keys:          lookup,
				Alg:           cfg.Alg,
				MaxAge:        time.Duration(cfg.MaxAgeSeconds) * time.Second,
				ClockSkew:     time.Duration(cfg.ClockSkewSeconds) * time.Second,
				BodyHashClaim: cfg.BodyHashClaim,
				MaxBodyBytes:  cfg.MaxBodyBytes,
				Now:           func() time.Time { return time.Unix(v.Now, 0) },
			})
			if err != nil {
				t.Fatal(err)
			}
			req := httptest.NewRequest(http.MethodPost, "/webhook", strings.NewReader(v.Body))
			req.Header.Set("Content-Type", "application/json")
			if v.Token != nil {
				req.Header.Set(cfg.Header, token(t, v.Token, trusted, stranger))
			}
			rec := httptest.NewRecorder()
			verify(echo(t)).ServeHTTP(rec, req)
			if rec.Code != v.Want.Status {
				t.Fatalf("status = %d, want %d (%s)", rec.Code, v.Want.Status, rec.Body.String())
			}
			if v.Want.Code == nil {
				if rec.Body.String() != v.Body {
					t.Fatalf("the route read %q, want %q", rec.Body.String(), v.Body)
				}
				return
			}
			var problem struct {
				Code string `json:"code"`
			}
			if err := json.Unmarshal(rec.Body.Bytes(), &problem); err != nil {
				t.Fatalf("problem body %q: %v", rec.Body.String(), err)
			}
			if problem.Code != *v.Want.Code {
				t.Fatalf("code = %q, want %q", problem.Code, *v.Want.Code)
			}
		})
	}
}
