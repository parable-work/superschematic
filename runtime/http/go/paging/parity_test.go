var update = flag.Bool("update", false, "rewrite runtime/http/testdata/page_parity.json")

// parityPath is the vector file the Go, TypeScript and Rust HTTP runtimes
// read, relative to this package.
const parityPath = "../../testdata/page_parity.json"

const parityComment = "Generated by runtime/http/go/paging (cd runtime/http/go && go test ./paging -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each run every vector through their page reader and builder (D60): paging.Parse, paging.EncodeCursor, paging.DecodeCursor and paging.FromRows in Go; readPage, encodeCursor, decodeCursor and pageFromRows in TypeScript; PageSpec::query, Cursor::encode, Cursor::decode and Page::from_rows in Rust. " +
	"reads: spec is an operation's @paginated limits and query a raw query string, which the runtime parses as its router does, percent-decoding and taking + for a space; " +
	"the reader answers request, the cursor (null for none) and the limit, or refuses it with problem, the 400's status, code, detail and details, compared as JSON values. " +
	"cursors: keyJSON is a key as compact JSON, its objects' members in sorted order and its numbers small integers or short decimals, so every runtime writes it back the same; " +
	"cursor is what encoding it gives, and decoding cursor into a JSON value gives keyJSON's value. " +
	"refused: decoding cursor into a JSON value is refused with problem. " +
	"fromRows: rows are JSON values, each its own key; building a page of them for limit gives page, items and next (null for none), as the page's JSON."

type paritySpec struct {
	DefaultLimit int `json:"defaultLimit"`
	MaxLimit     int `json:"maxLimit"`
}

type parityRequest struct {
	Cursor *string `json:"cursor"`
	Limit  int     `json:"limit"`
}

type parityProblem struct {
	Status  int     `json:"status"`
	Code    string  `json:"code"`
	Detail  string  `json:"detail"`
	Details Details `json:"details"`
}

type parityRead struct {
	Name    string         `json:"name"`
	Spec    paritySpec     `json:"spec"`
	Query   string         `json:"query"`
	Request *parityRequest `json:"request,omitempty"`
	Problem *parityProblem `json:"problem,omitempty"`
}

type parityCursor struct {
	Name    string `json:"name"`
	KeyJSON string `json:"keyJSON"`
	Cursor  string `json:"cursor"`
}

type parityRefused struct {
	Name    string        `json:"name"`
	Cursor  string        `json:"cursor"`
	Problem parityProblem `json:"problem"`
}

type parityFromRows struct {
	Name  string                `json:"name"`
	Rows  []json.RawMessage     `json:"rows"`
	Limit int                   `json:"limit"`
	Page  Page[json.RawMessage] `json:"page"`
}

type parityFile struct {
	Comment  string           `json:"comment"`
	Reads    []parityRead     `json:"reads"`
	Cursors  []parityCursor   `json:"cursors"`
	Refused  []parityRefused  `json:"refused"`
	FromRows []parityFromRows `json:"fromRows"`
}

// problemFromAppError is the vector's view of a refusal: the problem
// the router writes for it.
func problemFromAppError(t *testing.T, err error) parityProblem {
	t.Helper()
	var appErr *apperror.AppError
	if !errors.As(err, &appErr) {
		t.Fatalf("not an app error: %v", err)
	}
	details, ok := appErr.Details.(Details)
	if !ok {
		t.Fatalf("details %T, want paging.Details", appErr.Details)
	}
	return parityProblem{Status: appErr.HTTPStatus(), Code: appErr.ErrorCode, Detail: appErr.Message, Details: details}
}

// parseQuery reads a raw query string as a router does.
func parseQuery(raw string) (url.Values, error) {
	return url.ParseQuery(raw)
}

// parityCorpus builds the vectors, each with the answer the Go runtime
// gives.
func parityCorpus(t *testing.T) parityFile {
	t.Helper()
	shop := paritySpec{DefaultLimit: 20, MaxLimit: 100}
	small := paritySpec{DefaultLimit: 2, MaxLimit: 5}
	long := strings.Repeat("A", CursorMaxLength)
	reads := []parityRead{
		{Name: "nothing sent", Spec: shop, Query: ""},
		{Name: "the default of a small page", Spec: small, Query: ""},
		{Name: "a limit of 1", Spec: shop, Query: "limit=1"},
		{Name: "the max limit", Spec: shop, Query: "limit=100"},
		{Name: "a limit of 0", Spec: shop, Query: "limit=0"},
		{Name: "a limit past the max", Spec: shop, Query: "limit=101"},
		{Name: "a limit past a small max", Spec: small, Query: "limit=6"},
		{Name: "a negative limit", Spec: shop, Query: "limit=-1"},
		{Name: "a fraction", Spec: shop, Query: "limit=2.5"},
		{Name: "an exponent", Spec: shop, Query: "limit=1e1"},
		{Name: "a word", Spec: shop, Query: "limit=abc"},
		{Name: "an empty limit", Spec: shop, Query: "limit="},
		{Name: "a plus sign", Spec: shop, Query: "limit=%2B7"},
		{Name: "a space before the limit", Spec: shop, Query: "limit=%2010"},
		{Name: "a limit past 2^53 - 1", Spec: shop, Query: "limit=9007199254740992"},
		{Name: "a limit past int64", Spec: shop, Query: "limit=99999999999999999999"},
		{Name: "a limit sent twice", Spec: shop, Query: "limit=5&limit=500"},
		{Name: "an empty limit before another", Spec: shop, Query: "limit=&limit=5"},
		{Name: "a cursor of one character", Spec: shop, Query: "cursor=A"},
		{Name: "a cursor of 1024 characters", Spec: shop, Query: "cursor=" + long},
		{Name: "a cursor of 1025 characters", Spec: shop, Query: "cursor=" + long + "A"},
		{Name: "a cursor of 1025 characters with padding", Spec: shop, Query: "cursor=" + long + "%3D"},
		{Name: "an empty cursor", Spec: shop, Query: "cursor="},
		{Name: "a cursor with padding", Spec: shop, Query: "cursor=e30%3D"},
		{Name: "a cursor with a plus", Spec: shop, Query: "cursor=e3%2B0"},
		{Name: "a cursor with a slash", Spec: shop, Query: "cursor=e3%2F0"},
		{Name: "a cursor with a space", Spec: shop, Query: "cursor=e3%200"},
		{Name: "a cursor with a plus the query reads as a space", Spec: shop, Query: "cursor=e3+0"},
		{Name: "a cursor outside ASCII", Spec: shop, Query: "cursor=%C3%A930"},
		{Name: "a cursor sent twice with two values", Spec: shop, Query: "cursor=e30&cursor=MQ"},
		{Name: "a cursor and a limit", Spec: small, Query: "cursor=e30&limit=3"},
		{Name: "a refused cursor before a refused limit", Spec: shop, Query: "limit=0&cursor=e30%3D"},
		{Name: "other parameters beside the page", Spec: shop, Query: "statuses=placed&cursor=MQ&limit=10&q=anvil"},
	}
	for i := range reads {
		query, err := parseQuery(reads[i].Query)
		if err != nil {
			t.Fatalf("%s: %v", reads[i].Name, err)
		}
		request, refusal := Parse(query, Spec(reads[i].Spec))
		if refusal != nil {
			problem := problemFromAppError(t, refusal)
			reads[i].Problem = &problem
			continue
		}
		vector := parityRequest{Limit: request.Limit}
		if request.Cursor != "" {
			vector.Cursor = &request.Cursor
		}
		reads[i].Request = &vector
	}

	cursors := []parityCursor{
		{Name: "an order's position", KeyJSON: `{"id":"5b4a1c2e-0f3d-4b6a-9e8f-1a2b3c4d5e6f","placedAt":"2026-10-09T14:30:00Z"}`},
		{Name: "a number", KeyJSON: `2`},
		{Name: "a decimal", KeyJSON: `1.5`},
		{Name: "a string", KeyJSON: `"after"`},
		{Name: "a list", KeyJSON: `[1,"a",true,null]`},
		{Name: "an empty object", KeyJSON: `{}`},
		{Name: "text JSON escapes and text it does not", KeyJSON: `{"name":"Anvil <red> & co \"big\"","sku":"é-☃-😀","tab":"a\tb"}`},
		{Name: "a key two bytes past a multiple of three", KeyJSON: `"ab"`},
	}
	for i := range cursors {
		cursor, err := EncodeCursor(json.RawMessage(cursors[i].KeyJSON))
		if err != nil {
			t.Fatalf("%s: %v", cursors[i].Name, err)
		}
		cursors[i].Cursor = cursor
	}

	refused := []parityRefused{
		{Name: "an empty cursor", Cursor: ""},
		{Name: "padding", Cursor: "e30="},
		{Name: "a plus", Cursor: "e3+0"},
		{Name: "a slash", Cursor: "e3/0"},
		{Name: "a space", Cursor: "e3 0"},
		{Name: "one character, no byte", Cursor: "A"},
		{Name: "bits past the last byte", Cursor: "e31"},
		{Name: "base64url of text that is not JSON", Cursor: "bm90IGpzb24"},
		{Name: "base64url of two JSON values", Cursor: "MSAy"},
		{Name: "base64url of bytes that are not UTF-8", Cursor: "_w"},
		{Name: "base64url of JSON after a byte-order mark", Cursor: "77u_e30"},
		{Name: "1025 characters", Cursor: strings.Repeat("A", CursorMaxLength+1)},
	}
	for i := range refused {
		var key any
		err := DecodeCursor(refused[i].Cursor, &key)
		if err == nil {
			t.Fatalf("%s: DecodeCursor accepted %q as %v", refused[i].Name, refused[i].Cursor, key)
		}
		refused[i].Problem = problemFromAppError(t, err)
	}

	raw := func(values ...string) []json.RawMessage {
		rows := make([]json.RawMessage, len(values))
		for i, value := range values {
			rows[i] = json.RawMessage(value)
		}
		return rows
	}
	first := `{"id":"a","placedAt":"2026-10-09T14:30:00Z"}`
	second := `{"id":"b","placedAt":"2026-10-09T14:31:00Z"}`
	fromRows := []parityFromRows{
		{Name: "fewer rows than the limit", Rows: raw("1", "2"), Limit: 3},
		{Name: "as many rows as the limit", Rows: raw("1", "2", "3"), Limit: 3},
		{Name: "one row past the limit", Rows: raw("1", "2", "3", "4"), Limit: 3},
		{Name: "several rows past the limit", Rows: raw("1", "2", "3", "4", "5"), Limit: 2},
		{Name: "no rows", Rows: raw(), Limit: 2},
		{Name: "a limit of 1 over objects", Rows: raw(first, second), Limit: 1},
	}
	for i := range fromRows {
		page, err := FromRows(fromRows[i].Rows, fromRows[i].Limit, func(row json.RawMessage) any { return row })
		if err != nil {
			t.Fatalf("%s: %v", fromRows[i].Name, err)
		}
		if page.Items == nil {
			page.Items = []json.RawMessage{}
		}
		fromRows[i].Page = page
	}
	return parityFile{Comment: parityComment, Reads: reads, Cursors: cursors, Refused: refused, FromRows: fromRows}
}

// TestWriteParityVectors writes the corpus with -update, and otherwise
// fails when the committed file is not what the corpus gives.
func TestWriteParityVectors(t *testing.T) {
	data, err := json.MarshalIndent(parityCorpus(t), "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	data = append(data, '\n')
	if *update {
		if err := os.WriteFile(parityPath, data, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(parityPath)
	if err != nil {
		t.Fatalf("read %s (write it with -update): %v", parityPath, err)
	}
	if !bytes.Equal(committed, data) {
		t.Fatalf("%s is stale: run go test ./paging -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors runs the committed file through the Go reader and
// builder, as the TypeScript and Rust runtimes run it: through Read, the
// router's entry, so the problem a route writes is the vector's.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(parityPath)
	if err != nil {
		t.Fatal(err)
	}
	var file parityFile
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&file); err != nil {
		t.Fatal(err)
	}
	if len(file.Reads) == 0 || len(file.Cursors) == 0 || len(file.Refused) == 0 || len(file.FromRows) == 0 {
		t.Fatal("a section of the vectors is empty")
	}
	for _, vector := range file.Reads {
		recorder := httptest.NewRecorder()
		request := httptest.NewRequest(http.MethodGet, "/items?"+vector.Query, nil)
		got, ok := Read(recorder, request, Spec(vector.Spec))
		switch {
		case vector.Problem != nil:
			if ok {
				t.Errorf("%s: Read accepted %+v", vector.Name, got)
				continue
			}
			var problem parityProblem
			if err := json.Unmarshal(recorder.Body.Bytes(), &problem); err != nil {
				t.Fatalf("%s: %v", vector.Name, err)
			}
			if recorder.Code != vector.Problem.Status || !reflect.DeepEqual(problem, *vector.Problem) {
				t.Errorf("%s: problem %d %+v, want %+v", vector.Name, recorder.Code, problem, *vector.Problem)
			}
		case !ok:
			t.Errorf("%s: Read refused it: %s", vector.Name, recorder.Body.String())
		default:
			want := Request{Limit: vector.Request.Limit}
			if vector.Request.Cursor != nil {
				want.Cursor = *vector.Request.Cursor
			}
			if got != want {
				t.Errorf("%s: request %+v, want %+v", vector.Name, got, want)
			}
		}
	}
	for _, vector := range file.Cursors {
		var want any
		if err := json.Unmarshal([]byte(vector.KeyJSON), &want); err != nil {
			t.Fatal(err)
		}
		cursor, err := EncodeCursor(want)
		if err != nil || cursor != vector.Cursor {
			t.Errorf("%s: EncodeCursor of the decoded key = %q, %v, want %q", vector.Name, cursor, err, vector.Cursor)
		}
		var got any
		if err := DecodeCursor(vector.Cursor, &got); err != nil || !reflect.DeepEqual(got, want) {
			t.Errorf("%s: DecodeCursor = %v, %v, want %v", vector.Name, got, err, want)
		}
	}
	for _, vector := range file.Refused {
		var key any
		err := DecodeCursor(vector.Cursor, &key)
		if err == nil {
			t.Errorf("%s: DecodeCursor accepted it as %v", vector.Name, key)
			continue
		}
		if got := problemFromAppError(t, err); !reflect.DeepEqual(got, vector.Problem) {
			t.Errorf("%s: problem %+v, want %+v", vector.Name, got, vector.Problem)
		}
	}
	for _, vector := range file.FromRows {
		page, err := FromRows(vector.Rows, vector.Limit, func(row json.RawMessage) any { return row })
		if err != nil {
			t.Fatal(err)
		}
		got, err := json.Marshal(page)
		if err != nil {
			t.Fatal(err)
		}
		want, err := json.Marshal(vector.Page)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(compactJSON(t, got), compactJSON(t, want)) {
			t.Errorf("%s: page %s, want %s", vector.Name, got, want)
		}
	}
}

func compactJSON(t *testing.T, data []byte) []byte {
	t.Helper()
	var out bytes.Buffer
	if err := json.Compact(&out, data); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}
