type paritySpec struct {
	DefaultLimit int             `json:"defaultLimit"`
	MaxLimit     int             `json:"maxLimit"`
	Sort         *paritySortSpec `json:"sort,omitempty"`
}

type paritySortSpec struct {
	Param   string   `json:"param"`
	Fields  []string `json:"fields"`
	Default string   `json:"default"`
}

// spec is the vector's spec as the router carries it.
func (s paritySpec) spec(t *testing.T) Spec {
	t.Helper()
	spec := Spec{DefaultLimit: s.DefaultLimit, MaxLimit: s.MaxLimit}
	if s.Sort != nil {
		sort, ok := ParseSort(s.Sort.Default)
		if !ok {
			t.Fatalf("the default sort %q is no sort", s.Sort.Default)
		}
		spec.Sort = &SortSpec{Param: s.Sort.Param, Fields: s.Sort.Fields, Default: sort}
	}
	return spec
}

type parityRequest struct {
	Cursor *string `json:"cursor"`
	Limit  int     `json:"limit"`
	Sort   string  `json:"sort,omitempty"`
}

// request is the vector's view of a request the reader took.
func requestVector(request Request) parityRequest {
	vector := parityRequest{Limit: request.Limit, Sort: request.Sort.String()}
	if request.Cursor != "" {
		vector.Cursor = &request.Cursor
	}
	return vector
}

