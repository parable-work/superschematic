var update = flag.Bool("update", false, "rewrite runtime/http/testdata/page_parity.json")

// parityPath is the vector file the Go, TypeScript and Rust HTTP runtimes
// read, relative to this package.
const parityPath = "../../testdata/page_parity.json"

const parityComment = "Generated by runtime/http/go/paging (cd runtime/http/go && go test ./paging -run TestWriteParityVectors -update); do not edit. " +
	"The Go, TypeScript and Rust HTTP runtimes each run every vector through their page reader and builder (D60): paging.Parse, paging.EncodeCursor, paging.DecodeCursor and paging.FromRows in Go; readPage, encodeCursor, decodeCursor and pageFromRows in TypeScript; PageSpec::query, Cursor::encode, Cursor::decode and Page::from_rows in Rust. " +
	"reads: spec is an operation's @paginated limits and query a raw query string, which the runtime parses as its router does, WHATWG's form-urlencoded parser: pairs split at & alone, + a space, a % that starts no escape kept as it is; " +
	"the reader answers request, the cursor (null for none) and the limit, or refuses it with problem, the 400's status, code, detail and details, compared as JSON values. " +
	"cursors: keyJSON is a key as compact JSON, its objects' members in sorted order and its numbers small integers or short decimals, so every runtime writes it back the same; " +
	"cursor is what encoding it gives, and decoding cursor into a JSON value gives keyJSON's value. " +
	"refused: decoding cursor into a JSON value is refused with problem. " +
	"unencodable: encoding the key keyJSON fails, the implementation's error, since every router would refuse its cursor. " +
	"fromRows: rows are JSON values, each its own key; building a page of them for limit gives page, items and next (null for none), as the page's JSON."

type paritySpec struct {
	DefaultLimit int `json:"defaultLimit"`
	MaxLimit     int `json:"maxLimit"`
}

type parityRequest struct {
	Cursor *string `json:"cursor"`
	Limit  int     `json:"limit"`
}

type parityProblem struct {
	Status  int     `json:"status"`
	Code    string  `json:"code"`
	Detail  string  `json:"detail"`
	Details Details `json:"details"`
}

type parityRead struct {
	Name    string         `json:"name"`
	Spec    paritySpec     `json:"spec"`
	Query   string         `json:"query"`
	Request *parityRequest `json:"request,omitempty"`
	Problem *parityProblem `json:"problem,omitempty"`
}

type parityCursor struct {
	Name    string `json:"name"`
	KeyJSON string `json:"keyJSON"`
	Cursor  string `json:"cursor"`
}

type parityRefused struct {
	Name    string        `json:"name"`
	Cursor  string        `json:"cursor"`
	Problem parityProblem `json:"problem"`
}

type parityUnencodable struct {
	Name    string `json:"name"`
	KeyJSON string `json:"keyJSON"`
}

type parityFromRows struct {
	Name  string                `json:"name"`
	Rows  []json.RawMessage     `json:"rows"`
	Limit int                   `json:"limit"`
	Page  Page[json.RawMessage] `json:"page"`
}

type parityFile struct {
	Comment     string              `json:"comment"`
	Reads       []parityRead        `json:"reads"`
	Cursors     []parityCursor      `json:"cursors"`
	Refused     []parityRefused     `json:"refused"`
	Unencodable []parityUnencodable `json:"unencodable"`
	FromRows    []parityFromRows    `json:"fromRows"`
}

// problemFromAppError is the vector's view of a refusal: the problem
// the router writes for it.
func problemFromAppError(t *testing.T, err error) parityProblem {
	t.Helper()
	var appErr *apperror.AppError
	if !errors.As(err, &appErr) {
		t.Fatalf("not an app error: %v", err)
	}
	details, ok := appErr.Details.(Details)
	if !ok {
		t.Fatalf("details %T, want paging.Details", appErr.Details)
	}
	return parityProblem{Status: appErr.HTTPStatus(), Code: appErr.ErrorCode, Detail: appErr.Message, Details: details}
}

