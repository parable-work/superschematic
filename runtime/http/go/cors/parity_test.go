var update = flag.Bool("update", false, "rewrite runtime/http/testdata/cors_parity.json")

// parityPath is the vector file the Go and TypeScript HTTP runtimes read,
// relative to this package.
const parityPath = "../../testdata/cors_parity.json"

const parityComment = "Generated by runtime/http/go/cors (cd runtime/http/go && go test ./cors -run TestWriteParityVectors -update); do not edit. " +
	"The Go and TypeScript HTTP runtimes each decide every vector with their CORS check (D55, docs/stack-model.md section 8.10): Policy.Decide in Go, corsDecision in TypeScript. " +
	"Per vector: policy is an API's, the origins its CORS field lists and the methods of its operations; request is the method and the headers the browser sends, by canonical name. " +
	"want is the decision: preflight, true when the server answers the request itself with 204 and the headers alone, and headers, every header the answer carries by canonical name, none for a request without an Origin."

type parityFile struct {
	Comment string         `json:"comment"`
	Vectors []parityVector `json:"vectors"`
}

type parityPolicy struct {
	Origins []string `json:"origins"`
	Methods []string `json:"methods"`
}

type parityRequest struct {
	Method  string            `json:"method"`
	Headers map[string]string `json:"headers"`
}

type parityWant struct {
	Preflight bool              `json:"preflight"`
	Headers   map[string]string `json:"headers"`
}

type parityVector struct {
	Name    string        `json:"name"`
	Policy  parityPolicy  `json:"policy"`
	Request parityRequest `json:"request"`
	Want    parityWant    `json:"want"`
}

// parityCorpus builds the vectors, each with the decision Decide makes.
func parityCorpus() parityFile {
	const site = "https://shop-web.acme.dev"
	shop := parityPolicy{Origins: []string{"http://127.0.0.1:20441", site}, Methods: []string{"GET", "POST"}}
	none := parityPolicy{Origins: []string{}, Methods: []string{"GET"}}
	vectors := []parityVector{
		{Name: "a preflight from a listed origin", Policy: shop, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": site, "Access-Control-Request-Method": "POST", "Access-Control-Request-Headers": "authorization, content-type",
		}}},
		{Name: "a preflight from loopback", Policy: shop, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": "http://127.0.0.1:20441", "Access-Control-Request-Method": "GET",
		}}},
		{Name: "a preflight from an origin not listed", Policy: shop, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": "https://evil.example", "Access-Control-Request-Method": "GET",
		}}},
		{Name: "a preflight from a listed origin's other port", Policy: shop, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": "http://127.0.0.1:20442", "Access-Control-Request-Method": "GET",
		}}},
		{Name: "a preflight to an API no site calls", Policy: none, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": site, "Access-Control-Request-Method": "GET",
		}}},
		{Name: "a request from a listed origin", Policy: shop, Request: parityRequest{Method: "GET", Headers: map[string]string{
			"Origin": site, "Authorization": "Bearer t",
		}}},
		{Name: "a request from an origin not listed", Policy: shop, Request: parityRequest{Method: "POST", Headers: map[string]string{
			"Origin": "https://evil.example",
		}}},
		{Name: "a request with no origin", Policy: shop, Request: parityRequest{Method: "GET", Headers: map[string]string{
			"Authorization": "Bearer t",
		}}},
		{Name: "an OPTIONS request that asks for no method", Policy: shop, Request: parityRequest{Method: "OPTIONS", Headers: map[string]string{
			"Origin": site,
		}}},
	}
	for i := range vectors {
		v := &vectors[i]
		d := Policy{Origins: v.Policy.Origins, Methods: v.Policy.Methods}.Decide(v.Request.Method, header(v.Request.Headers))
		v.Want = parityWant{Preflight: d.Preflight, Headers: d.Headers}
	}
	return parityFile{Comment: parityComment, Vectors: vectors}
}

func header(headers map[string]string) http.Header {
	h := http.Header{}
	for name, value := range headers {
		h.Set(name, value)
	}
	return h
}

// TestWriteParityVectors keeps runtime/http/testdata/cors_parity.json equal
// to the vectors parityCorpus builds. It fails when the committed file is
// stale; -update rewrites it.
func TestWriteParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(parityCorpus()); err != nil {
		t.Fatal(err)
	}
	path := filepath.FromSlash(parityPath)
	if *update {
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run go test ./cors -run TestWriteParityVectors -update)", parityPath, err)
	}
	if !bytes.Equal(committed, buf.Bytes()) {
		t.Fatalf("%s is stale; run go test ./cors -run TestWriteParityVectors -update", parityPath)
	}
}

// TestParityVectors decides every committed vector, and runs each through
// Handler around a handler that answers 200, which a preflight never
// reaches.
func TestParityVectors(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(parityPath))
	if err != nil {
		t.Fatal(err)
	}
	var file parityFile
	if err := json.Unmarshal(data, &file); err != nil {
		t.Fatal(err)
	}
	if len(file.Vectors) == 0 {
		t.Fatal("no vectors")
	}
	for _, v := range file.Vectors {
		t.Run(v.Name, func(t *testing.T) {
			policy := Policy{Origins: v.Policy.Origins, Methods: v.Policy.Methods}
			d := policy.Decide(v.Request.Method, header(v.Request.Headers))
			if d.Preflight != v.Want.Preflight || !reflect.DeepEqual(d.Headers, v.Want.Headers) {
				t.Fatalf("Decide = %+v, want %+v", d, v.Want)
			}
			reached := false
			h := Handler(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
				reached = true
				w.WriteHeader(http.StatusOK)
			}), []API{{Policy: policy}})
			r, err := http.NewRequest(v.Request.Method, "http://shop-api.acme.dev/api/products", nil)
			if err != nil {
				t.Fatal(err)
			}
			r.Header = header(v.Request.Headers)
			w := &recorder{header: http.Header{}}
			h.ServeHTTP(w, r)
			wantStatus := http.StatusOK
			if v.Want.Preflight {
				wantStatus = http.StatusNoContent
			}
			if w.status != wantStatus || reached == v.Want.Preflight {
				t.Fatalf("Handler answered %d, reaching the handler %v; want %d", w.status, reached, wantStatus)
			}
			for name, value := range v.Want.Headers {
				if got := w.header.Get(name); got != value {
					t.Errorf("Handler's %s = %q, want %q", name, got, value)
				}
			}
			if len(w.header) != len(v.Want.Headers) {
				t.Errorf("Handler's headers = %v, want %v", w.header, v.Want.Headers)
			}
		})
	}
}

// TestHandlerPicksTheAPIThatTakesTheRequest: a server that serves two
// APIs answers a request with the policy of the API whose routes take it,
// a preflight by the method it asks for, and passes on one neither takes
// with no CORS header.
func TestHandlerPicksTheAPIThatTakesTheRequest(t *testing.T) {
	route := func(method, path string) func(string, string) bool {
		return func(m, p string) bool { return m == method && p == path }
	}
	h := Handler(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) { w.WriteHeader(http.StatusOK) }), []API{
		{Policy: Policy{Origins: []string{"https://a.dev"}, Methods: []string{"GET"}}, Match: route("GET", "/api/a")},
		{Policy: Policy{Origins: []string{"https://b.dev"}, Methods: []string{"POST"}}, Match: route("POST", "/api/b")},
	})
	for _, tc := range []struct {
		name, method, path, origin, ask, wantOrigin string
		wantStatus                                  int
	}{
		{"a's preflight from a", "OPTIONS", "/api/a", "https://a.dev", "GET", "https://a.dev", http.StatusNoContent},
		{"b's preflight from a", "OPTIONS", "/api/b", "https://a.dev", "POST", "", http.StatusNoContent},
		{"b's preflight from b", "OPTIONS", "/api/b", "https://b.dev", "POST", "https://b.dev", http.StatusNoContent},
		{"b's request from b", "POST", "/api/b", "https://b.dev", "", "https://b.dev", http.StatusOK},
		{"a preflight neither takes", "OPTIONS", "/api/c", "https://a.dev", "GET", "", http.StatusOK},
	} {
		t.Run(tc.name, func(t *testing.T) {
			r, _ := http.NewRequest(tc.method, "http://server"+tc.path, nil)
			r.Header.Set("Origin", tc.origin)
			if tc.ask != "" {
				r.Header.Set("Access-Control-Request-Method", tc.ask)
			}
			w := &recorder{header: http.Header{}}
			h.ServeHTTP(w, r)
			if w.status != tc.wantStatus || w.header.Get("Access-Control-Allow-Origin") != tc.wantOrigin {
				t.Fatalf("answered %d with origin %q; want %d with %q", w.status, w.header.Get("Access-Control-Allow-Origin"), tc.wantStatus, tc.wantOrigin)
			}
		})
	}
}

// recorder records an answer's status and headers.
type recorder struct {
	header http.Header
	status int
}

func (r *recorder) Header() http.Header { return r.header }

func (r *recorder) Write(p []byte) (int, error) {
	if r.status == 0 {
		r.status = http.StatusOK
	}
	return len(p), nil
}

func (r *recorder) WriteHeader(status int) {
	if r.status == 0 {
		r.status = status
	}
}
