func TestWithRegistry(t *testing.T) {
	schema := testSchema()

	reg := NewRegistry()
	var calledWith string
	reg.Register("Email", func(value string) []ValidationError {
		calledWith = value
		return []ValidationError{{Validator: "custom", Message: "custom error"}}
	})

	v := New(schema, WithRegistry(reg))
	errs := v.ValidateType("User", map[string]any{
		"name":   "Alice",
		"email":  "alice@example.com",
		"status": "active",
	})

	assert.True(t, errs.HasErrors())
	assert.Equal(t, "alice@example.com", calledWith)
	emailErrs := errs.GetFieldErrors("email")
	require.NotNil(t, emailErrs)
	assert.Equal(t, "custom", emailErrs[0].Validator)
}

