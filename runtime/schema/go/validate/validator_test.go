func TestValidateType_MillisecondsBoundaries(t *testing.T) {
	s := ir.NewSchema("test", ir.SchemaKindGeneral)
	s.Scalars["Milliseconds"] = &ir.ScalarDef{
		Name:      "Milliseconds",
		Primitive: "Int",
		Minimum:   ptr.To(int64(-9007199254740991)),
		Maximum:   ptr.To(int64(9007199254740991)),
	}
	s.Types["Timer"] = &ir.TypeDef{
		Name: "Timer",
		Kind: ir.TypeKindObject,
		Fields: []*ir.FieldDef{
			{Name: "elapsedMs", TypeRef: ir.TypeRef{Name: "Milliseconds"}, Required: true},
			{
				Name:        "nonNegativeElapsedMs",
				TypeRef:     ir.TypeRef{Name: "Milliseconds"},
				ValidateMin: ptr.To(float64(0)),
			},
		},
	}

	v := New(s)

	t.Run("accepts zero", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs": float64(0),
		})
		assert.False(t, errs.HasErrors())
	})

	t.Run("accepts negative values within the scalar range", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs": float64(-1),
		})
		assert.False(t, errs.HasErrors())
	})

	t.Run("rejects fractional values", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs": float64(1.5),
		})
		assert.True(t, errs.HasErrors())
		fieldErrs := errs.GetFieldErrors("elapsedMs")
		require.Len(t, fieldErrs, 1)
		assert.Equal(t, "type", fieldErrs[0].Validator)
		assert.Equal(t, "expected integer value", fieldErrs[0].Message)
	})

	t.Run("field minimum rejects a scalar-valid negative value", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs":            float64(-1),
			"nonNegativeElapsedMs": float64(-1),
		})
		assert.True(t, errs.HasErrors())
		fieldErrs := errs.GetFieldErrors("nonNegativeElapsedMs")
		require.Len(t, fieldErrs, 1)
		assert.Equal(t, "min", fieldErrs[0].Validator)
		assert.Equal(t, "must be at least 0", fieldErrs[0].Message)
	})

	t.Run("rejects values below min", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs": float64(-9007199254740992),
		})
		assert.True(t, errs.HasErrors())
		msErrs := errs.GetFieldErrors("elapsedMs")
		require.Len(t, msErrs, 1)
		assert.Equal(t, "min", msErrs[0].Validator)
		assert.Equal(t, "must be at least -9007199254740991", msErrs[0].Message)
	})

	t.Run("rejects values above max", func(t *testing.T) {
		errs := v.ValidateType("Timer", map[string]any{
			"elapsedMs": float64(9007199254740992),
		})
		assert.True(t, errs.HasErrors())
		msErrs := errs.GetFieldErrors("elapsedMs")
		require.Len(t, msErrs, 1)
		assert.Equal(t, "max", msErrs[0].Validator)
		assert.Equal(t, "must be at most 9007199254740991", msErrs[0].Message)
	})
}

