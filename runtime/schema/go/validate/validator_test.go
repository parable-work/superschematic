// Field-level string constraints (@validatePattern,
// @validateMinLength, @validateMaxLength) enforced by the Go validator,
// matching the TS and Python field-level constraint semantics.
func fieldConstraintSchema() *ir.Schema {
	s := ir.NewSchema("test", ir.SchemaKindGeneral)
	s.Scalars["Name"] = &ir.ScalarDef{
		Name:      "Name",
		Primitive: "String",
		MinLength: 2,
		MaxLength: 80,
	}
	s.Inputs["ConnectorAuthInput"] = &ir.TypeDef{
		Name: "ConnectorAuthInput",
		Kind: ir.TypeKindInput,
		Fields: []*ir.FieldDef{
			{Name: "domain", TypeRef: ir.TypeRef{Name: "String"}, ValidatePattern: `^[A-Za-z0-9][A-Za-z0-9-]*$`},
			{Name: "site", TypeRef: ir.TypeRef{Name: "Name"}, ValidatePattern: `^[a-z]+$`},
			{Name: "code", TypeRef: ir.TypeRef{Name: "String"}, ValidateMinLength: ptr.To(3), ValidateMaxLength: ptr.To(10)},
			{Name: "tags", TypeRef: ir.TypeRef{Name: "String", IsArray: true}, ValidatePattern: `^[a-z]+$`},
			{Name: "broken", TypeRef: ir.TypeRef{Name: "String"}, ValidatePattern: `[`},
			{Name: "count", TypeRef: ir.TypeRef{Name: "Int"}, ValidateMin: ptr.To(1.0), ValidateMax: ptr.To(99.0)},
		},
	}
	return s
}

func TestValidateInput_FieldPattern(t *testing.T) {
	v := New(fieldConstraintSchema())

	errs := v.ValidateInput("ConnectorAuthInput", map[string]any{
		"domain": "https://sunrun.my.salesforce.com",
	})
	domainErrs := errs.GetFieldErrors("domain")
	require.Len(t, domainErrs, 1)
	assert.Equal(t, "pattern", domainErrs[0].Validator)
	assert.Equal(t, "invalid format", domainErrs[0].Message)

	errs = v.ValidateInput("ConnectorAuthInput", map[string]any{"domain": "sunrun"})
	assert.False(t, errs.HasErrors())

	// Skip condition is absent-or-nil ONLY (parity with TS validate.ts:517).
	errs = v.ValidateInput("ConnectorAuthInput", map[string]any{})
	assert.False(t, errs.HasErrors())
	errs = v.ValidateInput("ConnectorAuthInput", map[string]any{"domain": nil})
	assert.False(t, errs.HasErrors())

	// A PRESENT empty string on an optional field runs the pattern.
	errs = v.ValidateInput("ConnectorAuthInput", map[string]any{"domain": ""})
	domainErrs = errs.GetFieldErrors("domain")
	require.Len(t, domainErrs, 1)
	assert.Equal(t, "pattern", domainErrs[0].Validator)
}

