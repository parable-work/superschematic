import type {
  ArgumentDef,
  EnumDef,
  FieldDef,
  FileUploadConfig,
  ImageConstraints,
  Import,
  IndexDef,
  MiddlewareConfig,
  RelationDef,
  ScalarDef,
  Schema,
  TypeDef,
  TypeRef,
  UnionDef,
} from '../validation/types';
import { BUILTIN_SCALARS } from '../builtin-scalars.generated';

/**
 * Reader for the superschematic Schema IR JSON format (`superschematic build --emit-ir`).
 *
 * The IR is the format-agnostic representation emitted by the Go schema
 * loader (ir/). It retains the legacy runtime
 * the runtime schema payload fields (primitive, jsonTag, restMethod, ...) specifically
 * so runtime consumers can be fed from it. This module maps
 * that JSON into the runtime `Schema` shape used by validation and the
 * schema-renderer.
 */

type JsonObject = Record<string, unknown>;

const builtinScalars = BUILTIN_SCALARS;

function isObject(value: unknown): value is JsonObject {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function asObject(value: unknown, path: string): JsonObject {
  if (!isObject(value)) {
    throw new Error(`runtime schema IR parse error: expected object at ${path}`);
  }
  return value;
}

function asString(value: unknown): string {
  return typeof value === 'string' ? value : '';
}

function asBoolean(value: unknown): boolean {
  return typeof value === 'boolean' ? value : false;
}

function asNumber(value: unknown): number {
  return typeof value === 'number' && Number.isFinite(value) ? value : 0;
}

function asNumberOrNull(value: unknown): number | null {
  return typeof value === 'number' && Number.isFinite(value) ? value : null;
}

function asStringOrNull(value: unknown): string | null {
  return typeof value === 'string' ? value : null;
}

function asStringArray(value: unknown): string[] {
  if (!Array.isArray(value)) {
    return [];
  }
  return value.filter((item): item is string => typeof item === 'string');
}

function docText(definition: JsonObject): string {
  return asString(definition.description) || asString(definition.comment);
}

/**
 * IR names scalars with dot namespaces ("Identity.UserID"); the runtime
 * schema uses the legacy underscore form ("Identity_UserID"). Type and enum
 * names never contain dots, so the replacement is identity for them.
 */
function normalizeTypeName(name: string): string {
  return name.replace(/\./g, '_');
}

function parseIRTypeRef(raw: unknown, path: string): TypeRef {
  const typeRef = asObject(raw, path);
  return {
    name: normalizeTypeName(asString(typeRef.name)),
    isArray: asBoolean(typeRef.isArray),
    elemNonNull: asBoolean(typeRef.elemNonNull),
  };
}

function parseIRRelation(raw: unknown): RelationDef | null {
  if (!isObject(raw)) {
    return null;
  }
  return {
    type: asString(raw.type),
    field: asString(raw.field),
  };
}

function parseIRMiddleware(raw: unknown): MiddlewareConfig | null {
  if (!isObject(raw)) {
    return null;
  }
  return {
    rateLimit: asNumberOrNull(raw.rateLimit),
    bodyLimit: asNumberOrNull(raw.bodyLimit),
    timeout: asNumberOrNull(raw.timeout),
    encrypted: asBoolean(raw.encrypted),
  };
}

function parseIRArgument(raw: unknown, path: string): ArgumentDef {
  const argument = asObject(raw, path);
  return {
    name: asString(argument.name),
    description: docText(argument),
    typeRef: parseIRTypeRef(argument.typeRef, `${path}.typeRef`),
    required: asBoolean(argument.required),
    defaultValue: asStringOrNull(argument.default),
    isQuery: asBoolean(argument.isQuery),
  };
}

function parseIRField(raw: unknown, path: string): FieldDef {
  const field = asObject(raw, path);
  const name = asString(field.name);
  const argumentsRaw = Array.isArray(field.arguments) ? field.arguments : [];
  const title = asString(field.title);
  const purpose = asString(field.purpose);
  const icon = asString(field.icon);
  const placeholder = asString(field.placeholder);

  const fieldDef: FieldDef = {
    name,
    description: docText(field),
    jsonKey: asString(field.jsonTag) || name,
    required: asBoolean(field.required),
    autoGenerated: asBoolean(field.autoGenerated),
    defaultValue: asStringOrNull(field.default),
    validateMin: asNumberOrNull(field.validateMin),
    validateMax: asNumberOrNull(field.validateMax),
    validateMinLength: asNumberOrNull(field.validateMinLength),
    validateMaxLength: asNumberOrNull(field.validateMaxLength),
    validateListMin: asNumberOrNull(field.validateListMin),
    validateListMax: asNumberOrNull(field.validateListMax),
    validatePattern: asString(field.validatePattern),
    arguments: argumentsRaw.map((argument, index) =>
      parseIRArgument(argument, `${path}.arguments[${index}]`)
    ),
    key: asBoolean(field.key),
    unique: asBoolean(field.unique),
    searchField: asBoolean(field.searchField),
    relation: parseIRRelation(field.relation),
    hasMany: asBoolean(field.hasMany),
    manyToMany: asBoolean(field.manyToMany),
    jsonField: asBoolean(field.jsonField),
    secret: asBoolean(field.secret),
    uiHidden: asBoolean(field.uiHidden),
    semanticRole: asString(field.semanticRole),
    temporalFormat: asString(field.temporalFormat),
    transformDedupKey: asBoolean(field.transformDedupKey),
    transformOrdering: asBoolean(field.transformOrdering),
    transformFingerprintInput: asBoolean(field.transformFingerprintInput),
    transformPartitionDate: asBoolean(field.transformPartitionDate),
    transformStructural: asBoolean(field.transformStructural),
    transformPersonEmail: asBoolean(field.transformPersonEmail),
    transformPersonName: asBoolean(field.transformPersonName),
    transformAccountId: asBoolean(field.transformAccountId),
    transformExternalUserId: asBoolean(field.transformExternalUserId),
    exclude: asBoolean(field.exclude),
    internalMetadata: asBoolean(field.internalMetadata),
    auth: asBoolean(field.auth),
    encrypted: asBoolean(field.encrypted),
    requireOwnership: asBoolean(field.requireOwnership),
    permissions: asStringArray(field.permissions),
    restMethod: asString(field.restMethod) || asString(field.httpMethod),
    paramType: asString(field.paramType),
    middleware: parseIRMiddleware(field.middleware),
    typeRef: parseIRTypeRef(field.typeRef, `${path}.typeRef`),
  };
  // Wire form omits empty metadata (Go omitempty); mirror that absence.
  if (title) {
    fieldDef.title = title;
  }
  if (purpose) {
    fieldDef.purpose = purpose;
  }
  if (icon) {
    fieldDef.icon = icon;
  }
  if (placeholder) {
    fieldDef.placeholder = placeholder;
  }
  return fieldDef;
}

function parseIRIndexes(raw: unknown): IndexDef[] {
  if (!Array.isArray(raw)) {
    return [];
  }
  const indexes: IndexDef[] = [];
  for (const indexRaw of raw) {
    if (!isObject(indexRaw)) {
      continue;
    }
    indexes.push({
      keys: asStringArray(indexRaw.keys),
      unique: asBoolean(indexRaw.unique),
    });
  }
  return indexes;
}

function parseIRType(name: string, raw: unknown, path: string): TypeDef {
  const definition = asObject(raw, path);
  const role = asString(definition.role) || asString(definition.kind);
  const fieldsRaw = Array.isArray(definition.fields) ? definition.fields : [];

  return {
    name,
    description: docText(definition),
    kind: role === 'APIInput' ? 'input' : 'object',
    fields: fieldsRaw.map((field, index) => parseIRField(field, `${path}.fields[${index}]`)),
    indexes: parseIRIndexes(definition.indexes),
    envVars: asBoolean(definition.envVars),
  };
}

function parseIREnum(name: string, raw: unknown, path: string): EnumDef {
  const definition = asObject(raw, path);
  const valuesRaw = Array.isArray(definition.values) ? definition.values : [];

  return {
    name,
    owner: asString(definition.owner),
    description: docText(definition),
    values: valuesRaw.map((valueRaw, index) => {
      const value = asObject(valueRaw, `${path}.values[${index}]`);
      return {
        name: asString(value.name),
        description: docText(value),
        serializedAs: asString(value.serializedAs),
      };
    }),
  };
}

function parseIRFileUpload(raw: unknown): FileUploadConfig | null {
  if (!isObject(raw)) {
    return null;
  }
  return {
    maxSize: asNumber(raw.maxSize),
    allowedTypes: asStringArray(raw.allowedTypes),
    category: asString(raw.category),
  };
}

function parseIRImageConstraints(raw: unknown): ImageConstraints | null {
  if (!isObject(raw)) {
    return null;
  }
  return {
    maxWidth: asNumber(raw.maxWidth),
    maxHeight: asNumber(raw.maxHeight),
    minAspectRatio: asNumberOrNull(raw.minAspectRatio),
    maxAspectRatio: asNumberOrNull(raw.maxAspectRatio),
    requireTransparency: asBoolean(raw.requireTransparency),
  };
}

function mapLanguagePrimitive(languagePrimitive: string): string {
  switch (languagePrimitive) {
    case 'number':
      return 'Float';
    case 'boolean':
      return 'Boolean';
    case 'object':
      return 'JSON';
    default:
      return 'String';
  }
}

function parseIRScalar(raw: unknown, path: string): ScalarDef {
  const definition = asObject(raw, path);
  const runtimeName = normalizeTypeName(asString(definition.name));
  const typeMappingsRaw = isObject(definition.typeMappings) ? definition.typeMappings : {};
  const typeMappings: Record<string, string> = {};
  for (const [language, mapped] of Object.entries(typeMappingsRaw)) {
    if (typeof mapped === 'string') {
      typeMappings[language] = mapped;
    }
  }

  return {
    name: runtimeName,
    description: docText(definition),
    primitive:
      asString(definition.primitive) ||
      mapLanguagePrimitive(asString(definition.languagePrimitive)),
    minLength: asNumber(definition.minLength),
    maxLength: asNumber(definition.maxLength),
    pattern: asString(definition.pattern),
    format: asString(definition.format),
    reservedWords: asStringArray(definition.reservedWords),
    caseInsensitive: asBoolean(definition.caseInsensitive),
    reservedWordsCaseInsensitive: asBoolean(definition.reservedWordsCaseInsensitive),
    reservedWordsMatchPartial: asBoolean(definition.reservedWordsMatchPartial),
    minimum: asNumberOrNull(definition.minimum),
    maximum: asNumberOrNull(definition.maximum),
    example: asString(definition.example),
    fileUpload: parseIRFileUpload(definition.fileUpload),
    imageConstraints: parseIRImageConstraints(definition.imageConstraints),
    hasCustomNormalize: asBoolean(definition.hasCustomNormalize),
    hasCustomValidate: asBoolean(definition.hasCustomValidate),
    hasCustomParse: asBoolean(definition.hasCustomParse),
    typeMappings,
  };
}

function parseIRUnion(name: string, raw: unknown, path: string): UnionDef {
  const definition = asObject(raw, path);
  return {
    name,
    description: docText(definition),
    types: asStringArray(definition.types),
  };
}

function parseIRImports(raw: unknown): Import[] {
  if (!Array.isArray(raw)) {
    return [];
  }
  const imports: Import[] = [];
  for (const importRaw of raw) {
    if (!isObject(importRaw)) {
      continue;
    }
    imports.push({
      from: asString(importRaw.from) || asString(importRaw.package),
      types: asStringArray(importRaw.types),
    });
  }
  return imports;
}

/**
 * Parses a superschematic Schema IR JSON document (the `superschematic build --emit-ir`
 * output, or several of them merged map-wise) into the runtime Schema.
 *
 * Types are split into runtime `types` and `inputs` by their IR role:
 * APIInput becomes an input; every other role (APIView, EmbeddedStruct,
 * DBTable, ...) becomes an object type. Namespaced scalar names are
 * normalized to their legacy underscore form so they line up with the
 * builtin scalar registry and scalar view components.
 */
export function parseSchemaIR(schema: unknown): Schema {
  const root = asObject(schema, 'root');

  const scalars: Record<string, ScalarDef> = {};
  const enums: Record<string, EnumDef> = {};
  const types: Record<string, TypeDef> = {};
  const inputs: Record<string, TypeDef> = {};
  const unions: Record<string, UnionDef> = {};

  const scalarsRaw = isObject(root.scalars) ? root.scalars : {};
  for (const [name, definition] of Object.entries(scalarsRaw)) {
    const scalar = parseIRScalar(definition, `scalars.${name}`);
    scalars[scalar.name] = scalar;
  }

  const typesRaw = isObject(root.types) ? root.types : {};
  for (const [name, definition] of Object.entries(typesRaw)) {
    const typeDef = parseIRType(name, definition, `types.${name}`);
    if (typeDef.kind === 'input') {
      inputs[name] = typeDef;
    } else {
      types[name] = typeDef;
    }
  }

  // Legacy payloads may carry a pre-split inputs map; honor it when present.
  const inputsRaw = isObject(root.inputs) ? root.inputs : {};
  for (const [name, definition] of Object.entries(inputsRaw)) {
    const inputDef = parseIRType(name, definition, `inputs.${name}`);
    inputDef.kind = 'input';
    inputs[name] = inputDef;
  }

  const enumsRaw = isObject(root.enums) ? root.enums : {};
  for (const [name, definition] of Object.entries(enumsRaw)) {
    enums[name] = parseIREnum(name, definition, `enums.${name}`);
  }

  const unionsRaw = isObject(root.unions) ? root.unions : {};
  for (const [name, definition] of Object.entries(unionsRaw)) {
    unions[name] = parseIRUnion(name, definition, `unions.${name}`);
  }

  const parsed: Schema = {
    name: asString(root.name) || undefined,
    kind: asString(root.kind) || undefined,
    description: asString(root.description) || undefined,
    rootType: asString(root.rootType) || undefined,
    imports: parseIRImports(root.imports),
    scalars: {
      ...builtinScalars,
      ...scalars,
    },
    enums,
    types,
    inputs,
    unions,
  };

  return parsed;
}

export function parseSchemaIRJson(schemaJson: string): Schema {
  let parsed: unknown;
  try {
    parsed = JSON.parse(schemaJson) as unknown;
  } catch (error) {
    throw new Error(`runtime schema IR parse error: invalid JSON: ${String(error)}`);
  }
  return parseSchemaIR(parsed);
}
