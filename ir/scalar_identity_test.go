func TestValidateCanonicalScalarName(t *testing.T) {
	valid := []string{"UUID", "Identity.UUID", "Temporal.DateTime", "A.B.C", "Slug"}
	for _, name := range valid {
		if err := ValidateCanonicalScalarName(name); err != nil {
			t.Errorf("ValidateCanonicalScalarName(%q) = %v, want nil", name, err)
		}
	}

	invalid := []string{"", "uuid", "Identity.", ".UUID", "Identity..UUID", "Identity_UUID", "identity.UUID"}
	for _, name := range invalid {
		if err := ValidateCanonicalScalarName(name); err == nil {
			t.Errorf("ValidateCanonicalScalarName(%q) = nil, want error", name)
		}
	}
}

