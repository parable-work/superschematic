// runtimeContractsPath is the file the TypeScript runtime's providers test
// reads (D159), relative to this package. Rewrite it with:
//
//	cd ir && go test -run TestRuntimeContractsMatchTheTypeScriptRuntime -update
const runtimeContractsPath = "../runtime/http/testdata/runtime_contracts.json"

// TestRuntimeContractsMatchTheTypeScriptRuntime writes RuntimeContracts as
// the file the TypeScript runtime's RUNTIME_CONTRACTS is held to, and fails
// when the committed file is stale.
func TestRuntimeContractsMatchTheTypeScriptRuntime(t *testing.T) {
	file := struct {
		Comment   string            `json:"comment"`
		Contracts []RuntimeContract `json:"contracts"`
	}{
		Comment:   "Generated by ir (cd ir && go test -run TestRuntimeContractsMatchTheTypeScriptRuntime -update); do not edit. The runtime interfaces (D159), each with the operations a provider must and may implement: ir.RuntimeContracts, which the build checks a provider package's manifest against, and RUNTIME_CONTRACTS in @superschematic/http-runtime/providers, whose test reads this file.",
		Contracts: RuntimeContracts,
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(file); err != nil {
		t.Fatal(err)
	}
	want := buf.Bytes()
	if *updateMemoryStoreParity {
		if err := os.WriteFile(runtimeContractsPath, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(runtimeContractsPath)
	if err != nil {
		t.Fatalf("%v; run: cd ir && go test -run TestRuntimeContractsMatchTheTypeScriptRuntime -update", err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; run: cd ir && go test -run TestRuntimeContractsMatchTheTypeScriptRuntime -update", runtimeContractsPath)
	}
}

func TestARuntimeProviderIsCheckedAgainstItsContract(t *testing.T) {
	good := func() *RuntimeProvider {
		return &RuntimeProvider{
			Name: "sms-relay", Implements: RuntimeChannel, Package: "@example/sms-relay",
			Operations: []string{"inbound", "send", "health"},
			Config:     []ProviderConfigKey{{Key: "TOKEN", Secret: true}, {Key: "URL"}},
			Role:       []string{"messages.relay"},
		}
	}
	if err := good().Check(); err != nil {
		t.Fatalf("a channel adapter with send, health and inbound: %v", err)
	}
	if p := good(); p.CallsTheApp() {
		t.Fatal("a provider whose config lists no CALLER_KEY calls the app")
	}
	calling := good()
	calling.Config = append(calling.Config, ProviderConfigKey{Key: ProviderCallerKey, Secret: true})
	if err := calling.Check(); err != nil || !calling.CallsTheApp() {
		t.Fatalf("a provider that lists a secret CALLER_KEY: %v, calls the app %v", err, calling.CallsTheApp())
	}
	p := good()
	p.Operations = nil
	if err := p.Check(); err != nil {
		t.Fatalf("a manifest that leaves its operations to the required ones: %v", err)
	}
	p.Normalize()
	if strings.Join(p.Operations, ",") != "send,health" {
		t.Fatalf("Normalize gave %v, want the required ones", p.Operations)
	}
	p = good()
	p.Normalize()
	if strings.Join(p.Operations, ",") != "send,health,inbound" || p.Config[0].Key != "TOKEN" {
		t.Fatalf("Normalize sorts by the contract's order and the keys: %v %v", p.Operations, p.Config)
	}

	for name, tc := range map[string]struct {
		edit func(*RuntimeProvider)
		want string
	}{
		"an interface the core does not define": {func(p *RuntimeProvider) { p.Implements = "payments" }, `implements "payments", which is no runtime interface`},
		"an operation the contract lacks":       {func(p *RuntimeProvider) { p.Operations = append(p.Operations, "complete") }, "a channel adapter has no operation complete"},
		"a required operation left out":         {func(p *RuntimeProvider) { p.Operations = []string{"send", "status"} }, "leave out health"},
		"a name with capitals":                  {func(p *RuntimeProvider) { p.Name = "SmsRelay" }, `name "SmsRelay" is lower-case`},
		"a lower-case config key":               {func(p *RuntimeProvider) { p.Config[1].Key = "url" }, `config key "url" is upper-case`},
		"a config key twice":                    {func(p *RuntimeProvider) { p.Config[1].Key = "TOKEN" }, "config key TOKEN is declared twice"},
		"a caller key that is no secret":        {func(p *RuntimeProvider) { p.Config = append(p.Config, ProviderConfigKey{Key: ProviderCallerKey}) }, "config key CALLER_KEY is the key the provider calls the app with"},
		"a role over a whole area":              {func(p *RuntimeProvider) { p.Role = []string{"messages"} }, `role permission "messages" names an area`},
		"a role that is no dotted path":         {func(p *RuntimeProvider) { p.Role = []string{"messages.*"} }, "is a dotted path of words"},
	} {
		t.Run(name, func(t *testing.T) {
			p := good()
			tc.edit(p)
			err := p.Check()
			if err == nil || !strings.Contains(err.Error(), tc.want) {
				t.Fatalf("Check() = %v, want it to say %q", err, tc.want)
			}
		})
	}
}

func TestProviderSlotsOfReadsTheEnvVarsClasses(t *testing.T) {
	s := &Schema{Name: "notes-api", Types: map[string]*TypeDef{
		"Base":   {Name: "Base", EnvVars: true, ProviderSlots: map[string]string{"VAULT": RuntimeCredentials}},
		"Config": {Name: "Config", EnvVars: true, Extends: "Base", ProviderSlots: map[string]string{"SMS": RuntimeChannel}},
	}}
	slots, err := s.ProviderSlotsOf()
	if err != nil || len(slots) != 2 || slots["SMS"] != RuntimeChannel || slots["VAULT"] != RuntimeCredentials {
		t.Fatalf("ProviderSlotsOf() = %v, %v", slots, err)
	}
	s.Types["Config"].ProviderSlots["VAULT"] = RuntimeChannel
	if _, err := s.ProviderSlotsOf(); err == nil || !strings.Contains(err.Error(), "a slot takes one interface") {
		t.Fatalf("a slot of two interfaces: %v", err)
	}
	delete(s.Types["Config"].ProviderSlots, "VAULT")
	s.Types["Other"] = &TypeDef{Name: "Other", ProviderSlots: map[string]string{"X": RuntimeModel}}
	if _, err := s.ProviderSlotsOf(); err == nil || !strings.Contains(err.Error(), "no @envVars class") {
		t.Fatalf("@providers off an @envVars class: %v", err)
	}
}
