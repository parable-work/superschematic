func TestSchema_JSONFieldNamesVerbatim(t *testing.T) {
	s := NewSchema("web-enums", SchemaKindGeneral)
	s.Enums["Status"] = &EnumDef{
		Name:   "Status",
		Values: []EnumValueDef{{Name: "Active", SerializedAs: "active"}},
	}
	s.Imports = []Import{{Package: "@schemas/enums", Types: []string{"TenantUserStatus"}}}

	data, err := json.Marshal(s)
	if err != nil {
		t.Fatalf("Marshal: %v", err)
	}

	var raw map[string]any
	if err := json.Unmarshal(data, &raw); err != nil {
		t.Fatalf("Unmarshal: %v", err)
	}
	for _, key := range []string{"name", "kind", "imports", "enums"} {
		if _, ok := raw[key]; !ok {
			t.Errorf("marshaled Schema missing key %q; got keys %v", key, mapKeys(raw))
		}
	}

	// Empty definition maps are omitted: this schema carries no types.
	for _, key := range []string{"types", "scalars", "unions", "operationSets", "platforms", "combinators", "primitives", "plots", "queries", "mutations", "rootType"} {
		if _, ok := raw[key]; ok {
			t.Errorf("marshaled Schema should omit key %q", key)
		}
	}

	enums, ok := raw["enums"].(map[string]any)
	if !ok {
		t.Fatalf("enums is not an object: %v", raw["enums"])
	}
	status, ok := enums["Status"].(map[string]any)
	if !ok {
		t.Fatalf("enums.Status is not an object: %v", enums["Status"])
	}
	for _, key := range []string{"name", "values"} {
		if _, ok := status[key]; !ok {
			t.Errorf("marshaled EnumDef missing key %q; got keys %v", key, mapKeys(status))
		}
	}
}

func mapKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	return keys
}
