func representativeTypeDef() *TypeDef {
	return &TypeDef{
		Name:    "TenantUser",
		Role:    RoleDBTable,
		Comment: "A user's membership in a tenant.",
		Extends: "Auditable",
		Implements: []TraitRef{
			{Name: "SoftDeletable"},
		},
		RawHeritage: &RawHeritage{
			Extends:    "Auditable",
			Implements: []string{"SoftDeletable"},
		},
		Source: &SourceRef{
			Target:            "web-db.TenantUser",
			Virtual:           []string{"displayName"},
			OmittedFromSource: []string{"passwordHash"},
		},
		Fields: []*FieldDef{
			{
				Name:          "id",
				TypeRef:       TypeRef{Name: "Identity.UUID"},
				Required:      true,
				Key:           true,
				Unique:        true,
				AutoGenerated: true,
			},
			{
				Name:          "createdAt",
				TypeRef:       TypeRef{Name: "Temporal.DateTime"},
				Required:      true,
				InheritedFrom: "Auditable",
			},
			{
				Name:    "displayName",
				TypeRef: TypeRef{Name: "Identity.Name"},
				Virtual: true,
				Comment: "Computed from first + last name.",
			},
		},
		Indexes: []IndexDef{{Keys: []string{"tenant"}, Unique: false}},
	}
}

func TestTypeDef_JSONFieldNamesVerbatim(t *testing.T) {
	data, err := json.Marshal(representativeTypeDef())
	if err != nil {
		t.Fatalf("Marshal: %v", err)
	}

	var raw map[string]any
	if err := json.Unmarshal(data, &raw); err != nil {
		t.Fatalf("Unmarshal: %v", err)
	}

	// Top-level keys must be the IR field names verbatim (lowerCamel).
	for _, key := range []string{"name", "role", "comment", "extends", "implements", "rawHeritage", "source", "fields", "indexes"} {
		if _, ok := raw[key]; !ok {
			t.Errorf("marshaled TypeDef missing key %q; got keys %v", key, mapKeys(raw))
		}
	}

	// Zero-valued optional fields must be omitted.
	for _, key := range []string{"owner", "description", "isTrait", "traitConfig", "jsonField", "versioned", "envVars", "denyUnknownFields"} {
		if _, ok := raw[key]; ok {
			t.Errorf("marshaled TypeDef should omit zero-valued key %q", key)
		}
	}

	fields, ok := raw["fields"].([]any)
	if !ok || len(fields) != 3 {
		t.Fatalf("fields = %v, want 3 entries", raw["fields"])
	}
	first, ok := fields[0].(map[string]any)
	if !ok {
		t.Fatalf("fields[0] is not an object: %v", fields[0])
	}
	for _, key := range []string{"name", "typeRef", "required", "key", "unique", "autoGenerated"} {
		if _, ok := first[key]; !ok {
			t.Errorf("marshaled FieldDef missing key %q; got keys %v", key, mapKeys(first))
		}
	}
	second, ok := fields[1].(map[string]any)
	if !ok {
		t.Fatalf("fields[1] is not an object: %v", fields[1])
	}
	if second["inheritedFrom"] != "Auditable" {
		t.Errorf("fields[1].inheritedFrom = %v, want Auditable", second["inheritedFrom"])
	}
	third, ok := fields[2].(map[string]any)
	if !ok {
		t.Fatalf("fields[2] is not an object: %v", fields[2])
	}
	if third["virtual"] != true {
		t.Errorf("fields[2].virtual = %v, want true", third["virtual"])
	}
}

func TestTypeDef_JSONRoundTrip(t *testing.T) {
	original := representativeTypeDef()

	data, err := json.Marshal(original)
	if err != nil {
		t.Fatalf("Marshal: %v", err)
	}

	var decoded TypeDef
	if err := json.Unmarshal(data, &decoded); err != nil {
		t.Fatalf("Unmarshal: %v", err)
	}

	if !reflect.DeepEqual(original, &decoded) {
		t.Errorf("JSON round trip mismatch:\noriginal: %+v\ndecoded:  %+v", original, &decoded)
	}
}

