	"Every segment, the declaration and each part, is 1 to 128 bytes of UTF-8 with no ':', '*', '?', '[', ']', '@', '\\', byte below 0x20 or 0x7f, and is refused, never escaped. " +
	"want is the name without the store's prefix, or null when it is refused; the reason is not compared. " +
	"With store set, fullName is the name the store keys or publishes under: the prefix, which is store, or store@member when member is set, then ':' and the name; a store or a member that is no segment is refused, want and fullName null. " +
	"rateLimit.windows: {name, limit, windowMs, nowMs, prevCount, currCount, want}. The shared rate limit's sliding window: curr = floor(nowMs / windowMs) * windowMs, prev = curr - windowMs, elapsed = nowMs - curr; estimate = prevCount * (windowMs - elapsed) / windowMs + currCount in IEEE doubles, in that order; this is the rule of the Go runtime's limiter, httprate: the request is allowed when round(estimate) + 1 <= limit, rounding half away from zero, and then increments the counter of the window starting at curr with a TTL of 2 * windowMs + 5000 ms; otherwise it is refused with Retry-After the window's length in whole seconds, windowMs / 1000. " +
	"want: {allowed, estimate, currWindowStart, prevWindowStart (Unix seconds), incrementTtlMs (0 when refused), retryAfterSeconds (0 when allowed)}. " +
	"rateLimit.keys: {name, service, operation, windowStart, clientKey, want}: the name, without the store's prefix, of the reserved rate-limit declaration's counter: rate-limit:<service>:<operation>:<windowStart in Unix seconds, base 10>:<lowercase hex SHA-256 of the UTF-8 clientKey>, or null when service or operation is no segment. " +
	"Every server names the operation <namespace>.<name>, the namespace its generated operation table holds (the operation set's name in kebab case, less its Queries, Mutations, Operations or Actions suffix, root for Query and Mutation) and the operation's name: product.getProduct for ProductQueries.getProduct."

// memoryStoreParityFile is the shape of memorystore_parity.json.
type memoryStoreParityFile struct {
	Comment   string                 `json:"comment"`
	Names     []memoryStoreNameCase  `json:"names"`
	RateLimit memoryStoreRateLimitVs `json:"rateLimit"`
}

type memoryStoreNameCase struct {
	Name        string   `json:"name"`
	Declaration string   `json:"declaration"`
	Parts       []string `json:"parts"`
	Store       string   `json:"store,omitempty"`
	Member      string   `json:"member,omitempty"`
	Want        *string  `json:"want"`
	FullName    *string  `json:"fullName,omitempty"`
}

type memoryStoreRateLimitVs struct {
	Windows []memoryStoreWindowCase `json:"windows"`
	Keys    []memoryStoreKeyCase    `json:"keys"`
}

type memoryStoreWindowCase struct {
	Name      string              `json:"name"`
	Limit     int64               `json:"limit"`
	WindowMs  int64               `json:"windowMs"`
	NowMs     int64               `json:"nowMs"`
	PrevCount int64               `json:"prevCount"`
	CurrCount int64               `json:"currCount"`
	Want      memoryStoreDecision `json:"want"`
}

type memoryStoreDecision struct {
	Allowed           bool    `json:"allowed"`
	Estimate          float64 `json:"estimate"`
	CurrWindowStart   int64   `json:"currWindowStart"`
	PrevWindowStart   int64   `json:"prevWindowStart"`
	IncrementTTLMs    int64   `json:"incrementTtlMs"`
	RetryAfterSeconds int64   `json:"retryAfterSeconds"`
}

type memoryStoreKeyCase struct {
	Name        string  `json:"name"`
	Service     string  `json:"service"`
	Operation   string  `json:"operation"`
	WindowStart int64   `json:"windowStart"`
	ClientKey   string  `json:"clientKey"`
	Want        *string `json:"want"`
}

// memoryStoreDecide is the shared rate limit's rule, as the vectors' comment
// states it.
func memoryStoreDecide(limit, windowMs, nowMs, prevCount, currCount int64) memoryStoreDecision {
	curr := nowMs / windowMs * windowMs
	prev := curr - windowMs
	elapsed := nowMs - curr
	estimate := float64(prevCount)*(float64(windowMs)-float64(elapsed))/float64(windowMs) + float64(currCount)
	d := memoryStoreDecision{Estimate: estimate, CurrWindowStart: curr / 1000, PrevWindowStart: prev / 1000}
	if int64(math.Round(estimate))+1 <= limit {
		d.Allowed = true
		d.IncrementTTLMs = 2*windowMs + MemoryStoreRateLimitWindowSlackSeconds*1000
		return d
	}
	d.RetryAfterSeconds = windowMs / 1000
	return d
}

// memoryStoreRateLimitName is the reserved declaration's counter's name.
func memoryStoreRateLimitName(service, operation string, windowStart int64, clientKey string) (string, error) {
	sum := sha256.Sum256([]byte(clientKey))
	return MemoryStoreName(MemoryStoreRateLimit, service, operation, formatInt(windowStart), hex.EncodeToString(sum[:]))
}

func formatInt(n int64) string {
	data, _ := json.Marshal(n)
	return string(data)
}

func memoryStoreParityCorpus(t *testing.T) memoryStoreParityFile {
	t.Helper()
	uuid := "3f2a9c1e-7b4d-4e8a-9c2f-1d5e6a7b8c9d"
	names := []memoryStoreNameCase{
		{Name: "a signal's name, one UUID part", Declaration: "stock-changed", Parts: []string{uuid}},
		{Name: "a declaration with no parts", Declaration: "receipts-swept"},
		{Name: "each part's wire string, in order", Declaration: "views", Parts: []string{uuid, "20261025", "north", "true", "a label"}},
		{Name: "a negative integer part", Declaration: "views", Parts: []string{"-42"}},
		{Name: "an explicit name's dots and underscores", Declaration: "stock.samples_v2", Parts: []string{"x"}},
		{Name: "a part that is not ASCII", Declaration: "views", Parts: []string{"café-ü"}},
		{Name: "a part of 128 bytes", Declaration: "views", Parts: []string{strings.Repeat("a", 128)}},
		{Name: "a part of 128 bytes in two-byte characters", Declaration: "views", Parts: []string{strings.Repeat("é", 64)}},
		{Name: "a part of 129 bytes", Declaration: "views", Parts: []string{strings.Repeat("a", 129)}},
		{Name: "a part of 130 bytes in two-byte characters", Declaration: "views", Parts: []string{strings.Repeat("é", 65)}},
		{Name: "an empty part", Declaration: "views", Parts: []string{uuid, ""}},
		{Name: "an empty declaration", Declaration: "", Parts: []string{uuid}},
		{Name: "a declaration that is no segment", Declaration: "stock:changed", Parts: []string{uuid}},
		{Name: "the store's prefix", Declaration: "stock-changed", Parts: []string{uuid}, Store: "shop-cache"},
		{Name: "a member's prefix", Declaration: "stock-changed", Parts: []string{uuid}, Store: "shop-cache", Member: "pr-12"},
		{Name: "a store that is no segment", Declaration: "stock-changed", Parts: []string{uuid}, Store: "shop:cache"},
		{Name: "a member that is no segment", Declaration: "stock-changed", Parts: []string{uuid}, Store: "shop-cache", Member: "pr@12"},
	}
	for _, c := range []struct{ what, char string }{
		{"a colon", ":"}, {"an asterisk", "*"}, {"a question mark", "?"}, {"an opening bracket", "["},
		{"a closing bracket", "]"}, {"an at sign", "@"}, {"a backslash", "\\"}, {"a NUL", "\x00"},
		{"a tab", "\t"}, {"a newline", "\n"}, {"the unit separator 0x1f", "\x1f"}, {"DEL", "\x7f"},
	} {
		names = append(names, memoryStoreNameCase{Name: "a part with " + c.what, Declaration: "views", Parts: []string{"a" + c.char + "b"}})
	}
	names = append(names, memoryStoreNameCase{Name: "a part with a space, which is allowed", Declaration: "views", Parts: []string{"a b"}})
	for i := range names {
		c := &names[i]
		if c.Parts == nil {
			c.Parts = []string{}
		}
		name, err := MemoryStoreName(c.Declaration, c.Parts...)
		if err != nil {
			continue
		}
		if c.Store == "" {
			c.Want = &name
			continue
		}
		if CheckMemoryStoreSegment(c.Store) != nil || (c.Member != "" && CheckMemoryStoreSegment(c.Member) != nil) {
			continue
		}
		full := MemoryStorePrefix(c.Store, c.Member) + ":" + name
		c.Want, c.FullName = &name, &full
	}

	const minute = 60_000
	start := int64(1_761_350_400_000) // 2025-10-25T00:00:00Z, a minute's start
	windows := []memoryStoreWindowCase{
		{Name: "the first request of a window", Limit: 10, WindowMs: minute, NowMs: start, PrevCount: 0, CurrCount: 0},
		{Name: "mid-window, under the limit", Limit: 10, WindowMs: minute, NowMs: start + 30_000, PrevCount: 4, CurrCount: 5},
		{Name: "mid-window, one under the limit", Limit: 10, WindowMs: minute, NowMs: start + 30_000, PrevCount: 2, CurrCount: 8},
		{Name: "at the limit", Limit: 10, WindowMs: minute, NowMs: start + 15_000, PrevCount: 0, CurrCount: 10},
		{Name: "over the limit", Limit: 10, WindowMs: minute, NowMs: start + 45_000, PrevCount: 0, CurrCount: 12},
		{Name: "a heavy previous window, early in this one", Limit: 10, WindowMs: minute, NowMs: start + 30_000, PrevCount: 30, CurrCount: 0},
		{Name: "a heavy previous window, late in this one", Limit: 10, WindowMs: minute, NowMs: start + 50_000, PrevCount: 30, CurrCount: 4},
		{Name: "a heavy previous window at this one's start", Limit: 10, WindowMs: minute, NowMs: start, PrevCount: 10, CurrCount: 0},
		{Name: "the last millisecond of a window, refused", Limit: 1, WindowMs: minute, NowMs: start + 59_999, PrevCount: 0, CurrCount: 1},
		{Name: "an hour's window", Limit: 100, WindowMs: 60 * minute, NowMs: start + 600_000, PrevCount: 60, CurrCount: 50},
		{Name: "a fractional estimate under the limit", Limit: 10, WindowMs: minute, NowMs: start + 40_000, PrevCount: 7, CurrCount: 7},
		{Name: "a fractional estimate that rounds up to the limit, refused", Limit: 10, WindowMs: minute, NowMs: start + 30_000, PrevCount: 3, CurrCount: 8},
	}
	for i := range windows {
		w := &windows[i]
		w.Want = memoryStoreDecide(w.Limit, w.WindowMs, w.NowMs, w.PrevCount, w.CurrCount)
	}

	keys := []memoryStoreKeyCase{
		{Name: "an IPv4 client", Service: "shop-api", Operation: "product.getProduct", WindowStart: start / 1000, ClientKey: "203.0.113.7"},
		{Name: "an IPv6 client, whose colons the hash hides", Service: "shop-api", Operation: "product.getProduct", WindowStart: start / 1000, ClientKey: "2001:db8::1"},
		{Name: "a user's key", Service: "shop-orders", Operation: "order.placeOrder", WindowStart: start/1000 + 60, ClientKey: "user:42"},
		{Name: "a namespace of two words, which the server spells in kebab case", Service: "shop-orders", Operation: "order-item.addItem", WindowStart: start / 1000, ClientKey: "198.51.100.20"},
		{Name: "an operation that is no segment", Service: "shop-api", Operation: "Product:get", WindowStart: start / 1000, ClientKey: "203.0.113.7"},
		{Name: "an empty service", Service: "", Operation: "product.getProduct", WindowStart: start / 1000, ClientKey: "203.0.113.7"},
	}
	for i := range keys {
		k := &keys[i]
		if name, err := memoryStoreRateLimitName(k.Service, k.Operation, k.WindowStart, k.ClientKey); err == nil {
			k.Want = &name
		}
	}
	return memoryStoreParityFile{Comment: memoryStoreParityComment, Names: names, RateLimit: memoryStoreRateLimitVs{Windows: windows, Keys: keys}}
}

// TestWriteMemoryStoreParityVectors keeps
// runtime/http/testdata/memorystore_parity.json equal to the vectors the
// rules here make; -update rewrites it.
func TestWriteMemoryStoreParityVectors(t *testing.T) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(memoryStoreParityCorpus(t)); err != nil {
		t.Fatal(err)
	}
	path := filepath.FromSlash(memoryStoreParityPath)
	if *updateMemoryStoreParity {
		if err := os.WriteFile(path, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	committed, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read %s: %v (run with -update)", path, err)
	}
	if !bytes.Equal(committed, buf.Bytes()) {
		t.Fatalf("%s is stale; run go test -run TestWriteMemoryStoreParityVectors -update", path)
	}
}

// TestMemoryStoreParityVectorsParse: the committed vectors parse, every
// section has cases with distinct names, and each case holds what the
// rules give, read back from the file.
func TestMemoryStoreParityVectorsParse(t *testing.T) {
	data, err := os.ReadFile(filepath.FromSlash(memoryStoreParityPath))
	if err != nil {
		t.Fatal(err)
	}
	var file memoryStoreParityFile
	dec := json.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&file); err != nil {
		t.Fatal(err)
	}
	if len(file.Names) == 0 || len(file.RateLimit.Windows) == 0 || len(file.RateLimit.Keys) == 0 {
		t.Fatal("a section is empty")
	}
	seen := map[string]bool{}
	refused, allowed := 0, 0
	for _, c := range file.Names {
		if seen["names/"+c.Name] {
			t.Errorf("names: %q repeats", c.Name)
		}
		seen["names/"+c.Name] = true
		name, err := MemoryStoreName(c.Declaration, c.Parts...)
		switch {
		case c.Want == nil && c.Store == "" && err == nil:
			t.Errorf("%s: refused, but the rule gives %q", c.Name, name)
		case c.Want != nil && (err != nil || name != *c.Want):
			t.Errorf("%s: want %q, the rule gives %q, %v", c.Name, *c.Want, name, err)
		}
		if c.Want == nil {
			refused++
		}
	}
	for _, w := range file.RateLimit.Windows {
		if seen["windows/"+w.Name] {
			t.Errorf("windows: %q repeats", w.Name)
		}
		seen["windows/"+w.Name] = true
		if got := memoryStoreDecide(w.Limit, w.WindowMs, w.NowMs, w.PrevCount, w.CurrCount); got != w.Want {
			t.Errorf("%s: want %+v, the rule gives %+v", w.Name, w.Want, got)
		}
		if w.Want.Allowed {
			allowed++
		}
	}
	if refused < 12 || allowed == 0 || allowed == len(file.RateLimit.Windows) {
		t.Errorf("the vectors refuse %d names and allow %d of %d windows", refused, allowed, len(file.RateLimit.Windows))
	}
}
