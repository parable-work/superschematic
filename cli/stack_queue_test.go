// qopsTree writes a stack over qops-db, a DB service with the queue
// Reminder in Postgres and SQLite, and qops-api, an API on it: Dev and Down
// on the local target with Postgres on the ports given, and Staging on the
// fake target. Beside it, qlite-stack deploys qops-db alone in Lite, on the
// fake target's SQLite platform. It returns qops-stack's directory.
func qopsTree(t *testing.T, devPort, downPort int) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), "schemas", "services")
	writeFiles(t, root, map[string]string{
		"qops-db/schema.config.yaml": "name: qops-db\nkind: DB\noutputs:\n  types:\n    go: { enabled: true }\n  sql: { dialects: [postgres, sqlite] }\n",
		"qops-db/src/db.schema.yaml": `name: qops-db
kind: DB
scalars:
  Identity.UUID:
    name: Identity.UUID
    languagePrimitive: string
types:
  # A cart, whose code a new one sends a Reminder of (D88).
  Cart:
    name: Cart
    role: DBTable
    fields:
      - { name: id, typeRef: { name: Identity.UUID }, required: true, key: true, autoGenerated: true }
      - { name: code, typeRef: { name: string }, required: true }
    enqueueOnChange:
      - { queue: Reminder, on: [insert], message: { cart: code } }
  # Sent for an abandoned cart.
  Reminder:
    name: Reminder
    role: EmbeddedStruct
    queue: { retries: 2 }
    fields:
      - { name: cart, typeRef: { name: string }, required: true }
      - { name: note, typeRef: { name: string } }
  # Sent once a day; no trigger enqueues it.
  Digest:
    name: Digest
    role: EmbeddedStruct
    queue: {}
    fields:
      - { name: day, typeRef: { name: string }, required: true }
`,
		"qops-api/schema.config.yaml": "name: qops-api\nkind: API\ndependencies:\n  - { name: qops-db, kind: DB }\noutputs:\n  types:\n    go: { enabled: true }\n  api: { enabled: true }\n",
		"qops-api/src/api.schema.yaml": `name: qops-api
kind: API
types:
  CartView:
    name: CartView
    role: APIView
    fields:
      - { name: id, typeRef: { name: string }, required: true }
operationSets:
  - name: Carts
    operations:
      - name: getCart
        typeRef: { name: CartView }
        required: true
        httpMethod: GET
        restPath: "carts/{id}"
        arguments:
          - { name: id, typeRef: { name: string }, required: true }
`,
		"qops-stack/schema.config.yaml": "name: qops-stack\nkind: Stack\noutputs: {}\n",
		"qops-stack/src/stack.schema.yaml": fmt.Sprintf(`kind: Stack
types:
  Qops:
    name: Qops
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: qops-api, kind: API }
  Dev:
    name: Dev
    role: EmbeddedStruct
    environment:
      target: local
      values: { postgresPort: %d }
  Down:
    name: Down
    role: EmbeddedStruct
    environment:
      target: local
      values: { postgresPort: %d }
  Staging:
    name: Staging
    role: EmbeddedStruct
    environment:
      target: fake
      values: { project: acme-staging, region: us-east1 }
`, devPort, downPort),
		// No fake connector reaches the fake target's SQLite platform, so
		// this stack deploys the DB service alone.
		"qlite-stack/schema.config.yaml": "name: qlite-stack\nkind: Stack\noutputs: {}\n",
		"qlite-stack/src/stack.schema.yaml": fmt.Sprintf(`kind: Stack
types:
  Qlite:
    name: Qlite
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: qops-db, kind: DB }
  Lite:
    name: Lite
    role: EmbeddedStruct
    environment:
      target: fake
      values: { project: acme-lite, region: us-east1 }
      settings:
        - of: { service: { name: qops-db, kind: DB } }
          platform: %s
`, stacktest.LitePlatform),
	})
	return filepath.Join(root, "qops-stack")
}

// runQueue runs `stack queue` with the args given over the stack at
// stackDir, or over qlite-stack beside it when the first is "lite", the
// fake target linked, and returns what it printed.
func runQueue(t *testing.T, stackDir string, args ...string) (string, error) {
	t.Helper()
	stdout, stderr, err := runQueueWith(t, &stacktest.Extension{}, stackDir, args...)
	return stdout + stderr, err
}

// runQueueWith runs `stack queue` as runQueue does, with ext linked, and
// returns its stdout and its stderr apart.
func runQueueWith(t *testing.T, ext *stacktest.Extension, stackDir string, args ...string) (string, string, error) {
	t.Helper()
	if args[0] == "lite" {
		stackDir, args = filepath.Join(filepath.Dir(stackDir), "qlite-stack"), args[1:]
	}
	var stdout, stderr bytes.Buffer
	root := New(Config{}, []registry.Extension{ext}...)
	root.SetOut(&stdout)
	root.SetErr(&stderr)
	root.SetIn(strings.NewReader(""))
	root.SetArgs(append(append([]string{"stack", "queue"}, args...), "--stack", stackDir))
	err := root.Execute()
	return stdout.String(), stderr.String(), err
}

// TestStackQueueRefuses refuses, before it runs anything, a queue named
// otherwise than <db>.<Queue>, a DB service the stack does not reach and a
// queue its DB service does not declare, an environment that places the
// queue's database on SQLite, a run on a cloud target that was never
// deployed, and a retry or a drop that names no ID and no --all, or both,
// an ID that is no UUID, a drop of every message without --yes, a limit
// under one, a timeout of none and a format other than text or json.
func TestStackQueueRefuses(t *testing.T) {
	stackDir := qopsTree(t, 5432, 5433)
	id := "3f2c8a10-5b1e-4c7a-9d2e-8f6b4a1c0e93"
	for name, tc := range map[string]struct {
		args []string
		want string
	}{
		"no dot":        {[]string{"dead", "Dev", "Reminder"}, `queue "Reminder": name it <db>.<Queue>, its DB service and its @queue class, such as shop-db.OrderPlaced`},
		"no service":    {[]string{"dead", "Dev", "shop-db.Reminder"}, "stack qops-stack reaches no DB service shop-db (its queues: qops-db.Digest, qops-db.Reminder)"},
		"no queue":      {[]string{"dead", "Dev", "qops-db.Nudge"}, "qops-db declares no queue Nudge (the stack's queues: qops-db.Digest, qops-db.Reminder)"},
		"no trigger":    {[]string{"backfill", "Dev", "qops-db.Digest"}, "no @enqueueOnChange of qops-db enqueues Digest, so stack queue backfill has no rows to enqueue it for"},
		"backfill ids":  {[]string{"backfill", "Dev", "qops-db.Reminder", id}, "accepts 2 arg(s), received 3"},
		"an API":        {[]string{"dead", "Dev", "qops-api.Reminder"}, "stack qops-stack reaches no DB service qops-api"},
		"environment":   {[]string{"dead", "Prod", "qops-db.Reminder"}, "stack qops-stack has no environment Prod"},
		"on SQLite":     {[]string{"lite", "dead", "Lite", "qops-db.Reminder"}, "environment Lite places qops-db on database qops-db, a sqlite database; stack queue reads, retries and drops a queue's dead messages on Postgres alone, and on SQLite it is not built (D68)"},
		"not deployed":  {[]string{"retry", "Staging", "qops-db.Reminder", "--all"}, "Staging was never deployed, so its database qops-db holds no queue yet; deploy it first"},
		"timeout":       {[]string{"dead", "Dev", "qops-db.Reminder", "--timeout", "0s"}, "--timeout 0s: wait for some time"},
		"no ids":        {[]string{"retry", "Dev", "qops-db.Reminder"}, "name the IDs of the dead messages to retry, as stack queue dead lists them, or pass --all"},
		"ids and all":   {[]string{"drop", "Dev", "qops-db.Reminder", id, "--all", "--yes"}, "drop --all drops every dead message; name no ID with it"},
		"bad id":        {[]string{"retry", "Dev", "qops-db.Reminder", "42"}, `"42" is not a message's ID`},
		"drop all":      {[]string{"drop", "Dev", "qops-db.Reminder", "--all"}, "drop --all deletes every dead message of qops-db.Reminder in Dev, which cannot be brought back: pass --yes with it to confirm"},
		"limit":         {[]string{"dead", "Dev", "qops-db.Reminder", "--limit", "0"}, "--limit 0: list one or more"},
		"format":        {[]string{"dead", "Dev", "qops-db.Reminder", "--format", "yaml"}, `--format "yaml": want text or json`},
		"no queue args": {[]string{"dead", "Dev"}, "accepts 2 arg(s), received 1"},
	} {
		t.Run(name, func(t *testing.T) {
			out, err := runQueue(t, stackDir, tc.args...)
			require.Error(t, err, out)
			assert.Contains(t, err.Error(), tc.want)
		})
	}
}

// TestStackQueueOnACloudEnvironment runs the queue commands over a
// deployed run on the fake target, whose queue runner returns the result
// a test gives it: the command hands the runner the queue document of the
// database that hosts the queue's DB service, prints its result as the
// local target's is printed, and writes no message to stderr. It surfaces
// the runner's error, and a target with no queue runner is refused.
func TestStackQueueOnACloudEnvironment(t *testing.T) {
	stackDir := qopsTree(t, 5432, 5433)
	const first = "00000000-0000-4000-8000-0000000000a1"
	ext := &stacktest.Extension{State: &stacktest.FakeState{}, Queues: &stacktest.FakeQueues{Results: map[string][]byte{
		"dead": []byte(`{"version": 1, "service": "qops-db", "queue": "Reminder", "operation": "dead", "total": 1, "messages": [
  {"id": "` + first + `", "attempts": 3, "lastError": "the cart is gone", "diedAt": "2026-10-20T09:00:00Z", "message": {"cart": "c-1", "note": "a private note"}}]}`),
	}}}
	manifest, err := json.Marshal(map[string]any{"version": stackdeploy.ManifestVersion, "stack": "qops-stack", "run": "Staging"})
	require.NoError(t, err)
	staging := registry.Run{Environment: &ir.ResolvedEnvironment{Stack: "qops-stack", Environment: "Staging"}}
	require.NoError(t, ext.State.WriteManifest(context.Background(), staging, manifest))

	stdout, stderr, err := runQueueWith(t, ext, stackDir, "dead", "Staging", "qops-db.Reminder", "--limit", "5")
	require.NoError(t, err, stdout+stderr)
	assert.Equal(t, "Queue qops-db.Reminder of Staging: 1 dead message, the oldest death first.\n\n"+first+
		"\n  attempts:   3\n  died at:    2026-10-20T09:00:00Z\n  last error: the cart is gone\n  message:    {\"cart\":\"c-1\",\"note\":\"a private note\"}\n", stdout)
	assert.Equal(t, "run a queue operation on qops-db, in database qops-db of Staging\n", stderr)
	want, err := queueops.Document(queueops.Request{Service: "qops-db", Queue: "Reminder", Operation: queueops.Dead, Limit: 5})
	require.NoError(t, err)
	docs := ext.Queues.Documents()
	require.Len(t, docs, 1)
	assert.Equal(t, string(want), string(docs[0]))

	stdout, _, err = runQueueWith(t, ext, stackDir, "retry", "Staging", "qops-db.Reminder", "--all", "--format", "json")
	require.NoError(t, err)
	assert.JSONEq(t, `{"version": 1, "service": "qops-db", "queue": "Reminder", "operation": "retry", "ids": []}`, stdout)
	assert.Contains(t, ext.Provisioner.Calls(), "queue qops-db: qops-db.Reminder retry")

	ext.Queues.Fail = errors.New("gcp: the queue operation failed in job qops-migrate: superschematic-migrate: queue Reminder of qops-db: 1 of the 1 message(s) named are not dead")
	_, _, err = runQueueWith(t, ext, stackDir, "drop", "Staging", "qops-db.Reminder", first)
	require.EqualError(t, err, ext.Queues.Fail.Error())

	none := &stacktest.Extension{State: ext.State, NoQueueRunner: true}
	_, _, err = runQueueWith(t, none, stackDir, "dead", "Staging", "qops-db.Reminder")
	require.EqualError(t, err, "target fake runs no queue operation, so `stack queue` does not reach the databases of environment Staging")
}

// TestStackQueueBackfillOnACloudEnvironment runs `stack queue backfill`
// (D88) over a deployed run on the fake target: the command hands the
// runner the document of a backfill of Reminder, whose statement is Cart's
// trigger's insert for every cart, as queueops writes it from qops-db's
// schema, and prints how many messages the runner enqueued.
func TestStackQueueBackfillOnACloudEnvironment(t *testing.T) {
	stackDir := qopsTree(t, 5432, 5433)
	ext := &stacktest.Extension{State: &stacktest.FakeState{}, Queues: &stacktest.FakeQueues{Results: map[string][]byte{
		"backfill": []byte(`{"version": 1, "service": "qops-db", "queue": "Reminder", "operation": "backfill", "total": 3}`),
	}}}
	manifest, err := json.Marshal(map[string]any{"version": stackdeploy.ManifestVersion, "stack": "qops-stack", "run": "Staging"})
	require.NoError(t, err)
	staging := registry.Run{Environment: &ir.ResolvedEnvironment{Stack: "qops-stack", Environment: "Staging"}}
	require.NoError(t, ext.State.WriteManifest(context.Background(), staging, manifest))

	stdout, stderr, err := runQueueWith(t, ext, stackDir, "backfill", "Staging", "qops-db.Reminder")
	require.NoError(t, err, stdout+stderr)
	assert.Equal(t, "Backfilled queue qops-db.Reminder of Staging: enqueued 3 messages, one for each row that meets its triggers' conditions.\n", stdout)

	schema, err := loader.LoadService(filepath.Join(filepath.Dir(stackDir), "qops-db"))
	require.NoError(t, err)
	statements, err := queueops.BackfillStatements(schema, sqlgen.Options{SchemaName: "qops-db"}, "Reminder")
	require.NoError(t, err)
	require.Len(t, statements, 1)
	assert.Contains(t, statements[0], "INSERT INTO reminder_queue (cart)\nSELECT src.code\nFROM cart AS src\nWHERE TRUE")
	want, err := queueops.Document(queueops.Request{Service: "qops-db", Queue: "Reminder", Operation: queueops.Backfill, Backfills: statements})
	require.NoError(t, err)
	docs := ext.Queues.Documents()
	require.Len(t, docs, 1)
	assert.Equal(t, string(want), string(docs[0]))
}

// TestStackQueueOnALocalEnvironment runs the queue commands over the local
// target against a Postgres server, which SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL
// names: Dev's postgresPort is its port, and qops_db, the database the
// local target names for qops-db, holds the queue's table as sqlgen writes
// it, with two dead messages and a ready one. The commands run the
// migration runner, built from runtime/migrate/go, at the URL the
// environment resolves. dead lists the two, the oldest death first, as
// text and as JSON, and up to --limit; retry makes one ready, due now,
// with no attempts, and refuses the ready one, changing nothing; drop
// deletes the other, and drop --all --yes finds nothing left; and Down,
// whose port nothing listens on, says to run stack dev.
func TestStackQueueOnALocalEnvironment(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: builds the migration runner and runs it against Postgres")
	}
	admin := os.Getenv("SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL")
	if admin == "" {
		t.Skip("set SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL to a Postgres on this machine whose role postgres may create databases")
	}
	u, err := url.Parse(admin)
	require.NoError(t, err)
	if host := u.Hostname(); (host != "localhost" && host != local.Loopback) || u.User.Username() != local.PostgresUser {
		t.Skipf("the local target connects as %s to %s; SUPERSCHEMATIC_MIGRATE_TEST_DATABASE_URL names %s on %s", local.PostgresUser, local.Loopback, u.User.Username(), host)
	}
	port := 5432
	if p := u.Port(); p != "" {
		_, err := fmt.Sscan(p, &port)
		require.NoError(t, err)
	}
	// The local target's URLs hold no password, since its container
	// trusts every connection; this server's comes through pgx's PGPASSWORD.
	if password, ok := u.User.Password(); ok {
		t.Setenv("PGPASSWORD", password)
	}
	runner := filepath.Join(t.TempDir(), local.MigrateBinary)
	build := exec.Command("go", "build", "-o", runner, "./cmd/superschematic-migrate")
	build.Dir = filepath.Join("..", "runtime", "migrate", "go")
	build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off")
	built, err := build.CombinedOutput()
	require.NoError(t, err, string(built))
	t.Setenv(local.MigrateEnv, runner)
	queuedb := buildQueueDB(t)

	stackDir := qopsTree(t, port, freeTCPPort(t))
	schema, err := loader.LoadService(filepath.Join(filepath.Dir(stackDir), "qops-db"))
	require.NoError(t, err)
	ddl, err := sqlgen.Generate(schema, sqlgen.Options{SchemaName: "qops-db"})
	require.NoError(t, err)
	ddlDir := t.TempDir()
	require.NoError(t, sqlgen.WriteDDL(ddl, ddlDir))
	createSQL, err := os.ReadFile(filepath.Join(ddlDir, "create.sql"))
	require.NoError(t, err)
	const (
		first  = "00000000-0000-4000-8000-0000000000a1"
		second = "00000000-0000-4000-8000-0000000000a2"
		ready  = "00000000-0000-4000-8000-0000000000a3"
	)
	seed := filepath.Join(ddlDir, "seed.sql")
	require.NoError(t, os.WriteFile(seed, append(createSQL, []byte(`
INSERT INTO reminder_queue (id, cart, note, state, attempts, last_error, updated_at) VALUES
  ('`+first+`', 'c-1', 'first', 'dead', 3, E'the cart is gone\nfor good', now() - interval '2 hours'),
  ('`+second+`', 'c-2', NULL, 'dead', 1, 'the claim of its last attempt expired before its handler finished', now() - interval '1 hour');
INSERT INTO reminder_queue (id, cart, state, due_at) VALUES ('`+ready+`', 'c-3', 'ready', now() + interval '1 hour');
`)...), 0o644))
	database := local.DatabaseName("qops-db")
	queueDB(t, queuedb, "create", admin, database, seed)
	t.Cleanup(func() { queueDB(t, queuedb, "drop", admin, database) })
	state := func(id string) string {
		t.Helper()
		return strings.TrimSpace(queueDB(t, queuedb, "query", admin, database,
			`SELECT state, attempts, due_at <= now(), claim_token IS NULL, COALESCE(last_error, '') FROM reminder_queue WHERE id = '`+id+`'`))
	}

	out, err := runQueue(t, stackDir, "dead", "Dev", "qops-db.Reminder")
	require.NoError(t, err, out)
	for _, want := range []string{
		"Queue qops-db.Reminder of Dev: 2 dead messages, the oldest death first.\n\n" + first + "\n  attempts:   3\n  died at:    ",
		"  last error: the cart is gone\n              for good\n  message:    {\"cart\":\"c-1\",\"note\":\"first\"}\n\n" + second + "\n  attempts:   1\n",
		"  last error: the claim of its last attempt expired before its handler finished\n  message:    {\"cart\":\"c-2\",\"note\":null}\n",
	} {
		assert.Contains(t, out, want)
	}
	assert.NotContains(t, out, ready)
	assert.NotContains(t, out, "--limit shows more")

	out, err = runQueue(t, stackDir, "dead", "Dev", "qops-db.Reminder", "--limit", "1", "--format", "json")
	require.NoError(t, err, out)
	var listed queueops.Result
	require.NoError(t, json.Unmarshal([]byte(out), &listed), out)
	require.Len(t, listed.Messages, 1)
	assert.Equal(t, int64(2), listed.Total)
	assert.Equal(t, first, listed.Messages[0].ID)
	assert.Equal(t, "the cart is gone\nfor good", listed.Messages[0].LastError)
	assert.Regexp(t, `^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\dZ$`, listed.Messages[0].DiedAt)
	out, err = runQueue(t, stackDir, "dead", "Dev", "qops-db.Reminder", "--limit", "1")
	require.NoError(t, err, out)
	assert.Contains(t, out, "Showing 1 of 2; --limit shows more.")

	// A retry that names a message that is not dead changes none.
	out, err = runQueue(t, stackDir, "retry", "Dev", "qops-db.Reminder", strings.ToUpper(first), ready)
	require.Error(t, err, out)
	assert.Equal(t, "local: queue Reminder of qops-db: 1 of the 2 message(s) named are not dead, so none was retried: "+ready+" is ready", err.Error())
	assert.Equal(t, "dead|3|true|true|the cart is gone\nfor good", state(first))

	out, err = runQueue(t, stackDir, "retry", "Dev", "qops-db.Reminder", strings.ToUpper(first))
	require.NoError(t, err, out)
	assert.Equal(t, "Retried 1 dead message of qops-db.Reminder in Dev: each is ready, due now, with no attempts.\n  "+first+"\n", out)
	assert.Equal(t, "ready|0|true|true|the cart is gone\nfor good", state(first))

	out, err = runQueue(t, stackDir, "drop", "Dev", "qops-db.Reminder", second)
	require.NoError(t, err, out)
	assert.Equal(t, "Dropped 1 dead message of qops-db.Reminder in Dev.\n  "+second+"\n", out)
	assert.Equal(t, "", state(second))

	out, err = runQueue(t, stackDir, "drop", "Dev", "qops-db.Reminder", "--all", "--yes")
	require.NoError(t, err, out)
	assert.Equal(t, "Queue qops-db.Reminder of Dev has no dead messages to drop.\n", out)
	out, err = runQueue(t, stackDir, "dead", "Dev", "qops-db.Reminder")
	require.NoError(t, err, out)
	assert.Equal(t, "Queue qops-db.Reminder of Dev has no dead messages.\n", out)
	assert.Equal(t, "ready|0|false|true|", state(ready))

	out, err = runQueue(t, stackDir, "dead", "Down", "qops-db.Reminder")
	require.Error(t, err, out)
	assert.Contains(t, err.Error(), "local: the database of qops-db at postgres://postgres@127.0.0.1:")
	assert.Contains(t, err.Error(), "does not answer (postgres: connect: ")
	assert.Contains(t, err.Error(), "run the environment with superschematic stack dev --environment Down, then run this from another terminal")
}

// buildQueueDB builds testdata/queuedb, a module of its own so the
// Postgres driver stays out of this one, and returns the binary.
func buildQueueDB(t *testing.T) string {
	t.Helper()
	module := t.TempDir()
	require.NoError(t, os.CopyFS(module, os.DirFS(filepath.Join("testdata", "queuedb"))))
	bin := filepath.Join(t.TempDir(), "queuedb")
	build := exec.Command("go", "build", "-o", bin, ".")
	build.Dir = module
	build.Env = append(os.Environ(), "GOFLAGS=-mod=readonly", "CGO_ENABLED=0", "GOWORK=off")
	out, err := build.CombinedOutput()
	require.NoError(t, err, string(out))
	return bin
}

// queueDB runs the queuedb binary and returns what it printed.
func queueDB(t *testing.T, bin string, args ...string) string {
	t.Helper()
	out, err := exec.Command(bin, args...).CombinedOutput()
	require.NoError(t, err, "queuedb %s: %s", strings.Join(args[:1], " "), out)
	return string(out)
}
