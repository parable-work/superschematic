// demoTree writes a schemas root in the YAML data form: a DB service, an
// API whose one DB dependency is its database and whose config holds a
// secret, and a stack that deploys the API on stacktest's fake target in
// Staging and in a parameterized Preview. It returns the stack's directory.
func demoTree(t *testing.T) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), "schemas", "services")
	files := map[string]string{
		"demo-db/schema.config.yaml": `name: demo-db
kind: DB
outputs:
  types:
    go: { enabled: true }
`,
		"demo-db/src/orders.schema.yaml": `name: demo-db
kind: DB
scalars:
  Identity.UUID:
    name: Identity.UUID
    languagePrimitive: string
types:
  Order:
    name: Order
    role: DBTable
    fields:
      - name: id
        typeRef: { name: Identity.UUID }
        required: true
        key: true
        autoGenerated: true
      - name: sku
        typeRef: { name: string }
        required: true
`,
		"demo-api/schema.config.yaml": `name: demo-api
kind: API
dependencies:
  - { name: demo-db, kind: DB }
outputs:
  types:
    go: { enabled: true }
  api: { enabled: true }
`,
		"demo-api/src/api.schema.yaml": `name: demo-api
kind: API
types:
  DemoConfig:
    name: DemoConfig
    role: EmbeddedStruct
    envVars: true
    fields:
      - name: API_KEY
        typeRef: { name: string }
        required: true
        secret: true
  OrderView:
    name: OrderView
    role: APIView
    fields:
      - name: id
        typeRef: { name: string }
        required: true
operationSets:
  - name: OrderQueries
    operations:
      - name: getOrder
        typeRef: { name: OrderView }
        required: true
        httpMethod: GET
        restPath: orders/:id
        arguments:
          - name: id
            typeRef: { name: string }
            required: true
`,
		"demo-stack/schema.config.yaml": `name: demo-stack
kind: Stack
outputs: {}
`,
		"demo-stack/src/stack.schema.yaml": `kind: Stack
types:
  Demo:
    name: Demo
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: demo-api, kind: API }
  Staging:
    name: Staging
    role: EmbeddedStruct
    environment:
      target: fake
      values: { project: acme-staging, region: us-east1 }
  Preview:
    name: Preview
    role: EmbeddedStruct
    extends: Staging
    rawHeritage: { extends: Staging }
    environment:
      parameters: [pr]
  Dev:
    name: Dev
    role: EmbeddedStruct
    environment:
      target: local
`,
	}
	for name, content := range files {
		path := filepath.Join(root, filepath.FromSlash(name))
		require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
		require.NoError(t, os.WriteFile(path, []byte(content), 0o644))
	}
	return filepath.Join(root, "demo-stack")
}

// fakeTerminal answers each prompt with the next value.
type fakeTerminal struct {
	answers []string
	prompts []string
}

func (f *fakeTerminal) Secret(prompt string) ([]byte, error) {
	f.prompts = append(f.prompts, prompt)
	if len(f.answers) == 0 {
		return nil, fmt.Errorf("no more answers")
	}
	answer := f.answers[0]
	f.answers = f.answers[1:]
	return []byte(answer), nil
}

// useTerminal makes the stack commands ask term for values.
func useTerminal(t *testing.T, term *fakeTerminal) {
	prev := newPrompter
	newPrompter = func(*cobra.Command) stackdeploy.Prompter {
		if term == nil {
			return nil
		}
		return term
	}
	t.Cleanup(func() { newPrompter = prev })
}

func demoImage(n int) string {
	return "demo-api=demo-api@sha256:" + strings.Repeat(fmt.Sprintf("%x", n), 64)
}

// TestStackCommands runs plan, deploy, secrets set, outputs, bootstrap and
// destroy over the demo tree on the fake target, which records the calls.
func TestStackCommands(t *testing.T) {
	stackDir := demoTree(t)
	ext := &stacktest.Extension{}
	exts := []registry.Extension{ext}
	run := func(args ...string) (string, error) {
		t.Helper()
		var stdout, stderr bytes.Buffer
		root := New(Config{}, exts...)
		root.SetOut(&stdout)
		root.SetErr(&stderr)
		root.SetIn(strings.NewReader(""))
		root.SetArgs(append([]string{"stack"}, append(args, "--stack", stackDir)...))
		err := root.Execute()
		assert.NotContains(t, stdout.String()+stderr.String(), "key-", "a secret value reached the output")
		assert.NotContains(t, stdout.String()+stderr.String(), "local \"key\"", "a secret value reached the output")
		return stdout.String(), err
	}
	useTerminal(t, nil)

	// A first plan: every node to create, a migration from an empty
	// database, a server with no image and a secret with no value.
	out, err := run("plan", "Staging")
	require.NoError(t, err)
	for _, want := range []string{
		"Plan of Staging",
		"create   demo-api.service",
		"Migration of demo-db on database demo-db: 2 expand, 0 contract step(s)",
		"CREATE TABLE \"order\"",
		"Servers with no image yet, planned at their repository: demo-api",
		"Secrets with no value: DemoConfig.API_KEY (stack secrets set Staging)",
	} {
		assert.Contains(t, out, want)
	}

	// Without a terminal, deploy stops after the infrastructure for the
	// missing secret; at one, it asks.
	_, err = run("deploy", "Staging", "--image", demoImage(1))
	require.ErrorContains(t, err, "secret DemoConfig.API_KEY has no value: run `stack secrets set Staging`")
	term := &fakeTerminal{answers: []string{"key-1"}}
	useTerminal(t, term)
	n := len(ext.Provisioner.Calls())
	out, err = run("deploy", "Staging", "--image", demoImage(1))
	require.NoError(t, err)
	assert.Equal(t, "deployed Staging\n", out)
	assert.Equal(t, []string{"Value of DemoConfig.API_KEY (read by demo-api): "}, term.prompts)
	var steps []string
	for _, call := range ext.Provisioner.Calls()[n:] {
		steps = append(steps, strings.SplitN(call, ":", 2)[0])
	}
	assert.Equal(t, []string{"render 7 nodes", "apply infrastructure", "migrate expand demo-db", "apply rollout 1"}, steps)

	// The plan of an unchanged tree changes nothing to migrate, and
	// deploy --expect runs the plan it wrote, with the image the manifest
	// records.
	planFile := filepath.Join(t.TempDir(), "plan.json")
	out, err = run("plan", "Staging", "--out", planFile)
	require.NoError(t, err)
	assert.Contains(t, out, "Migration of demo-db on database demo-db: 0 expand, 0 contract step(s)")
	assert.NotContains(t, out, "Servers with no image yet")
	_, err = run("deploy", "Staging", "--expect", planFile)
	require.NoError(t, err)

	// A plan file of another plan is refused.
	var shown stackdeploy.PlanResult
	data, err := os.ReadFile(planFile)
	require.NoError(t, err)
	require.NoError(t, json.Unmarshal(data, &shown))
	shown.Databases[0].Hash = "another"
	data, err = json.Marshal(shown)
	require.NoError(t, err)
	require.NoError(t, os.WriteFile(planFile, data, 0o644))
	_, err = run("deploy", "Staging", "--expect", planFile)
	require.ErrorContains(t, err, "not the ones the plan showed")

	// secrets set asks for the one named, which has a value.
	term = &fakeTerminal{answers: []string{"key-2"}}
	useTerminal(t, term)
	out, err = run("secrets", "set", "Staging", "DemoConfig.API_KEY")
	require.NoError(t, err)
	assert.Equal(t, "stored 1 secret value(s) of Staging\n", out)
	_, err = run("secrets", "set", "Staging", "Other.KEY")
	require.ErrorContains(t, err, "has no secret Other.KEY (its secrets: DemoConfig.API_KEY)")
	useTerminal(t, nil)
	_, err = run("secrets", "set", "Staging")
	require.ErrorContains(t, err, "stdin is not one")

	// outputs writes what the provisioner read.
	outputs := filepath.Join(t.TempDir(), "outputs.json")
	_, err = run("outputs", "Staging", "--out", outputs)
	require.NoError(t, err)
	data, err = os.ReadFile(outputs)
	require.NoError(t, err)
	assert.Contains(t, string(data), `"demo-api.service"`)

	// A member of Preview needs its parameter.
	_, err = run("plan", "Preview")
	require.ErrorContains(t, err, "takes parameter pr")
	_, err = run("deploy", "Preview", "--param", "pr=7", "--image", demoImage(2))
	require.NoError(t, err)

	// bootstrap runs the target's, with the repository named.
	_, err = run("bootstrap", "Staging", "--repository", "acme/shop")
	require.NoError(t, err)
	assert.Contains(t, ext.Provisioner.Calls(), "bootstrap Staging: repository acme/shop, credentials ")

	// destroy asks at a terminal, and runs with --yes.
	_, err = run("destroy", "Staging")
	require.ErrorContains(t, err, "pass --yes to destroy Staging")
	out, err = run("destroy", "Staging", "--yes")
	require.NoError(t, err)
	assert.Equal(t, "destroyed Staging\n", out)
	assert.True(t, slices.Contains(ext.Provisioner.Calls(), "destroy Staging"))

	// A local environment runs with stack dev, and secrets set writes the
	// secrets.env stack dev reads.
	for _, command := range []string{"plan", "deploy", "bootstrap", "destroy", "outputs"} {
		_, err = run(command, "Dev")
		require.ErrorContains(t, err, "environment Dev is on the local target, which `stack "+command+"` does not deploy: run it with `superschematic stack dev --environment Dev`")
	}
	useTerminal(t, &fakeTerminal{answers: []string{"local \"key\""}})
	_, err = run("secrets", "set", "Dev")
	require.NoError(t, err)
	schemasRoot := filepath.Dir(filepath.Dir(stackDir))
	values, err := local.ReadSecrets(filepath.Join(local.StateDir(schemasRoot, "demo-stack", "Dev"), local.SecretsFile))
	require.NoError(t, err)
	assert.Equal(t, map[string]string{"DemoConfig.API_KEY": "local \"key\""}, values)
	useTerminal(t, nil)

	_, err = run("plan", "Nowhere")
	require.ErrorContains(t, err, "stack demo-stack has no environment Nowhere (its environments: Dev, Preview, Staging)")
	_, err = run("deploy", "Staging", "--image", "demo-api")
	require.ErrorContains(t, err, "want <server>=<repository>@sha256:<digest>")
}

// TestStackBuild runs stack build and a deploy that builds over the demo
// tree, with a Dockerfile where build-all writes one, on the fake target.
func TestStackBuild(t *testing.T) {
	stackDir := demoTree(t)
	schemasRoot := filepath.Dir(filepath.Dir(stackDir))
	serverDir := filepath.Join(schemasRoot, "dist", "server", "demo-stack", "demo-api")
	require.NoError(t, os.MkdirAll(serverDir, 0o755))
	require.NoError(t, os.WriteFile(filepath.Join(serverDir, "Dockerfile"), []byte("FROM scratch\n"), 0o644))
	require.NoError(t, os.WriteFile(filepath.Join(serverDir, "Dockerfile.dockerignore"), []byte("*\n!schemas/dist/server\n"), 0o644))
	ext := &stacktest.Extension{}
	run := func(args ...string) (string, error) {
		t.Helper()
		var stdout, stderr bytes.Buffer
		root := New(Config{}, ext)
		root.SetOut(&stdout)
		root.SetErr(&stderr)
		root.SetIn(strings.NewReader(""))
		root.SetArgs(append([]string{"stack"}, append(args, "--stack", stackDir)...))
		err := root.Execute()
		return stdout.String(), err
	}
	useTerminal(t, &fakeTerminal{answers: []string{"key-1"}})

	out, err := run("build", "Staging")
	require.NoError(t, err)
	assert.Regexp(t, `^--image demo-api=demo-api@sha256:[0-9a-f]{64}\n$`, out)
	assert.Equal(t, []string{"build demo-api: schemas/dist/server/demo-stack/demo-api/Dockerfile"}, ext.Provisioner.Calls())
	assert.Equal(t, []string{"schemas/dist/server/", "schemas/dist/server/demo-stack/", "schemas/dist/server/demo-stack/demo-api/",
		"schemas/dist/server/demo-stack/demo-api/Dockerfile", "schemas/dist/server/demo-stack/demo-api/Dockerfile.dockerignore"},
		ext.Builder.Context("demo-api"))
	image := strings.TrimSpace(strings.TrimPrefix(out, "--image demo-api="))

	out, err = run("build", "Staging", "--format", "json", "--server", "demo-api")
	require.NoError(t, err)
	var result stackdeploy.BuildResult
	require.NoError(t, json.Unmarshal([]byte(out), &result))
	assert.Equal(t, map[string]string{"demo-api": image}, result.Images)
	_, err = run("build", "Staging", "--server", "demo-db")
	require.ErrorContains(t, err, "has no server demo-db")

	// --no-build with no image anywhere is refused; a deploy builds.
	_, err = run("deploy", "Staging", "--no-build")
	require.ErrorContains(t, err, "no image for server demo-api: the manifest records none, so pass --image")
	n := len(ext.Provisioner.Calls())
	_, err = run("deploy", "Staging")
	require.NoError(t, err)
	calls := ext.Provisioner.Calls()[n:]
	assert.Equal(t, "build demo-api: schemas/dist/server/demo-stack/demo-api/Dockerfile", calls[0])
	service := ext.Provisioner.Rendered().Resources.Resource("demo-api.service")
	assert.Equal(t, image, service.Properties["image"])

	// Nothing changed since the deploy: the build has nothing to build.
	out, err = run("build", "Staging", "--format", "json")
	require.NoError(t, err)
	result = stackdeploy.BuildResult{}
	require.NoError(t, json.Unmarshal([]byte(out), &result))
	assert.Empty(t, result.Built)
	assert.Equal(t, []string{"demo-api"}, result.Unchanged)
}

func TestParseGitHubRemote(t *testing.T) {
	for url, want := range map[string]string{
		"https://github.com/acme/shop.git":          "acme/shop",
		"https://github.com/acme/shop":              "acme/shop",
		"https://token@github.com/acme/shop.git":    "acme/shop",
		"git@github.com:acme/shop.git":              "acme/shop",
		"ssh://git@github.com/acme/shop-api.v2.git": "acme/shop-api.v2",
		"https://gitlab.com/acme/shop.git":          "",
		"https://github.com/acme":                   "",
	} {
		assert.Equal(t, want, parseGitHubRemote(url), url)
	}
}
