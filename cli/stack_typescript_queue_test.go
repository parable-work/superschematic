// tqServices is a TypeScript API with a queue, in the YAML form (D52,
// D53): tq-db declares the queue Reminder, whose TypeScript types export its
// definition; tq-shop, a TypeScript API on tq-db, declares the job
// QueueReminders and the worker SendReminders, which handles Reminder two
// at a time; tq-stack deploys tq-shop on the local target, on the ports
// given.
func tqServices(pgPort, storagePort, apiPort int) map[string]string {
	return map[string]string{
		"tq-db/schema.config.yaml": "name: tq-db\nkind: DB\noutputs:\n  types:\n    go: { enabled: true }\n    typescript: { enabled: true }\n",
		"tq-db/src/db.schema.yaml": `name: tq-db
kind: DB
scalars:
  Identity.UUID:
    name: Identity.UUID
    languagePrimitive: string
types:
  Cart:
    name: Cart
    role: DBTable
    fields:
      - { name: id, typeRef: { name: Identity.UUID }, required: true, key: true, autoGenerated: true }
  # Sent for an abandoned cart; a message that fails is dead at once.
  Reminder:
    name: Reminder
    role: EmbeddedStruct
    queue: { retries: 0, backoff: 1s }
    fields:
      - { name: cart, typeRef: { name: string }, required: true }
`,
		"tq-shop/schema.config.yaml": `name: tq-shop
kind: API
dependencies:
  - { name: tq-db, kind: DB }
outputs:
  types:
    typescript: { enabled: true }
  api: { enabled: true, language: TYPESCRIPT }
`,
		"tq-shop/src/shop.schema.yaml": `name: tq-shop
kind: API
imports:
  - package: "@schemas/tq-db"
    types: [Reminder]
types:
  Summary:
    name: Summary
    role: APIView
    fields:
      - { name: done, typeRef: { name: number }, required: true }
      - { name: dead, typeRef: { name: number }, required: true }
operationSets:
  - name: Reminders
    operations:
      - name: getSummary
        typeRef: { name: Summary }
        required: true
        httpMethod: GET
        restPath: summary
jobs:
  - name: QueueReminders
workers:
  - name: SendReminders
    queue: Reminder
    concurrency: 2
`,
		"tq-stack/schema.config.yaml": "name: tq-stack\nkind: Stack\noutputs: {}\n",
		"tq-stack/src/stack.schema.yaml": fmt.Sprintf(`kind: Stack
types:
  Reminders:
    name: Reminders
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: tq-shop, kind: API }
  Dev:
    name: Dev
    role: EmbeddedStruct
    environment:
      target: local
      values: { postgresPort: %d, storagePort: %d }
      settings:
        - of: { service: { name: tq-shop, kind: API } }
          values: { port: %d }
`, pgPort, storagePort, apiPort),
	}
}

// tqImplementation implements tq-shop: getSummary counts the queue's done
// and dead messages, QueueReminders enqueues three in one transaction, and
// SendReminders fails the one for the cart named poison.
const tqImplementation = `import { enqueue } from '@superschematic/http-runtime/postgres';
import { reminderQueue } from '@schemas/tq-db-types/queues';
import type { Constructor, JobsConstructor, WorkersConstructor } from '@schemas/tq-shop-api';

export const create: Constructor = deps => ({
  reminders: {
    async getSummary() {
      const { rows } = await deps.db.query('SELECT state, count(*)::int AS n FROM reminder_queue GROUP BY state');
      const count = (state: string) => (rows as { state: string; n: number }[]).find(row => row.state === state)?.n ?? 0;
      return { done: count('done'), dead: count('dead') };
    },
  },
});

export const createJobs: JobsConstructor = deps => ({
  async queueReminders() {
    const client = await deps.db.connect();
    try {
      await client.query('BEGIN');
      for (const cart of ['c-1', 'c-2', 'poison']) await enqueue(client, reminderQueue, { cart });
      await client.query('COMMIT');
    } finally {
      client.release();
    }
    deps.logger.info('queued reminders');
  },
});

export const createWorkers: WorkersConstructor = deps => ({
  async sendReminders(message) {
    if (message.cart === 'poison') throw new Error('no such cart');
    deps.logger.info('reminded', { cart: message.cart });
  },
});
`

// TestStackDevRunsTypeScriptJobsAndWorkers runs stack dev for real, with
// Docker and Bun, on a TypeScript API with a job and a worker (D52, D53).
// The build writes the job's and the worker's main.ts beside the server's;
// stack dev runs Postgres with tq-db migrated, its queue's table included,
// and the server and the worker on Bun; stack run, from another command,
// runs the job on Bun against it, which enqueues three messages in one
// transaction; the worker handles two and fails the third, which is dead
// at once, as the server's summary reads from the queue.
func TestStackDevRunsTypeScriptJobsAndWorkers(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: stack dev runs Docker, Postgres and Bun")
	}
	if err := exec.Command("docker", "info").Run(); err != nil {
		t.Skipf("Docker is not available: %v", err)
	}
	bun, err := exec.LookPath("bun")
	if err != nil {
		testpaths.RequireOrSkipTS(t, fmt.Sprintf("bun not available: %v", err))
	}
	paths := testpaths.Local(t)
	for _, step := range [][]string{{"install", "--frozen-lockfile"}, {"run", "build"}} {
		cmd := exec.Command(bun, step...)
		cmd.Dir = paths.HTTPRuntimeTypeScript
		if out, err := cmd.CombinedOutput(); err != nil {
			testpaths.RequireOrSkipTS(t, fmt.Sprintf("bun %s in the HTTP runtime: %v\n%s", strings.Join(step, " "), err, out))
		}
	}
	runner := filepath.Join(t.TempDir(), local.MigrateBinary)
	build := exec.Command("go", "build", "-o", runner, "./cmd/superschematic-migrate")
	build.Dir = filepath.Join("..", "runtime", "migrate", "go")
	build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off")
	out, err := build.CombinedOutput()
	require.NoError(t, err, string(out))
	t.Setenv(local.MigrateEnv, runner)

	repo := t.TempDir()
	schemasRoot := filepath.Join(repo, "schemas")
	servicesRoot := filepath.Join(schemasRoot, "services")
	pgPort, storagePort, apiPort := freeTCPPort(t), freeTCPPort(t), freeTCPPort(t)
	writeFiles(t, servicesRoot, tqServices(pgPort, storagePort, apiPort))
	// The workspace takes superscalar and the HTTP runtime from this
	// repository, as acme-shop's naming file has it.
	var naming strings.Builder
	naming.WriteString("[paths]\n")
	for key, dir := range map[string]string{"scalar_typescript": paths.ScalarTypeScript, "http_runtime_typescript": paths.HTTPRuntimeTypeScript} {
		rel, err := filepath.Rel(repo, dir)
		require.NoError(t, err)
		fmt.Fprintf(&naming, "%s = %q\n", key, filepath.ToSlash(rel))
	}
	require.NoError(t, os.WriteFile(filepath.Join(schemasRoot, "superschematic.toml"), []byte(naming.String()), 0o644))
	outputRoot := t.TempDir()
	// The container is the checkout's, named for the schemas root as the
	// build resolves it (D30, amended).
	canonical, err := stack.CanonicalSchemasRoot(schemasRoot)
	require.NoError(t, err)
	container := local.ContainerName("tq-stack", "Dev", local.Checkout(canonical, "tq-stack", "Dev"))
	t.Cleanup(func() { _ = exec.Command("docker", "rm", "--force", "--volumes", container).Run() })

	// A first build scaffolds tq-shop's implementation, which the test
	// replaces; no later build rewrites it.
	buf := new(bytes.Buffer)
	root := New(Config{})
	root.SetOut(buf)
	root.SetErr(buf)
	root.SetArgs([]string{"build-all", servicesRoot, "--out", outputRoot})
	require.NoError(t, root.Execute(), buf.String())
	for _, deployable := range []string{"tq-shop", "tq-shop-queue-reminders", "tq-shop-send-reminders"} {
		require.FileExists(t, filepath.Join(outputRoot, "server", "tq-stack", deployable, "main.ts"), buf.String())
	}
	writeFiles(t, repo, map[string]string{"typescript/tq-shop/index.ts": tqImplementation})

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	dev := &lockedBuffer{}
	root = New(Config{})
	root.SetOut(dev)
	root.SetErr(dev)
	root.SetArgs([]string{"stack", "dev", filepath.Join(servicesRoot, "tq-stack"), "--out", outputRoot, "--remove-data"})
	done := make(chan error, 1)
	go func() { done <- root.ExecuteContext(ctx) }()
	deadline := time.Now().Add(5 * time.Minute)
	for !strings.Contains(dev.String(), "is running:") {
		select {
		case err := <-done:
			t.Fatalf("stack dev returned before the stack ran: %v\n%s", err, dev)
		default:
		}
		if time.Now().After(deadline) {
			t.Fatalf("the stack did not come up:\n%s", dev)
		}
		time.Sleep(100 * time.Millisecond)
	}
	summary := func() string {
		t.Helper()
		resp, err := http.Get(local.ServerURL(apiPort) + "/api/summary")
		require.NoError(t, err)
		body, err := io.ReadAll(resp.Body)
		_ = resp.Body.Close()
		require.NoError(t, err)
		require.Equal(t, http.StatusOK, resp.StatusCode, "%s\n%s", body, dev)
		return string(body)
	}
	require.Contains(t, summary(), `"done":0,"dead":0`)

	// stack run, as from another terminal.
	run := new(bytes.Buffer)
	root = New(Config{})
	root.SetOut(run)
	root.SetErr(run)
	root.SetArgs([]string{"stack", "run", "Dev", "tq-shop-queue-reminders", "--stack", filepath.Join(servicesRoot, "tq-stack"), "--out", outputRoot})
	require.NoError(t, root.ExecuteContext(ctx), "%s\n%s", run, dev)
	require.Contains(t, run.String(), `"msg":"queued reminders"`)
	require.Contains(t, run.String(), `"msg":"job done"`)

	deadline = time.Now().Add(time.Minute)
	for !strings.Contains(summary(), `"done":2,"dead":1`) {
		if time.Now().After(deadline) {
			t.Fatalf("the worker did not handle the reminders: %s\n%s", summary(), dev)
		}
		time.Sleep(200 * time.Millisecond)
	}
	for _, want := range []string{`"msg":"worker started"`, `"msg":"reminded"`, `"msg":"message failed and is dead: its retries are spent"`} {
		require.Contains(t, dev.String(), want)
	}

	cancel()
	select {
	case err := <-done:
		require.NoError(t, err, dev.String())
	case <-time.After(time.Minute):
		t.Fatalf("stack dev did not stop:\n%s", dev)
	}
	require.Contains(t, dev.String(), `"msg":"worker stopped"`)
	t.Log(dev.String())
}
