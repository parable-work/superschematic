// acmeRating registers acme.Rating, the acme-schematic example's behavior,
// with the Rust crate that implements it at crates/behaviors in the
// project, as the example's extension does.
type acmeRating struct{ repo string }

func (acmeRating) Name() string { return "acme" }

func (r acmeRating) Register(reg *registry.Registry) error {
	declaration, err := os.ReadFile(filepath.Join(r.repo, "examples", "acme-schematic", "ext", "rating.behavior.json"))
	if err != nil {
		return err
	}
	return errors.Join(
		reg.RegisterBehavior(registry.BehaviorSpec{
			Extension:   "acme",
			Rust:        registry.BehaviorRust{Crate: "acme-behaviors", Path: "crates/behaviors", Register: "acme_behaviors::Rating"},
			Declaration: json.RawMessage(declaration),
		}),
		reg.RegisterToolInvocationPolicy(registry.ToolInvocationPolicy{Extension: "acme", Key: "confirm", Values: []string{"never", "always"}, Default: "never"}),
	)
}

// rateServices is an engine database whose Product composes acme.Rating,
// which only the project's engine crate runs (D58), in the YAML form:
// rate-api serves it from Go, rate-rs-api from Rust and rate-ts-api from
// TypeScript, each an API only a calling service may call, and rate-stack
// deploys the three on the local target, on the ports given, with rate-db's
// runner beside them.
func rateServices(pgPort, storagePort, goPort, rsPort, tsPort int) map[string]string {
	api := func(name, language string) string {
		return fmt.Sprintf(`name: %s
kind: API
public: true
dependencies:
  - { name: rate-db, kind: DB }
outputs:
  types:
    %s: { enabled: true }
  api: { enabled: true, language: %s }
`, name, strings.ToLower(language), language)
	}
	schema := func(name string) string {
		return fmt.Sprintf(`name: %s
kind: API
types:
  Count:
    name: Count
    role: APIView
    fields:
      - { name: products, typeRef: { name: number }, required: true }
operationSets:
  - name: Products
    serviceCallers: { mode: require }
    operations:
      - name: count
        typeRef: { name: Count }
        required: true
        httpMethod: GET
        restPath: count
`, name)
	}
	return map[string]string{
		"rate-db/schema.config.yaml": `name: rate-db
kind: DB
outputs:
  types:
    go: { enabled: true }
    rust: { enabled: true }
    typescript: { enabled: true }
  engine:
    policy: allowAll
`,
		"rate-db/src/db.schema.yaml": `name: rate-db
kind: DB
scalars:
  Identity.UUID:
    name: Identity.UUID
    languagePrimitive: string
types:
  # A table of the database's own beside the engine's.
  Shopper:
    name: Shopper
    role: DBTable
    fields:
      - { name: id, typeRef: { name: Identity.UUID }, required: true, key: true, autoGenerated: true }
  Product:
    name: Product
    role: DBTable
    behaviors:
      - name: acme.Rating
        config: { maxStars: 5 }
    fields:
      - { name: title, typeRef: { name: string }, required: true }
`,
		"rate-api/schema.config.yaml":     api("rate-api", "GO"),
		"rate-api/src/api.schema.yaml":    schema("rate-api"),
		"rate-rs-api/schema.config.yaml":  api("rate-rs-api", "RUST"),
		"rate-rs-api/src/api.schema.yaml": schema("rate-rs-api"),
		"rate-ts-api/schema.config.yaml":  api("rate-ts-api", "TYPESCRIPT"),
		"rate-ts-api/src/api.schema.yaml": schema("rate-ts-api"),
		"rate-stack/schema.config.yaml":   "name: rate-stack\nkind: Stack\noutputs: {}\n",
		"rate-stack/src/stack.schema.yaml": fmt.Sprintf(`kind: Stack
types:
  Ratings:
    name: Ratings
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: rate-api, kind: API }
        - { name: rate-rs-api, kind: API }
        - { name: rate-ts-api, kind: API }
  Dev:
    name: Dev
    role: EmbeddedStruct
    environment:
      target: local
      values: { postgresPort: %d, storagePort: %d }
      settings:
        - of: { service: { name: rate-api, kind: API } }
          values: { port: %d }
        - of: { service: { name: rate-rs-api, kind: API } }
          values: { port: %d }
        - of: { service: { name: rate-ts-api, kind: API } }
          values: { port: %d }
`, pgPort, storagePort, goPort, rsPort, tsPort),
	}
}

// TestStackDevBuildsTheProjectsEngine runs stack dev for real, with Docker,
// cargo and Bun, on a stack whose engine database composes acme.Rating, an
// extension's behavior only the project's engine crate runs (D58), with no
// CGO_LDFLAGS or SUPERSCHEMATIC_ENGINE_ADDON of the test's: stack dev
// builds the crate's ffi member for the Go server and the runner, which
// link its archive, and its napi member for the TypeScript server, whose
// process opens the engine on its addon; the Rust server depends on the
// crate itself, and builds it with its own crate. Each server deploys rate-db's
// engine document, which an engine without acme.Rating refuses, so /readyz
// answers 200 only on the project's engine, and then mounts its routes,
// which refuse a request with no caller.
func TestStackDevBuildsTheProjectsEngine(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: stack dev runs Docker, Postgres, cargo and Bun")
	}
	if err := exec.Command("docker", "info").Run(); err != nil {
		t.Skipf("Docker is not available: %v", err)
	}
	if _, err := exec.LookPath("cargo"); err != nil {
		t.Skipf("cargo is not available: %v", err)
	}
	bun, err := exec.LookPath("bun")
	if err != nil {
		testpaths.RequireOrSkipTS(t, fmt.Sprintf("bun not available: %v", err))
	}
	paths := testpaths.Local(t)
	// The HTTP runtime's dist/, built as the other TypeScript tests build
	// it, so this test waits for theirs rather than reading it mid-build.
	testpaths.BuildHTTPRuntime(t, bun, paths)
	if _, err := os.Stat(filepath.Join(paths.EngineTypeScript, "dist", "index.d.ts")); err != nil {
		testpaths.RequireOrSkipTS(t, fmt.Sprintf("no dist/ in %s; run bun run build there: %v", paths.EngineTypeScript, err))
	}
	t.Setenv("CGO_LDFLAGS", os.Getenv("CGO_LDFLAGS"))
	t.Setenv(projectengine.AddonEnv, "")
	runner := filepath.Join(t.TempDir(), local.MigrateBinary)
	build := exec.Command("go", "build", "-o", runner, "./cmd/superschematic-migrate")
	build.Dir = filepath.Join("..", "runtime", "migrate", "go")
	build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off")
	out, err := build.CombinedOutput()
	require.NoError(t, err, string(out))
	t.Setenv(local.MigrateEnv, runner)

	repo := testpaths.RepoRoot(t)
	project := testpaths.TempDir(t)
	schemasRoot := filepath.Join(project, "schemas")
	servicesRoot := filepath.Join(schemasRoot, "services")
	pgPort, storagePort, goPort, rsPort, tsPort := freeTCPPort(t), freeTCPPort(t), freeTCPPort(t), freeTCPPort(t), freeTCPPort(t)
	writeFiles(t, servicesRoot, rateServices(pgPort, storagePort, goPort, rsPort, tsPort))
	// acme.Rating's crate, which the project holds at the path its
	// registration names, its path dependencies on the engine at this
	// checkout's.
	crate := filepath.Join(repo, "examples", "acme-schematic", "crates", "behaviors")
	for _, file := range []string{"Cargo.toml", "Cargo.lock"} {
		data, err := os.ReadFile(filepath.Join(crate, file))
		require.NoError(t, err)
		content := strings.ReplaceAll(string(data), `"../../../../runtime/`, `"`+filepath.ToSlash(repo)+`/runtime/`)
		writeFiles(t, filepath.Join(project, "crates", "behaviors"), map[string]string{file: content})
	}
	for _, dir := range []string{"src", "declarations"} {
		require.NoError(t, os.CopyFS(filepath.Join(project, "crates", "behaviors", dir), os.DirFS(filepath.Join(crate, dir))))
	}
	// The naming file names this checkout's runtimes and engine crates, as a
	// project built against a checkout does.
	var naming strings.Builder
	naming.WriteString("[paths]\n")
	for _, p := range []struct{ key, dir string }{
		{"scalar_go", paths.ScalarGo},
		{"scalar_typescript", paths.ScalarTypeScript},
		{"scalar_rust", paths.ScalarRust},
		{"schema_runtime_rust", paths.SchemaRuntimeRust},
		{"http_runtime_rust", paths.HTTPRuntimeRust},
		{"schema_ir", paths.SchemaIR},
		{"schema_runtime_go", paths.SchemaRuntimeGo},
		{"http_runtime_go", paths.HTTPRuntimeGo},
		{"http_runtime_typescript", paths.HTTPRuntimeTypeScript},
		{"engine_go", paths.EngineGo},
		{"engine_typescript", paths.EngineTypeScript},
		{"engine_rust", paths.EngineRust},
		{"engine_behaviors_rust", paths.EngineBehaviorsRust},
		{"engine_workqueue_rust", paths.EngineWorkQueueRust},
		{"engine_commerce_rust", paths.EngineCommerceRust},
		{"engine_abi_rust", paths.EngineABIRust},
		{"engine_napi_rust", paths.EngineNapiRust},
	} {
		rel, err := filepath.Rel(project, p.dir)
		require.NoError(t, err)
		fmt.Fprintf(&naming, "%s = %q\n", p.key, filepath.ToSlash(rel))
	}
	require.NoError(t, os.WriteFile(filepath.Join(schemasRoot, "superschematic.toml"), []byte(naming.String()), 0o644))
	outputRoot := filepath.Join(schemasRoot, "dist")
	canonical, err := stack.CanonicalSchemasRoot(schemasRoot)
	require.NoError(t, err)
	container := local.ContainerName("rate-stack", "Dev", local.Checkout(canonical, "rate-stack", "Dev"))
	t.Cleanup(func() { _ = exec.Command("docker", "rm", "--force", "--volumes", container).Run() })

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	dev := &lockedBuffer{}
	root := New(Config{}, acmeRating{repo: repo})
	root.SetOut(dev)
	root.SetErr(dev)
	root.SetArgs([]string{"stack", "dev", filepath.Join(servicesRoot, "rate-stack"), "--out", outputRoot, "--remove-data"})
	done := make(chan error, 1)
	go func() { done <- root.ExecuteContext(ctx) }()
	// The first build compiles the engine three times: the archive, the
	// addon and the Rust server.
	deadline := time.Now().Add(40 * time.Minute)
	for !strings.Contains(dev.String(), "is running:") {
		select {
		case err := <-done:
			t.Fatalf("stack dev returned before the stack ran: %v\n%s", err, dev)
		default:
		}
		if time.Now().After(deadline) {
			t.Fatalf("the stack did not come up:\n%s", dev)
		}
		time.Sleep(200 * time.Millisecond)
	}
	for _, want := range []string{
		"build rate-api: cargo build --release of the engine crate of rate-db, its ffi member",
		"build rate-db-engine-runner: cargo build --release of the engine crate of rate-db, its ffi member",
		"build rate-ts-api: cargo build --release of the engine crate of rate-db, its napi member",
		"build rate-rs-api: cargo build --release --locked in server/rate-stack/rate-rs-api",
		`"archive":"schemas-rate-db-engine-ffi"`,
	} {
		require.Contains(t, dev.String(), want)
	}

	// Each server deploys the document, which only an engine with
	// acme.Rating accepts, before /readyz names its engine ready.
	for _, port := range []int{goPort, rsPort, tsPort} {
		deadline := time.Now().Add(time.Minute)
		for {
			resp, err := http.Get(local.ServerURL(port) + "/readyz")
			require.NoError(t, err, dev.String())
			body, _ := io.ReadAll(resp.Body)
			_ = resp.Body.Close()
			if resp.StatusCode == http.StatusOK {
				break
			}
			if time.Now().After(deadline) {
				t.Fatalf("the server on %d is not ready: %d %s\n%s", port, resp.StatusCode, body, dev)
			}
			time.Sleep(200 * time.Millisecond)
		}
		resp, err := http.Get(local.ServerURL(port) + "/engine/rate-db/namespaces/rate-db/schemas/Product")
		require.NoError(t, err)
		body, _ := io.ReadAll(resp.Body)
		_ = resp.Body.Close()
		// No credential: the engine's caller rule refuses before it reads.
		require.Equal(t, http.StatusUnauthorized, resp.StatusCode, "%s\n%s", body, dev)
	}

	cancel()
	select {
	case err := <-done:
		require.NoError(t, err, dev.String())
	case <-time.After(2 * time.Minute):
		t.Fatalf("stack dev did not stop:\n%s", dev)
	}
	t.Log(dev.String())
}
