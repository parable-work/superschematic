package cli

import (
	"fmt"

	"github.com/spf13/cobra"

	"github.com/parable-work/superschematic/internal/generator/naming"
	"github.com/parable-work/superschematic/internal/loader/schemaconfig"
	"github.com/parable-work/superschematic/internal/loader/schemafile"
)

// jsonSchemaFlags holds one json-schema command's flag values.
type jsonSchemaFlags struct {
	config     bool
	namingPath string
}

// newJSONSchemaCmd emits the JSON Schema definitions the JSON and YAML
// readers validate against.
func newJSONSchemaCmd(a *app) *cobra.Command {
	flags := &jsonSchemaFlags{}
	cmd := &cobra.Command{
		Use:   "json-schema",
		Short: "Emit the JSON Schema the JSON/YAML schema readers validate against",
		Long: `json-schema prints the JSON Schema definition for *.schema.json and
*.schema.yaml files: a multi-definition document mirroring the Schema IR, or
a single definition object. The schema is generated by reflection from the IR
structs, so it is exhaustive by construction -- unknown keys and unknown
decorator names fail validation.

With --config, prints the JSON Schema for the schema.config.json and
schema.config.yaml service configuration forms instead (generated from
@superschematic/schema-config).`,
		Args: cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			return runJSONSchema(cmd, a, flags)
		},
	}
	cmd.Flags().BoolVar(&flags.config, "config", false, "emit the schema.config.{json,yaml} JSON Schema instead")
	cmd.Flags().StringVar(&flags.namingPath, "naming", "", "naming config file (default: built-in names; json-schema has no service directory to find superschematic.toml from)")
	return cmd
}

func runJSONSchema(cmd *cobra.Command, a *app, flags *jsonSchemaFlags) error {
	if flags.config {
		_, _ = fmt.Fprint(cmd.OutOrStdout(), string(schemaconfig.Definition()))
		return nil
	}
	// The same registry build threads through the loader and generators;
	// a binary carrying extensions sees their kinds, decorators and
	// documents in the emitted schema.
	names := naming.Default()
	if flags.namingPath != "" {
		var err error
		if names, err = resolveNaming(flags.namingPath, ""); err != nil {
			return err
		}
	}
	reg, err := a.resolveRegistry(names)
	if err != nil {
		return err
	}
	definition, err := schemafile.DefinitionFor(reg)
	if err != nil {
		return err
	}
	_, _ = fmt.Fprint(cmd.OutOrStdout(), string(definition))
	return nil
}
