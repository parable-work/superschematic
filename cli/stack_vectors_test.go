// vectorStackTree writes a DB service with a 1024-dimension embedding and
// an HNSW index over it (D84), and a stack that deploys it to a local Dev,
// and returns the stack's directory.
func vectorStackTree(t *testing.T, pgPort int) string {
	t.Helper()
	root := filepath.Join(t.TempDir(), "schemas", "services")
	writeFiles(t, root, map[string]string{
		"vec-db/schema.config.yaml": "name: vec-db\nkind: DB\noutputs:\n  types:\n    go: { enabled: true }\n",
		"vec-db/src/embeddings.schema.yaml": `name: vec-db
kind: DB
scalars:
  Identity.UUID: { name: Identity.UUID, languagePrimitive: string }
  Embedding.Vector: { name: Embedding.Vector, languagePrimitive: string }
  Generic.Decimal: { name: Generic.Decimal, languagePrimitive: string }
types:
  LineItemEmbedding:
    name: LineItemEmbedding
    role: DBTable
    indexes:
      - keys: [embedding]
        method: hnsw
        ops: vector_cosine_ops
        m: 16
        efConstruction: 64
    fields:
      - name: id
        typeRef: { name: Identity.UUID }
        required: true
        key: true
        autoGenerated: true
      - name: text
        typeRef: { name: string }
        required: true
      - name: embedding
        typeRef: { name: Embedding.Vector }
        required: true
        validateDimensions: 1024
      - name: confidence
        typeRef: { name: Generic.Decimal }
        validatePrecision: 5
        validateScale: 2
`,
		"vec-stack/schema.config.yaml": "name: vec-stack\nkind: Stack\noutputs: {}\n",
		"vec-stack/src/stack.schema.yaml": fmt.Sprintf(`kind: Stack
types:
  Vectors:
    name: Vectors
    role: EmbeddedStruct
    stack:
      deploy:
        - { name: vec-db, kind: DB }
  Dev:
    name: Dev
    role: EmbeddedStruct
    environment:
      target: local
      values: { postgresPort: %d }
`, pgPort),
	})
	return filepath.Join(root, "vec-stack")
}

// TestStackDevMigratesAVectorDatabase runs `stack dev` with Docker over a
// stack whose database has a vector column (D84): with no postgresImage
// set, the local target runs pgvector's image, and the migration enables
// the vector extension and creates the vector(1024) column, the NUMERIC(5,2)
// one and the HNSW index.
func TestStackDevMigratesAVectorDatabase(t *testing.T) {
	if testing.Short() {
		t.Skip("-short: stack dev runs Docker and Postgres")
	}
	if err := exec.Command("docker", "info").Run(); err != nil {
		t.Skipf("Docker is not available: %v", err)
	}
	runner := filepath.Join(t.TempDir(), local.MigrateBinary)
	build := exec.Command("go", "build", "-o", runner, "./cmd/superschematic-migrate")
	build.Dir = filepath.Join("..", "runtime", "migrate", "go")
	build.Env = append(os.Environ(), "CGO_ENABLED=0", "GOWORK=off")
	out, err := build.CombinedOutput()
	require.NoError(t, err, string(out))
	t.Setenv(local.MigrateEnv, runner)

	stackDir := vectorStackTree(t, freeTCPPort(t))
	schemasRoot, err := stack.CanonicalSchemasRoot(filepath.Dir(filepath.Dir(stackDir)))
	require.NoError(t, err)
	container := local.ContainerName("vec-stack", "Dev", local.Checkout(schemasRoot, "vec-stack", "Dev"))
	t.Cleanup(func() { _ = exec.Command("docker", "rm", "--force", "--volumes", container).Run() })

	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	buf := &lockedBuffer{}
	root := New(Config{})
	root.SetOut(buf)
	root.SetErr(buf)
	root.SetArgs([]string{"stack", "dev", stackDir, "--out", t.TempDir(), "--remove-data"})
	done := make(chan error, 1)
	go func() { done <- root.ExecuteContext(ctx) }()

	deadline := time.Now().Add(6 * time.Minute)
	for !strings.Contains(buf.String(), "is running:") {
		select {
		case err := <-done:
			t.Fatalf("stack dev returned before the environment ran: %v\n%s", err, buf)
		default:
		}
		if time.Now().After(deadline) {
			t.Fatalf("the environment did not come up:\n%s", buf)
		}
		time.Sleep(100 * time.Millisecond)
	}
	require.Contains(t, buf.String(), "migrate vec-db: ")

	image, err := exec.Command("docker", "inspect", "--format", "{{.Config.Image}}", container).Output()
	require.NoError(t, err)
	require.Equal(t, local.DefaultVectorPostgresImage, strings.TrimSpace(string(image)))
	psql := func(query string) string {
		t.Helper()
		out, err := exec.Command("docker", "exec", container, "psql", "--username", local.PostgresUser, "--dbname", "vec_db",
			"--tuples-only", "--no-align", "--command", query).CombinedOutput()
		require.NoError(t, err, string(out))
		return strings.TrimSpace(string(out))
	}
	require.Equal(t, "vector", psql("SELECT extname FROM pg_extension WHERE extname = 'vector'"))
	require.Equal(t, "embedding|vector(1024)\nconfidence|numeric(5,2)", psql(
		"SELECT attname, format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'line_item_embedding'::regclass AND attname IN ('embedding', 'confidence') ORDER BY attnum"))
	require.Contains(t, psql("SELECT indexdef FROM pg_indexes WHERE tablename = 'line_item_embedding' AND indexdef LIKE '%hnsw%'"),
		"USING hnsw (embedding vector_cosine_ops) WITH (m='16', ef_construction='64')")

	cancel()
	select {
	case err := <-done:
		require.NoError(t, err, buf.String())
	case <-time.After(time.Minute):
		t.Fatalf("stack dev did not stop:\n%s", buf)
	}
}
