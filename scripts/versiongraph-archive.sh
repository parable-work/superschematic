#!/usr/bin/env bash
# Build the version-graph core's static archive for this host and stage it
# where the Go binding (runtime/versiongraph/go) links it:
# runtime/versiongraph/go/lib/<goos>_<goarch>/libsuperschematic_versiongraph.a.
#
# Go's build cache keys a cgo link on the LDFLAGS text, not on the archive's
# bytes, so a rebuilt archive would not relink a cached test binary. The script
# also writes the archive's SHA-256 into archive_stamp_<goos>_<goarch>.go in
# the binding (gitignored), which puts the archive's content into the
# package's build ID. superscalar's go/scripts/build_ffi.sh does the same.
#
# Usage:
#   scripts/versiongraph-archive.sh            # build and stage, print the -L flag
#   scripts/versiongraph-archive.sh --print    # print the -L flag only
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CRATE="$ROOT/runtime/versiongraph/rust"
GO_DIR="$ROOT/runtime/versiongraph/go"
ARCHIVE_NAME="libsuperschematic_versiongraph.a"

goos="$(go env GOOS)"
goarch="$(go env GOARCH)"
DEST="$GO_DIR/lib/${goos}_${goarch}"

case "${1:-}" in
  --print)
    echo "-L$DEST"
    exit 0
    ;;
  "")
    ;;
  *)
    echo "unknown argument: $1" >&2
    exit 2
    ;;
esac

BUILD_LOG="$(mktemp)"
trap 'rm -f "$BUILD_LOG"' EXIT

# cargo names the archive it built in its artifact records, wherever
# CARGO_TARGET_DIR or a config puts the target directory.
cargo build --release --manifest-path "$CRATE/Cargo.toml" --message-format=json-render-diagnostics >"$BUILD_LOG"
ARCHIVE="$(python3 - "$BUILD_LOG" "$ARCHIVE_NAME" <<'PY'
import json, sys

for line in open(sys.argv[1], encoding="utf-8"):
    try:
        message = json.loads(line)
    except ValueError:
        continue
    if message.get("reason") != "compiler-artifact":
        continue
    for path in message.get("filenames") or []:
        if path.endswith("/" + sys.argv[2]):
            print(path)
            sys.exit(0)
PY
)"
if [ -z "$ARCHIVE" ] || [ ! -f "$ARCHIVE" ]; then
  echo "cargo reported no $ARCHIVE_NAME" >&2
  exit 1
fi

mkdir -p "$DEST"
cp "$ARCHIVE" "$DEST/$ARCHIVE_NAME"

DIGEST="$(python3 -c 'import hashlib, sys; print(hashlib.sha256(open(sys.argv[1], "rb").read()).hexdigest())' "$DEST/$ARCHIVE_NAME")"
STAMP="$GO_DIR/archive_stamp_${goos}_${goarch}.go"
NEW_STAMP="$(mktemp)"
trap 'rm -f "$BUILD_LOG" "$NEW_STAMP"' EXIT
cat >"$NEW_STAMP" <<EOF
//go:build ${goos} && ${goarch}

package versiongraph

// Code generated by scripts/versiongraph-archive.sh. DO NOT EDIT.
//
// The SHA-256 of the static archive this package links. It changes when the
// archive changes, so the Go build cache cannot reuse a link against a stale
// one.
const archiveSHA256 = "${DIGEST}"
EOF
# Rewrite only on a change, so an unchanged archive keeps the cache warm.
if ! cmp -s "$NEW_STAMP" "$STAMP"; then
  cp "$NEW_STAMP" "$STAMP"
fi

echo "versiongraph archive ${DIGEST:0:12} staged under $DEST" >&2
echo "-L$DEST"
