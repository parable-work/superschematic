#!/usr/bin/env bash
# Build the version-graph core's static archive for this host and stage it
# where the Go binding (runtime/versiongraph/go) links it:
# runtime/versiongraph/go/lib/<goos>_<goarch>/libsuperschematic_versiongraph.a.
#
# Go's build cache keys a cgo link on the LDFLAGS text, not on the archive's
# bytes, so a rebuilt archive would not relink a cached test binary. The script
# also writes the archive's SHA-256 into archive_stamp_<goos>_<goarch>.go in
# the binding (gitignored), which puts the archive's content into the
# package's build ID. superscalar's go/scripts/build_ffi.sh does the same.
#
# Usage:
#   scripts/versiongraph-archive.sh            # build and stage, print the -L flag
#   scripts/versiongraph-archive.sh --prebuilt # download it prebuilt and stage it
#   scripts/versiongraph-archive.sh --print    # print the -L flag only
#
# --prebuilt builds nothing and needs no Rust (D82): it downloads the
# archive the prebuilt-deps workflow built from these sources with
# RUST_VERSION, checks it against the manifest prebuilt.pin pins, and
# stages it and its stamp as a build does (scripts/prebuilt_deps.py).
# Without cargo on PATH, a run with no argument does the same.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# shellcheck source=lib/archive.sh
. "$ROOT/scripts/lib/archive.sh"
CRATE="$ROOT/runtime/versiongraph/rust"
GO_DIR="$ROOT/runtime/versiongraph/go"
ARCHIVE_NAME="libsuperschematic_versiongraph.a"

archive_target
DEST="$(archive_lib_dir "$GO_DIR")"

prebuilt=0
case "${1:-}" in
  --print)
    echo "-L$DEST"
    exit 0
    ;;
  --prebuilt)
    prebuilt=1
    ;;
  "")
    ;;
  *)
    echo "unknown argument: $1" >&2
    exit 2
    ;;
esac
if [ "$prebuilt" = "0" ] && ! command -v cargo >/dev/null 2>&1; then
  echo "versiongraph-archive: cargo is not on PATH, so the archive comes prebuilt (D82)" >&2
  prebuilt=1
fi
if [ "$prebuilt" = "1" ]; then
  python3 "$ROOT/scripts/prebuilt_deps.py" fetch versiongraph --only versiongraph-archive
  echo "-L$DEST"
  exit 0
fi

# Go binaries link this archive beside superscalar's, so both are built
# with tools.env's RUST_VERSION (scripts/lib/archive.sh says why).
archive_toolchain

archive_build "$CRATE"
archive_stage "$ARCHIVE" "$DEST" "$ARCHIVE_NAME"

archive_stamp "$GO_DIR/archive_stamp_${goos}_${goarch}.go" <<EOF
//go:build ${goos} && ${goarch}

package versiongraph

// Code generated by scripts/versiongraph-archive.sh. DO NOT EDIT.
//
// The SHA-256 of the static archive this package links. It changes when the
// archive changes, so the Go build cache cannot reuse a link against a stale
// one.
const archiveSHA256 = "${DIGEST}"
EOF

echo "versiongraph archive ${DIGEST:0:12} staged under $DEST" >&2
echo "-L$DEST"
